/**
 * Байты словами. Общая функция, а не формат на месте: одно и то же число в двух
 * местах однажды покажется как «1,2 ГБ» и «1200 МБ».
 */
export function weightWords(bytes: number): string {
  if (bytes <= 0) return "0 байт";
  const mb = bytes / (1024 * 1024);
  if (mb < 1) return `${bytes} байт`;
  if (mb >= 1024) return `${(mb / 1024).toFixed(2)} ГБ`;
  return `${Math.round(mb)} МБ`;
}

