import type { ReactElement } from "react";
import { Button, Text } from "@fluentui/react-components";
import { t } from "../i18n/ru";
import { hintFor } from "../lib/hint";

/**
 * Строка ошибки, которую слышит экранный диктор.
 *
 * Зачем общий компонент, а не `role="alert"` руками на каждом месте. Таких мест
 * было 24, и в них ошибка просто появлялась на экране: зрячий человек её видел,
 * диктор — нет. Пропустить атрибут легко, потому что ничего не ломается: текст
 * виден, сборка зелёная, тесты проходят. Ошибка без объявления — это ошибка,
 * о которой человек не узнал, и ведёт она к тому же, что и молчание.
 *
 * Четыре правила:
 *
 *  * **ошибка объявляется сразу** (`role="alert"`): её нельзя пропустить,
 *    отложить или пролистать;
 *  * **показ не повторяется.** Один и тот же текст на экране — не повод
 *    повторять его диктору: `aria-live` срабатывает на появление, а не на
 *    каждый рендер, и повтор шёл бы при любом изменении состояния рядом;
 *  * **пустой текст ничего не объявляет.** `""` — это «ошибки нет», а не
 *    «неизвестная ошибка»: объявлять пустоту значит пугать человека;
 *  * **ошибка не исчезает сама.** У неё нет таймера: сообщение, которое
 *    пропало, пока человек читал, — это сообщение, которого не было;
 *  * **рядом «что сделать»** (шаг 351): ошибка без совета — тупик, а совет,
 *    написанный руками на сорока местах, разойдётся с ними через месяц.
 *    Совет идёт из правила `src/lib/hint.ts` по тексту ошибки.
 */
export function ErrorLine({
  text,
  className,
  withHint = true,
  onAct,
}: {
  /** Текст ошибки. Пусто — компонент не рендерится вовсе. */
  text: string | null | undefined;
  /** Класс оформления: цвет и размер задаёт вызывающий экран. */
  className?: string;
  /**
   * Добавить «что сделать». По умолчанию да; `false` — только для тех мест,
   * где совет уже написан рядом своим текстом, иначе он прозвучит дважды.
   */
  withHint?: boolean;
  /**
   * Куда ведёт кнопка «что сделать», если экран умеет туда отвести.
   *
   * Шаг 25: в отказе должна быть кнопка, а не только текст. Совет «откройте
   * „Модели“» без кнопки заставляет искать этот экран самому — то есть
   * повторять ту работу, ради которой написан совет. Но кнопка появляется не
   * всегда: если экран не знает, куда вести, честнее оставить текст, чем
   * показать кнопку, которая ничего не сделает (шаг 29 — обещание, которое
   * ломает доверие).
   */
  onAct?: () => void;
}): ReactElement | null {
  if (!text) return null;
  const hint = withHint ? hintFor(text) : null;
  // Кнопка — только там, где совет называет экран, который экран умеет открыть.
  const act = onAct !== undefined && hint !== null && hint.cause !== "unknown" ? onAct : undefined;

  return (
    <div className="error-line">
      <Text className={className} role="alert" aria-live="assertive">
        {/* Ошибка без подписи читается как случайная фраза: диктор начинает с
            «что случилось», даже если на экране это понятно из контекста. */}
        <span className="screen-reader-only">{t.errorPrefix} </span>
        {text}
        {/* Совет — отдельной фразой, а не в скобках: диктор читает его целиком,
            и человек слышит «что сделать», а не хвост сообщения. */}
        {hint ? (
          <>
            {" "}
            <span className="error-hint">{hint.advice}</span>
          </>
        ) : null}
      </Text>
      {act ? (
        <Button size="small" appearance="subtle" onClick={act}>
          {t.errorAct(hint?.cause ?? "")}
        </Button>
      ) : null}
    </div>
  );
}
