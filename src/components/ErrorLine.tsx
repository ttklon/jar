import type { ReactElement } from "react";
import { Text } from "@fluentui/react-components";
import { t } from "../i18n/ru";

/**
 * Строка ошибки, которую слышит экранный диктор.
 *
 * Зачем общий компонент, а не `role="alert"` руками на каждом месте. Таких мест
 * было 24, и в них ошибка просто появлялась на экране: зрячий человек её видел,
 * диктор — нет. Пропустить атрибут легко, потому что ничего не ломается: текст
 * виден, сборка зелёная, тесты проходят. Ошибка без объявления — это ошибка,
 * о которой человек не узнал, и ведёт она к тому же, что и молчание.
 *
 * Четыре правила:
 *
 *  * **ошибка объявляется сразу** (`role="alert"`): её нельзя пропустить,
 *    отложить или пролистать;
 *  * **показ не повторяется.** Один и тот же текст на экране — не повод
 *    повторять его диктору: `aria-live` срабатывает на появление, а не на
 *    каждый рендер, и повтор шёл бы при любом изменении состояния рядом;
 *  * **пустой текст ничего не объявляет.** `""` — это «ошибки нет», а не
 *    «неизвестная ошибка»: объявлять пустоту значит пугать человека;
 *  * **ошибка не исчезает сама.** У неё нет таймера: сообщение, которое
 *    пропало, пока человек читал, — это сообщение, которого не было.
 */
export function ErrorLine({
  text,
  className,
}: {
  /** Текст ошибки. Пусто — компонент не рендерится вовсе. */
  text: string | null | undefined;
  /** Класс оформления: цвет и размер задаёт вызывающий экран. */
  className?: string;
}): ReactElement | null {
  if (!text) return null;

  return (
    <Text className={className} role="alert" aria-live="assertive">
      {/* Ошибка без подписи читается как случайная фраза: диктор начинает с
          «что случилось», даже если на экране это понятно из контекста. */}
      <span className="screen-reader-only">{t.errorPrefix} </span>
      {text}
    </Text>
  );
}
