import { describe, expect, it } from "vitest";
import { causeOf, hintFor } from "./hint";

/**
 * Шаг 351: каждая ошибка имеет «что сделать» рядом.
 *
 * Зачем тест. Совет — текст, и он ломается молча: «попробуйте ещё раз»
 * проходит любую проверку и не помогает никому. Поэтому проверяем не наличие
 * строки, а то, что совет:
 *
 *  * есть у любого текста, включая пустой и незнакомый;
 *  * называет действие, а не чувство;
 *  * не обещает того, чего приложение не сделает.
 */

describe("причина по тексту ошибки", () => {
  it("узнаёт офлайн на обоих языках", () => {
    for (const text of [
      "нет сети",
      "could not resolve host: huggingface.co",
      "network is unreachable",
      "офлайн",
    ]) {
      expect(causeOf(text), text).toBe("network");
    }
  });

  it("повреждение важнее модели: советы у них разные", () => {
    // Битый файл лечится скачиванием, неверная модель — выбором другой. Если
    // «повреждён» не поймать раньше, человек получит совет «откройте модели»,
    // когда ему нужно «скачайте заново».
    expect(causeOf("файл модели повреждён или подменён")).toBe("hash");
    expect(causeOf("модель не подошла этому компьютеру")).toBe("model");
  });

  it("отличает права, занятый файл и место", () => {
    expect(causeOf("доступ запрещён")).toBe("rights");
    expect(causeOf("файл занят другим процессом")).toBe("busy");
    expect(causeOf("не хватает места на диске")).toBe("space");
  });

  it("незнакомый текст — «unknown», а не выдуманная причина", () => {
    expect(causeOf("что-то странное")).toBe("unknown");
    expect(causeOf("")).toBe("unknown");
  });
});

describe("совет", () => {
  it("есть у любой ошибки, включая пустую и незнакомую", () => {
    // Ошибка без совета — тупик. Даже «неизвестно» должно вести куда-то.
    for (const text of ["", "что-то странное", "error", "нет сети", "движок не запустился"]) {
      const hint = hintFor(text);
      expect(hint.advice.length, text).toBeGreaterThan(10);
    }
  });

  it("никогда не говорит «попробуйте ещё раз»", () => {
    // Это не совет: он не меняет ничего и звучит как отговорка. Человек
    // повторит то же самое и получит ту же ошибку.
    for (const text of [
      "нет сети",
      "доступ запрещён",
      "файл занят",
      "не хватает места",
      "хеш не совпал",
      "движок не запустился",
      "модель не подошла",
      "неизвестно",
    ]) {
      const advice = hintFor(text).advice.toLowerCase();
      expect(advice, text).not.toContain("ещё раз");
      expect(advice, text).not.toContain("попроб");
    }
  });

  it("совет называет место, где чинить, а не только сочувствие", () => {
    // У каждой причины — конкретное место или действие.
    expect(hintFor("нет сети").advice).toContain("без сети");
    expect(hintFor("доступ запрещён").advice).toContain("администратора");
    expect(hintFor("файл занят").advice).toContain("Закройте");
    expect(hintFor("не хватает места").advice).toContain("Модели");
    expect(hintFor("хеш не совпал").advice).toContain("Скачайте");
    expect(hintFor("движок не запустился").advice).toContain("Проверка себя");
    expect(hintFor("модель не подошла").advice).toContain("Модели");
  });

  it("у неизвестной ошибки путь к разбору, а не пустота", () => {
    const hint = hintFor("что-то странное");
    expect(hint.cause).toBe("unknown");
    expect(hint.advice).toContain("Истори");
  });
});
