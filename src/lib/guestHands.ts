/**
 * Шаг 405: ограничение для гостя — только безопасные руки.
 *
 * Гость — это человек, которому доверяют **включить и посмотреть**, но не
 * доверяют менять файлы от имени хозяина. Поэтому у гостя:
 *
 *  * **только чтение**: посмотреть место на диске, найти файл, ответить на вопрос;
 *  * **никаких опасных рук** — и не «с подтверждением», а совсем: гость не может
 *    подтвердить то, что ему не разрешено (чужое согласие не считается моим, шаг
 *    403);
 *  * **и не «спросить хозяина»** тихо: если хозяина нет, дело не идёт, и это
 *    говорится прямо, а не «попробуйте позже».
 *
 * Почему «максимум пользы»: гость с урезанными правами всё равно должен получать
 * ответы. «Нельзя ничего» — это не безопасность, это сломанное приложение.
 */

import type { Risk } from "./dangerPolicy";
import { isDangerous } from "./dangerPolicy";

/** Что может гость. */
export function allowed(risk: Risk): { ok: boolean; said: string } {
  if (risk === "read") return { ok: true, said: "можно: чтение ничего не меняет" };
  if (isDangerous(risk)) {
    return {
      ok: false,
      said: "гостю нельзя: это меняет файлы или действует от имени хозяина. Попросите хозяина, или это сделает он сам",
    };
  }
  return { ok: false, said: "гостю нельзя: вне чтения" };
}

/**
 * Что происходит с делом, в котором есть и чтение, и удаление.
 *
 * Не «выполним безопасную часть и бросим»: половина дела — это не дело. Говорим
 * заранее, до первого шага, чтобы гость не ждал зря.
 */
export function wholePlan(risks: readonly Risk[]): { runs: boolean; said: string } {
  const bad = risks.find((risk) => risk !== "read");
  if (bad === undefined) return { runs: true, said: "всё дело — чтение: гость может выполнить целиком" };
  return {
    runs: false,
    said: "в деле есть шаг, который меняет файлы: для гостя оно не выполнится целиком. Начать и бросить на середине было бы хуже",
  };
}

/**
 * Кто подтверждает опасное — только хозяин, и только лично.
 *
 * Гость может **попросить** хозяина: дело встанет и будет ждать его ответа, но не
 * «одобрено, потому что рядом сидел взрослый».
 */
export function askOwner(what: string): { waiting: boolean; said: string } {
  return {
    waiting: true,
    said: `«${what}» ждёт хозяина: гость может попросить, но подтвердить должен он сам, в своём профиле`,
  };
}

/**
 * Что гость всё-таки может — чтобы «только чтение» не стало «ничего нельзя».
 */
export function useful(): string[] {
  return [
    "посмотреть, сколько места на диске и что занимает больше всего",
    "найти файл по имени и сказать, где он",
    "ответить на вопрос по уже сохранённым фактам хозяина — если хозяин это разрешил",
    "объяснить, что приложение умеет, и как попросить",
  ];
}

/**
 * Чего гость не может.
 *
 * Список совпадает с опасными руками (шаг 336), и это не совпадение: гость — это
 * «никаких опасных», а не отдельный выдуманный список.
 */
export function cannot(): string[] {
  return ["удалять и перемещать файлы", "отправлять что-либо от имени хозяина", "тратить деньги", "менять настройки системы", "писать в папки хозяина"];
}
