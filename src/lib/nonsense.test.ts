import { describe, expect, it } from "vitest";
import { NOISE_REPLY, dispose, isNoise } from "./nonsense";

/**
 * Шаг 44: тишина, щелчок и кашель не становятся задачей.
 *
 * Самая частая жалоба — не «не понял», а «понял не то»: человек откашлялся,
 * приложение пошло создавать папку «кхм». Ложная фраза хуже неудачи: неудачу
 * видно сразу, ложную фразу — только после действия.
 *
 * Половина проверок — про **узость** правила: отбросить настоящую просьбу хуже,
 * чем один раз отправить «кхм».
 */
describe("шум или просьба", () => {
  it("кашель, междометие и протяжный звук — шум", () => {
    for (const text of ["кхм", "э", "Эээ", "а-а-а", "ммм", "хм", "угу", "..."]) {
      expect(isNoise(text)).toBe(true);
    }
  });

  it("тишина — тоже не фраза", () => {
    expect(isNoise("")).toBe(true);
    expect(isNoise("   ")).toBe(true);
    expect(isNoise("\n\t")).toBe(true);
  });

  it("одно настоящее слово делает фразу речью", () => {
    // «мм, а тема где» — вопрос, а не шум. Правило смотрит все слова, а не
    // первое: иначе просьбу с междометием в начале отбрасывало бы.
    expect(isNoise("мм, а тема где")).toBe(false);
    expect(isNoise("а теперь удали папку")).toBe(false);
    expect(isNoise("убери")).toBe(false);
    // «а» — шум, но «а» в начале просьбы — уже речь.
    expect(isNoise("а")).toBe(true);
  });

  it("английские звуки — те же, потому что распознавание иногда переключается", () => {
    expect(isNoise("hmm")).toBe(true);
    expect(isNoise("uh")).toBe(true);
    // А настоящая английская фраза — не шум: правило не про язык.
    expect(isNoise("delete the folder")).toBe(false);
  });
});

describe("что делать с распознанным", () => {
  it("три исхода, и они не путаются", () => {
    // «Тишина» и «шум» — разные новости: в первом случае человек молчал, во
    // втором что-то сказал, но не то. Один ответ на оба хуже каждого.
    expect(dispose("создай папку")).toBe("send");
    expect(dispose("кхм")).toBe("noise");
    expect(dispose("   ")).toBe("silence");
  });

  it("«ничего не услышал» не говорится тому, кто кашлял", () => {
    // Он слышал — просто это был кашель. И не «не понял»: понял, что не слова.
    expect(NOISE_REPLY).not.toContain("ничего не услышал");
    expect(NOISE_REPLY).toContain("повторите");
    // Коротко: ответ не должен отнимать время у второй попытки.
    expect(NOISE_REPLY.length).toBeLessThan(60);
  });
});
