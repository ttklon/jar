/**
 * Шаг 314: откат обновления — файл предыдущей версии рядом, одна кнопка, без сети.
 *
 * «Откат» в описаниях звучит как функция. На деле он либо есть, либо нет, и
 * проверяется одним вопросом: **что человек сделает, если новая версия не
 * запускается?** Если ответ «напишет в поддержку и подождёт» — отката нет.
 *
 * Три условия, без которых он не работает:
 *
 *  1. **файл предыдущей версии лежит рядом** — не «на сервере», не «в архиве
 *     релизов». Без сети (шаг 314 прямо про это) сервер недоступен;
 *  2. **одна кнопка** — в окне ошибки, а не «найдите app.old в папке»;
 *  3. **данные не откатываются молча** — если старая версия не читает новую
 *     схему (шаг 313), это говорится **до** нажатия, а не после.
 *
 * Кнопка называется действием, а не словом «откат»: «Вернуть версию 1.9», с
 * номером. «Откатить» человеку ни о чём не говорит.
 */

/** Что лежит рядом с программой. */
export interface Previous {
  /** Номер предыдущей версии. */
  readonly version: string;
  /** Файл рядом: имя и размер — чтобы было видно, что он цел. */
  readonly file: string;
  readonly bytes: number;
  /** Читает ли он текущую схему данных. */
  readonly readsSchema: number;
}

/** Что делаем. */
export interface Offer {
  /** Есть ли кнопка вообще. */
  readonly available: boolean;
  /** Текст на кнопке — действием и с номером. */
  readonly label: string;
  /** Что человеку сказать до нажатия. */
  readonly warning: string;
}

/**
 * Предложить откат.
 *
 * `schema` — схема данных сейчас. Если предыдущая версия её не читает, кнопка
 * остаётся (иначе человека запрут), но предупреждение об этом — первым.
 */
export function offer(previous: Previous | null, schema: number): Offer {
  if (previous === null || previous.bytes <= 0) {
    return {
      available: false,
      label: "",
      warning: "файла предыдущей версии рядом нет — откат недоступен; обновиться можно после выхода исправления",
    };
  }

  const label = `Вернуть версию ${previous.version}`;

  if (previous.readsSchema < schema) {
    return {
      available: true,
      label,
      warning: `внимание: версия ${previous.version} знает схему данных только до ${previous.readsSchema}, а сейчас ${schema} — новые записи она не увидит. Сделаем копию данных перед откатом`,
    };
  }

  return { available: true, label, warning: `вернётся версия ${previous.version}; память и файлы останутся на месте` };
}

/**
 * Где взять файл.
 *
 * Ответ — «рядом с программой», и это проверяется: путь не в интернете и не в
 * временной папке, которую чистят.
 */
export function where(): string {
  return "в папке программы рядом с текущей версией; чистильщики временных файлов её не трогают";
}

/**
 * Работает ли откат без сети.
 *
 * Единственная честная проверка: все ли нужные файлы на диске. Если хоть один
 * надо докачать — это не откат без сети.
 */
export function offline(paths: readonly { file: string; present: boolean }[]): { ok: boolean; missing: string[] } {
  const missing = paths.filter((item) => !item.present).map((item) => item.file);
  return { ok: missing.length === 0, missing };
}

/**
 * Что происходит с данными.
 *
 * Откат программы — не откат данных. Копия делается **до** отката, и имя её
 * говорит, что внутри.
 */
export function dataCopy(schema: number): string {
  return `data-до-отката-схема-${schema}.bak`;
}

/**
 * Проверка кнопки.
 *
 * Ловит «Откатить», «Вернуться назад» и прочие надписи без номера версии: человек
 * должен видеть, на что меняет.
 */
export function labelProblems(offer: Offer): string[] {
  if (!offer.available) return [];
  const problems: string[] = [];
  if (!/\d+\.\d+/.test(offer.label)) problems.push("на кнопке нет номера версии: человек не видит, на что меняет");
  if (/^(откат|откатить|назад|вернуться)$/i.test(offer.label.trim())) problems.push("слово «откат» человеку ни о чём не говорит");
  if (offer.warning.trim().length < 20) problems.push("нет предупреждения до нажатия");
  return problems;
}
