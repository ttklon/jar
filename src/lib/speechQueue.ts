/**
 * Очередь произнесения: следующий кусок ждёт, пока договорит предыдущий.
 *
 * Зачем именно очередь, а не «сказать каждый кусок»: `speak()` в `voice.ts`
 * начинает с `synth.cancel()` — это правильно для новой реплики и разрушительно
 * для потока. Без очереди человек слышал бы только последний кусок фразы.
 *
 * Ещё три решения, каждое легко сделать неверно:
 *
 *  * **пустой кусок не занимает очередь.** Иначе «договорил» было бы событием
 *    ни о чём, и следующий кусок ждал бы впустую;
 *  * **перебивание очищает всю очередь, а не один кусок.** Человек сказал
 *    «стоп» — договаривать остальное уже невежливо;
 *  * **ошибка синтеза не вешает очередь.** Если произнести не вышло, очередь
 *    идёт дальше, а причина уходит в `onProblem`: молчать обо всей фразе из-за
 *    одного сбоя — худший вариант из трёх.
 */

/** Как произнести один кусок. `false` — синтеза речи в окружении нет. */
export type Say = (text: string) => boolean;

export interface SpeechQueue {
  /** Поставить фразу в очередь. Пустая строка игнорируется. */
  push: (text: string) => void;
  /** Предыдущая фраза договорена (или не смогла начаться). */
  done: () => void;
  /** Перебили: замолчать и забыть всё, что ещё не сказано. */
  clear: () => void;
  /** Что в очереди прямо сейчас — для проверок и для «сказано N из M». */
  pending: () => number;
}

export function createSpeechQueue(
  say: Say,
  onProblem: (why: "no-voice" | "empty") => void = () => {},
): SpeechQueue {
  let queue: string[] = [];
  let speaking = false;
  let told = false;

  const next = () => {
    while (queue.length > 0) {
      // Куски приходят из потока с ведущим пробелом («. Сейчас»): пробел — это
      // разделитель фраз, а не часть речи. Срезаем, иначе он попадёт в синтез.
      const text = (queue.shift() as string).trim();
      if (text.length === 0) continue;

      // `speaking` выставляется ДО `say`: синтез может сообщить «договорил»
      // синхронно (короткая фраза, мгновенный движок), и тогда очередь обязана
      // уже знать, что говорит, — иначе `done()` сбросит флаг на пустоту и
      // следующий кусок не начнётся вовсе.
      speaking = true;
      if (say(text)) {
        return;
      }
      speaking = false;
      // Синтеза нет: очередь не может «договорить» никогда. Не копим её и не
      // притворяемся, что сказали, — называем причину один раз за ответ, а не
      // на каждую фразу: десять одинаковых сообщений — это шум.
      if (!told) onProblem("no-voice");
      told = true;
      queue = [];
      speaking = false;
      return;
    }
    speaking = false;
  };

  return {
    push(text: string): void {
      if (text.trim().length === 0) return;
      queue.push(text);
      if (!speaking) next();
    },
    done(): void {
      speaking = false;
      next();
    },
    clear(): void {
      queue = [];
      speaking = false;
    },
    pending(): number {
      return queue.length;
    },
  };
}
