/**
 * Удаление модели освобождает место, и это видно сразу (шаг 80).
 *
 * Дефект. Модель скачана, места на диске нет, и человек хочет её убрать. Что
 * происходит:
 *
 *  * **непонятно, сколько освободится** — «удалить модель» не говорит, 400 МБ
 *    это или 4.7 ГБ, а от этого зависит, поможет ли вообще;
 *  * **непонятно, где место**: написано «освобождено», а в проводнике та же
 *    цифра. Значит удалилось не то или не удалилось вовсе;
 *  * **непонятно, что теперь не работает**: удалил модель — перестал работать
 *    разговор, и это выясняется в следующий раз, когда человек хочет поговорить.
 *
 * Правило: **удаление называет три числа и одно следствие**.
 *
 *  1. **Сколько освободится** — до нажатия, на кнопке.
 *  2. **Сколько свободно стало** — после, обновлённым числом, а не «готово».
 *  3. **Сколько всего свободно** — чтобы человек понимал, хватает ли теперь на
 *     что-то ещё.
 *  4. **Что перестанет работать** — до нажатия: «разговор без этой модели не
 *     заработает, пока не скачаете снова».
 *
 * Почему не «удалить и спросить потом». Удаление необратимо: заново — это
 * полчаса загрузки. Вопрос после действия — это не выбор, а сообщение о
 * случившемся.
 */

/** Что известно о диске и модели. */
export interface Space {
  /** Сколько займёт удаляемая модель, мегабайт. */
  modelMb: number;
  /** Сколько свободно сейчас, мегабайт. */
  freeMb: number;
}

/** По-человечески: «4.5 ГБ», а не «4608 МБ». */
export function size(mb: number): string {
  if (mb < 1024) return `${Math.round(mb)} МБ`;
  return `${Math.round((mb / 1024) * 10) / 10} ГБ`;
}

/**
 * Что будет освобождено — **до** нажатия.
 *
 * На кнопке, а не в справке: от числа зависит, поможет ли удаление вообще.
 */
export function willFree(got: Space): string {
  return `освободится ${size(got.modelMb)}, свободно станет ${size(got.freeMb + got.modelMb)}`;
}

/**
 * Что перестанет работать — **до** нажатия.
 *
 * Названо следствие, а не «модель будет удалена»: удаление — это то, что
 * человек и так знает, а последствие — нет.
 */
export function breaks(name: string): string {
  return `без «${name}» разговор не запустится, пока вы не скачаете её снова`;
}

/**
 * Что показать после удаления.
 *
 * Три числа: сколько освободилось, сколько стало и сколько было, — чтобы
 * человек **сверил** с проводником. Расхождение здесь означает, что удалилось
 * не то, и это лучше заметить сразу.
 */
export function done(before: Space): string {
  return `удалено: освободилось ${size(before.modelMb)}, свободно ${size(before.freeMb + before.modelMb)} (было ${size(before.freeMb)})`;
}

/**
 * Хватит ли места после удаления на новую модель.
 *
 * Человек часто удаляет одну, чтобы скачать другую. Сказано **хватит или нет**
 * до удаления: иначе он удаляет, скачивает и снова упирается в место.
 */
export function enoughFor(before: Space, needMb: number): string {
  const after = before.freeMb + before.modelMb;
  return after >= needMb
    ? `после удаления хватит на модель ${size(needMb)} (свободно будет ${size(after)})`
    : `после удаления всё равно не хватит: нужно ${size(needMb)}, будет ${size(after)}`;
}

/**
 * Не удалять последнюю рабочую модель молча.
 *
 * Удалить единственную модель — законное желание («освобождаю диск»), но
 * приложение должно сказать, что после этого не работает **ничего**, а не
 * «модель удалена».
 */
export function lastOne(name: string): string {
  return `это последняя модель: после удаления приложение не сможет отвечать, пока вы не скачаете «${name}» или другую`;
}

/**
 * Подтверждение перед удалением — одним вопросом.
 *
 * Не модальное окно с тремя кнопками: человек уже решил, ему нужны числа и
 * следствие, а не выбор.
 */
export function confirm(got: Space, name: string): string {
  return `${willFree(got)}. ${breaks(name)}`;
}
