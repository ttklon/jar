/**
 * Бюджет задержки: простой ответ ≤ 1,5 с до первого звука на средней машине (шаг 123).
 *
 * Дефект. «Быстро» — это **ощущение**, а не число, и из-за этого:
 *
 *  * **цель не проверяема**: «отвечать быстро» нельзя ни подтвердить, ни опровергнуть;
 *  * **«слабый компьютер» объясняет всё**: любая задержка списывается на железо, и
 *    ни одна не признаётся дефектом;
 *  * **сложное и простое меряют одинаково**: разбор фразы и загрузка модели — разные
 *    задачи, и один бюджет на них либо слишком щедрый, либо слишком строгий;
 *  * **бюджет на всё дело вместо первого звука**: человек судит о скорости по тому,
 *    как скоро он **услышал** ответ, а не по тому, когда закончилось дело.
 *
 * Правило: **бюджет — число до первого звука, и он разный для простого и сложного**.
 *
 *  1. **Цель в миллисекундах**: простой ответ — 1500 мс **до первого звука**. Это то,
 *     что человек чувствует.
 *  2. **Простое и сложное различаются**: сложный разбор — не «медленный ответ», и
 *     сравнивать его с простым значит наказывать за честность.
 *  3. **Средняя машина названа**: бюджет по умолчанию — для машины, которую мы
 *     считаем средней; на слабой он **масштабируется**, а не игнорируется.
 *  4. **Нарушение — дефект, а не характер**: за пределами бюджета — пометка (шаг 124),
 *     и «слабый компьютер» — объяснение, а не оправдание.
 *  5. **Бюджет не двигают под результат**: иначе цель всегда достигается. Менять
 *     бюджет — отдельное решение с причиной.
 *
 * Почему не «бюджет на всё дело». Дело может идти минуту законно (переименование
 * 12 000 файлов), а первый звук — нет: молчание дольше полутора секунд человек
 * читает как «не услышало».
 */

/** Куда смотрим: бюджет ставится на первый звук, а не на конец дела. */
export type Milestone = "first-sound" | "first-token" | "deed";

/** Бюджет по классу задачи. */
export interface Budget {
  /** Простой ответ: разговор, короткая команда. */
  simple: number;
  /** Сложное: разбор длинной фразы, план из нескольких рук. */
  complex: number;
  /** Масштаб для машины: `1` — средняя, `2` — вдвое медленнее. */
  scale: number;
}

/**
 * Бюджет по умолчанию.
 *
 * 1,5 с — обещание из плана, а не измерение: его и проверяем.
 */
export const DEFAULT: Budget = { simple: 1500, complex: 4000, scale: 1 };

/** Что пришло от замера (шаг 121). */
export interface Spent {
  /** Класс задачи: простой ответ или сложный разбор. */
  kind: "simple" | "complex";
  /** Миллисекунды до первого звука. `null` — звука не было (напечатано, не сказано). */
  ms: number | null;
}

/** Вердикт по бюджету. */
export interface Verdict {
  /** Уложились ли. `null` — сравнивать не с чем. */
  within: boolean | null;
  /** Предел, с которым сравнивали, — числом: «1500 мс». */
  limit: number;
  /** Нарушение названо: пользователь видит его в отчёте (шаг 124). */
  violation: boolean;
  /** Словами. */
  said: string;
}

/**
 * Предел для задачи.
 *
 * Масштаб машины **умножает** бюджет, а не отменяет: на слабой машине цель мягче, но
 * она есть.
 */
export function limit(budget: Budget, kind: "simple" | "complex"): number {
  return Math.round(budget[kind] * budget.scale);
}

/**
 * Проверка бюджета.
 *
 * `null` — не «уложились»: если звука не было, бюджет до первого звука не про что.
 * Это и есть честный ответ, а не зелёная галочка.
 */
export function check(budget: Budget, spent: Spent): Verdict {
  const cap = limit(budget, spent.kind);
  if (spent.ms === null) {
    return {
      within: null,
      limit: cap,
      violation: false,
      said: `бюджет до первого звука не проверен: звука не было (предел ${cap} мс)`,
    };
  }
  if (spent.ms <= cap) {
    return { within: true, limit: cap, violation: false, said: `в бюджете: ${Math.round(spent.ms)} мс из ${cap}` };
  }
  // Нарушение — дефект, а не характер: «слабый компьютер» — объяснение, не оправдание.
  return {
    within: false,
    limit: cap,
    violation: true,
    said: `нарушение бюджета: ${Math.round(spent.ms)} мс вместо ${cap} — это дефект, а не характер машины`,
  };
}

/**
 * Итог по нескольким ответам.
 *
 * Доля нарушений — число, которое можно чинить; «в основном быстро» — нет.
 */
export function tally(budget: Budget, all: readonly Spent[]): { checked: number; violations: number; share: number } {
  const checked = all.filter((item) => item.ms !== null);
  const violations = checked.filter((item) => check(budget, item).violation).length;
  return { checked: checked.length, violations, share: checked.length === 0 ? 0 : violations / checked.length };
}

/** Итог словами — для отчёта. */
export function say(got: { checked: number; violations: number; share: number }): string {
  if (got.checked === 0) return "бюджет задержки не проверялся — замеров нет";
  if (got.violations === 0) return `бюджет держится: 0 нарушений из ${got.checked}`;
  return `нарушений бюджета: ${got.violations} из ${got.checked} (${Math.round(got.share * 100)}%)`;
}

/**
 * Что сказать про масштаб машины.
 *
 * Масштаб — **отдельное** решение: бюджет не двигают молча под результат.
 */
export function scaled(budget: Budget): string {
  if (budget.scale === 1) return `бюджет для средней машины: ${budget.simple} мс до первого звука`;
  return `бюджет умножен на ${budget.scale} для этой машины: ${budget.simple} → ${limit(budget, "simple")} мс`;
}
