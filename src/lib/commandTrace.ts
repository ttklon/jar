/**
 * Шаг 435: любая команда в журнале связана с делом, фразой и результатом.
 *
 * Запись «удаление — ок» бесполезна: непонятно, чья она, зачем и чем кончилась.
 * Чтобы журнал годился для разбора, **каждая** строка обязана отвечать на три
 * вопроса, и все три — ссылками, а не копиями:
 *
 *  * **дело** — какое (id или имя);
 *  * **фраза** — что человек сказал (вычищенная, шаг 98);
 *  * **результат** — что вышло, с доказательством (шаг 380).
 *
 * Ссылки, а не копии: одна фраза на всё дело, иначе в пяти строках пять копий, и
 * они разойдутся.
 *
 * И отдельное правило, без которого связь бесполезна: **сирота — ошибка**.
 * Строка без дела не «служебная», а потерянная: её нельзя ни найти по делу, ни
 * удалить вместе с ним.
 */

/** Строка журнала. */
export interface Entry {
  /** Команда: что именно делали. */
  readonly command: string;
  /** Дело, к которому относится; `null` — служебная строка уровня «мелочь». */
  readonly deed: string | null;
  /** Фраза человека, уже вычищенная. */
  readonly said: string;
  /** Результат. */
  readonly result: "done" | "failed" | "cancelled";
  /** Доказательство — если done. */
  readonly proof?: string;
}

/**
 * Проверить связь.
 *
 * Возвращает **сирот** — строк с результатом, но без дела или без фразы.
 * Служебные строки (без результата) не считаются: им связь не нужна.
 */
export function orphans(entries: readonly Entry[]): string[] {
  return entries
    .filter((entry) => entry.deed === null || entry.said.trim() === "")
    .map((entry) => entry.command);
}

/**
 * Одна строка по-русски.
 *
 * Дело и команда — первыми: по ним ищут. Фраза и доказательство — в скобках.
 */
export function line(entry: Entry): string {
  const where = entry.deed === null ? "без дела" : `дело «${entry.deed}»`;
  const tail: string[] = [];
  if (entry.said.trim() !== "") tail.push(`просили: «${entry.said}»`);
  if (entry.result === "done" && entry.proof) tail.push(entry.proof);

  const result = resultWord(entry.result);
  return `${where}: ${entry.command} — ${result}${tail.length > 0 ? ` (${tail.join("; ")})` : ""}`;
}

/** Результат по-русски. */
export function resultWord(result: Entry["result"]): string {
  const words: Record<Entry["result"], string> = { done: "сделано", failed: "не получилось", cancelled: "отменено" };
  return words[result];
}

/**
 * Все строки одного дела.
 *
 * По ним разбирают: «что происходило в этом деле» — по порядку, как записано.
 */
export function ofDeed(entries: readonly Entry[], deed: string): Entry[] {
  return entries.filter((entry) => entry.deed === deed);
}

/**
 * Что связь не делает.
 *
 * Не копирует фразу в каждую строку и не теряет её: одна ссылка на дело.
 */
export function notCopied(): string {
  return "фраза хранится у дела одна, а строки ссылаются на неё: копия в каждой строке разошлась бы при первой же правке";
}

/**
 * Что проверяет тест.
 *
 * Три требования к каждой неслужебной строке.
 */
export function checks(): string[] {
  return [
    "есть дело: строку можно найти по делу и удалить вместе с ним",
    "есть фраза человека — вычищенная, но его словами",
    "есть результат; у «сделано» — доказательство, а не только слово",
  ];
}
