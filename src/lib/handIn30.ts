/**
 * Шаг 476: руководство разработчика — как добавить руку за 30 минут.
 *
 * Шаг 468 дал порядок действия. Здесь — **время**: руководство, по которому рука
 * добавляется за полчаса, а не за день. Тридцать минут — не обещание, а бюджет:
 * на каждом шаге сказано, сколько он занимает и **что делать, если не успел**.
 *
 * Почему бюджет важнее подробности: если шаг не влезает в свои минуты, значит
 * что-то не так с шагом, а не с разработчиком. И тогда это видно сразу, а не
 * через три дня, когда «доделаю потом» стало нормой.
 */

/** Шаг с бюджетом времени. */
export interface Step {
  readonly n: number;
  /** Что сделать. */
  readonly do: string;
  /** Бюджет в минутах. */
  readonly minutes: number;
  /** Что делать, если не уложился: сократить, а не растянуть. */
  readonly ifLate: string;
}

/** Всего минут на руку. */
export const BUDGET = 30;

/**
 * Шаги добавления руки.
 *
 * Пять шагов, сумма — ровно бюджет; это проверяется, а не декларируется.
 */
export function steps(): Step[] {
  return [
    { n: 1, do: "проверить, что руки ещё нет: `ls src/lib | grep -i <тема>` и `git log -1 -- <путь>`", minutes: 3, ifLate: "не искать дольше: если за три минуты не понял, есть ли, — считай, что нет, и добавляй с другим именем" },
    { n: 2, do: "описать правило в `src/lib/<рука>.ts`: вход — фраза, выход — что сделать; без Rust и без окна", minutes: 10, ifLate: "если правило не влезает в десять минут — оно слишком большое: разделить на две руки, а не растягивать" },
    { n: 3, do: "добавить в `DANGEROUS`, если рука что-то удаляет, отправляет или меняет необратимо", minutes: 2, ifLate: "пропускать нельзя: без записи рука не спросит подтверждения — это дефект, а не недоделка" },
    { n: 4, do: "тест рядом: по одному `describe` на правило и мутация нарочно, чтобы он упал", minutes: 10, ifLate: "не сокращать тест: лучше одна рука без реализации, чем рука без теста" },
    { n: 5, do: "строка в реестре действий и прогон `npx tsc -b`", minutes: 5, ifLate: "прогон не пропускать: неиспользуемый импорт не ловит `vitest`, а ловит CI" },
  ];
}

/**
 * Сводка бюджета.
 *
 * Сумма считается: руководство, которое не укладывается в бюджет, обещает
 * больше, чем может.
 */
export function budget(list: readonly Step[] = steps()): { total: number; ok: boolean; said: string } {
  const total = list.reduce((sum, step) => sum + step.minutes, 0);
  return { total, ok: total <= BUDGET, said: `шагов ${list.length}, минут ${total} из ${BUDGET}${total > BUDGET ? " — не укладывается: сокращать шаги, а не бюджет" : ""}` };
}

/**
 * Что делать, если рука не влезла.
 *
 * Три исхода — и все про то, чтобы рука была маленькой.
 */
export function ifTooBig(): string[] {
  return [
    "разделить на две руки: каждая со своим правилом и своим тестом",
    "вынести сложность в правило (`src/lib`), а не в выполнение",
    "если и после этого не влезает — рука ещё не понята: вернуться к шагу 2 с меньшим объёмом",
  ];
}

/**
 * Чего руководство не позволяет.
 *
 * Три запрета; первый — «доделаю потом».
 */
export function notDo(): string[] {
  return [
    "не «доделаю потом»: шаг, который не влез, сокращают сейчас",
    "не пропуск `DANGEROUS` ради сроков",
    "не рука без теста «пока так»: она пройдёт в релиз",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу обещаний.
 */
export function checks(): string[] {
  return [
    "сумма шагов не больше тридцати минут — посчитано, а не написано",
    "у каждого шага есть «что делать, если не уложился»",
    "опасность руки — на третьем шаге, до реализации",
  ];
}
