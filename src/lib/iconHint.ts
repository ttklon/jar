/**
 * Подсказки к иконкам появляются и с клавиатуры (шаг 193).
 *
 * Дефект. Подсказка у нас была одна — атрибут `title`. Он делает ровно две вещи,
 * и обе не те:
 *
 *  * **появляется только от мыши.** Человек, идущий по экрану Tab'ом, подсказку не
 *    видит вовсе: у него нет курсора, который надо навести;
 *  * **не доходит до диктора как подсказка.** `title` читается как имя элемента,
 *    только если другого имени нет, и **молчит**, если имя есть: у кнопки с
 *    `aria-label` подсказка `title` не объявляется — то есть теряется самая
 *    полезная часть, «что будет»;
 *  * **показывается с задержкой в секунду** и исчезает через несколько: с
 *    клавиатуры это не подсказка, а лотерея.
 *
 * Правила:
 *
 *  1. **подсказка привязана через `aria-describedby`**, а не через `title`:
 *     тогда её читают и глаза (по фокусу), и диктор;
 *  2. **с клавиатуры — по фокусу, без задержки.** Фокус уже значит «я здесь»;
 *     ждать секунду, чтобы узнать, куда попал, — это про мышь;
 *  3. **имя и подсказка — разные вещи.** Имя — что это («Озвучить»), подсказка —
 *     что будет («озвучит ответ службой Windows; текст уйдёт системе»). Слить их
 *     значит либо потерять имя, либо потерять предупреждение;
 *  4. **Esc закрывает, фокус не теряется**: подсказка не диалог;
 *  5. **идентификатор выводится из имени**, а не случайный: случайный меняется
 *     при каждой перерисовке, и `aria-describedby` начинает указывать в пустоту.
 *
 * Модуль не рисует: он отвечает, что показать и по какому событию.
 */

/** Что показать. */
export interface IconHint {
  /** Имя элемента — короткое: «Озвучить». */
  name: string;
  /** Подсказка — что будет: «озвучит ответ службой Windows…». */
  hint: string;
  /** Идентификатор, на который указывает `aria-describedby`. */
  describedBy: string;
}

/** Событие, которое открыло подсказку. */
export type Trigger = "focus" | "hover" | "press" | "escape" | "blur" | "leave";

/**
 * Показать ли подсказку по событию.
 *
 * С клавиатуры — немедленно: фокус уже значит «я здесь». С мыши — тоже, и
 * `hover` не отменяет уже открытую по фокусу: две подсказки одновременно — две
 * правды, и она мигает у человека, который пользуется обоими способами.
 */
export function show(trigger: Trigger, alreadyOpen: boolean): boolean {
  if (trigger === "focus") return true;
  if (trigger === "hover") return true;
  if (trigger === "press") return true;
  if (trigger === "escape") return false;
  if (trigger === "blur" || trigger === "leave") return false;
  return alreadyOpen;
}

/**
 * Что сказать диктору.
 *
 * Имя и подсказка — **две фразы**, а не одна слипшаяся: человек слышит
 * «Озвучить. озвучит ответ…», а не «Озвучить озвучит ответ».
 */
export function spoken(got: IconHint): string {
  const name = got.name.trim();
  const hint = got.hint.trim();
  if (name.length === 0) return hint;
  if (hint.length === 0) return name;
  return `${name}. ${hint}`;
}

/**
 * Идентификатор подсказки для `aria-describedby`.
 *
 * Из имени, а не случайный. Пробелы и знаки — в дефисы: id с пробелом не
 * находится, и `aria-describedby` молча указывает в никуда.
 */
export function id(name: string): string {
  const slug = name
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, "-")
    .replace(/^-+|-+$/g, "");
  return `hint-${slug.length > 0 ? slug : "icon"}`;
}

/**
 * Есть ли у элемента всё, что нужно для доступной подсказки.
 *
 * «Добавили `aria-describedby`» и «добавили, куда он указывает» — разные вещи, и
 * вторая забывается. `title` при этом остаётся законным, но **не считается**
 * подсказкой: он только для мыши.
 */
export function complete(element: { label: string; describedBy: string; target: string }): {
  ok: boolean;
  why: string;
} {
  if (element.label.trim().length === 0) return { ok: false, why: "нет имени: диктор скажет «кнопка»" };
  if (element.describedBy.trim().length === 0) {
    return { ok: false, why: `${element.label}: нет подсказки — с клавиатуры узнавать нечего` };
  }
  if (element.describedBy !== element.target) {
    return {
      ok: false,
      why: `${element.label}: aria-describedby указывает на «${element.describedBy}», а подсказка называется «${element.target}»`,
    };
  }
  return { ok: true, why: "" };
}
