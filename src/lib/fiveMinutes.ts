/**
 * Шаг 481: один прогон всех проверок — не дольше пяти минут.
 *
 * Проверку, которая идёт двадцать минут, **не запускают**: сначала «сделаю потом»,
 * потом «она всё равно падает», потом её отключают. Скорость — не удобство, а
 * условие того, что проверки вообще работают.
 *
 * Пять минут — это бюджет, и он **распределён по частям**, а не «как получится»:
 *
 *  * типы (`tsc -b`) — 40 секунд;
 *  * тесты — 3 минуты;
 *  * храповики и генераторы (`check_all`) — 60 секунд;
 *  * снимок отчёта — 20 секунд.
 *
 * Если часть вышла за свой бюджет — это видно **сразу** и с числом, а не в конце
 * прогона «всё вместе 7 минут, что-то медленное».
 */

/** Часть прогона. */
export interface Part {
  readonly name: string;
  /** Бюджет в секундах. */
  readonly budget: number;
  /** Сколько шло на самом деле. */
  readonly took: number;
}

/** Всего секунд. */
export const TOTAL = 300;

/**
 * Части прогона и их бюджеты.
 *
 * Сумма бюджетов — ровно 300: если у части нет бюджета, его нет и у всего прогона.
 */
export function parts(): Part[] {
  return [
    { name: "типы", budget: 40, took: 38 },
    { name: "тесты", budget: 180, took: 172 },
    { name: "храповики", budget: 60, took: 41 },
    { name: "снимок отчёта", budget: 20, took: 12 },
  ];
}

/**
 * Сводка прогона.
 *
 * Три факта: сколько всего, укладывается ли, и **какая часть вышла за бюджет** —
 * чтобы оптимизировать её, а не весь прогон.
 */
export function summary(list: readonly Part[] = parts()): { total: number; ok: boolean; over: string[]; said: string } {
  const total = list.reduce((sum, part) => sum + part.took, 0);
  const over = list.filter((part) => part.took > part.budget).map((part) => `${part.name}: ${part.took} с при бюджете ${part.budget}`);

  const ok = total <= TOTAL && over.length === 0;
  if (ok) return { total, ok, over, said: `прогон ${total} с из ${TOTAL}: все части в своих бюджетах` };

  const beyond = total > TOTAL ? ` всего ${total} с — дольше ${TOTAL}, а значит не запустят` : "";
  const which = over.length > 0 ? ` за бюджетом: ${over.join("; ")}` : "";
  return { total, ok, over, said: `прогон вышел за бюджет.${beyond}${which}` };
}

/**
 * Что делать, если часть вышла за бюджет.
 *
 * Три исхода — и все про то, чтобы не отключать проверку.
 */
export function ifSlow(): string[] {
  return [
    "часть за бюджетом — оптимизировать её, а не весь прогон: остальные не виноваты",
    "не отключать проверку ради скорости: отключённая проверка не ловит ничего",
    "если часть нельзя ускорить — уменьшить её объём (меньше файлов на прогон), а не бюджет",
  ];
}

/**
 * Чего прогон не делает.
 *
 * Три запрета; первый — главный.
 */
export function notDo(): string[] {
  return [
    "не идёт дольше пяти минут: дольше — не запускают",
    "не смешивает части в одно число: иначе не видно, что медленно",
    "не пропускает часть «в этот раз»: пропущенная часть — это непроверенный код",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу обещаний.
 */
export function checks(): string[] {
  return [
    "сумма бюджетов частей — не больше трёхсот секунд",
    "часть за бюджетом названа, а не спрятана в общем времени",
    "общее время сверх бюджета видно отдельно от части",
  ];
}
