/**
 * Вердикт проверки — вместе с машиной, ОС, версией и датой (шаги 3 и 4).
 *
 * Дефект, который это лечит. В документах и на экранах стояло «работает» без
 * того, **где** это видели. Через месяц такой статус нельзя ни опровергнуть, ни
 * воспроизвести: неизвестно, на какой машине, под какой Windows и в какой версии
 * приложения его получили. Он не доказывает ничего и при этом выглядит
 * доказательством.
 *
 * Правило поэтому жёсткое: вердикт без машины, ОС, версии и даты — **не
 * доказательство**, и называется «не проверено», а не «работает». Это не
 * педантизм: именно из-за отсутствия этих четырёх полей слово «готово» уже один
 * раз вводило в заблуждение.
 *
 * Зачем ещё «срок годности». Даже полное доказательство стареет: драйвер
 * обновился, Windows обновилась, версия приложения сменилась. Доказательство,
 * полученное на другой версии приложения, к этой версии не относится, и
 * `stillHolds` это говорит прямо, а не оставляет читателю соображать.
 */

/** Что за машина и в каких условиях получен вердикт. */
export interface Proof {
  /** Имя машины (hostname) — не «компьютер пользователя». */
  machine: string;
  /** ОС с версией: «Windows 11 23H2». Без версии ОС не отличить от другой. */
  os: string;
  /** Версия приложения: `0.1.0`. */
  appVersion: string;
  /** Когда проверено, ISO-дата. Дата — потому что доказательство стареет. */
  checkedAt: string;
}

/** Вердикт: что проверили и что получилось. */
export interface Verdict {
  /** Что именно проверяли — коротко, понятием человека. */
  what: string;
  /** Получилось или нет. */
  passed: boolean;
  /** Где и когда. `null` — не записано, и тогда это не доказательство. */
  proof: Proof | null;
}

/**
 * Полнота доказательства.
 *
 * Пустая строка — такой же пробел, как отсутствие: `machine: " "` не говорит,
 * на какой машине проверяли. Проверяем **все** поля, потому что любое
 * отсутствующее ломает воспроизводимость: без ОС не повторить, без версии не
 * отнести к сборке, без даты не понять, актуально ли.
 */
export function complete(proof: Proof | null): proof is Proof {
  if (!proof) return false;
  const fields: (string | undefined)[] = [proof.machine, proof.os, proof.appVersion, proof.checkedAt];
  return fields.every((field) => typeof field === "string" && field.trim().length > 0);
}

/** Можно ли считать вердикт доказательством. Без полного `proof` — нет. */
export function isProof(verdict: Verdict): boolean {
  return verdict.passed && complete(verdict.proof);
}

/**
 * Как вердикт называется человеку.
 *
 * Не «работает / не работает», а с границей: «доказано на этой машине» или
 * «не доказано». Второе — не обвинение и не поломка: это честное «здесь не
 * проверяли». Разница между «сломано» и «не проверено» — это и есть шаг 4.
 */
export function proofLabel(verdict: Verdict): string {
  if (!verdict.passed) return "провал";
  return complete(verdict.proof) ? "доказано на этой машине" : "не доказано";
}

/**
 * Держится ли доказательство для текущих условий.
 *
 * Почему по версии приложения, а не по сроку. Истечение по календарю — это
 * догадка («месяц прошёл, наверное, сломалось»), а смена версии — факт: код
 * другой, и доказательство относится к другому коду. ОС сравнивается по
 * строке целиком: обновление Windows меняет строку, и это тоже смена условий.
 * `null` — условий не знаем, и тогда честнее не утверждать, что держится.
 */
export function stillHolds(verdict: Verdict, now: { os: string; appVersion: string } | null): boolean {
  if (!isProof(verdict) || verdict.proof === null) return false;
  if (!now) return false;
  return verdict.proof.appVersion === now.appVersion && verdict.proof.os === now.os;
}

/**
 * Строка «на этой машине доказано / не доказано» (шаг 4).
 *
 * Одна фраза, которую можно поставить рядом с любым экраном. Она отвечает на
 * вопрос, который человек задаёт **до** нажатия: «а это здесь точно сработает?»
 * Молчание на этот вопрос читается как «да».
 *
 * Когда доказательств несколько (их и бывает несколько), правило простое: экран
 * считается доказанным, только если доказаны **все** его утверждения. Одно
 * непроверенное — и граница есть.
 */
export function borderLine(verdicts: readonly Verdict[], now: { os: string; appVersion: string } | null): string {
  if (verdicts.length === 0) {
    // Пусто — это не «всё хорошо»: это «здесь ничего не проверяли».
    return "на этой машине не доказано: проверок не было";
  }
  const proven = verdicts.filter((verdict) => stillHolds(verdict, now)).length;
  if (proven === verdicts.length) {
    return `на этой машине доказано: ${proven} ${plural(proven, "проверка", "проверки", "проверок")}`;
  }
  const unproven = verdicts.length - proven;
  // Называем, чего не хватает: «не доказано» без числа — упрёк, с числом — работа.
  return `на этой машине не доказано: ${unproven} из ${verdicts.length} ${plural(verdicts.length, "проверки", "проверок", "проверок")}`;
}

function plural(count: number, one: string, few: string, many: string): string {
  const mod10 = count % 10;
  const mod100 = count % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
