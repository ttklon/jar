/**
 * Шаг 269: память не хранит секреты — пароли, ключи, токены не попадают.
 *
 * Разрыв, который это закрывает. `secrets.ts` (шаг 98) уже умеет вычищать
 * секреты из фразы: `clean()` находит `sk-…`, `ghp_…`, «пароль: …», номер
 * карты. Но память — **другой склад**, и проверка к ней не подключена: фраза
 * вычищалась **до отправки модели**, а в память писалась как есть. То есть
 * секрет не уходил наружу и оставался на диске — что ничем не лучше.
 *
 * Почему проверка стоит **на записи**, а не на чтении. Вычистить при чтении
 * значит хранить секрет и надеяться, что все читатели вспомнят о проверке.
 * Рано или поздно один не вспомнит: экспорт памяти (шаг 266), поиск по памяти
 * (шаг 268), отчёт. Поэтому в память секрет не попадает **вовсе**.
 *
 * Правила:
 *
 *  1. **вычистка до записи.** Не «пометим, что там секрет» — вычистим;
 *  2. **место помечено.** `[секрет]` вместо значения: «какой ключ я давал» —
 *     вопрос, на который память честно отвечает «был ключ, не храню»;
 *  3. **что нашли — сказано, само значение — нет.** Сообщение не должно
 *     повторять секрет: иначе он попадёт в журнал, из которого его не убрать;
 *  4. **не только «пароль», но и форма.** Секретом бывает длинная строка без
 *     слова «пароль» рядом — ключ по префиксу, номер карты, JWT. Проверка
 *     ищет **и слово, и форму**.
 */

import { clean, type Clean } from "./secrets";

/** Что записывается в память. */
export interface Fact {
  /** Вид: `folder`, `program`, `voice`, `method` … */
  readonly kind: string;
  /** Значение — то, что человек назвал. */
  readonly value: string;
}

/** Итог проверки перед записью. */
export interface Guarded {
  /** Что можно писать: значение уже вычищено. */
  readonly fact: Fact;
  /** Найдено ли секретное. */
  readonly secret: boolean;
  /** Что сказать человеку — без самого секрета. */
  readonly said: string;
  /** Что нашли: виды, а не значения. */
  readonly found: readonly string[];
}

/**
 * Подготовить факт к записи в память.
 *
 * Вызывать **до** записи, а не после: у памяти нет «отменить» (шаг 263 — «вернуть
 * нельзя»), и вычищать записанное значит переписывать историю.
 */
export function guard(fact: Fact): Guarded {
  const got: Clean = clean(fact.value);
  if (!got.any) {
    return { fact, secret: false, said: "", found: [] };
  }
  return {
    fact: { kind: fact.kind, value: got.text },
    secret: true,
    // Значение не повторяется: «нашёл ключ» — ответ, «нашёл ключ sk-abc…» —
    // утечка в журнал, из которого его уже не убрать.
    said:
      `в памяти будет «${got.text}»: нашёл ${got.found.join(", ")} — не храню. ` +
      "Само значение в память не попало",
    found: got.found,
  };
}

/**
 * Пакет: подготовить много фактов за раз.
 *
 * Один проход по всем, а не «по одному с проверкой на каждом шаге»: так нельзя
 * забыть проверку на третьем вызове из пяти — именно так она и пропадает.
 */
export function guardAll(facts: readonly Fact[]): { saved: Fact[]; said: string[]; secrets: number } {
  const saved: Fact[] = [];
  const said: string[] = [];
  let secrets = 0;
  for (const fact of facts) {
    const got = guard(fact);
    // Факт с секретом **не выбрасывается целиком**: «папка с паролем» — это
    // всё ещё папка, и забыть её значит забыть полезное вместе с опасным.
    saved.push(got.fact);
    if (got.secret) {
      secrets += 1;
      said.push(got.said);
    }
  }
  return { saved, said, secrets };
}

/**
 * Проверка того, что уже лежит в памяти.
 *
 * Нужна отдельно от `guard`: записи, сделанные **до** этой правки, никто не
 * вычищал. Проверка говорит, сколько их и какие, — и это не повод молчать о
 * том, что нашлось.
 */
export function sweep(stored: readonly Fact[]): { dirty: Fact[]; said: string } {
  const dirty = stored.filter((fact) => clean(fact.value).any);
  if (dirty.length === 0) return { dirty, said: "в памяти секретов нет" };
  // Названы **виды и места**, не значения: отчёт читают люди, а не только
  // владелец секрета.
  return {
    dirty,
    said:
      `в памяти ${dirty.length} запис${dirty.length === 1 ? "ь" : "и"} с секретами: ` +
      dirty.map((fact) => fact.kind).join(", ") +
      " — их надо вычистить",
  };
}

/**
 * Вычистить найденное: то же правило, что на записи.
 *
 * Отдельная функция, потому что «нашли» и «исправили» — разные события, и
 * смешивать их значит не показать человеку, что было.
 */
export function purge(stored: readonly Fact[]): { clean: Fact[]; said: string } {
  const cleaned = stored.map((fact) => guard(fact).fact);
  const got = sweep(stored);
  return {
    clean: cleaned,
    said: got.dirty.length === 0 ? "чистить нечего" : `вычищено ${got.dirty.length}, значения не сохранены`,
  };
}

/**
 * Стоит ли вообще запоминать этот вид.
 *
 * Секреты — не «вид памяти», у которого плохое значение, а вид, которого в
 * памяти быть не должно. Проверка отдельная, чтобы «не запоминай пароли» было
 * правилом, а не надеждой на вычистку.
 */
export const NEVER: readonly string[] = ["password", "token", "api-key", "secret", "card"];

/** Можно ли запоминать такой вид вовсе. */
export function allowed(kind: string): { ok: boolean; said: string } {
  if (NEVER.includes(kind)) {
    return { ok: false, said: `вид «${kind}» в памяти не хранится: это секрет по своей природе` };
  }
  return { ok: true, said: "" };
}
