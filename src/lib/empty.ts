/**
 * Пустота говорится словами (шаги 9 и 13).
 *
 * Дефект. Пустой список выглядит как «всё хорошо»: раздел без строк читается как
 * «здесь нечего чинить», хотя на самом деле «здесь ничего не проверяли». Это
 * два разных факта, и второй — важнее: он говорит о границе знания, а не о
 * состоянии мира.
 *
 * Поэтому у пустоты три **разных** причины, и каждая называется своим словом:
 *
 *  * `nothing-yet` — ничего не проверяли: раздел ещё не начат. «здесь ничего не
 *    проверялось»;
 *  * `unknown` — спросили, но ответа нет: источник недоступен или не ответил.
 *    «не удалось узнать» — и это не то же, что «ничего не проверяли»;
 *  * `really-empty` — проверили и правда пусто. «проверено: здесь ничего нет».
 *
 * Почему три, а не одно «нет данных». Первое читается как «мы не дошли»,
 * второе — как «что-то сломалось», третье — как факт. Склеить их в одно значит
 * снова позволить человеку решить за нас, что происходит.
 *
 * И ещё одно правило, из шага 13: **«непроверенное» — это статус, а не
 * пустое место**. Пункт без проверки показывается строкой «не проверено», а не
 * отсутствием пункта: отсутствие выглядит как «не проблема».
 */

/** Почему в разделе пусто. */
export type Emptiness = "nothing-yet" | "unknown" | "really-empty";

/** Что сказать человеку. Одно место, чтобы формулировки не разъезжались. */
export function emptyText(reason: Emptiness): string {
  switch (reason) {
    case "nothing-yet":
      return "здесь ничего не проверялось";
    case "unknown":
      return "не удалось узнать — источник не ответил";
    case "really-empty":
      return "проверено: здесь ничего нет";
  }
}

/**
 * Что показать, если список пуст.
 *
 * `null` — когда есть что показать: правило не должно заставлять писать
 * заглушку поверх настоящих данных.
 */
export function emptyLine<T>(items: readonly T[], reason: Emptiness): string | null {
  return items.length === 0 ? emptyText(reason) : null;
}

/**
 * Выбрать причину пустоты по фактам, а не по настроению.
 *
 * `asked` — спрашивали ли источник; `answered` — ответил ли он; `error` — была
 * ли ошибка. Порядок проверок важен: ошибка — всегда `unknown`, даже если
 * спрашивали; не спрашивали — `nothing-yet`; спросили и получили пусто —
 * `really-empty`.
 */
export function emptinessOf(info: { asked: boolean; answered: boolean; error: boolean }): Emptiness {
  if (info.error) return "unknown";
  if (!info.asked) return "nothing-yet";
  if (!info.answered) return "unknown";
  return "really-empty";
}
