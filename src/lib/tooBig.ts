/**
 * Отметка «модель не влезает в память» — до скачивания (шаг 73).
 *
 * Дефект. Человек скачивает 4.7 ГБ, ждёт полчаса, запускает — и модель не
 * влезает. Дальше два плохих исхода:
 *
 *  * приложение **свопится** и отвечает по тридцать секунд, и человек думает,
 *    что оно медленное;
 *  * приложение падает при загрузке, и человек думает, что оно сломано.
 *
 * В обоих случаях он узнал о нехватке памяти **после** получаса ожидания, хотя
 * узнать это можно было по двум числам до начала.
 *
 * Правило: **не влезает — сказано до скачивания**, и не «наверное».
 *
 *  1. Отметка стоит **на карточке**, а не в справке: её видно там, где
 *     принимают решение.
 *  2. Сказано **сколько** нужно и **сколько** есть — иначе человек не поймёт,
 *     «чуть-чуть» или «втрое».
 *  3. Сказано **что делать**: закрыть программы, взять модель поменьше. Отметка
 *     без пути — это запрет, а не помощь.
 *  4. Порог **с запасом**: модель, которая влезает в притык, начинает свопиться
 *     под нагрузкой, и «влезает» превращается в «иногда тормозит».
 *
 * Почему не «скачаем и попробуем». Скачивание — это полчаса и гигабайты; проба
 * должна стоить двух чисел, а не получаса.
 */

/** Сколько памяти нужно модели: и минимум, и что останется после системы. */
export interface Fit {
  /** Нужно модели, мегабайт. */
  needsMb: number;
  /** Есть свободно, мегабайт. */
  hasMb: number;
}

/**
 * Что сказать про помещение.
 *
 * Три состояния: влезает с запасом, влезает в притык (и это предупреждение), не
 * влезает. Притык назван отдельно, потому что это **не «влезает»**: под
 * нагрузкой такой запас исчезает.
 */
export type Verdict = "fits" | "tight" | "no";

/**
 * Запас, при котором «влезает» честно.
 *
 * Четверть сверх нужного: модель в работе просит кеш контекста (шаг 67) и
 * память на сам движок, и в притык она свопится под нагрузкой.
 */
export const SAFE_SPARE = 0.25;

export function verdict(fit: Fit): Verdict {
  if (fit.hasMb < fit.needsMb) return "no";
  const spare = (fit.hasMb - fit.needsMb) / Math.max(1, fit.needsMb);
  return spare >= SAFE_SPARE ? "fits" : "tight";
}

/** Нужно и есть — числами, в гигабайтах: «нужно 6.1 ГБ, есть 4 ГБ». */
export function numbers(fit: Fit): string {
  const gb = (mb: number) => `${Math.round((mb / 1024) * 10) / 10} ГБ`;
  return `нужно ${gb(fit.needsMb)}, есть ${gb(fit.hasMb)}`;
}

/**
 * Отметка для карточки.
 *
 * Не «не влезает» одной фразой: названы числа и путь. Иначе человек уходит
 * искать «как увеличить память» вместо «взять модель поменьше».
 */
export function mark(fit: Fit): string {
  const left = numbers(fit);
  switch (verdict(fit)) {
    case "fits":
      return `помещается: ${left}`;
    case "tight":
      // Честно: «влезает, но в притык» — это предупреждение, а не разрешение.
      return `влезает в притык: ${left} — под нагрузкой может подтормаживать`;
    case "no":
      return `не помещается: ${left} — закройте программы или возьмите модель поменьше`;
  }
}

/**
 * Можно ли предлагать скачивание.
 *
 * Нельзя при `no` — и **можно** при `tight`: это выбор человека, а не запрет.
 * Запрещать притык значит решать за него; не предупредить — обманывать.
 */
export function downloadable(fit: Fit): boolean {
  return verdict(fit) !== "no";
}

/**
 * Сколько памяти освободить, чтобы влезло.
 *
 * Названо числом: «закройте программы» без числа не говорит, хватит ли закрыть
 * браузер или нужно закрыть всё.
 */
export function freeMb(fit: Fit): number {
  if (verdict(fit) !== "no") return 0;
  const target = Math.ceil(fit.needsMb * (1 + SAFE_SPARE));
  return Math.max(0, target - fit.hasMb);
}

/** Освободить — словами, с числом. */
export function freeWord(fit: Fit): string | null {
  const mb = freeMb(fit);
  if (mb === 0) return null;
  return `освободите ещё ${Math.ceil(mb / 1024)} ГБ или возьмите модель поменьше`;
}

/**
 * Что сказать, если не влезает ничего.
 *
 * Причина и путь: чаще всего памяти занята браузером, и это **решается**, а не
 * приговор железу.
 */
export function nothing(): string {
  return "памяти не хватает ни на одну модель — закройте браузер и тяжёлые программы, и самая маленькая поместится";
}
