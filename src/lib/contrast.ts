/**
 * Высокий контраст и системная тема, а не только тёмная по умолчанию (шаг 186).
 *
 * Дефект. Тема умела три состояния (шаг 197/200), но **контраст не был учтён
 * никак**. А это другой вопрос, чем «светлая или тёмная»:
 *
 *  * человеку с плохим зрением нужен не «правильный оттенок», а **границы**: рамка
 *    у кнопки, разделитель у карточки, не «серый на сером»;
 *  * в Windows есть режим высокой контрастности, и он **заменяет** цвета темы, а
 *    не смешивается с ними: если рисовать свои цвета поверх, интерфейс станет
 *    нечитаемым ровно у того, кто включил режим ради читаемости;
 *  * «уменьшение движения» — третья настройка, и она тоже системная: человек,
 *    которому анимация мешает, уже сказал об этом системе, и спрашивать второй раз
 *    значит не слышать первого ответа.
 *
 * Правила:
 *
 *  1. **систему спрашивают, а не угадывают.** Три отдельных вопроса: тёмная ли
 *     тема, высокий ли контраст, меньше ли движения. Один ответ не заменяет другой;
 *  2. **в режиме контраста цвета не свои.** `forced-colors: active` значит, что
 *     система даёт палитру; приложение обязано назвать, что рисовать не своими
 *     цветами, и не ставить `background-image`, который эта палитра не отменит;
 *  3. **контраст — это границы, а не ярче.** «Сделать текст белее» не помогает,
 *     если кнопка без рамки сливается с фоном;
 *  4. **меньше движения — выключаем, а не замедляем.** Замедленная анимация
 *     всё ещё анимация для того, кому она мешает;
 *  5. **незнание — не «выключено».** Не умеет движок рассказать про контраст —
 *     это «неизвестно», а не «обычный режим»: иначе проверка молчит там, где
 *     настройка есть.
 *
 * Модуль не трогает DOM: он решает, что включить, и объясняет почему.
 */

/** Что система рассказала о настройках доступности. */
export interface System {
  /** Тёмная тема включена. */
  dark: boolean;
  /** Высокий контраст включён. */
  contrast: boolean;
  /** Меньше движения. */
  reduceMotion: boolean;
}

/** Что делать приложению. */
export interface Plan {
  /** Тема: светлая или тёмная. */
  theme: "light" | "dark";
  /** Цвета берём у системы, а не свои. */
  systemColors: boolean;
  /** Анимации выключены полностью (не замедлены). */
  still: boolean;
  /** Что сказать человеку — если есть что. */
  said: string;
}

/**
 * Спросить систему.
 *
 * `query` — та же функция, что у `prefersDark`: так проверка не зависит от
 * браузера, и её можно прогнать на выдуманных ответах.
 */
export function ask(query: (q: string) => boolean, fallbackDark = true): System {
  try {
    return {
      dark: query("(prefers-color-scheme: dark)"),
      // `forced-colors` — стандартное имя; `-ms-high-contrast` остался в старых
      // движках, и спрашивать только одно значит не заметить настройку.
      contrast: query("(forced-colors: active)") || query("(-ms-high-contrast: active)"),
      reduceMotion: query("(prefers-reduced-motion: reduce)"),
    };
  } catch {
    // Движок не умеет `matchMedia` — тёмная тема как раньше, но контраст и
    // движение остаются «неизвестны», и это сказано отдельно.
    return { dark: fallbackDark, contrast: false, reduceMotion: false };
  }
}

/** Что включить по системным настройкам. */
export function plan(system: System): Plan {
  const still = system.reduceMotion;
  if (system.contrast) {
    return {
      // В режиме контраста тема — системная: свои цвета здесь мешают, а не помогают.
      theme: system.dark ? "dark" : "light",
      systemColors: true,
      still,
      said: "высокая контрастность включена: цвета и рамки берутся у системы, свои не навязываются",
    };
  }
  if (still) {
    return {
      theme: system.dark ? "dark" : "light",
      systemColors: false,
      still: true,
      said: "уменьшение движения включено: анимации выключены полностью, а не замедлены",
    };
  }
  return { theme: system.dark ? "dark" : "light", systemColors: false, still: false, said: "" };
}

/**
 * Что нельзя делать своими цветами.
 *
 * Перечень того, что в режиме контраста ломается чаще всего. Он не «стили» и не
 * CSS, а **список мест**, которые надо проверить: заливка, тень, картинка на фоне,
 * прозрачность. Прозрачность — потому что системная палитра её не отменяет, и
 * «полупрозрачный чёрный» остаётся нечитаемым на чёрном.
 */
export const FRAGILE: readonly { what: string; why: string }[] = [
  { what: "заливка градиентом", why: "система её не отменяет, а цвета в ней свои" },
  { what: "тень вместо рамки", why: "тень не видна в высоком контрасте: граница пропадает" },
  { what: "полупрозрачность", why: "прозрачность система не отменяет — текст остаётся серым на сером" },
  { what: "картинка на фоне текста", why: "контраст текста на картинке не проверяется системой" },
];

/** Проверка: в режиме контраста ничего из хрупкого не используется. */
export function fragile(used: readonly string[]): string[] {
  return FRAGILE.filter((item) => used.includes(item.what)).map((item) => `${item.what}: ${item.why}`);
}

/**
 * Что показать в настройках.
 *
 * «Высокая контрастность» — не переключатель приложения, а состояние системы; но
 * человек должен видеть, что приложение её **заметило**, иначе он решит, что его
 * настройку проигнорировали.
 */
export function note(system: System): string {
  const parts: string[] = [];
  parts.push(system.dark ? "тема системы: тёмная" : "тема системы: светлая");
  parts.push(
    system.contrast
      ? "высокая контрастность: включена — цвета берутся у системы"
      : "высокая контрастность: выключена",
  );
  parts.push(
    system.reduceMotion ? "уменьшение движения: включено — анимаций нет" : "уменьшение движения: выключено",
  );
  return parts.join(" · ");
}
