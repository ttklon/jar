/**
 * Шаг 295: свои сильные стороны назвать явно — русский, локальность, руки на Windows.
 *
 * Таблица заимствований к этому месту выросла до девяти строк, и в ней легко
 * превратиться в **копию без души**: у каждого пункта есть чужой образец, своего
 * не видно. У нас три вещи, которых у образцов нет или есть хуже:
 *
 *  * **русский язык** — не «перевод интерфейса», а понимание речи, формулировок
 *    и команд по-русски, включая падежи и «включи свет на кухне»;
 *  * **локальность** — модель и память на этой машине, без сети и без аккаунта;
 *  * **руки на Windows** — не «помощник отвечает текстом», а нажимает, открывает,
 *    печатает: то, что веб-ассистент физически не может.
 *
 * Слабость, которую надо назвать вместе: первые два — требования, третье —
 * риск. «Руки» сильны ровно настолько, насколько надёжен захват клавиатуры, а он
 * ломается на играх, удалённом рабочем столе и защищённых окнах. Поэтому сила
 * заявляется **с границей**, а не лозунгом.
 */

/** Своя сильная сторона — с границей и доказательством. */
export interface Strength {
  readonly id: "ru" | "local" | "hands";
  /** Как называется для человека. */
  readonly name: string;
  /** Что именно мы умеем, чего нет у образца. */
  readonly edge: string;
  /** Где это перестаёт работать — обязательно. */
  readonly limit: string;
}

/** Три силы: ровно столько, сколько можно удержать в голове. */
export const STRENGTHS: readonly Strength[] = [
  {
    id: "ru",
    name: "русский язык",
    edge: "понимаем команду так, как её говорят: «включи свет на кухне», «сделай потише»",
    limit: "смешанная речь «включи Docker desktop» — не всегда; распознавание на слух слабее печати",
  },
  {
    id: "local",
    name: "локальность",
    edge: "модель, память и история — на этой машине: работает без сети и без аккаунта",
    limit: "без сети не работают те вещи, которым нужен сайт; большая модель требует памяти",
  },
  {
    id: "hands",
    name: "руки на Windows",
    edge: "нажимаем, открываем и печатаем в окнах Windows, а не только отвечаем текстом",
    limit: "игры, удалённый рабочий стол и защищённые окна не трогаем — и говорим об этом сразу",
  },
];

/** Короткая формулировка для «О программе»: одна строка на силу. */
export function shortLine(strength: Strength): string {
  return `${strength.name}: ${strength.edge}`;
}

/**
 * Проверка, что сила не превратилась в лозунг.
 *
 * Требования: названа граница, и граница не «в будущем починим» — она про то,
 * что не работает **сейчас**.
 */
export function audit(strengths: readonly Strength[] = STRENGTHS): { ok: boolean; problems: string[] } {
  const problems: string[] = [];
  const seen = new Set<string>();

  for (const strength of strengths) {
    if (seen.has(strength.id)) problems.push(`сила «${strength.name}» заявлена дважды`);
    seen.add(strength.id);

    if (strength.limit.trim().length < 15) problems.push(`«${strength.name}»: граница не названа — это лозунг`);
    if (/починим|в будущем|скоро/i.test(strength.limit)) {
      problems.push(`«${strength.name}»: граница обещает будущее вместо нынешнего предела`);
    }
    if (strength.edge.trim().length < 20) problems.push(`«${strength.name}»: не сказано, что именно умеем`);
  }

  if (strengths.length > 3) problems.push("сил больше трёх — их не удержать в голове, и это уже список фич");

  return { ok: problems.length === 0, problems };
}

