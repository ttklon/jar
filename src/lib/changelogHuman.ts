/**
 * Шаг 316: журнал обновлений — что изменилось, по-человечески.
 *
 * «Исправлены баги», «улучшена стабильность», «внутренние изменения» — это три
 * способа сказать «ничего». Человек открывает журнал с одним вопросом: **из-за
 * меня это обновление или нет?** Если в журнале нельзя найти ответ, журнала нет.
 *
 * Поэтому запись строится по одному шаблону:
 *
 *  * **что было не так** — с точки зрения человека, не кода;
 *  * **что теперь** — что он заметит сам;
 *  * **кого это касается** — «всех» — плохой ответ, лучше назвать условие:
 *    «у кого ноутбук на батарее», «у кого Windows 11».
 *
 * И одна строка «если у вас было вот это — теперь вот так». Заглушки ловятся
 * машинно, потому что «улучшена стабильность» пишется само собой.
 */

/** Запись журнала. */
export interface Entry {
  /** Что было не так. */
  readonly was: string;
  /** Что теперь. */
  readonly now: string;
  /** Кого касается — условие, а не «всех». */
  readonly who: string;
}

/** Заглушки, которые ничего не говорят. */
const EMPTY = /исправлен\S*\s+баг|улучшен\S*\s+(стабильн|производ|качеств)\S*|внутренн\S*\s+изменени\S*|разные улучшени\S*|оптимизац\S*/i;

/**
 * Запись хороша, когда в ней есть что-то, что человек мог заметить.
 *
 * Проверка не стилистическая: если «что теперь» нельзя увидеть, запись не нужна.
 */
export function check(entry: Entry): string[] {
  const problems: string[] = [];

  if (EMPTY.test(entry.was) || EMPTY.test(entry.now)) {
    problems.push(`«${entry.was} → ${entry.now}»: так пишут, когда сказать нечего`);
  }
  if (entry.was.trim().length < 15) problems.push("«что было» слишком короткое, чтобы человек узнал свой случай");
  if (entry.now.trim().length < 15) problems.push("«что теперь» слишком короткое: человек не поймёт, что заметит");
  if (/^(все|всех|всем|пользовател\S*)$/i.test(entry.who.trim().replace(/[.,;:!?]+$/, ""))) {
    problems.push(`«кого касается: ${entry.who}» — значит, никто конкретно`);
  }
  return problems;
}

/** Проверить весь журнал. */
export function audit(entries: readonly Entry[]): string[] {
  return entries.flatMap((entry) => check(entry));
}

/**
 * Строка для человека.
 *
 * Порядок: было → теперь → кого. Кто в конце, потому что если запись не про
 * тебя, дальше можно не читать.
 */
export function line(entry: Entry): string {
  return `${entry.was} — теперь ${entry.now} (${entry.who})`;
}

/**
 * Раздел «важное» в начале.
 *
 * Обновление, которое ломает привычку, нельзя ставить в середину списка из
 * двадцати строк: его надо увидеть до нажатия «обновить».
 */
export interface Version {
  readonly version: string;
  readonly important: readonly string[];
  readonly entries: readonly Entry[];
}

export function digest(version: Version): string {
  if (version.important.length === 0) return `Версия ${version.version}: ${version.entries.length} изменений`;
  return `Версия ${version.version}: сначала важное — ${version.important.join("; ")}`;
}

/**
 * Что сказать про обновление, которое не меняет ничего заметного.
 *
 * Ответ существует, и он не «исправлены баги»: если показать нечего — так и
 * сказать, а не выдумывать строку.
 */
export function nothingVisible(): string {
  return "Заметных изменений нет: обновление про надёжность — исправлены редкие падения, которые вы, скорее всего, не замечали";
}

/** Проверка: заглушка «исправлены баги» не просачивается в кнопку. */
export function badLine(text: string): boolean {
  return EMPTY.test(text);
}
