/**
 * Ответ по умолчанию — короткий; длинное — по просьбе (шаг 47).
 *
 * Дефект. Ответ произносился целиком: модель напишет абзац на десять секунд
 * речи, и человек десять секунд слушает вместо того, чтобы получить ответ.
 * Голосовой ответ — это **ответ**, а не чтение документа: длинный голосовой
 * ответ раздражает вдвойне, потому что его нельзя пролистать.
 *
 * Правило двухслойное, и оба слоя нужны:
 *
 *  1. **что сказать вслух** — первое предложение, и только если оно само по себе
 *     понятно. «Он оказался прав.» — не ответ: без остального это загадка;
 *  2. **что оставить на экране** — всё остальное, целиком и без потерь. Короткий
 *     ответ не значит «выбросить текст»: человек должен иметь возможность
 *     прочитать то, что не стали читать ему.
 *
 * «По просьбе» — это не кнопка «показать ещё», а вопрос, который человек задаёт
 * словами: «подробнее», «а почему», «расскажи». Поэтому распознавание просьбы
 * тоже здесь: иначе на «расскажи подробнее» приложение снова ответит одной
 * фразой, и человек решит, что его не слышат.
 */

/** Сколько предложений произносится по умолчанию. Одно — это и есть «коротко». */
export const SHORT_SENTENCES = 1;

/** Слова, которыми просят подробностей. Закрытый список: не угадываем. */
const WANTS_MORE = [
  "подробнее",
  "подробней",
  "расскажи",
  "объясни",
  "а почему",
  "почему",
  "ещё",
  "еще",
  "детали",
  "детальнее",
];

/**
 * Просят ли подробностей.
 *
 * Совпадение по **вхождению** слова, а не по всей фразе: «расскажи подробнее»
 * может прийти с лишними словами, и это всё равно просьба. Но «почему» — слово,
 * которое встречается и в самом вопросе («почему упало»), поэтому просьбой оно
 * считается только короткой фразой: длинный вопрос про «почему» — это новый
 * вопрос, а не просьба продолжить старый.
 */
export function wantsMore(text: string): boolean {
  const normalized = text.toLocaleLowerCase("ru").replace(/ё/g, "е").trim();
  if (normalized.length === 0) return false;
  const words = normalized.split(/\s+/u).filter((word) => word.length > 0);
  // Короткая фраза целиком — просьба: «а почему?», «подробнее».
  if (words.length <= 3 && WANTS_MORE.some((word) => normalized.includes(word))) return true;
  // Длинная: просьбой считается только явное «подробнее/расскажи», а не
  // «почему» — иначе любой вопрос про причину продолжал бы прошлый ответ.
  return ["подробнее", "подробней", "расскажи", "объясни", "детальнее", "детали"].some((word) =>
    normalized.includes(word),
  );
}

/**
 * Разбить ответ на предложения.
 *
 * По границам предложений, а не по точкам внутри чисел и сокращений: «1.5»
 * остаётся «1.5», «т.е.» не рвётся.
 */
export function sentences(text: string): string[] {
  const out: string[] = [];
  let current = "";
  for (let index = 0; index < text.length; index += 1) {
    const char = text[index] ?? "";
    current += char;
    if (char !== "." && char !== "!" && char !== "?" && char !== "…") continue;
    const next = text[index + 1] ?? "";
    // Граница — когда дальше пробел и не цифра: «1.5» — не конец фразы.
    if (next === "" || (/\s/.test(next) && !/\d/.test(text[index + 2] ?? ""))) {
      const part = current.trim();
      if (part.length > 0) out.push(part);
      current = "";
    }
  }
  const rest = current.trim();
  if (rest.length > 0) out.push(rest);
  return out;
}

/**
 * Что сказать вслух.
 *
 * `null` — произносить нечего: текст пустой. Тогда и молчим, а не читаем
 * «ничего не найдено» голосом.
 *
 * Просьба о подробностях (`more`) снимает ограничение: человек сам попросил
 * слушать дольше.
 */
export function spoken(text: string, more = false): string | null {
  const parts = sentences(text.trim());
  if (parts.length === 0) return null;
  if (more) return parts.join(" ");
  return answerStart(parts).slice(0, SHORT_SENTENCES).join(" ");
}

/**
 * Приветствие или вежливость — не ответ (найдено e2e, шаг 47).
 *
 * Первый прогон прочёл «Здравствуйте!» и остановился: по правилу это было
 * законченное первое предложение. По смыслу это **не ответ** — человек ждал
 * «чем помочь», а услышал приветствие и тишину. Настоящее поведение поймал e2e
 * голоса, а не тест правила: правило было верным, а **выбор предложения** — нет.
 *
 * Поэтому первое предложение выбирается не по счёту, а по смыслу: приветствия и
 * вежливые вставки пропускаются, ответ начинается с первого содержательного
 * предложения. Если содержательного нет вовсе (модель только поздоровалась) —
 * произносится всё, что есть: молчание хуже приветствия.
 */
// `\b` после кириллицы не работает без флага `u` на границе слов: здесь граница
// задана явно — начало строки, слово целиком, конец строки.
const GREETING = /^(здравствуйте|привет|добрый день|добрый вечер|доброе утро|рад|рада|конечно|хорошо|окей|ок|понял|поняла)[\s,!.…]*$/iu;

export function answerStart(parts: readonly string[]): string[] {
  // Приветствие может стоять после префикса: «модель переспрашивает:
  // Здравствуйте!». Смотрим на часть **после двоеточия** — префикс говорит, кто
  // это сказал, а не что сказано.
  const body = (part: string) => {
    const after = part.split(":").slice(1).join(":").trim();
    return after.length > 0 ? after : part.trim();
  };
  const index = parts.findIndex((part) => !GREETING.test(body(part)));
  // Всё — вежливость: произносим как есть, а не молчим.
  return index === -1 ? [...parts] : parts.slice(index);
}

/**
 * Что оставить на экране — всё, без потерь.
 *
 * Короткий ответ не значит «выбросить текст»: то, что не стали читать вслух,
 * человек должен прочитать. Возвращается тот же текст, и это нарочно: любая
 * «сокращалка» здесь — потеря, о которой человек не узнает.
 */
export function onScreen(text: string): string {
  return text.trim();
}

/**
 * Что сказать человеку о том, что часть ответа осталась на экране.
 *
 * Не «есть ещё кое-что»: это загадка. Называется, что можно попросить и что
 * осталось.
 */
export function moreLine(hidden: number): string | null {
  if (hidden <= 0) return null;
  return `остальное на экране — скажите «подробнее», и прочитаю целиком`;
}
