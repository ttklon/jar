/**
 * Не терять фразу, если микрофон отключился в середине (шаг 55).
 *
 * Дефект. Запись обрывается — выдернули гарнитуру, села батарейка, система
 * отобрала микрофон, — и **всё сказанное исчезает**. Человек говорил двадцать
 * секунд и получил пустоту: ни текста, ни «не услышал», ни возможности
 * продолжить. Самое обидное, что распознать уже записанное можно: звук был, он
 * просто оборван.
 *
 * Правило: оборванная запись — это **не потеря**, а недоговорённая фраза.
 *
 *  1. Уже записанное сохраняется и разбирается: человек сказал — это его.
 *  2. Сказано, **что случилось и что делать**: «микрофон отключился на 12-й
 *     секунде — сказанное сохранено, нажмите и продолжите».
 *  3. Если запись слишком короткая, чтобы что-то значить (`USABLE_MS`), —
 *     говорим честно «не успел услышать» и просим повторить, а не выдаём
 *     обрывок за ответ.
 *  4. Продолжение **дописывается к сказанному**, а не заменяет: «продолжите»
 *     обещает продолжение.
 *
 * Почему не выбрасываем обрывок. Соблазн большой: оборванная запись — «грязная».
 * Но двадцать секунд речи с обрывком в конце лучше пустоты, и человек уже
 * потратил на них силы. Выбросить — значит наказать его за севшую батарейку.
 */

/** Сколько нужно, чтобы из обрывка вышел смысл. */
export const USABLE_MS = 400;

/** Что известно об оборванной записи. */
export interface Dropped {
  /** Сколько миллисекунд успели записать. */
  recordedMs: number;
  /** Сколько было произнесено до обрыва (если известно). */
  heard?: string;
  /** Что уже сказано до этого — для дописывания. */
  before?: string;
}

/**
 * Что делать с оборванной записью.
 *
 * `keep` — разобрать и сохранить; `ask` — слишком мало, просим повторить;
 * `join` — дописать к сказанному раньше.
 */
export type Verdict = "keep" | "ask" | "join";

export function verdict(dropped: Dropped): Verdict {
  if (dropped.recordedMs < USABLE_MS) return "ask";
  if (dropped.before !== undefined && dropped.before.trim().length > 0) return "join";
  return "keep";
}

/**
 * Что сказать человеку.
 *
 * Названы три вещи: **что случилось** (микрофон отключился), **сколько успели**
 * (в секундах — человек помнит, сколько говорил) и **что делать**. Без третьего
 * сообщение об обрыве превращается в сообщение о поломке.
 */
export function say(dropped: Dropped): string {
  const seconds = Math.max(1, Math.round(dropped.recordedMs / 1000));
  switch (verdict(dropped)) {
    case "ask":
      // Честно: обрывок не выдаём за ответ. «Продолжите» здесь соврало бы —
      // продолжать нечего.
      return "микрофон отключился сразу — ничего не успел услышать, повторите";
    case "join":
      // Дописываем, а не начинаем заново: человек уже сказал первую половину.
      return `микрофон отключился на ${seconds}-й секунде — сказанное сохранено, нажмите и продолжите`;
    case "keep":
      return `микрофон отключился на ${seconds}-й секунде — сказанное сохранено, сейчас разберу`;
  }
}

/**
 * Собрать фразу из двух частей: до обрыва и после.
 *
 * Склейка без повторного «я» и без лишних точек: человек продолжал фразу, а не
 * начинал новую. Пустая часть не оставляет висящей запятой.
 */
export function join(before: string, after: string): string {
  const left = before.trim().replace(/[,\s]+$/, "");
  const right = after.trim().replace(/^[,\s]+/, "");
  if (left.length === 0) return right;
  if (right.length === 0) return left;
  return `${left}, ${right}`;
}

/**
 * Сколько успели — словами, а не числом секунд в уме.
 *
 * «0.4 секунды» — это то, что человек не считает; «меньше секунды» — считает.
 */
export function heardWord(recordedMs: number): string {
  if (recordedMs < 1000) return "меньше секунды";
  const seconds = Math.round(recordedMs / 1000);
  const last2 = seconds % 100;
  const last1 = seconds % 10;
  const word =
    last2 >= 11 && last2 <= 14
      ? "секунд"
      : last1 === 1
        ? "секунда"
        : last1 >= 2 && last1 <= 4
          ? "секунды"
          : "секунд";
  return `${seconds} ${word}`;
}
