/**
 * Один движок для всех ролей по умолчанию, разные — по желанию (шаг 75).
 *
 * Это **корректировка шага 62**, и она важнее, чем кажется.
 *
 * Шаг 62 сказал: у каждой роли своя модель. Это верно про **потребности**, но
 * неверно как настройка по умолчанию. Зоопарк моделей — когда на пять ролей
 * четыре файла — оказывается хуже одной модели:
 *
 *  * **память занята всеми**, даже теми, что понадобятся завтра;
 *  * **диск съеден** четырьмя копиями того, что могло быть одной;
 *  * **человек не понимает**, какая модель отвечает: разная скорость и разное
 *    качество выглядят как нестабильность (это ровно то, от чего мы уходили
 *    в шаге 62, — и они оба правы);
 *  * **чинить нечего по отдельности**: ошибка в ответе неизвестно чьей модели.
 *
 * Правило: **один движок по умолчанию, разные — по желанию и с причиной**.
 *
 *  1. Пока человек не сказал иначе, работает **одна** модель, самая большая из
 *     влезающих (шаг 63). Она справляется со всеми ролями — хуже, но понятно.
 *  2. Роль получает свою модель **только когда выигрыш доказан**: замер показал,
 *     что дешёвая модель справляется (шаг 66), или иначе не влезает.
 *  3. **Включается по одной**: человек меняет роль, видит «было так / стало
 *     так» и решает. Сразу четыре замены — это зоопарк, которого мы избегали.
 *  4. Отличие от умолчания **названо**: «код идёт на 7B, остальное на 3B» —
 *     видно, и потому не выглядит случайностью.
 */

/** Решение: сколько движков и какие. */
export type Setup =
  /** Один движок на всё — умолчание. */
  | { kind: "one"; model: string }
  /** Несколько, с причиной на каждую роль. */
  | { kind: "many"; byRole: Record<string, string>; why: Record<string, string> };

/** Роль, о которой говорит человек. */
export interface Ask {
  /** Для какой роли просят отдельную модель. */
  role: string;
  /** Модель, которую просят. */
  model: string;
  /** Почему: выигрыш доказан замером или иначе не влезает. */
  reason: "measured" | "fits" | "want";
}

/**
 * Что отдать по умолчанию.
 *
 * Одна модель, самая большая из влезающих. Не «лучшая на роль»: лучшая на роль —
 * это выбор, а умолчание не должно быть выбором.
 */
export function byDefault(biggest: string): Setup {
  return { kind: "one", model: biggest };
}

/**
 * Разрешить отдельную модель для роли.
 *
 * **Только с доказанной причиной**: `measured` (замер показал, что дешёвая
 * справляется — шаг 66) или `fits` (иначе не влезает). `want` — «хочу» —
 * принимается, но **называется желанием**, а не улучшением: человек имеет
 * право, а приложение не должно делать вид, что это выгоднее.
 *
 * Одна роль за раз: человек должен увидеть разницу, прежде чем менять
 * следующую.
 */
export function allow(setup: Setup, ask: Ask): { setup: Setup; said: string } {
  const base = setup.kind === "one" ? setup.model : Object.values(setup.byRole)[0] ?? "";
  const byRole: Record<string, string> =
    setup.kind === "one" ? {} : { ...setup.byRole };
  const why: Record<string, string> = setup.kind === "one" ? {} : { ...setup.why };

  // Зоопарк начинается с **третьей** модели: «одна плюс одна по доказанной
  // причине» — ещё не зоопарк, а вот три разных файла на пять ролей уже
  // занимают память всеми и путают, чей ответ.
  const used = new Set([base, ...Object.values(byRole), ask.model]);
  if (used.size > 2) {
    return {
      setup,
      said: `три модели и больше — это зоопарк: память занята всеми, а разная скорость выглядит как нестабильность. Сначала попробуйте две`,
    };
  }

  byRole[ask.role] = ask.model;
  why[ask.role] =
    ask.reason === "measured"
      ? "замер показал, что справляется дешевле"
      : ask.reason === "fits"
        ? "иначе не влезает в память"
        : "ваш выбор — не улучшение, а решение человека";

  return {
    setup: { kind: "many", byRole, why },
    said:
      ask.reason === "want"
        ? `${roleWord(ask.role)} — на «${ask.model}»: это ваш выбор, по скорости он не выигрывает`
        : `${roleWord(ask.role)} — на «${ask.model}»: ${why[ask.role]}`,
  };
}

/**
 * Что сказать про текущую настройку.
 *
 * При одной модели — сказано, что это **умолчание**, а не «так лучше»: иначе
 * человек не знает, что можно иначе.
 */
export function say(setup: Setup): string {
  if (setup.kind === "one") {
    return `одна модель на всё — «${setup.model}»: проще, и одинаково понятно, какая отвечает`;
  }
  const parts = Object.entries(setup.byRole).map(
    // Причина показана **полностью**: обрезанное «так захотел…» не объясняет,
    // выигрыш это или просто выбор.
    ([role, model]) => `${roleWord(role)} — «${model}» (${setup.why[role] ?? "причина не названа"})`,
  );
  return `моделей больше одной: ${parts.join("; ")}`;
}

/**
 * Разные модели — это **отличие от умолчания**, и оно должно быть видно.
 *
 * Если человек не может ответить «какая модель сейчас отвечала», настройка
 * вредна: ошибку не с чем связать.
 */
export function differs(setup: Setup): boolean {
  return setup.kind === "many" && Object.keys(setup.byRole).length > 0;
}

/**
 * Вернуться к одной модели.
 *
 * Обязательный путь назад: зоопарк, из которого нельзя выйти одним действием,
 * остаётся навсегда.
 */
export function reset(setup: Setup): Setup {
  const model = setup.kind === "one" ? setup.model : Object.values(setup.byRole)[0] ?? "";
  return byDefault(model);
}

/** Название роли по-русски — для текста человеку. */
export function roleWord(role: string): string {
  switch (role) {
    case "intent":
      return "понять фразу";
    case "chat":
      return "разговор";
    case "plan":
      return "план";
    case "code":
      return "код";
    case "embed":
      return "поиск по смыслу";
    default:
      return role;
  }
}
