/**
 * Как человека звать.
 *
 * Шаг 37: первый запуск задаёт **один** вопрос — «как тебя называть?» — и
 * запоминает ответ. Второй друг знает имя; без него приложение говорит «вы» и
 * обращается безлично, а после трёх дней это уже заметно.
 *
 * Четыре решения, которые легко сделать неправильно:
 *
 *  * **вопрос необязательный** (шаг 38: отказ от знакомства не блокирует работу).
 *    Пустое имя — законный ответ, а не ошибка ввода. Поэтому `saveName("")` не
 *    бросает и не ругается: он стирает имя;
 *  * **спросить один раз** (шаг 39: после первого запуска разрешения не
 *    спрашиваются повторно). Спрашивали или нет — отдельный факт от того, какое
 *    имя дали: человек мог отказаться, и тогда имя останется пустым навсегда,
 *    но вопрос возвращаться не должен;
 *  * **сломанное хранилище — это «не запомнил», а не падение.** Экран из-за
 *    имени не ломается; хуже было бы не открыть разговор из-за записи в
 *    `localStorage`;
 *  * **имя не уходит никуда, кроме разговора с человеком.** Здесь только
 *    хранение: имя не пишется в журнал дел и не попадает в запросы к модели —
 *    это проверяет шаг про приватность, а не этот модуль, но модуль не должен
 *    давать повода думать иначе.
 *
 * Модуль ничего не знает про React: правило, а не экран.
 */

import { availableStorage, type StorageLike } from "./firstRun";

/** Само имя. Пусто — человек не захотел или хранилище сломалось. */
export const NAME_KEY = "zshelper.person.name";

/** Спрашивали ли уже. Отдельно от имени — см. выше про отказ (шаг 38). */
export const ASKED_KEY = "zshelper.person.asked";

/**
 * Сколько символов помним.
 *
 * Не для экономии: имя длиной в абзац — это уже не имя, и оно попало бы в
 * каждую фразу разговора. Предел назван явно, чтобы это не выяснилось
 * молчаливым обрезанием посреди слова при обращении.
 */
export const NAME_LIMIT = 40;

/**
 * Привести имя к виду, в котором его можно показать.
 *
 * Обрезаем пробелы по краям и сворачиваем повторные: «  Аня  » и «Аня» — одно
 * имя, и хранить два разных значит однажды поздороваться с пробелами.
 */
export function cleanName(raw: string): string {
  return raw.trim().replace(/\s+/g, " ").slice(0, NAME_LIMIT);
}

/** Запомнить имя. Пусто — стереть (это законный ответ, а не ошибка). */
export function saveName(raw: string, storage: StorageLike | null = availableStorage()): boolean {
  if (!storage) return false;
  try {
    const name = cleanName(raw);
    if (name === "") storage.removeItem(NAME_KEY);
    else storage.setItem(NAME_KEY, name);
    // Спросили — и больше не спрашиваем, даже если имя пустое (шаг 39).
    storage.setItem(ASKED_KEY, "1");
    return true;
  } catch {
    return false;
  }
}

/** Как звать. Пусто — не назвался или прочитать нельзя. */
export function readName(storage: StorageLike | null = availableStorage()): string {
  if (!storage) return "";
  try {
    const value = storage.getItem(NAME_KEY);
    // Приводим и при чтении: чужая запись могла быть сделана старой версией.
    return value === null ? "" : cleanName(value);
  } catch {
    return "";
  }
}

/**
 * Пора ли спрашивать имя.
 *
 * Один раз за всё время. Сломанное хранилище значит «не спрашивать»: возвращать
 * вопрос при каждом запуске — это анкета, а не знакомство.
 */
export function shouldAskName(storage: StorageLike | null = availableStorage()): boolean {
  if (!storage) return false;
  try {
    return storage.getItem(ASKED_KEY) !== "1";
  } catch {
    return false;
  }
}

/**
 * Обращение к человеку.
 *
 * С именем — «Аня», без имени — безлично, но не «пользователь»: человек не
 * пользователь, он человек. Пустая строка значит «обращайся без имени», и
 * вызывающий решает, куда её поставить.
 */
export function address(name: string): string {
  return name === "" ? "" : name;
}
