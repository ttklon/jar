/**
 * Корзина вместо удаления по умолчанию (шаг 163): ошибка должна быть поправима.
 *
 * Дефект. Ручка удаления в ядре умеет и то и другое — в корзину и мимо, — но
 * **решала не она**: план мог позвать удаление мимо неё, а фраза «удали эту
 * папку» не уточняла, что значит «удали». Человек узнавал разницу после: в
 * корзине находка, мимо — нет.
 *
 * Правила:
 *
 *  1. **по умолчанию — корзина.** «Удали» без уточнения значит «убери с глаз,
 *     но оставь путь назад»: ошибка в чужом деле должна быть поправима;
 *  2. **мимо корзины — только словом.** Человек может хотеть стереть навсегда,
 *     но это его слово, а не наше умолчание: «навсегда», «безвозвратно»,
 *     «мимо корзины»;
 *  3. **«навсегда» важнее «удали».** Отрицание и спор: «не в корзину» — это
 *     просьба мимо, а «не удаляй» — просьба не трогать; путать их значит стереть
 *     там, где просили остановиться;
 *  4. **журнал нужен не для красоты.** Восстановление работает только по тому,
 *     что записано; поэтому удаление, не попавшее в журнал, честно названо
 *     «вернуть нельзя» ещё до нажатия, а не после;
 *  5. **что вернётся — сказать.** «Верну из журнала: 3 записи» — это не то же,
 *     что «вернуть можно»: число проверяется.
 *
 * Модуль ничего не удаляет. Он решает, **куда** уйдёт удаление, и что об этом
 * сказать — до нажатия.
 */

/** Куда уходит удаление. */
export type Where = "trash" | "gone";

/** Что человек хотел: слова его фразы. */
export interface Wanted {
  /** Куда: корзина или мимо неё. */
  where: Where;
  /** Почему так решили — словами для экрана. */
  why: string;
  /** Была ли просьба явной или это умолчание. */
  explicit: boolean;
}

/** Слова, которые просят стереть мимо корзины. */
const GONE = ["навсегда", "безвозвратно", "мимо корзины", "не в корзину", "стереть окончательно"];

/** Слова, которые просят именно корзину. */
const TRASH = ["в корзину", "корзину", "с глаз", "убрать, но оставить"];

/** Слова, которые вообще просят не удалять. */
const STOP = ["не удаляй", "не трогай", "не стирай", "оставь"];

/**
 * Куда уйдёт удаление по фразе.
 *
 * Порядок проверок — это и есть правило: сперва «не удаляй» (не трогать), потом
 * «мимо корзины» (явная просьба), потом «в корзину» (явная), и только потом
 * умолчание — корзина.
 */
export function where(phrase: string): Wanted {
  const text = phrase.toLowerCase();
  if (STOP.some((word) => text.includes(word))) {
    return {
      where: "trash",
      why: "сказано не трогать: удаления не будет",
      explicit: true,
    };
  }
  const gone = GONE.find((word) => text.includes(word));
  if (gone) {
    // «Не в корзину» — это просьба мимо, а не «не удаляй»: различать их важно.
    return {
      where: "gone",
      why: `сказано стереть мимо корзины («${gone}») — вернуть будет нельзя`,
      explicit: true,
    };
  }
  const trash = TRASH.find((word) => text.includes(word));
  if (trash) {
    return {
      where: "trash",
      why: `сказано убрать в корзину («${trash}») — вернуть можно`,
      explicit: true,
    };
  }
  return {
    where: "trash",
    why: "по умолчанию убираю в корзину: ошибка должна быть поправима",
    explicit: false,
  };
}

/**
 * Что записать в журнал до удаления — и что сказать, если записать некуда.
 *
 * Журнал — не отчёт для красоты: из него восстанавливают. Поэтому «записать
 * некуда» называется до нажатия, а не выясняется после.
 */
export function journalNote(recorded: boolean, where_: Where): string {
  if (recorded) {
    return where_ === "trash"
      ? "записано в журнал: вернуть можно из корзины или из журнала"
      : "записано в журнал: мимо корзины, вернуть можно только из журнала";
  }
  return where_ === "trash"
    ? "в журнал не записалось — вернуть можно только через корзину, по журналу нет"
    : "в журнал не записалось, а мимо корзины это значит «не вернуть»: журнал — единственный путь назад";
}

/**
 * Можно ли обещать возврат.
 *
 * Обещать «вернём» без записи в журнале и без корзины — это обещание, которое
 * сломается ровно тогда, когда понадобится.
 */
export function returnable(where_: Where, recorded: boolean): { can: boolean; said: string } {
  if (recorded) return { can: true, said: "вернуть можно: запись в журнале есть" };
  if (where_ === "trash") return { can: true, said: "вернуть можно из корзины: журнала для этого дела нет" };
  return { can: false, said: "вернуть нельзя: ни корзины, ни записи в журнале" };
}

/**
 * Сколько записей журнала действительно вернут файлы на место.
 *
 * Журнал помнит и то, чего уже нет (файл убрали руками), и то, что было в другой
 * сессии. Число «вернётся 3 из 5» — ответ на «чего ждать от кнопки».
 */
export function restoreCount(
  entries: readonly { from: string; kind: string }[],
  exists: (path: string) => boolean,
): { can: number; total: number; said: string } {
  const total = entries.length;
  const can = entries.filter((entry) => exists(entry.from)).length;
  if (total === 0) return { can: 0, total: 0, said: "в журнале пусто: возвращать нечего" };
  if (can === total) return { can, total, said: `вернётся ${total} из ${total}: всё на месте` };
  return {
    can,
    total,
    said: `вернётся ${can} из ${total}: остальные уже убраны не нами или не на месте`,
  };
}

/** Одна строка для экрана: куда уйдёт и что с возвратом. */
export function say(wanted: Wanted, recorded: boolean): string {
  const back = returnable(wanted.where, recorded);
  return `${wanted.where === "trash" ? "удаление в корзину" : "удаление мимо корзины"} · ${back.said}`;
}
