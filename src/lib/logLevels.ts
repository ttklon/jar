/**
 * Шаг 421: локальный журнал с понятными уровнями, без выхода наружу.
 *
 * Журнал уже есть (`journal`, `journalTiming`), но без **уровней** он превращается
 * в поток строк, где важное не найти. А уровни из мира серверов («DEBUG/INFO/
 * WARN/ERROR») для человека плохи: «WARN» ничего не говорит.
 *
 * Поэтому уровни называются по-русски и значат ровно то, что нужно человеку:
 *
 *  * **дело** — что выполнено: обычная запись, её большинство;
 *  * **ошибка** — не получилось, и это важно;
 *  * **внимание** — получилось, но стоит посмотреть (медленно, отменено на середине);
 *  * **мелочь** — служебное, нужно поддержке, а не человеку.
 *
 * И второе, главное: **журнал только локальный**. Ни одной функции отправки — это
 * проверяется формой модуля, а не обещанием.
 */

/** Уровень. */
export type Level = "дело" | "ошибка" | "внимание" | "мелочь";

/** Запись. */
export interface Line {
  readonly at: number;
  readonly level: Level;
  readonly what: string;
}

/**
 * Какой уровень по умолчанию.
 *
 * По умолчанию в журнале **дело и выше** — то есть всё, кроме мелочи. Мелочь не
 * потому плоха, что не нужна, а потому что её много: 200 строк «нажал кнопку»
 * прячут 3 строки «не получилось».
 */
export function visible(level: Level, showTrivia = false): boolean {
  if (level === "мелочь") return showTrivia;
  return true;
}

/**
 * Отобрать для показа.
 *
 * Новые сверху (журнал читают ради последнего) и с порогом по числу строк.
 */
export function show(lines: readonly Line[], limit = 50, showTrivia = false): Line[] {
  return lines
    .filter((line) => visible(line.level, showTrivia))
    .sort((a, b) => b.at - a.at)
    .slice(0, limit);
}

/**
 * Пометка строки.
 *
 * Только для строк, где уровень **не** «дело»: иначе каждый десяток строк
 * начинается с одного и того же слова, и глаз его перестаёт видеть.
 */
export function mark(line: Line): string {
  if (line.level === "дело") return line.what;
  const marks: Record<Exclude<Level, "дело">, string> = { ошибка: "не получилось", внимание: "стоит посмотреть", мелочь: "служебное" };
  return `${marks[line.level]}: ${line.what}`;
}

/**
 * Куда уходит журнал.
 *
 * Никуда. Функция существует только чтобы это **проверялось**: `[]` — и любой
 * сетевой адрес здесь был бы регрессией.
 */
export function destinations(): string[] {
  return [];
}

/**
 * Что уровни значат.
 *
 * Список — для экрана «что такое журнал»: человек должен понимать, что искать.
 */
export function meaning(): { level: Level; said: string }[] {
  return [
    { level: "дело", said: "что выполнено: обычная запись" },
    { level: "ошибка", said: "не получилось, и это важно" },
    { level: "внимание", said: "получилось, но стоит посмотреть: медленно или отменено на середине" },
    { level: "мелочь", said: "служебное: нужно поддержке, а не человеку" },
  ];
}
