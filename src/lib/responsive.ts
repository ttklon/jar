/**
 * Не блокировать интерфейс ни на одном шаге (шаг 126).
 *
 * Дефект. Пока идёт длинное дело, экран **блокируется целиком**:
 *
 *  * **зависшая кнопка выглядит поломкой**: `disabled` на всём — и человек не может ни
 *    остановить, ни посмотреть журнал, ни спросить «что происходит»;
 *  * **стоп недоступен**: кнопка «стоп» тоже `disabled`, потому что «идёт работа».
 *    Именно тогда она и нужна;
 *  * **состояние не названо**: почему всё серое — непонятно; «думает» и «упало» и
 *    выглядят одинаково;
 *  * **блокировка навсегда**: промис, который не завершился (нет таймаута), оставляет
 *    экран серым до перезагрузки.
 *
 * Правило: **ни один шаг не блокирует всё; блокируется только то, что столкнётся**.
 *
 *  1. **Блокируется действие, а не экран**: нельзя запустить второй разбор той же
 *     фразы, но можно остановить, открыть журнал, посмотреть план.
 *  2. **Стоп доступен всегда, когда есть что останавливать** — в том числе посреди
 *     работы. Он и существует для этого.
 *  3. **Занятость названа**: что именно идёт («распознаю», «думаю», «выполняю»), а не
 *     просто серое.
 *  4. **Занятость снимается при любом исходе**: успех, ошибка, отмена. Забытое снятие
 *     — это блокировка до перезагрузки.
 *  5. **Занятость не «липкая»**: повторное нажатие не запускает вторую работу, но и
 *     не залипает навсегда.
 *
 * Почему не «disable всё, пока думает». Это самый простой способ получить «приложение
 * зависло» на отзыве — при том что процесс жив и ждёт.
 */

/** Что сейчас идёт. */
export type Job = "none" | "listening" | "transcribing" | "thinking" | "planning" | "running" | "speaking";

/** Кнопка или поле, которое может быть недоступно. */
export type Control = "submit" | "stop" | "journal" | "plan" | "approve" | "run" | "mic" | "repeat";

/**
 * Можно ли нажать.
 *
 * Блокируется **только то, что столкнётся**: второй запуск того же действия.
 * Остальное остаётся живым.
 */
export function can(job: Job, control: Control): boolean {
  switch (control) {
    case "stop":
      // Стоп доступен всегда, когда есть что останавливать — и особенно посреди работы.
      return job !== "none";
    case "journal":
    case "plan":
      // Смотреть — никогда не мешает.
      return true;
    case "submit":
      // Второй разбор во время разбора столкнётся: вот и всё, что блокируется.
      return job === "none" || job === "listening";
    case "mic":
      // Микрофон не включается, пока идёт разбор: два потока звука мешают друг другу.
      return job === "none" || job === "listening";
    case "run":
      // Запуск плана — только когда ничего не идёт.
      return job === "none";
    case "approve":
    case "repeat":
      // Согласие можно дать и во время работы: оно про следующий шаг.
      return true;
  }
}

/** Словами: что идёт. */
export function word(job: Job): string {
  switch (job) {
    case "none":
      return "свободно";
    case "listening":
      return "слушаю";
    case "transcribing":
      return "распознаю";
    case "thinking":
      return "думаю";
    case "planning":
      return "собираю план";
    case "running":
      return "выполняю";
    case "speaking":
      return "говорю";
  }
}

/**
 * Занято ли что-то.
 *
 * Отдельная функция, потому что `job !== "none"` пишут по-разному в разных местах, и
 * одно место обязательно забывает «говорю».
 */
export function busy(job: Job): boolean {
  return job !== "none";
}

/**
 * Что можно нажать прямо сейчас — списком.
 *
 * Нужно для проверки: если список во время работы пуст, значит экран заблокирован
 * целиком, и это дефект.
 */
export function available(job: Job): Control[] {
  const all: Control[] = ["submit", "stop", "journal", "plan", "approve", "run", "mic", "repeat"];
  return all.filter((control) => can(job, control));
}

/**
 * Снятие занятости — при любом исходе.
 *
 * Возвращает «свободно» и **не** оставляет `thinking` висеть: забытое снятие — это
 * блокировка до перезагрузки.
 */
export function settled(job: Job, outcome: "ok" | "failed" | "cancelled"): Job {
  // Исход не важен: любая работа кончается одинаково — свободно.
  void outcome;
  return job === "none" ? job : "none";
}

/**
 * Что сказать, когда кнопка недоступна.
 *
 * Не «недоступно», а **почему**: «сначала дождитесь разбора» — это ответ, «серая
 * кнопка» — нет.
 */
export function why(job: Job, control: Control): string {
  if (can(job, control)) return "";
  if (control === "submit" || control === "mic") {
    return `сначала дождитесь: ${word(job)}`;
  }
  if (control === "run") {
    return `нельзя запустить, пока ${word(job)} — сначала остановите или дождитесь`;
  }
  return `недоступно, пока ${word(job)}`;
}

/**
 * Зависшая работа.
 *
 * Если занятость держится дольше предела — это **дефект**, и он должен быть виден, а
 * не выглядеть «ещё думает».
 */
export const STUCK_MS = 30_000;

export function stuck(job: Job, since: number, now: number): { stuck: boolean; said: string } {
  if (!busy(job)) return { stuck: false, said: "" };
  const took = now - since;
  if (took <= STUCK_MS) return { stuck: false, said: "" };
  return {
    stuck: true,
    said: `${word(job)} дольше ${Math.round(STUCK_MS / 1000)} с — это зависание, а не работа; можно остановить`,
  };
}
