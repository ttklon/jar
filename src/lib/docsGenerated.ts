/**
 * Шаг 469: все документы генерируются или проверяются.
 *
 * Документ, который никто не генерирует и никто не проверяет, живёт своей жизнью:
 * его правят, когда вспомнят, и он расходится с кодом. Через полгода он врёт — и
 * его не замечают, потому что он **выглядит** проверенным.
 *
 * Поэтому у каждого документа в проекте ровно один из трёх видов:
 *
 *  * **сгенерирован** — есть генератор (`tools/*.py`) и проверка «перегенерируй
 *    — будет ли разница» (шаг 490);
 *  * **проверяем** — его содержимое сверяется с чем-то машинным: ссылки, числа,
 *    обещания;
 *  * **ручной и помечен** — с датой и областью проверки (шаг 477), и это
 *    осознанное исключение, а не забытый файл.
 *
 * Четвёртого вида нет: «просто документ» — это документ, который устареет.
 */

/** Вид документа. */
export type Kind = "сгенерирован" | "проверяем" | "ручной";

/** Документ. */
export interface Doc {
  /** Путь относительно корня. */
  readonly path: string;
  readonly kind: Kind;
  /** Генератор или проверка — для сгенерированных и проверяемых. */
  readonly by?: string;
  /** Дата проверки и область — для ручных. */
  readonly dated?: { at: string; scope: string };
}

/**
 * Найти непокрытые документы.
 *
 * Возвращает **пути**: при падении нужно видеть, какой файл остался без
 * генератора и без проверки.
 */
export function uncovered(docs: readonly Doc[]): string[] {
  return docs.filter((doc) => {
    if (doc.kind === "ручной") return doc.dated === undefined || doc.dated.at.trim() === "" || doc.dated.scope.trim() === "";
    return doc.by === undefined || doc.by.trim() === "";
  }).map((doc) => doc.path);
}

/**
 * Найти документы, у которых генератор или проверка не существуют.
 *
 * `known` — что реально есть в `tools/`.
 */
export function phantom(docs: readonly Doc[], known: readonly string[]): string[] {
  return docs
    .filter((doc) => doc.kind !== "ручной" && doc.by !== undefined && !known.includes(doc.by))
    .map((doc) => `${doc.path}: ${doc.by} не существует`);
}

/**
 * Сводка.
 *
 * Три числа: сколько сгенерировано, проверяется и ручных. Ручных должно быть
 * **мало** — и это видно числом.
 */
export function summary(docs: readonly Doc[]): { made: number; checked: number; manual: number; said: string } {
  const made = docs.filter((doc) => doc.kind === "сгенерирован").length;
  const checked = docs.filter((doc) => doc.kind === "проверяем").length;
  const manual = docs.filter((doc) => doc.kind === "ручной").length;

  const total = docs.length;
  const share = total === 0 ? 0 : Math.round((manual / total) * 100);
  return {
    made,
    checked,
    manual,
    said: `документов ${total}: сгенерировано ${made}, проверяется ${checked}, ручных ${manual} (${share}%)${share > 20 ? " — многовато: ручной документ устареет первым" : ""}`,
  };
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу видов.
 */
export function checks(): string[] {
  return [
    "у каждого сгенерированного есть генератор, и он существует",
    "у каждого проверяемого есть проверка, и она существует",
    "у каждого ручного есть дата и область проверки",
  ];
}

/**
 * Чего не бывает.
 *
 * Один вид, которого нет.
 */
export function notDo(): string {
  return "«просто документ» без генератора, проверки и даты — это документ, который устареет, и его не заметят: он выглядит проверенным";
}
