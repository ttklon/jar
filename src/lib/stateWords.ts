/**
 * Шаг 2 (вторая строка): словарь состояния.
 *
 * «Не установлено / не проверено / проверено на этой машине» — три разных состояния,
 * и путать их нельзя. «Не проверено» — это не «не работает», а «никто не смотрел»;
 * «проверено на этой машине» — не «проверено везде».
 *
 * Без словаря интерфейс говорит «не работает» там, где надо сказать «не проверено», и
 * человек идёт чинить то, что, возможно, работает.
 *
 * Словарь маленький и **закрытый**: состояние — одно из четырёх, и у него есть
 * обещанное поведение. Новое состояние нельзя ввести словом «полуработает».
 */

/** Состояние. */
export type State = "не установлено" | "не проверено" | "проверено на этой машине" | "не работает";

/** Что состояние значит и что делает интерфейс. */
export interface Meaning {
  readonly state: State;
  /** Что это значит — для человека. */
  readonly means: string;
  /** Что показываем. */
  readonly shows: string;
  /** Можно ли этим пользоваться. */
  readonly usable: boolean;
}

/**
 * Словарь.
 *
 * Четыре записи, и у каждой — что показываем. `usable` — единственный машинный
 * признак: кнопка активна или понятно, чего не хватает.
 */
export function words(): Meaning[] {
  return [
    { state: "не установлено", means: "этого ещё нет на компьютере", shows: "кнопка «установить» и сколько места", usable: false },
    { state: "не проверено", means: "есть, но никто не смотрел, работает ли", shows: "кнопка «проверить» — и никакого «не работает»", usable: false },
    { state: "проверено на этой машине", means: "работает здесь и сейчас", shows: "спокойный вид без обещаний про другие машины", usable: true },
    { state: "не работает", means: "проверяли и не получилось", shows: "причина и что сделать", usable: false },
  ];
}

/**
 * Найти значение.
 *
 * Неизвестное состояние — ошибка, а не «полуработает»: интерфейс не должен
 * показывать слово, которого нет в словаре.
 */
export function meaning(state: string): Meaning | null {
  return words().find((word) => word.state === state) ?? null;
}

/**
 * Проверить надпись.
 *
 * Нарушения: слово не из словаря, «не проверено» названо «не работает» (это разные
 * вещи и разные действия человека), «проверено» без «на этой машине» (обещание
 * больше проверенного).
 */
export function check(label: string): string[] {
  const problems: string[] = [];

  if (meaning(label) === null) problems.push(`«${label}» — не из словаря: ${words().map((word) => word.state).join(" / ")}`);
  if (/^не работает$/.test(label.trim()) && !label.includes("проверяли")) problems.push("«не работает» без проверки — это «не проверено», а действие другое");
  if (/проверено/.test(label) && !label.includes("на этой машине")) problems.push(`«${label}»: без «на этой машине» это обещание больше проверенного`);

  return problems;
}

/**
 * Что сказать, когда «не проверено».
 *
 * Не «не работает», а «проверить» — одно действие.
 */
export function notChecked(): string {
  return "не проверено: нажмите «проверить» — это займёт секунду и скажет точно";
}

/**
 * Чего словарь не делает.
 *
 * Три запрета; главный — не вводить полу-состояния.
 */
export function notDo(): string[] {
  return [
    "не вводит «полуработает» и «вроде да»: состояние закрытое",
    "не называет «не проверено» неработающим: человек пойдёт чинить то, что, возможно, работает",
    "не пишет «проверено» без «на этой машине»",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу путаниц.
 */
export function checks(): string[] {
  return [
    "четыре состояния, и словарь закрыт",
    "«не проверено» и «не работает» — разные и с разными действиями",
    "«проверено» всегда с «на этой машине»",
  ];
}
