/**
 * Что делать, когда проверка себя не прошла.
 *
 * Зачем это отдельный модуль, а не текст в экране. Вердикт отвечает на вопрос
 * «всё ли хорошо», и этого мало: человек, увидевший «✗ память», не знает, что
 * дальше. «Попробуйте перезапустить» — не ответ, а пожатие плечами; ответ —
 * «перекачать модель» или «починить папку данных», то есть конкретное действие,
 * которое можно нажать.
 *
 * Три правила:
 *
 *  * **у каждого отказа есть действие**, и оно названо глаголом: не «проблема
 *    с моделью», а «Скачать модель заново»;
 *  * **не всё чинится приложением.** Для автозапуска и версии честнее сказать
 *    «это не чинится кнопкой», чем показать кнопку, которая ничего не делает;
 *  * **неизвестная проверка не получает выдуманного совета.** Новое имя в ядре
 *    без правила здесь — «действия нет», а не «попробуйте ещё раз».
 */

/** Что можно сделать по кнопке. Пустая строка — кнопки нет, и это сказано. */
export type Repair = "download-model" | "reinstall-engine" | "reset-data" | "rewrite-memory" | "none";

export interface Advice {
  /** Глагол на кнопке: «Скачать модель заново». Пусто — кнопки нет. */
  action: string;
  /** Почему это действие, словами человека. Всегда непустое. */
  why: string;
  /** Что именно починится по нажатию. */
  repair: Repair;
}

/**
 * Совет по имени проверки из ядра.
 *
 * Имена — те, что печатает `selfcheck.rs`/`evals.rs`: «версия», «реестр»,
 * «папка данных», «память», «автозапуск», «движок», «модель». Имя может
 * приходить с уточнением («модель: файл»), поэтому сверяем по началу.
 */
export function adviceFor(name: string): Advice {
  const key = name.trim().toLowerCase();
  if (key.startsWith("модель")) {
    return {
      action: "Скачать модель заново",
      why: "Скачивание проверяет SHA-256: битый файл заменится целиком, а не «подлечится».",
      repair: "download-model",
    };
  }
  if (key.startsWith("движок")) {
    return {
      action: "Переустановить движок",
      why: "Движок — отдельный архив: его можно заменить, не трогая ни модель, ни память.",
      repair: "reinstall-engine",
    };
  }
  if (key.startsWith("папка данных")) {
    return {
      action: "Сбросить кеш",
      why: "Кеш — это временные файлы: их удаление не трогает журнал, память и модели.",
      repair: "reset-data",
    };
  }
  if (key.startsWith("память")) {
    return {
      action: "Пересоздать базу памяти",
      why: "Повреждённая база сохраняется рядом копией: журнал не теряется, но и не мешает работать.",
      repair: "rewrite-memory",
    };
  }
  if (key.startsWith("автозапуск")) {
    return {
      action: "",
      why: "Это настройка Windows, а не файл приложения: включите её на экране «Настройки».",
      repair: "none",
    };
  }
  if (key.startsWith("версия")) {
    return {
      action: "",
      why: "Версия не чинится: она такая, какая установлена.",
      repair: "none",
    };
  }
  if (key.startsWith("реестр")) {
    return {
      action: "",
      why: "Реестр встроен в программу при сборке — испортить его извне нельзя, значит и чинить нечего.",
      repair: "none",
    };
  }
  // Новое имя без правила — честное «действия нет». Выдуманный совет хуже
  // отсутствующего: человек нажмёт кнопку и не поймёт, что произошло.
  return {
    action: "",
    why: "Для этой проверки готового действия нет — и придумывать его на ходу хуже, чем сказать прямо.",
    repair: "none",
  };
}

/** Совет для вердикта целиком: у прошедшего проверку кнопки нет. */
export function adviceForVerdict(verdict: { name: string; passed: boolean }): Advice | null {
  if (verdict.passed) return null;
  return adviceFor(verdict.name);
}

/** Сколько отказов — столько и действий: сводка для заголовка. */
export function failedCount(verdicts: { passed: boolean }[]): number {
  return verdicts.filter((verdict) => !verdict.passed).length;
}
