/**
 * Шаг 281: Raycast — палитра, быстрый старт, единый вход.
 *
 * Что взято. У Raycast запуск начинается с **одного поля**, в которое можно
 * писать что угодно: имя команды, фразу, начало пути. Не «меню из десяти
 * разделов» и не «поиск по настройкам» — одно поле, и оно же вход.
 *
 * Что **не** взято и почему:
 *
 *  * **расширения**. У Raycast их тысячи, и они — источник его силы и его
 *    сложности. Нам нужен русский голос и руки на Windows, а не магазин
 *    расширений: чужой плагин не знает ни наших подтверждений, ни наших прав;
 *  * **облачный индекс**. Палитра, которая знает про человека всё заранее,
 *    удобна ровно до вопроса «а откуда вы это знаете». Наш вход ничего не
 *    индексирует заранее: что человек набрал, то и ищется (шаги 192, 268, 275);
 *  * **единый вход = единое поле, а не единый экран.** Смысл не в том, чтобы
 *    всё свести в одно окно, а в том, что не надо помнить, **где** это лежит.
 *
 * Здесь только то, что делает вход быстрым: пустое поле показывает частые и
 * последние (а не «ничего не найдено»), набранное ищется по смыслу, а Enter
 * выполняет **то, что подсвечено**, а не то, что было первым.
 */

/** Строка палитры: команда, экран или найденный факт — всё в одном списке. */
export interface Entry {
  /** Устойчивый ключ: без него «выполнить подсвеченное» выполняет не то. */
  readonly id: string;
  readonly title: string;
  /** Что будет, если нажать Enter, — словами, до нажатия. */
  readonly does: string;
  /** Насколько часто выбирали: для пустого поля. */
  readonly times?: number;
  /** Когда последний раз выбирали: свежее важнее частого (шаг 261). */
  readonly last?: number;
  /** Опасное — требует подтверждения (шаг 82), и это видно в строке. */
  readonly risky?: boolean;
}

/** Что показывает палитра. */
export interface Shown {
  readonly items: readonly Entry[];
  /** Что сказать над списком: почему именно это. */
  readonly said: string;
}

/**
 * Пустое поле.
 *
 * Главная ошибка палитры — пустой экран с курсором: человек не знает, что писать,
 * и закрывает. Частые и последние — не «реклама», а подсказка слова: увидев
 * «почисти диск», человек вспоминает, что так и называется.
 */
export function idle(entries: readonly Entry[], limit = 5): Shown {
  const useful = entries.filter((entry) => (entry.times ?? 0) > 0 || entry.last !== undefined);
  if (useful.length === 0) {
    return {
      items: [],
      said: "начните писать: команду, папку или вопрос — например «почисти диск»",
    };
  }
  const sorted = [...useful].sort((a, b) => (b.last ?? 0) - (a.last ?? 0) || (b.times ?? 0) - (a.times ?? 0));
  return { items: sorted.slice(0, limit), said: "последнее и частое" };
}

/**
 * Выбор по подсветке, а не по порядку.
 *
 * «Enter выполняет первое» кажется очевидным и ломается ровно тогда, когда
 * человек стрелками выбрал другое: приложение выполнит не то, что он видит
 * выделенным. Это худший класс ошибки — действие без согласия с тем, что на
 * экране.
 */
export function picked(items: readonly Entry[], index: number): { entry: Entry | null; said: string } {
  if (items.length === 0) return { entry: null, said: "нечего выполнять: список пуст" };
  if (index < 0 || index >= items.length) {
    return { entry: null, said: `подсветки нет (выбрана строка ${index + 1} из ${items.length}) — выберите стрелками` };
  }
  const entry = items[index]!;
  return { entry, said: entry.does };
}

/** Что сказать, когда ничего не нашлось. */
export function empty(query: string): string {
  const clean = query.trim();
  if (clean === "") return "начните писать";
  return `по запросу «${clean}» ничего нет — попробуйте другое слово или скажите голосом`;
}
