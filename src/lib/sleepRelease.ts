/**
 * Шаг 457: спящий режим — остановить запись, отпустить движок.
 *
 * Что происходит, если этого не делать. Windows уходит в сон, а приложение
 * продолжает держать:
 *
 *  * **микрофон** — ноутбук в чехле записывает шорохи, и на утро в памяти
 *    появляются «факты» из случайных звуков;
 *  * **движок модели** — 2–4 ГБ памяти заняты всю ночь, а ноутбук в это время
 *    разряжается заметнее;
 *  * **идущее дело** — оно прерывается посреди шага, и при пробуждении никто не
 *    знает, на чём остановился.
 *
 * Поэтому сон — это **событие с последствиями**: запись останавливается, движок
 * выгружается, незавершённое дело запоминается как «прервано сном». Пробуждение
 * — не «продолжить всё», а «ждать, пока попросят».
 */

/** Что было до сна. */
export interface Before {
  /** Шла ли запись микрофона. */
  readonly recording: boolean;
  /** Был ли загружен движок. */
  readonly engine: boolean;
  /** Сколько шагов дела выполнено — если дело шло. */
  readonly stepsDone: number;
  readonly deed?: string;
}

/** Что сделали. */
export interface After {
  readonly recording: boolean;
  readonly engine: boolean;
  /** Как запомнили дело: `null` — дела не было. */
  readonly deedNote: string | null;
  readonly said: string;
}

/**
 * Уснуть.
 *
 * Запись и движок — выключены; дело — запомнено с номером шага. Не «продолжим с
 * того же места» тихо: при пробуждении спросим.
 */
export function sleep(before: Before): After {
  const parts: string[] = [];
  if (before.recording) parts.push("запись остановлена");
  if (before.engine) parts.push("движок отпущен");
  if (before.deed !== undefined) parts.push(`дело «${before.deed}» прервано сном на шаге ${before.stepsDone}`);

  return {
    recording: false,
    engine: false,
    deedNote: before.deed === undefined ? null : `«${before.deed}»: выполнено ${before.stepsDone} шагов, прервано сном`,
    said: parts.length === 0 ? "уходим в сон: отпускать нечего" : `${parts.join("; ")}. При пробуждении спрошу, продолжать ли`,
  };
}

/**
 * Проснуться.
 *
 * Ничего не возобновляем сами: микрофон не включается без нажатия, дело — с
 * вопросом. «Продолжить всё молча» — это и есть тот случай, когда ноутбук в
 * сумке что-то удаляет.
 */
export function wake(after: After): { said: string; ask: boolean } {
  const parts: string[] = ["проснулись"];
  if (after.deedNote !== null) {
    return { said: `${parts[0]}: ${after.deedNote}. Продолжить с этого шага?`, ask: true };
  }
  parts.push("запись не включаю сама: нажмите, если она нужна");
  return { said: parts.join(": "), ask: false };
}

/**
 * Что сон выключает обязательно.
 *
 * Список — приёмочный, каждый пункт проверяется.
 */
export function releases(): string[] {
  return ["микрофон: не записывать в чехле", "движок: не держать гигабайты всю ночь", "идущее дело: не прерывать посреди шага молча"];
}

/**
 * Что не делает сон.
 *
 * Три запрета — про «проснулись и начали без человека».
 */
export function notDo(): string[] {
  return [
    "не включает запись при пробуждении без нажатия",
    "не продолжает дело молча: спрашивает",
    "не забывает, на каком шаге остановились: номер запомнен",
  ];
}
