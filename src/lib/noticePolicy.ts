/**
 * Шаг 337: уведомление об успехе — настраиваемо, об ошибке — всегда.
 *
 * Асимметрия не из вредности. Успех, о котором человек знает, — приятная мелочь.
 * Ошибка, о которой он не знает, — **дело, которого не было**, и узнает он об
 * этом, когда оно понадобится.
 *
 * Поэтому:
 *
 *  * **об ошибке** — всегда и не отключается. В настройках нет галочки «не
 *    сообщать об ошибках»: такая галочка означает «сломайся тихо»;
 *  * **об успехе** — три уровня: «не сообщать», «только если не у экрана»,
 *    «сообщать всегда»;
 *  * **о пропуске** — средний уровень по умолчанию (шаг 326): пропуск не успех и
 *    не ошибка, но если человек ждал отчёт, ему надо знать.
 */

/** Что произошло. */
export type Outcome = "done" | "failed" | "skipped";

/** Что человек выбрал для успехов. */
export type SuccessLevel = "none" | "away" | "always";

/** Настройки уведомлений одного правила. */
export interface Settings {
  readonly success: SuccessLevel;
  /** Человек у экрана — из шага 324. */
  readonly atDesk: boolean;
}

/**
 * Показывать ли уведомление.
 *
 * Ошибка — всегда, и это **не настройка**: её нельзя выключить даже вызвав эту
 * функцию с любыми настройками.
 */
export function show(outcome: Outcome, settings: Settings): { show: boolean; said: string } {
  if (outcome === "failed") {
    return { show: true, said: "об ошибке — всегда: «не сообщать об ошибках» значит «сломайся тихо»" };
  }

  if (outcome === "skipped") {
    return { show: true, said: "пропуск не успех и не ошибка, но если ждали отчёт — знать надо" };
  }

  if (settings.success === "always") return { show: true, said: "вы просили сообщать об успехах всегда" };
  if (settings.success === "away") {
    return settings.atDesk
      ? { show: false, said: "успех виден в окне: вы у экрана" }
      : { show: true, said: "успех, а вы не у экрана — сообщаю" };
  }
  return { show: false, said: "вы просили не сообщать об успехах: смотрите журнал, когда нужно" };
}

/**
 * Что нельзя выключить.
 *
 * Отдельно от `show`, чтобы галочки в интерфейсе строились из этого списка, а не
 * из воображения дизайнера.
 */
export function cannotDisable(): string[] {
  return ["ошибки", "предупреждение о петле (шаг 335)", "сообщение о безопасности обновления (шаг 318)"];
}

/**
 * Как выглядят три уровня для человека.
 *
 * Словами, а не «all/none/auto»: человек выбирает между понятными состояниями.
 */
export function levels(): { value: SuccessLevel; label: string }[] {
  return [
    { value: "none", label: "не сообщать: успехи видно в журнале" },
    { value: "away", label: "только если меня нет за компьютером" },
    { value: "always", label: "сообщать всегда" },
  ];
}

/**
 * Что человек увидит в настройках правил.
 *
 * Не «уведомления: вкл», а строка, из которой видно, что ошибки всё равно
 * придут.
 */
export function summary(settings: Settings): string {
  const level = settings.success === "none" ? "успехи не сообщаются" : settings.success === "always" ? "успехи сообщаются всегда" : "успехи — только когда вас нет";
  return `${level}; ошибки сообщаются всегда`;
}

/**
 * Почему у ошибки нет настройки.
 *
 * Аргумент, который приходится повторять: тихая ошибка — это не экономия
 * внимания, а обещание, которое нарушено незаметно.
 */
export function whyAlways(): string {
  return "ошибка без сообщения — это обещание, которое нарушено незаметно: человек узнает о нём, когда дело понадобится";
}

/**
 * Сведение с `resultNotice` (фаза 1, шаг 41): роли разведены, а не слиты.
 *
 * Оба модуля отвечали на «показывать ли уведомление» — это был настоящий дубль.
 * Проверка показала, что `show` здесь уже учитывает `atDesk`, то есть полнее.
 * Поэтому:
 *
 *  * **решение** — только тут (`show`): настройка плюс «у экрана ли человек»;
 *  * **текст** — только в `resultNotice`: что написать и как связать несколько
 *    результатов в одно сообщение.
 *
 * Второй правды о «показывать ли» нет — и появиться не должно.
 */
export function roles(): string[] {
  return [
    "показывать ли — `show` здесь: один ответ на два вопроса",
    "что написать — `text` в `resultNotice`",
    "несколько результатов — одна сводка, а не пять окон",
  ];
}
