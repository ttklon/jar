/**
 * Шаг 470: FAQ — десять вопросов, которые задают на самом деле.
 *
 * FAQ пишут из головы: «Что такое ZShelper?», «Как он работает?» — вопросы, которые
 * никто не задаёт. Настоящий FAQ берётся из писем поддержки, и в нём вопросы
 * звучат **неудобно**:
 *
 *  * «Он слушает меня постоянно?» — нет, но это надо объяснить, а не отрицать;
 *  * «А если он удалит не то?» — может, поэтому и спрашивает;
 *  * «Зачем ему интернет, если он локальный?» — незачем, и это проверяется.
 *
 * Правила FAQ:
 *
 *  * **десять** — больше не читают, меньше не покрывают;
 *  * каждый ответ начинается с **прямого ответа** («нет», «да», «локально»), а не
 *    с истории;
 *  * ответ **короче вопроса не бывает** — «да» без объяснения не ответ;
 *  * на неприятный вопрос ответ всё равно есть — пропущенный вопрос читается как
 *    «скрывают».
 */

/** Вопрос и ответ. */
export interface Faq {
  /** Как спрашивают — разговорной фразой. */
  readonly q: string;
  /** Ответ; первое слово — прямой ответ. */
  readonly a: string;
  /** Неудобный ли вопрос. */
  readonly awkward: boolean;
}

/** Сколько вопросов в FAQ. */
export const NEEDED = 10;

/** Первые слова прямого ответа. */
const DIRECT = ["да", "нет", "локально", "только", "по-разному", "не", "всё", "ничего", "никуда", "около"];

/**
 * Проверить FAQ.
 *
 * Нарушения — числом: сколько вопросов, какой ответ не прямой, какой короче
 * вопроса.
 */
export function check(faq: readonly Faq[]): string[] {
  const problems: string[] = [];

  if (faq.length !== NEEDED) problems.push(`вопросов ${faq.length}, а нужно ровно ${NEEDED}`);

  const seen = new Set<string>();
  for (const item of faq) {
    const key = item.q.toLowerCase().trim();
    if (seen.has(key)) problems.push(`「${item.q}」 повторяется`);
    seen.add(key);

    const first = item.a.trim().split(/\s+/)[0]?.toLowerCase().replace(/[,.!?:;]/g, "") ?? "";
    if (!DIRECT.includes(first)) problems.push(`「${item.q}」: ответ начинается с «${first}», а не с прямого ответа`);

    if (item.a.trim().length <= item.q.trim().length) problems.push(`「${item.q}」: ответ короче вопроса — это не ответ`);
  }

  return problems;
}

/**
 * Неудобные вопросы — обязательны.
 *
 * Три штуки: слушает ли, удалит ли не то, зачем интернет. FAQ без них — реклама.
 */
export function awkward(): Faq[] {
  return [
    { q: "Он слушает меня постоянно?", a: "Нет: микрофон открывается по горячей клавише и закрывается, когда дело закончено. Индикатор в трее это показывает.", awkward: true },
    { q: "А если он удалит не то?", a: "Да, может — поэтому опасные действия спрашивают подтверждение, а удаление всегда в корзину, не мимо.", awkward: true },
    { q: "Зачем ему интернет, если он локальный?", a: "Ничего: модель на диске, интернет не нужен. Если в журнале есть запрос наружу — это дефект, а не функция.", awkward: true },
  ];
}

/**
 * Обычные вопросы.
 *
 * Семь штук, и все — те, что спрашивают в первых десяти письмах.
 */
