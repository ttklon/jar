/**
 * Шаг, который нельзя отменить, помечен до запуска и спрашивает сильнее (шаг 113).
 *
 * Дефект. Необратимость узнаётся **после** нажатия:
 *
 *  * **вопрос той же силы**: «удалить 12 файлов» и «посчитать 12 файлов» спрашивают
 *    одинаково — одной галочкой, и человек жмёт её не читая;
 *  * **пометки нет до запуска**: пока план на экране, не видно, какой шаг нельзя
 *    вернуть; видно становится, когда «отменить» не сработало;
 *  * **общее согласие покрывает необратимое**: «выполнить всё» — это одно нажатие, и
 *    необратимый шаг в нём растворяется;
 *  * **цена ошибки не названа**: «нельзя отменить» — не то же, что «12 файлов
 *    исчезнут без копии».
 *
 * Правило: **чем дороже ошибка, тем сильнее вопрос, и сила названа**.
 *
 *  1. **Пометка до запуска**: у необратимого шага свой знак в плане, не в отчёте.
 *  2. **Сильнее — значит другой вопрос**, а не тот же с «вы уверены?»: вопрос
 *     называет **цену** («12 файлов исчезнут без копии»), а не повторяет действие.
 *  3. **Общее согласие не покрывает необратимое**: «выполнить всё» не значит «удали».
 *     Иначе одно нажатие делает то, чего человек не читал.
 *  4. **Сила не резиновая**: три уровня — обычная галочка, названная цена, ввод
 *     слова. Больше уровней — это анкета, и её пролистывают.
 *  5. **Пометка не снимается**: если человек согласился, знак остаётся — он описывает
 *     шаг, а не состояние согласия.
 *
 * Почему не «спросить дважды». Дважды — это два одинаковых вопроса, и второй
 * отвечают не читая. Сила вопроса растёт **качеством**, а не количеством.
 */

/** Как спрашивают. */
export type Ask =
  /** Обычная галочка: шаг отменяем. */
  | "check"
  /** Цена названа: шаг необратим, и человек видит, что исчезнет. */
  | "price"
  /** Ввести слово: цена высокая, и «да» должно быть намеренным. */
  | "word";

/** Шаг, о котором спрашивают. */
export interface Danger {
  /** Что делает — словами. */
  what: string;
  /** Можно ли отменить сделанное. */
  undoable: boolean;
  /** Что исчезнет без возврата — словами. Пусто у отменяемого. */
  price?: string;
  /** Риск из реестра. */
  risk: string;
}

/**
 * Насколько сильный вопрос.
 *
 * `destructive` и всё неотменяемое — минимум «цена». Слово требуется там, где
 * задето **много**: число в цене больше одного.
 */
export function level(item: Danger): Ask {
  if (item.undoable) return "check";
  const many = /\d+/u.exec(item.price ?? "");
  if (item.risk === "destructive" && many !== null && Number(many[0]) > 1) return "word";
  return "price";
}

/**
 * Пометка для плана — до запуска.
 *
 * Знак есть у каждого шага: пустой знак — тоже знак, и он значит «отменяемо».
 */
export function mark(item: Danger): string {
  if (item.undoable) return "отменяемо";
  const price = item.price?.trim();
  return price ? `НЕ ОТМЕНИТЬ: ${price}` : "НЕ ОТМЕНИТЬ: возврата нет";
}

/**
 * Вопрос — в зависимости от силы.
 *
 * Цена в вопросе, а не в примечании под ним: примечание не читают.
 */
export function question(item: Danger): { ask: Ask; text: string } {
  const ask = level(item);
  const price = item.price?.trim();
  if (ask === "check") {
    // Обычный вопрос не пугает: иначе пуганое согласие обесценивает настоящее.
    return { ask, text: `${item.what}?` };
  }
  if (ask === "price") {
    return { ask, text: `${item.what}. Это не отменить${price ? `: ${price}` : ""}. Продолжить?` };
  }
  // Слово: «да» должно быть намеренным, а не мышечным.
  return { ask, text: `${item.what}. Не отменить: ${price ?? "возврата нет"}. Напишите «удалить», чтобы подтвердить` };
}

/**
 * Можно ли выполнять после ответа.
 *
 * Проверяется **по уровню**: галочка не считается ответом на вопрос со словом —
 * иначе сильный вопрос обходится слабым ответом.
 */
export function allows(item: Danger, answer: { checked?: boolean; word?: string }): boolean {
  const ask = level(item);
  if (ask === "check") return answer.checked === true;
  if (ask === "price") return answer.checked === true;
  const word = answer.word?.trim().toLowerCase() ?? "";
  const wanted = item.risk === "destructive" ? "удалить" : "подтверждаю";
  return word === wanted;
}

/**
 * Покрывает ли общее согласие этот шаг.
 *
 * **Никогда**, если шаг необратим: «выполнить всё» — это про отменяемое.
 */
export function covers(danger: Danger, wholePlan: boolean): boolean {
  if (!wholePlan) return false;
  return danger.undoable;
}

/**
 * Сводка для плана: сколько шагов и какой силы.
 *
 * Числом, а не «осторожно»: «необратимых 2 из 5, из них со словом 1» — это отчёт.
 */
export function summary(items: readonly Danger[]): string {
  const permanent = items.filter((item) => !item.undoable).length;
  if (permanent === 0) return `все ${items.length} шагов отменяемы`;
  const words = items.filter((item) => level(item) === "word").length;
  return `необратимых ${permanent} из ${items.length}${words > 0 ? `, из них со словом ${words}` : ""}`;
}
