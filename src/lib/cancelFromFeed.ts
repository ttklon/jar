/**
 * Шаг 368: отмена доступна из ленты, а не только внутри дела — меньше кликов.
 *
 * Плохой путь: увидеть в ленте, что идёт не то → открыть дело → найти кнопку
 * отмены. Три клика, и каждый — время, пока дело продолжает делать не то.
 *
 * Поэтому кнопка отмены есть **на строке ленты**, и она делает то же самое, что
 * внутри дела (шаг 377): один код, одно поведение.
 *
 * Тонкость: отмена в ленте — это не «убрать из списка». Человек нажмёт и решит,
 * что закрыл, а дело продолжит идти. Поэтому кнопка:
 *
 *  * **называется «Отменить»**, а не «×»;
 *  * **спрашивает только если нельзя отменить** (уже отправили): тогда говорит
 *    правду, а не притворяется;
 *  * **показывает, что отмена прошла** — в строке видно «отменено», а не пусто.
 */

/** Дело в ленте. */
export interface FeedItem {
  readonly id: string;
  readonly what: string;
  readonly state: "running" | "waiting" | "done" | "failed" | "cancelled";
  /** Можно ли отменить: шаг, который уже отправлен, отменить нельзя. */
  readonly cancellable: boolean;
}

/** Что делает кнопка. */
export interface Action {
  /** Показывать ли кнопку вообще. */
  readonly show: boolean;
  /** Что будет, если нажать. */
  readonly said: string;
  /** Отмена невозможна — объяснить, а не спрятать. */
  readonly impossible: boolean;
}

/**
 * Кнопка отмены на строке.
 *
 * У завершённого дела кнопки нет: отменять нечего, а «повторить» — другое
 * действие (шаг 375).
 */
export function action(item: FeedItem): Action {
  if (item.state === "done" || item.state === "failed" || item.state === "cancelled") {
    return { show: false, said: "", impossible: false };
  }
  if (!item.cancellable) {
    return {
      show: true,
      impossible: true,
      said: `«${item.what}» отменить нельзя: шаг уже отправлен — остановлю на следующем`,
    };
  }
  return { show: true, impossible: false, said: `отменю «${item.what}» — то же, что кнопка внутри дела` };
}

/**
 * Что стало в строке после отмены.
 *
 * «Отменено» — а не пустая строка: человек должен видеть, что нажатие
 * сработало.
 */
export function afterCancel(item: FeedItem): string {
  return `${item.what}: отменено — остальные шаги не выполнялись`;
}

/**
 * Один код на два места.
 *
 * Проверка ловит расхождение, которое появляется первым: в ленте отмена сделана
 * «своей» функцией, и ведёт себя иначе.
 */
export function sameBehaviour(feed: Action, inside: Action): string[] {
  if (feed.show !== inside.show || feed.impossible !== inside.impossible) {
    return ["отмена в ленте и внутри дела ведут себя по-разному: должен быть один код, а не две кнопки"];
  }
  return [];
}

/**
 * Что нельзя делать с кнопкой.
 *
 * «×» без подписи — самый частый вариант, и он же самый опасный: выглядит как
 * «убрать из списка».
 */
export function notDo(): string[] {
  return [
    "не «×» без подписи: выглядит как «убрать из списка», а отменяет дело",
    "не скрывать кнопку у неотменяемого дела: человек будет искать, почему её нет",
    "не убирать строку после отмены: «отменено» — это результат, его надо видеть",
  ];
}
