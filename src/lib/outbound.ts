/**
 * Что уйдёт наружу: адреса, тела, когда (шаг 167).
 *
 * Дефект. «Всё работает локально» было обещанием в README и в `hint.ts`, но
 * человеку негде было **увидеть** его: экран говорил «работает без сети», а
 * проверить это можно было, только поверив. Приватность — наблюдаемое свойство:
 * либо человек видит список адресов, тел и условий, либо это не приватность, а
 * реклама.
 *
 * Правила:
 *
 *  1. **список из данных, а не из обещаний.** Единственная сеть в ядре —
 *     `download.rs` (сторож 20 валит сборку, если появится другая дверь), и
 *     адрес — тот, что человек сам дал ссылкой или вписал в настройке;
 *  2. **тело названо, а не «данные».** «Тело — ничего: только запрос файла
 *     модели» — это ответ; «передаются данные для работы» — нет;
 *  3. **когда назван момент.** «только по нажатию «Скачать», один раз» — а не
 *     «иногда»;
 *  4. **локальный адрес — не «наружу».** `127.0.0.1` — это свой же компьютер,
 *     и путать его с интернетом значит пугать человека зря и прятать настоящее;
 *  5. **пусто — сказать пусто.** «Наружу не уходит ничего» — это законный,
 *     проверяемый ответ, а не отсутствие списка;
 *  6. **чего не знаем — не додумываем.** Адрес не назван — «адрес задаёт
 *     ссылка», а не «example.com».
 *
 * Модуль не делает запросов и ничего не решает: он собирает то, что уже
 * известно, в одно место, которое можно прочитать глазами.
 */

/** Куда уходит. */
export type Place = "outside" | "loopback";

/** Одна запись: что, куда, когда и с каким телом. */
export interface Exit {
  /** Что уходит: «модель разговора», «движок распознавания». */
  what: string;
  /** Куда: хост. `null` — адрес задаёт человек (ссылка или настройка). */
  host: string | null;
  /** Куда это по сути. */
  place: Place;
  /** Что именно в теле запроса. */
  body: string;
  /** Когда. */
  when: string;
  /** Можно ли не пускать. */
  optional: boolean;
}

/**
 * Дверь наружу — одна, и это загрузка.
 *
 * Список собран по коду ядра: `download.rs` — единственное место с сетью
 * (сторож 20 «одна дверь»). Модель разговора и движок распознавания качаются
 * одним путём, поэтому и записи две, а не «много».
 */
export const EXITS: readonly Exit[] = [
  {
    what: "модель разговора (.gguf)",
    host: null,
    place: "outside",
    body: "ничего, кроме запроса файла: ни фразы, ни истории, ни путей",
    when: "только по нажатию «Скачать», один раз на файл",
    optional: true,
  },
  {
    what: "движок распознавания речи (ggml-*.bin)",
    host: null,
    place: "outside",
    body: "ничего, кроме запроса файла: голос остаётся на машине",
    when: "только по нажатию «Скачать», один раз на файл",
    optional: true,
  },
];

/**
 * Локальные адреса: свой же компьютер.
 *
 * `127.0.0.1`, `localhost`, `::1` — это не «наружу». Их надо показывать
 * отдельно и называть своими: иначе человек, увидев `127.0.0.1:8080`, решит,
 * что приложение что-то отправило в интернет.
 */
export const LOCAL: readonly Exit[] = [
  {
    what: "движок модели: запросы к llama-server",
    host: "127.0.0.1",
    place: "loopback",
    body: "фраза и подсказка — но только до своего же компьютера",
    when: "пока модель думает: на каждую фразу, локально",
    optional: false,
  },
];

/** Хост из адреса — или `null`, если адрес не назван. */
export function hostOf(url: string): string | null {
  const match = /^https?:\/\/([^/?#]+)/i.exec(url.trim());
  return match ? match[1]! : null;
}

/** Локальный ли хост: свой компьютер, а не интернет. */
export function isLocal(host: string | null): boolean {
  if (host === null) return false;
  // IPv6: голый `::1` и в скобках `[::1]:8080` — один и тот же адрес. Делить по
  // первому двоеточию здесь нельзя: `::1` от этого становится пустой строкой.
  const lowered = host.trim().toLowerCase();
  if (lowered === "::1" || lowered.startsWith("[::1]")) return true;
  const bracketed = /^\[([^\]]+)\]/.exec(lowered);
  const name = bracketed ? bracketed[1]! : lowered.split(":")[0]!;
  return name === "127.0.0.1" || name === "localhost" || name === "::1" || name === "0.0.0.0";
}

/**
 * Список «что уйдёт наружу» с конкретными адресами, если их дали.
 *
 * `urls` — то, что человек вписал в настройке или ссылкой. Пусто — адрес задаёт
 * он сам, и это так и сказано: подставить «huggingface.co» значило бы назвать
 * адрес, которого может и не быть.
 */
export function exits(urls: readonly string[] = []): Exit[] {
  const named = urls.map((url) => hostOf(url)).filter((host): host is string => host !== null);
  const outside = EXITS.map((exit, index) => {
    const host = named[index] ?? named[0] ?? null;
    return { ...exit, host };
  });
  // Локальное в тот же список, но с пометкой: оно идёт своим чередом.
  return [...outside, ...LOCAL];
}

/**
 * Что уйдёт при **выключенной** сети: ничего.
 *
 * Это не украшение: список при выключенной сети должен быть пустым, иначе
 * «выключено» — не выключено.
 */
export function whenOffline(list: readonly Exit[]): Exit[] {
  return list.filter((exit) => exit.place === "outside" && exit.optional === false);
}

/** Одна строка на запись: что, куда, когда, что в теле. */
export function line(exit: Exit): string {
  const where = exit.place === "loopback" ? `свой компьютер (${exit.host})` : exit.host ?? "адрес задаёт ссылка";
  const mark = exit.optional ? "" : " · без этого не работает";
  return `${exit.what} → ${where} · ${exit.when} · тело: ${exit.body}${mark}`;
}

/**
 * Итог: сколько уходит наружу и сколько остаётся на машине.
 *
 * Числом, потому что «всё локально» проверяется счётом, а не верой.
 */
export function summary(list: readonly Exit[]): string {
  const outside = list.filter((exit) => exit.place === "outside");
  const local = list.filter((exit) => exit.place === "loopback");
  if (outside.length === 0) {
    return local.length === 0
      ? "наружу не уходит ничего: ни одного адреса вне машины"
      : `наружу не уходит ничего; на своём компьютере — ${local.length} ${local.length === 1 ? "обращение" : "обращения"}`;
  }
  return `наружу: ${outside.length} ${outside.length === 1 ? "дверь" : "двери"}; на своём компьютере — ${local.length}`;
}

/**
 * Что сказать, если сеть включена, но человек ничего не скачивал.
 *
 * «Список пуст» и «ничего не было» — разные факты: первое про возможность,
 * второе про факт. Показывать «наружу ничего не ушло» без проверки нельзя.
 */
export function happened(events: readonly { subject: string; kind: string }[]): string {
  const sent = events.filter((event) => event.kind === "finished" && event.subject.includes("скачать"));
  if (sent.length === 0) return "за это время наружу ничего не уходило: скачиваний не было";
  return `скачиваний было ${sent.length}: адреса — те, что вы дали ссылкой`;
}
