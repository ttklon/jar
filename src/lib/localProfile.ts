/**
 * Шаг 406: локальные профили — без аккаунта и без сети.
 *
 * «Профиль» в больших программах означает аккаунт: почта, пароль, синхронизация,
 * «войдите, чтобы продолжить». Здесь — наоборот, и это не ограничение, а
 * обещание: профиль живёт в файле на диске, и его существование не требует ни
 * одного сетевого запроса.
 *
 * Почему это важно именно для профилей:
 *
 *  * **аккаунт — это утечка, даже когда «мы не продаём данные»**: пока он есть,
 *    есть и то, что можно потерять, слить или запросить у владельца;
 *  * **сеть нужна не всегда, а профиль нужен всегда** — в поезде, в деревне, на
 *    машине без интернета;
 *  * **два человека за одним компьютером — не повод заводить сервер**.
 *
 * Проверяется не словами, а списком: что профиль содержит, чего в нём нет, и что
 * происходит при выключенной сети.
 */

/** Что лежит в локальном профиле. */
export interface Local {
  readonly person: { readonly id: string; readonly name: string };
  readonly facts: readonly string[];
  readonly grants: readonly { readonly risk: string; readonly scope: string }[];
}

/**
 * Что профиль содержит.
 *
 * Только три вещи, и все — то, что человек сам сказал и разрешил.
 */
export function contents(): string[] {
  return ["имя", "факты, которые человек сказал", "разрешения, которые человек дал"];
}

/**
 * Чего в профиле нет.
 *
 * Список — ответ на «а вдруг там всё равно что-то есть».
 */
export function absent(): string[] {
  return ["пароль: его нет, потому что нет входа", "почта и телефон: незачем", "идентификатор устройства: профиль не привязан к машине", "журнал активности, кроме своих дел"];
}

/**
 * Работает ли профиль без сети.
 *
 * `online` — есть ли сеть. Ответ всегда «работает», и это тоже проверяется: если
 * однажды появится «требуется интернет», тест упадёт.
 */
export function worksOffline(online: boolean): { ok: boolean; said: string } {
  return { ok: true, said: online ? "профиль работает: сеть не нужна и не используется" : "профиль работает без сети: он в файле на диске" };
}

/**
 * Где лежит.
 *
 * Просто путь в папке данных программы — и это всё, что нужно знать человеку,
 * чтобы сделать копию или удалить.
 */
export function where(dataDir: string): string {
  const sep = dataDir.includes("\\") ? "\\" : "/";
  return `${dataDir.replace(/[\\/]+$/, "")}${sep}profiles`;
}

/**
 * Что проверяет тест.
 *
 * Три проверки: нет сети, нет аккаунта, нет привязки к устройству.
 */
export function checks(): string[] {
  return [
    "создание профиля не делает ни одного сетевого запроса",
    "ни одно поле профиля не похоже на учётную запись: нет пароля, почты, телефона",
    "профиль переносится на другую машину файлом — и это не требует сервера",
  ];
}

/**
 * Что обещание не значит.
 *
 * «Без аккаунта» ≠ «без сети вообще»: модель скачивается, обновления
 * проверяются. Но профиль от этого не зависит.
 */
export function notAll(): string {
  return "«без аккаунта» не значит «без сети вообще»: модель скачивается и обновления проверяются, но профиль от этого не зависит";
}
