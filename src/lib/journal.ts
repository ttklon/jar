/**
 * Журнал ошибок, сгруппированный по причинам, а не по времени.
 *
 * Зачем. Журнал по времени отвечает на вопрос «что случилось в 14:32» — это
 * нужно для разбора одного случая. Но человек, у которого «что-то не работает
 * третий день», задаёт другой вопрос: **что болит**. Список из двадцати строк
 * «не удалось» подряд на него не отвечает: причины в нём перемешаны, и одна
 * повторяющаяся ошибка выглядит как двадцать разных.
 *
 * Поэтому здесь группировка по причине с числом и временем:
 *
 *  * **причина — не текст ошибки целиком**, а её суть: «нет сети», «не хватает
 *    прав», «файл занят», «модель не скачалась». Тексты различаются словами,
 *    причина — нет;
 *  * **счётчик и время видны сразу**: «нет сети — 7 раз, последний в 14:32»
 *    говорит больше, чем семь одинаковых строк;
 *  * **неизвестное не выбрасывается**: если причину узнать нельзя, она
 *    попадает в «другие» со своим текстом, а не исчезает. Пропавшая ошибка —
 *    худший вид лжи в журнале.
 */

/** Одна строка журнала в том виде, в каком её отдаёт ядро. */
export interface JournalLine {
  outcome: string;
  at_ms: number;
}

export interface ReasonGroup {
  /** Короткая причина: «нет сети», «файл занят». */
  reason: string;
  /** Сколько раз. Всегда больше нуля. */
  times: number;
  /** Когда случилось в последний раз (Unix-мс) — для «последний раз в …». */
  lastMs: number;
  /** Первый текст ошибки как пример — чтобы было что показать подробнее. */
  sample: string;
}

/**
 * Причина по тексту итога.
 *
 * Правила нарочно грубые и по-русски: они должны узнавать причину в живом
 * тексте ошибок Windows и наших собственных сообщений, а не разбирать их
 * грамматически. Неизвестное — «другое», и текст остаётся виден.
 */
export function reasonOf(outcome: string): string {
  const text = outcome.toLowerCase();
  if (!text.startsWith("error") && !text.startsWith("denied")) return "";
  // Порядок важен: «нет сети» проверяется раньше «таймаута», потому что
  // таймаут в офлайне — следствие, а не причина.
  if (/сет|network|dns|offline|нет соединения|host|resolve/.test(text)) return "нет сети";
  if (/доступ|access|denied|прав|permission|запрещ/.test(text)) return "не хватает прав";
  if (/занят|locked|busy|используется/.test(text)) return "файл занят";
  if (/места|space|диск/.test(text)) return "не хватает места";
  if (/скач|download|загруз|хеш|hash/.test(text)) return "скачивание не удалось";
  if (/модел|model|gguf/.test(text)) return "модель не подошла";
  if (/движок|engine|server|llama/.test(text)) return "движок не запустился";
  if (/таймаут|timeout|не ответ|долго/.test(text)) return "не дождались ответа";
  if (/отмен|cancel/.test(text)) return "отменено человеком";
  return "другое";
}

/**
 * Группирует неудачные строки по причинам.
 *
 * Успех (`ok`) в список не попадает: журнал ошибок — про ошибки. Пустой вход —
 * пустой список, а не группа «0 раз»: ноль раз — это не причина.
 */
export function groupReasons(lines: JournalLine[]): ReasonGroup[] {
  const groups = new Map<string, ReasonGroup>();
  for (const line of lines) {
    const reason = reasonOf(line.outcome);
    if (!reason) continue;
    const seen = groups.get(reason);
    if (seen) {
      seen.times += 1;
      if (line.at_ms > seen.lastMs) {
        seen.lastMs = line.at_ms;
        // Свежий пример полезнее старого: ошибка могла измениться.
        seen.sample = line.outcome;
      }
    } else {
      groups.set(reason, {
        reason,
        times: 1,
        lastMs: line.at_ms,
        sample: line.outcome,
      });
    }
  }
  // Сначала то, что болит чаще. При равенстве — то, что случилось позже:
  // свежая ошибка важнее вчерашней.
  return [...groups.values()].sort((a, b) => b.times - a.times || b.lastMs - a.lastMs);
}
