/**
 * Если фраза похожа на две разные руки — спросить одним коротким вопросом (шаг 95).
 *
 * Дефект. Неоднозначная фраза решается **молча**, и решается она порядком в
 * списке: какое действие нашлось лучше по словам, то и исполняется. Дальше:
 *
 *  * **человек не знает, что был выбор**: «почисти папку» могло значить
 *    «удалить временные файлы» или «разложить по типам» — приложение выбрало
 *    одно и не сказало;
 *  * **выбор оказывается не тем**, и это выясняется после действия, а не до;
 *  * **спросить «уточните, что вы имели в виду»** — это не вопрос, а отказ:
 *    человек уже сказал, ему нужен выбор **из того, что нашлось**.
 *
 * Правило: **видно, что выбора два, и выбор делается одним коротким вопросом**.
 *
 *  1. Вопрос содержит **только то, что нашлось**, и коротко: «что именно:
 *     очистить корзину или найти крупные файлы?» — а не список реестра.
 *  2. Вариантов **два-три**, а не десять: десять — это не вопрос, а меню. Если
 *     нашлось больше — берём **самые вероятные три** и говорим, что есть ещё.
 *  3. Вопрос **не задаётся**, если разница не влияет на результат: два одинаковых
 *     по последствиям варианта — это шум, а не выбор (шаг 82).
 *  4. Если один вариант **опасный**, а другой нет — это **не равный выбор**:
 *     опасный назван опасным в самом вопросе, а не после.
 *  5. Пока вопрос не отвечен — **ничего не исполняется**: молчаливо выбранный
 *     вариант — это выбор за человека.
 *
 * Почему не «выбрать самый вероятный». Самый вероятный — это догадка. При
 * удалении догадка стоит файлов, а один короткий вопрос стоит секунды.
 */

/** Один вариант — то, что действительно нашлось. */
export interface Option {
  /** Что будет сделано: «очистить корзину». */
  what: string;
  /** Позиция в плане — чтобы ответ связался с шагом. */
  position: number;
  /** Опасен ли: необратимо. */
  dangerous: boolean;
}

/**
 * Сколько вариантов спрашивать.
 *
 * Не десять: десять — это меню, а не вопрос. Три — это ещё выбор; больше —
 * человек перестаёт читать и жмёт первое.
 */
export const ASK = 3;

/** Нужен ли вопрос. */
export interface Ask {
  /** Спрашивать ли. */
  ask: boolean;
  /** Варианты по порядку — только те, что нашлись. */
  options: Option[];
  /** Сколько всего нашлось, если больше, чем показываем. */
  hidden: number;
  /** Почему — для показа и теста. */
  why: string;
}

/**
 * Решение о вопросе.
 *
 * Ничего не нашлось — не вопрос, а честное «не нашлось» (шаг 82). Нашлось
 * ровно одно — тоже не вопрос.
 */
export function need(options: readonly Option[]): Ask {
  if (options.length === 0) {
    return { ask: false, options: [], hidden: 0, why: "под фразу ничего не подошло — скажу, что не нашлось" };
  }
  if (options.length === 1) {
    const only = options[0] as Option;
    return {
      ask: false,
      options: [only],
      hidden: 0,
      why: `под фразу подходит одно: «${only.what}»`,
    };
  }
  if (!differs(options)) {
    return { ask: false, options: [...options], hidden: 0, why: "варианты дают одно и то же — выбирать не из чего" };
  }
  return {
    ask: true,
    options: options.slice(0, ASK),
    hidden: Math.max(0, options.length - ASK),
    why: `под фразу подходит ${options.length} разных — спрошу одним коротким вопросом`,
  };
}

/**
 * Различаются ли варианты по последствиям.
 *
 * Два варианта, которые делают одно и то же (или оба ничего не меняют), — это
 * шум: вопрос о них — работа без пользы.
 */
export function differs(options: readonly Option[]): boolean {
  const risky = options.some((option) => option.dangerous);
  const safe = options.some((option) => !option.dangerous);
  if (risky && safe) return true;
  const what = new Set(options.map((option) => option.what.trim().toLowerCase()));
  return what.size > 1;
}

/**
 * Короткий вопрос.
 *
 * Опасный вариант **назван опасным в самом вопросе**: иначе человек выбирает
 * «удалить» и узнаёт цену после.
 */
export function question(ask: Ask): string {
  if (!ask.ask) return ask.why;
  const options = ask.options.map((option) =>
    option.dangerous ? `${option.what} (это необратимо)` : option.what,
  );
  const tail = ask.hidden > 0 ? `; ещё ${ask.hidden} — скажите, если не то` : "";
  return `что именно: ${options.join(" или ")}${tail}?`;
}

/**
 * Можно ли начинать.
 *
 * Пока вопрос не отвечен — **нельзя**: молчаливо выбранный вариант — это выбор
 * за человека.
 */
export function go(ask: Ask, answered: number | null): boolean {
  return !ask.ask || answered !== null;
}

/**
 * Что сказать после ответа.
 *
 * Названо, **что выбрано** — чтобы человек видел, что его ответ понят, а не
 * «начинаю».
 */
export function chosen(ask: Ask, answered: number | null): string {
  if (!ask.ask) return ask.why;
  const found = ask.options.find((option) => option.position === answered);
  return found === undefined
    ? "ответ не связался с вариантом — скажите ещё раз, пожалуйста"
    : `понял: «${found.what}»${found.dangerous ? " — это необратимо, подтвердите" : ""}`;
}
