/**
 * Проверять понимание по результату: сходится ли шаг с фразой (шаг 86).
 *
 * Дефект. Приложение докладывает «готово» по факту **исполнения**, а не по
 * совпадению с просьбой. Отсюда два вида «успеха», которые хуже ошибки:
 *
 *  * **сделано не то, но без ошибки**: «открой отчёт» открыло папку — действие
 *    выполнено, отчёт не открыт, человек видит «готово» и пустой экран;
 *  * **сделано то, но не так**: «найди большие файлы» нашло файлы, отсортировав
 *    по дате, — ответ есть, а на вопрос не отвечает.
 *
 * Правило: **шаг сверяется с фразой, а не только с успехом выполнения**.
 *
 *  1. У шага есть **предмет** (объект из разбора, шаг 81) и **признак**
 *     (определение: размер, дата, имя). Успех — это когда результат содержит
 *     предмет **и** соответствует признаку.
 *  2. **Открылось не то** — это не успех. «Открыл папку» на «открой отчёт» —
 *     честный отказ, а не «готово».
 *  3. **Сделано, но без признака** — «сделано, но по дате, а вы просили по
 *     размеру». Сказано, а не замолчано: человек сам решит, годится ли.
 *  4. «Готово» говорится **только когда сходится**. Иначе слово «готово»
 *     перестаёт значить «получилось» — и тогда его пропускают, как и лишний
 *     вопрос (шаг 82).
 *
 * Почему не «проверить потом глазами». Человек проверяет глазами только то, в
 * чём сомневается; «готово» — это как раз сигнал не сомневаться.
 */

import type { Qualifier } from "./intent";

/** Что просили. */
export interface Asked {
  /** Предмет: «отчёт», «большие файлы». */
  object: string;
  /** Признак: по размеру, по дате, по имени. */
  qualifier: Qualifier;
}

/** Что получилось. */
export interface Got {
  /** Что открылось или нашлось — словами результата. */
  what: string;
  /** По какому признаку результат упорядочен или отобран, если видно. */
  by: Qualifier | "нет";
  /** Сколько предметов нашлось. */
  count: number;
}

/** Сходится ли. */
export type Fit =
  /** Сходится: предмет тот и признак тот. */
  | "fits"
  /** Предмет другой: открылось/нашлось не то. */
  | "wrong-thing"
  /** Предмет тот, признак не тот: сделано, но не так. */
  | "wrong-way"
  /** Предмет есть, но пусто: нашлось ноль. */
  | "empty";

/**
 * Сверка результата с фразой.
 *
 * Сравнение предмета — по **основе слова**: «отчёт» и «отчёты» — один предмет,
 * «отчёт» и «папка» — разные.
 */
export function check(asked: Asked, got: Got): Fit {
  if (!sameThing(asked.object, got.what)) return "wrong-thing";
  if (got.count === 0) return "empty";
  // «Нет признака» — не «другой признак»: результат мог не показать, как
  // отобрано, и это не повод объявлять ошибку.
  if (asked.qualifier !== "нет" && got.by !== "нет" && got.by !== asked.qualifier) return "wrong-way";
  return "fits";
}

/**
 * Основа слова: «отчёты» → «отчет», «файлы» → «файл».
 *
 * Режем по **любым** не-буквам, а не по пробелам: «отчёт-март.pdf» — это
 * «отчет» + «март» + «pdf», и «отчёт» должен с ним сойтись. И срезаем окончание
 * только когда после него остаётся не меньше трёх букв: иначе «отчёт» теряет
 * «т» и перестаёт быть собой.
 */
function stem(word: string): string {
  return word
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^\p{L}\p{N}]+/u)
    .filter((part) => part.length >= 3)
    .map((part) => {
      const cut = part.replace(/(ами|ями|ов|ей|ы|и|а|я|е|у|ю|ой|ый|ая|ое|ые|ых|ому)$/u, "");
      return cut.length >= 3 ? cut : part;
    })
    .sort()
    .join(" ");
}

function sameThing(asked: string, got: string): boolean {
  const one = stem(asked);
  const two = stem(got);
  if (one.length === 0 || two.length === 0) return false;
  // Пересечение основ, а не равенство: «большие файлы» и «файлы в загрузках» —
  // всё ещё файлы, разница в признаке, а не в предмете.
  const left = new Set(one.split(" "));
  return two.split(" ").some((word) => left.has(word));
}

/**
 * Что сказать человеку.
 *
 * «Готово» — **только когда сходится**. В остальных случаях названо, что не так
 * и что получилось на самом деле: человек должен узнать правду до того, как
 * начнёт искать глазами.
 */
export function say(asked: Asked, got: Got): string {
  switch (check(asked, got)) {
    case "fits":
      return `готово: ${got.what}`;
    case "wrong-thing":
      return `не то: вы просили «${asked.object}», а получилось «${got.what}» — это не выполнено`;
    case "wrong-way":
      return `сделано, но не так: просили ${word(asked.qualifier)}, а получилось ${word(got.by)}`;
    case "empty":
      return `«${asked.object}» не нашлось ни одного — это пусто, а не выполнено`;
  }
}

function word(qualifier: Qualifier | "нет"): string {
  switch (qualifier) {
    case "размер":
      return "по размеру";
    case "имя":
      return "по названию";
    case "дата":
      return "по дате";
    case "тип":
      return "по типу";
    case "место":
      return "в указанном месте";
    case "нет":
      return "без признака";
  }
}

/**
 * Считать ли шаг выполненным.
 *
 * **Нет**, если предмет другой или пусто: «выполнено» с не тем предметом ломает
 * журнал (шаг 37) и учит не читать отчёты.
 */
export function done(fit: Fit): boolean {
  return fit === "fits" || fit === "wrong-way";
}

/**
 * Надо ли остановить план.
 *
 * Ошибка предмета — **да**: следующие шаги опираются на результат этого, и
 * продолжать значит делать не то, что просили (шаг 83).
 */
export function stop(fit: Fit): boolean {
  return fit === "wrong-thing" || fit === "empty";
}
