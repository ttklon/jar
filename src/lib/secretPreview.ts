/**
 * Секреты маскируются в предпросмотре и журнале (шаг 103).
 *
 * Дефект. Маскировка смотрит **только на имя поля** (`describePlanParams`,
 * шаг 101): `token: …` скрыт, а `path: C:\keys\sk-…` — нет. Отсюда:
 *
 *  * **секрет в «безопасном» поле** показывается целиком — в предпросмотре, на
 *    экране, в скриншоте, который человек кому-то отправит;
 *  * **журнал получает фразы как есть**: `heard` — это то, что услышано, и там
 *    бывает пароль, названный вслух (шаг 88: журнал нужен для разбора, но он же
 *    становится хранилищем чужих секретов);
 *  * **маска без размера**: три `[скрыто]` подряд в одном плане — человек не
 *    понимает, тот же это ключ или другой, и соглашается на неизвестное;
 *  * **граница не названа**: где именно маскируется и где нет — догадки. Кто-то
 *    считает, что «журнал локальный, значит можно».
 *
 * Правило: **два правила, а не одно, и граница названа**.
 *
 *  1. **По имени поля** — как было: `password`, `token`, `api_key`, `secret`,
 *     `credential`, `authorization`.
 *  2. **По значению** — всегда и независимо от имени: список шаблонов **один** и
 *     тот же, что у вычистки фразы (шаг 98). Второй список разошёлся бы с первым.
 *  3. **Маска называет размер**: `[скрыт: 24 символа]` — видно, тот же ключ или
 *     другой, и при этом ни одного символа значения.
 *  4. **Граница названа**: предпросмотр плана, журнал разбора, текст ошибки. Всё,
 *     что уходит из приложения наружу, и всё, что остаётся в журнале, проходит
 *     через эту функцию — а не «где вспомнили».
 *  5. **Проверяемо**: `audit` берёт то, что приложение **собирается показать**, и
 *     отвечает, остался ли там секрет. Не обещание, а проверка.
 *
 * Почему не «маскировать всё подряд». Маска на обычном пути ломает согласие:
 * человек должен видеть `D:\Отчёты`, чтобы понять, на что соглашается. Поэтому
 * маскируется секрет, а не весь текст.
 */

import { clean as cleanSecrets, MARK } from "./secrets";

/**
 * Имена полей, которые считаются секретом целиком.
 *
 * Список **по имени**, а не по виду значения: в поле `password` секретом может
 * быть что угодно, и угадывать шаблоном там нечего.
 */
const SECRET_NAME =
  /password|passphrase|secret|token|(?:api|access|private|client)[_-]?key|credential|authorization|bearer/i;

/** Где маскировка обязательна. Названа, а не подразумевается. */
export interface Place {
  /** Где показывается. */
  where: string;
  /** Что там маскируется. */
  rule: string;
}

/**
 * Граница.
 *
 * Перечислена, потому что «мы маскируем секреты» без перечня мест означает
 * «маскируем там, где вспомнили». Тест сверяет этот список с вызовами.
 */
export function boundary(): Place[] {
  return [
    { where: "предпросмотр плана", rule: "параметры — по имени и по значению, цель и пояснения — по значению" },
    { where: "журнал разбора", rule: "услышанное и понятое — по значению, до записи" },
    { where: "текст ошибки", rule: "по значению: ошибка цитирует фразу, а фраза бывает с паролем" },
  ];
}

/**
 * Маска одного значения.
 *
 * Сначала имя поля: если поле секретное — значение не разбирается вовсе (иначе
 * `password: "hunter2"` не совпал бы ни с одним шаблоном и уехал открытым).
 * Потом значение: секрет может лежать в поле `path` или `note`.
 */
export function mask(name: string, value: string): string {
  if (SECRET_NAME.test(name)) {
    // Имя поля уже говорит, что это за значение, поэтому маска прежняя —
    // контракт экрана шага 101 не ломается.
    return "[скрыто]";
  }
  return maskedInside(value);
}

/**
 * Длина в символах — единственное, что сообщается о найденном секрете.
 *
 * Нужна там, где имя поля ничего не говорит: два ключа в одном плане иначе
 * выглядят одинаково, и человек соглашается на неизвестное.
 */
function SymbolLength(value: string): string {
  return `${Array.from(value).length} симв.`;
}

/** Секрет, найденный в несекретном поле: маска плюс длина. */
export function maskedInside(value: string): string {
  const got = cleanSecrets(value);
  if (!got.any) return value;
  // Длина считается по найденному секрету: человек спрашивает «тот же ключ?», и
  // длина всего поля на этот вопрос не отвечает.
  const secret = secretIn(value);
  return `${got.text} [скрыт: ${SymbolLength(secret ?? value)}]`;
}

/** Сам секрет — только для подсчёта длины, наружу не уходит. */
function secretIn(value: string): string | null {
  const found = value.match(/\bsk-[A-Za-z0-9_-]{16,}|\bghp_[A-Za-z0-9]{20,}|\bAKIA[0-9A-Z]{16}\b/);
  return found === null ? null : found[0];
}

/** Сколько символов в строке — для маски «того же или другого ключа». */
export function size(value: string): number {
  return Array.from(value).length;
}

/**
 * Параметры для показа.
 *
 * Заменяет маскировку «по имени» из шага 101: к ней добавлено правило по
 * значению, а сама шапка («параметров нет») осталась прежней — на неё опираются
 * экраны.
 */
export function params(input?: Record<string, string>): string {
  if (!input || Object.keys(input).length === 0) return "параметров нет";
  return Object.entries(input)
    .map(([name, value]) => `${name}: ${mask(name, value)}`)
    .join("; ");
}

/** Свободный текст: цель, пояснение шага, сообщение об ошибке. */
export function text(value: string): string {
  return cleanSecrets(value).text;
}

/**
 * Строка журнала до записи.
 *
 * Журнал — это фразы человека, и они остаются в журнале. Поэтому вычистка идёт
 * **до** записи, а не при показе: то, что записано, уже не вычистить.
 */
export function heard(value: string): string {
  return cleanSecrets(value).text;
}

/**
 * Проверка границы.
 *
 * Берёт то, что приложение собирается показать или записать, и ищет в этом
 * секреты. Пустой список — граница держит; непустой называет **место**, а не
 * только факт.
 */
export function audit(outgoing: readonly { where: string; value: string }[]): string[] {
  const leaks: string[] = [];
  for (const item of outgoing) {
    if (cleanSecrets(item.value).any) {
      leaks.push(`${item.where}: остался секрет`);
    }
  }
  return leaks;
}

/** Что сказать человеку, если что-то скрыто. */
export function say(shown: string, original: string): string {
  if (shown === original) return "";
  return `часть значения скрыта — на экране ${shown}, длина сохранена`;
}

/** Маркер вычищенного значения — тот же, что у вычистки фразы. */
export const MASKED = MARK;
