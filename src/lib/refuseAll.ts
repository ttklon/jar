/**
 * План, который нельзя собрать из рук, честно отказывает целиком (шаг 115).
 *
 * Дефект. Из плана в несколько шагов приложение выполняет **ту часть, которая
 * собирается**, и молчит об остальном:
 *
 *  * **половина — это не «частично хорошо»**: «создать папку, переместить отчёт,
 *    удалить исходник» без рук для перемещения создаёт папку и удаляет исходник —
 *    то есть **теряет** файл, которого человек хотел сохранить;
 *  * **молчание читается как успех**: отчёт «2 шага выполнено» не говорит, что
 *    третий не выполнялся никогда;
 *  * **человек не знает, чего не хватает**: «не умею» без названия руки — тупик, из
 *    которого нельзя выйти (не понятно, что доучить);
 *  * **порядок мог бы спасти**: иногда не хватает не руки, а **перестановки** — и это
 *    другой ответ, чем «не умею».
 *
 * Правило: **нельзя собрать — не выполняем ничего, и называем, чего нет**.
 *
 *  1. **Отказ — целиком**: половина плана, собранного наполовину, — это изменённый
 *     мир без цели, ради которой его меняли.
 *  2. **Отказ называет, чего не хватает**: «нет руки: `файлы|переместить`» — это
 *     задача на обучение, а не тупик.
 *  3. **Отказ отделяет «не умею» от «нельзя»**: нет руки — научусь; запрещено
 *     политикой — не научусь, и это **другой** ответ человеку.
 *  4. **Отказ предлагает ближайшее**: что можно сделать вместо — без потери данных.
 *  5. **Отказ не выполняет «полезную часть»** даже если она безопасна: «но это же
 *     безобидное» — то же искушение, что в шаге 104, и там оно уже отвергнуто.
 *
 * Почему не «выполнить, что можем, и предупредить». Предупреждение после действия —
 * это не выбор, а факт. Если человек не может сказать «нет», он уже согласился.
 */

/** Шаг плана — с точки зрения сборки из рук. */
export interface Planned {
  /** Что делает — словами. */
  what: string;
  /** Адрес руки. */
  tool: string;
  /** Есть ли рука, которая это умеет. */
  hand: boolean;
  /** Разрешено ли политикой (у существующей руки). */
  allowed: boolean;
}

/** Почему шаг не встаёт в план. */
export interface Missing {
  position: number;
  what: string;
  tool: string;
  /** `no-hand` — не умею; `forbidden` — нельзя. */
  kind: "no-hand" | "forbidden";
  /** Словами. */
  said: string;
}

/**
 * Чего не хватает.
 *
 * Разделение «не умею» и «нельзя» — не педантизм: первое превращается в задачу на
 * обучение, второе — нет, и обещать обучение там, где запрещено, значит врать.
 */
export function missing(plan: readonly Planned[]): Missing[] {
  const out: Missing[] = [];
  plan.forEach((step, position) => {
    if (!step.hand) {
      out.push({
        position,
        what: step.what,
        tool: step.tool,
        kind: "no-hand",
        said: `не умею: «${step.what}» — нет руки ${step.tool}`,
      });
      return;
    }
    if (!step.allowed) {
      out.push({
        position,
        what: step.what,
        tool: step.tool,
        kind: "forbidden",
        said: `нельзя: «${step.what}» запрещено политикой — этому не научусь, это решение, а не умение`,
      });
    }
  });
  return out;
}

/** Решение по плану целиком. */
export interface Verdict {
  /** Выполнять ли план. */
  run: boolean;
  /** Чего не хватает — по строке на шаг. */
  why: string[];
  /** Что предложить вместо; пусто, если предложить нечего. */
  instead: string;
}

/**
 * Решение по плану.
 *
 * Отказ целиком, но **с пользой**: названо, чего не хватает, и предложено ближайшее.
 * Отказ без предложения — тупик; предложение без отказа — выполненная половина.
 */
export function judge(plan: readonly Planned[]): Verdict {
  if (plan.length === 0) {
    return { run: false, why: ["план пуст — делать нечего, и это не успех"], instead: "" };
  }
  const gaps = missing(plan);
  if (gaps.length === 0) return { run: true, why: [], instead: "" };

  const forget = gaps.filter((gap) => gap.kind === "no-hand");
  const instead =
    gaps.length === 1 && gaps[0]?.kind === "forbidden"
      ? "части этого плана запрещены политикой — соберите план без них, и он соберётся"
      : gaps.length === 1
        ? `можно сделать только это: «${gaps[0]?.what ?? ""}» — без остального плана`
        : forget.length === gaps.length
        ? `можно доучить ${forget.length === 1 ? "одну руку" : `${forget.length} руки`}: тогда план соберётся целиком`
        : "часть плана запрещена политикой — соберите план без неё, и он соберётся";

  return {
    run: false,
    // Все дыры названы, а не первая: чинить одну и наткнуться на следующую — обидно.
    why: ["не выполню ничего: план собирается не целиком", ...gaps.map((gap) => gap.said), instead],
    instead,
  };
}

/**
 * Что записать в обучение.
 *
 * Только «не умею»: «нельзя» в обучение не уходит — иначе очередь задач на обучение
 * наполняется тем, что делать запрещено.
 */
export function learn(plan: readonly Planned[]): string[] {
  return missing(plan)
    .filter((gap) => gap.kind === "no-hand")
    .map((gap) => gap.what);
}

/**
 * Можно ли предложить план без недостающих шагов.
 *
 * Нет, если удаление шага **меняет смысл** остальных: «переместить» без «создать
 * папку» — другое действие. Здесь правило простое и честное: не предлагаем, если
 * хоть один оставшийся шаг зависит от убранного.
 */
export function withoutGaps(plan: readonly Planned[], depends: readonly (readonly number[])[]): Planned[] | null {
  const gaps = new Set(missing(plan).map((gap) => gap.position));
  if (gaps.size === 0) return [...plan];
  for (let index = 0; index < plan.length; index += 1) {
    if (gaps.has(index)) continue;
    const needs = depends[index] ?? [];
    if (needs.some((need) => gaps.has(need))) return null;
  }
  return plan.filter((_, index) => !gaps.has(index));
}

/** Итог словами — одной строкой для экрана. */
export function say(verdict: Verdict): string {
  if (verdict.run) return "план собирается целиком — можно выполнять";
  return verdict.why.join(". ");
}
