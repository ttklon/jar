import { describe, expect, it } from "vitest";
import { differ, missing, parse, same, say } from "./intent";

/**
 * Шаг 81: разбор намерения — глагол + объект, а не совпадение слов.
 *
 * Сегодня «найди большие файлы» и «найди файл по имени» получают одно действие:
 * в обеих фразах есть «найди» и «файл». Но это разные дела.
 */
describe("глагол и объект — разные места", () => {
  it("глагол — что делать, объект — над чем", () => {
    const got = parse("найди отчёты");
    expect(got.verb).toBe("найди");
    expect(got.object).toContain("отчет");
  });

  it("порядок слов не мешает найти главное действие", () => {
    expect(parse("в загрузках открой папку").verb).toBe("открой");
    expect(parse("открой папку в загрузках").verb).toBe("открой");
  });

  it("нет действия — сказано, чего не хватает", () => {
    // Разбор не угадывает: фраза без глагола — это не команда.
    expect(parse("большие файлы в загрузках").verb).toBe("неизвестно");
    expect(missing(parse("большие файлы в загрузках"))).toContain("действие");
  });
});

describe("определение меняет смысл, а не украшает фразу", () => {
  it("«большие файлы» и «файл по имени» — разные намерения", () => {
    // Это и есть ответ на вопрос, зачем разбор.
    expect(parse("найди большие файлы").qualifier).toBe("размер");
    expect(parse("найди файл по имени").qualifier).toBe("имя");
    expect(differ("найди большие файлы", "найди файл по имени")).toBe(true);
  });

  it("те же глагол и объект без определения — тоже другое", () => {
    expect(differ("найди файлы", "найди большие файлы")).toBe(true);
  });

  it("одинаковое намерение разными словами — одно и то же", () => {
    // «Поищи» и «найди» — один глагол; «крупные» и «большие» — один размер.
    expect(same(parse("найди большие файлы"), parse("поищи крупные файлы"))).toBe(true);
  });

  it("дата и место тоже различают", () => {
    expect(parse("удали вчерашние отчёты").qualifier).toBe("дата");
    expect(parse("удали отчёты в загрузках").qualifier).toBe("место");
  });

  it("чего нет во фразе, того нет и в намерении", () => {
    // Соблазн «поставить размер по умолчанию» велик, а результат — действие,
    // которого человек не просил.
    expect(parse("найди отчёты").qualifier).toBe("нет");
    expect(parse("найди отчёты").qualifierWord).toBeNull();
  });
});

describe("два действия — два глагола", () => {
  it("«найди и удали» — не глагол «найди-удали»", () => {
    const got = parse("найди и удали старые отчёты");
    expect(got.verbs).toContain("найди");
    expect(got.verbs).toContain("удали");
    expect(got.verb).toBe("найди");
  });
});

describe("разбор можно показать человеку", () => {
  it("сказано, что понято, а не «ок»", () => {
    // Человек должен увидеть «вы просите найти по размеру» и поправить.
    expect(say(parse("найди большие файлы"))).toContain("по размеру");
    expect(say(parse("найди файл по имени"))).toContain("по названию");
  });

  it("без действия сказано, что и как сказать", () => {
    expect(say(parse("большие файлы"))).toContain("нет действия");
  });

  it("без объекта — вопрос, а не действие", () => {
    // «Найди» без объекта — это вопрос, а не команда.
    expect(say(parse("найди"))).toContain("что именно");
    expect(missing(parse("найди"))).toContain("объект");
  });
});
