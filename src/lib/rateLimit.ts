/**
 * Шаг 335: ограничение частоты — не чаще N раз в час. Защита от петли.
 *
 * Петля делается в две минуты: правило «когда в загрузках появляется файл —
 * разложить по папкам», а раскладка сама создаёт файл (отчёт, лог, ярлык). Через
 * час загрузки разобраны десять тысяч раз.
 *
 * Ограничение частоты — это не «оптимизация», а предохранитель. Три правила:
 *
 *  1. **жёсткий предел** на правило: 6 запусков в час. Не настраивается вниз до
 *     «неограниченно» — это тот случай, где «я знаю, что делаю» стоит дорого;
 *  2. **петля узнаётся по причине**: если три раза подряд дело запустилось
 *     срабатыванием, которое оно же и создало, это петля, и правило встаёт на
 *     паузу, а не продолжает;
 *  3. **пропуск по лимиту честный**: в журнале «пропущено — лимит частоты», а не
 *     тишина.
 */

/** Сколько запусков в час разрешено. */
export const PER_HOUR = 6;

/** История запусков правила. */
export interface Run {
  /** Минута запуска — абсолютная, в минутах. */
  readonly at: number;
  /** Запуск вызван тем же событием, которое правило создало. */
  readonly selfCaused: boolean;
}

/**
 * Можно ли запускать.
 *
 * `now` — минута. Считаем только последний час: старые запуски лимит не держат.
 */
export function mayRun(runs: readonly Run[], now: number): { ok: boolean; said: string } {
  const lastHour = runs.filter((run) => now - run.at < 60);
  if (lastHour.length >= PER_HOUR) {
    return {
      ok: false,
      said: `пропущено — лимит частоты: ${lastHour.length} запусков за час, больше ${PER_HOUR} не делаем`,
    };
  }

  // Петля: три подряд своих же запусков — это не «много», это «само себя кормит».
  const tail = runs.slice(-3);
  if (tail.length === 3 && tail.every((run) => run.selfCaused)) {
    return {
      ok: false,
      said: "остановился: три запуска подряд вызваны тем, что сделало само правило — это петля, а не работа",
    };
  }

  return { ok: true, said: `можно: ${lastHour.length} из ${PER_HOUR} за час` };
}

/**
 * Что делать, когда лимит сработал.
 *
 * Не «спрятать»: правило на паузе, человеку сказано, что случилось и что
 * проверить.
 */
export function afterLimit(what: string, why: "limit" | "loop"): string {
  if (why === "loop") {
    return `«${what}» на паузе: похоже, правило запускает само себя. Проверьте, не разложить ли файл снова в ту же папку`;
  }
  return `«${what}» пропущено по лимиту: ${PER_HOUR} запусков в час — это предел; если нужно чаще, дело стоит делать непрерывно, а не правилом`;
}

/**
 * Что человеку видно в строке.
 *
 * Сколько израсходовано — чтобы «почему не сработало» было видно заранее.
 */
export function state(runs: readonly Run[], now: number): string {
  const lastHour = runs.filter((run) => now - run.at < 60).length;
  if (lastHour === 0) return "за последний час не запускалось";
  return `за последний час ${lastHour} из ${PER_HOUR}`;
}

/**
 * Чего лимит не делает.
 *
 * Не мешает редкому и не делает частоту «настройкой в ноль»: предохранитель,
 * который можно выключить, не предохранитель.
 */
export function notFor(): string[] {
  return [
    "не мешает правилу, которое срабатывает раз в день: лимит только про частые",
    "не отключается полностью: вверх можно поднять осознанно, «безлимит» — нет",
    "не молчит: каждый пропуск по лимиту виден в журнале",
  ];
}
