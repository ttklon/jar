/**
 * Шаг 323: правило автоматического дела — того же типа, что уже подтверждали вручную.
 *
 * Доверие зарабатывается, но зарабатывается **не словами**, а числом: правило
 * «каждый день убирать загрузки» создаётся тихо, только если человек сам уже
 * делал это руками и подтверждал. Иначе — первое срабатывание спрашивает.
 *
 * Почему это не бюрократия: автоматическое дело, которое человек не делал руками,
 * почти всегда означает, что он не понимает, что произойдёт. Он увидит результат
 * утром и не поймёт, откуда он.
 *
 * Что считается «подтверждали вручную»:
 *
 *  * **тот же тип дела** — не «похожий». «Убрать загрузки» и «убрать рабочий
 *    стол» — разные дела, и подтверждение одного не разрешает другое;
 *  * **не меньше двух раз**: один раз — случайность, два — привычка;
 *  * **недавно** — 30 дней. То, что человек делал год назад, он не помнит;
 *  * **без отказа после** — если после последнего подтверждения он отменил то же
 *    дело, счёт обнуляется.
 */

/** История одного типа дела. */
export interface History {
  /** Тип дела — совпадает точно, а не «похоже». */
  readonly kind: string;
  /** Сколько раз человек подтвердил вручную. */
  readonly confirmed: number;
  /** Когда последний раз — миллисекунды. */
  readonly lastAt: number;
  /** Когда последний раз отменил (0 — не отменял). */
  readonly cancelledAt: number;
}

/** Сколько подтверждений нужно. */
export const ENOUGH_CONFIRMS = 2;

/** Насколько свежей считается привычка: 30 дней. */
export const FRESH_MS = 30 * 86_400_000;

/** Что можно автоматизировать без вопроса. */
export function mayRunQuietly(history: History | null, now: number): { ok: boolean; said: string } {
  if (history === null) {
    return { ok: false, said: "вы этого ещё не делали руками: первое срабатывание спросит, а не сделает само" };
  }
  if (history.cancelledAt > history.lastAt) {
    return { ok: false, said: "после последнего подтверждения вы это отменили — счёт начнётся заново" };
  }
  if (history.confirmed < ENOUGH_CONFIRMS) {
    return {
      ok: false,
      said: `подтверждали ${history.confirmed} раз — нужно ${ENOUGH_CONFIRMS}: один раз это случайность`,
    };
  }
  if (now - history.lastAt > FRESH_MS) {
    return { ok: false, said: "последний раз это было больше 30 дней назад: привычку считаем утраченной" };
  }
  return { ok: true, said: `вы делали это ${history.confirmed} раз сами — можно без вопроса` };
}

/**
 * Что спросить, если доверия не хватает.
 *
 * Вопрос — про конкретное дело, а не «разрешить автоматизацию?». И с вариантом
 * «спрашивать каждый раз», чтобы человек мог не решать сейчас.
 */
export function ask(kind: string): string {
  return `Утром я обычно ${kind} — делать это сам каждый день или спрашивать каждый раз?`;
}

/**
 * Что повышает доверие.
 *
 * Только ручное подтверждение. «Он нажал „да“ один раз в вопросе» — не
 * подтверждение дела.
 */
export function learn(history: History | null, now: number): History {
  return {
    kind: history?.kind ?? "",
    confirmed: (history?.confirmed ?? 0) + 1,
    lastAt: now,
    cancelledAt: history?.cancelledAt ?? 0,
  };
}

/**
 * Что доверие сбивает.
 *
 * Отмена — не наказание, а сигнал: человек не хотел, чтобы это делалось.
 */
export function cancel(history: History, now: number): History {
  return { ...history, cancelledAt: now };
}

/**
 * Разные дела не путаются.
 *
 * Проверка ловит самое частое упрощение: «уборка» как один тип на всё.
 */
export function sameKind(a: string, b: string): boolean {
  const norm = (text: string) => text.trim().toLowerCase().replace(/\s+/g, " ");
  return norm(a) === norm(b);
}

/**
 * Что сказать человеку, когда правило создаётся.
 *
 * Одна строка, и в ней — статус доверия, а не «правило создано».
 */
export function status(history: History | null, now: number): string {
  const verdict = mayRunQuietly(history, now);
  return verdict.ok
    ? "правило создано: сработает само, без вопроса"
    : `правило создано, но первое время будет спрашивать: ${verdict.said}`;
}
