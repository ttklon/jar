/**
 * Предзагрузка ядра при старте в фоне, а не по первой фразе (шаг 131).
 *
 * Дефект. Ядро поднималось **по первой фразе**, и первая фраза платила за всё:
 *
 *  * **3 секунды ожидания там, где человек уже говорит**: он нажал микрофон —
 *    приложение только начинает поднимать ядро, хотя окно открыто 20 секунд;
 *  * **предзагрузка без очереди — вред**: поднимать тяжёлое ядро, пока человек ждёт
 *    ответ, значит отнимать у него процессор;
 *  * **предзагрузка без причины — трата**: поднимать ядро, если модели нет или
 *    человек не собирается говорить, — это батарея и память впустую;
 *  * **молчаливая предзагрузка путает**: если она идёт, «первое слово» и «холодный
 *    старт» перестают быть честными, пока не сказано, что подъём уже идёт.
 *
 * Правило: **ядро поднимается в фоне при старте окна — но только когда это не мешает**.
 *
 *  1. **В фоне, а не по фразе**: окно открыто → подъём начат. Первая фраза не платит.
 *  2. **Не в ущерб ответу**: если человек уже что-то ждёт, предзагрузка ждёт своей
 *     очереди; на слабой машине (шаг 123) она не начинается вовсе.
 *  3. **Только если есть что поднимать**: нет модели — не поднимаем, и это сказано.
 *  4. **Видно, что идёт**: «ядро поднимается в фоне» — факт; иначе первый быстрый
 *     ответ выглядит как чудо, а первый медленный — как поломка.
 *  5. **Неудача предзагрузки ничего не ломает**: фраза поднимет ядро как раньше, и это
 *     тоже честно.
 *
 * Почему не «поднимать всегда и сразу». На слабой машине предзагрузка отнимает
 * процессор именно тогда, когда человек уже говорит, и делает хуже — поэтому решение
 * принимается, а не готово заранее.
 */

/** Что известно при старте. */
export interface Start {
  /** Есть ли модель и движок (шаг 69): без них поднимать нечего. */
  installed: boolean;
  /** Слабая ли машина (шаг 123): на ней предзагрузка отнимает процессор. */
  weak: boolean;
  /** Идёт ли уже работа, которую человек ждёт. */
  busy: boolean;
  /** Человек сам сказал «не надо» (настройка). */
  refused: boolean;
  /** Предзагрузка уже была (повторный старт не должен поднимать второе ядро). */
  done: boolean;
}

/** Решение. */
export interface Plan {
  /** Начинать ли сейчас. */
  start: boolean;
  /** Что сказать; пусто — молчим, потому что это фон. */
  said: string;
  /** Почему нет — чтобы «не подняли» было обосновано, а не забыто. */
  why: string;
}

/**
 * Начинать ли предзагрузку.
 *
 * Решение принимается, а не делается всегда: на слабой машине предзагрузка — вред.
 */
export function plan(start: Start): Plan {
  if (start.refused) return { start: false, said: "", why: "человек попросил не поднимать заранее" };
  if (!start.installed) return { start: false, said: "", why: "поднимать нечего: движка или модели нет" };
  if (start.done) return { start: false, said: "", why: "ядро уже поднимали — второе не нужно" };
  if (start.busy) {
    // Человек ждёт ответ: отнимать процессор сейчас — значит сделать хуже.
    return { start: false, said: "", why: "человек ждёт ответ — предзагрузка подождёт своей очереди" };
  }
  if (start.weak) {
    // На слабой машине подъём в фоне отнимает у первой фразы больше, чем экономит.
    return { start: false, said: "", why: "машина слабая: предзагрузка отняла бы процессор у ответа" };
  }
  return { start: true, said: "ядро поднимается в фоне — первая фраза не платит за старт", why: "" };
}

/**
 * Что сказать человеку про предзагрузку.
 *
 * Фон не должен быть тайной: быстрый первый ответ выглядит чудом, а медленный —
 * поломкой, если не сказано, что подъём идёт.
 */
export function say(got: Plan, done = false, failed = false): string {
  if (failed) return "ядро не поднялось в фоне — первая фраза поднимет его сама";
  if (done) return "ядро поднято заранее: первая фраза не платит за старт";
  if (got.start) return got.said;
  return got.why;
}

/**
 * Стала ли первая фраза дешевле.
 *
 * Два числа рядом: «с предзагрузкой 400 мс», «без неё 3400 мс». Это и есть ответ на
 * «стоило ли».
 */
export function cheapened(coldMs: number, warmMs: number): { saved: number; said: string } {
  const saved = Math.max(0, coldMs - warmMs);
  return {
    saved,
    said:
      saved > 0
        ? `первая фраза: ${warmMs} мс вместо ${coldMs} — сэкономлено ${saved} мс`
        : `первая фраза не стала быстрее: ${warmMs} мс против ${coldMs}`,
  };
}

/**
 * Неудача предзагрузки не ломает ничего.
 *
 * Возвращает прежнее поведение: фраза поднимет ядро сама. Отдельная функция, потому
 * что «фон упал» не должно превращаться в «ничего не работает».
 */
export function fallback(failed: boolean): { stillWorks: boolean; said: string } {
  if (!failed) return { stillWorks: true, said: "" };
  return { stillWorks: true, said: "предзагрузка не удалась — первая фраза поднимет ядро как раньше" };
}

/**
 * Очередь: предзагрузка не мешает ответу.
 *
 * Если человек заговорил во время предзагрузки, ответ **не ждёт** её конца — он её
 * прерывает, и ядро поднимается заново по фразе (125).
 */
export function yieldToHuman(preloading: boolean, humanWaiting: boolean): { keepGoing: boolean; said: string } {
  if (preloading && humanWaiting) {
    return { keepGoing: false, said: "человек заговорил — предзагрузка уступает, ответ важнее" };
  }
  return { keepGoing: preloading, said: "" };
}
