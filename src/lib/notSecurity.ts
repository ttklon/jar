/**
 * Шаг 277: память не влияет на безопасность — запреты не «запоминаются» как
 * разрешения.
 *
 * Почему это отдельный шаг, а не «и так понятно». Память по своей природе учится
 * на повторениях (шаги 261–272): дважды открыл папку — предлагаем её. И ровно
 * этот механизм опасен рядом с безопасностью, потому что **вопросы похожи**:
 *
 *  * «человек часто даёт доступ к папкам» — наблюдение;
 *  * «человек согласен на доступ к папкам» — решение, и его нельзя вывести из
 *    наблюдения. Он согласился **тогда и на то**, а не «вообще».
 *
 * Отсюда четыре способа, которыми память ломает безопасность, и все четыре
 * выглядят как забота:
 *
 *  1. **«вы всегда разрешаете — больше не спрашиваю».** Повтор согласия
 *     принимается за постоянное согласие. Это ровно то, что человек согласием не
 *     называл;
 *  2. **отказ забывается, а разрешение помнится.** «Больше не спрашивай» могло
 *     быть сказано про **конкретное** действие и **конкретную** папку; из этого
 *     не следует «спрашивай реже вообще»;
 *  3. **запрет превращается в факт памяти.** «Не давай доступ к D:\\Личное»
 *     попадает в память как предпочтение и потом «подставляется» — то есть
 *     приложение само себе выдаёт разрешение на основании запрета;
 *  4. **память приезжает из файла.** Импорт (266/276) переносит факты, но не
 *     согласия, — иначе чужой файл выдавал бы доступ на этом компьютере.
 *
 * Правило: **безопасность решается здесь и сейчас, память может только
 * огорчить.** Всё, что она умеет, — подсказать, стать причиной **вопроса**, не
 * ответом. И у вопроса всегда есть отказ, который запоминается отдельно от
 * «предпочтений».
 */

import { CHANNELS, allows, type Book, type Channel } from "./grants";

/**
 * Что память может сказать про безопасность.
 *
 * Не «можно» и не «нельзя» — только «стоит спросить».
 */
export type Hint =
  /** Память не имеет отношения к вопросу. */
  | { kind: "none" }
  /** Спросить, потому что раньше человек это делал. */
  | { kind: "ask"; because: string }
  /** Промолчать и **не** подставлять: вопрос решается заново. */
  | { kind: "silent"; because: string };

/**
 * Может ли память что-то решить вместо согласия.
 *
 * Никогда. Функция существует, чтобы это было видно в коде, а не только в
 * комментарии: её вызывают на каждом шаге, который что-то открывает, и она
 * всегда отвечает «нет» с причиной.
 */
export function decides(_fact: { kind: string; value: string }): { allowed: false; why: string } {
  return {
    allowed: false,
    why: "память не выдаёт разрешений: согласие даётся на показанный план, здесь и сейчас",
  };
}

/**
 * Подсказка памяти к вопросу о доступе.
 *
 * Важное: подсказка **никогда** не снимает вопрос. Она может изменить его текст
 * («раньше вы открывали это в D:\\Отчёты») и не может изменить ответ.
 */
export function hint(
  fact: { kind: string; value: string; times: number },
  book: Book,
): Hint {
  const channel = channelOf(fact.kind);
  if (channel === null) return { kind: "none" };
  if (!allows(book, channel)) {
    // Канал закрыт — подсказка неуместна: предлагать то, чего нельзя, значит
    // обещать действие, которое не начнётся.
    return { kind: "silent", because: `канал «${channel}» не разрешён — сначала спросим об этом, не о папке` };
  }
  if (fact.times < 2) return { kind: "none" };
  return { kind: "ask", because: `раньше вы выбирали ${fact.value}, но разрешение даётся заново` };
}

/**
 * Что запомнить из отказа.
 *
 * Отказ — не предпочтение. У него есть область: действие и предмет. «Не
 * спрашивай про эту папку снова» — законно; «не спрашивай про доступ вообще» —
 * это уже отзыв канала, и он живёт в `grants`, а не в памяти.
 */
export interface Refusal {
  /** Канал, к которому относится. */
  readonly channel: Channel;
  /** Предмет: папка, программа — то, о чём спросили. */
  readonly subject: string;
  /** Когда отказались. */
  readonly at: number;
  /** Сколько раз уже отказывались: повтор отказа — тоже отказ, не согласие. */
  readonly times: number;
}

/**
 * Разобрать «нет» в записи.
 *
 * Отказ **не** стирает и не ослабляет согласие канала: он говорит только «этот
 * предмет не предлагать». Смешать их значит либо закрыть человеку канал за один
 * отказ, либо, наоборот, оставить открытым то, от чего он отказался.
 */
export function refuse(
  refusals: readonly Refusal[],
  channel: Channel,
  subject: string,
  now: number,
): Refusal[] {
  const existing = refusals.find((refusal) => refusal.channel === channel && refusal.subject === subject);
  if (existing === undefined) {
    return [...refusals, { channel, subject, at: now, times: 1 }];
  }
  return refusals.map((refusal) =>
    refusal === existing ? { ...refusal, at: now, times: refusal.times + 1 } : refusal,
  );
}

/**
 * Можно ли предлагать предмет.
 *
 * Три отказа — предел: после третьего предлагать перестаём совсем и говорим
 * почему. Один отказ может быть случайным («нажал не туда»), три — решение.
 */
export const ENOUGH = 3;

export function mayOffer(refusals: readonly Refusal[], channel: Channel, subject: string): { ok: boolean; said: string } {
  const got = refusals.find((refusal) => refusal.channel === channel && refusal.subject === subject);
  if (got === undefined) return { ok: true, said: "" };
  if (got.times < ENOUGH) {
    return { ok: true, said: `вы уже отказывались ${got.times} ${timesWord(got.times)} — спрошу ещё раз, но не буду настаивать` };
  }
  return {
    ok: false,
    said: `вы отказались ${got.times} раза — больше не предлагаю; если передумали, скажите «можно» и я спрошу`,
  };
}

/**
 * Можно ли записать факт в память, не превращая его в разрешение.
 *
 * Проверка стоит на записи: факт вида «доступ», «разрешение», «grant» в памяти
 * не появляется вовсе — даже если человек сказал «запомни, что я разрешаю».
 * Разрешение живёт в `grants` со своей датой и отзывом, и второго места для него
 * быть не должно.
 */
export const NEVER_FACTS: readonly string[] = ["grant", "permission", "access", "доступ", "разрешение"];

export function mayStore(kind: string): { ok: boolean; said: string } {
  const clean = kind.toLowerCase();
  if (NEVER_FACTS.some((word) => clean.includes(word))) {
    return {
      ok: false,
      said: "разрешения не хранятся в памяти: они даются на показанный план, и отозвать их можно только там",
    };
  }
  return { ok: true, said: "" };
}

/**
 * Проверить согласия после переноса памяти.
 *
 * Согласия **не переезжают**: они про этот компьютер и этого человека. Если файл
 * всё же содержит согласия (старая версия, ручная правка), они не применяются —
 * и это называется, а не молчит.
 */
export function afterImport(
  book: Book,
  file: { preferences?: readonly { kind: string }[]; commands?: readonly unknown[] },
): { book: Book; said: string } {
  const suspicious = (file.preferences ?? []).filter((preference) => !mayStore(preference.kind).ok);
  const allowed = CHANNELS.filter((channel) => allows(book, channel)).length;
  if (suspicious.length === 0) {
    return {
      book,
      said:
        allowed === 0
          ? "согласия не переносятся: на этом компьютере пока ничего не разрешено"
          : `согласия не переносятся: действуют только те ${allowed}, что даны здесь`,
    };
  }
  return {
    book,
    said: `в файле было ${suspicious.length} записей о доступе — они не применены: согласия даются только здесь`,
  };
}

function channelOf(kind: string): Channel | null {
  if (kind === "folder") return "files";
  if (kind === "voice") return "mic";
  if (kind === "program") return "net";
  return null;
}

function timesWord(times: number): string {
  const ten = times % 100;
  if (ten >= 11 && ten <= 14) return "раз";
  const unit = times % 10;
  if (unit === 1) return "раз";
  if (unit >= 2 && unit <= 4) return "раза";
  return "раз";
}
