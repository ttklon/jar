/**
 * Шаг 471: страница «20 фраз, которые точно работают» — на экранах приложения.
 *
 * Такую страницу обычно держат в документации на сайте — и она отстаёт от кода на
 * месяцы. Здесь она **на экране**, и это не украшение: человек, который запустил
 * приложение и не знает, что сказать, видит двадцать готовых фраз и говорит одну.
 *
 * Правила страницы:
 *
 *  * она **на виду**: первый запуск, пустое окно, «что сказать» из трея — не
 *    спрятана за «Помощь»;
 *  * фразы **сгруппированы по тому, что человек хочет**, а не по внутренним
 *    рукам: «навести порядок», «найти», «записать»;
 *  * у каждой фразы видно, что она **сделает** — иначе пробовать страшно.
 */

/** Группа фраз. */
export interface Group {
  /** Что человек хочет. */
  readonly want: string;
  /** Фразы, как говорят. */
  readonly said: readonly string[];
  /** Что произойдёт — одна строка на группу. */
  readonly gets: string;
}

/** Сколько фраз на странице. */
export const NEEDED = 20;

/**
 * Группы.
 *
 * Пять групп по четыре — и каждая названа желанием, а не рукой.
 */
export function groups(): Group[] {
  return [
    { want: "навести порядок", said: ["почисти загрузки", "убери рабочий стол", "разбери папку загрузки по типам", "удали старые архивы"], gets: "файлы разложены или удалены в корзину, с подтверждением" },
    { want: "найти", said: ["найди счета за март", "где я сохранил договор", "найди все pdf за прошлый год", "что я скачал вчера"], gets: "список найденного, а не открытая папка" },
    { want: "записать", said: ["запиши, что я обещал позвонить маме", "напомни завтра в десять позвонить", "запиши в заметки: купить хлеб", "запиши мысль"], gets: "заметка или напоминание, и сказано, куда записано" },
    { want: "посмотреть", said: ["сколько осталось места", "какие программы занимают много места", "когда последний раз чистил", "что запущено сейчас"], gets: "ответ словами, без открытия диспетчера" },
    { want: "сделать с окнами", said: ["поставь окно на левую половину", "сверни всё", "переключись на браузер", "закрой это окно"], gets: "окно на месте, и сказано, какое" },
  ];
}

/**
 * Все фразы — для проверки.
 *
 * Двадцать: пять групп по четыре.
 */
export function phrases(): string[] {
  return groups().flatMap((group) => [...group.said]);
}

/**
 * Где страница показывается.
 *
 * Три места, и первое — при первом запуске, до того как человек растерялся.
 */
export function shownAt(): string[] {
  return [
    "первый запуск: подсказка вместо пустого окна",
    "пустой бриф: «скажите или выберите фразу»",
    "значок в трее → «что сказать» (шаг 453)",
  ];
}

/**
 * Проверить страницу.
 *
 * Нарушения: не двадцать фраз, пустая фраза, группа без «что произойдёт»,
 * больше пяти фраз в группе (тогда это список, а не выбор).
 */
export function check(gs: readonly Group[] = groups()): string[] {
  const problems: string[] = [];
  const total = gs.reduce((sum, group) => sum + group.said.length, 0);

  if (total !== NEEDED) problems.push(`фраз ${total}, а нужно ${NEEDED}`);
  if (gs.length < 4) problems.push(`групп ${gs.length}: меньше четырёх — это не выбор, а список`);

  for (const group of gs) {
    if (group.said.length > 5) problems.push(`«${group.want}»: ${group.said.length} фраз — больше пяти не выбирают`);
    if (group.gets.trim() === "") problems.push(`«${group.want}»: не сказано, что произойдёт`);
    if (group.said.some((phrase) => phrase.trim() === "")) problems.push(`«${group.want}»: пустая фраза`);
  }

  return problems;
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "двадцать фраз, пять групп по четыре",
    "группа названа желанием, и у неё сказано, что произойдёт",
    "фразы на экране, а не в документе на сайте",
  ];
}
