/**
 * Шаг 443: автозапуск при входе — по желанию, и отключается там же.
 *
 * Автозапуск — самая частая причина «я это не устанавливал». Человек ставит
 * программу, она при перезагрузке оказывается в трее, и доверие кончается.
 *
 * Три правила, и все — про согласие:
 *
 *  * **по умолчанию выключен**: включается галочкой, а не «поставил — значит
 *    хочу»;
 *  * **включается и выключается в одном месте** — в настройках, а не «включить
 *    здесь, выключить через Диспетчер задач»;
 *  * **выключение убирает запись полностью**, а не «ставит в отключённые»: в
 *    Диспетчере задач человек должен увидеть пусто, а не строку с галочкой.
 *
 * Технически (Rust `autostart.rs`): одна запись `HKCU\...\Run`, путь в кавычках,
 * `--minimized` для тихого старта. Здесь — правила и проверки.
 */

/** Что показывает галочка. */
export interface Setting {
  /** Включён ли. */
  readonly on: boolean;
  /** Где включается — всегда в настройках программы. */
  readonly where: string;
  /** Что будет при входе в Windows. */
  readonly said: string;
}

/**
 * Показать настройку.
 *
 * `entries` — сколько записей автозапуска найдено в реестре. Больше одной —
 * дефект, и он **называется**, а не чинится молча: две записи — это два запуска.
 */
export function show(on: boolean, entries: number): Setting {
  if (entries > 1) {
    return {
      on,
      where: "Настройки → Запуск",
      said: `нашлось ${entries} записей автозапуска — это ошибка: при входе запустились бы обе. Уберите лишние здесь же`,
    };
  }
  return {
    on,
    where: "Настройки → Запуск",
    said: on ? "при входе в Windows программа откроется в трее и не будет мешать" : "при входе в Windows программа не запускается; запустить можно ярлыком",
  };
}

/**
 * Включить и выключить.
 *
 * Возвращает **решение**, а не запись в реестр: запись — дело Rust, а проверки —
 * здесь, чтобы их можно было прогнать тестом.
 */
export function toggle(on: boolean): { on: boolean; entries: number; said: string } {
  if (on) return { on: true, entries: 1, said: "включено: одна запись, путь в кавычках — иначе Windows не запустит программы с пробелом в пути" };
  return { on: false, entries: 0, said: "выключено: записи нет вовсе, а не «отключена» — в Диспетчере задач пусто" };
}

/**
 * Что делает автозапуск.
 *
 * Тихий старт: окно не появляется, а программа ждёт в трее. Это и есть смысл.
 */
export function behaviour(): string {
  return "при входе — тихо, в трее: окно не открывается, фраза запускается горячей клавишей";
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по одной на правило.
 */
export function checks(): string[] {
  return [
    "по умолчанию записи нет",
    "включение создаёт ровно одну запись",
    "выключение убирает запись, а не отключает её",
  ];
}

/**
 * Чего автозапуск не делает.
 *
 * Три запрета, и первый — главный.
 */
export function notDo(): string[] {
  return [
    "не включается сам при установке: только галочкой",
    "не требует администратора: запись в HKCU, а не в HKLM",
    "не оставляет «отключённую» запись в Диспетчере задач",
  ];
}
