/**
 * Повтор руки: только если шаг безопасно повторить, иначе — вопрос (шаг 144).
 *
 * Дефект. Повтор шёл **по факту «не получилось»**, а не по риску:
 *
 *  * **двойное удаление хуже отказа**: шаг «удалить файл» упал на середине — файла уже
 *    нет, — и повтор удаляет **соседний** файл, потому что «второй файл тоже подходит»;
 *  * **повтор безопасного шага — трата времени человека**: «прочитать размер» не
 *    получилось из-за таймаута, и спрашивать «повторить?» незачем — надо повторять;
 *  * **риск не тот, что у действия**: «переместить» обратимо, а «переместить поверх»
 *    — нет; смотреть надо на **шаг**, а не на имя руки;
 *  * **вопрос без причины — пила**: «повторить?» без «потому что шаг необратим» —
 *    это формальность, которую нажимают не читая.
 *
 * Правило: **повторяется только безопасное; необратимое — вопрос с причиной**.
 *
 *  1. **Безопасное повторяется само**: чтение, проверка, запрос размера — их повтор
 *     ничего не портит.
 *  2. **Необратимое не повторяется само никогда**: удаление, запись поверх, отправка
 *     денег — повтор может сделать хуже, чем отказ.
 *  3. **Вопрос называет причину**: «шаг необратим: повтор может удалить второй файл»
 *     — это ответ, «повторить?» — нет.
 *  4. **Неизвестный риск — вопрос**: незнание не разрешение.
 *  5. **Отказ повтора — не отказ дела**: шаг помечается «повтор требует слова», дело
 *     продолжается с другими шагами.
 *
 * Почему не «повторять всё, пока не получится». «Пока не получится» — это рецепт
 * повторить удаление трижды; лучше остановиться и спросить.
 */

/** Риск шага — как в реестре. */
export type Risk = "read" | "write-local" | "external" | "destructive" | "identity" | "money";

/** Повторяем ли шаг сам. */
export interface Repeat {
  /** Повторять без вопроса. */
  auto: boolean;
  /** Спросить человека (когда `auto === false`). */
  ask: boolean;
  /** Что сказать: причина, а не «повторить?». */
  said: string;
}

/**
 * Можно ли повторить шаг.
 *
 * «Прочитать» и «проверить» — да; всё, что меняет мир, — только спросив, и с причиной.
 */
export function repeatOf(risk: Risk | string, why: string): Repeat {
  if (risk === "read") {
    // Повтор чтения ничего не портит — спрашивать незачем.
    return { auto: true, ask: false, said: `повторяю: чтение безопасно (${why})` };
  }
  if (risk === "write-local") {
    // Запись повторяема, но не «бесплатна»: спросим, назвав, что перезапишется.
    return { auto: false, ask: true, said: `повтор перезапишет: ${why} — повторить?` };
  }
  if (risk === "external") {
    return { auto: false, ask: true, said: `повтор уйдёт наружу второй раз: ${why} — повторить?` };
  }
  if (risk === "destructive") {
    // Двойное удаление хуже отказа: повтор может задеть соседний объект.
    return {
      auto: false,
      ask: true,
      said: `шаг необратим: повтор может удалить второй объект, а не этот (${why}) — повторить?`,
    };
  }
  if (risk === "identity" || risk === "money") {
    return {
      auto: false,
      ask: true,
      said: `повтор может списать или войти второй раз (${why}) — повторить?`,
    };
  }
  // Неизвестный риск — незнание не разрешение.
  return { auto: false, ask: true, said: `риск шага неизвестен (${why}) — повторить?` };
}

/** Что пометить в отчёте, если повтор без слова не делается. */
export function mark(risk: Risk | string, why: string): string {
  const got = repeatOf(risk, why);
  if (got.auto) return "";
  return `повтор требует слова: ${got.said}`;
}

/** Дело продолжается с другими шагами: отказ повтора — не отказ дела. */
export function continues(stepFailed: boolean, repeatAsked: boolean): { continue: boolean; said: string } {
  if (!stepFailed) return { continue: true, said: "" };
  if (repeatAsked) {
    return {
      continue: true,
      said: "этот шаг ждёт слова, остальные идут дальше: один шаг не отменяет дело",
    };
  }
  return { continue: true, said: "" };
}

/**
 * Сколько раз уже повторяли — и когда пора остановиться.
 *
 * «Пока не получится» — это рецепт повторить удаление трижды; после трёх — стоп.
 */
export const MAX_REPEATS = 3;

export function enough(times: number): { stop: boolean; said: string } {
  if (times < MAX_REPEATS) return { stop: false, said: "" };
  return { stop: true, said: `повторяли ${times} раза — дальше не повторяю: это уже не сбой, а неверный шаг` };
}

/** Что сказать про повтор в отчёте — числом. */
export function report(risk: Risk | string, times: number, told: boolean): string {
  if (times === 0) return "";
  if (told) return `повторено ${times} раза, и каждый — с вашего слова`;
  return `повторено ${times} раза без вопроса: шаг безопасен (${risk})`;
}
