/**
 * Каждый разбор проходит журнал: фраза → функция (или отказ) (шаг 88).
 *
 * Дефект. Разбор падает **молча**: человек сказал, приложение что-то поняло (или
 * нет), и от этого не остаётся ничего. Отсюда:
 *
 *  * **нельзя улучшать**: нельзя починить то, о чём нет данных — какие фразы не
 *    понимаются, в каком месте разбора теряются;
 *  * **нельзя спорить**: человек говорит «оно меня не понимает», и обе стороны
 *    правы, потому что примера нет;
 *  * **нельзя проверить догадку**: «наверное, дело в длинных фразах» остаётся
 *    догадкой навсегда.
 *
 * Правило: **каждая фраза оставляет строку — что услышано, что понято, что
 * сделано или почему отказано**.
 *
 *  1. Строка пишется **сразу**, а не после успеха: именно неудачи и нужны.
 *  2. В строке **три поля**, и каждое обязательно: услышано (может быть
 *     искажено распознаванием), понято (может быть `null`), сделано или
 *     причина отказа. Одного «понято» недостаточно: не видно, что было на входе.
 *  3. **Отказ — такая же строка**, как успех: «не умею: нет руки» — это данные, а
 *     не пустота.
 *  4. Журнал **не растёт без предела** (шаг 60: сто строк): иначе через месяц его
 *     нельзя пролистать, а он же становится хранилищем чужих фраз.
 *  5. Журнал **не уходит наружу** сам: это фразы человека.
 *
 * Почему не «писать только ошибки». Тогда видно, что сломалось, но не видно,
 * сколько всего работало, — а без знаменателя «сломалось 3 раза» не говорит
 * ничего.
 */

/** Что случилось с фразой. */
export type Outcome =
  /** Понято и сделано. */
  | { kind: "done"; did: string }
  /** Понято, но не сделано: отказ с причиной. */
  | { kind: "refused"; cause: string }
  /** Не понято вовсе. */
  | { kind: "not-understood" }
  /** Ещё разбирается — строка уже есть, конец допишется. */
  | { kind: "in-progress" };

/** Строка журнала разбора. */
export interface Row {
  /** Когда — по часам, а не «давно». */
  at: number;
  /** Что услышано: может быть искажено распознаванием, и это важно видеть. */
  heard: string;
  /** Как понято. `null` — не поняли вовсе. */
  understood: string | null;
  /** Что сделано или почему отказано. */
  outcome: Outcome;
}

/**
 * Сколько строк храним.
 *
 * Не «всё»: журнал, который растёт без предела, через месяц нельзя пролистать, и
 * он же становится хранилищем чужих приватных фраз.
 */
export const KEEP = 100;

/**
 * Записать строку.
 *
 * Новые — сверху: смотреть начинают с недавнего. Старые уходят, но **не
 * молча**: счётчик вытесненных нужен, чтобы не думать, что журнал полный.
 */
export interface Log {
  rows: Row[];
  /** Сколько строк вытеснено — чтобы «сто строк» не значило «всё было». */
  dropped: number;
}

export function push(log: Log, row: Row): Log {
  const rows = [row, ...log.rows].slice(0, KEEP);
  return { rows, dropped: log.dropped + Math.max(0, log.rows.length + 1 - KEEP) };
}

/** Пустой журнал. */
export function empty(): Log {
  return { rows: [], dropped: 0 };
}

/**
 * Дописать итог к последней строке с этой фразой.
 *
 * Разбор асинхронный: строка появляется сразу («разбираю…»), итог — когда он
 * есть. Если итог потеряется, строка останется с «разбираю…» — и это **видно**,
 * а не выглядит успехом.
 */
export function finish(log: Log, at: number, understood: string | null, outcome: Outcome): Log {
  return {
    ...log,
    rows: log.rows.map((row) => (row.at === at ? { ...row, understood, outcome } : row)),
  };
}

/**
 * Что видно в строке — одной строкой текста.
 *
 * Три поля подряд, потому что смысл — в их **связи**: фраза, разбор, итог.
 */
export function text(row: Row): string {
  const outcome =
    row.outcome.kind === "done"
      ? `сделано: ${row.outcome.did}`
      : row.outcome.kind === "refused"
        ? `отказ: ${row.outcome.cause}`
        : row.outcome.kind === "not-understood"
          ? "не понято"
          : "разбираю…";
  return `«${row.heard}» → ${row.understood ?? "?"} → ${outcome}`;
}

/**
 * Доля неудач по журналу.
 *
 * Без знаменателя «сломалось 3 раза» не говорит ничего: три из трёх и три из
 * трёхсот — разные вещи. Считаются только **завершённые** строки: «разбираю…»
 * ещё не результат.
 */
export function failures(log: Log): { failed: number; total: number; share: number } {
  const done = log.rows.filter((row) => row.outcome.kind !== "in-progress");
  const failed = done.filter((row) => row.outcome.kind !== "done").length;
  return { failed, total: done.length, share: done.length === 0 ? 0 : failed / done.length };
}

/**
 * Что чинить в первую очередь.
 *
 * Группировка по **началу** понятого: «не понимает фразы про файлы» полезнее, чем
 * «не понимает фразы вообще». Неудачи без разбора идут отдельной группой —
 * «совсем не понято» — это другой дефект, чем «понято неверно».
 */
export function worst(log: Log, limit = 3): { reason: string; times: number }[] {
  const counts = new Map<string, number>();
  for (const row of log.rows) {
    if (row.outcome.kind === "done" || row.outcome.kind === "in-progress") continue;
    // Порядок важен: если понято **не то**, это дефект разбора, и он важнее
    // причины отказа — иначе «поняли неверно» прячется за «не хватает прав».
    const key =
      row.understood === null
        ? "не понято вовсе"
        : row.outcome.kind === "refused"
          ? `отказ: ${row.outcome.cause} · понято как «${row.understood}»`
          : `не выполнено: ${row.understood}`;
    counts.set(key, (counts.get(key) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([reason, times]) => ({ reason, times }))
    .sort((left, right) => right.times - left.times)
    .slice(0, limit);
}

/**
 * Журнал не уходит наружу сам.
 *
 * Фразы человека — его фразы: ни отправки, ни «улучшения продукта». Функция
 * названа, чтобы это не потерялось при правках.
 */
export function leaves(_log: Log): false {
  return false;
}
