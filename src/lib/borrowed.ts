/**
 * Проверить таблицу.
 *
 * Три вещи, которые делают её бесполезной: заимствование без боли (украшение),
 * заимствование без цены (значит, копировали продукт целиком) и строка без шага
 * (текст, оторванный от работы).
 */
export function audit(rows: readonly Row[] = ROWS): { ok: boolean; said: string; problems: string[] } {
  const problems: string[] = [];

  for (const row of rows) {
    if (row.pain.trim() === "") {
      problems.push(`«${row.what}»: не названа боль — это украшение, а не заимствование`);
    }
    if (row.notTaken.trim() === "") {
      problems.push(`«${row.what}»: не сказано, что не взяли — значит, скопировали продукт, а не приём`);
    }
    if (!/^\d+$/.test(row.step)) {
      problems.push(`«${row.what}»: не связано с шагом плана`);
    }
    if (!/приём|поле|сесси|клавиш|правил|текст|команд|требован|действие|распознаван|синтез/i.test(row.what)) {
      problems.push(`«${row.what}»: похоже на название продукта, а не на приём`);
    }
  }

  const names = new Set(rows.map((row) => row.what));
  if (names.size !== rows.length) {
    problems.push("одно и то же заимствование записано дважды");
  }

  return {
    ok: problems.length === 0,
    said:
      problems.length === 0
        ? `заимствований ${rows.length}: у каждого названа боль, цена и шаг`
        : `проблем ${problems.length}: ${problems.slice(0, 2).join("; ")}`,
    problems,
  };
}

/** Таблица как текст для документа: одна строка на заимствование. */
export function table(rows: readonly Row[] = ROWS): string {
  const head = "| что взяли | откуда | зачем | чего не взяли | шаг |\n| --- | --- | --- | --- | --- |";
  const body = rows.map((row) => `| ${row.what} | ${row.from} | ${row.pain} | ${row.notTaken} | ${row.step} |`);
  return [head, ...body].join("\n");
}

/** Что сказать, если заимствование не закрывает ни одной боли. */
export function decoration(rows: readonly Row[] = ROWS): readonly string[] {
  return rows.filter((row) => row.pain.trim() === "").map((row) => row.what);
}
