/**
 * Шаг 290: свести заимствования в таблицу «что взяли и почему».
 *
 * Зачем таблица, а не абзац в документации. Заимствование живёт в коде годами, а
 * причина, по которой его взяли, — в чужой голове и в переписке. Через год никто
 * не помнит, зачем здесь `OVERHEAD_MB = 1500` и почему палитра одна, а горячих
 * клавиш три. Таблица отвечает на три вопроса, и все три нужны, чтобы не тащить
 * чужую сложность **молча**:
 *
 *  1. **что взяли** — приём, а не продукт: «одно поле как вход», а не «Raycast»;
 *  2. **зачем** — какую нашу боль это закрывает (шаг 296). Заимствование без
 *     боли — украшение, и его надо называть украшением;
 *  3. **какую цену не берём.** У каждого приёма есть то, что вместе с ним
 *     приходит: расширения, облако, сервис. Это самая важная колонка — она
 *     отличает «взяли урок» от «скопировали продукт».
 *
 * И четвёртый вопрос, который задают позже всех: **лицензия** (шаг 291).
 * Приём не защищён авторским правом, код — защищён; таблица фиксирует, что мы
 * взяли именно приём, и тогда лицензия чужого продукта к нам не относится.
 */

/** Одна строка таблицы. */
export interface Row {
  /** Что взяли — приём, словами. */
  readonly what: string;
  /** Откуда — продукт, для истории. */
  readonly from: string;
  /** Какую нашу боль закрывает. Пусто — украшение, и это видно. */
  readonly pain: string;
  /** Что не взяли вместе с приёмом. */
  readonly notTaken: string;
  /** Шаг плана, где это сделано: связь с работой, а не с текстом. */
  readonly step: string;
}

