/**
 * Шаг 322: триггеры — время, событие (файл появился, диск полон), вход в систему.
 *
 * «Когда — тогда» (шаг 284) описывал правила, которые человек говорит словами.
 * Здесь — **события**, на которые программа умеет смотреть, и правило: не всякое
 * «когда» проверяемо.
 *
 * Три вида, и у каждого своя цена:
 *
 *  * **время** — самое простое, но именно оно чаще всего срабатывает не вовремя
 *    (компьютер спал);
 *  * **событие** — «файл появился», «диск полон». Требует наблюдения, а
 *    наблюдение за папкой — это служба, которая ест батарею и права. Поэтому
 *    список папок закрытый: только загрузки, рабочий стол, свои папки;
 *  * **вход в систему** — удобно и опасно: всё, что запускается при входе,
 *    замедляет машину и попадает в «автозагрузку», которую чистят.
 *
 * Главное правило: **событие, которое нельзя проверить, не предлагается.** «Когда
 * курсор наведён на угол» звучит прекрасно и не работает после перезагрузки.
 */

/** Тип триггера. */
export type Trigger =
  | { kind: "time"; at: number }
  | { kind: "fileAppeared"; folder: Folder }
  | { kind: "diskFull"; percent: number }
  | { kind: "signIn" };

/** Папки, за которыми разрешено наблюдать. */
export type Folder = "downloads" | "desktop" | "documents" | "custom";

/** Что наблюдаем — только по делу. */
export const WATCHABLE: readonly Folder[] = ["downloads", "desktop", "documents", "custom"];

/**
 * Проверка триггера.
 *
 * Возвращает не «ок», а что именно не так: непонятное «когда» — самая частая
 * причина «автоматизация не работает».
 */
export function check(trigger: Trigger): string[] {
  const problems: string[] = [];

  if (trigger.kind === "time") {
    if (trigger.at < 0 || trigger.at >= 24 * 60) problems.push("время вне суток: 0–1439 минут");
  }
  if (trigger.kind === "fileAppeared") {
    if (!WATCHABLE.includes(trigger.folder)) {
      problems.push(`папка «${trigger.folder}» не в списке наблюдения: за чужими папками не следим (права и батарея)`);
    }
  }
  if (trigger.kind === "diskFull") {
    if (trigger.percent <= 0 || trigger.percent >= 100) problems.push("порог диска должен быть между 1 и 99 %");
    if (trigger.percent < 5) problems.push("меньше 5 % — уже поздно: не получится даже сохранить отчёт");
  }

  return problems;
}

/**
 * Как триггер называется для человека.
 *
 * «signIn» человеку ничего не говорит; «когда я вхожу в систему» — говорит.
 */
export function describe(trigger: Trigger): string {
  if (trigger.kind === "time") {
    const hour = Math.floor(trigger.at / 60);
    const minute = trigger.at % 60;
    return `каждый день в ${String(hour).padStart(2, "0")}:${String(minute).padStart(2, "0")}`;
  }
  if (trigger.kind === "fileAppeared") {
    const names: Record<Folder, string> = {
      downloads: "в «Загрузках»",
      desktop: "на рабочем столе",
      documents: "в «Документах»",
      custom: "в вашей папке",
    };
    return `когда ${names[trigger.folder]} появляется файл`;
  }
  if (trigger.kind === "diskFull") return `когда на диске остаётся меньше ${trigger.percent} % места`;
  return "когда вы входите в систему";
}

/**
 * Что триггер не может.
 *
 * Называется до создания правила: человек, который ждёт «наведения курсора»,
 * создаст правило, которое молча не сработает.
 */
export function limits(trigger: Trigger): string[] {
  if (trigger.kind === "signIn") {
    return [
      "после входа уходит несколько секунд, пока система успокоится — дело может подождать 10–20 секунд",
      "всё, что срабатывает при входе, попадает в автозагрузку: если таких правил много, вход станет медленнее",
    ];
  }
  if (trigger.kind === "fileAppeared") {
    return [
      "файл может появиться недокачанным: ждём, пока размер перестанет меняться",
      "за папками вне списка не следим: это права и расход батареи",
    ];
  }
  if (trigger.kind === "diskFull") {
    return ["порог срабатывает один раз, а не каждую минуту: иначе получится спам"];
  }
  return ["если компьютер спал в это время, дело не пропадёт — спросим, сделать ли его позже"];
}

/**
 * Что человек вправе ожидать от входа в систему.
 *
 * Отдельно, потому что тут легче всего обещать лишнее: «всё будет готово» —
 * неправда, программы при входе запускаются не одновременно.
 */
export function atSignIn(): string {
  return "после входа пройдёт 10–20 секунд, прежде чем всё успокоится: дела запускаются после этого, а не сразу";
}
