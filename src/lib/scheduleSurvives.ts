/**
 * Шаг 328: расписание переживает перезапуск и сон — иначе оно бесполезно.
 *
 * Две разные поломки, и обе тихие:
 *
 *  * **перезапуск** — расписание жило в памяти процесса и исчезало вместе с ним.
 *    Человек настроил, выключил компьютер, включил — правил нет;
 *  * **сон** — компьютер проспал 09:00. Проснулся в 11:40. Что теперь: сделать
 *    пропущенное сразу, не делать вовсе, или дождаться завтрашнего 09:00?
 *
 * Правильный ответ на сон — **не угадывать**, а спросить один раз и запомнить
 * (шаг 334). А вот правильный ответ на перезапуск — не спрашивать: расписание
 * должно быть в базе, а не в памяти.
 *
 * Здесь — проверки того, что расписание переживает всё это, и что после
 * пробуждения не выстраивается очередь из пропущенных срабатываний.
 */

/** Где живёт расписание. */
export type Storage = "memory" | "file" | "database";

/**
 * Переживёт ли расписание перезапуск.
 *
 * В памяти — нет, и это надо назвать прямо: «расписание в памяти» выглядит
 * рабочим до первого выключения.
 */
export function survivesRestart(storage: Storage): { ok: boolean; said: string } {
  if (storage === "memory") {
    return { ok: false, said: "расписание в памяти процесса: после выключения компьютера правил не будет" };
  }
  return { ok: true, said: `расписание в ${storage === "database" ? "базе данных" : "файле"}: переживёт перезапуск` };
}

/**
 * Что делать после пробуждения.
 *
 * `missed` — сколько срабатываний прошло, пока компьютер спал. Ответ: **не
 * больше одного вопроса**, сколько бы их ни было.
 */
export function afterSleep(missed: number, choice: "ask" | "doNow" | "skip"): { said: string; runs: number } {
  if (missed === 0) return { said: "ничего не пропущено", runs: 0 };

  if (choice === "doNow") {
    // Не очередь: если проспали три утренних отчёта, нужен один, а не три.
    return { said: `пропущено ${missed}: делаю один раз, а не ${missed} подряд — иначе после недели отпуска будет буря`, runs: 1 };
  }
  if (choice === "skip") {
    return { said: `пропущено ${missed}: пропускаю до следующего раза, в журнале будет «пропущено»`, runs: 0 };
  }
  return { said: `пропущено ${missed}: спрошу один раз «сделать пропущенное?» и запомню ответ`, runs: -1 };
}

/**
 * Часы, которые человек вернул назад (перевод времени, поездка).
 *
 * Опасный случай: время «назад» на час может запустить всё, что было за этот
 * час, второй раз. Поэтому время идёт только вперёд: если новые часы меньше
 * последней известной минуты — ждём, пока догонят.
 */
export function clockWentBack(lastMinute: number, nowMinute: number): { run: boolean; said: string } {
  if (nowMinute >= lastMinute) return { run: true, said: "время идёт вперёд" };
  return {
    run: false,
    said: `часы показывают раньше последнего запуска (${nowMinute} < ${lastMinute}): ждём, пока догонят, чтобы не повторить прошедшее`,
  };
}

/**
 * Сон дольше суток.
 *
 * «Догнать всё» здесь особенно плохо: за три дня накопится шесть ежедневных
 * дел, и человек получит их все разом.
 */
export function longSleep(hours: number): string | null {
  if (hours < 24) return null;
  return `компьютер спал ${Math.floor(hours / 24)} ${plural(Math.floor(hours / 24), "сутки", "суток", "суток")}: пропущенное не догоняем очередью — спросим один раз`;
}

/** Русское склонение по числу. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}

/**
 * Что проверяет тест на самом деле.
 *
 * Не «расписание сработало», а «после сна оно не выстроило очередь».
 */
export function checks(): string[] {
  return [
    "после перезапуска приложения расписание на месте",
    "после сна пропущенное спрашивается один раз, а не очередью",
    "часы назад не запускают прошедшее второй раз",
    "выход из спящего режима не запускает всё, что пропущено за неделю",
  ];
}
