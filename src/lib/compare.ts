/**
 * Сравнение двух моделей на пяти своих фразах одной кнопкой (шаг 76).
 *
 * Дефект. Выбрать модель «правильно» нельзя, прочитав чужие бенчмарки: они
 * меряют чужое — чужие фразы, чужой язык, чужие задачи. Человеку нужно знать
 * не «какая модель лучше вообще», а **какая лучше на его фразах**.
 *
 * И тут же второй дефект: сравнение требует усилий. Чтобы сравнить самому,
 * надо придумать фразы, произнести их дважды, записать ответы, сравнить —
 * никто этого не делает, и выбор остаётся случайным.
 *
 * Правило: **одна кнопка, пять своих фраз, два ответа рядом**.
 *
 *  1. Фразы **свои**: модель, которая хорошо отвечает на чужие примеры, может
 *     плохо отвечать на «открой квартал-3» (шаг 57).
 *  2. Фраз **пять**, и это число названо: на одной можно случайно попасть, на
 *     пяти — уже видно закономерность, а больше человек не будет читать.
 *  3. Ответы **рядом**, а не по очереди: по очереди сравнение требует памяти,
 *     а человек помнит предыдущий ответ примерно никак.
 *  4. **Замер идёт вместе с качеством** (шаг 65): быстрая модель, которая
 *     ошибается, хуже медленной, которая не ошибается, — и наоборот.
 *  5. Выбор делает **человек**: приложение показывает разницу, а не решает за
 *     него. Автоматический выбор по «похожести на хороший ответ» — это
 *     угадывание.
 *
 * Почему не сравнение на «эталонных» фразах приложения. Эталонные фразы
 * проверяют то, что считаем важным мы, а не то, что важно человеку. Пять его
 * фраз полезнее пятидесяти наших.
 */

/** Сколько фраз нужно для сравнения. */
export const PHRASES = 5;

/** Один ответ модели на одну фразу. */
export interface Answer {
  /** Текст ответа. */
  text: string;
  /** Сколько миллисекунд до первого токена. */
  firstTokenMs: number;
  /** Токенов в секунду. */
  perSecond: number;
}

/** Результат одной модели на всех фразах. */
export interface Side {
  /** Имя модели. */
  model: string;
  /** Ответы по порядку фраз; `null` — не ответила (сбой). */
  answers: (Answer | null)[];
}

/** Готово ли сравнение. */
export interface Ready {
  ok: boolean;
  /** Почему нельзя сравнивать — или что не так с фразами. */
  why: string;
}

/**
 * Проверка перед сравнением.
 *
 * Фраз должно быть **ровно столько**, сколько нужно: меньше пяти — случайность,
 * больше — никто не прочтёт. Пустая фраза тоже не считается: сравнение на
 * пустоте ничего не говорит.
 */
export function ready(phrases: readonly string[]): Ready {
  const clean = phrases.map((phrase) => phrase.trim()).filter((phrase) => phrase.length > 0);
  if (clean.length === 0) {
    return { ok: false, why: "добавьте фразы, на которых хотите сравнить — своих, а не примеров" };
  }
  if (clean.length < PHRASES) {
    return {
      ok: false,
      why: `нужно ${PHRASES} фраз: на одной можно случайно попасть, на ${PHRASES} уже видно закономерность`,
    };
  }
  return { ok: true, why: `сравню на ${PHRASES} фразах — ваших` };
}

/**
 * Где одна модель лучше другой — по каждой фразе.
 *
 * Ответ «лучше» тут **не выносится**: показывается разница в скорости, а
 * качество оценивает человек. Но сбой (модель не ответила) назван: это не
 * «медленнее», а «не справилась».
 */
export type Row = "left" | "right" | "same" | "left-failed" | "right-failed" | "both-failed";

export function row(left: Side, right: Side, index: number): Row {
  const one = left.answers[index] ?? null;
  const two = right.answers[index] ?? null;
  if (one === null && two === null) return "both-failed";
  if (one === null) return "left-failed";
  if (two === null) return "right-failed";
  // «Лучше» по скорости — только когда разница заметна: 1.02 против 1.05 не
  // разница, а шум.
  const delta = (one.firstTokenMs - two.firstTokenMs) / Math.max(1, two.firstTokenMs);
  if (Math.abs(delta) < 0.2) return "same";
  return delta < 0 ? "left" : "right";
}

/**
 * Итог: сколько фраз выиграла каждая.
 *
 * Названо числом, а не «в целом лучше»: «в целом» скрывает, что модели
 * различаются **на разных фразах**, и человек выбирает не лучшую, а ту, чьи
 * провалы его не касаются.
 */
export function score(left: Side, right: Side): { left: number; right: number; same: number; failed: number } {
  const count = Math.max(left.answers.length, right.answers.length);
  let forLeft = 0;
  let forRight = 0;
  let same = 0;
  let failed = 0;
  for (let index = 0; index < count; index += 1) {
    const verdict = row(left, right, index);
    if (verdict === "left") forLeft += 1;
    else if (verdict === "right") forRight += 1;
    else if (verdict === "same") same += 1;
    else failed += 1;
  }
  return { left: forLeft, right: forRight, same, failed };
}

/**
 * Что сказать человеку.
 *
 * Названы **счёт и где разошлось**, а не «модель A лучше». Выбор за человеком,
 * и решение по счёту без чтения ответов — это угадывание.
 */
export function say(left: Side, right: Side): string {
  const got = score(left, right);
  const head = `«${left.model}» быстрее в ${got.left} из ${left.answers.length}, «${right.model}» — в ${got.right}`;
  if (got.failed > 0) {
    return `${head}; не справились обе или одна: ${got.failed} — это не скорость, а сбой`;
  }
  if (got.same === left.answers.length) {
    return `${head} — разница в скорости незаметна, смотрите на ответы`;
  }
  return `${head} — прочитайте ответы: быстрее не значит лучше`;
}

/**
 * Можно ли выбирать по счёту.
 *
 * Ответ почти всегда «нет»: счёт говорит о скорости, а выбирают **по ответам**.
 * Функция нужна, чтобы это не потерялось при правках.
 */
export function byScoreOnly(): false {
  return false;
}
