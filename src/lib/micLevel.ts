/**
 * Настройка микрофона: уровень и тестовая фраза (шаг 51).
 *
 * Дефект. Проверка микрофона существовала и отвечала «работает / не работает».
 * Это не ответ на вопрос человека: он пришёл, потому что **его не слышат**, и
 * ему нужно знать, слышат ли **сейчас** и достаточно ли громко. «Работает» при
 * этом может значить «микрофон открылся, но вас едва слышно».
 *
 * Что здесь есть:
 *
 *  * **уровень** — не «0–100 без смысла», а **слово**: «тихо», «нормально»,
 *    «громко», «слишком громко — перегрузка». Человеку не нужно число: ему нужно
 *    знать, надо ли говорить громче или пересесть;
 *  * **тестовая фраза** — что сказать, чтобы проверить. Не «скажите что-нибудь»:
 *    человек должен знать, что именно, и что после этого произойдёт;
 *  * **что поправить** — совет по состоянию, а не общий «проверьте микрофон».
 *
 * Перегрузка — отдельное слово, а не «громко». «Громко» — это хорошо; перегрузка
 * — это искажение, из которого распознавание делает мусор, и человек должен
 * понять, что говорить громче не надо, а надо отодвинуться.
 */

/** Что показывает уровень. */
export type Level = "silent" | "quiet" | "good" | "loud" | "clipping";

/** Порог, выше которого сигнал искажается. У цифрового звука потолок — 1. */
export const CLIP_AT = 0.98;

/** Границы слов: тихо до 0.05, хорошо до 0.5, громко до потолка. */
export const QUIET_BELOW = 0.05;
export const GOOD_BELOW = 0.5;

/** Что видно и что слышно: `level` — текущая громкость 0…1. */
export function level(peak: number): Level {
  if (!Number.isFinite(peak) || peak <= 0) return "silent";
  if (peak >= CLIP_AT) return "clipping";
  if (peak < QUIET_BELOW) return "quiet";
  if (peak < GOOD_BELOW) return "good";
  return "loud";
}

/**
 * Слово для человека. Написано так, как он сам бы сказал.
 *
 * «Нормально» вместо «оптимально»: второе — из отчёта, первое — из жизни.
 */
export const LEVEL_WORD: Record<Level, string> = {
  silent: "тишина",
  quiet: "тихо",
  good: "нормально",
  loud: "громко",
  clipping: "слишком громко",
};

/**
 * Что поправить.
 *
 * Совет по состоянию, а не общий: «проверьте микрофон» ничего не говорит.
 * У молчания причин две, и они разные — не говорят или не слышат, — поэтому
 * совет называет обе, не выбирая за человека.
 */
export function advice(level_: Level): string {
  switch (level_) {
    case "silent":
      return "ничего не слышу: скажите фразу вслух — если так же тихо, выберите другой микрофон";
    case "quiet":
      return "слышно тихо: говорите ближе к микрофону или громче";
    case "good":
      return "слышно хорошо: можно проверять фразой";
    case "loud":
      return "громко, но разборчиво: так тоже подходит";
    case "clipping":
      return "перегрузка: отодвиньтесь от микрофона — искажение режет слова, и разбор получается мусорный";
  }
}

/**
 * Тестовая фраза — одна и названа.
 *
 * Не «скажите что-нибудь»: человек должен знать, что сказать, и что после этого
 * произойдёт. Фраза короткая, чтобы проверка занимала секунду, и осмысленная —
 * чтобы её можно было узнать в поле «Услышал».
 */
export const TEST_PHRASE = "проверка микрофона";

/** Что произойдёт после фразы. Обещание проверяемое, чтобы человек ждал именно это. */
export const TEST_RESULT = "услышанное появится рядом — это и есть проверка";

/**
 * Готов ли уровень к проверке фразой.
 *
 * Тишина — не повод не пробовать: возможно, человек просто молчит. Но сказать
 * об этом надо **до**, иначе он скажет фразу в закрытый микрофон и решит, что
 * тот сломан.
 */
export function ready(level_: Level): boolean {
  return level_ !== "silent" && level_ !== "clipping";
}
