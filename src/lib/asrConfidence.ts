/**
 * Показывать уверенность распознавания словами (шаг 58).
 *
 * Дефект. Распознавание выдаёт текст и молчит о том, **насколько оно уверено**.
 * А это решает, что человеку делать: при высокой уверенности он просто
 * подтверждает, при низкой — проверяет и правит. Без этого числа человек
 * либо перепроверяет каждый раз (и это утомляет), либо не проверяет никогда (и
 * получает «не то»).
 *
 * Второй дефект хуже первого. Модель показывает **только итоговый текст**, и
 * человек не видит, **где** она сомневалась. Он читает «открой блок нот»,
 * понимает, что это «блокнот», но правит всю фразу целиком — а править надо
 * было одно слово.
 *
 * Правило: уверенность показывается **словами и по словам**.
 *
 *  1. **Три слова, а не процент.** «Услышал точно», «услышал так», «мог
 *     ослышаться» — человеку нужно знать, проверять ли, а не сравнивать 0.87 с
 *     0.62.
 *  2. **Сомнительные слова называются отдельно.** Не «уверенность 0.62», а
 *     «мог ослышаться в: блок нот» — человек правит одно слово, а не всю фразу.
 *  3. **Правка не стирает фразу.** Человек правит слово прямо в строке; остальное
 *     остаётся. Начинать заново из-за одного слова — наказание за точность.
 *  4. **«Услышал так» — это предложение, а не приговор.** Текст можно принять
 *     или поправить; сказать «я услышал» честнее, чем показать текст как факт.
 *
 * Почему не показывать процент. Проценты от распознавания не откалиброваны:
 * «уверенность 90%» редко значит, что в девяти случаях из десяти верно. Слово
 * не обещает точности, которой нет, и не требует пересчёта в голове.
 */

/** Насколько уверено распознавание — тремя ступенями. */
export type Sure = "sure" | "likely" | "unsure";

/** Уверенность в одном слове. */
export interface Word {
  text: string;
  /** Насколько распознавание уверено в этом слове, 0…1. */
  confidence: number;
  /** Правка человека, если он её внёс. */
  fixed?: string;
}

/**
 * Порог «точно» и порог «мог ослышаться».
 *
 * Между ними — «услышал так»: обычно верно, но проверить стоит.
 */
export const SURE_AT = 0.85;
export const UNSURE_BELOW = 0.55;

/**
 * Уверенность целой фразы.
 *
 * По **худшему** слову, а не по среднему: фраза «открой блокнот и сохрани»
 * с одним неверным словом может значить совсем другое действие, и средняя
 * уверенность спрячет это за семью верными словами.
 */
export function sure(words: readonly Word[]): Sure {
  if (words.length === 0) return "unsure";
  const worst = Math.min(...words.map((word) => word.confidence));
  if (worst >= SURE_AT) return "sure";
  if (worst >= UNSURE_BELOW) return "likely";
  return "unsure";
}

/**
 * Слова, в которых распознавание сомневалось.
 *
 * Именно их и надо править; показывать всю фразу как сомнительную значит
 * заставить человека перепроверять то, что и так верно.
 */
export function doubts(words: readonly Word[]): string[] {
  return words
    .filter((word) => !word.fixed && word.confidence < SURE_AT)
    .map((word) => word.text);
}

/** Итоговый текст: с учётом правок человека. */
export function text(words: readonly Word[]): string {
  return words
    // Пустая правка — уже убранное слово, а не «правки нет»: `undefined` здесь
    // значило бы «оставь как было», и «убери» не срабатывало бы.
    .map((word) => (word.fixed === undefined ? word.text : word.fixed))
    .filter((part) => part.length > 0)
    .join(" ")
    .trim();
}

/**
 * Поправить одно слово, не трогая остальные.
 *
 * Пустая правка — это «убери слово»: человек мог понять, что слова не должно
 * быть, — и это тоже правка, а не ошибка ввода.
 */
export function fix(words: readonly Word[], index: number, value: string): Word[] {
  if (index < 0 || index >= words.length) return [...words];
  const next = [...words];
  const word = next[index];
  if (!word) return next;
  const clean = value.trim();
  // Пустая правка ставится как пустая строка, а не как «нет правки»: иначе
  // «уберите это слово» неотличимо от «я ничего не менял».
  next[index] = { ...word, fixed: clean };
  return next;
}

/**
 * Что показать человеку — словами.
 *
 * Назван **сам факт сомнения** и **где именно**: «мог ослышаться в: блок нот».
 * Без второго сообщение не помогает: человек не знает, куда смотреть.
 */
export function say(words: readonly Word[]): string {
  const level = sure(words);
  if (level === "sure") return "услышал точно";
  const bad = doubts(words);
  const list = bad.slice(0, 3).join(", ");
  const more = bad.length > 3 ? " и ещё" : "";
  return level === "likely"
    ? `услышал так — проверьте: ${list}${more}`
    : `мог ослышаться в: ${list}${more} — поправьте слово или повторите`;
}

/**
 * Подпись к итоговому тексту.
 *
 * «Я услышал» честнее, чем показать текст как факт: человек не отвечает за
 * ошибку распознавания, но должен знать, что она возможна.
 */
export function askConfirm(words: readonly Word[]): string | null {
  return doubts(words).length > 0 ? "услышал так — поправьте, если не то" : null;
}
