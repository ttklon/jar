/**
 * Ошибка разбора не запускает ничего и говорит, что не понято (шаг 97).
 *
 * Дефект. Когда разбор не понял фразу, происходит одно из двух, и оба хуже
 * честного «не понял»:
 *
 *  * **запускается ближайшее похожее**: «почисти место в документе» → «освободи
 *    место на диске» → удаление файлов. Слова совпали, намерение — нет;
 *  * **не происходит ничего, но и не говорится ничего**: человек ждёт, потом
 *    повторяет, потом думает, что приложение сломалось.
 *
 * Правило: **не понял — значит ничего не сделал, и это сказано словами**.
 *
 *  1. «Не понял» — **результат**, а не пустота: он виден человеку и назван.
 *  2. Ничего не запускается **включая чтение**: «нашёл похожее и показал» — это
 *     уже решение за человека, и он начинает считать похожее ответом.
 *  3. Сказано **что именно** не понято: действие, объект или всё вместе. Иначе
 *     человек не знает, что поправить.
 *  4. Есть **пример**, как сказать иначе: без примера «скажите иначе» — это
 *     просьба к человеку придумать язык приложения.
 *  5. «Не понял» **не стыдит**: не «некорректная команда», а «не понял: …».
 *     Человек говорил нормально — это разбор не справился.
 *
 * Почему не «попробовать лучшее из найденного». Лучшее из найденного при неверном
 * намерении — это случайное действие. При чтении оно безвредно и потому особенно
 * опасно: человек привыкает, что похожее сходит за ответ.
 */

import type { Intent } from "./intent";

/** Что не понято. */
export type Gap =
  /** Нет действия: «большие файлы в загрузках». */
  | "действие"
  /** Есть действие, нет объекта: «найди». */
  | "объект"
  /** Не понято намерение вовсе: «ыыы», шум. */
  | "всё"
  /** Понято, но данных не хватает: «перенеси туда». */
  | "место";

/** Решение: запускать ли что-нибудь. */
export interface Result {
  /** Запускать ли. Для «не понял» — всегда `false`. */
  run: boolean;
  /** Что не понято. */
  gap: Gap;
  /** Что сказать человеку. */
  said: string;
}

/**
 * Разбор «не понято».
 *
 * `run` — `false` **во всех** случаях непонимания, включая частичное: «найди»
 * без объекта — это не «найти всё», это вопрос.
 */
export function check(intent: Intent): Result {
  if (intent.verb === "неизвестно") {
    return {
      run: false,
      gap: "всё",
      said: "не понял фразу — ничего не делаю. Скажите, что сделать: «найди большие файлы в загрузках»",
    };
  }
  if (intent.object.trim() === "") {
    return {
      run: false,
      gap: "объект",
      said: `понял действие «${intent.verb}», но не понял, над чем — ничего не делаю. Скажите: «${intent.verb} отчёты»`,
    };
  }
  return { run: true, gap: "всё", said: "" };
}

/**
 * Частичное непонимание: действие и объект есть, места нет.
 *
 * «Перенеси туда» без «туда» — это не «перенести в загрузки по умолчанию»: это
 * действие, которого человек не просил.
 */
export function where(text: string): Result | null {
  const clean = text.trim();
  if (/(?:^|\s)(?:туда|сюда|там|тут)(?=\s|$)/i.test(clean) && !/(?:в|на)\s+\S/.test(clean)) {
    return {
      run: false,
      gap: "место",
      said: "понял действие, но не понял, куда — ничего не делаю. Назовите папку: «перенеси в Загрузки»",
    };
  }
  return null;
}

/**
 * Что показать при непонимании — **пример**, а не «скажите иначе».
 *
 * Без примера «скажите иначе» — это просьба придумать язык приложения.
 */
export function example(gap: Gap): string {
  switch (gap) {
    case "действие":
      return "например: «найди большие файлы в загрузках»";
    case "объект":
      return "например: «удали отчёты за март»";
    case "место":
      return "например: «перенеси отчёты в папку Архив»";
    case "всё":
      return "например: «почисти корзину» или «покажи, что занимает место»";
  }
}

/**
 * Не стыдить.
 *
 * «Некорректная команда» — это про человека, хотя ошибся разбор. Названо прямо,
 * чтобы при правках не появилось «некорректный запрос».
 */
export function blame(text: string): boolean {
  return /некорректн|неправильн(?:ая|ый)\s+(?:команда|запрос)|ошибка\s+пользователя/i.test(text);
}

/**
 * Итог: сказать и ничего не делать.
 *
 * Одной функцией, чтобы «не понял» нельзя было случайно превратить в действие:
 * `run` тут всегда `false`, а текст — всегда с примером.
 */
export function say(result: Result): string {
  if (result.run) return "";
  // Всегда с примером: без примера «скажите иначе» — просьба придумать язык.
  return `${result.said.trim()}. ${example(result.gap)}`;
}

/** Запускать ли — единственное место, где это решается. */
export function run(result: Result): boolean {
  return result.run;
}
