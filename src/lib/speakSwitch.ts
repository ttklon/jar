/**
 * Ответ голосом можно выключить одной кнопкой (шаг 59).
 *
 * Дефект. Голосовой ответ полезен не всегда. В опенспейсе он мешает соседям; в
 * наушниках — наоборот, единственный способ не смотреть на экран; ночью — будит
 * домашних. А выключается он **в настройках**: человек в опенспейсе лихорадочно
 * ищет, где это, и до конца дня отвечает шёпотом «да нет, не надо».
 *
 * Второе, хуже первого: выключив голос, человек **не может его вернуть на одну
 * фразу**. Модель просит подтвердить опасное действие — тут бы и произнести
 * вопрос вслух, — но микрофон уже выключен, и человек пропускает подтверждение.
 *
 * Правило: голос **выключается одной кнопкой на экране** и работает как пауза.
 *
 *  1. Кнопка одна и всегда рядом: не в настройках. Настройки — это место, где
 *     ищут и не находят.
 *  2. Выключенный голос **не немой навсегда**: важное (`confirm`, `error`)
 *     проговаривается даже при выключенном голосе, если это сказано человеку.
 *     Молча пропустить вопрос об опасном действии — хуже, чем нарушить тишину.
 *  3. Состояние **видно словом**, а не только значком: «голос выключен» на
 *     экране, иначе человек слышит тишину и не понимает, это ответ или сбой.
 *  4. Выключение **не сбрасывает** режим «слушаю всегда» и не трогает микрофон:
 *     это две разные вещи, и путать их — значит выключить не то.
 */

/** Почему голос выключен — от этого зависит, что делать с важным. */
export type Why = "by-me" | "quiet-hours" | "no-voice" | "speaking";

/** Что происходит с ответом голосом. */
export interface Voice {
  /** Говорить ли обычные ответы. */
  on: boolean;
  /** Почему выключено (или почему включено). */
  why: Why;
}

/** Голос работает — обычный ответ звучит. */
export const ON: Voice = { on: true, why: "speaking" };

/**
 * Выключить голос **по своей воле**.
 *
 * Причина «я так решил» отличается от «тихие часы»: своё решение человек
 * помнит, а расписание — нет, и напоминать о нём надо по-разному.
 */
export const OFF: Voice = { on: false, why: "by-me" };

/** Нажатие на кнопку голоса — туда и обратно, одной кнопкой. */
export function toggle(voice: Voice): Voice {
  return voice.on ? OFF : ON;
}

/**
 * Что важнее тишины.
 *
 * `confirm` — модель спрашивает про необратимое действие; `error` — что-то
 * сломалось. Оба проговариваются **даже при выключенном голосе**: молча
 * пропустить вопрос об опасном действии хуже, чем нарушить тишину.
 *
 * `answer` — обычный ответ: при выключенном голосе молчит, и это то, чего
 * человек и хотел.
 */
export type Kind = "answer" | "confirm" | "error";

export function speaks(voice: Voice, kind: Kind): boolean {
  if (kind === "confirm" || kind === "error") return true;
  return voice.on;
}

/**
 * Что сказать, если важное проговаривается при выключенном голосе.
 *
 * Сказано **почему** голос зазвучал: иначе человек решит, что кнопка не
 * работает, и полезет её чинить.
 */
export function sayAnyway(kind: Kind): string | null {
  if (kind === "answer") return null;
  return kind === "confirm"
    ? "голос выключен, но это нужно подтвердить — говорю вслух"
    : "голос выключен, но случилась ошибка — говорю вслух";
}

/**
 * Что человек видит на кнопке.
 *
 * Состояние — **словом**: значок динамика не читается ни диктором, ни
 * дальтоником, ни тем, кто смотрит в сторону.
 */
export function word(voice: Voice): string {
  if (voice.on) return "голос включён";
  switch (voice.why) {
    case "quiet-hours":
      return "голос выключен тихими часами — нажмите, чтобы включить";
    case "no-voice":
      return "голос недоступен: на этой машине нет движка речи";
    default:
      return "голос выключен вами — нажмите, чтобы включить";
  }
}

/**
 * Можно ли включить голос.
 *
 * Если движка речи нет, кнопка не врёт: она говорит, что нажать бесполезно.
 * Кнопка, которая нажимается и ничего не делает, хуже отсутствующей.
 */
export function canTurnOn(voice: Voice): boolean {
  return voice.on || voice.why !== "no-voice";
}

/**
 * Голос и микрофон — разные вещи.
 *
 * Выключение голоса **не** выключает микрофон и не сбрасывает «слушаю всегда».
 * Это разные устройства и разные ожидания: человек, выключивший ответы голосом,
 * всё ещё хочет говорить.
 */
export function micNeeded(voice: Voice): boolean {
  void voice;
  return true;
}
