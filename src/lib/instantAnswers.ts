/**
 * Кэш ответов на «что умеешь / где данные / как дела» без модели (шаг 132).
 *
 * Дефект. Ответ, который **известен при сборке**, всё равно собирался на месте:
 *
 *  * **«мгновенно» означало «быстро»**: ответ ждал чтения реестра (127), а реестр — это
 *    файл на диске и список инструментов; между нажатием и словом всё равно полсекунды;
 *  * **кэш жил до перезапуска**: закрыл окно — снова ждёшь; а «как дела» спрашивают
 *    именно при запуске;
 *  * **собирали то, что не меняется**: «данные лежат только на этой машине» — это
 *    свойство приложения, а не реестра; пересобирать его каждый раз бессмысленно;
 *  * **мгновенность не измерялась**: «долго/быстро» на глаз, хотя кадр — это 16 мс, и
 *    всё, что дольше, уже видно как задержку.
 *
 * Правило: **частый ответ готов до вопроса, и это проверяется числом**.
 *
 *  1. **Ответ лежит заранее** — в том числе между запусками (сохранённый), а не
 *     собирается в момент вопроса.
 *  2. **Он не ждёт реестра**: числа подставляются при первом чтении, но если чтения ещё
 *     не было — ответ всё равно **есть**, и он говорит «числа из прошлого запуска».
 *  3. **Мгновенно — это ≤ кадра (16 мс)**, а не «на глаз быстро»: это проверяется.
 *  4. **Устаревшее помечено, а не выдано за свежее**: счётчики могли измениться — так и
 *     сказано, и это не мешает ответу быть мгновенным.
 *  5. **Модель не спрашивают вовсе** — и это не «повезло», а условие: ответ не зависит
 *     от неё.
 *
 * Почему не «просто захардкодить». Захардкоженный текст не знает чисел реестра и врёт
 * при изменении; здесь текст **устойчив** (свойства, а не числа) и подставляет числа,
 * когда они есть.
 */

/** Вопрос, на который ответ готов заранее. */
export type Ask = "skills" | "data" | "health";

/** Готовый ответ. */
export interface Ready {
  ask: Ask;
  /** Текст; числа подставляются, если известны. */
  said: string;
  /** Откуда числа: свежие, прошлого запуска или их нет. */
  numbers: "fresh" | "past" | "none";
  /** Версия реестра, по которой собран ответ (пусто — чисел не было). */
  version: string;
}

/** Что известно о реестре в момент сборки. */
export interface Numbers {
  actions: number;
  hands: number;
  version: string;
}

/**
 * Собрать ответ — **без** обращения к реестру.
 *
 * `numbers` может быть `null`: ответ всё равно готов, просто без чисел. Это и есть
 * мгновенность: ждать нечего.
 */
export function build(ask: Ask, numbers: Numbers | null, past = false): Ready {
  const numbersState: Ready["numbers"] = numbers === null ? "none" : past ? "past" : "fresh";
  const head =
    numbers === null
      ? ""
      : `умею ${numbers.actions} действий; руками делаю ${numbers.hands}; `;

  switch (ask) {
    case "skills":
      return {
        ask,
        // Свойство («умею то, что в реестре») отдельно от числа (835): число может
        // устареть, свойство — нет.
        said: `${head}полный список — в журнале`,
        numbers: numbersState,
        version: numbers?.version ?? "",
      };
    case "data":
      return {
        ask,
        // Это свойство приложения, а не реестра: числа не нужны вовсе.
        said: "данные лежат только на этой машине; наружу ничего не уходит",
        numbers: "none",
        version: "",
      };
    case "health":
      return {
        ask,
        said: "работаю на этой машине; если что-то долго — скажу числом",
        numbers: "none",
        version: "",
      };
  }
}

/** Кэш, который переживает перезапуск. */
export interface Store {
  entries: Map<Ask, Ready>;
}

export function store(past: readonly Ready[] = []): Store {
  const entries = new Map<Ask, Ready>();
  for (const entry of past) entries.set(entry.ask, entry);
  return { entries };
}

/**
 * Ответ — сразу, из готового.
 *
 * Возвращает **синхронно**: асинхронность здесь означала бы кадр задержки на ровном
 * месте.
 */
export function instant(storeIn: Store, ask: Ask): Ready {
  return storeIn.entries.get(ask) ?? build(ask, null);
}

/**
 * Обновить числами — но не раньше, чем они есть.
 *
 * Пометка `past` сохраняется: ответ из прошлого запуска **называется** прошлым, а не
 * выдаётся за свежий.
 */
export function refresh(storeIn: Store, ask: Ask, numbers: Numbers, wasPast: boolean): Ready {
  const got = build(ask, numbers, wasPast);
  storeIn.entries.set(ask, got);
  return got;
}

/**
 * Мгновенно ли.
 *
 * «Мгновенно» — это ≤ кадра (16 мс): всё, что дольше, человек видит как задержку, и
 * называть это «мгновенно» значит врать.
 */
export const FRAME_MS = 16;

export function instantEnough(ms: number): { ok: boolean; said: string } {
  if (ms <= FRAME_MS) return { ok: true, said: `${ms} мс — в кадре` };
  return { ok: false, said: `${ms} мс — дольше кадра (${FRAME_MS} мс): это задержка, а не «мгновенно»` };
}

/**
 * Что сказать про откуда-взятость.
 *
 * Мгновенный ответ не значит «свежий»: если числа прошлого запуска — так и сказано.
 */
export function provenance(ready: Ready): string {
  switch (ready.numbers) {
    case "fresh":
      return "числа из реестра этого запуска";
    case "past":
      return "числа из прошлого запуска — могли измениться";
    case "none":
      return "без чисел: реестр ещё не прочитан";
  }
}

/** Что сохранить на следующий запуск. */
export function save(storeIn: Store): Ready[] {
  return [...storeIn.entries.values()];
}

/** Спросили ли модель — по условию ответа, а не «повезло». */
export function modelNeeded(ask: Ask): boolean {
  // Все три ответа — свойства приложения и реестра; модель для них не нужна.
  void ask;
  return false;
}
