/**
 * Хранить последнюю фразу и контекст для «а теперь то же с другой папкой» (шаг 96).
 *
 * Дефект. «А теперь то же с другой папкой» — **самая естественная** фраза, и она
 * не работает. Приложение либо не понимает («то же» — это не действие), либо
 * понимает как новую задачу и делает что-то правдоподобное. Дальше:
 *
 *  * **человек повторяет всё**: пять слов вместо «то же» — это не лень человека, а
 *    работа, которую он не хотел;
 *  * **«то же» понимается как вся прошлая фраза**, включая путь: «сделай копию в
 *    D:\Backup», «а теперь то же с другой папкой» — копирует в тот же D:\Backup,
 *    то есть **не то**;
 *  * **контекст теряется между запусками**: приложение закрыли, и «то же» уже
 *    ничего не значит.
 *
 * Правило: **хранится не фраза, а её разложение, и заменяется только то, что
 * названо**.
 *
 *  1. Хранится **глагол, объект и параметры** — то, что можно заменить по частям.
 *     Текст фразы хранится только для показа.
 *  2. «То же» берёт **прошлое разложение** и заменяет **названные части**: «с
 *     другой папкой» заменяет папку, а всё остальное остаётся.
 *  3. **Замена по названию, а не по позиции**: «с другой папкой» заменяет `path`,
 *     а не «второй параметр».
 *  4. Если в прошлой фразе **не было** того, что назвали («с другим размером», а
 *     размера не было), — это **не «то же»**, а новая задача: заменить нечего, и
 *     молча добавить параметр значит придумать.
 *  5. Если прошлая фраза была **опасной**, «то же» наследует опасность и
 *     подтверждение (шаг 94): «то же» не делает опасное безопасным.
 *
 * Почему не «подставить прошлую фразу целиком». Тогда «то же с другой папкой»
 * скопирует в ту же папку: прошлая фраза содержала путь, и целиком он остаётся
 * прошлым. Это ровно тот случай, когда «то же» значит «не то».
 */

/** Разложение прошлой фразы — то, что можно заменить по частям. */
export interface Context {
  /** Глагол: «скопируй». */
  verb: string;
  /** Объект: «отчёт». */
  object: string;
  /** Параметры по имени: `path`, `period`, `count`. */
  params: Record<string, string>;
  /** Что человек сказал — для показа, а не для разбора. */
  said: string;
  /** Была ли прошлая фраза опасной. */
  dangerous: boolean;
}

/** Что человек хочет заменить. */
export interface Swap {
  /** Имя параметра: `path`, `period`, `count`. */
  key: string;
  /** Новое значение. */
  value: string;
}

/**
 * Слова, по которым понятно, **что** менять.
 *
 * «С другой папкой» → `path`, «за другой месяц» → `period`, «на пять штук» →
 * `count`. Список короткий и **по имени**, а не по позиции: позиция в прошлой
 * фразе могла быть любой.
 */
const SWAPS: [RegExp, string][] = [
  [/(?:с\s+)?друг(?:ой|ую|ого|им)\s+(?:папк|путем|путём|каталог|диском|диске)/i, "path"],
  [/(?:в|по)\s+друг(?:ой|ую)\s+папк/i, "path"],
  [/(?:за|в)\s+друг(?:ой|ом)\s+(?:месяц|период|день|год|неделю)/i, "period"],
  [/(?:на\s+)?(?:пять|десять|два|три|четыре|\d+)\s+(?:штук|файлов|копи)/i, "count"],
  [/(?:с\s+)?друг(?:им|ого)\s+(?:именем|названием)/i, "name"],
];

/**
 * Разбор «то же, но …».
 *
 * Возвращает, **что менять**, и остаётся ли это «тем же»: если менять нечего —
 * это не «то же», а новая задача (шаг 97: лучше «не понял», чем «сделал не то»).
 */
export interface Result {
  /** Что менять. Пусто — «то же без изменений». */
  swaps: Swap[];
  /** Значения, которых в прошлой фразе не было: приклеить нечего. */
  missing: string[];
  /** Можно ли исполнять как «то же». */
  ok: boolean;
  /** Почему — для показа и теста. */
  why: string;
}

/** Замена по подобию: «то же с другой папкой» — это контекст. */
export function parse(phrase: string, context: Context | null): Result {
  const clean = phrase.trim();
  const withoutSame = /(?:^|\s)(?:то\s+же|так\s+же|то\s+же\s+самое)/i.test(clean);

  // Найти, что назвали.
  const swaps: Swap[] = [];
  for (const [pattern, key] of SWAPS) {
    if (pattern.test(clean) && !swaps.some((swap) => swap.key === key)) {
      const value = valueOf(clean, key);
      swaps.push({ key, value });
    }
  }

  if (!withoutSame) {
    return { swaps, missing: [], ok: false, why: "это не «то же» — новая задача, контекст не нужен" };
  }

  if (context === null) {
    return {
      swaps,
      missing: [],
      ok: false,
      why: "«то же» — но прошлой фразы нет: что именно повторить, неизвестно",
    };
  }

  if (swaps.length === 0) {
    return { swaps: [], missing: [], ok: true, why: `то же: «${context.said}»` };
  }

  // Замена по имени: если параметра в прошлой фразе не было — приклеить нечего.
  const missing = swaps.filter((swap) => context.params[swap.key] === undefined).map((swap) => swap.key);
  if (missing.length > 0) {
    return {
      swaps,
      missing,
      ok: false,
      why: `в прошлой фразе не было «${missing.join(", ")}» — это не «то же», скажите задачу целиком`,
    };
  }

  return {
    swaps,
    missing: [],
    ok: true,
    why: `то же, но «${swaps.map((swap) => `${swap.key} = ${swap.value}`).join(", ")}»`,
  };
}

/** Что именно поставили вместо: «D:\Work». */
function valueOf(phrase: string, key: string): string {
  if (key === "path") {
    // «С другой папкой» не называет папку — значит, её надо спросить, а не
    // придумать. Пустое значение — честное «какая папка?».
    // Путь бывает и «D:\Work», и «Мои документы»: сначала то, что после папки,
    // а если там кириллица с пробелом — до союза или конца фразы.
    // `\w` в JavaScript без флага `u` не берёт кириллицу — «папкой» не совпадало.
    const named = /(?:папк|каталог)[\p{L}]*\s+(?:в|на)?\s*([A-Za-z]:[^\s,.;]*|"[^"]+"|[^,.;]+)/iu.exec(phrase);
    if (named !== null) return named[1] ?? "";
    return "";
  }
  if (key === "period") {
    const month = /(январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр)/i.exec(phrase);
    return month ? (month[0] ?? "").toLowerCase() : "";
  }
  if (key === "count") {
    const count = /\d+/.exec(phrase);
    return count ? (count[0] ?? "") : "";
  }
  return "";
}

/**
 * Итоговый контекст — с заменами.
 *
 * Прошлое разложение **не мутируется**: «то же» может быть сказано дважды, и
 * второй раз должен остаться от прошлой фразы, а не от первой замены.
 */
export function apply(context: Context, result: Result): Context {
  if (!result.ok) return context;
  const params = { ...context.params };
  for (const swap of result.swaps) params[swap.key] = swap.value;
  return {
    ...context,
    params,
    // Опасность **наследуется**: «то же» не делает опасное безопасным.
    dangerous: context.dangerous,
  };
}

/**
 * Что сказать человеку.
 *
 * Названо **что осталось и что заменилось**: «то же: скопируй отчёт, path =
 * D:\Work». Иначе человек не видит, что именно повторится.
 */
export function say(context: Context | null, result: Result): string {
  if (!result.ok) return result.why;
  if (context === null) return result.why;
  const changed = result.swaps.map((swap) => `${swap.key} = ${swap.value}`).join(", ");
  const danger = context.dangerous ? " — и это по-прежнему необратимо" : "";
  return changed === ""
    ? `то же: «${context.said}»${danger}`
    : `то же: «${context.said}», но ${changed}${danger}`;
}

/**
 * Чего не хватает для исполнения.
 *
 * «С другой папкой» без названия папки — это вопрос «какой?», а не повод
 * придумать путь.
 */
export function gaps(result: Result): string[] {
  const empty = result.swaps.filter((swap) => swap.value === "").map((swap) => swap.key);
  return result.missing.length > 0 ? [...result.missing, ...empty] : empty;
}
