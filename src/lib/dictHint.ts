/**
 * Подсказка распознавателю по словарю реестра (шаг 56).
 *
 * Дефект. Распознавание не знает имён программ и путей, и ошибается в них
 * **предсказуемо**: «эксель» превращается в «и к сердцу», «блокнот» — в «блок
 * нот», «ви эс код» — в «виси код». Человек произносит единственное важное
 * слово фразы, а именно его и слышат неправильно.
 *
 * Почему термины важнее остальных слов. Ошибка в «поставь на паузу» почти
 * невозможна — слова частые, и модель их знает. Ошибка в имени программы
 * вероятна и **ломает всю фразу**: «открой блокнот» с неверным «блок нот»
 * превращается в другой запрос, а не в запрос с опечаткой.
 *
 * Правило: словарь реестра **подсказывает** распознавателю, а подсказка — это
 * не приказ.
 *
 *  1. Подсказка **не засоряет фразу**: в неё идут имена и их написания, а не
 *     все слова из `KNOWN` — иначе частые слова («файл», «текст») начнут
 *     перетягивать на себя чужую речь.
 *  2. Подсказка **небольшая** (`MAX_TERMS`): у длинного списка падает точность
 *     на обычной речи — распознаватель начинает ловить совпадения, которых нет.
 *  3. Без программы перед человеком подсказка берётся из **всех** знакомых
 *     программ, но короткая: терминов, которые человек может назвать, не так
 *     много.
 *  4. Сказано, что подсказка была: без этого человек не знает, почему одна и та
 *     же фраза распознаётся по-разному, и считает это нестабильностью.
 */

/**
 * Сколько терминов отдаём распознавателю.
 *
 * Мало — не покроем, много — испортим обычную речь. Двадцать — компромисс,
 * проверенный на живом разговоре.
 */
export const MAX_TERMS = 20;

/** Что подсказать распознавателю. */
export interface Hint {
  /** Термины в том порядке, в каком их стоит подсказывать. */
  terms: string[];
  /** Подсказка относится к программе перед человеком или ко всем знакомым. */
  focus: "window" | "all";
}

/**
 * Собрать подсказку.
 *
 * `known` — словарь `KNOWN` в виде «имя программы → слова, которыми её зовут».
 * `process` — программа перед человеком (может быть неизвестна).
 *
 * Имена (включая латиницу) идут **первыми**: их распознаватель путает чаще
 * всего, и подсказка нужна именно им. Частые слова из словаря отбрасываются:
 * «файл» и «текст» и так знает любой распознаватель, а лишний вес в подсказке
 * они забирают.
 */
export function hint(
  known: Record<string, string[]>,
  process: string | null,
  /** Слова, которые человек добавил сам (шаг 57). */
  own: readonly string[] = [],
): Hint {
  const focus = process !== null && known[process.toLowerCase()] !== undefined ? "window" : "all";

  // Свои термины — первыми: человек добавил их, потому что их не слышат.
  const terms: string[] = [];
  const add = (term: string) => {
    const clean = term.trim();
    if (clean.length === 0) return;
    if (!terms.some((have) => have.toLowerCase() === clean.toLowerCase())) terms.push(clean);
  };

  for (const term of own) add(term);

  // Только имена программ и их латинские написания: это то, что путается.
  const names = Object.keys(known);
  if (focus === "window" && process !== null) {
    const own_ = known[process.toLowerCase()] ?? [];
    // Сначала сама программа, потом остальные знакомые — чтобы человек,
    // сказавший «открой хром», был понят даже из блокнота.
    add(process.replace(/\.exe$/i, ""));
    for (const word of own_) if (LATIN.test(word)) add(word);
  } else {
    for (const name of names) add(name.replace(/\.exe$/i, ""));
  }

  return { terms: terms.slice(0, MAX_TERMS), focus };
}

/** Латиница и цифры: «vs code», «pdf», «vlc» — их распознаватель путает чаще. */
const LATIN = /[a-z0-9]/i;

/**
 * Что сказать человеку: почему эта фраза распозналась лучше обычного.
 *
 * Сказано **чем именно помогли** и что это можно выключить: иначе подсказка
 * выглядит как случайность и человек ей не доверяет.
 */
export function sayHint(hint_: Hint): string | null {
  if (hint_.terms.length === 0) return null;
  const list = hint_.terms.slice(0, 4).join(", ");
  return hint_.focus === "window"
    ? `распознаю точнее: слова программы «${hint_.terms[0]}» — ${list}`
    : `распознаю точнее имена программ: ${list}`;
}

/**
 * Небольшая ли подсказка.
 *
 * Длинный список вредит: распознаватель начинает «слышать» термины там, где их
 * нет. Функция нужна тесту и настройке, чтобы предел не потерялся при правках.
 */
export function fits(hint_: Hint): boolean {
  return hint_.terms.length <= MAX_TERMS;
}
