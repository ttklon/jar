/**
 * Первая строка ответа — до плана: «понял, делаю» (шаг 133).
 *
 * Дефект. Первое слово (128) отвечало «я здесь», но не отвечало **«я понял»**:
 *
 *  * **«разбираю» не говорит, что услышано правильно**: человек не знает, поняли его
 *    или разбирают не то — и повторяет фразу другими словами;
 *  * **признание и работа смешаны**: «понял» — это про услышанное, «делаю» — про
 *    начатое; слитые в одну фразу, они приходят тогда, когда уже поздно поправлять;
 *  * **подтверждение теряется в плане**: план — это уже «как», а человек в этот момент
 *    ждёт «ты меня понял?»;
 *  * **«понял» без повтора — пустое**: «понял» и молчание неотличимы, если не сказано,
 *    **что** понято.
 *
 * Правило: **первая строка — «понял + что понял», и она раньше плана**.
 *
 *  1. **Признание раньше плана**: «понял, переименовываю фото» — до шагов.
 *  2. **Повтор того, что понято** — своими словами, коротко: он же и проверка, что
 *     понято правильно.
 *  3. **Одно предложение, не абзац**: первая строка — это строка.
 *  4. **Если понято неточно — так и сказано**: «понял как X — поправьте, если нет», а не
 *     уверенное неверное.
 *  5. **Не обещание**: «понял» — факт, «сейчас всё будет» — обещание (128).
 *
 * Почему не «показать план и этим подтвердить». План показывает **как**, и человек,
 * читая шаги, вынужден сам догадываться, то ли это; первая строка отвечает прямо и
 * раньше, чем читать.
 */

/** Что понято. */
export interface Understood {
  /** Дело словами, как понял помощник: «переименовать фото в папке». */
  what: string;
  /** Насколько уверен: точное совпадение с реестром или догадка. */
  confident: boolean;
}

/**
 * Первая строка.
 *
 * Собирается **до** плана: для неё нужно только понятое дело, а не шаги.
 */
export function line(got: Understood, planReady = false): string {
  // План не нужен, и это условие: строка не ждёт шагов.
  void planReady;
  const what = got.what.trim();
  if (what === "") {
    // Пусто — не «понял»: пустой повтор был бы ложью.
    return "понял не до конца — скажите, что сделать";
  }
  if (!got.confident) {
    // Догадка названа догадкой: «понял как X — поправьте» лучше уверенного неверного.
    return `понял как «${what}» — поправьте, если не так`;
  }
  return `понял, делаю: ${what}`;
}

/**
 * Одна ли это строка.
 *
 * Первая строка — это строка: если в ней перевод строки или она длиннее 80 знаков, она
 * перестаёт быть первой строкой и становится абзацем, который не читают.
 */
export const LINE_MAX = 80;

export function isLine(said: string): { ok: boolean; said: string } {
  if (/[\n\r]/.test(said)) {
    return { ok: false, said: "это не строка: внутри перевод строки — человек прочтёт только первую половину" };
  }
  if (said.length > LINE_MAX) {
    return { ok: false, said: `это не строка: ${said.length} знаков при пределе ${LINE_MAX}` };
  }
  return { ok: true, said: `${said.length} знаков — строка` };
}

/**
 * Повтор понятого — коротким.
 *
 * Длинный повтор («переименовать все фотографии в папке Загрузки, начиная с 2024 года»)
 * — это уже план; в первой строке нужен смысл, а не параметры.
 */
export function briefly(what: string, max = 40): string {
  const clean = what.trim().replace(/\s+/g, " ");
  if (clean.length <= max) return clean;
  // Обрезаем по слову, а не по букве: «переименовать все фотогр…» читается как сбой.
  const cut = clean.slice(0, max);
  const at = cut.lastIndexOf(" ");
  return `${(at > 0 ? cut.slice(0, at) : cut).trim()}…`;
}

/**
 * Порядок: первая строка, потом план.
 *
 * Возвращает порядок, а не текст: важно, что признание идёт раньше шагов.
 */
export function order(first: string, plan: readonly string[]): string[] {
  return [first, ...plan];
}

/**
 * Не стало ли признание опоздавшим.
 *
 * Если первая строка появляется вместе с готовым отчётом, «понял» уже не помогает:
 * поправлять нечего.
 */
export function early(firstAt: number | null, finishedAt: number | null): { ok: boolean; said: string } {
  if (firstAt === null) return { ok: false, said: "первой строки не было — человек не знал, поняли ли его" };
  if (finishedAt !== null && firstAt >= finishedAt) {
    return { ok: false, said: "первая строка пришла вместе с готовым — поправлять уже поздно" };
  }
  return { ok: true, said: "первая строка раньше готового — поправить ещё можно" };
}

/**
 * Поправка человека после первой строки.
 *
 * Если он поправил — новое признание, а не продолжение старого: «понял» один раз на
 * одно понимание.
 */
export function corrected(got: Understood, wasCorrected: boolean): string {
  if (!wasCorrected) return line(got);
  return line({ what: got.what, confident: true }).replace("понял, делаю:", "понял заново, делаю:");
}
