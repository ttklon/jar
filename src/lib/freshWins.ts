/**
 * Шаг 265: память не подменяет свежую фразу — приоритет у сказанного сейчас.
 *
 * Дефект. Память и разбор фразы жили рядом и не встречались. Человек говорит
 * «открой отчёты в D:\\Новое\\Отчёты», а приложение подставляет запомненное
 * `D:\\Отчёты`: подсказка перекрывает то, что сказали **сейчас**. Это худший вид
 * ошибки — не «не понял», а «понял и заменил своим».
 *
 * Почему так выходит само собой. Подсказка — удобная: поле уже заполнено
 * «вероятным», и разбор видит заполненное поле. Заполненное поле неотличимо от
 * сказанного, и догадка побеждает по умолчанию. Отсюда правило.
 *
 * Правила:
 *
 *  1. **сказанное сейчас — всегда сильнее памяти.** Не «обычно», не «при
 *     равной уверенности»: названное человеком значение не заменяется никогда;
 *  2. **память заполняет только пустое**, и заполненное помечается как
 *     подсказка, а не как сказанное. Человек должен видеть разницу;
 *  3. **противоречие называется, а не разрешается молча.** Если сказанное
 *     отличается от запомненного, это не повод «поправить» человека — это повод
 *     сказать: «вы сказали `D:\\Новое`, раньше было `D:\\Отчёты`, беру
 *     сказанное»;
 *  4. **исправление после подстановки не считается новым словом.** Человек
 *     стирает подсказку и печатает своё — это его слово, и оно сильнее памяти
 *     тем более.
 */

/** Откуда взялось значение. */
export type Source =
  /** Человек сказал или напечатал. */
  | "said"
  /** Подставлено из памяти. */
  | "memory"
  /** Ничего нет. */
  | "empty";

/** Что человек сказал сейчас и что помнит приложение. */
export interface Field {
  /** Значение, которое человек сказал сам; пусто — не говорил. */
  readonly said: string;
  /** Значение из памяти; пусто — памяти нет. */
  readonly remembered: string;
}

/** Итог: что взять, откуда и что об этом сказать. */
export interface Chosen {
  /** Значение поля: сказанное, иначе запомненное, иначе пусто. */
  readonly value: string;
  /** Откуда оно. */
  readonly from: Source;
  /** Словами: почему именно это. */
  readonly why: string;
  /** Мешает ли память свежему слову — то, что обязано быть названо. */
  readonly conflict: boolean;
}

/**
 * Выбрать значение поля.
 *
 * Память **не спорит** со сказанным: она либо заполняет пустое, либо отходит.
 * Здесь же решается, что сказать человеку, если они разошлись.
 */
export function choose(field: Field): Chosen {
  const said = normalize(field.said);
  const remembered = normalize(field.remembered);

  if (said) {
    // Сказанное не заменяется никогда — даже если память «увереннее».
    const conflict = remembered !== "" && !same(said, remembered);
    return {
      value: field.said.trim(),
      from: "said",
      why: conflict
        ? `вы сказали «${field.said.trim()}», в памяти «${field.remembered.trim()}» — беру сказанное`
        : "сказано сейчас",
      conflict,
    };
  }

  if (remembered) {
    // Подстановка помечается как подстановка: заполненное поле не должно
    // выглядеть как сказанное.
    return {
      value: field.remembered.trim(),
      from: "memory",
      why: "вы ничего не сказали — подставил из памяти",
      conflict: false,
    };
  }

  return { value: "", from: "empty", why: "пусто: ни сказанного, ни памяти", conflict: false };
}

/**
 * Сказанное и запомненное совпадают.
 *
 * Сравнение — без учёта регистра, лишних слэшей и кавычек: `D:\Отчёты`,
 * `d:\отчёты` и `D:\Отчёты\` для человека одно и то же, и объявлять это
 * противоречием значит поднимать шум на пустом месте.
 */
function same(left: string, right: string): boolean {
  return normalize(left) === normalize(right);
}

function normalize(value: string): string {
  return value
    .trim()
    .replace(/^["']|["']$/g, "")
    .replace(/\\+/g, "\\")
    .replace(/\\$/, "")
    .toLowerCase();
}

/**
 * Что показать рядом со значением.
 *
 * Подсказка обязана быть отличима от сказанного **без цвета и без наведения**:
 * человек, который видит заполненное поле, считает его своим.
 */
export function mark(chosen: Chosen): string {
  if (chosen.from === "said") return "";
  if (chosen.from === "memory") return "из памяти";
  return "";
}

/**
 * Заполнить поле подсказкой, не поссорившись с человеком.
 *
 * Возвращает то, что нужно показать, и **не трогает** сказанное: это главное,
 * что проверяет тест. Функция отдельная, потому что вызывающий код легко
 * перепутает порядок — сначала разобрать, потом подставить.
 */
export function fill(field: Field): { value: string; hint: string; note: string } {
  const chosen = choose(field);
  return {
    // Сказанное возвращается как есть: ни нормализации, ни обрезки — человек
    // увидит ровно то, что набрал.
    value: chosen.from === "said" ? field.said : chosen.value,
    hint: mark(chosen),
    note: chosen.conflict ? chosen.why : "",
  };
}

/**
 * Исправил ли человек подсказку.
 *
 * Это не «противоречие с памятью»: человек стёр догадку и написал своё. Такое
 * слово сильнее памяти тем более, и записывать его надо как сказанное.
 */
export function edited(shown: string, typed: string): boolean {
  return shown !== typed;
}

/** Сводка для журнала: сколько раз память уступила свежему слову. */
export function counts(chosen: readonly Chosen[]): { said: number; memory: number; conflicts: number } {
  return {
    said: chosen.filter((item) => item.from === "said").length,
    memory: chosen.filter((item) => item.from === "memory").length,
    conflicts: chosen.filter((item) => item.conflict).length,
  };
}
