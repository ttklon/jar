/**
 * Шаг 412: переключение профиля не перезапускает приложение.
 *
 * Перезапуск «чтобы применилось» — это привычка из мира, где профиль живёт в
 * отдельных процессах с отдельными базами. Здесь этого не нужно: память — набор
 * фактов в памяти программы, разрешения — список, и всё это меняется на лету.
 *
 * Что перезапуск ломал бы по-настоящему:
 *
 *  * **идущее дело** терялось бы (шаг 410: оно не должно теряться);
 *  * **несохранённая фраза** в поле ввода исчезала бы — человек переключился и
 *    потерял то, что набирал;
 *  * **модель пришлось бы загружать заново** — на слабой машине это десятки
 *    секунд;
 *  * **окно открывалось бы заново** — с другим размером и на другом месте, если
 *    позиция не сохранилась.
 *
 * Поэтому переключение — это **смена трёх ссылок**: память, разрешения, текущий
 * человек. И проверка, что после неё всё на месте.
 */

import type { Profile } from "./peopleProfiles";

/** Что держит приложение во время работы. */
export interface Live {
  /** Чей профиль сейчас. */
  readonly who: Profile;
  /** Что в поле ввода — не теряется. */
  readonly draft: string;
  /** Идущее дело: сколько шагов выполнено. */
  readonly stepsDone: number;
  /** Загружена ли модель. */
  readonly modelReady: boolean;
  /** Открыто ли окно (всегда да, пока работает). */
  readonly window: boolean;
}

/**
 * Переключить.
 *
 * `profiles` — куда переключаем; `who` — id или имя. Возвращает новое состояние
 * и **что сохранилось**, чтобы экран мог это сказать.
 */
export function switchTo(live: Live, profiles: readonly Profile[], who: string): { live: Live; kept: string[]; said: string } {
  const found = profiles.find((profile) => profile.person.id === who || profile.person.name === who);
  if (found === undefined) {
    return { live, kept: [], said: `нет такого человека: «${who}» — не переключился, всё осталось как было` };
  }

  const kept: string[] = [];
  if (live.draft !== "") kept.push("набранная фраза");
  if (live.stepsDone > 0) kept.push("идущее дело");
  if (live.modelReady) kept.push("загруженная модель");

  return {
    live: { ...live, who: found },
    kept,
    said: `теперь «${found.person.name}». ${kept.length > 0 ? `Осталось на месте: ${kept.join(", ")}.` : "Ничего не потерялось."}`,
  };
}

/**
 * Что не должно случиться при переключении.
 *
 * Возвращает список нарушений — а не булево, чтобы видеть, что именно сломалось.
 */
export function verify(before: Live, after: Live): string[] {
  const problems: string[] = [];
  if (before.draft !== after.draft) problems.push(`фраза в поле ввода потерялась: «${before.draft}» → «${after.draft}»`);
  if (after.stepsDone < before.stepsDone) problems.push("идущее дело потеряло выполненные шаги");
  if (before.modelReady && !after.modelReady) problems.push("модель выгрузилась: на слабой машине это десятки секунд ожидания");
  if (!after.window) problems.push("окно закрылось и открылось заново");
  return problems;
}

/**
 * Сколько занимает переключение.
 *
 * Ноль перезапусков — и это проверяется числом, а не словами.
 */
export function cost(): { restarts: number; said: string } {
  return { restarts: 0, said: "переключение — смена трёх ссылок: память, разрешения, человек. Перезапусков ноль" };
}

/**
 * Что переключение всё-таки меняет.
 *
 * Список, чтобы было видно: меняется ровно то, что должно.
 */
export function changes(): string[] {
  return [
    "факты памяти: теперь ищем в памяти нового человека",
    "разрешения: опасное без его согласия снова спрашивается",
    "подпись в журнале: дальше пишется новый автор",
  ];
}
