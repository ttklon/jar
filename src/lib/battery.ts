/**
 * Шаг 236: долгая работа на батарее — замер расхода в простое и в деле, числа.
 *
 * Почему «числа», а не «экономно». «Мы заботимся о батарее» проверить нельзя:
 * это обещание без единицы измерения. А «в простое — 0,4 %/час, в разговоре —
 * 6 %/час» можно сравнить с прошлой версией и заметить, что стало хуже. Без
 * чисел регрессия расхода невидима: приложение просто «как-то садится».
 *
 * Три правила:
 *
 *  1. **простой и дело — разные числа.** В простое приложение почти не должно
 *     есть батарею; в разговоре — ест, и это нормально. Одно среднее число
 *     скрывает оба факта;
 *  2. **число — с единицей и с временем**, а не «много/мало»: «6 %/час» человек
 *     сразу переводит в «пять часов работы», «много» — ни во что;
 *  3. **не наврать**: если замер невозможен (нет данных о заряде), это
 *     говорится, а не подменяется оценкой. Оценка, выданная за замер, — тот же
 *     самообман, что и процент из воздуха.
 *
 * Чего модуль не делает: не читает батарею сам. Замеры приносит вызывающий:
 * `{at, percent, busy}` — так правило проверяется без железа.
 */

/** Один замер: время и заряд. */
export interface Sample {
  /** Время в миллисекундах (одни часы для всех замеров). */
  at: number;
  /** Заряд в процентах, 0..100. */
  percent: number;
  /** Был ли разговор в этот момент. */
  busy: boolean;
}

/** Итог по одному режиму. */
export interface Rate {
  /** Процентов в час. `null` — посчитать нельзя. */
  perHour: number | null;
  /** Сколько замеров легло в расчёт. */
  samples: number;
  /** Почему `null`, если `null`. */
  why: string;
}

/**
 * Минимум замеров для честной оценки: три точки на два интервала.
 *
 * По двум точкам процент в час считается, но любой сбой (округление заряда до
 * целого, просадка на старте программы) даёт число, которое потом живёт в
 * отчёте как факт.
 */
export const MIN_SAMPLES = 3;

/**
 * Минимальная длительность наблюдения — пять минут.
 *
 * Заряд сообщается целыми процентами: за минуту он не меняется, и «0 %/час»
 * получилось бы просто от неточности округления.
 */
export const MIN_SPAN_MS = 5 * 60 * 1000;

/**
 * Процент в час по замерам одного режима.
 *
 * Считается по **крайним** точкам, а не по среднему всех разностей: заряд
 * округлён до целого, и среднее по мелким разностям накапливает ошибку
 * округления в одну сторону.
 */
export function rate(samples: readonly Sample[], busy: boolean, span = MIN_SPAN_MS): Rate {
  const picked = samples.filter((sample) => sample.busy === busy).sort((a, b) => a.at - b.at);
  if (picked.length < MIN_SAMPLES) {
    return {
      perHour: null,
      samples: picked.length,
      why: `замеров ${picked.length}, нужно ${MIN_SAMPLES} — по одной-двум точкам число было бы округлением, а не замером`,
    };
  }
  const first = picked[0]!;
  const last = picked[picked.length - 1]!;
  const spanMs = last.at - first.at;
  if (spanMs < span) {
    return {
      perHour: null,
      samples: picked.length,
      why:
        `наблюдали ${Math.round(spanMs / 60000)} мин, нужно ${Math.round(span / 60000)}: ` +
        "заряд округлён до целого процента, и на коротком отрезке это не измерение",
    };
  }
  // Заряд **вырос** — это зарядка, а не расход. Считать «−3 %/час» расходом
  // значит показывать отрицательное потребление.
  const drop = first.percent - last.percent;
  if (drop < 0) {
    return { perHour: null, samples: picked.length, why: "заряд рос: компьютер был на зарядке" };
  }
  const perHour = (drop / spanMs) * 3600 * 1000;
  // Точность названа, а не замазана нулём. Заряд приходит **целыми процентами**:
  // за час наблюдения падение на 1% — это «от 0 до 2 %/час», и выдать «1,0»
  // значит соврать в обе стороны. Поэтому малый расход называется словами с
  // верхней границей, а не числом, которое выглядит точным.
  const unit = (1 / spanMs) * 3600 * 1000;
  if (perHour < unit * 2) {
    return {
      perHour: Math.round(perHour * 10) / 10,
      samples: picked.length,
      why:
        `меньше ${(unit * 2).toFixed(1).replace(".", ",")} %/час — это меньше шага округления заряда; ` +
        "точнее скажет только наблюдение дольше",
    };
  }
  return { perHour: Math.round(perHour * 10) / 10, samples: picked.length, why: "" };
}

/** Расход в двух режимах сразу — то, что обещано шагом. */
export interface Report {
  idle: Rate;
  busy: Rate;
  /** Строка для человека: два числа рядом, а не одно среднее. */
  said: string;
}

/**
 * Отчёт по замерам.
 *
 * Оба режима считаются **независимо**: если в простое замеров не хватило, это
 * не повод не назвать число для разговора — и наоборот.
 */
export function report(samples: readonly Sample[], span = MIN_SPAN_MS): Report {
  const idle = rate(samples, false, span);
  const busy = rate(samples, true, span);
  return { idle, busy, said: say(idle, busy) };
}

function one(name: string, got: Rate): string {
  if (got.perHour === null) return `${name}: не измерено — ${got.why}`;
  return `${name}: ${got.perHour.toFixed(1).replace(".", ",")} %/час (${got.samples} замеров)`;
}

/** Строка для человека: единица названа, время названо, оценки не выданы за замер. */
export function say(idle: Rate, busy: Rate): string {
  return `${one("в простое", idle)}; ${one("в разговоре", busy)}`;
}

/**
 * Сколько часов проработает от текущего заряда при таком расходе.
 *
 * `null`, если расход не измерен или равен нулю: «бесконечно» — не ответ,
 * который помогает человеку.
 */
export function hours(percent: number, perHour: number | null): number | null {
  if (perHour === null || perHour <= 0) return null;
  return Math.round((percent / perHour) * 10) / 10;
}
