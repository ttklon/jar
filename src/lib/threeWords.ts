/**
 * Отчёт по шагу: сделано / не сделано / неизвестно — тремя словами (шаг 118).
 *
 * Дефект. Отчёт пользуется словами, которые **не различают главное**:
 *
 *  * **`failed` без разбора читается как «не сделано»** — хотя шаг мог выполниться и
 *    сломаться на проверке; тогда «не сделано» — ложь, а «сделано» — тоже;
 *  * **пропущенный шаг попадает в «сделано»**: `skipped` в отчёте есть, а на экране
 *    его нет, и человек считает, что сделано всё;
 *  * **нет третьего слова**: «неизвестно» — честный статус, когда шаг выполнился, а
 *    проверить нечем (шаг 111: проверки не было), но приложение выбирает между
 *    «сделано» и «не сделано» наугад;
 *  * **слов много**: «выполнено», «готово», «успешно», «ок», «провалено», «отменено»
 *    — шесть слов на три факта, и каждое значит своё.
 *
 * Правило: **три слова, и каждое — факт, а не настроение**.
 *
 *  1. **Сделано** — только когда есть подтверждение проверкой (шаг 111).
 *  2. **Не сделано** — когда известно, что не сделано: провал, отказ, отмена до
 *     начала, пропуск.
 *  3. **Неизвестно** — когда приложение **не знает**: проверки не было, доказательство
 *     противоречит статусу (шаг 106), шаг прерван посередине.
 *  4. **Неизвестно — не прячется**: оно считается отдельно и называется числом. Три
 *     слова полезны только вместе.
 *  5. **Перевод один на всё приложение**: шесть слов на три факта дают шесть ответов
 *     на один вопрос.
 *
 * Почему не «пять статусов, как в ядре». Пять статусов — для ядра, которому нужно
 * различать причину. Человеку нужен ответ на вопрос «сделано ли», и у него три
 * варианта, а не пять.
 */

/** Три слова — ответ человеку. */
export type Answer = "сделано" | "не сделано" | "неизвестно";

/** Что пришло от ядра — со всеми подробностями. */
export interface Raw {
  /** Статус, как его назвала рука. */
  status: "ok" | "failed" | "cancelled" | "skipped" | "pending";
  /** Доказательство, если оно есть. */
  proof?: string;
  /** Сказала ли рука, что проверка подтвердилась. */
  confirmed?: boolean;
  /** Противоречие: «успех» с доказательством провала (шаг 106). */
  conflicted?: boolean;
  /** Прервано посередине: таймаут, отмена во время шага. */
  interrupted?: boolean;
}

/**
 * Ответ по шагу.
 *
 * Порядок проверок важен: сначала «неизвестно» — оно перекрывает и «сделано», и «не
 * сделано», потому что при незнании оба были бы догадкой.
 */
export function answer(raw: Raw): Answer {
  if (raw.conflicted) return "неизвестно";
  if (raw.interrupted) return "неизвестно";
  switch (raw.status) {
    case "ok": {
      // «Сделано» требует подтверждения: без него это вера (шаг 111).
      if (raw.confirmed === false) return "неизвестно";
      return "сделано";
    }
    case "failed":
      // Провал на проверке — это «сделано и сломано»; без доказательства — «не сделано».
      return raw.proof !== undefined && raw.proof.trim().length > 0 ? "неизвестно" : "не сделано";
    case "cancelled":
    case "skipped":
      // Не начиналось — значит не сделано, и это факт.
      return "не сделано";
    case "pending":
      return "неизвестно";
  }
}

/** Все три слова — в одном месте, чтобы экран не придумывал четвёртого. */
export const WORDS: readonly Answer[] = ["сделано", "не сделано", "неизвестно"];

/** Итог по плану: три числа. */
export interface Tally {
  done: number;
  notDone: number;
  unknown: number;
  total: number;
}

export function tally(raws: readonly Raw[]): Tally {
  const counts = { done: 0, notDone: 0, unknown: 0 };
  for (const raw of raws) {
    const got = answer(raw);
    if (got === "сделано") counts.done += 1;
    else if (got === "не сделано") counts.notDone += 1;
    else counts.unknown += 1;
  }
  return { ...counts, total: raws.length };
}

/**
 * Итог словами — три числа рядом.
 *
 * Только сумма «сделано N» без двух других — это не отчёт, а обещание: неизвестное
 * молча становится сделанным.
 */
export function say(got: Tally): string {
  if (got.total === 0) return "шагов нет — нечего отчитывать";
  const parts = [`сделано ${got.done}`, `не сделано ${got.notDone}`];
  parts.push(`неизвестно ${got.unknown}`);
  const head = `из ${got.total}`;
  return `${head}: ${parts.join(", ")}`;
}

/**
 * Что делать с неизвестным.
 *
 * Отдельно, потому что «неизвестно» требует **действия** (перепроверить), а «не
 * сделано» — решения (повторить или нет). Сводить их в один список — терять это.
 */
export function unsure(raws: readonly Raw[]): number[] {
  return raws.map((raw, index) => (answer(raw) === "неизвестно" ? index : -1)).filter((index) => index >= 0);
}

/**
 * Можно ли считать дело удавшимся.
 *
 * Только когда **нет ни одного** неизвестного и ни одного «не сделано»: «в целом
 * получилось» при двух неизвестных — это вера, а не отчёт.
 */
export function success(got: Tally): boolean {
  return got.total > 0 && got.notDone === 0 && got.unknown === 0;
}
