/**
 * Шаг 447: правильная работа с несколькими пользователями Windows.
 *
 * У Windows бывает несколько учётных записей на одном компьютере, и это **не** то
 * же самое, что профили внутри программы (шаг 401). Разница принципиальная:
 *
 *  * **пользователь Windows** — отдельная папка `C:\Users\имя`, отдельный реестр
 *    (`HKCU`), и два пользователя Windows **не видят файлов друг друга**;
 *  * **профиль программы** — несколько человек в одной папке, с общим диском.
 *
 * Отсюда три правила, которые надо соблюсти, и все — про то, чтобы не сломать
 * чужое:
 *
 *  * **данные живут в папке пользователя** (`%APPDATA%`), а не в `C:\Program
 *    Files`: иначе второй пользователь Windows либо не запустит программу, либо
 *    увидит чужие дела;
 *  * **автозапуск — только свой**: `HKCU`, никогда `HKLM`, иначе программа
 *    запустится у всех, кто войдёт;
 *  * **обновление — для всех или по одному**: `HKLM` для установки требует
 *    администратора, и это единственное место, где он честно нужен.
 */

/** Где лежит. */
export type Place = "appdata" | "programFiles" | "shared";

/** Что кладём. */
export type Data = "память" | "журнал" | "настройки" | "модель" | "автозапуск";

/**
 * Куда положить.
 *
 * Модель — единственное исключение: она большая и одна на машину, поэтому лежит
 * в общей папке **только для чтения**, и каждый пользователь скачивает заново
 * при отсутствии доступа.
 */
export function place(data: Data): { where: Place; why: string } {
  switch (data) {
    case "память":
    case "журнал":
    case "настройки":
      return { where: "appdata", why: "это личное: второй пользователь Windows не должен видеть чужие дела" };
    case "модель":
      return { where: "shared", why: "модель большая и одна на машину; она только читается, и её можно скачать заново" };
    case "автозапуск":
      return { where: "appdata", why: "запись в HKCU — только для этого пользователя; HKLM запустил бы программу у всех" };
  }
}

/**
 * Что случится со вторым пользователем Windows.
 *
 * Не «всё своё» и не «ничего»: свои память и настройки, общая модель.
 */
export function forSecondUser(): string[] {
  return [
    "память и журнал: пустые — он начинает с чистого листа, и это правильно",
    "настройки: свои, а не первого пользователя",
    "модель: общая, если доступна на чтение; иначе скачается заново",
    "автозапуск: выключен, пока он сам не включит",
  ];
}

/**
 * Нужен ли администратор.
 *
 * Только для установки в `Program Files` и только один раз — при установке.
 * Ни память, ни автозапуск, ни обновление модели администратора не требуют.
 */
export function adminNeeded(what: "install" | "autostart" | "memory" | "model" | "update"): { needed: boolean; said: string } {
  if (what === "install") return { needed: true, said: "установка в Program Files — единственное место, где администратор честно нужен" };
  if (what === "update") return { needed: true, said: "обновление для всех пользователей требует администратора; если его нет — обновится только этот пользователь" };
  return { needed: false, said: "администратор не нужен: всё в папке пользователя" };
}

/**
 * Что нельзя делать.
 *
 * Три ошибки, каждая из которых обнаруживается у второго пользователя.
 */
export function notDo(): string[] {
  return [
    "не писать данные в Program Files: второй пользователь не запустит программу",
    "не ставить автозапуск в HKLM: программа запустится у всех, кто войдёт",
    "не считать профиль программы заменой пользователю Windows: это разные вещи и разные папки",
  ];
}

/**
 * Что проверить тестом.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "память, журнал и настройки — в папке пользователя",
    "автозапуск — только HKCU",
    "администратор нужен только для установки и общего обновления",
  ];
}
