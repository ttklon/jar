/**
 * Шаг 289: Whisper.cpp/Piper — офлайн, бесплатно, предсказуемо (без включения
 * лицензионно несовместимого).
 *
 * Что взято. Распознавание (Whisper.cpp) и синтез (Piper) работают **локально**:
 * ни одного байта наружу, бесплатно, и одинаково каждый раз — без «сервис
 * недоступен» и «лимит исчерпан».
 *
 * Что не взято и почему: модели и обвязка с лицензией, несовместимой с
 * бесплатным распространением. Это не «юридическая осторожность», а
 * практическое правило: компонент с такой лицензией превращает бесплатное
 * приложение в условно-бесплатное, и человек узнаёт об этом не от нас.
 *
 * Три правила:
 *
 *  1. **список компонентов закрыт и проверяется.** Не «мы стараемся», а
 *     `allowed()` на каждом: компонент вне списка не загружается;
 *  2. **локальность проверяется, а не обещается.** У «локальной» библиотеки
 *     бывает телеметрия по умолчанию; поэтому у каждого компонента — признак
 *     «не ходит в сеть», и он обязателен;
 *  3. **цена названа честно.** Локально — это не «лучше во всём»: медленнее
 *     облака на слабой машине и хуже на редких языках. Молчать об этом значит
 *     обещать то, чего нет.
 */

/** Лицензия компонента — в терминах, а не текстом лицензии. */
export type License =
  /** Можно использовать и распространять бесплатно, в том числе в составе приложения. */
  | "free"
  /** Можно использовать локально, но распространение ограничено. */
  | "restricted"
  /** Несовместима с бесплатным распространением. */
  | "incompatible";

/** Компонент локального контура. */
export interface Part {
  readonly id: string;
  readonly name: string;
  /** Что делает: `speech-to-text`, `text-to-speech`, `language-model`. */
  readonly role: string;
  readonly license: License;
  /** Проверено ли, что не ходит в сеть. Обязательный признак, а не флаг по желанию. */
  readonly offline: boolean;
}

/**
 * Разрешённые компоненты.
 *
 * Короткий список осознанно: каждый новый компонент — это чужой код в контуре,
 * который обещает приватность, и проверять его придётся заново.
 */
export const ALLOWED: readonly Part[] = [
  { id: "whisper.cpp", name: "Whisper.cpp", role: "speech-to-text", license: "free", offline: true },
  { id: "piper", name: "Piper", role: "text-to-speech", license: "free", offline: true },
  { id: "silero-vad", name: "Silero VAD", role: "voice-activity", license: "free", offline: true },
];

/** Можно ли брать компонент. */
export function allowed(part: Part): { ok: boolean; said: string } {
  if (part.license === "incompatible") {
    return {
      ok: false,
      said: `${part.name}: лицензия несовместима с бесплатным распространением — такой компонент делает приложение условно-бесплатным`,
    };
  }
  if (part.license === "restricted") {
    return {
      ok: false,
      said: `${part.name}: использовать можно, распространять — нет; в сборку такой не пойдёт`,
    };
  }
  if (!part.offline) {
    return {
      ok: false,
      said: `${part.name}: не проверено, что работает без сети — «локальный» компонент с телеметрией не локальный`,
    };
  }
  return { ok: true, said: `${part.name}: свободная лицензия, без сети` };
}

/** Проверить весь контур: все ли разрешены и покрыты ли роли. */
export function audit(parts: readonly Part[]): { ok: boolean; said: string; problems: string[] } {
  const problems = parts.map(allowed).filter((got) => !got.ok).map((got) => got.said);
  const roles = new Set(parts.filter((part) => allowed(part).ok).map((part) => part.role));
  const missing = ["speech-to-text", "text-to-speech"].filter((role) => !roles.has(role));
  if (missing.length > 0) {
    problems.push(`нет компонента для: ${missing.join(", ")} — разговор не заработает целиком`);
  }
  return {
    ok: problems.length === 0,
    said: problems.length === 0 ? `контур локальный: ${parts.length} компонентов, все без сети` : problems.join("; "),
    problems,
  };
}

/**
 * Цена локальности — честно.
 *
 * «Локально» не значит «лучше во всём»: молчать об этом значит обещать то, чего
 * нет, и человек узнает разницу на первой длинной записи.
 */
export function tradeoffs(): readonly string[] {
  return [
    "медленнее облака на слабой машине: распознавание идёт на процессоре, а не на большом сервере",
    "хуже на редких языках и сильном акценте — модели меньше, чем у сервисов",
    "первый запуск дольше: модель загружается в память",
  ];
}

/** Что сказать человеку про офлайн одним предложением. */
export function offlinePromise(): string {
  return "распознавание и голос работают без сети: ни одного байта наружу, и одинаково каждый раз";
}
