/**
 * Шаг 408: «забыть профиль» — одной кнопкой, но с настоящим подтверждением.
 *
 * Удаление — тоже право. Профиль, который нельзя удалить, — это не профиль, а
 * ловушка: человек попробовал, не понравилось, и теперь его имя навсегда в списке.
 *
 * Но «одной кнопкой» и «без подтверждения» — разные вещи:
 *
 *  * **подтверждение называет, что именно исчезнет**, а не «вы уверены?». Человек
 *    должен узнать, что вместе с именем уйдут 12 фактов и 2 разрешения;
 *  * **«забыть» ≠ «удалить всё»**: модель, настройки и расписания остаются —
 *    их не просили трогать (шаг 417);
 *  * **отменить можно не после удаления.** Поэтому удаление идёт с задержкой в
 *    один шаг: «забыть» кладёт профиль в корзину на 30 дней, и только потом
 *    стирает. Но если человек нажал дважды — не «насильно», а честно сказав, что
 *    корзины не будет.
 */

import type { Profile } from "./peopleProfiles";

/**
 * Что исчезнет.
 *
 * Перечисляется по частям и с числами: «12 фактов», а не «вся память».
 */
export function willGo(profile: Profile): string[] {
  return [
    `имя «${profile.person.name}»`,
    `${profile.facts.length} ${plural(profile.facts.length, "факт", "факта", "фактов")} памяти`,
    `${profile.allowed.length} ${plural(profile.allowed.length, "разрешение", "разрешения", "разрешений")}`,
  ];
}

/**
 * Что останется.
 *
 * Список — чтобы человек не боялся нажать: модель не придётся качать заново.
 */
export function stays(): string[] {
  return ["скачанная модель: она про компьютер, а не про человека", "настройки программы: язык, тема, шрифт", "расписания общих задач"];
}

/**
 * Подтверждение.
 *
 * Три части: что исчезнет, что останется, сколько есть времени передумать.
 */
export function confirm(profile: Profile, days: number): string {
  return [
    `Забыть профиль «${profile.person.name}»?`,
    `Исчезнет: ${willGo(profile).join(", ")}.`,
    `Останется: ${stays().join("; ")}.`,
    `Можно передумать ${days} ${plural(days, "день", "дня", "дней")}: до тех пор профиль лежит в корзине, но никому не виден.`,
  ].join(" ");
}

/**
 * Первое нажатие — в корзину.
 *
 * «Никому не виден» — важная часть: профиль в корзине не должен попадать в поиск
 * и в переключение, иначе «забыл» окажется «спрятал, но оно работает».
 */
export function forget(name: string, at: number, days: number): { hidden: boolean; purgeAt: number; said: string } {
  const purgeAt = at + days * 86_400_000;
  return {
    hidden: true,
    purgeAt,
    said: `профиль «${name}» убран из списка и поиска; окончательно исчезнет ${date(purgeAt)} — до тех пор можно вернуть`,
  };
}

/**
 * Второе нажатие — сразу.
 *
 * «Удалить сейчас» законно, но человек должен знать, что назад нельзя.
 */
export function now(name: string): string {
  return `удаляю профиль «${name}» сейчас и без корзины: вернуть не получится`;
}

/**
 * Вернуть из корзины.
 */
export function restore(name: string): string {
  return `профиль «${name}» вернулся: он снова в списке, факты и разрешения на месте`;
}

/**
 * Что удаление не делает.
 *
 * Три вещи, которых «забыть» не означает — и все три про общие данные (шаг 417).
 */
export function notDo(): string[] {
  return [
    "не удаляет файлы, которые этот человек удалял делом: дело уже случилось",
    "не трогает общие расписания и модель: их не просили",
    "не удаляет журнал, где он попросил дела: без автора дел журнал перестал бы быть честным",
  ];
}

/** Дата по-русски. */
function date(ms: number): string {
  const d = new Date(ms);
  return `${d.getDate()}.${String(d.getMonth() + 1).padStart(2, "0")}.${d.getFullYear()}`;
}

/** Склонение по числу. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
