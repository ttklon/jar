/**
 * Шаг 482: кэш зависимостей и артефактов — не качать одно и то же.
 *
 * Прогон в пять минут (шаг 481) невозможен, если каждый раз качать `node_modules` и
 * цель `tsc`. Кэш — не удобство, а часть бюджета: без него прогон
 * непредсказуем по времени, и его перестают запускать.
 *
 * Три кэша, и у каждого **ключ**, который нельзя перепутать:
 *
 *  * **зависимости** — ключ по `package-lock.json`: изменился лок — кэш не тот;
 *  * **сборка** (`tsc -b`) — ключ по лок-файлу и по `tsconfig`, плюс по **всем**
 *    исходникам: правка одного файла не должна оставить старую цель;
 *  * **артефакты тестов** — по исходникам теста.
 *
 * Правило одно: **кэш, который может быть неверным, хуже отсутствующего**. Он даёт
 * зелёный прогон на старом коде — и это ровно тот случай, когда дефект доезжает до
 * человека.
 */

/** Вид кэша. */
export type Kind = "deps" | "build" | "test";

/** Кэш. */
export interface Cache {
  readonly kind: Kind;
  /** Ключ, под которым лежит. */
  readonly key: string;
  /** От чего ключ зависит — чтобы было видно, полный ли он. */
  readonly from: readonly string[];
}

/**
 * Правильный ли ключ.
 *
 * `changed` — что изменилось с прошлого раза. Ключ верен, если изменившегося в
 * списке `from` нет: зависимость от лок-файла не должна «видеть» правку `.ts`.
 */
export function keyOk(cache: Cache, changed: readonly string[]): { ok: boolean; said: string } {
  const hits = changed.filter((path) => cache.from.some((from) => path === from || path.startsWith(`${from}/`)));

  return hits.length === 0
    ? { ok: true, said: `кэш ${cache.kind} годится: изменилось только то, от чего он не зависит` }
    : { ok: false, said: `кэш ${cache.kind} не годится: изменилось ${hits.join(", ")} — пересобрать` };
}

/**
 * Что должно быть в ключе.
 *
 * Три зависимости для сборки; их отсутствие — главная причина «зелёного на старом».
 */
export function mustKey(): string[] {
  return [
    "`package-lock.json`: другой лок — другие зависимости",
    "`tsconfig.json`: другие настройки типов — другая сборка",
    "`src`: все исходники — правка одного файла не должна оставить старую цель",
  ];
}

/** Обязательные части ключа сборки — те же три, но машинно. */
export const BUILD_REQUIRES = ["package-lock.json", "tsconfig.json", "src"] as const;

/**
 * Проверить кэш сборки.
 *
 * Отдельно от `keyOk`: у сборки должно быть **всё** из `mustKey`, иначе кэш
 * неполный и врёт.
 */
export function buildComplete(cache: Cache): string[] {
  if (cache.kind !== "build") return [];
  const human: Record<string, string> = { "package-lock.json": "лок-файла", "tsconfig.json": "настроек типов", src: "исходников" };

  return BUILD_REQUIRES.filter((need) => !cache.from.includes(need)).map((need) => `в ключе сборки нет ${human[need]}: кэш может быть неверным`);
}

/**
 * Чего кэш не делает.
 *
 * Три запрета; первый — главный.
 */
export function notDo(): string[] {
  return [
    "не сохраняет кэш, который может быть неверным: лучше пересобрать",
    "не кэширует по времени («свежее пяти минут») — только по содержимому",
    "не переиспользует кэш другой ветки без проверки ключа",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу кэшей.
 */
export function checks(): string[] {
  return [
    "ключ каждого кэша полный: лок, конфиг, исходники",
    "изменение вне ключа не делает кэш «негодным» — иначе он бесполезен",
    "неполный ключ сборки назван, а не принят молча",
  ];
}
