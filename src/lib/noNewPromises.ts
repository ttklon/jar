/**
 * Шаг 496: не добавлять новых обещаний, пока старые не доказаны.
 *
 * Каждое новое обещание («ещё научусь делать X») забирает внимание у старого,
 * которое ещё не доказано. Через месяц обещаний двадцать, доказано восемь, и
 * человек, читая документацию, не может отличить одно от другого.
 *
 * Правило простое: **пока в списке есть недоказанное, новое не добавляется**.
 * Исключение одно, и оно осознанное: новое обещание **заменяет** недоказанное —
 * тогда список не растёт.
 *
 * Это правило про **порядок**, а не про запрет развития: сначала доказать, потом
 * обещать. Иначе проект обещает быстрее, чем делает.
 */

/** Обещание. */
export interface Promise_ {
  /** Что обещано. */
  readonly text: string;
  /** Доказано ли: тест с утверждением и приёмка (шаги 487, 492). */
  readonly proven: boolean;
}

/** Список обещаний. */
export interface Book {
  readonly items: readonly Promise_[];
}

/**
 * Можно ли добавить.
 *
 * Три исхода: `можно` (всё доказано), `сначала доказать` (есть недоказанное),
 * `только вместо` (новая замена старого недоказанного — список не растёт).
 */
export function mayAdd(book: Book, replaces?: string): { verdict: "можно" | "сначала доказать" | "только вместо"; said: string } {
  const unproven = book.items.filter((item) => !item.proven);

  if (replaces !== undefined) {
    const target = book.items.find((item) => item.text === replaces || item.text.includes(replaces));
    if (target === undefined) return { verdict: "сначала доказать", said: `«${replaces}» нет в списке: заменять нечего — новое обещание добавит долг` };
    if (target.proven) return { verdict: "сначала доказать", said: `«${replaces}» уже доказано: нечего заменять — новое обещание добавит долг` };
    return { verdict: "только вместо", said: `можно: новое обещание заменяет недоказанное «${replaces}», список не растёт` };
  }

  if (unproven.length === 0) return { verdict: "можно", said: "можно: все обещания доказаны" };

  return {
    verdict: "сначала доказать",
    said: `нельзя: недоказанных ${unproven.length} (${unproven.slice(0, 3).map((item) => `«${item.text}»`).join(", ")}${unproven.length > 3 ? "…" : ""}) — сначала доказать или заменить`,
  };
}

/**
 * Применить добавление.
 *
 * Возвращает **новый** список: обещание, которое нельзя добавить, не добавляется,
 * и это видно по длине.
 */
export function add(book: Book, text: Promise_, replaces?: string): { book: Book; verdict: string } {
  const decision = mayAdd(book, replaces);
  if (decision.verdict === "сначала доказать") return { book, verdict: decision.said };

  const items = replaces === undefined ? [...book.items, text] : book.items.filter((item) => item.text !== replaces && !item.text.includes(replaces)).concat(text);
  return { book: { items }, verdict: decision.said };
}

/**
 * Что считается доказанным.
 *
 * Два условия, и оба машинные — как в шагах 487 и 492.
 */
export function provenMeans(): string[] {
  return [
    "есть тест с утверждением: вызов без `expect` доказательством не считается",
    "есть приёмка на трёх машинах: «работает у меня» — не приёмка",
  ];
}

/**
 * Чего правило не делает.
 *
 * Три запрета; главный — не запрет развития.
 */
export function notDo(): string[] {
  return [
    "не запрещает развитие: сначала доказать, потом обещать",
    "не считает «в работе» доказательством: в работе — это и есть недоказанное",
    "не позволяет добавлять «в порядке исключения»: исключение — это замена",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три исхода правила.
 */
export function checks(): string[] {
  return [
    "при недоказанных новое не добавляется",
    "замена недоказанного не растит список",
    "замена доказанного тоже не разрешена — заменять нечего",
  ];
}
