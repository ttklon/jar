/**
 * Профиль машины за 3–8 секунд (шаг 61).
 *
 * Дефект. Чтобы выбрать модель, надо знать железо. Без этого остаётся
 * «попробуем 7B» — и на слабом ноутбуке она либо не загрузится, либо будет
 * думать по тридцать секунд на фразу. Человек решит, что приложение медленное,
 * и уйдёт; а дело было в размере модели, выбранном наугад.
 *
 * Правило: **четыре факта за несколько секунд**, и все четыре — из тех, что
 * решают выбор модели.
 *
 *  1. **Ядра** — сколько потоков можно занять. Это прямая скорость на CPU:
 *     у 7B считают токены ядра, а не «видеокарта вообще».
 *  2. **Память** — сколько влезет в неё целиком. Модель, которая не влезла,
 *     начинает свопиться, и это медленнее, чем модель поменьше.
 *  3. **GPU** — есть ли и сколько видеопамяти. Это главный ускоритель; без
 *     него считают на CPU, и это в разы медленнее.
 *  4. **Диск** — не «сколько места», а **насколько быстрый**: модель на 4 ГБ
 *     читается с SSD за секунды, с HDD — за минуту. От этого зависит, будет
 *     ли «первый запуск» ожиданием.
 *
 * Почему 3–8 секунд, а не «замерим всё честно». Замер дисковой скорости честно
 * занимает минуты (чтение большого файла несколько раз). Человек уже согласился
 * ждать 3–8 секунд, потому что видит полосу прогресса; минуту он не ждёт.
 * Поэтому диск определяется **по типу тома**, а не по замеру: это приближение,
 * но оно честно названо приближением.
 */

/** Тип диска: от него зависит, сколько ждать загрузки модели. */
export type Disk = "ssd" | "hdd" | "unknown";

/** Видеокарта: есть ли и сколько видеопамяти. */
export interface Gpu {
  /** Есть ли ускоритель, который умеет считать модель. */
  found: boolean;
  /** Видеопамяти в мегабайтах; 0 — неизвестно или интегрированная. */
  vramMb: number;
  /** Как называется — человеку это нужно, чтобы понять «почему медленно». */
  name: string | null;
}

/** Профиль: то, на что опирается выбор модели. */
export interface Profile {
  /** Логических ядер. */
  cores: number;
  /** Оперативной памяти в мегабайтах. */
  ramMb: number;
  gpu: Gpu;
  disk: Disk;
  /** Когда снят: профиль устаревает (поставили память, подключили eGPU). */
  at: number;
}

/**
 * Сколько памяти нужно самой системе.
 *
 * Модель, занявшая всю память, заставит систему свопиться, и это медленнее
 * любой маленькой модели. Гигабайт с запасом — не роскошь, а условие.
 */
export const FOR_SYSTEM_MB = 1024;

/**
 * Сколько памяти можно отдать модели.
 *
 * **Не половина памяти.** Дефект, который нашёл тест шага 70: на машине с
 * 4 ГБ половина минус гигабайт системе давала 1 ГБ, а самой маленькой модели
 * нужно 1.9 ГБ — и приложение говорило «ничего не помещается», хотя 1.5B там
 * живёт нормально.
 *
 * Правильно — **сколько остаётся после системы**, а не доля: система занимает
 * фиксированное место, а не пропорцию. Половина была осторожностью, которая
 * на слабых машинах превращалась в отказ от работы.
 *
 * `FOR_SYSTEM_MB` и есть эта доля системы; остальное можно отдать модели.
 */
export function forModel(profile: Profile): number {
  return Math.max(0, profile.ramMb - FOR_SYSTEM_MB);
}

/**
 * Умеет ли машина считать модель на видеокарте.
 *
 * Ниже 2 ГБ видеопамяти считать нечего: туда не влезет даже 0.5B в Q4. Такая
 * видеокарта — не ускоритель, и обещать её человеку нельзя.
 */
export function gpuUsable(profile: Profile): boolean {
  return profile.gpu.found && profile.gpu.vramMb >= 2048;
}

/**
 * Класс машины — словами, а не числом.
 *
 * Числа человек не переводит в решения; «слабая» и «сильная» — переводит.
 * Класс нужен для выбора лестницы моделей (шаг 63), а не для красоты.
 */
export type Class = "weak" | "medium" | "strong";

export function grade(profile: Profile): Class {
  const usable = gpuUsable(profile);
  const ramGb = profile.ramMb / 1024;
  if (ramGb >= 32 && usable && profile.gpu.vramMb >= 8192) return "strong";
  // Средняя — если хватает **одного** из двух: памяти или ядер. Требовать и то
  // и другое значит записать в «слабые» машину с 16 ядрами и 8 ГБ, на которой
  // 1.5B пойдёт нормально.
  if (ramGb >= 16 || profile.cores >= 8 || usable) return "medium";
  return "weak";
}

/**
 * Сколько времени займёт загрузка модели этого размера — оценка, названная
 * оценкой.
 *
 * Считаем по типу диска: SSD — 200 МБ/с, HDD — 80 МБ/с (реальный HDD на
 * последовательном чтении редко быстрее). Диск неизвестен — берём SSD:
 * ошибиться в оптимистичную сторону дешевле, чем напугать человека зря.
 */
export function loadSeconds(profile: Profile, sizeMb: number): number {
  const speed = profile.disk === "hdd" ? 80 : 200;
  return Math.max(1, Math.round(sizeMb / speed));
}

/**
 * Что сказать человеку о его машине.
 *
 * Названы **факты и их следствие**, а не только цифры: «8 ядер, 16 ГБ, без
 * видеокарты — считать будет на процессоре, это медленнее» говорит человеку,
 * чего ждать. Голые цифры он не переведёт в ожидание.
 */
export function say(profile: Profile): string {
  const ramGb = Math.round(profile.ramMb / 1024);
  const gpu = gpuUsable(profile)
    ? `видеокарта ${profile.gpu.name ?? "своя"}, ${Math.round(profile.gpu.vramMb / 1024)} ГБ`
    : "видеокарты для модели нет — считать будет на процессоре";
  const disk = profile.disk === "hdd" ? "диск медленный: первый запуск дольше" : "диск быстрый";
  return `${profile.cores} ядер, ${ramGb} ГБ памяти, ${gpu}, ${disk}`;
}

/**
 * Понятно ли, что профиль — **приближение**.
 *
 * Диск определяется по типу тома, а не замером: честнее сказать «примерно»,
 * чем выдать оценку за измерение. Это записано в тексте, а не только в коде.
 */
export function approximate(): string {
  return "диск определён по типу — это оценка, а не замер";
}

/**
 * Не устарел ли профиль.
 *
 * Железо меняют: поставили память, подключили внешнюю видеокарту. Профиль
 * старше суток пересчитывается молча — он дешёвый (3–8 секунд).
 */
export const STALE_MS = 24 * 60 * 60 * 1000;

export function stale(profile: Profile, now: number): boolean {
  return now - profile.at > STALE_MS;
}

/**
 * Собрать профиль из того, что знает движок.
 *
 * Всё здесь — **приближение, названное приближением**:
 *
 *  * ядра — `hardwareConcurrency`, и это логические ядра: физических обычно
 *    вдвое меньше, но для оценки скорости счёта логические и нужны;
 *  * память — `deviceMemory`, и браузер отдаёт её **округлённой** до степени
 *    двойки и ограниченной сверху: точного числа он не показывает никому;
 *  * видеокарта — через WebGL: названия и объёма видеопамяти браузер не даёт,
 *    но отдаёт строку рендерера, а по ней видно, своя это карта или
 *    встроенная;
 *  * диск — по `navigator.connection` его не узнать, поэтому «неизвестен», и
 *    тогда оценка берётся оптимистичная (см. `loadSeconds`).
 *
 * Функция **никогда не бросает**: неизвестный факт — это 0 или «unknown», а не
 * повод не запускаться.
 */
export function measure(now: number): Profile {
  const nav = typeof navigator === "undefined" ? undefined : navigator;
  const cores = Math.max(1, nav?.hardwareConcurrency ?? 1);
  // `deviceMemory` — в гигабайтах, и браузер округляет её до степени двойки.
  const gb = (nav as unknown as { deviceMemory?: number } | undefined)?.deviceMemory;
  const ramMb = gb && gb > 0 ? Math.round(gb * 1024) : 8 * 1024;

  return {
    cores,
    ramMb,
    gpu: readGpu(),
    disk: "unknown",
    at: now,
  };
}

/**
 * Видеокарта через WebGL.
 *
 * Браузер не даёт ни объёма видеопамяти, ни точного имени — только строку
 * рендерера. По ней видно главное: своя карта или встроенная. Встроенной
 * («Intel», «AMD Radeon Graphics», «Apple M») **не обещаем** ускорения: она
 * делит память с системой, и на ней 7B не поедет.
 */
function readGpu(): Gpu {
  if (typeof document === "undefined") return { found: false, vramMb: 0, name: null };
  try {
    const canvas = document.createElement("canvas");
    const gl = canvas.getContext("webgl") as WebGLRenderingContext | null;
    if (!gl) return { found: false, vramMb: 0, name: null };
    const info = gl.getExtension("WEBGL_debug_renderer_info");
    const name = info ? String(gl.getParameter(info.UNMASKED_RENDERER_WEBGL) ?? "") : "";
    const builtIn = /intel|radeon graphics|apple m|microsoft basic/i.test(name);
    if (builtIn) return { found: false, vramMb: 0, name: name.length > 0 ? name : null };
    return { found: name.length > 0, vramMb: 0, name: name.length > 0 ? name : null };
  } catch {
    return { found: false, vramMb: 0, name: null };
  }
}

/**
 * Как часто замерять — по классу машины, а не по константе (шаг 221).
 *
 * Дефект. Профиль управлял выбором модели (`forModel`, `grade`) и на этом
 * заканчивался: интервалы мониторинга были **жёсткие 1000 мс** в четырёх местах
 * (`DownloadBar`, `ReadinessCard`, `Ask`, `Voice`). На слабой машине мониторинг
 * тем самым **сам становится причиной тормозов**: раз в секунду опрос статуса
 * читает диск, считает хеши и шлёт IPC — на двух ядрах и 4 ГБ это заметная доля
 * того, что человек видит как «приложение тормозит».
 *
 * Правила:
 *
 *  * **редко, но заметно.** Слабый класс — раз в 3 с, средний — 1.5 с, сильный —
 *    1 с. Реже 3 с нельзя: прогресс скачивания с шагом 3 с читается как «встало»,
 *    и человек идёт искать другой файл;
 *  * **счётные вещи реже, чем заметные**: таймер разговора должен идти
 *    по-прежнему секундой, а опрос статуса — по классу машины. Смешать их значит
 *    либо врать про длительность разговора, либо грузить слабую машину;
 *  * **на слабой машине человеку сказано**: замеры реже, и это не «подвисает»,
 *    а решение;
 *  * **класс неизвестен — берём средний**: неизвестность не повод ни грузить, ни
 *    заставлять ждать три секунды.
 */

/** Интервалы в миллисекундах. */
export interface Cadence {
  /** Опрос статуса и прогресса — то, что читает диск. */
  poll: number;
  /** Строка прогресса скачивания: заметная вещь, но её можно и пореже. */
  progress: number;
  /** Таймер разговора — секундой всегда: иначе он врёт про длительность. */
  clock: number;
}

/** Частота замеров для класса машины. */
export function cadence(cls: Class | "unknown"): Cadence {
  // Таймер — всегда секундой, независимо от машины: он не измеряет, а считает.
  const clock = 1000;
  if (cls === "weak") return { poll: 3000, progress: 3000, clock };
  if (cls === "strong") return { poll: 1000, progress: 1000, clock };
  // medium и unknown — вместе: неизвестность не повод ни грузить, ни ждать.
  return { poll: 1500, progress: 1500, clock };
}

/**
 * Частота по профилю — сразу, без промежуточного класса.
 *
 * `at` в профиле — время снятия; просроченный профиль не меняет частоту: старый
 * профиль неточен, но не опасен, а спрашивать железо на каждый рендер — хуже.
 */
export function cadenceFor(profile: Profile): Cadence {
  return cadence(grade(profile));
}

/**
 * Что сказать человеку про замеры.
 *
 * Молчаливое «редко» читается как «подвисает». Одна фраза снимает вопрос и
 * заодно объясняет, что это забота, а не поломка.
 */
export function cadenceNote(cls: Class | "unknown"): string {
  if (cls === "weak") {
    return "машина слабая: замеры раз в 3 секунды, чтобы мониторинг не тормозил сам";
  }
  return "";
}

/**
 * Проверка: частота действительно реже на слабой машине и таймер не тронут.
 *
 * Записана рядом с правилом, потому что «профиль управляет частотой» — обещание,
 * которое ломается одной константой в экране.
 */
export function cadenceSane(): { ok: boolean; why: string } {
  const weak = cadence("weak");
  const strong = cadence("strong");
  if (!(weak.poll > strong.poll)) return { ok: false, why: "на слабой машине опрос не реже, чем на сильной" };
  if (weak.clock !== strong.clock) return { ok: false, why: "таймер разговора зависит от машины и врёт про длительность" };
  if (weak.poll < 3000) return { ok: false, why: "прогресс с шагом меньше 3 с читается как «встало»" };
  return { ok: true, why: "" };
}
