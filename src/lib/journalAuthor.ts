/**
 * Шаг 414: журнал показывает, чей профиль выполнил дело.
 *
 * Журнал с автором уже есть (`whoAsked`, шаг 404) — но там автор **попросил**.
 * Здесь вопрос другой: **кто выполнил**. Это не всегда одно и то же:
 *
 *  * Анна попросила общее дело — выполнил профиль Анны;
 *  * Анна попросила, но дело выполнялось по расписанию, когда она уже вышла, —
 *    выполнял профиль того, кто был активен;
 *  * гость попросил чтение — выполнил гостевой профиль;
 *  * и самый неприятный случай: **расписание сработало, а профиль хозяина был
 *    выключен**. Дело не выполняется молча от чьего-то имени: оно ждёт.
 *
 * Поэтому в записи две роли, а не одна: `asked` и `did`. Когда они совпадают —
 * в строке одно имя, когда нет — два, и видно, почему.
 */

/** Запись журнала выполнения. */
export interface Ran {
  readonly what: string;
  /** Кто попросил. */
  readonly asked: string;
  /** Кто выполнил — профиль, от чьего имени шло действие. */
  readonly did: string | null;
  /** Почему не совпало — если не совпало. */
  readonly why?: string;
}

/**
 * Строка журнала.
 *
 * «Анна попросила — выполнил профиль Анны» звучит канцелярски. Если имена
 * совпадают: «почисти загрузки — Анна». Если нет: «почисти загрузки — попросила
 * Анна, выполнил профиль Сына (расписание Анны сработало при её профиле в
 * отпуске)».
 */
export function line(r: Ran): string {
  if (r.did === null) return `${r.what} — попросила ${r.asked}, не выполнено${r.why ? `: ${r.why}` : ""}`;
  if (r.did === r.asked) return `${r.what} — ${r.asked}`;
  return `${r.what} — попросила ${r.asked}, выполнил профиль ${r.did}${r.why ? ` (${r.why})` : ""}`;
}

/**
 * Может ли расписание выполнить дело, когда профиль автора не активен.
 *
 * Ответ — нет, если дело опасное: оно ждёт хозяина (шаг 405: подтверждает только
 * хозяин и лично). Безопасное — может, и тогда автор записывается честно.
 */
export function scheduleWhileAway(asked: string, dangerous: boolean): { runs: boolean; said: string } {
  if (dangerous) {
    return { runs: false, said: `дело ждёт ${asked}: оно опасное, а ${asked} сейчас не за компьютером — от чужого имени опасное не выполняется` };
  }
  return { runs: true, said: `безопасное дело выполнится от профиля «${asked}», даже если он не активен — и в журнале будет видно, чей это профиль` };
}

/**
 * Сводка по людям.
 *
 * «Анна: 12 дел, Сын: 3» — не рейтинг, а понимание, чьи дела занимают машину.
 */
export function byPerson(entries: readonly Ran[]): { name: string; count: number }[] {
  const counts = new Map<string, number>();
  for (const entry of entries) counts.set(entry.did ?? entry.asked, (counts.get(entry.did ?? entry.asked) ?? 0) + 1);
  return [...counts.entries()].map(([name, count]) => ({ name, count })).sort((a, b) => b.count - a.count || a.name.localeCompare(b.name));
}

/**
 * Что журнал не делает.
 *
 * Не «следит за активностью»: он пишет **выполненные дела**, а не то, кто когда
 * подходил к компьютеру.
 */
export function notWatching(): string[] {
  return [
    "не пишет, кто когда вошёл и вышел из профиля: это не дело, а слежка",
    "не ставит оценок: «12 дел» — это работа, а не характеристика человека",
    "не скрывает несовпадение: если попросил один, а выполнил профиль другого, оба имени в строке",
  ];
}
