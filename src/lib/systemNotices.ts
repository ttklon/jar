/**
 * Шаг 442: уведомления Windows вместо собственных всплывашек.
 *
 * Своя всплывашка в правом нижнем углу — это всегда плохо, даже когда красивая:
 *
 *  * она **не попадает в «Центр уведомлений»** — закрыл и забыл, вернуться нельзя;
 *  * она **не уважает «Не беспокоить»** — а это единственный переключатель,
 *    которому человек верит;
 *  * её **нет в истории**, когда приложение закрыто;
 *  * она **выглядит чужой** — не как система, и человек не понимает, откуда она.
 *
 * Поэтому все уведомления идут через систему, а свои всплывашки — только для
 * того, что нельзя откладывать, и таких случаев ровно два: «нужно подтверждение»
 * (дело стоит, пока не ответите) и «вопрос от программы», на который ждём ответа
 * прямо сейчас.
 */

/** Вид уведомления. */
export type Kind = "успех" | "ошибка" | "вопрос" | "пауза" | "отмена";

/** Что отправляем. */
export interface Notice {
  /** Только системное — решается этим полем, а не экраном. */
  readonly system: boolean;
  readonly title: string;
  readonly body: string;
  /** Что будет по нажатию. */
  readonly action: string;
  /** Важность: `высокая` пробивает «Не беспокоить» только у вопросов. */
  readonly urgent: boolean;
}

/**
 * Собрать уведомление.
 *
 * Заголовок — не «ZShelper», а что случилось: в центре уведомлений и так видно,
 * какая программа.
 */
export function notice(kind: Kind, detail: string): Notice {
  switch (kind) {
    case "успех":
      return { system: true, title: "Готово", body: detail, action: "открыть отчёт", urgent: false };
    case "ошибка":
      return { system: true, title: "Не получилось", body: detail, action: "посмотреть, что случилось", urgent: false };
    case "вопрос":
      return { system: true, title: "Нужен ваш ответ", body: detail, action: "ответить", urgent: true };
    case "пауза":
      return { system: true, title: "Расписания на паузе", body: detail, action: "продолжить", urgent: false };
    case "отмена":
      return { system: true, title: "Отменено", body: detail, action: "открыть дело", urgent: false };
  }
}

/**
 * Что делаем, если система уведомления запретила.
 *
 * Не «всё равно показать свою всплывашку»: человек выключил уведомления — значит
 * не хочет. Сообщение появится в окне, когда он его откроет, и в трее.
 */
export function whenBlocked(kind: Kind): string {
  if (kind === "вопрос") return "вопрос останется в окне и в трее: дело не начнётся без ответа, и вы увидите его при следующем открытии";
  return "уведомление не показать, но оно останется в окне и в трее: ничего не потеряется";
}

/**
 * Что система делает лучше нас.
 *
 * Список — для объяснения «почему не своя всплывашка».
 */
export function systemDoes(): string[] {
  return [
    "попадает в «Центр уведомлений»: закрыл — можно вернуться",
    "уважает «Не беспокоить» без нашего участия",
    "видна, даже когда приложение закрыто",
    "выглядит как система, а не как чужое окно",
  ];
}

/**
 * Когда всё же показываем в окне, а не уведомлением.
 *
 * Один случай: окно уже открыто и в фокусе — уведомление дублировало бы.
 */
export function inWindowInstead(windowFocused: boolean): boolean {
  return windowFocused;
}

/**
 * Что уведомление не делает.
 *
 * Три запрета — про назойливость.
 */
export function notDo(): string[] {
  return [
    "не дублирует то, что уже видно в открытом окне",
    "не показывает успех на каждое дело: уведомление о каждом деле — это шум",
    "не пробивает «Не беспокоить» ничем, кроме вопроса, на который ждём ответа",
  ];
}
