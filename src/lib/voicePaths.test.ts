import { describe, expect, it } from "vitest";
import { behaviourFor, command } from "./stopWords";
import { dispose, isNoise } from "./nonsense";
import { before } from "./beforeDoing";

/**
 * Шаг 50: шум, пауза и перебивание — **три разных** результата.
 *
 * Требование прямолинейное, а проваливается чаще всего: три разных входа легко
 * свести к двум исходам («отправили» / «не отправили»), и тогда:
 *
 *  * кашель звучит как «ничего не услышал» — человек думает, что микрофон сломан;
 *  * пауза превращается в шум — человек ждёт, а приложение молчит;
 *  * перебивание уходит как просьба — приложение выполняет «подожди».
 *
 * Здесь проверяется и различие, и общее: **ни одно из трёх не отправляется как
 * задача**. Это две разные вещи, и обе обязательны.
 */

describe("три входа — три разных результата", () => {
  it("шум, пауза и перебивание ведут в разные стороны", () => {
    // Три **разных** ответа, а не один. Проверяется именно различие: свёл к
    // одному — значит сломал одно из трёх.
    const noise = dispose("кхм");
    const silence = dispose("   ");
    // Перебивание — не «распознанный текст», а команда: свой разбор.
    const interrupt = command("подожди");

    expect(noise).toBe("noise");
    expect(silence).toBe("silence");
    expect(interrupt).toBe("interrupt");
    expect(new Set([noise, silence, interrupt]).size).toBe(3);
  });

  it("ни одно из трёх не отправляется как задача", () => {
    // Это и есть «один тест на «ничего не отправилось»» из плана.
    const sent: string[] = [];
    const send = (text: string) => sent.push(text);

    for (const heard of ["кхм", "   ", "подожди"]) {
      // Обычный путь отправки — только когда ничего особенного не услышали.
      if (dispose(heard) === "send" && command(heard) === null) send(heard);
    }

    expect(sent).toEqual([]);
  });

  it("а обычная фраза — отправляется", () => {
    // Обратная проверка: правило не должно глотать всё подряд.
    expect(dispose("создай папку")).toBe("send");
    expect(command("создай папку")).toBeNull();
  });

  it("перебивание разбирается до исполнения, а не после", () => {
    // «Подожди» — не текст для исполнения: это сначала остановка и слушание
    // дальше. Если разбирать после, приложение уже начнёт выполнять «подожди».
    expect(behaviourFor("подожди")?.listenOn).toBe(true);
    expect(behaviourFor("подожди")?.halt).toBe(false);
    // А «стоп» — наоборот, и это видно в том же месте.
    expect(behaviourFor("стоп")?.halt).toBe(true);
  });

  it("шум не путается с паузой по ответу", () => {
    // Разные новости: в первом случае человек что-то сказал (кашель), во втором
    // молчал. Один ответ на оба — это дефект, от которого шаг и лечит.
    expect(isNoise("кхм")).toBe(true);
    expect(isNoise("")).toBe(true); // оба не фраза…
    expect(dispose("кхм")).not.toBe(dispose("")); // …но новости разные
  });

  it("решение «спрашивать ли» не мешает трём исходам", () => {
    // Даже если действие опасное, шум и пауза не доходят до вопроса: спрашивать
    // не о чем, фразы нет.
    expect(before({ text: "", irreversible: true, broad: true, confidence: null }).kind).toBe("ask");
    expect(dispose("кхм")).toBe("noise");
  });
});
