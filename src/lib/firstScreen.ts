/**
 * Шаг 379: нет дел — три примера фраз и поле ввода. Не пусто.
 *
 * Пустой экран с полем ввода — это «догадайся сам, что я умею». Человек не знает
 * ни словаря, ни границ: можно ли попросить «разбери загрузки»? а «напиши маме»?
 * Три примера отвечают на это без инструкции.
 *
 * Какие три — не любые. Они должны:
 *
 *  * **показать разное**: безобидное дело, дело с файлами и дело по расписанию —
 *    иначе человек решит, что программа умеет один жанр;
 *  * **быть настоящими**: фраза, которую программа правда выполнит, а не
 *    «попробуйте написать что-нибудь»;
 *  * **не пугать**: первым — самое безопасное (чтение), а не удаление.
 *
 * И поле ввода **сразу активно**: человек может не читать примеры, а начать
 * печатать.
 */

/** Пример фразы. */
export interface Example {
  readonly said: string;
  /** Что будет — чтобы человек понимал, прежде чем нажать. */
  readonly what: string;
  readonly kind: "safe" | "files" | "schedule";
}

/**
 * Три примера.
 *
 * Порядок не случаен: самое безопасное первым. Пример «удали всё» первым — это
 * приглашение удалить всё.
 */
export function examples(): Example[] {
  return [
    { said: "сколько места на диске", what: "посмотрю и скажу — ничего не меняю", kind: "safe" },
    { said: "почисти загрузки от старых файлов", what: "покажу список до удаления и спрошу", kind: "files" },
    { said: "проверяй место на диске каждый день в 9 утра", what: "создам расписание; запускать буду только с вашего согласия", kind: "schedule" },
  ];
}

/** Что видно на пустом экране. */
export interface Screen {
  /** Поле активно без «начните с примера». */
  readonly input: boolean;
  /** Подсказка над полем. */
  readonly hint: string;
  readonly examples: readonly Example[];
  /** Кнопку «Начать» не показываем: нажимать надо «Выполнить» рядом с фразой. */
  readonly startButton: boolean;
}

/**
 * Собрать экран.
 *
 * Имя человека, если известно, — иначе без обращения: «Анна, что сделать?» лучше,
 * но «что сделать?» честнее, чем «Пользователь».
 */
export function screen(name?: string): Screen {
  const who = name && name.trim() !== "" ? `${name.trim()}, ` : "";
  return {
    input: true,
    hint: `${who}что сделать? Можно своими словами — я переспрошу, если не пойму`,
    examples: examples(),
    startButton: false,
  };
}

/**
 * Что проверяет пустой экран.
 *
 * Список — перечень проверок к шагу: пустота, догадка, страшный первый пример.
 */
export function checks(s: Screen): string[] {
  const problems: string[] = [];
  if (!s.input) problems.push("поле ввода неактивно: человек должен начать с примера, хотя может начать печатать");
  if (s.examples.length !== 3) problems.push(`примеров ${s.examples.length}, а нужно три: один жанр — это ложное обещание`);
  if (s.startButton) problems.push("кнопка «Начать» рядом с полем: фраза отправляется «Выполнить», а не начинается");
  if (s.examples[0] && s.examples[0].kind !== "safe") problems.push("первый пример не самый безопасный: приглашение нажать опасное");
  if (new Set(s.examples.map((e) => e.kind)).size !== s.examples.length) problems.push("примеры одного жанра: программа выглядит умеющей меньше, чем умеет");
  return problems;
}

/**
 * Что примеры не делают.
 *
 * Не выполняются от нажатия на пример: пример подставляет фразу в поле, и человек
 * её видит перед запуском.
 */
export function notRun(): string {
  return "нажатие на пример подставляет фразу в поле, а не выполняет её: человек сначала видит, что попросит";
}
