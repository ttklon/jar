/**
 * Первое слово ответа — раньше, чем полный план (шаг 128).
 *
 * Дефект. Приложение **молчит, пока не готов весь ответ**:
 *
 *  * **человек не знает, услышали ли его**: 3 секунды тишины — это «сломалось» или
 *    «думает»? Ответа нет ни на это, ни на «что происходит»;
 *  * **молчание тянет за собой повтор**: человек говорит фразу снова, и теперь две
 *    фразы в очереди;
 *  * **первое слово приходит вместе с последним**: «делаю» и отчёт о сделанном — это
 *    разные факты, но произносятся одновременно, и первый бесполезен;
 *  * **намерение не названо**: даже когда ясно, что делать (реестр знает действие),
 *    человек ждёт модель — хотя «переименовываю» известно сразу.
 *
 * Правило: **сначала сказать «делаю», потом делать**.
 *
 *  1. **Первое слово — сразу**, до плана: оно отвечает на «услышал ли», а не на «что
 *     получилось».
 *  2. **Оно честное**: «разбираю» — если ещё непонятно; «переименовываю» — если
 *     действие уже известно из реестра. Не «сейчас всё будет».
 *  3. **Оно короткое**: одно слово-дело, а не пересказ плана — план ещё не готов.
 *  4. **Оно не отменяет второе**: полный ответ приходит следом, и первое слово не
 *     подменяет его.
 *  5. **Если сразу ясно, что не смогу** — первое слово и есть отказ: «не умею» лучше,
 *     чем «делаю» и потом «не смог».
 *
 * Почему не «показать спиннер». Спиннер говорит «что-то происходит», но не говорит,
 * **что** — а человеку нужно знать, услышали ли его и правильно ли поняли.
 */

/** Что сказать первым словом. */
export interface First {
  /** Само слово/фраза — то, что произносится сразу. */
  word: string;
  /** Известно ли уже, что именно делать (а не «разбираюсь»). */
  known: boolean;
  /** Не отказ ли это. */
  refuse: boolean;
}

/**
 * Первое слово по фразе и реестру.
 *
 * `verb` — глагол действия, если реестр уже узнал его; `null` — ещё не узнан.
 */
export function first(verb: string | null, refuse = false): First {
  if (refuse) {
    // «Не умею» лучше, чем «делаю» и потом «не смог».
    return { word: "не умею", known: true, refuse: true };
  }
  if (verb === null || verb.trim() === "") {
    // Честно: ещё непонятно, что именно, — но услышал.
    return { word: "разбираю", known: false, refuse: false };
  }
  // Одно слово-дело: «переименовываю», а не «сейчас переименую все фото».
  return { word: form(verb), known: true, refuse: false };
}

/**
 * Глагол → «что я делаю».
 *
 * Не «переименовать» (это план), а «переименовываю» (это сейчас).
 */
export function form(verb: string): string {
  const clean = verb.trim().toLowerCase();
  if (clean === "") return "делаю";
  // -овать → -овываю (переименовать → переименовываю): правило раньше общего -ать,
  // иначе «переименоваю» — не по-русски.
  if (/овать$/.test(clean)) return `${clean.slice(0, -5)}овываю`;
  // -ыть → -ываю: откры-ть → открыв-аю (а не «открю»).
  if (/ыть$/.test(clean)) return `${clean.slice(0, -3)}ываю`;
  // -ить → -яю: провер-ить → провер-яю (а не «проверю» — это будущее, а не сейчас).
  if (/ить$/.test(clean)) return `${clean.slice(0, -3)}яю`;
  // Глаголы на -ать/-ять → -аю/-яю; на -ить/-еть → -ю; остальное — как есть.
  if (/ать$/.test(clean)) return `${clean.slice(0, -3)}аю`;
  if (/ять$/.test(clean)) return `${clean.slice(0, -3)}яю`;
  if (/еть$/.test(clean)) return `${clean.slice(0, -3)}ю`;
  if (/ыть$/.test(clean)) return `${clean.slice(0, -3)}ю`;
  return clean;
}

/**
 * Можно ли сказать первое слово **сейчас**.
 *
 * Сразу — да: это и есть смысл шага. Первое слово не ждёт плана.
 */
export function canSayNow(planReady: boolean): boolean {
  // Параметр оставлен нарочно: он показывает, что ответ **не** зависит от плана, и
  // это видно глазами в вызывающем коде.
  void planReady;
  return true;
}

/**
 * Что сказать, если первое слово запоздало.
 *
 * Если план уже готов, а первое слово ещё не сказано — говорить его поздно: «делаю»
 * после «сделал» звучит как ошибка.
 */
export function late(got: First, planReady: boolean): string {
  if (!planReady) return got.word;
  // Позднее первое слово не произносится: оно уже неправда.
  return "";
}

/**
 * Не выдаёт ли первое слово обещание, которого нет.
 *
 * «Сейчас всё будет» — обещание; «разбираю» — факт. Функция нужна, чтобы это было
 * проверяемо, а не «на глаз».
 */
export function honest(got: First): boolean {
  const word = got.word.toLowerCase();
  if (/(будет|сейчас всё|минут|подожди|подождите|скоро)/.test(word)) return false;
  return got.known || word === "разбираю";
}

/**
 * Последовательность: первое слово, потом полное.
 *
 * Возвращает **порядок**, а не текст: важно, что первое слово идёт раньше, даже если
 * полный ответ уже готов к моменту вывода.
 */
export function order(got: First, full: string): string[] {
  const spoken = late(got, false);
  return spoken === "" ? [full] : [spoken, full];
}

/**
 * Сколько человек ждал первого слова.
 *
 * Отдельно от общего времени: первое слово — про «услышали ли», и его задержка
 * считается сама по себе (бюджет — шаг 123).
 */
export function waited(startedAt: number, firstAt: number | null): { ms: number | null; said: string } {
  if (firstAt === null) return { ms: null, said: "первого слова не было — человек не знал, услышали ли его" };
  const ms = firstAt - startedAt;
  return { ms, said: `первое слово через ${Math.round(ms)} мс` };
}
