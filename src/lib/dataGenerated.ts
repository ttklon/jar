/**
 * Шаг 490: изменение данных без генерации валит сборку — дисциплина данных.
 *
 * Часть файлов в `data/` и `docs/` **производная**: их пишут генераторы
 * (`tools/*.py`). Человек может поправить такой файл руками — и он будет прав до
 * следующей генерации, а потом правка исчезнет молча. Или наоборот: генератор
 * изменился, файл не перегенерировали, и в репозитории старый.
 *
 * Проверка одна и строгая: **для каждого производного файла перегенерировать и
 * сравнить**. Разница — красное, с именем файла и командой, которой перегенерировать.
 *
 * Это и есть дисциплина: не «помни про генерацию», а «забыл — сборка не пустит».
 */

/** Производный файл. */
export interface Generated {
  /** Путь. */
  readonly path: string;
  /** Генератор — команда или скрипт в `tools/`. */
  readonly by: string;
  /** Что в файле сейчас. */
  readonly current: string;
  /** Что генератор выдаёт сейчас. */
  readonly fresh: string;
}

/**
 * Сравнить.
 *
 * Возвращает **пути и команды**: «data/report.json — перегенерируйте
 * `python3 tools/report_snapshot.py --write`». Без команды сообщение бесполезно.
 */
export function stale(items: readonly Generated[]): string[] {
  return items
    .filter((item) => item.current !== item.fresh)
    .map((item) => `${item.path}: не перегенерирован — запустите ${item.by}`);
}

/**
 * Правлен ли файл руками.
 *
 * Признак — не «кто правил» (этого не видно), а **совпадение с прошлой
 * генерацией**: если текущее содержимое равно тому, что генератор выдавал раньше,
 * а свежее другое — значит правили генератор, а файл забыли. Если текущее не равно
 * ни тому, ни другому — файл правили руками.
 */
export function handEdited(item: Generated, previous: string): boolean {
  return item.current !== previous && item.current !== item.fresh;
}

/**
 * Сводка.
 *
 * Три числа: сколько производных, сколько в порядке, сколько руками.
 */
export function summary(items: readonly Generated[], previous: ReadonlyMap<string, string>): { ok: boolean; said: string } {
  const bad = stale(items);
  const manual = items.filter((item) => handEdited(item, previous.get(item.path) ?? "")).map((item) => item.path);

  if (bad.length === 0) return { ok: true, said: `производных ${items.length}: все совпадают с генератором` };

  const why = manual.length > 0 ? ` Правлены руками: ${manual.join(", ")} — правка исчезнет при генерации.` : "";
  return { ok: false, said: bad.join("; ") + why };
}

/**
 * Что делать, если файл правили руками.
 *
 * Два исхода: правка настоящая (тогда её вносят в генератор) или случайная (тогда
 * перегенерировать).
 */
export function ifManual(): string[] {
  return [
    "правка настоящая — вносится в **генератор**, а не в файл: иначе исчезнет",
    "правка случайная — перегенерировать и не вспоминать",
    "третий вариант не рассматривается: файл, который правят и руками, и генератором, всегда расходится",
  ];
}

/**
 * Чего проверка не делает.
 *
 * Три запрета; главный — не «обновить файл, чтобы стало зелено».
 */
export function notDo(): string[] {
  return [
    "не правит производный файл, чтобы сравнение сошлось: это та же ручная правка",
    "не пропускает файл «он редко меняется»",
    "не держит производный файл без генератора: тогда это не производный, а ручной",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу случаев.
 */
export function checks(): string[] {
  return [
    "каждый производный файл сверяется с генератором",
    "расхождение называет файл и команду",
    "файл, правленный руками, назван отдельно от забытого",
  ];
}
