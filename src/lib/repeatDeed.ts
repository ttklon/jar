/**
 * Повтор дела: показать, что изменится, и спросить один раз (шаг 107).
 *
 * Дефект. «Повторить» выглядит как одна кнопка и обещает то же самое — а на деле
 * повтор **другого дела**, и это выясняется после:
 *
 *  * **повтор сюрпризом**: файлы с прошлого раза изменились, и то же действие
 *    теперь заденет не то — человек узнаёт об этом по результату;
 *  * **повтор спрашивает дважды**: сначала «повторить?», потом «вы уверены?», и на
 *    второй вопрос человек жмёт «да» не читая, потому что уже ответил;
 *  * **повтор молчит о том, что уже сделано**: вчерашние 12 файлов на месте, и
 *    повтор переименовывает их второй раз;
 *  * **повтор обещан там, где его нет**: скачивание и распознавание повторяются
 *    по своим правилам, а кнопка одна.
 *
 * Правило: **одно согласие — на показанную разницу**.
 *
 *  1. **Сначала разница, потом вопрос**: «с прошлого раза изменилось: файлов 12 →
 *     15, папка та же» — и только после этого «повторить?».
 *  2. **Один вопрос, а не два**. Второй «вы уверены» обесценивает первый: на него
 *     отвечают не читая.
 *  3. **Уже сделанное названо**: «8 файлов уже переименованы — их повтор не
 *     тронет».
 *  4. **Повтор не обещан там, где его нет**: причина названа, а кнопка не врёт.
 *  5. **Ничего не изменилось — сказано прямо**: «повтор ничего не изменит», и это
 *     отдельный, хороший ответ, а не повод промолчать.
 *
 * Почему не «просто повторить то же». То же действие на изменившихся данных — это
 * **другое действие**, и согласие на прошлое к нему не относится (шаг 102: согласие
 * привязано к параметрам).
 */

/** Что было в прошлый раз и что сейчас — по одному предмету. */
export interface Before {
  /** Что за предмет: «файлов в Загрузках». */
  what: string;
  /** Сколько было в прошлый раз. `null` — прошлого дела нет, и это сказано. */
  then: number | null;
  /** Сколько сейчас. `null` — посчитать не удалось, и это сказано. */
  now: number | null;
}

/** Что изменилось с прошлого раза. */
export interface Delta {
  what: string;
  then: number | null;
  now: number | null;
  /** Словами: «было 12, стало 15» или «посчитать не удалось». */
  said: string;
  /** Изменилось ли настолько, что повтор — уже другое действие. */
  changed: boolean;
}

/**
 * Разница по одному предмету.
 *
 * `null` — не «ноль»: «посчитать не удалось» и «файлов не осталось» — разные
 * факты, и путать их значит молча согласиться на неизвестное.
 */
export function delta(item: Before): Delta {
  if (item.then === null) {
    // Сравнивать не с чем — это факт, а не «изменилось» и не «то же самое».
    return {
      what: item.what,
      then: null,
      now: item.now,
      said: `${item.what}: сравнивать не с чем — прошлого дела нет, сейчас ${item.now ?? "не посчитать"}`,
      changed: item.now !== null,
    };
  }
  if (item.now === null) {
    return {
      what: item.what,
      then: item.then,
      now: null,
      said: `${item.what}: было ${item.then}, сейчас посчитать не удалось`,
      // Неизвестное считается изменившимся: согласие дают на известное.
      changed: true,
    };
  }
  const changed = item.now !== item.then;
  return {
    what: item.what,
    then: item.then,
    now: item.now,
    said: changed ? `${item.what}: было ${item.then}, стало ${item.now}` : `${item.what}: ${item.now}, как в прошлый раз`,
    changed,
  };
}

/** Что предложить человеку перед повтором. */
export interface Offer {
  /** Спросить ли вообще: `false` — повторять нечего или нельзя. */
  ask: boolean;
  /** Что будет сделано — одной строкой, до вопроса. */
  preview: string;
  /** Единственный вопрос, который задаётся. */
  question: string;
  /** Почему нельзя повторить; пусто, если можно спрашивать. */
  why: string;
}

/**
 * Предложение повтора.
 *
 * Один вопрос на показанную разницу. Если разница пуста — «повтор ничего не
 * изменит», и это тоже ответ, а не молчание.
 */
export function offer(items: readonly Before[], canRepeat: boolean, why = ""): Offer {
  if (!canRepeat) {
    // Кнопка не врёт: причина названа, и её не прячут за «недоступно».
    return { ask: false, preview: "", question: "", why: why || "это дело не повторяется тем же планом" };
  }
  const deltas = items.map(delta);
  const changed = deltas.filter((item) => item.changed);
  const preview =
    changed.length === 0
      ? "повтор ничего не изменит: всё как в прошлый раз"
      : changed.map((item) => item.said).join("; ");

  return {
    ask: true,
    preview,
    question: "повторить?",
    why: "",
  };
}

/**
 * Уже сделанное.
 *
 * Названо до вопроса: иначе повтор молча делает работу второй раз, а человек
 * считает, что продолжает вчерашнюю.
 */
export function already(done: number, total: number, what: string): string {
  if (done <= 0) return "";
  if (done >= total) return `${what}: уже сделано всё (${done} из ${total}) — повторять нечего`;
  return `${what}: уже сделано ${done} из ${total} — повтор их не тронет`;
}

/**
 * Что делать после ответа.
 *
 * Ровно два исхода и **никакого второго вопроса**: «да» — это да.
 */
export function decide(yes: boolean, got: Offer): { run: boolean; said: string } {
  if (!got.ask) return { run: false, said: got.why };
  if (!yes) return { run: false, said: "не повторяю" };
  return { run: true, said: `повторяю — ${got.preview}` };
}
