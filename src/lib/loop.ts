import { DEEDS_PER_HOUR, type QueueItem } from "./queue";

/**
 * Петля улучшения: **сделать — посмотреть — поправить**.
 *
 * Зачем она. «Доведи проект до максимума, пока я не скажу стоп» — это не одно дело, а
 * много дел подряд, и разница между работой и топтанием на месте видна только тому, кто
 * после каждого круга смотрит, изменилось ли что-нибудь. Поэтому здесь три роли и ни одной
 * лишней:
 *
 *  * **сделать** — очередное дело берётся так же, как любое другое: тот же план, та же
 *    политика, то же подтверждение. Петля не даёт ни одного нового права — она решает
 *    только, когда спросить модель про следующее дело;
 *  * **посмотреть** — по отчёту видно, что действительно сделалось: план дошёл до конца,
 *    сделался наполовину или не сделалось ничего. Это не оценка «стало лучше», а факт;
 *  * **поправить** — на сбой даётся **одна** поправка. Не потому что жалко, а потому что
 *    вторая такая же поправка после первой неудачи — это уже долбёжка.
 *
 * Правила, по которым петля останавливается, важнее самого цикла:
 *
 *  * **«стоп» человека** — первое и последнее слово, до всего остального;
 *  * **памяти на исходе** — не начинаем новое (это «нет», а не «помедленнее»);
 *  * **потолок в час выбран** — продолжение после него, а не «ещё чуть-чуть»;
 *  * **круг ничего не изменил, и поправка тоже** — топчемся: говорим это и отдаём человеку,
 *    вместо того чтобы крутиться бесконечно;
 *  * **дважды не удалось довести до конца** — тоже человеку: петля не умеет чинить то,
 *    чего не понимает.
 *
 * Здесь нет ни одного запуска и ни одного вопроса к модели: модуль только решает, что
 * делать дальше, а делает вызывающий. Так правило можно проверить без машины, без окон и
 * без человека — и видно, что решает правило, а не настроение.
 */

/** Что показал «посмотреть» после круга. */
export type Look =
  /** План дошёл до конца: обещанное сделано. */
  | "done"
  /** Сделалась часть — значит, есть что поправить. */
  | "part"
  /** Не сделалось ничего: поправлять пока нечего, надо менять подход. */
  | "nothing";

/** Итог одного круга так, как его видно по отчёту ядра. */
export interface RoundOutcome {
  /** Сколько шагов отчиталось «сделано». */
  completed: number;
  /** Сколько шагов было в плане. */
  steps: number;
  /** Чем кончился прогон. `null` — план дошёл до конца. */
  stopped: string | null;
}

/**
 * Что показал круг. Считаем по отчёту, а не по обещаниям: «запуск прошёл» без единого
 * сделанного шага — это не сделано, а пустая работа, и называть её успехом нельзя.
 */
export function look(round: RoundOutcome): Look {
  if (round.completed === 0) return "nothing";
  if (round.stopped === null && round.completed === round.steps) return "done";
  return "part";
}

/**
 * Сколько поправок даётся на один сбой.
 *
 * Одна. Поправка — это шанс, что помеха была случайной (файл был занят, окно не успело
 * открыться), а не способ повторять одно и то же, пока не повезёт.
 */
export const MAX_FIX_TRIES = 1;

/** Что известно петле перед очередным шагом. */
export interface LoopState {
  /** Что показали уже сделанные круги — по порядку. */
  rounds: readonly Look[];
  /**
   * Сколько поправок уже потрачено на **текущий** сбой.
   *
   * Счёт сбрасывается удачным кругом: новый сбой — новая поправка. Иначе петля
   * запомнила бы одну осечку навсегда и после неё отдавала бы человеку каждый
   * следующий сбой, хотя чинить их она умеет.
   */
  fixes: number;
  /** Человек сказал «стоп». */
  stopped: boolean;
  /** Сколько дел ещё можно начать в этом часу. */
  left: number;
  /** Разрешает ли машина начинать новое. */
  mayStart: boolean;
}

/** Что делать дальше: спросить следующее улучшение, поправить сбой или остановиться. */
export interface LoopStep {
  action: "ask" | "fix" | "stop";
  /** Почему так — словами. Молчаливая остановка неотличима от поломки. */
  why: string;
}

/**
 * Шаг петли.
 *
 * Порядок проверок — это и есть приоритет: слово человека, потом машина, потом счёт, и
 * только затем работа. Если поменять местами, петля научится уговаривать: «ещё один круг,
 * память всё равно почти свободна».
 */
export function step(state: LoopState): LoopStep {
  if (state.stopped) {
    return { action: "stop", why: "остановлено вами: новых кругов не начинаю" };
  }

  if (!state.mayStart) {
    return {
      action: "stop",
      why: "машина просит не начинать: памяти на исходе — это «нет», а не «помедленнее»",
    };
  }

  if (state.left <= 0) {
    return {
      action: "stop",
      why: `потолок ${DEEDS_PER_HOUR} дел в час выбран: следующий круг — после него`,
    };
  }

  const last = state.rounds[state.rounds.length - 1];
  if (last === undefined) {
    return { action: "ask", why: "первый круг: спрашиваю, что улучшить" };
  }

  if (last === "done") {
    return {
      action: "ask",
      why: `круг ${state.rounds.length} сделан — спрашиваю следующее улучшение`,
    };
  }

  const round = state.rounds.length;

  if (state.fixes >= MAX_FIX_TRIES) {
    return {
      action: "stop",
      why:
        last === "nothing"
          ? `круг ${round} ничего не изменил, и поправка тоже — топчемся на месте: дальше нужны вы`
          : `круг ${round} опять сделался наполовину — поправка не помогла: дальше нужны вы`,
    };
  }

  return {
    action: "fix",
    why:
      last === "nothing"
        ? `круг ${round} ничего не изменил — одна поправка, а не десять`
        : `круг ${round} сделался наполовину — поправляю то, что осталось`,
  };
}

/**
 * Вопрос модели про поправку.
 *
 * Отличие от продолжения по цели: здесь модель видит, **что именно не сделалось**, и
 * отвечает не «что улучшить завтра», а «чем заменить то, что не вышло». Один-два шага, а
 * не «переделай проект целиком»: переделка целого после одной осечки — это не поправка.
 */
export function fixQuery(origin: string, items: readonly QueueItem[]): string {
  const lines = items
    .filter((item) => item.origin === origin && (item.state === "failed" || item.state === "held"))
    .map((item) => {
      const verdict = item.state === "failed" ? "не вышло" : "нужно слово человека";
      return `— ${item.goal}: ${verdict}${item.note ? ` (${item.note})` : ""}`;
    });

  return [
    `Цель: «${origin}». Очередной круг не удался.`,
    "Что было:",
    ...lines,
    "Предложи одно-два дела, которые исправляют именно это, а не переделывают всё заново.",
    "Если исправить нельзя без человека — так и скажи, без новых дел.",
  ].join("\n");
}

/**
 * Строка счёта по цели для экрана: сколько кругов и чем кончился последний.
 *
 * Счёт ведётся по кругам, а не по времени: «четыре круга, последний ничего не изменил»
 * человек может проверить, а «работаю уже давно» — нет.
 */
export function roundLine(origin: string, rounds: readonly Look[]): string {
  const last = rounds[rounds.length - 1];
  if (rounds.length === 0) return `цель «${origin}»: кругов ещё не было`;
  const done = rounds.filter((result) => result === "done").length;
  const verdict =
    last === "done"
      ? "последний сделан"
      : last === "part"
        ? "последний сделался наполовину"
        : "последний ничего не изменил";
  return `цель «${origin}»: кругов ${rounds.length}, из них сделано ${done} — ${verdict}`;
}
