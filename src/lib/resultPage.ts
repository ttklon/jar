/**
 * Шаг 499: показать результат человеку — одна страница «что теперь работает»
 * и честный список «что нет».
 *
 * Итог проекта нельзя показывать таблицей из пятисот строк: её не читают. Нужна
 * **одна страница**, и на ней две половины, и обе обязательны:
 *
 *  * **что работает** — то, что человек может сделать сейчас, на своём компьютере;
 *  * **что нет** — то же честно, с причиной (шаг 465), и это не мелкий шрифт внизу.
 *
 * Первая половина без второй — реклама. Вторая без первой — отчёт о неудачах. Вместе
 * они дают то, ради чего всё делалось: **человек знает, что получит, и не
 * разочаруется**.
 *
 * И правило про числа: «500 шагов» — это про работу, а не про человека. Человеку
 * важны **вещи**, которые он может сделать, поэтому считаются они.
 */

/** Что теперь работает. */
export interface Works {
  /** Что человек может сделать. */
  readonly can: string;
  /** Как это выглядит для него — одна фраза. */
  readonly sees: string;
}

/** Что не работает — с причиной. */
export interface Doesnt {
  /** Чего не будет. */
  readonly cant: string;
  /** Почему — не «не поддерживается». */
  readonly why: string;
}

/**
 * Проверить страницу.
 *
 * Нарушения: нет «что нет» вовсе, у «что нет» нет причины, «что работает» описано
 * словами реализации, а не тем, что видит человек.
 */
export function check(works: readonly Works[], doesnt: readonly Doesnt[]): string[] {
  const problems: string[] = [];

  if (works.length === 0) problems.push("не сказано, что работает: страница ничего не показывает");
  if (doesnt.length === 0) problems.push("нет списка «что нет»: страница превращается в рекламу");

  for (const item of works) {
    // Длина — не признак: «вызов clean()» длинное, но это реализация, а не то,
    // что видит человек. Поэтому ловим и слова из кода.
    const sees = item.sees.trim();
    if (sees.length < 10 || /вызов|вызывается|функци|метод|pars|clean\(|state\./i.test(sees)) {
      problems.push(`«${item.can}»: «${sees}» — описание реализации, а не то, что видит человек`);
    }
  }
  for (const item of doesnt) {
    if (item.why.trim().length < 15 || /не поддерживается|в будущих версиях|пока нет/i.test(item.why)) {
      problems.push(`«${item.cant}»: причина «${item.why}» — оправдание, а не причина`);
    }
  }

  return problems;
}

/**
 * Страница целиком.
 *
 * Две половины, и «что нет» — не сноской, а таким же разделом.
 */
export function page(works: readonly Works[], doesnt: readonly Doesnt[]): string {
  const lines = ["# Что теперь работает", ""];

  lines.push(`Работает (${works.length}):`, "");
  for (const item of works) lines.push(`- **${item.can}** — ${item.sees}`);

  lines.push("", `Не работает (${doesnt.length}) — и почему:`, "");
  for (const item of doesnt) lines.push(`- **${item.cant}** — ${item.why}`);

  return lines.join("\n");
}

/**
 * Про что страница не говорит.
 *
 * Одно число, которого на странице нет: шаги плана. Человеку они не нужны.
 */
export function noStepNumbers(): string {
  return "на странице нет числа шагов: «сделано 500» — это про работу, а человеку важно, что он может сделать";
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "две половины: что работает и что нет",
    "у «что нет» причина, а не «не поддерживается»",
    "считаются вещи, а не шаги",
  ];
}

/**
 * Чего страница не делает.
 *
 * Три запрета; главный — не реклама.
 */
export function notDo(): string[] {
  return [
    "не прячет «что нет» в сноску или мелкий шрифт",
    "не считает шаги достижением человека",
    "не пишет «скоро»: срок без доказательства — обещание, которого не будет",
  ];
}
