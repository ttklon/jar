/**
 * Шаг 477: у всех документов есть дата и область проверки.
 *
 * Документ без даты читается как **сегодняшний**, даже если ему два года. Человек
 * не может отличить «так и есть» от «так было» — и проверяет всё сам, то есть не
 * доверяет документу.
 *
 * Поэтому у каждого документа в шапке две вещи:
 *
 *  * **дата проверки** — когда человек (или генератор) последний раз сверял его с
 *    кодом;
 *  * **область** — что именно сверено, а что нет. «Проверено: клавиши, установка.
 *    Не проверено: работа на Windows 10» — честнее, чем «актуально».
 *
 * И порог: документ, не проверенный дольше **90 дней**, помечается в CI — не
 * удаляется, а получает видимую строку «не проверялся с …».
 */

/** Документ с датой. */
export interface Doc {
  /** Путь. */
  readonly path: string;
  /** Дата проверки `YYYY-MM-DD`. */
  readonly at: string;
  /** Что сверено. */
  readonly scope: string;
  /** Что не сверено — необязательно, но лучше, чем молчать. */
  readonly notScope?: string;
}

/** Сколько дней документ считается свежим. */
export const FRESH_DAYS = 90;

/** Разбор даты — тот же, что у остальных модулей: строка `YYYY-MM-DD`. */
export function days(date: string): number | null {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return null;
  const ms = Date.parse(`${date}T00:00:00Z`);
  return Number.isNaN(ms) ? null : ms / 86_400_000;
}

/**
 * Что не так с документом.
 *
 * Нарушения: нет даты, дата не по форме, нет области, область — «актуально».
 */
export function check(doc: Doc): string[] {
  const problems: string[] = [];

  if (days(doc.at) === null) problems.push(`«${doc.path}»: даты нет или она не по форме ГГГГ-ММ-ДД`);
  if (doc.scope.trim().length < 10) problems.push(`«${doc.path}»: область проверки короче десяти знаков`);
  if (/^(актуально|проверено|всё ок|в порядке)$/i.test(doc.scope.trim())) problems.push(`«${doc.path}»: «${doc.scope}» — не область: что именно сверено?`);

  return problems;
}

/**
 * Устаревшие документы — на дату `today`.
 *
 * Возвращает пути с числом дней: «docs/GUIDE.md: 127 дней».
 */
export function stale(docs: readonly Doc[], today: string): string[] {
  const now = days(today);
  if (now === null) return [`«${today}» — не дата: сравнивать не с чем`];

  return docs
    .map((doc) => ({ doc, at: days(doc.at) }))
    .filter(({ at }) => at !== null && now - at > FRESH_DAYS)
    .map(({ doc, at }) => `${doc.path}: ${Math.floor(now - (at ?? now))} дней`);
}

/**
 * Строка в шапке документа.
 *
 * Видна человеку; у устаревшего — с пометкой, а не скрытая.
 */
export function header(doc: Doc, today: string): string {
  const now = days(today);
  const at = days(doc.at);
  const aged = now !== null && at !== null && now - at > FRESH_DAYS;

  const base = `Проверено: ${doc.at} — ${doc.scope}`;
  return aged ? `${base}. **Не проверялся ${Math.floor((now ?? 0) - (at ?? 0))} дней — сверьте или поставьте дату**` : base;
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "у каждого документа дата по форме и область, а не «актуально»",
    "старше девяноста дней — помечен видимой строкой, а не удалён",
    "в шапке сказано, что сверено, а что нет",
  ];
}

/**
 * Чего дата не делает.
 *
 * Три запрета: обновление даты не делает документ верным.
 */
export function notDo(): string[] {
  return [
    "не ставит новую дату без проверки: это ложь с печатью",
    "не удаляет документ за старость: старый документ полезнее отсутствующего",
    "не пишет «актуально» вместо области: «актуально» не значит ничего",
  ];
}
