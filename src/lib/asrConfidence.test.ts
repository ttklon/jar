import { describe, expect, it } from "vitest";
import {
  askConfirm,
  doubts,
  fix,
  say,
  SURE_AT,
  sure,
  text,
  UNSURE_BELOW,
  type Word,
} from "./asrConfidence";

/**
 * Шаг 58: уверенность словами, «услышал так» с правкой.
 *
 * Без этого человек либо перепроверяет каждую фразу, либо не проверяет никогда.
 */
const w = (text_: string, confidence: number, fixed?: string): Word =>
  fixed === undefined ? { text: text_, confidence } : { text: text_, confidence, fixed };

describe("уверенность — слово, а не процент", () => {
  it("три ступени, и они звучат по-русски", () => {
    // «Уверенность 90%» редко значит 9 из 10: проценты распознавания не
    // откалиброваны, и слово не обещает точности, которой нет.
    expect(sure([w("открой", 0.95), w("блокнот", 0.9)])).toBe("sure");
    expect(sure([w("открой", 0.95), w("блокнот", 0.7)])).toBe("likely");
    expect(sure([w("блок", 0.3)])).toBe("unsure");
    expect(SURE_AT).toBeGreaterThan(UNSURE_BELOW);
  });

  it("фраза судится по худшему слову, а не по среднему", () => {
    // Одно неверное слово меняет действие: «сохрани» вместо «удали». Средняя
    // уверенность спрячет это за семью верными словами.
    const mixed = [w("и", 0.99), w("сохрани", 0.99), w("всё", 0.2)];
    expect(sure(mixed)).toBe("unsure");
  });

  it("пустая фраза не считается уверенной", () => {
    expect(sure([])).toBe("unsure");
  });
});

describe("сомнительные слова названы отдельно", () => {
  it("правится одно слово, а не вся фраза", () => {
    // Человек читает «блок нот», понимает «блокнот» — и правит слово, а не
    // перепечатывает фразу.
    const words = [w("открой", 0.95), w("блок", 0.4), w("нот", 0.35)];
    expect(doubts(words)).toEqual(["блок", "нот"]);
    expect(doubts([w("открой", 0.95), w("блокнот", 0.9)])).toEqual([]);
  });

  it("правка не меняет уверенность — слово уже проверено человеком", () => {
    const words = fix([w("блок", 0.3)], 0, "блокнот");
    expect(words[0]?.fixed).toBe("блокнот");
    expect(doubts(words)).toEqual([]);
  });

  it("правка одного слова сохраняет остальные", () => {
    const words = fix([w("открой", 0.95), w("блок", 0.4), w("сейчас", 0.9)], 1, "блокнот");
    expect(text(words)).toBe("открой блокнот сейчас");
  });

  it("пустая правка — это «убери слово», а не ошибка ввода", () => {
    // Человек мог понять, что слова не должно быть.
    expect(text(fix([w("открой", 0.9), w("ну", 0.4), w("файл", 0.9)], 1, "  "))).toBe("открой файл");
  });

  it("правка за границей списка не ломает словарь", () => {
    expect(fix([w("а", 0.9)], 5, "б")).toEqual([w("а", 0.9)]);
  });
});

describe("что человеку сказать", () => {
  it("при уверенности — коротко, без тревоги", () => {
    expect(say([w("открой", 0.95)])).toBe("услышал точно");
  });

  it("при сомнении названо, где именно, и что делать", () => {
    // Без «где» человек не знает, куда смотреть.
    const said = say([w("открой", 0.95), w("блок", 0.3), w("нот", 0.3)]);
    expect(said).toContain("блок");
    expect(said).toContain("нот");
    expect(said).toMatch(/поправьте|повторите/);
  });

  it("«услышал так» — предложение, а не приговор", () => {
    // Сказать «я услышал» честнее, чем показать текст как факт.
    expect(askConfirm([w("блок", 0.3)])).toContain("поправьте");
    expect(askConfirm([w("блокнот", 0.95)])).toBeNull();
  });

  it("длинный список сомнений не превращается в полотно", () => {
    // Список из десяти слов никто не прочтёт; названы первые три.
    const words = Array.from({ length: 8 }, (_, index) => w(`слово${index}`, 0.2));
    const said = say(words);
    expect(said).toContain("и ещё");
    expect(said.length).toBeLessThan(120);
  });
});
