/**
 * Шаг 318: тихое обновление только с согласия; иначе — уведомление.
 *
 * Тихое обновление — это когда программа ставит новую версию без вопроса. Оно
 * бывает полезным (человек не думает о версиях) и неприятным (он не понимает,
 * почему утром всё выглядит иначе, и не может это выключить).
 *
 * Правило простое и симметричное: **тихо — только если человек согласился тихо
 * обновляться.** Нет согласия — уведомление, и установка по его действию.
 *
 * Что обязано быть в согласии, иначе оно ничего не согласует:
 *
 *  * **что** ставится: исправления и безопасность — да; новые функции и смена
 *    вида — нет, их спрашиваем всегда;
 *  * **когда**: после закрытия программы, не во время дела (шаг 317);
 *  * **как отменить** — и отмена не должна требовать «сначала обновитесь».
 */

/** Согласие человека на тихое обновление. */
export interface Consent {
  readonly quiet: boolean;
  /** Когда дал согласие. */
  readonly at: number;
}

/** Какой род изменений в обновлении. */
export type Kind = "fix" | "security" | "feature" | "look";

/** Что делаем. */
export type Action = "silent" | "notify" | "askNow";

/**
 * Решение по обновлению.
 *
 * Смотрите на порядок: `security` идёт тихо только при согласии, но и **без**
 * согласия не ставится молча — ставится с уведомлением. Мы нигде не ставим
 * молча, если человек не сказал «да, тихо».
 */
export function decide(kind: Kind, consent: Consent | null, busy: boolean): { action: Action; said: string } {
  if (busy) {
    // Тихое обновление во время дела — то же, что громкое: оно рвёт работу.
    return { action: "notify", said: "ждём конца дела, потом уведомим" };
  }

  if (kind === "fix") {
    if (consent?.quiet === true) return { action: "silent", said: "исправления при согласии на тихое обновление — ставим после закрытия" };
    return { action: "notify", said: "исправления: уведомим, поставит человек" };
  }

  if (kind === "security") {
    const base = "в обновлении исправлен изъян безопасности — об этом говорим всегда, даже при согласии";
    if (consent?.quiet === true) return { action: "notify", said: `${base}; поставим после закрытия, если вы не отмените` };
    return { action: "askNow", said: `${base}; спрашиваем сразу, а не ждём удобного момента` };
  }

  if (kind === "feature") {
    return { action: "notify", said: "новые возможности не ставятся тихо никогда: человек должен знать, что появилось" };
  }

  return { action: "notify", said: "меняется вид — спрашиваем: перемены в интерфейсе замечают все, а не только те, кто их хотел" };
}

/** Что показывает уведомление — одна строка, без JSON и номеров сборки. */
export function notifyText(kind: Kind): string {
  if (kind === "security") return "Вышло обновление с исправлением безопасности. Поставить при следующем закрытии?";
  if (kind === "fix") return "Вышло обновление с исправлениями. Поставить при следующем закрытии?";
  if (kind === "feature") return "Вышло обновление: новые возможности. Что именно — коротко в журнале изменений";
  return "Вышло обновление, которое меняет вид программы. Посмотреть, что изменится?";
}

/**
 * Что человек видит в настройках.
 *
 * Не «автоматические обновления: вкл/выкл», а три понятных варианта.
 */
export function setting(consent: Consent | null): string {
  if (consent?.quiet === true) return "Обновления: исправления ставятся сами после закрытия; новые возможности — с вопросом";
  if (consent === null) return "Обновления: спрашиваем перед каждой установкой";
  return "Обновления: спрашиваем перед каждой установкой";
}

/**
 * Отмена согласия.
 *
 * Не «сначала обновитесь до версии, где это настраивается», и не через
 * переписку: одна кнопка, действует сразу.
 */
export function revoke(at: number): Consent {
  return { quiet: false, at };
}

/**
 * Проверка, что тихое обновление не стало «тихим по умолчанию».
 *
 * Ловит самую частую подмену: согласие поставили при первом запуске, в длинном
 * окне, где его не читали.
 */
export function auditSetup(firstRunConsent: boolean, explicit: boolean): string[] {
  const problems: string[] = [];
  if (firstRunConsent && !explicit) {
    problems.push("тихое обновление включено при первом запуске: это не согласие, а галочка в длинном окне");
  }
  return problems;
}
