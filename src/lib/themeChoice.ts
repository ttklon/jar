/**
 * Шаг 200: тема — светлая, тёмная, «как в системе».
 *
 * Зашитая тёмная тема — это выбор за человека. Днём на светлом фоне тёмное окно
 * читается хуже, а «как в системе» — единственный вариант, который не надо
 * перенастраивать после заката.
 *
 * Поэтому три варианта, и **умолчание — «как в системе»**: оно совпадает с тем, что
 * человек уже выбрал для компьютера. Светлая и тёмная — для тех, кому системная не
 * подходит.
 *
 * И правило, которое ловят тестом: **тема читается, а не угадывается**. Если система
 * не сообщает тему — берём светлую, потому что «не знаю» и «тёмная» — разные вещи.
 */

/** Что выбрал человек. */
export type Choice = "светлая" | "тёмная" | "как в системе";

/** Что на самом деле.
 *
 * Одно из двух: третьего не бывает, и это важно: приложение не может быть «как в
 * системе» — оно либо светлое, либо тёмное.
 */
export type Resolved = "светлая" | "тёмная";

/** Умолчание. */
export const DEFAULT: Choice = "как в системе";

/**
 * Какая тема получится.
 *
 * «Как в системе» — то, что сообщила система; система молчит — светлая.
 */
export function resolve(choice: Choice, systemSays: Resolved | null): { theme: Resolved; said: string } {
  if (choice === "как в системе") {
    const theme: Resolved = systemSays ?? "светлая";
    return { theme, said: systemSays === null ? "система не сообщила тему — берём светлую" : `как в системе: ${theme}` };
  }
  return { theme: choice, said: `выбрано: ${choice}` };
}

/**
 * Что предложить в настройках.
 *
 * Три варианта, и у каждого — что он значит. «Как в системе» первым: это умолчание.
 */
export function options(): { choice: Choice; means: string }[] {
  return [
    { choice: "как в системе", means: "как у компьютера и меняется вместе с ним" },
    { choice: "светлая", means: "всегда светлая: днём читается лучше" },
    { choice: "тёмная", means: "всегда тёмная: вечером глазам спокойнее" },
  ];
}

/**
 * Проверить настройку.
 *
 * Нарушения: варианта нет среди трёх, тема зашита (всегда тёмная без выбора).
 */
export function check(choice: string): string[] {
  const problems: string[] = [];
  const known = ["светлая", "тёмная", "как в системе"];
  if (!known.includes(choice)) problems.push(`«${choice}» — не вариант темы: ${known.join(", ")}`);
  return problems;
}

/**
 * Чего тема не делает.
 *
 * Три запрета; главный — не зашитая тёмная.
 */
export function notDo(): string[] {
  return [
    "не зашита тёмной: это выбор за человека",
    "не переключается сама по времени суток: человек выбрал, и выбор держится",
    "не «угадывает» системную тему: если система молчит, берём светлую, а не тёмную",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу вариантов.
 */
export function checks(): string[] {
  return [
    "три варианта, умолчание — «как в системе»",
    "«как в системе» действительно следует системе",
    "система молчит — светлая, а не тёмная",
  ];
}
