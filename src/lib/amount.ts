/** «Сорок два» → 42. `null` — не число. */
export function number(text: string): number | null {
  const clean = text.toLowerCase().trim();
  if (/^\d+$/.test(clean)) return Number(clean);
  let total = 0;
  let seen = false;
  for (const word of clean.split(/[\s-]+/)) {
    const value =
      HUNDREDS[word] !== undefined
        ? HUNDREDS[word]
        : TENS[word] !== undefined
          ? TENS[word]
          : TEENS[word] !== undefined
            ? TEENS[word]
            : ONES[word] !== undefined
              ? ONES[word]
              : null;
    if (value === null || value === undefined) return seen ? total : null;
    total += value;
    seen = true;
  }
  return seen ? total : null;
}

/** Слова, которые выглядят как количество, но числа не дают. */
const VAGUE = /(?:^|\s)(несколько|много|немного|кучу|куча|все|всё|часть|горсть)(?=\s|$)/i;

/** Номер слова — чтобы не завидовать «тысяче». */
const NUMBER_WORDS =
  /(?:\d+|(?:ноль|один|одна|одно|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|одиннадцать|двенадцать|тринадцать|четырнадцать|пятнадцать|шестнадцать|семнадцать|восемнадцать|девятнадцать|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|восемьдесят|девяносто|сто|двести|триста|четыреста|пятьсот|шестьсот|семьсот|восемьсот|девятьсот)(?:[\s-]+(?:один|одна|два|две|три|четыре|пять|шесть|семь|восемь|девять|десять|одиннадцать|двенадцать|тринадцать|четырнадцать|пятнадцать|шестнадцать|семнадцать|восемнадцать|девятнадцать|двадцать|тридцать|сорок|пятьдесят|шестьдесят|семьдесят|восемьдесят|девяносто))?)/gi;

/**
 * Разбор количества.
 *
 * Порядок важен: диапазон и сравнение — **раньше** отдельного числа, иначе «от
 * трёх до десяти» схлопнется в «три».
 */
export function parse(phrase: string): Amount {
  const clean = phrase.toLowerCase().replace(/ё/g, "е");

  // Диапазон: «от трёх до десяти», «с 3 по 10», «3–10».
  const range = /(?:от|с)\s+([\wа-яё\s-]{1,20}?)\s+(?:до|по)\s+([\wа-яё\s-]{1,20}?)(?=\s|$|,|\.)/iu.exec(clean);
  if (range !== null) {
    const from = number((range[1] ?? "").trim());
    const to = number((range[2] ?? "").trim());
    if (from !== null && to !== null) return from <= to ? { kind: "range", from, to } : { kind: "range", from: to, to: from };
  }

  // Сравнение: «больше 500», «меньше трёх».
  const more = /(?:больше|более|свыше)\s+([\wа-яё\d\s-]{1,20}?)(?=\s|$|,|\.)/iu.exec(clean);
  if (more !== null) {
    const value = number((more[1] ?? "").trim());
    if (value !== null) return { kind: "more", value };
  }
  const less = /(?:меньше|менее)\s+([\wа-яё\d\s-]{1,20}?)(?=\s|$|,|\.)/iu.exec(clean);
  if (less !== null) {
    const value = number((less[1] ?? "").trim());
    if (value !== null) return { kind: "less", value };
  }

  const vague = VAGUE.exec(clean);
  if (vague !== null) return { kind: "vague", word: vague[1] ?? "" };

  NUMBER_WORDS.lastIndex = 0;
  const first = NUMBER_WORDS.exec(clean);
  if (first !== null) {
    const value = number(first[0]);
    if (value !== null) return { kind: "exact", value };
  }

  return { kind: "none" };
}

/** Месяцы — для «с марта». */
const MONTHS: Record<string, number> = {
  январ: 0,
  феврал: 1,
  март: 2,
  апрел: 3,
  ма: 4,
  июн: 5,
  июл: 6,
  август: 7,
  сентябр: 8,
  октябр: 9,
  ноябр: 10,
  декабр: 11,
};

/**
 * Дата «с марта» — от какого момента.
 *
 * Месяц **без года** — последний прошедший: в ноябре «с марта» значит март этого
 * года. Год назад — это была бы другая фраза («с марта прошлого года»).
 */
export function since(phrase: string, now: number): number | null {
  const clean = phrase.toLowerCase().replace(/ё/g, "е");
  if (/(?:^|\s)с\s+(\S+)/.test(clean) === false) return null;
  for (const [stem, index] of Object.entries(MONTHS)) {
    if (new RegExp(`${stem}`, "i").test(clean)) {
      const base = new Date(now);
      const year = index > base.getMonth() ? base.getFullYear() - 1 : base.getFullYear();
      return new Date(year, index, 1).getTime();
    }
  }
  return null;
}

/**
 * «Сколько» — вопрос или количество.
 *
 * «Сколько файлов в папке» — вопрос, а не «удали три файла». Смешать их значит
 * выполнить действие вместо ответа на вопрос.
 */
export function question(phrase: string): boolean {
  const clean = phrase.toLowerCase().trim();
  // `\b` после кириллицы без флага `u` не срабатывает — проверяем начало слова
  // и то, что дальше идёт разделитель или конец фразы.
  if (/^(?:сколько|как\s+много)(?=\s|$)/.test(clean)) {
    // «Сколько» в начале — вопрос; «удали сколько-то» — нет.
    return !/^(?:удали|найди|скопируй|перемести|покажи|посчитай)(?=\s|$)/.test(clean);
  }
  return /\?$/.test(clean);
}

/**
 * Что сказать человеку.
 *
 * Названо **что понято**, а на «несколько» — честно «сколько — не сказано»:
 * подставить число значит придумать за человека.
 */
export function say(amount: Amount): string {
  switch (amount.kind) {
    case "exact":
      return `сколько: ${amount.value}`;
    case "range":
      return `сколько: от ${amount.from} до ${amount.to} — диапазон, а не одно число`;
    case "more":
      return `сколько: больше ${amount.value}`;
    case "less":
      return `сколько: меньше ${amount.value}`;
    case "vague":
      return `«${amount.word}» — это не число: сколько именно, не сказано, и я не подставляю`;
    case "none":
      return "сколько — не сказано";
  }
}

/**
 * Достаточно ли для опасного действия.
 *
 * Для необратимого «несколько» недостаточно: число должно быть точным или
 * диапазоном. Иначе «удали несколько файлов» — это лотерея.
 */
export function enough(amount: Amount): boolean {
  return amount.kind === "exact" || amount.kind === "range" || amount.kind === "more" || amount.kind === "less";
}
