/**
 * Разбор «сколько» и «какие именно»: числа, диапазоны, даты (шаг 92).
 *
 * Дефект. Человек говорит «удали файлы старше трёх месяцев» — и это либо не
 * понимается, либо понимается как «удали файлы». Дальше три беды:
 *
 *  * **уточнения становятся вопросом**, который уже прозвучал в фразе: «сколько
 *    файлов?» на «удали первые пять» — это переспрашивание того, что сказано;
 *  * **диапазон схлопывается в одно число**: «от трёх до десяти» превращается в
 *    «три» или «десять» — и удаляется не то;
 *  * **дата понимается приблизительно**: «с марта» — это март этого года или
 *    любого? Разница в объёме удаляемого огромна.
 *
 * Правило: **число, диапазон и дата понимаются точно — или честно не поняты**.
 *
 *  1. **Числа словами** («пять», «двадцать пять») — такие же числа, как цифры:
 *     люди говорят, а не печатают.
 *  2. **Диапазон — это диапазон**, а не два разных числа: «с трёх до десяти»
 *     означает интервал, и схлопнуть его нельзя.
 *  3. **«Несколько»/«много»/«немного»** — не число: подставить «десять» значит
 *     придумать за человека. Это честный «сколько — не сказано».
 *  4. **Дата без года** относится к **последнему прошедшему** месяцу/дню: «с
 *     марта» в ноябре — это март этого года. Сказано, а не угадано молча.
 *  5. **«Сколько» как вопрос** — отдельно от «сколько» как количество: «сколько
 *     файлов в папке» — это вопрос, а не «удали три файла».
 *
 * Почему не «достаточно сильная модель поймёт». Поймёт — и подставит что-нибудь
 * правдоподобное. А когда речь об удалении, правдоподобное число — это не то
 * число, и цена ошибки необратима.
 */

/** Число, диапазон или «не сказано». */
export type Amount =
  /** Одно число. */
  | { kind: "exact"; value: number }
  /** Диапазон включительно. */
  | { kind: "range"; from: number; to: number }
  /** «Больше/меньше N» — сравнение, а не количество. */
  | { kind: "more"; value: number }
  | { kind: "less"; value: number }
  /** Сказано, но числа нет: «несколько», «много». */
  | { kind: "vague"; word: string }
  /** Не сказано вовсе. */
  | { kind: "none" };

