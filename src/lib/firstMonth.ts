/**
 * Шаг 329: первый месяц — предложение подтвердить автоматизацию, а не тихий запуск.
 *
 * Даже заработанное доверие (шаг 323) не делает автоматизацию невидимой в первый
 * месяц. Причина не в недоверии к человеку, а в том, что **у него ещё нет опыта с
 * этим правилом**: он не видел, как оно срабатывает, и не знает, что именно оно
 * заденет.
 *
 * Поэтому первый месяц правило работает **с показом**: делает дело и говорит,
 * что сделало, — но не спрашивает разрешения каждый раз, иначе это не
 * автоматизация, а тридцать вопросов.
 *
 * Тонкость: «первый месяц» — с момента создания **этого** правила, а не
 * программы. Второе правило, созданное через год, тоже проходит месяц показа.
 */

/** Возраст правила и что с ним было. */
export interface Rule {
  /** Когда создано. */
  readonly createdAt: number;
  /** Сколько раз уже срабатывало само. */
  readonly ranQuietly: number;
  /** Сколько раз человек подтверждал после показа. */
  readonly acknowledged: number;
}

/** Длина показа: 30 дней. */
export const MONTH_MS = 30 * 86_400_000;

/** Сколько показов нужно, даже если месяц прошёл раньше. */
export const SHOWS_NEEDED = 5;

/**
 * Прошёл ли первый месяц.
 *
 * Два условия, а не одно: месяц **и** пять показов. Правило, которое не
 * сработало ни разу за месяц, опыта не дало — и «месяц прошёл» здесь обманчиво.
 */
export function grewUp(rule: Rule, now: number): { ok: boolean; said: string } {
  const age = now - rule.createdAt;
  const shows = Math.min(rule.ranQuietly, rule.acknowledged);

  if (age < MONTH_MS) {
    const days = Math.ceil((MONTH_MS - age) / 86_400_000);
    return { ok: false, said: `правило молодое: показываем ещё ${days} ${plural(days, "день", "дня", "дней")}` };
  }
  if (shows < SHOWS_NEEDED) {
    return {
      ok: false,
      said: `срабатывало ${shows} раз: нужен ${SHOWS_NEEDED} показов — месяц прошёл, а опыта почти нет`,
    };
  }
  return { ok: true, said: `показано ${shows} раз за месяц: правило выросло, дальше — тихо` };
}

/**
 * Как ведёт себя молодое правило.
 *
 * Делает и говорит, а не спрашивает: тридцать вопросов — это не автоматизация.
 */
export function duringFirstMonth(rule: Rule, now: number): { ask: boolean; said: string } {
  if (grewUp(rule, now).ok) return { ask: false, said: "тихо" };
  return {
    ask: false,
    said: "сделаю и скажу, что сделало: в первый месяц автоматизация показывает себя, а не спрашивает разрешения каждый раз",
  };
}

/**
 * Что человек может сделать после показа.
 *
 * Три ответа, и все сохраняются: «хорошо, так и надо», «больше не делай»,
 * «вот тут поправь». Последний — не «настройки», а сразу правка правила.
 */
export function afterShow(answer: "fine" | "stop" | "tune"): string {
  if (answer === "fine") return "запомнил: дальше без показа";
  if (answer === "stop") return "выключил правило: вернуть можно в списке расписаний";
  return "правило на паузе, пока не поправим: что изменить — время, условие или само дело?";
}

/**
 * Что показывается в первый раз.
 *
 * Не «правило сработало», а что именно стало иначе — человек не видел процесса.
 */
export function show(what: string, detail: string): string {
  return `Сам сделал: ${what} — ${detail}. В первый месяц показываю, чтобы вы видели, что происходит`;
}

/**
 * Что считается «показом».
 *
 * Не отправленное уведомление, а **замеченное**: если человек не открыл
 * приложение и не отреагировал, показ не состоялся, и опыт не накопился.
 */
export function countsAsShow(seen: boolean, reacted: boolean): boolean {
  return seen && reacted;
}

/** Русское склонение по числу. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
