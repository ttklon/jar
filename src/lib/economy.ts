/**
 * Шаг 232: режим «экономный» — реже замеры, меньше анимаций, та же работа.
 *
 * Почему отдельный режим, а не «и так экономим на слабых». Частота замеров
 * сейчас зависит от **железа**: слабая машина получает редкие замеры, сильная —
 * частые. Но человек на сильной машине тоже бывает на батарее, и ему нужно то
 * же самое. А человек на слабой машине может хотеть частых замеров, потому что
 * ему важно видеть прогресс. Режим — это выбор человека, а не приговор железа.
 *
 * Три правила, и третье — главное:
 *
 *  1. **реже замеры** — не реже раза в 5 секунд: реже человек решает, что
 *     приложение зависло;
 *  2. **меньше анимаций** — но не «без анимаций»: исчезновение всякого движения
 *     читается как поломка, а не как экономия;
 *  3. **та же работа** — экономия не меняет **что** делается, только **как
 *     часто** это видно. Это и проверяется: набор действий, пороги риска и
 *     тексты отказа не зависят от режима.
 *
 * Чего режим не делает: не отключает проверки, не откладывает подтверждения и
 * не сокращает число шагов. Экономить на безопасности — не экономия.
 */

import type { Cadence } from "./machineProfile";

/** Экономный ли режим. `auto` — по железу, как раньше. */
export type Mode = "auto" | "economy";

/** Что режим меняет в показе. */
export interface Look {
  /** Частота замеров. */
  cadence: Cadence;
  /** Длительность анимаций в миллисекундах. `0` — не «нет», а «почти нет». */
  animationMs: number;
  /** Показывать ли подсказку про режим: молчаливое изменение читается как сбой. */
  note: string | null;
}

/**
 * Частота в экономном режиме.
 *
 * Пять секунд — предел: реже человек решает, что приложение зависло, и это
 * дороже сэкономленного. Таймер разговора **не трогается**: он считает, а не
 * измеряет, и «реже» сделало бы его врущим.
 */
export const ECONOMY_CADENCE: Cadence = { poll: 5000, progress: 5000, clock: 1000 };

/**
 * Анимации в экономном режиме — короткие, но **есть**.
 *
 * `0` выглядит заманчиво и читается как «интерфейс сломался»: исчезновение
 * всякого движения — не экономия, а сюрприз.
 */
export const ECONOMY_ANIMATION_MS = 90;

/** Анимации в обычном режиме. */
export const NORMAL_ANIMATION_MS = 220;

/** Как показать работу при текущем режиме. */
export function look(mode: Mode, hardware: Cadence): Look {
  if (mode === "economy") {
    return {
      cadence: ECONOMY_CADENCE,
      animationMs: ECONOMY_ANIMATION_MS,
      note: "экономный режим: замеры раз в 5 секунд, анимации короче — работа та же",
    };
  }
  return { cadence: hardware, animationMs: NORMAL_ANIMATION_MS, note: null };
}

/**
 * Что режим **не** меняет. Функция существует ради проверки: всё, что здесь
 * перечислено, обязано остаться одинаковым в обоих режимах.
 */
export interface Work {
  /** Сколько действий в реестре доступно. */
  actions: number;
  /** Порог, выше которого нужно подтверждение. */
  confirmFrom: string;
  /** Что говорится при отказе. */
  refusal: string;
}

/** Работа при режиме: намеренно **не** смотрит на режим. */
export function work(actual: Work, _mode: Mode): Work {
  return actual;
}

/**
 * Режим из сохранённого значения. Незнакомое значение — `auto`, а не
 * `economy`: включать экономию вместо человека — значит решать за него.
 */
export function parse(saved: string | null | undefined): Mode {
  return saved === "economy" ? "economy" : "auto";
}

/** Строка для журнала: режим назван, а не подразумевается. */
export function describe(mode: Mode): string {
  return mode === "economy" ? "экономный режим включён" : "обычный режим";
}
