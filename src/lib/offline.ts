/**
 * Сеть выключена — это режим, а не поломка.
 *
 * Зачем отдельный модуль. «Работает без сети» — обещание, которое проверяется не
 * словами, а поведением: при запуске приложение не должно делать ни одного
 * запроса, а любое действие должно отвечать, а не висеть. Правило здесь, без
 * React, чтобы его проверяли тесты: `navigator.onLine` в компоненте глазами не
 * проверишь.
 *
 * Три правила, и все три — следствие того, как это ломается:
 *
 *  * **отсутствие сети не ошибка.** `false` — это не «сломалось», это «сейчас
 *    так»; интерфейс обязан говорить «недоступно без сети», а не «не получилось»;
 *  * **один список того, что без сети недоступно.** Список, разбросанный по
 *    экранам, однажды разойдётся, и человек увидит две правды об одном;
 *  * **неизвестное считается доступным.** `navigator.onLine` врёт в обе стороны
 *    (есть Wi-Fi без интернета, есть локалка без «сети»). Поэтому по умолчанию —
 *    «попробуй», а не «нельзя»: запретить действие, которое сработало бы, хуже,
 *    чем дать ему честно провалиться.
 */

/** Что без сети недоступно — перечень, а не пересказ. */
export const NEEDS_NETWORK = [
  "скачать модель",
  "скачать движок",
  "скачать распознавание речи",
] as const;

export type NeedsNetwork = (typeof NEEDS_NETWORK)[number];

/**
 * Есть ли сеть — насколько об этом можно судить.
 *
 * `null` — неизвестно: браузера нет (`navigator` отсутствует), или свойство не
 * поддерживается. Неизвестное — не повод запрещать: см. третье правило.
 */
export function onlineState(nav: { onLine?: boolean } | undefined): boolean | null {
  if (!nav) return null;
  return typeof nav.onLine === "boolean" ? nav.onLine : null;
}

/**
 * Что сказать человеку о действии, которому нужна сеть.
 *
 * `null` — сказать нечего, действуй. Иначе — одна фраза, и она объясняет, что
 * именно недоступно, а не «ошибка сети».
 */
export function offlineNote(online: boolean | null, what: NeedsNetwork): string | null {
  if (online !== false) return null;
  return `${what}: без сети не получится. Всё остальное работает — модель и движок уже на диске.`;
}

/** Что работает без сети — чтобы «недоступно» не читалось как «ничего нельзя». */
export function worksOffline(): string[] {
  return [
    "поговорить — если модель и движок уже скачаны",
    "разобрать сказанное — если распознавание уже скачано",
    "любое действие на этом компьютере",
    "история, настройки и память",
  ];
}
