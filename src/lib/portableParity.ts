/**
 * Шаг 306: портативная версия с теми же проверками — одно поведение, не два.
 *
 * Портативная сборка (распаковал в папку, запустил, ничего не ставил) — удобная
 * и потому опасная: она **выпадает из всех проверок**, которые привязаны к
 * установщику. Первым делом теряются подпись, обновления и запись в журнал, а
 * человек об этом не знает — для него это «та же программа».
 *
 * Правило: **портативность меняет место, а не поведение.** Что именно она меняет —
 * названо списком:
 *
 *  * **где данные** — рядом с программой, а не в `%LOCALAPPDATA%`: иначе «на
 *    флешке» превращается в «память на рабочем компьютере, который не наш»;
 *  * **нет записи в «Программы и компоненты»** — и это нормально, но тогда
 *    удаление — это удаление папки, и об этом надо сказать заранее;
 *  * **нет автоматического обновления молча** — портативная сборка не должна
 *    сама решать, где её место. Обновление — это замена папки человеком, и
 *    программа только говорит, что вышла новая версия.
 *
 * А проверки **остаются те же**: подпись скачанного пакета, хеш модели,
 * целостность после первого запуска.
 */

/** Как поставлена программа. */
export type Flavor = "installer" | "portable";

/** Что меняется при портативной установке. */
export const PORTABLE_DIFF = [
  "данные лежат в папке data рядом с программой, а не в %LOCALAPPDATA%",
  "в «Программы и компоненты» записи нет — удаление это удаление папки",
  "обновление не ставится само: программа говорит о новой версии, замену делает человек",
];

/** Чего портативность не меняет — и это список, а не обещание. */
export const SAME_ALWAYS = [
  "подпись и хеш скачанного пакета проверяются",
  "хеш модели проверяется после загрузки",
  "целостность проверяется на первом запуске",
  "журнал первого запуска пишется",
];

/**
 * Где данные.
 *
 * Портативная сборка хранит данные рядом — иначе смысл теряется.
 */
export function dataPath(flavor: Flavor, base: string): string {
  return flavor === "portable" ? `${base}\\data` : "%LOCALAPPDATA%\\ZShelper\\data";
}

/**
 * Что человек должен знать до первого запуска портативной версии.
 *
 * Не «портативная версия» на странице загрузки, а три факта: где данные, как
 * удалять, как обновлять.
 */
export function before(flavor: Flavor): string {
  if (flavor === "installer") {
    return "данные в %LOCALAPPDATA%; удаление — через «Программы и компоненты», с выбором сохранить ли данные";
  }
  return "данные в папке data рядом с программой; удаление — удалить папку; обновление — распаковать новую версию поверх";
}

/**
 * Проверка, что портативная сборка не хитрит.
 *
 * Возвращает нарушения, а не «ok»: важно, какая именно проверка отключена.
 */
export function audit(flavor: Flavor, checks: readonly string[]): string[] {
  const problems: string[] = [];

  for (const required of SAME_ALWAYS) {
    if (!checks.includes(required)) problems.push(`портативная сборка потеряла проверку: ${required}`);
  }
  if (flavor === "installer" && checks.includes("свои проверки установщика")) {
    problems.push("у установщика не должно быть отдельного списка «свои проверки»: проверки одни на всех");
  }
  return problems;
}

/**
 * Обновление портативной сборки.
 *
 * Программа не подменяет свои файлы, пока работает: на Windows это ловушка для
 * самой себя (файл занят), а на флешке — способ потерять и старую, и новую.
 */
export function update(flavor: Flavor): string {
  if (flavor === "portable") return "новая версия скачивается рядом и распаковывается вместо старой папки после закрытия";
  return "обновление ставится в фоне и применяется после закрытия";
}

/** Одна строка для страницы загрузки — без слова «полноценная». */
export function tagline(flavor: Flavor): string {
  return flavor === "portable"
    ? "Портативная: те же проверки, данные рядом с программой"
    : "Установщик: права администратора не нужны";
}
