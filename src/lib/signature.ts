/**
 * Подпись и хеш внешних файлов там, где это возможно (шаг 174).
 *
 * Дефект. У моделей хеш есть и проверяется (`readiness::sha256_well_formed`,
 * сверка после загрузки). А у **программ**, которые запускаются, не проверялось
 * ничего: путь, и всё. Значит «запустить программу» означало «запустить файл,
 * о котором мы не знаем ни кто его сделал, ни тот ли это файл».
 *
 * Что можно и чего нельзя:
 *
 *  * **подпись есть не у всего** — у портативных сборок и свободных программ её
 *    часто нет, и «нет подписи» — это не «вирус», а «мы не знаем, кто сделал»;
 *  * **плохая подпись — хуже отсутствия.** Отсутствие подписи значит «не
 *    проверяли»; испорченная подпись значит «файл подменили» — это два разных
 *    факта, и склеивать их значит прятать второй;
 *  * **хеш нужен, когда есть с чем сверить.** Хеш без эталона — просто число:
 *    «sha256: ab12…» не говорит «тот файл», пока не сказано «и он совпал с
 *    ожидаемым»;
 *  * **совпадение хеша сильнее подписи** по смыслу «тот ли это файл», но слабее
 *    по смыслу «кто его сделал»: подпись говорит об авторе, хеш — об
 *    идентичности. Это разные вопросы, и путать их нельзя;
 *  * **незнание не разрешение.** Нет ни подписи, ни эталона — «проверить нечем»,
 *    и человек решает сам, а не получает зелёную галочку.
 *
 * Модуль ничего не подписывает и не хеширует: он **сравнивает** то, что принесли.
 * Поэтому правило проверяется без криптографии и без Windows.
 */

/** Что известно о подписи файла. */
export type Signed =
  | "valid" // подпись есть и сходится
  | "none" // подписи нет вовсе
  | "broken" // подпись есть, но не сходится (файл подменили)
  | "unknown"; // проверить не удалось

/** Что известно о хеше. */
export interface Hash {
  /** Посчитанный хеш файла. `null` — не считали. */
  actual: string | null;
  /** Ожидаемый хеш из каталога. `null` — эталона нет. */
  expected: string | null;
}

/** Итог проверки: что можно сказать человеку. */
export interface Verdict {
  /** Можно ли считать файл тем, что ожидали. */
  trust: "yes" | "no" | "unknown";
  /** Словами: что именно проверено. */
  said: string;
  /** Требует ли отдельного слова человека. */
  ask: boolean;
}

/** Хеш в правильной форме: 64 шестнадцатеричных знака, как в ядре. */
export function hashWellFormed(hash: string): boolean {
  return /^[0-9a-f]{64}$/i.test(hash.trim());
}

/**
 * Сверить хеш.
 *
 * Регистр не важен (ядро хранит в нижнем, а человек может вставить в верхнем), но
 * длина и алфавит — важны: обрезанный хеш «сходится» с большим числом файлов, и
 * принимать его за проверку нельзя.
 */
export function match(hash: Hash): { ok: boolean; said: string } {
  const actual = hash.actual?.trim() ?? "";
  const expected = hash.expected?.trim() ?? "";

  if (expected.length === 0) {
    // Хеш без эталона — это число, а не проверка.
    return { ok: false, said: "эталона нет: хеш сам по себе ничего не доказывает" };
  }
  if (!hashWellFormed(expected)) {
    return { ok: false, said: `эталон испорчен: «${expected.slice(0, 12)}…» — не 64 шестнадцатеричных знака` };
  }
  if (actual.length === 0) {
    return { ok: false, said: "хеш файла не посчитан: сверять нечего" };
  }
  if (actual.toLowerCase() === expected.toLowerCase()) {
    return { ok: true, said: `хеш совпал: ${actual.slice(0, 12)}…` };
  }
  return {
    ok: false,
    said: `хеш НЕ совпал: файл ${actual.slice(0, 12)}…, ждали ${expected.slice(0, 12)}… — это другой файл`,
  };
}

/**
 * Свести подпись и хеш в один ответ.
 *
 * Порядок проверок — это и есть правило: испорченная подпись важнее всего
 * (файл подменили), затем хеш (тот ли файл), затем подпись (кто сделал), и
 * только потом «проверить нечем».
 */
export function check(signed: Signed, hash: Hash): Verdict {
  if (signed === "broken") {
    return {
      trust: "no",
      said: "подпись не сходится: файл подменили после подписи — запускать нельзя",
      ask: false,
    };
  }

  const hashed = match(hash);
  if (hash.expected !== null && hash.expected.trim().length > 0) {
    if (!hashed.ok) {
      return { trust: "no", said: hashed.said, ask: false };
    }
    // Хеш совпал — файл тот. Подпись говорит отдельно, кто его сделал.
    return {
      trust: "yes",
      said:
        signed === "valid"
          ? `${hashed.said}; подпись сходится`
          : `${hashed.said}; подписи нет или не проверена — это про автора, а не про файл`,
      ask: signed !== "valid",
    };
  }

  if (signed === "valid") {
    return { trust: "yes", said: "подпись сходится: автора видно; эталона хеша нет — файл сверить не с чем", ask: false };
  }

  if (signed === "none") {
    return {
      trust: "unknown",
      said: "ни подписи, ни эталона хеша: проверить нечем — это не «чисто», это «не проверено»",
      ask: true,
    };
  }

  return { trust: "unknown", said: "подпись проверить не удалось: незнание не разрешение", ask: true };
}

/** Одна строка для экрана: что проверено и чем. */
export function line(signed: Signed, hash: Hash): string {
  const got = check(signed, hash);
  const mark = got.trust === "yes" ? "проверено" : got.trust === "no" ? "НЕ проверено" : "проверить нечем";
  return `${mark}: ${got.said}`;
}

/**
 * Что делать, если проверка невозможна.
 *
 * Не «запустить всё равно» и не «запретить всё»: сказать, что именно не
 * проверено, и оставить решение человеку — но **с предупреждением**, а не молча.
 */
export function uncheckable(what: string): string {
  return `${what}: подписи нет и эталона хеша нет — запуск возможен только по вашему слову, и это не проверка`;
}
