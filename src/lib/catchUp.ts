/**
 * Шаг 334: пропущенный запуск (компьютер спал) — сделать или пропустить, по выбору человека.
 *
 * Компьютер спал в 09:00. Человек открыл ноутбук в 11:40. Есть три ответа, и все
 * три разумны — зависит от дела:
 *
 *  * **отчёт о диске** — сделать сейчас, он всё равно полезен;
 *  * **напоминание принять таблетку в 8** — сейчас вредно: пропустить;
 *  * **уборка загрузок раз в час** — не делать три раза разом.
 *
 * Поэтому выбор — **у дела**, а не глобальная настройка: человек не будет
 * настраивать это в одном месте и путаться, почему одно правило догоняет, а
 * другое нет.
 *
 * И один раз всё равно спрашиваем: первый пропуск даёт вопрос, ответ
 * запоминается на это правило (шаг 329 — тот же принцип).
 */

/** Как правило ведёт себя с пропуском. */
export type Policy = "catchUp" | "skip" | "ask";

/** Правило и пропуск. */
export interface Rule {
  readonly what: string;
  readonly policy: Policy;
  /** Опасное дело: догонять можно, но с подтверждением. */
  readonly dangerous: boolean;
  /** Сколько срабатываний пропущено. */
  readonly missed: number;
}

/** Что делаем. */
export interface Decision {
  readonly action: "doOnce" | "skip" | "ask";
  readonly said: string;
}

/**
 * Решение по пропуску.
 *
 * Главное правило: **сколько бы ни было пропущено — срабатывание одно.** После
 * недели отпуска человек не должен получить семь отчётов.
 */
export function decide(rule: Rule): Decision {
  if (rule.missed <= 0) return { action: "skip", said: "пропусков нет" };

  if (rule.dangerous) {
    return {
      action: "ask",
      said: `пропущено ${rule.missed}: дело меняет мир, поэтому спрошу «сделать сейчас?» — само не запустится`,
    };
  }

  if (rule.policy === "skip") {
    return {
      action: "skip",
      said: `пропущено ${rule.missed}: пропускаю до следующего раза, в журнале будет «пропущено»`,
    };
  }

  if (rule.policy === "ask") {
    return { action: "ask", said: `пропущено ${rule.missed}: спрошу один раз и запомню ответ для этого правила` };
  }

  return {
    action: "doOnce",
    said: `пропущено ${rule.missed}: делаю один раз, а не ${rule.missed} подряд`,
  };
}

/**
 * Что предложить при создании правила.
 *
 * Подсказка по роду дела, а не пустое поле: человек выбирает из двух, а не
 * сочиняет политику.
 */
export function suggest(dangerous: boolean, frequent: boolean): Policy {
  if (dangerous) return "ask";
  if (frequent) return "skip";
  return "catchUp";
}

/**
 * Что человек видит в строке расписания после пропуска.
 *
 * Не «пропущено 7» без последствий, а что будет дальше.
 */
export function line(rule: Rule): string {
  const verdict = decide(rule);
  if (verdict.action === "skip" && rule.missed > 0) return `${rule.what}: пропущено ${rule.missed}, следующее — по расписанию`;
  if (verdict.action === "doOnce") return `${rule.what}: пропущено ${rule.missed}, сделаю один раз`;
  if (verdict.action === "ask") return `${rule.what}: пропущено ${rule.missed}, спрошу`;
  return `${rule.what}: пропусков нет`;
}

/**
 * Чего нельзя делать ни при каком выборе.
 *
 * Список нужен, потому что «догнать» легко превращается в очередь: «сделаю все
 * пропущенные по порядку» звучит аккуратно и на деле означает семь уборок разом.
 */
export function forbidden(): string[] {
  return [
    "выполнять все пропущенные по очереди — после отпуска это буря",
    "молча подменять пропуск успехом — в журнале должно быть «пропущено»",
    "догонять опасное дело без подтверждения",
  ];
}
