import { describe, expect, it } from "vitest";
import { briefly, corrected, early, isLine, line, LINE_MAX, order } from "./ackLine";

/**
 * Шаг 133: первая строка ответа — до плана: «понял, делаю».
 *
 * «Разбираю» говорило «я здесь», но не «я понял» — и человек повторял фразу.
 */
describe("признание раньше плана", () => {
  it("строка не ждёт плана", () => {
    // Плана ещё нет, а строка уже есть.
    expect(line({ what: "переименовать фото", confident: true }, false)).toBe(
      "понял, делаю: переименовать фото",
    );
  });

  it("идёт раньше шагов", () => {
    expect(order("понял, делаю: переименовать фото", ["шаг 1", "шаг 2"])).toEqual([
      "понял, делаю: переименовать фото",
      "шаг 1",
      "шаг 2",
    ]);
  });
});

describe("сказано, что именно понято", () => {
  it("«понял» без повтора неотличим от молчания", () => {
    expect(line({ what: "переименовать фото", confident: true })).toContain("переименовать фото");
  });

  it("повтор короткий: параметры — это план, а не первая строка", () => {
    const long = "переименовать все фотографии в папке Загрузки начиная с 2024 года";
    const short = briefly(long);
    expect(short.length).toBeLessThanOrEqual(41);
    // Обрезка по слову, а не по букве.
    expect(short.endsWith("…")).toBe(true);
    expect(short).toContain(" ");
  });
});

describe("догадка названа догадкой", () => {
  it("«понял как X — поправьте» лучше уверенного неверного", () => {
    expect(line({ what: "удалить всё", confident: false })).toBe(
      "понял как «удалить всё» — поправьте, если не так",
    );
  });
});

describe("первая строка — это строка", () => {
  it("80 знаков — ещё строка", () => {
    expect(isLine("а".repeat(LINE_MAX)).ok).toBe(true);
  });

  it("перевод строки — уже абзац", () => {
    const got = isLine("понял\nделаю");
    expect(got.ok).toBe(false);
    expect(got.said).toContain("человек прочтёт только первую половину");
  });

  it("длиннее предела — не строка, и это названо числом", () => {
    expect(isLine("а".repeat(LINE_MAX + 1)).said).toContain(`${LINE_MAX + 1} знаков при пределе ${LINE_MAX}`);
  });
});

describe("ничего не понято — так и сказано", () => {
  it("пустой повтор не выдаётся за «понял»", () => {
    expect(line({ what: "  ", confident: true })).toBe("понял не до конца — скажите, что сделать");
  });
});

describe("признание вовремя", () => {
  it("раньше готового — поправить ещё можно", () => {
    expect(early(400, 2400).ok).toBe(true);
  });

  it("вместе с готовым — поздно, и так названо", () => {
    expect(early(2400, 2400).said).toContain("поправлять уже поздно");
  });

  it("не было строки — человек не знал, поняли ли его", () => {
    expect(early(null, 2400).said).toContain("не знал, поняли ли его");
  });

  it("после поправки — новое признание, а не продолжение старого", () => {
    expect(corrected({ what: "открыть папку", confident: true }, true)).toBe("понял заново, делаю: открыть папку");
  });
});
