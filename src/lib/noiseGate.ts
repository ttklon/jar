/**
 * Порог шума подстраивается: «я говорю» или «телевизор говорит» (шаг 43).
 *
 * Дефект. Порог был жёстким числом. В тихой комнате он ловил кухонный
 * холодильник и отправлял шум как просьбу; в шумной — не ловил ничего, и человек
 * не мог заставить приложение себя услышать. Одно число не может быть верным в
 * обеих комнатах.
 *
 * Правило поэтому двухслойное, и оба слоя нужны:
 *
 *  1. **фон** — то, что слышно постоянно. Он оценивается по **тихим** замерам,
 *     а не по среднему: среднее поднимает речь и шум, и порог уезжает вверх
 *     ровно тогда, когда человек говорит;
 *  2. **порог** — фон плюс запас. Запас не «на глаз»: он в децибелах и
 *     переводится в линейную шкалу, потому что громкость так и измеряется.
 *
 * Почему не «просто умножить на два». Удвоение громкости — это +6 дБ, и в тихой
 * комнате этого мало (шорох пройдёт), а в шумной — много (человек не дотянется).
 * Поэтому запас считается от **фона**, а не от порога: тише фон — меньше нужный
 * запас, и наоборот.
 *
 * Главное, чего здесь нет: **подстройки под речь**. Порог не поднимается, пока
 * человек говорит, — иначе приложение перестаёт себя слышать ровно в тот момент,
 * когда его просят замолчать. Фон обновляется только тишиной.
 */

/** Запас над фоном в децибелах. +9 дБ — речь заметно громче комнаты. */
export const MARGIN_DB = 9;

/** Ниже этого порог не опускается: совсем тихая комната означает «нет сигнала». */
export const FLOOR_DB = -60;

/** Выше этого порог не поднимается: иначе в шумной комнате человека не слышно. */
export const CEIL_DB = -20;

/** Как громко, в дБ. `-Infinity` — полная тишина (не бывает, но бывает 0). */
export function db(level: number): number {
  if (!Number.isFinite(level) || level <= 0) return -Infinity;
  return 20 * Math.log10(level);
}

/** Обратно из дБ в линейную громкость. */
export function fromDb(value: number): number {
  if (!Number.isFinite(value)) return 0;
  return Math.pow(10, value / 20);
}

/**
 * Фон по тихим замерам.
 *
 * Не среднее и не минимум: среднее поднимает речь, минимум — единичный щелчок.
 * Берётся **треть тихих** замеров и их медиана: она не боится ни щелчка, ни
 * того, что человек сказал слово посреди окна.
 */
export function noiseFloor(levels: readonly number[]): number {
  const sorted = levels.filter((level) => Number.isFinite(level) && level > 0).sort((a, b) => a - b);
  if (sorted.length === 0) return 0;
  const quiet = sorted.slice(0, Math.max(1, Math.ceil(sorted.length / 3)));
  const middle = quiet[Math.floor(quiet.length / 2)] ?? quiet[0] ?? 0;
  return middle;
}

/**
 * Порог, выше которого считается «человек говорит».
 *
 * Ограничен снизу и сверху — и это не мелочь: без нижней границы в полной тишине
 * порог равен нулю и ловит дыхание; без верхней в шумной комнате он уходит так
 * высоко, что человека не слышно.
 */
export function gate(floor: number, marginDb = MARGIN_DB): number {
  const thresholdDb = Math.min(CEIL_DB, Math.max(FLOOR_DB, db(floor) + marginDb));
  return fromDb(thresholdDb);
}

/** Слышно ли человека на этом замере. */
export function speaking(level: number, floor: number): boolean {
  return level >= gate(floor);
}

/** Фон после обновления: плавно, только тишиной. */
export function nextFloor(floor: number, level: number, moved = 0.05): number {
  if (speaking(level, floor)) return floor; // речь не двигает фон
  if (!Number.isFinite(level) || level <= 0) return floor;
  // Линейное сглаживание: комната меняется плавно, и один щелчок не сдвигает
  // порог.
  return floor * (1 - moved) + level * moved;
}

/**
 * Как это назвать человеку.
 *
 * Называется фон и порог **числами**: «порог подстроен» без чисел — это то же
 * «готово», от которого мы ушли. Человек, у которого не работает, должен иметь
 * возможность сказать, какие у него числа.
 */
export function gateLine(floor: number, threshold: number): string {
  const floorDb = db(floor);
  const thresholdDb = db(threshold);
  if (!Number.isFinite(floorDb) || !Number.isFinite(thresholdDb)) {
    return "микрофон молчит — ни фона, ни речи";
  }
  return `фон ${floorDb.toFixed(0)} дБ, порог ${thresholdDb.toFixed(0)} дБ — подстраивается под комнату`;
}
