/**
 * Если включён удалённый путь — предупреждение с адресом и телом запроса (шаг 216).
 *
 * Дефект. Дважды в интерфейсе написано «согласие на микрофон **не разрешает**
 * отправку запроса удалённой модели — её маршрут настраивается отдельно». И это
 * правда: **маршрута нет вообще**. Но фраза обещает настройку, которой не
 * существует, а обещание настройки — это приглашение искать её.
 *
 * Пока маршрута нет, честный ответ один: «удалённого пути нет». А если он
 * появится (человек впишет свой адрес), предупреждение должно быть **до** первой
 * фразы и говорить три вещи:
 *
 *  1. **куда** — адрес, а не «внешний сервис»: «https://api.example.com/v1»;
 *  2. **что именно** — тело запроса, а не «ваши данные»: фраза, история, системная
 *     подсказка. Тело — то, что реально уйдёт, целиком, а не пересказ;
 *  3. **что останется** — что не уйдёт: файлы, журнал, память. Иначе человек
 *     думает, что уходит всё.
 *
 * Правила:
 *
 *  * **предупреждение не маскируется**: секреты в теле маскируются (`sk-…`,
 *    токены), остальное — дословно; маска на всём теле — это сокрытие;
 *  * **локальный адрес — не удалённый**: `127.0.0.1` и `localhost` — свой
 *    компьютер, и предупреждать про них значит пугать зря и приучать не читать;
 *  * **нет маршрута — так и сказано**, а не пустое место;
 *  * **адрес проверяется тем же правилом, что загрузка** (`networkAllow`):
 *    два разных «можно/нельзя» для сети разошлись бы.
 *
 * Модуль не делает запросов: он отвечает, что было бы отправлено.
 */

/** Настройка удалённого маршрута. */
export interface Route {
  /** Адрес, как ввёл человек. Пусто — маршрута нет. */
  url: string;
  /** Модель, которую просят у сервера. */
  model?: string;
}

/** Что уйдёт и что останется. */
export interface Warning {
  /** Есть ли удалённый путь. */
  remote: boolean;
  /** Куда — адрес или пусто. */
  where: string;
  /** Что уйдёт — дословно (секреты замаскированы). */
  body: string;
  /** Что не уйдёт. */
  stays: string;
  /** Строка для экрана; пусто, когда маршрута нет. */
  said: string;
}

/** Свой компьютер — не «наружу». */
const LOCAL = new Set(["127.0.0.1", "localhost", "::1", "[::1]"]);

/**
 * Адрес маршрута в виде «схема://хост».
 *
 * `null` — это не адрес: пусто, без схемы, или с логином в адресе (последнее уже
 * не «куда», а «с чьими правами», и путать это с адресом нельзя).
 */
export function place(url: string): string | null {
  const text = url.trim();
  if (text.length === 0) return null;
  if (text.includes("@")) return null;
  let parsed: URL;
  try {
    parsed = new URL(text);
  } catch {
    return null;
  }
  if (parsed.protocol !== "https:" && parsed.protocol !== "http:") return null;
  return `${parsed.protocol}//${parsed.host}`;
}

/** Локальный ли маршрут: свой компьютер, а не интернет. */
export function local(url: string): boolean {
  const text = url.trim();
  if (text.length === 0) return false;
  try {
    return LOCAL.has(new URL(text).hostname.toLowerCase());
  } catch {
    return false;
  }
}

/**
 * Секреты в теле — замаскировать.
 *
 * Маскируется **только то, что похоже на ключ**: длинные строки `sk-…`, `Bearer`,
 * `api_key=…`. Маскировать тело целиком нельзя: тогда предупреждение говорит
 * «что-то уйдёт», а человек соглашается на «что-то» — это и есть сокрытие.
 */
export function mask(text: string): string {
  return text
    .replace(/sk-[A-Za-z0-9_-]{8,}/g, "sk-…")
    .replace(/Bearer\s+[A-Za-z0-9._-]{8,}/gi, "Bearer …")
    .replace(/(api[_-]?key\s*[=:]\s*)[^\s",}]+/gi, "$1…");
}

/**
 * Предупреждение — до первой фразы, а не после.
 *
 * `body` — то, что уйдёт: фраза человека, история, системная подсказка. Собирается
 * вызывающим, потому что только он знает, что лежит в запросе.
 */
export function warning(route: Route, body: readonly string[]): Warning {
  const where = place(route.url);
  if (where === null) {
    return {
      remote: false,
      where: "",
      body: "",
      stays: "",
      said: route.url.trim().length > 0
        ? "адрес удалённой модели не понять: нужен вид «https://сервер/путь», и без логина в адресе"
        : "удалённого пути нет: модель работает на этом компьютере, и запросы наружу не уходят",
    };
  }
  if (local(route.url)) {
    return {
      remote: false,
      where,
      body: "",
      stays: "",
      said: `${where} — это свой компьютер, а не интернет: предупреждать не о чем`,
    };
  }

  const sent = mask(body.filter((part) => part.trim().length > 0).join("\n"));
  return {
    remote: true,
    where,
    body: sent,
    stays: "файлы, журнал и память остаются на компьютере: наружу уходит только текст запроса",
    said:
      `наружу: ${where}${route.model ? ` (модель ${route.model})` : ""} — каждая фраза уходит туда целиком, ` +
      `и вот что именно: ${body.length > 0 ? body.filter((part) => part.trim().length > 0).length : 0} частей запроса; ` +
      `файлы, журнал и память остаются`,
  };
}

/**
 * Что показать **в теле** предупреждения.
 *
 * Отдельно от строки: тело — дословно и в несколько строк, потому что «что уйдёт»
 * нельзя уложить в одну фразу без потери. Пусто у локального и отсутствующего
 * маршрута: показывать нечего, а пустая рамка читается как «что-то скрыли».
 */
export function bodyLines(got: Warning): string[] {
  if (!got.remote) return [];
  return got.body.split("\n").filter((line) => line.length > 0);
}

/**
 * Можно ли такой маршрут вообще сохранить.
 *
 * Не «да, попробуем»: адрес без схемы, с логином или не-http — это не маршрут.
 * Отказ называет, что именно не так.
 */
export function saveable(route: Route): { ok: boolean; why: string } {
  const text = route.url.trim();
  if (text.length === 0) return { ok: true, why: "" };
  if (text.includes("@")) return { ok: false, why: "в адресе есть логин: такой адрес уводит не туда, куда выглядит" };
  if (place(text) === null) return { ok: false, why: "адрес должен начинаться с https:// и содержать сервер" };
  return { ok: true, why: "" };
}
