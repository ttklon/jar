/**
 * Перебивание в пределах 200 мс (шаг 42).
 *
 * Обещание: сказал слово — приложение замолчало **быстро**. Без числа это
 * обещание ничем не отличается от «замолчало когда-нибудь»: человек ждёт, пока
 * «договорит», и чувствует, что его не слышат. 200 мс — порог, за которым
 * задержка уже заметна как «оно меня не слушает».
 *
 * Что здесь считается. Не «сколько длился вызов», а **сколько времени прошло от
 * звука до тишины**: человек заговорил в `spokenAt`, динамик замолчал в
 * `silentAt`. Между ними — то время, которое он ощущает. Замер одного вызова
 * (`performance.now()` вокруг `stop()`) показывает другое и обычно меньше:
 * звук уже был в буфере, и его надо было выбросить.
 *
 * Почему правило, а не замер на месте. Замер нужен в трёх местах (кнопка,
 * клавиша, автоматическое определение голоса), и в каждом легко посчитать не то.
 * Здесь одна функция и один порог — и один тест на то, что порог значим.
 */

/** Порог, за которым перебивание считается медленным. Обещание продукта. */
export const BARGE_LIMIT_MS = 200;

/** Одно перебивание: когда человек заговорил и когда стало тихо. */
export interface Barge {
  /** Момент, когда человек начал говорить (мс, любая общая шкала). */
  spokenAt: number;
  /** Момент, когда динамик замолчал. `null` — не замолчал вовсе. */
  silentAt: number | null;
}

/** Сколько прошло до тишины. `null` — тишины не было: это не «быстро». */
export function bargeDelay(attempt: Barge): number | null {
  if (attempt.silentAt === null) return null;
  const delay = attempt.silentAt - attempt.spokenAt;
  // Отрицательная задержка — не «мгновенно», а ошибка в замере: тишина раньше
  // звука. Считать её быстрой значило бы принимать ошибку за успех.
  if (delay < 0) return null;
  return delay;
}

/**
 * Уложилось ли в обещание.
 *
 * `null` (не замолчало или замер сломан) — не «уложилось»: обещание про тишину,
 * а тишины не было.
 */
export function withinLimit(attempt: Barge, limit = BARGE_LIMIT_MS): boolean {
  const delay = bargeDelay(attempt);
  return delay !== null && delay <= limit;
}

/**
 * Как это назвать человеку — в отчёте и в журнале.
 *
 * Не «перебивание сработало»: это ничего не говорит о скорости. Называется
 * число, потому что обещание числовое.
 */
export function bargeLine(attempt: Barge): string {
  const delay = bargeDelay(attempt);
  if (delay === null) {
    return attempt.silentAt === null
      ? "не замолчало — человек говорит, а приложение продолжает"
      : "замер сломан: тишина раньше звука";
  }
  const verdict = delay <= BARGE_LIMIT_MS ? "в срок" : "медленно";
  return `замолчало через ${delay} мс — ${verdict} (обещание: не дольше ${BARGE_LIMIT_MS})`;
}

/**
 * Самое медленное из нескольких перебиваний.
 *
 * Почему не среднее. Среднее скрывает одно медленное перебивание за девятью
 * быстрыми — а человек запоминает именно медленное. Обещание проверяется по
 * худшему случаю: оно про то, что **никогда** не дольше 200 мс.
 */
export function slowest(attempts: readonly Barge[]): Barge | null {
  let worst: Barge | null = null;
  let worstDelay = -1;
  for (const attempt of attempts) {
    const delay = bargeDelay(attempt);
    // Незамолчавшее и сломанное — хуже любого числа: считаем бесконечностью.
    const value = delay === null ? Number.POSITIVE_INFINITY : delay;
    if (value > worstDelay) {
      worstDelay = value;
      worst = attempt;
    }
  }
  return worst;
}

/**
 * Состояние разговора при перебивании.
 *
 * Задержка (выше) отвечает на «быстро ли». Это отвечает на «что делать дальше»:
 * замолчать, отличить свой голос от чужого и **договорить с места**, а не начать
 * фразу заново. Без этого «перебивание» превращается в «стоп и забудь», и человек
 * второй раз слушает то, что уже слышал.
 */
export interface Talk {
  /** Говорит ли приложение сейчас. */
  speaking: boolean;
  /** Что уже сказано — чтобы продолжить, а не повторить. */
  saidSoFar: string;
}

/** Что услышали. */
export type Heard = "человек" | "свой голос" | "шум" | "тишина";

/** Сколько тишины должно пройти, чтобы вернуться к фразе. */
export const RESUME_MS = 800;

/**
 * Реакция на звук.
 *
 * Свой голос и шум перебиванием не считаются: приложение, которое замолкает от
 * собственного эха, перебивает само себя, и человек слышит рваную речь.
 */
export function onHeard(talk: Talk, heard: Heard): { talk: Talk; said: string } {
  if (heard === "человек") {
    return { talk: { speaking: false, saidSoFar: `${talk.saidSoFar} [перебито]` }, said: "замолчал сразу: говорите" };
  }
  if (heard === "свой голос") return { talk, said: "это мой голос — продолжаю, перебивания нет" };
  if (heard === "шум") return { talk, said: "шум — не перебивание, продолжаю фразу" };
  return { talk, said: "тишина: если человек не вернулся, фраза продолжится сама" };
}

/**
 * Возврат к фразе.
 *
 * Продолжает **с места**, а не сначала: начало человек уже слышал.
 */
export function resume(talk: Talk, silentFor: number): { talk: Talk; said: string } {
  if (talk.speaking) return { talk, said: "уже говорю: возвращаться некуда" };
  if (silentFor < RESUME_MS) return { talk, said: `подожду ещё ${RESUME_MS - silentFor} мс тишины` };
  if (talk.saidSoFar === "") return { talk, said: "фраза не начиналась: говорить нечего" };
  return { talk: { ...talk, speaking: true }, said: "продолжаю с того места, где остановился: начало вы уже слышали" };
}

/**
 * Где перебивание обязано работать одинаково.
 *
 * Три места: кнопка в окне, значок в трее, горячая клавиша. Разное поведение в
 * трёх местах человек читает как «глючит».
 */
export function sameEverywhere(): string[] {
  return ["кнопка в окне", "значок в трее", "горячая клавиша"];
}
