/**
 * Бюджет задержки под подставным медленным ядром (шаг 130).
 *
 * Дефект. Скорость **не проверялась тестом**, и регрессия проходила молча:
 *
 *  * **на быстрой машине всё «быстро»**: тест, который просто ждёт, ничего не
 *    доказывает — он доказывает скорость машины, а не поведение;
 *  * **медленное ядро не встречалось**: настоящая задержка приходила из ядра, а в
 *    тестах ядро отвечало мгновенно (заглушка), и «зависание» не проверялось;
 *  * **бюджет не был границей**: 5 секунд в тесте проходили так же, как 50 мс, —
 *    потому что никто их не сравнивал с пределом;
 *  * **регрессия ловится глазами**: «стало медленнее» замечают по жалобе, а не по
 *    красному тесту.
 *
 * Правило: **ядро в тесте может быть медленным, и бюджет — это проверяемое число**.
 *
 *  1. **Время — подставное**: часы идут по шагам, а не по `setTimeout`. Тест не
 *     зависит от скорости машины и не может «пройти потому что быстро».
 *  2. **Медленное ядро изображается**: `slow(ms)` — ядро, которое тратит заданное
 *     время; так проверяется поведение при задержке, а не сама задержка.
 *  3. **Бюджет сравнивается с числом**: `over(ms)` — и это нарушение, а не «вроде
 *     долго».
 *  4. **Быстрое ядро не оправдывает медленный код**: если код добавил 2 секунды
 *     своего, «ядро было быстрым» ничего не меняет.
 *  5. **Тест не спит**: `setTimeout`-тест на 5 секунд — это 5 секунд в прогоне и
 *     ложная стабильность на загруженной машине.
 *
 * Почему часы, а не реальные задержки. Реальные задержки в тестах дают нестабильный
 * результат: тот же код то проходит, то нет, в зависимости от загрузки машины. Часы
 * по шагам дают точное повторение и настоящую проверку бюджета.
 */

/** Часы, которые идут только тогда, когда их просят. */
export interface Clock {
  /** Сколько «прошло» по часам, мс. */
  now: number;
}

export function clock(at = 0): Clock {
  return { now: at };
}

/**
 * Подставное ядро с задержкой.
 *
 * `ms` — сколько ядро «думает». Реального ожидания нет: часы двигает `kernel`.
 */
export function slow(clockIn: Clock, ms: number): { expect: number; run: () => Promise<number> } {
  return {
    // Сколько тест **обязан** увидеть на часах после вызова — без сна.
    expect: ms,
    run: async () => {
      clockIn.now += ms;
      return ms;
    },
  };
}

/** Сколько стоит вызов — по часам, а не по секундомеру. */
export async function timed(clk: Clock, run: () => Promise<unknown>): Promise<number> {
  const startedAt = clk.now;
  await run();
  return clk.now - startedAt;
}

/** Нарушение бюджета — числом, а не «вроде долго». */
export function over(ms: number, budget: number): { over: boolean; by: number; said: string } {
  const diff = ms - budget;
  if (diff <= 0) {
    return { over: false, by: 0, said: `${ms} мс из ${budget} — в бюджете` };
  }
  return { over: true, by: diff, said: `${ms} мс при бюджете ${budget} — превышение на ${diff} мс` };
}

/**
 * Проверка «быстрое ядро не оправдывает медленный код».
 *
 * `kernelMs` — сколько заняло ядро, `totalMs` — сколько заняло всё. Разница —
 * собственные накладные расходы кода; именно они и регрессируют.
 */
export function own(totalMs: number, kernelMs: number): { ms: number; said: string } {
  const ms = Math.max(0, totalMs - kernelMs);
  return {
    ms,
    said:
      ms > 0
        ? `своих ${ms} мс при ядре ${kernelMs} мс — этого ядро не объясняет`
        : "своих расходов нет: всё время — у ядра",
  };
}

/**
 * Сценарий регрессии.
 *
 * Возвращает отчёт, который можно сравнивать: «было 400, стало 2400» — это факт, а
 * «стало медленнее» — мнение.
 */
export interface Scenario {
  name: string;
  budget: number;
  ms: number;
}

export function check(scenario: Scenario): { ok: boolean; said: string } {
  const got = over(scenario.ms, scenario.budget);
  return {
    ok: !got.over,
    said: got.over ? `${scenario.name}: ${got.said}` : `${scenario.name}: ${got.said}`,
  };
}

/** Отчёт по всем сценариям: сколько прошло бюджет. */
export function report(scenarios: readonly Scenario[]): string {
  const bad = scenarios.filter((scenario) => over(scenario.ms, scenario.budget).over);
  if (bad.length === 0) return `все ${scenarios.length} сценариев в бюджете`;
  return `за бюджетом ${bad.length} из ${scenarios.length}: ${bad.map((scenario) => scenario.name).join(", ")}`;
}
