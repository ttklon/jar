/**
 * Показывать замер в журнале рядом с делом (шаг 122).
 *
 * Дефект. Замер есть, но **живёт отдельно от дела**:
 *
 *  * **на экране одна цифра**: «отвечает 4 секунды» — средняя по всем делам, и по
 *    ней не видно, что распознавание объёма занимает 9 секунд, а разговор — одну;
 *  * **нельзя ответить на «что медленно на этой машине»**: журнал знает, какое дело
 *    было, и не знает, сколько оно шло;
 *  * **медленные дела не отличаются от быстрых**: в списке одинаковая строка, и
 *    жалоба «тут долго» не подтверждается и не опровергается;
 *  * **замер без дела бесполезен**: миллисекунды сами по себе не говорят, **что**
 *    было медленным — какая фраза, какой шаг.
 *
 * Правило: **замер лежит рядом с делом, и медленное названо числом**.
 *
 *  1. **У строки журнала есть замер**: не отдельная таблица, которую никто не
 *     откроет, а поле той же строки.
 *  2. **Замер не перебивает дело**: сначала что сделано, потом «1,2 с». Число —
 *     уточнение, а не заголовок.
 *  3. **Медленное помечено**, а не только замерено: порог назван, и нарушение видно
 *     (шаг 124: бюджет задержки).
 *  4. **Самая медленная строка названа**: «на этой машине медленнее всего —
 *     распознавание» — ответ на вопрос, а не сортируемая таблица.
 *  5. **Замера нет — сказано «не замерено»**, а не «0 мс»: ноль выглядит как
 *     мгновенно.
 *
 * Почему не «показывать среднее». Среднее прячет хвост: если одно дело из десяти
 * шло 30 секунд, среднее — 3,4, и «нормально» становится ложью.
 */

/** Строка журнала с замером — то, что видно человеку. */
export interface Entry {
  /** Что было сказано. */
  heard: string;
  /** Что сделано. */
  did: string;
  /** Сколько шло, мс. `null` — не замеряли. */
  ms: number | null;
}

/** Бюджет задержки по умолчанию — для пометки «медленное». */
export const SLOW_MS = 1500;

/**
 * Формат числа для человека.
 *
 * До секунды — миллисекунды, дальше — секунды с одним знаком: «1204 мс» читается
 * хуже, чем «1,2 с», а «0,0004 с» — хуже, чем «0 мс».
 */
export function duration(ms: number | null): string {
  if (ms === null) return "не замерено";
  if (ms < 1000) return `${Math.round(ms)} мс`;
  return `${(ms / 1000).toFixed(1).replace(".", ",")} с`;
}

/**
 * Строка журнала целиком.
 *
 * Дело первым: число — уточнение к делу, а не заголовок строки.
 */
export function text(entry: Entry, slow = SLOW_MS): string {
  const took = duration(entry.ms);
  // Помечено, а не только замерено: «1,9 с» без пометки человек сравнит сам, а
  // сравнить ему не с чем.
  const late = entry.ms !== null && entry.ms > slow ? ` — дольше ${duration(slow)}` : "";
  return `«${entry.heard}» → ${entry.did} · ${took}${late}`;
}

/**
 * Самое медленное дело.
 *
 * Ответ на вопрос «что медленно на этой машине», а не сортировка: человеку нужен
 * ответ, а не таблица.
 */
export function slowest(entries: readonly Entry[]): Entry | null {
  let best: Entry | null = null;
  for (const entry of entries) {
    if (entry.ms === null) continue;
    if (best === null || entry.ms > (best.ms ?? 0)) best = entry;
  }
  return best;
}

/**
 * Сколько дел не уложилось в бюджет.
 *
 * Числом, а не «в основном быстро»: доля нарушений — это то, что можно чинить.
 */
export function late(entries: readonly Entry[], slow = SLOW_MS): { count: number; total: number; share: number } {
  const measured = entries.filter((entry) => entry.ms !== null);
  const over = measured.filter((entry) => (entry.ms ?? 0) > slow).length;
  return { count: over, total: measured.length, share: measured.length === 0 ? 0 : over / measured.length };
}

/** Итог словами — для подвала журнала. */
export function say(entries: readonly Entry[], slow = SLOW_MS): string {
  const got = late(entries, slow);
  if (got.total === 0) return "замеров нет — сказать про задержку нечего";
  const parts = [`не уложилось в ${duration(slow)}: ${got.count} из ${got.total}`];
  const worst = slowest(entries);
  if (worst !== null && got.count > 0) {
    // Самое медленное — с фразой: иначе «медленно» не к чему приложить.
    parts.push(`медленнее всего: «${worst.heard}» — ${duration(worst.ms)}`);
  }
  return parts.join(", ");
}

/**
 * Отношение к бюджету.
 *
 * `null` — замера нет: «в норме» без замера — это обещание, а не факт.
 */
export function within(entry: Entry, slow = SLOW_MS): boolean | null {
  if (entry.ms === null) return null;
  return entry.ms <= slow;
}
