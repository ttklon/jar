/**
 * Шаг 402: быстрое переключение «это я» перед чувствительным делом.
 *
 * Профили есть (шаг 401), но переключение — это экран настроек, три нажатия и
 * поиск нужного пункта. А нужно оно **в момент дела**: человек подошёл, взял
 * ноутбук, и первое же дело — удалить что-то в своей папке.
 *
 * Поэтому переключение — вопрос **внутри дела**, перед опасным шагом, и всего один:
 * «это вы?» с двумя-тремя именами. Не «выберите профиль на экране профилей».
 *
 * Три решения:
 *
 *  * **спрашиваем только перед опасным** — перед чтением это лишний шум, и его
 *    через неделю перестают читать;
 *  * **не угадываем по поведению** («это наверняка Анна») — ошибка стоит дорого, а
 *    вопрос стоит секунды;
 *  * **отвеченный вопрос держится до конца дела** — иначе спросим на каждом шаге.
 */

import type { Risk } from "./dangerPolicy";
import { isDangerous } from "./dangerPolicy";
import type { Person } from "./peopleProfiles";

/** Когда спрашивать. */
export function need(risk: Risk, others: readonly Person[]): { ask: boolean; why: string } {
  if (!isDangerous(risk)) return { ask: false, why: "безопасное дело: не спрашиваем, иначе вопрос перестают читать" };
  if (others.length === 0) return { ask: false, why: "человек один: спрашивать некого" };
  return { ask: true, why: `опасное дело, а на компьютере ${others.length + 1} человек — уточню перед первым шагом` };
}

/**
 * Вопрос и варианты.
 *
 * Текущий человек — первым и уже отмеченным: чаще всего он и есть. Остальные — с
 * именем, а не «другой профиль».
 */
export function ask(current: Person, others: readonly Person[]): { said: string; options: Person[] } {
  return {
    said: `Опасное дело: оно выполнится от имени «${current.name}». Это вы?`,
    options: [current, ...others],
  };
}

/**
 * Что меняется после ответа.
 *
 * Права — по выбранному человеку (шаг 403), память — его. Само дело при этом не
 * начинается заново: переключение встраивается, а не перезапускает (шаг 412).
 */
export function after(picked: Person, current: Person): { changed: boolean; said: string } {
  if (picked.id === current.id) return { changed: false, said: `выполняю от имени «${picked.name}»` };
  return { changed: true, said: `теперь дело идёт от имени «${picked.name}»: права и память — его, шаги, которые уже выполнены, остаются выполненными` };
}

/**
 * Что происходит с уже выполненными шагами.
 *
 * Не откатываются и не переименовываются: они были выполнены от имени прежнего
 * человека, и журнал это помнит (шаг 414). Притвориться, что всё сделал новый, —
 * это ложь в журнале.
 */
export function alreadyDone(count: number): string {
  if (count === 0) return "выполненных шагов нет: дело начнётся с первого";
  return `уже выполнено ${count} ${count === 1 ? "шаг" : "шагов"} от прежнего человека — в журнале так и останется`;
}

/**
 * Чего переключение не делает.
 *
 * Три соблазна — угадать, спрашивать на каждом шаге, перезапустить дело.
 */
export function notDo(): string[] {
  return [
    "не угадывает по поведению: ошибка стоит дорого, а вопрос — секунды",
    "не спрашивает на каждом шаге: ответ держится до конца дела",
    "не перезапускает дело: переключение встраивается в уже идущее",
  ];
}
