/**
 * Один вход: поле «скажи или напиши», которое всегда на виду (шаг 181).
 *
 * Зачем правило, а не просто поле в разметке. У одного поля два исхода, и
 * разница между ними — не оформление, а то, что человек получит:
 *
 *  * **вход совпал с экраном** («голос», «журнал», «руки») — ведём туда. Человек
 *    набрал название экрана, а не фразу для разговора, и отправить это в модель
 *    значило бы ответить ему «не понял» на вопрос, которого он не задавал;
 *  * **иначе** — это фраза для разговора, и она уходит на экран «Голос» вместе с
 *    собой, чтобы не набирать второй раз.
 *
 * Почему совпадение должно быть **полным**, а не по подстроке. Палитра ищет
 * подстрокой: «го» находит «Голос» — это удобно, когда цель — экран. Но здесь
 * «го» в ответ на фразу «го в папку» уведёт человека с разговора на экран,
 * который он не просил. Поэтому экраном считается только совпадение целиком
 * (после `fold`: регистр и ё/е — не разница), и ничего больше.
 */

import { filterCommands, fold, type Command } from "./commands";

/** Что сделать с тем, что человек набрал в едином поле. */
export type EntryOutcome =
  /** Перейти на экран. `label` — как экран называется, чтобы это было видно. */
  | { kind: "screen"; id: string; label: string }
  /** Отправить как фразу в разговор. `text` уже обрезан по краям. */
  | { kind: "phrase"; text: string }
  /** Набрано только пробельное — делать нечего. */
  | { kind: "empty" };

/**
 * Разобрать то, что набрано в едином поле.
 *
 * `commands` — тот же список, что у палитры (`Ctrl+K`): два поля, которые ведут
 * по экранам, не должны знать разные имена экранов.
 */
export function readEntry(commands: readonly Command[], query: string): EntryOutcome {
  const text = query.trim();
  if (text.length === 0) return { kind: "empty" };

  // Совпадение целиком, а не подстрокой: см. объяснение в начале файла.
  const needle = fold(text);
  const screen = filterCommands(commands, text).find(
    (command) =>
      fold(command.label) === needle ||
      (command.keywords ?? []).some((word) => fold(word) === needle),
  );

  if (screen) return { kind: "screen", id: screen.id, label: screen.label };
  return { kind: "phrase", text };
}
