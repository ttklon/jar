/**
 * Явный индикатор «сейчас услышат» (шаг 49).
 *
 * Дефект. Включён ли микрофон, человек угадывал: кнопка меняла цвет, и всё.
 * Цвет — плохой ответ на вопрос «меня слышат?»: его не видит дальтоник, не
 * слышит диктор, не замечает тот, кто смотрит в сторону, и не передаёт трей.
 * Человек говорит в пустоту, а приложение молчит — и он решает, что оно
 * сломалось.
 *
 * Правило: у микрофона **всегда** есть слово. Не «иконка» и не «оттенок», а
 * слово, которое можно прочитать, услышать и передать иконке в трее. Цвет
 * остаётся подсказкой, но он **второй**, а не единственный.
 *
 * Состояний шесть, и каждое отличается словом, потому что они значат разное:
 *
 *  * **не слушаю** — микрофон закрыт. Это норма, а не ошибка;
 *  * **слушаю** — прямо сейчас речь уходит в распознавание;
 *  * **услышал, разбираю** — речь закончилась, идёт разбор;
 *  * **думаю** — разбор закончился, идёт ответ;
 *  * **спрашиваю подтверждения** — пауза, человек должен решить;
 *  * **ошибка** — что-то не так, и названо что.
 *
 * Почему не одно «активно / неактивно». «Слушаю» и «разбираю» человеку нужно
 * различать: в первом случае можно перебить словом, во втором — уже поздно, надо
 * ждать. Склеить их значит отнять у человека возможность понять, что происходит.
 */

/** Что происходит с микрофоном. */
export type MicState = "closed" | "listening" | "parsing" | "thinking" | "asking" | "error";

/**
 * Слово для каждого состояния.
 *
 * Написано так, как человек сказал бы вслух: «слушаю», а не «активен». Слово
 * должно читаться в трее при 16 пикселях и произноситься диктором без запинки.
 */
export const MIC_WORD: Record<MicState, string> = {
  closed: "не слушаю",
  listening: "слушаю",
  parsing: "услышал, разбираю",
  thinking: "думаю",
  asking: "жду ответа",
  error: "не получилось",
};

/**
 * Слышит ли приложение прямо сейчас.
 *
 * Только `listening`: в остальных состояниях микрофон закрыт, и «услышат» было
 * бы неправдой. Это то, что подсвечивается — и то же самое передаётся в трей.
 */
export function hears(state: MicState): boolean {
  return state === "listening";
}

/**
 * Слово для трея. Короче, потому что места мало, но **то же самое по смыслу**.
 *
 * Отдельная функция, а не обрезка: обрезка «услышал, разбираю» до «услышал»
 * теряет разницу с «слушаю», и человек в трее видит одно и то же в двух разных
 * состояниях. Это и есть дефект, от которого уходим.
 */
export const TRAY_WORD: Record<MicState, string> = {
  closed: "микрофон выключен",
  listening: "слушаю",
  parsing: "разбираю",
  thinking: "думаю",
  asking: "жду ответа",
  error: "ошибка",
};

/** Разные слова для разных состояний — проверяемое свойство, а не пожелание. */
export function allWordsDistinct(): boolean {
  const words = Object.values(MIC_WORD);
  return new Set(words).size === words.length;
}

/**
 * Что человеку сказать словами — для диктора и подсказки.
 *
 * Здесь можно длиннее: экран и диктор не ограничены местом трея. Главное —
 * сказать **что это значит**, а не только «состояние».
 */
export function sayWord(state: MicState): string {
  switch (state) {
    case "closed":
      return "микрофон выключен — приложение не слышит";
    case "listening":
      return "слушаю: говорите, я услышу";
    case "parsing":
      return "услышал — разбираю сказанное";
    case "thinking":
      return "думаю над ответом";
    case "asking":
      return "жду вашего ответа";
    case "error":
      return "не получилось — причина на экране";
  }
}
