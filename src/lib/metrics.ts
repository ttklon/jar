/**
 * Шаг 244: метрики в CI — сколько фраз понято, сколько дел дошло до конца.
 *
 * Почему именно эти две и почему в CI. Про продукт легко сказать «стало лучше» и
 * нельзя проверить: у нас нет ни одного числа, которое **меняется от правки**.
 * Два числа закрывают это, и оба считаются из журнала, а не из ощущения:
 *
 *  * **сколько фраз понято** — доля просьб, для которых нашлось дело, от всех
 *    произнесённых. Падение здесь значит «перестали понимать», и это видно в
 *    первый же день, а не по жалобе через месяц;
 *  * **сколько дел дошло до конца** — доля доведённых до `ok` от начатых.
 *    Падение здесь значит «стали бросать на середине»: самая дорогая поломка,
 *    потому что человек уже потратил время.
 *
 * Три правила, без которых метрика хуже отсутствия метрики:
 *
 *  1. **знаменатель назван.** «Понято 87%» без «из чего» — не число. Каждая
 *     метрика отвечает, от чего считается доля;
 *  2. **ноль и «не измеряли» — разные вещи.** Пустая неделя даёт `null`, а не
 *     `0%`: ноль — это «перестали понимать», а не «никто не говорил»;
 *  3. **порог, а не «смотрим глазами».** CI падает, когда число хуже порога, и
 *     порог назван в коде. Иначе «упало на 30%» замечают через месяц.
 *
 * Чего модуль не делает: не собирает данные сам. Он считает по записям журнала:
 * так его проверяют на подставных числах, а не на живой машине.
 */

/** Одна запись журнала в том виде, в каком она нужна метрике. */
export interface Line {
  /** Была ли фраза понята: нашлось ли для неё дело. */
  readonly understood: boolean;
  /** Дело было начато (иначе фраза понята, но до дела не дошло). */
  readonly started: boolean;
  /** Дело закончилось успехом. `false` и у провала, и у отмены. */
  readonly finished: boolean;
}

/** Одно число: доля, знаменатель и порог. */
export interface Metric {
  /** Имя для CI: по нему находят, что упало. */
  readonly name: string;
  /** Доля 0..1 или `null`, если считать не из чего. */
  readonly value: number | null;
  /** Из чего считается: число в знаменателе. */
  readonly of: number;
  /** Порог: ниже — CI падает. */
  readonly floor: number;
  /** Словами, что значит падение. */
  readonly means: string;
}

/**
 * Пороги.
 *
 * Не «примерно 80», а два разных числа, потому что поломки разные:
 *
 *  * понимание ниже **85%** — человек повторяет одну просьбу дважды из семи.
 *    Это уже не «иногда», а «пользуются и злятся»;
 *  * доведение ниже **70%** — больше трёх из десяти дел бросаются на середине.
 *    Столько человек не прощает: он уже потратил время и получил обломок.
 *
 * Оба числа — не цель, а **пол**: цель выше. Порог выбирается по тому, когда
 * становится стыдно, а не по тому, чего легко достичь.
 */
export const FLOORS = {
  understood: 0.85,
  finished: 0.7,
} as const;

/** Сколько фраз понято: доля `understood` от всех строк. */
export function understoodOf(lines: readonly Line[]): Metric {
  return rate(
    "understood",
    lines.filter((line) => line.understood).length,
    lines.length,
    FLOORS.understood,
    "перестали понимать: человек повторяет просьбу дважды",
  );
}

/** Сколько дел доведено до конца: доля `finished` от **начатых**, а не от всех. */
export function finishedOf(lines: readonly Line[]): Metric {
  // Знаменатель — начатые дела, а не все строки: фраза, которую поняли и на
  // которую человек передумал, не «брошенное на середине дело». Считать её
  // провалом значило бы наказывать за честную отмену.
  const started = lines.filter((line) => line.started);
  return rate(
    "finished",
    started.filter((line) => line.finished).length,
    started.length,
    FLOORS.finished,
    "стали бросать на середине: время потрачено, результата нет",
  );
}

function rate(
  name: string,
  hit: number,
  of: number,
  floor: number,
  means: string,
): Metric {
  // «Не измеряли» — это `null`, а не ноль: ноль означает «перестали», и путать
  // их значит поднимать тревогу на пустой неделе и молчать на настоящей поломке.
  const value = of === 0 ? null : hit / of;
  return { name, value, of, floor, means };
}

/** Все метрики разом: то, что печатает CI. */
export function all(lines: readonly Line[]): Metric[] {
  return [understoodOf(lines), finishedOf(lines)];
}

/** Прошло ли число порог. `null` (не измеряли) не считается провалом. */
export function passes(metric: Metric): boolean {
  return metric.value === null || metric.value >= metric.floor;
}

/** Что CI должен сказать: строка на метрику, с числом и знаменателем. */
export function report(metrics: readonly Metric[]): string[] {
  return metrics.map((metric) => {
    const name = metric.name === "understood" ? "фраз понято" : "дел доведено";
    if (metric.value === null) {
      return `${name}: не измеряли — записей нет (это не 0%, а «нечего считать»)`;
    }
    const percent = Math.round(metric.value * 1000) / 10;
    const floor = Math.round(metric.floor * 100);
    const verdict = passes(metric) ? "ok" : `ниже порога ${floor}%: ${metric.means}`;
    return `${name}: ${percent}% из ${metric.of} — ${verdict}`;
  });
}

/** Есть ли провал: по этому CI решает, краснеть ли. */
export function failed(metrics: readonly Metric[]): boolean {
  return metrics.some((metric) => !passes(metric));
}

/**
 * Сравнение с прошлым прогоном.
 *
 * Зачем: «сегодня 84%» само по себе не говорит, стало хуже или лучше. Падение на
 * пять пунктов при пороге 85 — это регресс, даже если вчера было 90. А рост с 60
 * до 84 (ниже порога) — движение в верную сторону, и краснеть на нём незачем
 * сверх порога.
 */
export function compared(current: Metric, previous: number | null): string {
  if (current.value === null) return "сравнивать не с чем: сейчас нечего считать";
  if (previous === null) return "сравнивать не с чем: прошлого прогона нет";
  const delta = Math.round((current.value - previous) * 1000) / 10;
  if (delta === 0) return "без изменений";
  const sign = delta > 0 ? "+" : "";
  return `${sign}${delta} п.п. к прошлому прогону`;
}
