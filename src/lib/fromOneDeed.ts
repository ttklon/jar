/**
 * Шаг 332: автоматизация создаётся из уже сделанного дела одной кнопкой «каждый день».
 *
 * Человек не программирует расписание: он **только что сделал дело руками** и,
 * если оно оказалось полезным, говорит «а давай каждый день». Всё, что нужно для
 * правила, уже есть в этом деле:
 *
 *  * **что** — план, который только что выполнился;
 *  * **когда** — время запуска, если оно в деле было;
 *  * **доверие** — само дело было подтверждено человеком (шаг 323).
 *
 * Поэтому кнопка не открывает форму. Она берёт дело и показывает, что получится.
 *
 * Ограничение, которое надо назвать: **не всякое дело можно повторить**. Дело с
 * параметром «этот файл» каждый день будет повторяться над тем же файлом, который
 * к тому времени уже удалён. Такое правило создаётся, но сразу говорит, что
 * сломается.
 */

/** Сделанное дело. */
export interface Done {
  /** Название — словами человека. */
  readonly what: string;
  /** Когда начали — миллисекунды. */
  readonly at: number;
  /** Шаги, которые выполнились. */
  readonly steps: readonly { readonly kind: string; readonly target: string }[];
  /** Подтверждал ли человек каждый шаг. */
  readonly confirmed: boolean;
}

/** Что получится. */
export interface Made {
  /** Можно ли создать правило. */
  readonly ok: boolean;
  /** Текст кнопки — действие и время. */
  readonly label: string;
  /** Что будет происходить. */
  readonly said: string;
  /** Что сломается со временем. */
  readonly warning: string | null;
}

/**
 * Создать правило из дела.
 *
 * Время берётся из дела: если оно было в 09:12, правило будет «каждый день в
 * 09:12», а не «в 09:00» — человек делал в это время не случайно.
 */
export function fromDeed(deed: Done): Made {
  if (!deed.confirmed) {
    return {
      ok: false,
      label: "",
      said: "это дело не подтверждено: автоматизировать то, чего человек не делал сам, нельзя",
      warning: null,
    };
  }
  if (deed.steps.length === 0) {
    return { ok: false, label: "", said: "в деле не было шагов — повторять нечего", warning: null };
  }

  // Время — локальное: человек делал дело в 9 утра по своим часам, а не по UTC.
  const date = new Date(deed.at);
  const minute = date.getHours() * 60 + date.getMinutes();
  const clock = `${String(Math.floor(minute / 60)).padStart(2, "0")}:${String(minute % 60).padStart(2, "0")}`;

  // Шаг с конкретным файлом: путь, который завтра может не существовать.
  const concrete = deed.steps.find((step) => /[\\/]/.test(step.target) || /\.\w{2,4}$/.test(step.target));
  const warning = concrete
    ? `в деле был конкретный файл (${concrete.target}): если его не будет, дело пропустится с причиной, а не упадёт`
    : null;

  return {
    ok: true,
    label: `Каждый день в ${clock}`,
    said: `каждый день в ${clock}: ${deed.what}`,
    warning,
  };
}

/**
 * Что показывается до создания.
 *
 * Три строки — когда, что, что будет с пропуском. Формы нет: всё уже в деле.
 */
export function preview(made: Made): string {
  if (!made.ok) return made.said;
  const lines = [made.said, "если компьютер спал — спрошу, сделать ли пропущенное"];
  if (made.warning) lines.push(made.warning);
  return lines.join("\n");
}

/**
 * Кнопка появляется только там, где дело уже было.
 *
 * Не «создать автоматизацию» в пустом списке: без дела нет ни времени, ни
 * доверия, и получится форма, из-за которой люди не пользуются расписаниями.
 */
export function whereButton(): string {
  return "после выполненного дела — «Каждый день в это время», а не в отдельном разделе настроек";
}

/**
 * Что происходит, когда дело повторить нельзя.
 *
 * Честный отказ лучше правила, которое сломается завтра: дело «удалить эти 12
 * файлов» не повторяется, потому что файлов больше нет.
 */
export function notRepeatable(reason: string): string {
  return `это дело нельзя повторять каждый день: ${reason}. Можно создать правило «когда появляется файл» — оно не зависит от конкретных имён`;
}
