/**
 * Два дела в одной фразе — разложить и сделать по очереди (шаг 83).
 *
 * Дефект. «Найди отчёт за март и отправь его маме» — сегодня фраза съедается
 * **целиком**: разбор ищет глагол (находит «найди»), и второй глагол либо
 * теряется, либо превращает фразу в одну команду, которую модель выполняет
 * так, как ей удобно. Следствия:
 *
 *  * **вторая половина теряется молча** — человек думает, что отправлено, а
 *    отправлено не было;
 *  * **порядок нарушается**: «найди и отправь» исполняется как «отправь», если
 *    отправка нашлась лучше по словам, — и тогда отправляется не то;
 *  * **связь между делами теряется**: «его» во второй половине указывает на
 *    результат первой, и без разложения это «его» некуда приложить.
 *
 * Правило: **разложить, показать и сделать по очереди**.
 *
 *  1. Разделять по **союзу и по второму глаголу**, а не по запятой: запятая в
 *     русской речи ставится и внутри одного дела.
 *  2. **Порядок сохраняется**: дела исполняются в том порядке, в котором
 *     сказаны, потому что человек сказал их в этом порядке не случайно.
 *  3. Второе дело может **ссылаться на первое** («его», «туда»): связь
 *     сохраняется, а не теряется.
 *  4. Если второе дело **зависит** от результата первого (отправить найденное),
 *     оно не начинается, пока первое не завершилось.
 *  5. Обе половины **видны человеку** до исполнения: иначе он узнает о второй,
 *     когда она уже случилась.
 *
 * Почему не «модель сама разберётся». Модель разберётся, но **не покажет** и
 * **не остановится**, если первое дело не удалось: она сделает второе с тем,
 * что есть. А «отправить не тот файл» — ошибка, которую видно не сразу.
 */

import { parse, type Intent } from "./intent";

/** Одно дело. */
export interface Deed {
  /** Текст дела — как сказал человек. */
  text: string;
  /** Разбор дела: глагол, объект, определение. */
  intent: Intent;
  /** Ссылается ли на результат предыдущего дела («его», «туда», «этот»). */
  usesPrevious: boolean;
}

/**
 * Разделители двух дел.
 *
 * Союз «и» — только когда дальше идёт **глагол**: «найди и покажи» — два дела,
 * «найди отчёты и письма» — одно. Это различие и есть суть шага.
 */
const CONJUNCTIONS = /(?:^|\s)(?:и|потом|затем|после этого|а потом)(?=\s)/gi;

/** Слова, которые ссылаются на предыдущий результат. */
const BACK_REFERENCES = /(?:^|\s)(?:его|её|ее|их|туда|этот|эту|это|тот|той|из него|из неё|из нее)(?=\s|$)/i;

/**
 * Разложение фразы на дела.
 *
 * Если дело одно — возвращается одно дело: разложение не должно ломать простые
 * фразы ради единообразия.
 */
export function split(phrase: string): Deed[] {
  const clean = phrase.trim();
  if (clean.length === 0) return [];

  const parts: string[] = [];
  let start = 0;
  // Свой экземпляр на каждый вызов: у общего regex с флагом g `lastIndex`
  // сохраняется между вызовами, и второй раз фраза не делится вовсе.
  const marks = new RegExp(CONJUNCTIONS.source, CONJUNCTIONS.flags);
  let found: RegExpExecArray | null;
  while ((found = marks.exec(clean)) !== null) {
    const after = clean.slice(found.index + found[0].length).trim();
    const head = after.split(/\s+/)[0] ?? "";
    // «И» перед не-глаголом — это перечисление объектов, а не второе дело.
    const candidate = asDeed(after);
    if (candidate.intent.verb === "неизвестно") continue;
    if (head.length === 0) continue;
    parts.push(clean.slice(start, found.index).trim());
    start = found.index + found[0].length;
  }
  parts.push(clean.slice(start).trim());

  return parts
    .filter((part) => part.length > 0)
    .map((part) => asDeed(part));
}

function asDeed(text: string): Deed {
  return {
    text,
    intent: parse(text),
    usesPrevious: BACK_REFERENCES.test(text),
  };
}

/**
 * Сколько дел.
 *
 * Названо числом, а не «несколько»: человек должен видеть, что приложение
 * поняло два дела, а не одно длинное.
 */
export function count(deeds: readonly Deed[]): number {
  return deeds.length;
}

/**
 * Можно ли начинать второе дело.
 *
 * Если второе ссылается на первое («отправь **его**»), оно не начинается, пока
 * первое не завершилось: иначе отправлять нечего.
 */
export function ready(deeds: readonly Deed[], index: number, previousOk: boolean): boolean {
  if (index === 0) return true;
  return !(deeds[index]?.usesPrevious ?? false) || previousOk;
}

/**
 * Что сказать до исполнения — список дел по порядку.
 *
 * Обе половины видны **до**: иначе человек узнает о второй, когда она уже
 * случилась.
 */
export function plan(deeds: readonly Deed[]): string[] {
  return deeds.map((deed, index) => {
    const chain = deed.usesPrevious ? " — с тем, что получилось в предыдущем" : "";
    return `${index + 1}. ${deed.text}${chain}`;
  });
}

/**
 * Что делать, если первое дело не удалось.
 *
 * **Остановиться** и сказать, а не продолжать: второе дело обычно зависит от
 * первого, и «отправить что осталось» — это не то, что просили. Человек решает
 * сам, продолжать ли.
 */
export function failed(deeds: readonly Deed[], index: number): string {
  const next = deeds[index + 1];
  if (next === undefined) {
    return `дело ${index + 1} не вышло: «${deeds[index]?.text ?? ""}» — дальше дел нет`;
  }
  return next.usesPrevious
    ? `дело ${index + 1} не вышло: «${deeds[index]?.text ?? ""}». Дальше — «${next.text}», и она опирается на результат: не начинаю, иначе сделаю не то`
    : `дело ${index + 1} не вышло: «${deeds[index]?.text ?? ""}». Дальше — «${next.text}»: продолжить или остановиться — решайте вы`;
}

/**
 * Сказано ли, что дело не одно.
 *
 * Молчаливое деление фразы на два дела хуже, чем неделение: человек не ждёт
 * второго действия и не понимает, почему приложение что-то ещё делает.
 */
export function says(deeds: readonly Deed[]): string | null {
  return deeds.length > 1 ? `в фразе ${deeds.length} дела — сделаю по очереди, в вашем порядке` : null;
}
