/**
 * Шаг 439: журнал доступен только своему профилю.
 *
 * Профили разделяют память и разрешения (шаг 401), поиск (шаг 418). Журнал — тот
 * же вопрос, но с одной оговоркой, и она важная:
 *
 *  * **свой журнал человек видит всегда** — это его дела;
 *  * **чужой журнал гость не видит никогда** — иначе «гостевой режим» перестаёт
 *    быть режимом (шаг 405);
 *  * **хозяину компьютера чужие дела видны** — он отвечает за то, что здесь
 *    происходит, и без этого не сможет ни разобраться, ни удалить чужой профиль
 *    (шаг 404).
 *
 * Разница с `profileSearchScope` (шаг 418): там — поиск, здесь — **доступ к
 * журналу целиком**, включая экспорт для поддержки (шаг 423). Экспорт — самый
 * опасный путь: он отдаёт файл наружу.
 */

import type { Profile } from "./peopleProfiles";

/** Что делает человек с журналом. */
export type Action = "read" | "export" | "delete" | "statistics";

/**
 * Можно ли.
 *
 * `owner` — кто владеет делами. `ownerOfComputer` — заведён ли он хозяином
 * (у гостя его нет по определению).
 */
export function may(viewer: Profile, owner: Profile, action: Action, ownerOfComputer: boolean): { ok: boolean; said: string } {
  if (viewer.person.id === owner.person.id) {
    return { ok: true, said: "свой журнал: своё и читать, и выгружать, и стирать" };
  }

  if (viewer.guest) {
    return { ok: false, said: "гость чужих дел не видит: ни читать, ни выгружать, ни считать" };
  }

  if (!ownerOfComputer) {
    return { ok: false, said: "чужие дела видны только хозяину компьютера — он отвечает за то, что здесь происходит" };
  }

  // Хозяину — чтение и счётчики; удаление чужого журнала не «право», а часть
  // удаления профиля (шаг 417), где есть подтверждение и выбор.
  if (action === "delete") {
    return { ok: false, said: "чужой журнал не удаляется вручную: он уходит только с профилем и с подтверждением" };
  }
  return { ok: true, said: action === "export" ? "хозяину можно выгрузить и чужой журнал — но в файле будет видно, чей он" : "хозяину можно: он отвечает за компьютер" };
}

/**
 * Отфильтровать записи журнала.
 *
 * Не «показать и потом спрятать»: отброшенное не должно доходить до списка.
 */
export function visible<T extends { readonly owner: string }>(viewer: Profile, owner: Profile, entries: readonly T[], ownerOfComputer: boolean): T[] {
  return may(viewer, owner, "read", ownerOfComputer).ok ? [...entries] : [];
}

/**
 * Что происходит с журналом, когда профиль удаляют.
 *
 * Не удаляется автоматически: журнал — история машины, и в нём есть дела других
 * людей (шаг 417). Автор остаётся строкой.
 */
export function onDelete(name: string): string {
  return `журнал остаётся: дела «${name}» были историей этой машины, и в них есть другие люди. Автор в строках сохраняется`;
}

/**
 * Что проверяет тест.
 *
 * Три случая — и все три про разные ответы.
 */
export function cases(): { who: string; sees: string }[] {
  return [
    { who: "свой журнал", sees: "всегда" },
    { who: "чужой журнал у гостя", sees: "никогда" },
    { who: "чужой журнал у хозяина компьютера", sees: "виден, кроме удаления" },
  ];
}
