/**
 * Шаг 97: перебивание — заговорил, и приложение замолчало.
 *
 * Приложение, которое говорит и не слышит, что его перебивают, — это не разговор, а
 * радио. Человек ждёт конца фразы, забывает, что хотел, и раздражается.
 *
 * Поэтому правило простое и симметричное на **обеих** кнопках микрофона (в окне и в
 * трее): заговорил — приложение замолчало **сразу**, на середине слова.
 *
 * Но есть тонкость, из-за которой это не «выключить звук при любом шуме»:
 *
 *  * **свой голос** приложения попадает в микрофон и «перебивает сам себя»: его
 *    надо отличать от человека;
 *  * **кашель и хлопок** — не речь: тишина после них должна вернуть фразу;
 *  * после перебивания **фраза не теряется**: она договаривается словами, а не
 *    «начнём сначала».
 */

/** Что слышно. */
export type Heard = "речь человека" | "свой голос" | "шум" | "тишина";

/** Состояние. */
export interface State {
  /** Говорит ли приложение сейчас. */
  readonly speaking: boolean;
  /** Что накоплено для повторения, если человек перебил середину. */
  readonly saidSoFar: string;
}

/** Сколько тишины должно пройти, чтобы вернуться к фразе. */
export const RESUME_MS = 800;

/**
 * Реакция на звук.
 *
 * Четыре исхода, и все разные. Главное: **свой голос не перебивает**.
 */
export function onHeard(state: State, heard: Heard): { state: State; said: string } {
  if (heard === "речь человека") {
    return { state: { ...state, speaking: false, saidSoFar: `${state.saidSoFar} [перебито]` }, said: "замолчал сразу: говорите" };
  }
  if (heard === "свой голос") {
    return { state, said: "это мой голос — продолжаю, перебивания нет" };
  }
  if (heard === "шум") {
    return { state, said: "шум — не перебивание, продолжаю фразу" };
  }
  return { state, said: "тишина: если человек не вернулся, фраза продолжится сама" };
}

/**
 * Возврат к фразе.
 *
 * Три условия: прошло достаточно тишины, приложение не говорит, фраза не закончена.
 * «Начнём сначала» — запрещено: человек уже слышал начало.
 */
export function resume(state: State, silentFor: number): { state: State; said: string } {
  if (state.speaking) return { state, said: "уже говорю: возвращаться некуда" };
  if (silentFor < RESUME_MS) return { state, said: `подожду ещё ${RESUME_MS - silentFor} мс тишины` };
  if (state.saidSoFar === "") return { state, said: "фраза не начиналась: говорить нечего" };

  return { state: { ...state, speaking: true }, said: "продолжаю с того места, где остановился: начало вы уже слышали" };
}

/**
 * Обе кнопки.
 *
 * Три места, где перебивание обязано работать одинаково: окно, трей, горячая
 * клавиша. Разное поведение в трёх местах человек читает как «глючит».
 */
export function sameEverywhere(): string[] {
  return ["кнопка в окне", "значок в трее", "горячая клавиша"];
}

/**
 * Чего перебивание не делает.
 *
 * Три запрета; главный — не начинать сначала.
 */
export function notDo(): string[] {
  return [
    "не начинает фразу сначала: человек уже слышал начало",
    "не замолкает от своего голоса: приложение перебило бы само себя",
    "не считает шум речью: кашель не должен обрывать объяснение",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу исходов, которые легко перепутать.
 */
export function checks(): string[] {
  return [
    "речь человека — замолкает сразу",
    "свой голос и шум — не перебивание",
    "после перебивания фраза договаривается, а не начинается заново",
  ];
}
