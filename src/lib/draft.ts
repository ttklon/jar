/**
 * Черновик фразы: то, что человек уже набрал или сказал, но ещё не отправил.
 *
 * Зачем отдельный модуль, а не `useState` и `localStorage` в экране. Потеря
 * фразы — худший первый опыт (шаг 26): человек говорил, приложение закрылось
 * (обновление, трей, перезагрузка), и сказанное исчезло. Это не «неудобство»,
 * это повод больше не говорить.
 *
 * Четыре решения, которые легко сделать неправильно:
 *
 *  * **черновик сохраняется на каждое изменение, а не на «отправить».** Момент,
 *    когда приложение закрывают, выбрать нельзя — значит, писать надо сразу.
 *    Запись мелкая и редкая (человек печатает, а не цикл в 60 Гц), и это дешевле
 *    любой попытки поймать закрытие окна;
 *  * **отправленная фраза черновик не оставляет.** Иначе на следующем запуске
 *    человек видит свой же прошлый вопрос и думает, что он не ушёл. Уборка идёт
 *    там, где фраза стала делом, а не в экране;
 *  * **сломанное хранилище — это «черновик не сохранился», а не падение.**
 *    Приложение работает и без него; хуже было бы потерять экран из-за записи;
 *  * **пустой черновик не хранится.** `""` — это «ничего не набрано», и держать
 *    его в хранилище значит при следующем запуске делать вид, что что-то было.
 *
 * Модуль ничего не знает про React: он про правило, а не про экран. Поэтому его
 * проверяют тестами без рендера.
 */

import { availableStorage, type StorageLike } from "./firstRun";

/** Ключ один: черновик у приложения один — фраза, которую человек ещё не сказал. */
export const DRAFT_KEY = "zshelper.draft.phrase";

/**
 * Сколько символов максимум помним.
 *
 * Не ради экономии места: хранилище небольшое, и одна «фраза» в мегабайт
 * вытеснила бы очередь дел. Ограничение названо явно, чтобы оно не выяснилось
 * молчаливой потерей черновика целиком.
 */
export const DRAFT_LIMIT = 4000;

/** Что сохранить. Пусто или только пробелы — значит, стираем черновик. */
export function saveDraft(text: string, storage: StorageLike | null = availableStorage()): boolean {
  // Хранилища нет — сказать «не сохранил» честно, но не бросать.
  if (!storage) return false;
  try {
    if (text.trim() === "") {
      storage.removeItem(DRAFT_KEY);
      return true;
    }
    storage.setItem(DRAFT_KEY, text.slice(0, DRAFT_LIMIT));
    return true;
  } catch {
    return false;
  }
}

/** Что было набрано в прошлый раз. Пусто — ничего не было или прочитать нельзя. */
export function readDraft(storage: StorageLike | null = availableStorage()): string {
  if (!storage) return "";
  try {
    const value = storage.getItem(DRAFT_KEY);
    if (value === null) return "";
    // Обрезанный хвост не должен превращаться в другой по смыслу вопрос,
    // поэтому лимит применяется и при чтении — на случай чужой записи.
    return value.slice(0, DRAFT_LIMIT);
  } catch {
    return "";
  }
}

/**
 * Фраза стала делом — черновик больше не нужен.
 *
 * Отдельная функция, а не `saveDraft("")`: так место, где убирают, само говорит,
 * почему убирает. `saveDraft("")` читается как «человек стёр текст», а это другое
 * событие, и путать их в коде опасно: однажды `saveDraft("")` перестанет значить
 * «убрать», и отправка перестанет чистить.
 */
export function clearDraft(storage: StorageLike | null = availableStorage()): void {
  if (!storage) return;
  try {
    storage.removeItem(DRAFT_KEY);
  } catch {
    // Не убралось — не беда: следующий `saveDraft` перезапишет черновик.
  }
}
