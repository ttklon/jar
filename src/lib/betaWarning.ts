/**
 * Шаг 315: канал beta с явным предупреждением — выбор человека, а не сюрприз.
 *
 * Beta нужна не «для смелых», а чтобы ловить поломки до stable. И чтобы она
 * работала, человек должен понимать, на что подписывается, **до** переключения,
 * а не из письма «извините, мы вас сломали».
 *
 * Что предупреждение обязано сказать, иначе это не предупреждение:
 *
 *  1. **что beta может сломаться** — не «возможны ошибки» вообще, а что именно
 *     уже ломалось: голос, руки, обновление данных;
 *  2. **что данные совместимы вперёд, но не назад** — перешли на beta со схемой
 *     4, вернуться на stable со схемой 3 можно, но новые записи она не увидит
 *     (шаги 313/314);
 *  3. **как вернуться** — одна кнопка, и она будет, а не «напишите нам»;
 *  4. **что beta обновляется чаще** — и это не опция.
 *
 * Согласие фиксируется **по каналу**, а не «галочкой при установке»: переключение
 * в beta — отдельное действие с отдельным «понятно».
 */

/** Что человеку говорят перед переключением. */
export interface Warning {
  readonly title: string;
  readonly lines: readonly string[];
  /** Текст кнопки — действие, а не «ОК». */
  readonly confirm: string;
}

/** Что уже ломалось в beta — живые примеры важнее общих слов. */
export const KNOWN_BREAKS = [
  "голос: распознавание иногда теряло первую секунду фразы",
  "руки: клик по кнопке мог уйти не в то окно",
  "данные: откат на stable после beta терял последние записи — теперь предупреждаем заранее",
];

/** Предупреждение перед переключением на beta. */
export function warning(fromSchema: number): Warning {
  return {
    title: "Канал beta: программа может ломаться",
    lines: [
      "beta обновляется чаще и раньше: обновления приходят без вашего участия",
      ...KNOWN_BREAKS.slice(0, 2).map((line) => `уже ломалось: ${line}`),
      `данные: если вернётесь на stable, её схема (${fromSchema - 1}) не увидит новые записи — копия делается перед возвратом`,
      "вернуться можно одной кнопкой в настройках, без переустановки",
    ],
    confirm: "Понятно, включить beta",
  };
}

/**
 * Проверка предупреждения.
 *
 * Ловит «возможны ошибки», «не рекомендуется новичкам» и кнопку «ОК» — всё, что
 * выглядит как предупреждение и ничего не говорит.
 */
export function audit(warn: Warning): string[] {
  const problems: string[] = [];
  const text = [warn.title, ...warn.lines].join(" ");

  if (/возможны ошибки|может быть нестабильн|не рекомендуется новичкам/i.test(text)) {
    problems.push("«возможны ошибки» — не предупреждение: не сказано, что именно ломается");
  }
  if (!/уже ломалось/.test(text)) problems.push("нет ни одного известного случая: значит, предупреждение выдумано");
  if (!/вернуться|вернётесь/i.test(text)) problems.push("не сказано, как вернуться");
  if (!/схем|данн/i.test(text)) problems.push("не сказано, что будет с данными");
  if (/^(ок|ok|да|хорошо)$/i.test(warn.confirm.trim())) {
    problems.push("кнопка «ОК» не подтверждает согласие: нужно действие словами");
  }
  if (warn.lines.length < 3) problems.push("меньше трёх строк — это не предупреждение, а отговорка");

  return problems;
}

/**
 * Согласие: помним, на что именно согласился человек.
 *
 * «Согласился на beta» недостаточно: через полгода beta станет другой, а
 * согласие — тем же. Поэтому запоминаем **версию предупреждения** и показываем
 * новое, если текст изменился.
 */
export interface Consent {
  readonly channel: "stable" | "beta";
  /** Отпечаток текста предупреждения. */
  readonly textHash: string;
  readonly at: number;
}

export function consent(warn: Warning, at: number): Consent {
  // Отпечаток без криптографии: достаточно, чтобы отличать тексты.
  const text = [warn.title, ...warn.lines, warn.confirm].join("|");
  let hash = 0;
  for (let i = 0; i < text.length; i += 1) hash = (hash * 31 + text.charCodeAt(i)) | 0;
  return { channel: "beta", textHash: String(hash), at };
}

/** Нужно ли показать предупреждение снова. */
export function needsWarning(saved: Consent | null, current: Warning): boolean {
  if (saved === null) return true;
  return saved.textHash !== consent(current, saved.at).textHash;
}

/**
 * Что beta меняет в поведении обновлений.
 *
 * Не «чаще приходят обновления» вообще, а: тихое обновление выключено, и это
 * **не настройка**, которую можно вернуть (шаг 318 рядом).
 */
export function policy(): string {
  return "в beta тихое обновление выключено всегда: приходит уведомление, ставит человек — beta не должна ставиться сама";
}
