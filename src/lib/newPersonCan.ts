/**
 * Шаг 498: новый человек может продолжить без меня — проверка зрелости.
 *
 * «Продолжить без меня» — это не про документацию. Это про то, что человек без
 * доступа к автору:
 *
 *  * **находит, где менять**: файл, тест, место в плане — по одному вопросу «где?»;
 *  * **понимает, почему так**: журнал решений (шаг 497);
 *  * **проверяет себя сам**: прогон, который говорит «да» или «нет» без меня;
 *  * **не наступает на те же грабли**: известные дефекты и ограничения описаны.
 *
 * Проверка зрелости — это **набор вопросов с машиночитаемыми ответами**. Если на
 * любой из них ответ «спросить автора», проект не готов: он держится на человеке,
 * который однажды уйдёт.
 */

/** Вопрос зрелости. */
export interface Question {
  /** Что должен уметь новый человек. */
  readonly can: string;
  /** Есть ли машинный ответ: путь в репозитории или команда. */
  readonly answer: string | null;
}

/**
 * Вопросы, на которые должен быть ответ.
 *
 * Пять — ровно те, на которых держится «продолжить без меня».
 */
export function questions(): Question[] {
  return [
    { can: "найти, где менять разбор фразы", answer: "src/lib/parsePhrase.ts" },
    { can: "добавить руку и проверить себя", answer: "docs/MASTER-PLAN-500.md + `npx vitest run`" },
    { can: "понять, почему решение такое, а не иное", answer: "docs/DECISIONS.md" },
    { can: "прогнать все проверки одной командой", answer: "`python3 tools/check_all.py`" },
    { can: "узнать, чего программа не делает", answer: "docs/LIMITS.md" },
  ];
}

/**
 * Проверка зрелости.
 *
 * Ответ `null` — «спросить автора». Это и есть единственный провал.
 */
export function check(list: readonly Question[] = questions()): { ok: boolean; missing: string[]; said: string } {
  const missing = list.filter((question) => question.answer === null || question.answer.trim() === "").map((question) => question.can);

  return {
    ok: missing.length === 0,
    missing,
    said: missing.length === 0
      ? `готово: на все ${list.length} вопросов есть машинный ответ, автор не нужен`
      : `не готово: «спросить автора» нужен для ${missing.length} (${missing.join("; ")})`,
  };
}

/**
 * Ответ обязан быть **машинным**.
 *
 * Путь или команда, а не «в документации». Мысль «в документации написано» — это
 * ровно то состояние, в котором автор ещё нужен.
 */
export function answerLooks(): string[] {
  return [
    "путь в репозитории: `src/lib/parsePhrase.ts`",
    "команда: `python3 tools/check_all.py`",
    "документ с названием: `docs/DECISIONS.md`",
  ];
}

/**
 * Чего проверка не делает.
 *
 * Три запрета; главный — «в документации» не ответ.
 */
export function notDo(): string[] {
  return [
    "не принимает «в документации написано» за ответ: нужен путь или команда",
    "не считает устный рассказ автора ответом: он не переживёт автора",
    "не проверяет «человек справится» на веру: проверка — набор вопросов, на каждый есть ответ",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу условий зрелости.
 */
export function checks(): string[] {
  return [
    "на каждый вопрос есть путь или команда",
    "ответ «спросить автора» — единственный провал",
    "проверка знает, как выглядит машинный ответ",
  ];
}
