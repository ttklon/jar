/**
 * Шаг 375: повторить дело — с изменённой фразой. Естественная правка.
 *
 * Человек сделал дело, оно почти подошло, и он хочет «то же, но в другую папку».
 * Плохой путь: заново набирать всю фразу. Хороший: «повторить», и фраза
 * открывается **для правки**, с уже подставленными значениями.
 *
 * Тонкость, из-за которой это отдельный шаг: правится **фраза**, а не поля формы.
 * «Почисти загрузки, только файлы старше месяца» — это то, что человек сказал, и
 * менять он хочет слово, а не выбирать «срок: 30 дней» из списка.
 *
 * И вторая тонкость: после правки **пересобирается план**, а не переиспользуется
 * старый. Иначе «другая папка» окажется в фразе, а удалять будет из прежней.
 */

/** Выполненное дело. */
export interface Done {
  /** Фраза, которую человек сказал. */
  readonly said: string;
  /** Что было сделано — чтобы показать последствия новой фразы. */
  readonly did: string;
}

/** Что правится. */
export interface Edit {
  /** Новая фраза. */
  readonly said: string;
  /** Чем отличается от прежней — словами. */
  readonly diff: string[];
}

/**
 * Открыть дело для правки.
 *
 * Возвращает фразу и **что поменялось**, если поменялось: человек должен видеть,
 * что он изменил, а не сравнивать два текста глазами.
 */
export function open(done: Done, said: string): Edit {
  return { said, diff: diff(done.said, said) };
}

/** Разница между фразами — по словам. */
export function diff(before: string, after: string): string[] {
  const a = words(before);
  const b = words(after);
  const removed = a.filter((word) => !b.includes(word));
  const added = b.filter((word) => !a.includes(word));

  const out: string[] = [];
  if (removed.length > 0) out.push(`убрано: ${removed.join(", ")}`);
  if (added.length > 0) out.push(`добавлено: ${added.join(", ")}`);
  return out;
}

function words(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[\s,.!?;:]+/)
    .filter((word) => word.length > 0);
}

/**
 * Что показывается до повторного запуска.
 *
 * Фраза, разница и **предупреждение о последствиях**: если шаг удаляет, а фраза
 * изменилась, повтор — это уже другое дело, и человек должен это видеть.
 */
export function preview(edit: Edit, dangerous: boolean): string[] {
  const lines = [`Повторить: ${edit.said}`];
  if (edit.diff.length > 0) lines.push(...edit.diff.map((line) => `  ${line}`));
  if (dangerous) lines.push("это дело меняет файлы: повтор выполнится заново, а не «доделает» прошлое");
  return lines;
}

/**
 * Что нельзя переиспользовать.
 *
 * План строится заново из новой фразы. Переиспользование плана — самая частая
 * ошибка: в фразе новая папка, а в плане старая.
 */
export function rebuild(): string {
  return "план строится заново из новой фразы: «другая папка» в фразе, а в плане — прежняя, и есть та ошибка, которую никто не замечает";
}

/**
 * Чего повтор не делает.
 *
 * Не «доделывает»: прошлое осталось прошлым, повтор — новое дело и новая запись
 * в журнале.
 */
export function notResume(): string {
  return "повтор — новое дело: он не «доделывает» прошлое и получает свою запись в журнале";
}
