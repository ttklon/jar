/**
 * Шаг 325: ночью — только безопасные действия или тишина.
 *
 * С `nightQuiet.ts` (шаг 239) уже решено, **насколько тихо** говорить ночью:
 * молча, пока не накопится, и с причиной, когда всё-таки говорим. Здесь — другой
 * вопрос: **что вообще можно делать**, пока человек спит.
 *
 * Две особенности есть только ночью: результат некому остановить, а провал никто
 * не заметит. Поэтому делим не «важное/неважное», а **обратимое/нет**:
 *
 *  * **безопасное** (прочитать, посчитать, сохранить отчёт, проверить обновление,
 *    скачать в свою папку) — можно, даже если человек спит;
 *  * **меняющее мир** (удалить, переименовать, отправить, установить) — нельзя без
 *    подтверждения: утром может выясниться, что удалено не то;
 *  * **тревожное** (окно поверх, звук, включение экрана) — нельзя никогда:
 *    разбудить человека ради отчёта о диске — ошибка, а не забота.
 */

/** Что делает дело. */
export type Deed = "read" | "change" | "alarm";

/** Ночная граница: 23:00–07:00, а не «когда темно». */
export const NIGHT_FROM = 23 * 60;
export const NIGHT_TO = 7 * 60;

/** Ночь ли сейчас — по минуте от полуночи. */
export function isNight(minute: number): boolean {
  return minute >= NIGHT_FROM || minute < NIGHT_TO;
}

/**
 * Можно ли делать это ночью.
 *
 * Возвращает решение и **что будет** при отказе: тишина и вопрос утром, а не
 * «попробую позже молча».
 */
export function mayDo(deed: Deed, minute: number): { allowed: boolean; said: string } {
  if (deed === "alarm") {
    return {
      allowed: false,
      said: "всплывающие окна и звук ночью не показываем никогда: разбудить человека ради отчёта — ошибка, а не забота",
    };
  }

  if (!isNight(minute)) return { allowed: true, said: "день: обычные правила" };

  if (deed === "read") return { allowed: true, said: "ночью читать и считать можно: результат человек увидит утром" };

  return {
    allowed: false,
    said: "ночью мир не меняем: удаление и переименование подождут до утра и спросят подтверждение",
  };
}

/**
 * Что происходит с отложенным.
 *
 * Не «выполнится утром само»: утром человек может передумать, и это нормально.
 */
export function deferred(): string {
  return "утром спросим: «вчера не стал это делать ночью — сделать сейчас?»";
}

/**
 * Что разрешено ночью — с причиной у каждого, а не просто «разрешено».
 */
export function safeList(): string[] {
  return [
    "проверить место на диске — только читает",
    "посчитать отчёт — сохраняет в свою папку",
    "проверить обновления — скачивает, но не ставит",
    "загрузить модель — файл в нашей папке, чужого не трогает",
  ];
}

/** Что ночью не делаем — каждый пункт меняет мир. */
export function notList(): string[] {
  return [
    "удалить файлы — утром может выясниться, что удалено не то",
    "переименовать и разложить — человек не увидит, куда",
    "установить обновление — программа перезапустится без него",
    "отправить сообщение — от имени человека, пока он спит",
  ];
}

/**
 * Человек включил компьютер в 3 ночи — он у экрана, и ночные правила к нему не
 * относятся: он тут и может подтвердить.
 */
export function awake(minute: number, lastInputMs: number): boolean {
  if (!isNight(minute)) return true;
  return lastInputMs < 2 * 60 * 1000;
}

/** Одна строка в настройках. */
export function setting(): string {
  return "Ночью (23:00–07:00): читаю и считаю, мир не меняю; отложенное спрошу утром";
}
