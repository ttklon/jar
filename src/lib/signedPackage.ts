/**
 * Шаг 302: подпись сборки и проверка скачанного пакета — без исключений.
 *
 * С `signature.ts` (шаг 174) уже проверяются чужие программы. Здесь — **своя**:
 * установщик, который человек скачал с сайта. Тут другая ловушка: собственный
 * бинарник кажется «своим», и его проверку откладывают первой.
 *
 * Что делаем и почему:
 *
 *  * **подписываем установщик Authenticode** — не «на всякий случай», а потому
 *    что Windows SmartScreen без подписи встречает человека красным окном
 *    «неизвестный издатель», и половина людей на этом останавливается;
 *  * **проверяем пакет до запуска** — размер, хеш, подпись, издатель. Порядок
 *    важен: хеш говорит «тот файл», подпись — «кто сделал»;
 *  * **отсутствие подписи ≠ вирус, но и не «всё хорошо»**: без подписи мы не
 *    знаем издателя — это отдельный факт, который надо назвать;
 *  * **просроченный сертификат ≠ подделка.** Подпись, поставленная до истечения
 *    срока, остаётся действительной; просроченная метка времени — другое дело.
 */

/** Что скачали. */
export interface Package {
  /** Имя файла — для человека. */
  readonly name: string;
  /** Размер в байтах: совпал ли с обещанным. */
  readonly bytes: number;
}

/** Что о пакете известно. */
export interface Facts {
  /** Ожидаемый размер из манифеста. */
  readonly expectedBytes: number;
  /** Ожидаемый хеш. */
  readonly hash: string;
  /** Фактический хеш скачанного. */
  readonly actualHash: string;
  /** Есть ли подпись. */
  readonly signed: boolean;
  /** Издатель из сертификата. */
  readonly publisher?: string;
  /** Наш издатель. */
  readonly us: string;
  /** Действительна ли подпись (цепочка + время). */
  readonly valid: boolean;
}

/** Что решили. */
export type Verdict = "run" | "ask" | "stop";

/** Проверить пакет до запуска. */
export function verify(pkg: Package, facts: Facts): { verdict: Verdict; said: string } {
  if (pkg.bytes !== facts.expectedBytes) {
    return { verdict: "stop", said: `размер ${pkg.bytes} вместо ${facts.expectedBytes} — скачалось не то или не до конца` };
  }
  if (facts.actualHash !== facts.hash) {
    return { verdict: "stop", said: "хеш не совпал: файл изменился после публикации — запускать нельзя" };
  }
  if (!facts.signed) {
    // Не «вирус», но и не «всё хорошо».
    return {
      verdict: "ask",
      said: "подписи нет: мы не знаем, кто сделал этот файл. Хеш совпал со страницей загрузки",
    };
  }
  if (!facts.valid) {
    return { verdict: "stop", said: "подпись недействительна: файл подменён или сертификат отозван" };
  }
  if (facts.publisher !== facts.us) {
    return { verdict: "stop", said: `подписал «${facts.publisher}», а не «${facts.us}»: это чужой пакет` };
  }
  return { verdict: "run", said: `подписано «${facts.us}», хеш совпал — запускаем` };
}

/**
 * Что сказать про отсутствие подписи.
 *
 * «Неизвестный издатель» — правда, но человеку нужно знать, что делать дальше.
 */
export function noSignature(name: string): string {
  return `${name} без подписи: издатель неизвестен. Сверьте хеш со страницей загрузки — если он не совпал, файл не запускайте`;
}

/**
 * Просроченный сертификат.
 *
 * Важная тонкость, которую легко испортить: подпись, поставленная **до**
 * истечения срока, остаётся действительной — иначе старые установщики «портились»
 * бы сами через два года.
 */
export function expired(countersigned: boolean): { ok: boolean; said: string } {
  if (countersigned) {
    return { ok: true, said: "сертификат просрочен, но метка времени стоит: подпись действительна" };
  }
  return { ok: false, said: "сертификат просрочен без метки времени: проверить, когда ставили подпись, нечем" };
}

/**
 * Установщик не должен требовать отключить антивирус (шаг 311 рядом).
 *
 * Здесь только ответ на вопрос «а если антивирус ругается»: правильный ответ —
 * подпись и репутация, а не «добавьте в исключения».
 */
export function antivirusSays(): string {
  return "если антивирус ругается — не отключайте его: пришлите нам отчёт, значит, у нас проблема в сборке";
}
