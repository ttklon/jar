/**
 * Шаг 310: тест обновления N → N+1 → откат на N — и данные целы.
 *
 * Это не проверка кода, а **репетиция**: прогон, который делают на каждой версии,
 * с настоящими файлами данных, и который отвечает на один вопрос — «если
 * обновление сломается, человек останется при своём?»
 *
 * Почему отдельно от юнит-тестов: юнит-тест проверяет, что `afterInstall()`
 * возвращает `rollback`. Репетиция проверяет, что после этого отката **файл
 * памяти на диске тот же**, факты читаются, и программа запускается со старой
 * версией.
 *
 * Что сравнивается до и после — поимённо:
 *
 *  * число фактов памяти и их хеш (не «файл на месте», а то же содержимое);
 *  * настройки: два-три ключа, которые точно есть;
 *  * журнал: он не должен **терять** записи, но может получить новые;
 *  * модели: файл тот же по хешу, иначе обновление «докачало» гигабайты.
 */

/** Состояние данных в одной точке репетиции. */
export interface Snapshot {
  /** Точка: до, после обновления, после отката. */
  readonly at: string;
  /** Хеш файла памяти — не размер, а содержимое. */
  readonly memoryHash: string;
  /** Сколько фактов прочиталось. */
  readonly facts: number;
  /** Ключи настроек, которые должны пережить всё. */
  readonly settings: readonly string[];
  /** Сколько записей в журнале. */
  readonly journal: number;
  /** Хеш файла модели. */
  readonly modelHash: string;
}

/** Итог репетиции. */
export interface DrillResult {
  readonly ok: boolean;
  readonly problems: string[];
  /** Что сказать человеку — одна строка. */
  readonly said: string;
}

/**
 * Репетиция: сравнить «до» и «после отката».
 *
 * Точка «после обновления» тоже проверяется, но мягче: там допустимы новые
 * записи и настройки. Точка «после отката» обязана совпасть с «до» — кроме
 * журнала, который только растёт.
 */
export function drill(before: Snapshot, afterUpdate: Snapshot, afterRollback: Snapshot): DrillResult {
  const problems: string[] = [];

  // Обновление не должно терять данные — это проверяется уже здесь, до отката.
  if (afterUpdate.facts < before.facts) {
    problems.push(`обновление потеряло ${before.facts - afterUpdate.facts} фактов ещё до отката`);
  }

  if (afterRollback.memoryHash !== before.memoryHash) {
    problems.push("после отката файл памяти другой: откат программы испортил данные");
  }
  if (afterRollback.facts !== before.facts) {
    problems.push(`после отката фактов ${afterRollback.facts}, а было ${before.facts}`);
  }
  for (const key of before.settings) {
    if (!afterRollback.settings.includes(key)) problems.push(`после отката пропала настройка «${key}»`);
  }
  if (afterRollback.journal < before.journal) {
    problems.push(`журнал потерял ${before.journal - afterRollback.journal} записей: история не должна укорачиваться`);
  }
  if (afterRollback.modelHash !== before.modelHash) {
    problems.push("файл модели изменился: откат не должен трогать гигабайты");
  }

  return {
    ok: problems.length === 0,
    problems,
    said:
      problems.length === 0
        ? `репетиция прошла: ${before.facts} фактов, ${before.settings.length} настроек и модель на месте после обновления и отката`
        : `репетиция провалена (${problems.length}): ${problems.join("; ")}`,
  };
}

/**
 * Что репетиция обязана покрыть, чтобы ей можно было верить.
 *
 * Три вещи, которые легко забыть: откат **без сети** (иначе это не откат),
 * имя пользователя с кириллицей, и обновление с версии, которая уже читала
 * данные (не с чистой установки).
 */
export function coverage(): string[] {
  return [
    "откат выполняется без сети — иначе проверяется не откат, а скачивание",
    "имя пользователя с кириллицей и пробелом в пути",
    "обновление с версии, у которой уже есть данные, а не с чистой установки",
    "версия N+1 сломана намеренно — иначе откат не проверяется вовсе",
  ];
}

/**
 * Как часто делаем.
 *
 * Не «перед каждым релизом» — это размывается. Числом: на каждый релиз, плюс
 * раз в месяц на самой свежей сборке из канала beta.
 */
export function when(): string {
  return "на каждый релиз и раз в месяц на свежей beta: откат, который не проверяли полгода, не работает";
}
