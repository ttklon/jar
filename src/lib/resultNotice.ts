/**
 * Шаг 324: уведомление о результате, если человек не у экрана.
 *
 * Автоматическое дело, которое «сделалось» и не сказало об этом, — это то же
 * самое, что дело, которое не сделалось. Человек не знает ни результата, ни
 * того, что оно вообще было.
 *
 * Но и обратное неверно: уведомление, которое приходит всегда, перестают читать
 * через три дня. Поэтому решение зависит от одного факта — **у экрана человек
 * или нет**.
 *
 *  * **у экрана** — результат видно в приложении, отдельное окно не нужно;
 *  * **не у экрана** — уведомление, одно, с результатом и возможностью
 *    открыть;
 *  * **ошибка — всегда**, даже если человек у экрана: ошибки не должны ждать.
 *
 * «Мало ли он отошёл на минуту» — решается временем: если дело закончилось и
 * человек не трогал клавиатуру больше десяти минут, он не у экрана.
 */

/** Состояние человека. */
export interface AtDesk {
  /** Сколько миллисекунд назад было последнее действие. */
  readonly idleMs: number;
  /** Есть ли открытое окно приложения на переднем плане. */
  readonly foreground: boolean;
}

/** Порог «ушёл»: 10 минут. */
export const AWAY_MS = 10 * 60 * 1000;

/** Что произошло с делом. */
export type Outcome = "done" | "failed" | "skipped";

/**
 * Нужно ли уведомление.
 *
 * `skipped` тоже уведомляет, но по-другому: «условие не наступило» — это не
 * успех и не ошибка (шаг 326), и человеку это важно знать, если он ждал.
 */
export function notify(outcome: Outcome, desk: AtDesk): { show: boolean; why: string } {
  if (outcome === "failed") return { show: true, why: "об ошибке говорим всегда: она не должна ждать, пока человек вернётся" };
  if (outcome === "skipped") {
    return { show: true, why: "дело пропущено: если человек его ждал, он должен знать, что его не было" };
  }
  if (desk.foreground) return { show: false, why: "результат виден в окне: отдельное уведомление только помешает" };
  if (desk.idleMs > AWAY_MS) return { show: true, why: "человек не у экрана больше десяти минут: без уведомления он не узнает о результате" };
  return { show: false, why: "человек рядом: результат виден в приложении, уведомление не нужно" };
}

/**
 * Текст уведомления.
 *
 * Результат, а не «задача выполнена»: что именно стало видно человеку. Плюс
 * одна строка «что дальше» — открыть или неважно.
 */
export function text(outcome: Outcome, what: string, detail: string): string {
  if (outcome === "done") return `${what}: ${detail}`;
  if (outcome === "failed") return `${what} не получилось: ${detail}. Открыть, чтобы разобраться?`;
  return `${what} не запускалось: ${detail}`;
}

/**
 * Сколько уведомлений за раз.
 *
 * Три дела, сделанные в одну минуту, — три уведомления, и это уже стена. Одно,
 * со списком внутри.
 */
export function bundle(items: readonly string[]): string {
  if (items.length === 0) return "";
  if (items.length === 1) return items[0]!;
  return `Сделано ${items.length} дела: ${items.join("; ")}. Подробности в приложении`;
}

/**
 * Что уведомление не делает.
 *
 * Список короткий, потому что соблазнов много: звук, поверх всего, повтор.
 */
export function forbidden(): string[] {
  return [
    "звук: уведомление о деле, которое человек не просил ждать, не должно привлекать внимание к себе",
    "поверх всех окон: дело не срочнее того, чем человек занят",
    "повтор, пока не нажмут: это уже преследование",
  ];
}

/**
 * Что сказать, если человек вернулся.
 *
 * Одно сообщение в приложении, а не пять уведомлений накопительно: то, что он не
 * видел, показывается один раз.
 */
export function onReturn(items: readonly string[]): string {
  if (items.length === 0) return "пока вас не было, автоматических дел не было";
  return `пока вас не было: ${items.join("; ")}`;
}
