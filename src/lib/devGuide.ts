/**
 * Шаг 468: документация для разработчика — как добавить экран / руку / тест.
 *
 * «Прочитай код» — не документация. Новый человек (или я сам через полгода) должен
 * добавить экран, руку или тест, **не разбираясь в проекте целиком**.
 *
 * Для этого нужны три вещи, и каждая — про порядок действий:
 *
 *  * **шаги по порядку**: файл, тест, пометка в плане, прогон — и что будет, если
 *    пропустить шаг;
 *  * **где что лежит** — не «в src», а «правило в `src/lib`, экран рядом, тест
 *    рядом с правилом»;
 *  * **чего не делать** — самые частые ошибки новичка: дублировать модуль,
 *    трогать чужой файл, обходить проверку.
 *
 * Именно последнее и экономит время: без него новый человек **правит правильное
 * место неправильным способом**.
 */

/** Вид работы. */
export type Task = "экран" | "рука" | "тест";

/** Шаг инструкции. */
export interface Step {
  readonly n: number;
  readonly do: string;
  /** Что будет, если пропустить. */
  readonly skip: string;
}

/**
 * Инструкция.
 *
 * Нумерованные шаги с последствием пропуска — не «рекомендации», а порядок.
 */
export function steps(task: Task): Step[] {
  const common: Step[] = [
    { n: 1, do: "проверить, нет ли уже такого: `ls src/lib | grep -i <тема>` и `git log -1 -- <путь>`", skip: "дубль модуля: два правила про одно, и они разойдутся" },
  ];

  const byTask: Record<Task, Step[]> = {
    экран: [
      { n: 2, do: "правило — в `src/lib/<имя>.ts`, без React: то, что можно проверить тестом", skip: "логика в разметке: её нельзя проверить, и она ломается при правке вёрстки" },
      { n: 3, do: "тест рядом: `src/lib/<имя>.test.ts`, по одному describe на правило", skip: "правило есть, но никто не узнает, когда оно перестанет работать" },
      { n: 4, do: "экран подключает правило, а не повторяет его", skip: "два источника правды: экран и правило начнут расходиться" },
    ],
    рука: [
      { n: 2, do: "опасность руки — в список `DANGEROUS` (шаг 336), до написания выполнения", skip: "рука без риска: удаление без подтверждения — и это замечают после" },
      { n: 3, do: "правило в `src/lib`, выполнение — в Rust; правило проверяется тестом", skip: "проверка в Rust без теста: Rust-тестов меньше, и регрессия живёт дольше" },
      { n: 4, do: "строка в реестре действий — иначе GUI не узнает о руке", skip: "рука есть, но её нет в списке: человек её не найдёт" },
    ],
    тест: [
      { n: 2, do: "тест проверяет **поведение**, а не реализацию: «что видит человек», а не «какая функция вызвана»", skip: "зелёный тест при сломанном поведении" },
      { n: 3, do: "мутация: сломать код нарочно и убедиться, что тест упал", skip: "тест, который не ловит ничего, — это ложное спокойствие" },
      { n: 4, do: "прогон `npx tsc -b` — тесты тоже типизируются", skip: "неиспользуемый импорт в тесте пройдёт `vitest` и упадёт в CI" },
    ],
  };

  return [...common, ...byTask[task]];
}

/**
 * Где что лежит.
 *
 * Три места, и правило простое: правило отдельно от экрана.
 */
export function layout(): string[] {
  return [
    "`src/lib/<имя>.ts` — правило, без React: чистая функция и русские комментарии с «почему так»",
    "`src/lib/<имя>.test.ts` — тест рядом с правилом, а не в отдельной папке",
    "`src/` — экраны и подключение правил; `src-tauri/src/` — то, что нельзя сделать в JS",
  ];
}

/**
 * Чего не делать.
 *
 * Четыре ошибки новичка, каждая — с последствием.
 */
export function mistakes(): string[] {
  return [
    "не дублировать существующее правило: сначала `ls src/lib | grep -i`",
    "не перезаписывать файл, который уже есть: `git checkout HEAD -- <путь>` вернёт",
    "не обходить проверку «временно»: временное живёт дольше постоянного",
    "не писать тест, который проверяет реализацию: он упадёт при любом рефакторинге",
  ];
}

/**
 * Что должно быть в каждом правиле.
 *
 * Четыре вещи — и все про будущего читателя.
 */
export function inEveryModule(): string[] {
  return ["в шапке — какой шаг плана и почему так, а не иначе", "русские комментарии у неочевидных решений", "типы на экспорте: вызывающий не должен догадываться", "ни одного `console.log` и ни одной ссылки на окно"];
}
