/**
 * Шаг 461: GUIDE читается за 10 минут и отвечает «что сказать, чтобы получить X».
 *
 * Руководство пользователя, которое начинается с «философии продукта» и
 * «архитектуры», не читается никем. Человек пришёл с вопросом «как почистить
 * загрузки» — и должен найти на него ответ **в первую минуту**, а не на третьей
 * странице после «мы верим в приватность».
 *
 * Поэтому GUIDE строится **вопросами**, а не разделами:
 *
 *  * **«что сказать» → «что будет»** — таблицей, без вступления;
 *  * **10 минут** — это не «коротко», а **измеримое**: примерно 2000 слов и не
 *    больше 20 вопросов. Число проверяется;
 *  * **каждый вопрос — из настоящей фразы**, а не из описания функции.
 *
 * И отдельное правило: **если ответа нет, GUIDE говорит об этом**. Раздел
 * «чего приложение не делает» — не приложение к руководству, а его часть
 * (шаг 465).
 */

/** Раздел руководства. */
export interface Section {
  /** Вопрос человека — его словами. */
  readonly ask: string;
  /** Что сказать. */
  readonly say: string;
  /** Что будет. */
  readonly get: string;
}

/** Пределы, за которыми руководство перестают читать. */
export const LIMITS = { words: 2100, sections: 20, minutes: 10 } as const;

/**
 * Сколько времени читать.
 *
 * 200 слов в минуту — медленное чтение по слогам; так считают «сколько это
 * займёт» честно.
 */
export function minutes(words: number): number {
  return Math.ceil(words / 200);
}

/**
 * Уложиться ли в десять минут.
 *
 * Возвращает **нарушения**, а не булево: «на 12 минут» полезнее, чем «нет».
 */
export function fits(sections: readonly Section[]): { ok: boolean; words: number; minutes: number; said: string } {
  const words = sections.reduce((sum, section) => sum + count(section), 0);
  const mins = minutes(words);
  const problems: string[] = [];

  if (sections.length > LIMITS.sections) problems.push(`вопросов ${sections.length}, а больше ${LIMITS.sections} за десять минут не прочитать`);
  if (mins > LIMITS.minutes) problems.push(`${mins} мин вместо ${LIMITS.minutes}: сократить до ${LIMITS.words} слов`);

  return {
    ok: problems.length === 0,
    words,
    minutes: mins,
    said: problems.length === 0 ? `войдёт в ${LIMITS.minutes} минут: ${words} слов, ${sections.length} вопросов` : problems.join("; "),
  };
}

/** Слов в разделе — грубо, по пробелам: точность до слова тут не нужна, нужен порядок. */
function count(section: Section): number {
  return [...section.ask, ...section.say, ...section.get].join(" ").split(/\s+/).filter(Boolean).length;
}

/**
 * Что обязано быть в начале.
 *
 * Первый раздел — самая частая просьба, а не «что такое ZShelper».
 */
export function firstMust(): string {
  return "первый раздел — самая частая просьба («почисти загрузки»), а не «что такое ZShelper»: человек пришёл с делом, а не за описанием";
}

/**
 * Как строится раздел.
 *
 * Три поля, и все три — про человека: что сказать, что будет, а не «функция X
 * делает Y».
 */
export function format(): string[] {
  return ["вопрос человеками словами", "что сказать", "что будет — с честной оговоркой, если спросят подтверждение"];
}

/**
 * Что проверяет тест.
 *
 * Четыре проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "не длиннее 2100 слов и 20 вопросов",
    "каждый раздел — вопрос, фраза и результат",
    "первый раздел — самая частая просьба",
    "если ответа нет — сказано, а не выдумано",
  ];
}
