/**
 * Квантование по умолчанию — Q4_K_M (шаг 64).
 *
 * Дефект. Один и тот же вес можно хранить с разной точностью: Q2, Q4, Q5, Q8.
 * Чем точнее — тем больше файл и тем больше памяти, но и тем меньше потерь
 * качества. На сайте модели всегда лежит «лучший» вариант, и человек тянет Q8:
 * файл вдвое больше, памяти вдвое больше, скорость вдвое ниже — **и разницы в
 * ответах не замечает**.
 *
 * Правило: **Q4_K_M по умолчанию**, остальное — по доказанной причине.
 *
 *  1. Q4_K_M — точка, где качество почти не отличается от полного, а размер
 *     вдвое меньше. Это не «компромисс», это **выбор по умолчанию**, и он не
 *     требует от человека решения.
 *  2. Q8 — только когда железо **доказано** замером (шаг 65), а не по паспорту:
 *     иначе человек платит памятью за точность, которой не увидит.
 *  3. Q2/Q3 не предлагаются вовсе: на них модель **заметно глупеет**, и это
 *     уже не компромисс, а поломка. Размер файла не оправдывает неверные ответы.
 *  4. Что выбрано — **названо словами** и с ценой: «Q4_K_M, 4.4 ГБ» говорит
 *     человеку, за что он платит памятью.
 *
 * Почему K_M, а не просто Q4. `K_M` — смешанное квантование: важные веса
 * (attention) точнее, остальные грубее. В обычном Q4 качество падает на длинном
 * контексте; K_M держит его, и стоит того же. Это **вид квантования по
 * умолчанию**, а не деталь реализации: от него зависит, где модель начнёт
 * путаться.
 */

/** Способ хранения весов. */
export type Kind = "Q2_K" | "Q3_K_M" | "Q4_K_M" | "Q5_K_M" | "Q8_0";

/** Что известно о способе. */
export interface Level {
  kind: Kind;
  /** Бит на вес: от него зависит размер файла. */
  bits: number;
  /** Насколько теряется качество — по опыту, а не по паспорту. */
  loss: string;
  /** Предлагаем ли этот способ вообще. */
  offered: boolean;
}

/**
 * Ступени квантования.
 *
 * `loss` — не «1–2%» из чужой таблицы, а **что человек увидит**: «на длинном
 * контексте путается», «почти не отличается». Проценты никто не переводит в
 * опыт.
 */
export const LEVELS: Level[] = [
  { kind: "Q2_K", bits: 2.6, loss: "заметно глупеет: путает факты и обрывает мысль", offered: false },
  { kind: "Q3_K_M", bits: 3.9, loss: "теряет длинный контекст: забывает начало разговора", offered: false },
  { kind: "Q4_K_M", bits: 4.8, loss: "почти не отличается от полного — этим и пользуемся", offered: true },
  { kind: "Q5_K_M", bits: 5.7, loss: "чуть точнее Q4_K_M, но файл на пятую часть больше", offered: true },
  { kind: "Q8_0", bits: 8.5, loss: "точнее полного не бывает — но и разницы с Q4_K_M не видно", offered: true },
];

/** Ступень, которая берётся без решения человека. */
export const DEFAULT: Kind = "Q4_K_M";

/** Не предлагаем вовсе: не компромисс, а поломка. */
export const FORBIDDEN: Kind[] = ["Q2_K", "Q3_K_M"];

/** Найти ступень по названию. */
export function level(kind: Kind): Level | undefined {
  return LEVELS.find((item) => item.kind === kind);
}

/**
 * Что взять по умолчанию.
 *
 * Всегда Q4_K_M: это точка, где качество почти не отличается от полного, а
 * размер вдвое меньше. Решения от человека не требует.
 */
export function choose(): Level {
  return level(DEFAULT)!;
}

/**
 * Когда Q8 **оправдан**.
 *
 * Только по доказанной причине: железо показало запас памяти **и** замер
 * скорости (шаг 65). «Может, будет лучше» — не причина: человек заплатит
 * памятью за точность, которой не увидит.
 *
 * `proven` — есть замер на этой машине; `spareMb` — сколько памяти останется
 * свободной после Q8. Без обоих — Q4_K_M, и это не отказ, а умолчание.
 */
export function upgrade(proven: boolean, spareMb: number): Level {
  const q4 = choose();
  const q8 = level("Q8_0")!;
  // Запаса после Q8 должно хватить не «в ноль», а с местом на систему.
  if (proven && spareMb >= 4096) return q8;
  return q4;
}

/**
 * Размер файла при способе квантования.
 *
 * Бит на вес × число весов / 8. Это оценка, но она **линейна и предсказуема**:
 * человек видит, во что ему обойдётся Q8, до загрузки.
 */
export function sizeMb(paramsB: number, kind: Kind): number {
  const bits = level(kind)?.bits ?? 4.8;
  // paramsB — миллиарды параметров; 1e9 × бит / 8 / 1e6 байт = МБ.
  return Math.round((paramsB * 1e9 * bits) / 8 / 1e6);
}

/**
 * Что сказать человеку про выбранное квантование.
 *
 * Названы **способ и цена**, а не только способ: «Q4_K_M, 4.4 ГБ» говорит, за
 * что платят памятью. И сказано, что это умолчание: иначе человек ищет, где
 * «включить лучше».
 */
export function say(kind: Kind, paramsB: number): string {
  const chosen = level(kind);
  const mb = sizeMb(paramsB, kind);
  const gb = Math.round(mb / 102.4) / 10;
  const parts = [`${kind}, ${gb} ГБ`];
  if (kind === DEFAULT) {
    parts.push("по умолчанию: качество почти как у полного, а памяти вдвое меньше");
  } else if (kind === "Q8_0") {
    parts.push("точнее, и это доказано замером на этой машине");
  }
  if (chosen && !chosen.offered) parts.push("такой вариант мы не предлагаем");
  return parts.join(" — ");
}

/**
 * Почему Q2/Q3 не предлагаются.
 *
 * Сказано, потому что человек увидит их в интернете и спросит: «а можно
 * поменьше?». Ответ — не «нельзя», а **что он потеряет**.
 */
export function whyNotSmaller(): string {
  return "меньше Q4 — это не компромисс, а поломка: модель путает факты и забывает начало разговора, и размер файла этого не оправдывает";
}
