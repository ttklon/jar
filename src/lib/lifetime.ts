/**
 * Шаг 264: срок жизни — временное забывается, постоянное подтверждается.
 *
 * Почему это отдельное правило, а не «поле `stale` в каждом модуле». Сейчас
 * свежесть считается **в двух местах и по-разному**: `preferences.ts` держит
 * `STALE_MS = 30 дней`, `methods.ts` — `AGES_MS = 7 дней`. Оба числа верные для
 * своего вида, но правила «почему 30, а не 7» нет ни в одном из них, и третий
 * вид появится с третьим числом.
 *
 * Суть в другом: у фактов разная **природа**, и она задаёт срок.
 *
 *  * **временное** — то, что относится к сегодняшней работе: какая папка
 *    открыта, что делали в этот день. Через неделю это уже история, и хранить
 *    её как «текущее» — значит врать;
 *  * **постоянное** — то, что человек выбрал как привычку: голос, громкость,
 *    программа. Оно не портится от времени — **но требует подтверждения**: если
 *    человек не возвращался к нему полгода, это уже не привычка, а архив;
 *  * **одноразовое** — то, что нельзя выводить из одного случая вообще.
 *
 * Правило: срок не «сколько хранить», а **что делать по истечении**. Временное
 * забывается само. Постоянное не забывается — оно **перестаёт считаться
 * текущим** и спрашивает подтверждение. Разница принципиальная: стереть голос
 * человека через год — это потеря; перестать подставлять его молча — это
 * вежливость.
 */

/** Природа факта: она и задаёт срок. */
export type Nature = "temporary" | "lasting" | "once";

/**
 * Срок по природе, в днях.
 *
 * Числа не «примерно»: у каждого своё основание, и оно записано здесь, чтобы
 * третий вид не получил четвёртое случайное число.
 */
export const DAYS: Readonly<Record<Nature, number | null>> = {
  // Неделя: смена рабочих дней (пятница → понедельник) ещё внутри, смена
  // проекта — уже нет.
  temporary: 7,
  // Полгода: привычка, к которой не возвращались полгода, — это архив. Не
  // «много», а «дольше любой сезонной смены».
  lasting: 180,
  // Одноразовое не имеет срока: его не должно быть вовсе.
  once: null,
};

/** Что делать, когда срок вышел. */
export type Fate =
  /** Забыть: стереть из памяти. */
  | "forget"
  /** Спросить подтверждение: держать, но не подставлять молча. */
  | "confirm"
  /** Не запоминать вообще. */
  | "never";

/** Окончательное решение по факту. */
export interface Verdict {
  readonly nature: Nature;
  /** Возраст в днях. */
  readonly days: number;
  /** Что делать. */
  readonly fate: Fate;
  /** Почему — словами, с числом. */
  readonly why: string;
}

/**
 * Решение по факту.
 *
 * `confirmedAt` — когда человек последний раз подтвердил факт **делом** (выбрал
 * голос, поправил громкость). Не «когда записали»: запись могла быть год назад,
 * а выбор — вчера.
 */
export function decide(nature: Nature, lastAt: number, now: number): Verdict {
  if (nature === "once") {
    // Один случай — не факт: человек мог один раз зайти не туда.
    return {
      nature,
      days: 0,
      fate: "never",
      why: "один случай не запоминается: это может быть ошибка, а не привычка",
    };
  }
  const days = Math.max(0, Math.floor((now - lastAt) / (24 * 60 * 60 * 1000)));
  const limit = DAYS[nature]!;
  if (days <= limit) {
    return { nature, days, fate: nature === "temporary" ? "forget" : "confirm", why: fresh(nature, days, limit) };
  }
  return {
    nature,
    days,
    fate: nature === "temporary" ? "forget" : "confirm",
    why:
      nature === "temporary"
        ? `${days} дней — больше ${limit}: это уже история, а не текущая работа`
        : `${days} дней без подтверждения — больше ${limit}: держим, но молча не подставляем`,
  };
}

/**
 * Свежий факт: `fate` «forget»/«confirm» здесь означает не «сделать это
 * сейчас», а «что случится, когда срок выйдет».
 *
 * Возвращается то же значение, что и у просроченного, — но с другой причиной.
 * Так вызывающему не надо разбираться в двух формах ответа.
 */
function fresh(nature: Nature, days: number, limit: number): string {
  const left = limit - days;
  return nature === "temporary"
    ? `свежо: ${days} дней, забудется через ${left}`
    : `подтверждено ${days} назад, доверие до ${limit}`;
}

/**
 * Можно ли подставить факт молча.
 *
 * Вот и вся разница шага: **постоянное не забывается, но и не подставляется
 * вечно**. «Спросить» — это не отказ, это строка «подставить голос Алла?» с
 * уже выбранным ответом.
 */
export function substitute(verdict: Verdict): { ok: boolean; ask: boolean; said: string } {
  if (verdict.fate === "never") return { ok: false, ask: false, said: verdict.why };
  if (verdict.fate === "forget") return { ok: false, ask: false, said: verdict.why };
  const stale = verdict.why.includes("без подтверждения");
  if (stale) return { ok: true, ask: true, said: verdict.why };
  return { ok: true, ask: false, said: verdict.why };
}

/**
 * Подтвердить факт — то, что делает человек, выбирая его снова.
 *
 * Возвращает новое время, а не мутирует: подтверждение — событие, и его видно в
 * истории.
 */
export function confirm(_lastAt: number, now: number): number {
  return now;
}

/**
 * Проверить, что сроки не перепутаны местами.
 *
 * `temporary` обязан истекать раньше `lasting`, иначе «временное» живёт дольше
 * привычки — и весь смысл деления теряется. Проверка стоит в коде, потому что
 * сроки правили руками уже дважды.
 */
export function consistent(): boolean {
  const temporary = DAYS.temporary;
  const lasting = DAYS.lasting;
  return temporary !== null && lasting !== null && temporary < lasting;
}

/** Строка для экрана памяти: что будет с фактом. */
export function say(verdict: Verdict): string {
  if (verdict.fate === "never") return "не запоминается";
  if (verdict.nature === "temporary") {
    return verdict.days > DAYS.temporary! ? "забыто" : `забудется через ${DAYS.temporary! - verdict.days} дн.`;
  }
  return verdict.why.includes("без подтверждения")
    ? "спросим перед подстановкой"
    : "действует";
}
