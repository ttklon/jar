/**
 * Шаг 338: пауза всех расписаний одной кнопкой — отпуск.
 *
 * Человек уезжает на неделю. Ноутбук остаётся включённым, и расписания
 * продолжают работать: ночная уборка, отчёты, «спросить подтверждение» — всё это
 * копится в уведомлениях, к которым он вернётся. Хуже: он не сможет ответить на
 * вопрос о подтверждении, и правило встанет на паузу само, но с ошибкой.
 *
 * Поэтому нужна одна кнопка: **«Пауза всех расписаний»**. И у неё свои правила:
 *
 *  1. **одна кнопка, всё сразу** — не по одному правилу;
 *  2. **видно, что на паузе и когда вернётся** — «до понедельника» или «до
 *     возвращения»;
 *  3. **автоматическое продолжение не молчит**: при возвращении сказано «семь
 *     правил снова работают»;
 *  4. **пауза не теряет доверие и историю** (шаг 327): пауза — не удаление.
 */

/** Состояние паузы. */
export interface Paused {
  /** Сколько правил на паузе. */
  readonly count: number;
  /** Когда началась. */
  readonly from: number;
  /** Когда закончится; 0 — до возвращения руками. */
  readonly until: number;
}

/**
 * Пауза всего.
 *
 * `until = 0` — «до возвращения»: человек не знает, когда вернётся, и не должен
 * угадывать дату.
 */
export function pauseAll(count: number, from: number, until: number): Paused {
  return { count, from, until };
}

/**
 * Как это выглядит для человека.
 *
 * Не «на паузе: 7» без смысла, а с датой или «до возвращения».
 */
export function state(paused: Paused, now: number): string {
  if (paused.count === 0) return "все расписания работают";
  if (paused.until === 0) return `${paused.count} ${plural(paused.count, "расписание", "расписания", "расписаний")} на паузе до вашего возвращения`;
  if (paused.until <= now) return "пауза истекла — сейчас расписания снова работают";
  const when = new Date(paused.until).toISOString().slice(0, 10);
  return `${paused.count} ${plural(paused.count, "расписание", "расписания", "расписаний")} на паузе до ${when}`;
}

/**
 * Продолжение после паузы.
 *
 * Первое — не запуск всего пропущенного (это буря, шаг 334), а сводка: сколько
 * правил снова работает и что было пропущено.
 */
export function resume(paused: Paused, missed: number): string {
  const rules = `${paused.count} ${plural(paused.count, "расписание", "расписания", "расписаний")} снова работает`;
  if (missed === 0) return rules;
  return `${rules}; за паузу пропущено ${missed} ${plural(missed, "запуск", "запуска", "запусков")} — догонять не будем, следующий по расписанию`;
}

/**
 * Что пауза не делает.
 *
 * Список нужен, потому что «пауза всех» легко превращается в «выключить всё
 * навсегда» или в «и опасные дела тоже пусть идут».
 */
export function keeps(): string[] {
  return [
    "правила не удаляются: пауза — не удаление",
    "история и доверие сохраняются: после паузы правило не спрашивает заново",
    "выполняющиеся сейчас дела не обрываются: пауза действует на следующие",
    "опасное дело на паузе не выполняется даже с подтверждением: подтверждать некому",
  ];
}

/**
 * Молчаливое продолжение — тоже проблема.
 *
 * Если пауза кончилась по времени, а человек ничего не видел, он не знает, что
 * правила снова работают. Поэтому при возвращении — одна строка.
 */
export function afterReturn(): string {
  return "при возвращении — одна строка: сколько правил снова работает и что было пропущено; без неё человек не знает, что пауза кончилась";
}

/** Русское склонение по числу. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
