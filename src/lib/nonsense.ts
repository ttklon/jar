/**
 * Тишина, щелчок и кашель не становятся задачей (шаг 44).
 *
 * Самая частая жалоба на голосовой ввод — не «не понял», а **«понял не то»**:
 * человек откашлялся, распознавание выдало «кхм», и приложение пошло создавать
 * папку с этим названием. Ложная фраза хуже неудачи: неудачу видно сразу, а
 * ложную фразу человек замечает после того, как действие случилось.
 *
 * Здесь два разных случая, и путать их нельзя:
 *
 *  * **пусто** — «не разобрал». Это уже есть в `voice.ts`: пустой результат не
 *    отправляется, а говорится «ничего не услышал — повтори»;
 *  * **мусор** — «разобрал, но это не слова». `кхм`, `э`, `а-а-а`, `ммм`, `...`.
 *    Такое нельзя отправлять, но и «ничего не услышал» говорить не совсем
 *    верно — человек что-то сказал, просто не то. Поэтому отдельный ответ.
 *
 * Правило нарочно **узкое**. Список шума закрыт, и незнакомое слово считается
 * речью: отбросить настоящую просьбу «убери» из-за того, что оно похоже на
 * междометие, — хуже, чем один раз отправить «кхм». Поэтому проверка идёт по
 * целым словам и по **всему** тексту: «а» — шум, «а теперь удали папку» — речь.
 */

/** Междометия и звуки, которые распознавание выдаёт как слова. */
const NOISE_WORDS = new Set([
  "а",
  "аа",
  "ааа",
  "э",
  "ээ",
  "эээ",
  "ы",
  "мм",
  "ммм",
  "м",
  "кхм",
  "кх",
  "гм",
  "хм",
  "угу",
  "ага",
  "о",
  "оо",
  "ох",
  "ах",
  "ух",
  "эх",
]);

/**
 * Совсем короткие английские звуки — распознавание иногда переключается на
 * английский и выдаёт их вместо русских. Те же по смыслу, поэтому тот же ответ.
 */
const NOISE_LATIN = new Set(["a", "e", "m", "mm", "hmm", "hm", "uh", "um", "ah", "oh"]);

/** Что осталось от текста, если убрать всё, что не буквы и не цифры. */
function core(text: string): string {
  return text
    .toLocaleLowerCase("ru")
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}

/**
 * Это шум, а не фраза.
 *
 * Возвращает `true` только когда **каждое** слово — из списка звуков. Одно
 * незнакомое слово делает фразу речью: «мм, а» — шум, «мм, а тема где» — вопрос.
 */
export function isNoise(text: string): boolean {
  const normalized = core(text);
  if (normalized.length === 0) return true; // пусто — тоже не фраза
  const words = normalized.split(" ").filter((word) => word.length > 0);
  return words.every((word) => NOISE_WORDS.has(word) || NOISE_LATIN.has(word));
}

/**
 * Что сказать человеку, когда услышали шум.
 *
 * Не «ничего не услышал»: он **слышал** — просто это был кашель. И не «не
 * понял»: понял, что это не слова. Ответ короткий, чтобы не отнимать время у
 * второй попытки.
 */
export const NOISE_REPLY = "это не похоже на просьбу — повторите словами";

/**
 * Что делать с распознанным текстом: отправить, спросить заново или сказать
 * «ничего не услышал».
 *
 * Одно место решает, чтобы три экрана не решали по-своему: раньше условие
 * писалось на месте, и на одном экране уходило «кхм», а на другом нет.
 */
export type Disposition = "send" | "noise" | "silence";

export function dispose(text: string): Disposition {
  if (text.trim().length === 0) return "silence";
  if (isNoise(text)) return "noise";
  return "send";
}
