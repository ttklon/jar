/**
 * Прогон на подставном медленном и подставном пустом окружении (шаг 253).
 *
 * Дефект. Проверки шли на нормальном окружении: всё отвечает, всё есть. Две
 * крайности оставались непроверенными, и обе встречаются у живого человека:
 *
 *  * **медленное** — машина занята, диск шуршит, ответ приходит за 4 секунды;
 *  * **пустое** — ни моделей, ни движка, ни журнала; первый запуск после
 *    переустановки, и всё отвечает «нет».
 *
 * Что в них ломается — разное:
 *
 *  * на медленном ломается **терпение**: интерфейс показывает «загружаю…» и не
 *    говорит, что долго; человек решает, что зависло, и жмёт второй раз;
 *  * на пустом ломается **честность**: код, который рассчитывал на данные,
 *    падает или рисует пустоту без слов — и «нет данных» не отличается от
 *    «сломалось».
 *
 * Правила:
 *
 *  1. **медленное — не сломанное**: ожидание дольше порога обязано быть
 *     **сказано**, а не только показано точками;
 *  2. **повторное нажатие на медленном не запускает второй запрос**: два
 *     запроса на одну кнопку — это двойная загрузка и двойной счёт;
 *  3. **пустое — тоже ответ**: пустой список говорит «пусто», а не молчит;
 *  4. **пустое не роняет**: отсутствие любого поля не должно превращаться в
 *     исключение — «нет» это данные, а не ошибка.
 *
 * Модуль ничего не запускает: он даёт подставные среды для прогона.
 */

/** Что за окружение. */
export type Env = "normal" | "slow" | "empty";

/** Порог, после которого ожидание обязано быть сказано словами. */
export const SLOW_AFTER_MS = 2000;

/**
 * Сколько ждать ответа в этой среде.
 *
 * Именно **сколько**, а не «медленно/быстро»: тест должен уметь подставить это
 * число, а не ждать по-настоящему.
 */
export function delay(env: Env): number {
  return env === "slow" ? 4000 : 0;
}

/**
 * Что показать, пока ответа нет.
 *
 * На нормальном — ничего: мгновенное ожидание не нужно объяснять. На медленном —
 * слова, и с числом секунд, потому что «загружаю» без числа не отвечает на
 * вопрос «это зависло?».
 */
export function waiting(env: Env, elapsedMs: number): string | null {
  if (env !== "slow" || elapsedMs < SLOW_AFTER_MS) return null;
  return `долго: ждём ${Math.round(elapsedMs / 1000)} с. Это медленная машина или занятый диск, а не зависание`;
}

/**
 * Пустые данные этой среды.
 *
 * На `empty` всё пусто, и это **данные**, а не ошибка: приложение обязано
 * работать и говорить «пусто».
 */
export function payload<T>(env: Env, full: T, nothing: T): T {
  return env === "empty" ? nothing : full;
}

/**
 * Разрешено ли повторное нажатие.
 *
 * Пока запрос в полёте — нет. На медленном это особенно важно: человек жмёт
 * второй раз именно потому, что «долго», и второй запрос удваивает и загрузку, и
 * счёт.
 */
export function canPress(inFlight: boolean): boolean {
  return !inFlight;
}

/**
 * Что сказать, если нажали второй раз.
 *
 * Не «игнорировать»: молчание на нажатие читается как «кнопка не работает», и
 * человек жмёт третий раз.
 */
export function secondPress(waitingMs: number): string {
  return `уже идёт: ждём ${Math.round(waitingMs / 1000)} с, второй раз начинать не нужно`;
}

/**
 * Проверка обещаний на обеих средах — списком, а не «прогнали глазами».
 *
 * Возвращает нарушения по именам: каждое — среда плюс правило.
 */
export function audit(): string[] {
  const problems: string[] = [];
  if (waiting("slow", SLOW_AFTER_MS) === null) {
    problems.push("медленное: на пороге ожидание не сказано");
  }
  if (waiting("slow", SLOW_AFTER_MS - 1) !== null) {
    problems.push("медленное: ожидание сказано раньше порога — это шум");
  }
  if (waiting("normal", 5000) !== null) {
    problems.push("нормальное: на нормальном окружении сказано «долго»");
  }
  if (canPress(true)) problems.push("медленное: второй запрос запускается поверх первого");
  if (!secondPress(3000).includes("уже идёт")) problems.push("второе нажатие: не сказано, что уже идёт");
  if (payload("empty", [1, 2], []).length !== 0) problems.push("пустое: данные не пустые");
  if (payload("normal", [1, 2], []).length !== 2) problems.push("нормальное: данные потерялись");
  return problems;
}
