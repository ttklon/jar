/**
 * Шаг 479: скриншоты обновляются вместе с экранами или помечаются устаревшими.
 *
 * Шаг 463 привязывает снимок к отпечатку экрана. Здесь — **что делать**, когда
 * отпечаток разошёлся: три исхода, и все лучше, чем «снимок остался как был».
 *
 *  1. **обновить** — экран изменился незначительно, снимок переснимают;
 *  2. **пометить** — переснять сейчас нечем (нет нужной темы, нет времени): в
 *     документе снимок остаётся, но с видимой строкой «снимок до версии 1.4»;
 *  3. **убрать** — экрана больше нет: снимок удаляют, а не оставляют «на память».
 *
 * И запрет: скриншот **никогда** не остаётся без пометки. Молча устаревший
 * скриншот хуже отсутствующего: по нему ищут кнопку, которой нет.
 */

/** Состояние снимка. */
export type State = "свежий" | "переснять" | "помечен" | "убрать";

/** Снимок. */
export interface Shot {
  readonly screen: string;
  /** Отпечаток экрана, на котором снят. */
  readonly fingerprint: string;
  /** Отпечаток экрана сейчас. */
  readonly now: string;
  /** Есть ли экран ещё. */
  readonly exists: boolean;
  /** Помечен ли «до версии». */
  readonly marked: boolean;
}

/**
 * Что делать со снимком.
 *
 * Решение по двум фактам: экран есть и отпечаток совпал.
 */
export function decide(shot: Shot): State {
  if (!shot.exists) return "убрать";
  if (shot.fingerprint === shot.now) return "свежий";
  return shot.marked ? "помечен" : "переснять";
}

/**
 * Что показать в документе.
 *
 * У помеченного — версия, до которой снят; иначе снимок читается как текущий.
 */
export function caption(shot: Shot, untilVersion: string): string {
  const state = decide(shot);
  if (state === "убрать") return `Экрана «${shot.screen}» больше нет`;
  if (state === "помечен") return `Экран «${shot.screen}» — снимок до версии ${untilVersion}: детали могли измениться`;
  if (state === "переснять") return `Экран «${shot.screen}» — снимок устарел, переснять или пометить`;
  return `Экран «${shot.screen}» — снимок текущий`;
}

/**
 * Все снимки без пометки, которые устарели.
 *
 * Это и есть ошибка CI: молча устаревший снимок.
 */
export function unmarked(shots: readonly Shot[]): string[] {
  return shots.filter((shot) => decide(shot) === "переснять").map((shot) => shot.screen);
}

/**
 * Чего нельзя.
 *
 * Три запрета; первый — главный.
 */
export function notDo(): string[] {
  return [
    "не оставлять устаревший снимок без пометки: по нему ищут кнопку, которой нет",
    "не оставлять снимок удалённого экрана «на память»",
    "не переснимать вручную без записи версии: пометка нужна и после пересъёмки",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три исхода и один запрет.
 */
export function checks(): string[] {
  return [
    "снимок живёт по отпечатку, а не по дате",
    "у любого устаревшего снимка видна пометка с версией",
    "снимок исчезнувшего экрана убран, а не оставлен",
  ];
}
