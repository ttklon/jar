import { describe, expect, it } from "vitest";
import { canSayNow, first, form, honest, late, order, waited } from "./firstWord";

/**
 * Шаг 128: первое слово ответа — раньше, чем полный план.
 *
 * Тишина 3 секунды не отвечала на «услышал ли», и человек повторял фразу.
 */
describe("первое слово — сразу, до плана", () => {
  it("не ждёт плана", () => {
    expect(canSayNow(false)).toBe(true);
  });

  it("идёт раньше полного ответа", () => {
    expect(order(first("переименовать"), "готово: переименовал 12 фото")).toEqual([
      "переименовываю",
      "готово: переименовал 12 фото",
    ]);
  });

  it("полный ответ остаётся полным — первое слово его не подменяет", () => {
    expect(order(first("проверить"), "свободно 120 ГБ")[1]).toBe("свободно 120 ГБ");
  });
});

describe("первое слово честное", () => {
  it("действие известно — названо дело, а не «сейчас всё будет»", () => {
    expect(first("переименовать")).toEqual({ word: "переименовываю", known: true, refuse: false });
  });

  it("ещё непонятно — так и сказано: «разбираю», а не обещание", () => {
    expect(first(null)).toEqual({ word: "разбираю", known: false, refuse: false });
  });

  it("обещание не выдаётся за факт", () => {
    expect(honest({ word: "сейчас всё будет", known: false, refuse: false })).toBe(false);
    expect(honest(first(null))).toBe(true);
  });

  it("глагол становится «что я делаю», а не «что сделать»", () => {
    expect(form("переименовать")).toBe("переименовываю");
    expect(form("проверить")).toBe("проверяю");
    expect(form("открыть")).toBe("открываю");
  });
});

describe("если сразу ясно, что не смогу — первое слово и есть отказ", () => {
  it("«не умею» лучше, чем «делаю» и потом «не смог»", () => {
    expect(first(null, true)).toEqual({ word: "не умею", known: true, refuse: true });
  });
});

describe("запоздалое первое слово не произносится", () => {
  it("«делаю» после «сделал» — это неправда", () => {
    expect(late(first("переименовать"), true)).toBe("");
  });

  it("пока план не готов — произносится", () => {
    expect(late(first("переименовать"), false)).toBe("переименовываю");
  });
});

describe("задержка первого слова считается отдельно", () => {
  it("первое слово через N мс", () => {
    expect(waited(0, 400).said).toBe("первое слово через 400 мс");
  });

  it("не было первого слова — сказано прямо", () => {
    // Молчание не превращается в «0 мс»: человек ничего не услышал.
    expect(waited(0, null).ms).toBeNull();
    expect(waited(0, null).said).toContain("не знал, услышали ли его");
  });
});
