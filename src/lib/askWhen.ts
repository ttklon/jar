/**
 * Уточняющий вопрос — только когда без него исполнение опасно (шаг 82).
 *
 * Дефект. Приложение спрашивает **через раз**, и оба края плохи:
 *
 *  * **Слишком часто**: на «открой загрузки» — «какие загрузки?», на «который
 *    час» — «вы имеете в виду время?». Каждый вопрос — это работа, которую
 *    человек **не хотел**: он говорил, чтобы стало быстрее, а стал диктант.
 *  * **Слишком редко**: «удали отчёты» исполняется молча, если отчётов триста,
 *    и человек узнаёт об этом после. Вопрос после необратимого действия — не
 *    выбор, а сообщение о случившемся.
 *
 * Правило: **вопрос задаётся при двух условиях вместе — необратимо и
 * неоднозначно**.
 *
 *  1. **Необратимо** (шаг 12: удалить, отправить, перезаписать) — вопрос нужен,
 *     потому что отменить нечем.
 *  2. **Неоднозначно** — на фразе несколько разных объектов, и исполнение
 *     одного вместо другого даст не тот результат.
 *  3. Если действие **обратимо** (открыть, найти, показать) — вопрос не
 *     задаётся никогда: ошибка стоит одного повторного слова, а вопрос стоит
 *     минуты.
 *  4. Если **однозначно** — вопрос не задаётся, даже если необратимо: «удали
 *     файл `отчёт-март.pdf`» понятно, и вопрос «удалить?» — это просто
 *     торможение на ровном месте.
 *
 * Почему не «спросить на всякий случай». Вопрос, заданный без нужды, учит
 * человека отвечать не читая — и тогда настоящий вопрос он тоже пропустит.
 * Цена лишнего вопроса не в секунде, а в том, что **все** вопросы перестают
 * работать.
 */

/** Что известно о действии до исполнения. */
export interface Plan {
  /** Необратимо ли: отменить нечем. */
  irreversible: boolean;
  /** Сколько разных объектов подходит под фразу. */
  matches: number;
  /** Названный объект точен («файл отчёт-март.pdf») или родовой («отчёты»). */
  exact: boolean;
}

/** Нужен ли вопрос. */
export interface Ask {
  /** Задавать ли. */
  ask: boolean;
  /** Почему — для показа человеку и для проверки тестом. */
  why: string;
}

/**
 * Решение о вопросе.
 *
 * Единственное «да» — необратимо **и** неоднозначно. Всё остальное — исполнять
 * и сказать, что сделано (с возможностью отменить, где отмена есть).
 */
export function need(plan: Plan): Ask {
  if (!plan.irreversible) {
    return {
      ask: false,
      why: "действие обратимо: ошибка стоит одного слова, а вопрос — минуты",
    };
  }
  if (plan.exact && plan.matches <= 1) {
    return {
      ask: false,
      why: "объект назван точно: спрашивать не о чем",
    };
  }
  if (plan.matches === 0) {
    return {
      ask: false,
      why: "под фразу ничего не подходит — не спрашивать, а сказать, что не нашлось",
    };
  }
  return {
    ask: true,
    why: `действие необратимо, а под фразу подходит ${plan.matches}: без вопроса можно стереть не то`,
  };
}

/**
 * Сколько в вопросе перечислять.
 *
 * Не «300 файлов найдено» и не «много»: **число и три первых имени**, потому
 * что человеку нужно узнать свой файл, а не прочитать список. Число говорит,
 * насколько велик риск, три имени — что именно.
 */
export const SHOW = 3;

export function question(plan: Plan, names: readonly string[]): string {
  const count = plan.matches;
  if (count === 1) {
    // Одно совпадение, но объект назван родово: вопрос **именем**, а не «да/нет».
    return `удалить «${names[0] ?? "этот файл"}»? это необратимо`;
  }
  const shown = names.slice(0, SHOW).map((name) => `«${name}»`).join(", ");
  const rest = count > SHOW ? ` и ещё ${count - SHOW}` : "";
  return `под фразу подходит ${count}: ${shown}${rest} — это необратимо, укажите, что именно`;
}

/**
 * Что сказать, когда вопрос не задаётся, но действие необратимо.
 *
 * Сделано и **сказано** с возможностью отмены, если она есть. Молчание после
 * удаления — это то, из-за чего человек не знает, удалилось ли.
 */
export function done(plan: Plan, what: string): string {
  if (!plan.irreversible) return `${what} — сделано`;
  return `${what} — удалено без вопроса: объект был назван точно`;
}

/**
 * Лишний вопрос — это дефект, а не осторожность.
 *
 * Названо прямо: каждый вопрос, заданный без нужды, обучает не читать вопросы.
 * Функция есть, чтобы тест мог проверить обе стороны.
 */
export function wasted(plan: Plan): boolean {
  return !need(plan).ask;
}

/**
 * Правило одной строкой — для экрана настроек.
 *
 * Человек должен понимать, почему его спрашивают: это не «так решило
 * приложение», а конкретный риск.
 */
export function rule(): string {
  return "спрашиваю, только если действие необратимо и под фразу подходит не одно — иначе делаю и говорю, что сделал";
}
