/**
 * Планшет и сенсор: крупные цели, никаких действий только по наведению (шаг 223).
 *
 * Дефект. Навигация была доведена до 44 px (шаг 196), и на этом «все устройства»
 * заканчивалось. Две дыры:
 *
 *  * **размер цели — не решение, а константа.** 44 px хороши для пальца, но
 *    крупная цель там, где мышь, — это разреженный экран: тот же 44 px на
 *    настольном компьютере отнимает место, ничего не добавляя. Размер должен
 *    зависеть от указателя, а не от вкуса;
 *  * **действия по наведению.** `:hover` — косметика, пока он меняет цвет. Но
 *    как только действие спрятано за наведением (иконка «удалить» появляется при
 *    hover), на сенсоре его **нет вовсе**: наведение там не существует, и кнопка
 *    либо не появляется, либо появляется по первому касанию — то есть первое
 *    касание тратится на проявление, а не на действие.
 *
 * Правила:
 *
 *  1. **палец — не меньше 44 px по короткой стороне**, мышь — 32: меньше 32 и
 *     мышью неудобно, больше — разрежает;
 *  2. **если нет наведения, действия по наведению нет**: `hoverOnly` — дефект, а
 *     не «неудобство». Проверка называет элемент;
 *  3. **неизвестный указатель — считается сенсорным.** `matchMedia` может
 *     отсутствовать, а `pointer: fine` может соврать (ноутбук с тачскрином);
 *     выбрать крупные цели и ошибиться безопаснее, чем выбрать мелкие;
 *  4. **на сенсоре нет «правого клика» и «средней кнопки»** — меню по правому
 *     клику, если оно есть, обязано иметь кнопку.
 *
 * Модуль не рисует: он отвечает, какие размеры применить и что нельзя прятать.
 */

/** Тип указателя — насколько об этом можно судить. */
export type Pointer = "fine" | "coarse" | "unknown";

/** Размеры цели по короткой стороне, в логических пикселях. */
export interface Sizes {
  /** Кнопка и пункт меню. */
  control: number;
  /** Строка списка: палец попадает в строку, а не в галочку. */
  row: number;
  /** Отступ между целями: промах по одной не должен нажимать соседнюю. */
  gap: number;
}

/** Что применить при таком указателе. */
export function sizes(pointer: Pointer): Sizes {
  // Неизвестный — как сенсор: крупные цели ошибаются в безопасную сторону.
  if (pointer === "fine") return { control: 32, row: 36, gap: 6 };
  return { control: 44, row: 48, gap: 10 };
}

/**
 * Прочитать тип указателя у среды.
 *
 * `coarse` — палец, `fine` — мышь или трекпад. Сначала спрашиваем про
 * `pointer: coarse`, а не про `hover`: планшет с мышью отдаёт `hover: hover` и
 * `pointer: coarse` одновременно, и по наведению мы бы решили «мышь», хотя
 * пальцем тоже будут.
 */
export function pointerOf(media: ((query: string) => { matches: boolean }) | undefined): Pointer {
  if (!media) return "unknown";
  try {
    if (media("(pointer: coarse)").matches) return "coarse";
    if (media("(pointer: fine)").matches) return "fine";
    return "unknown";
  } catch {
    // Среда сломалась на запросе — не повод ставить мелкие цели.
    return "unknown";
  }
}

/** Элемент, действие которого доступно только по наведению. */
export interface HoverOnly {
  /** Что это за элемент — словами, чтобы проверка называла, а не считала. */
  what: string;
  /** Прячется ли он до наведения (`display: none`, `opacity: 0`, `visibility: hidden`). */
  hiddenUntilHover: boolean;
  /** Есть ли другое действие, доступное всегда (кнопка «ещё», меню). */
  reachable: boolean;
}

/**
 * Можно ли так делать на сенсоре.
 *
 * `hiddenUntilHover && !reachable` — дефект. `hiddenUntilHover && reachable` —
 * терпимо: действие всё равно доступно, а подсказка при наведении — ускорение
 * для мыши, не единственный путь.
 */
export function hoverOnly(got: HoverOnly): { ok: boolean; why: string } {
  if (!got.hiddenUntilHover) return { ok: true, why: "" };
  if (got.reachable) return { ok: true, why: "" };
  return {
    ok: false,
    why:
      `${got.what}: действие есть только по наведению — на сенсоре наведения нет, ` +
      "и это действие там недоступно; нужна постоянная кнопка или «ещё»",
  };
}

/**
 * Проверка списка — все дефекты разом, а не первый.
 *
 * Первый дефект останавливает правку: исправили один, прогнали, нашли второй.
 * Поэтому список.
 */
export function problems(items: readonly HoverOnly[]): string[] {
  return items.map(hoverOnly).filter((item) => !item.ok).map((item) => item.why);
}

/**
 * Сказать человеку, что интерфейс подстроился.
 *
 * Молчаливое изменение размера читается как «сломалось»: кнопки вдруг стали
 * крупными и всё поехало. Одна фраза снимает вопрос.
 */
export function notice(pointer: Pointer): string {
  if (pointer === "coarse") return "сенсорный экран: цели крупнее, скрытых за наведением действий нет";
  return "";
}
