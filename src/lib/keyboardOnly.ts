/**
 * Шаг 193: главный сценарий без мыши.
 *
 * `Ctrl+K` → буквы → Enter → фраза → Enter. Пять нажатий, и дело начато — руки не
 * уходят с клавиатуры. Это не про удобство: человек, который печатает, теряет
 * больше времени на переход к мыши, чем на саму работу.
 *
 * Но сценарий без мыши — это не «всё на клавишах». Это **полный путь**, у которого
 * на каждом шаге есть ответ на три вопроса:
 *
 *  * **куда я попал** — сказано словами (для диктора, шаг 198);
 *  * **что нажму** — Enter ведёт дальше, Escape возвращает;
 *  * **как я узнаю, что получилось** — результат виден и объявлен.
 *
 * Если на любом шаге нужен Tab по кругу двадцать раз — это не сценарий без мыши.
 */

/** Шаг сценария. */
export interface Step {
  /** Что нажали — по порядку. */
  readonly key: string;
  /** Куда попали. */
  readonly where: string;
  /** Что услышит диктор — словами. */
  readonly heard: string;
}

/**
 * Сценарий.
 *
 * Пять шагов, ровно те, что в шаге плана: палитра, буквы, Enter, фраза, Enter.
 */
export function steps(): Step[] {
  return [
    { key: "Ctrl+K", where: "поле палитры", heard: "палитра, наберите буквы экрана" },
    { key: "буквы", where: "список экранов, подсвечен первый", heard: "первый результат подсвечен" },
    { key: "Enter", where: "экран дела, поле фразы", heard: "поле фразы, говорите или печатайте" },
    { key: "фраза", where: "бриф дела", heard: "понял так, подтвердите" },
    { key: "Enter", where: "дело выполняется", heard: "выполняю" },
  ];
}

/**
 * Проверить сценарий.
 *
 * Нарушения: шаг без «что услышит», шаг без места, Esc не возвращает (нет
 * возврата — значит тупик), больше семи шагов до дела.
 */
export function check(list: readonly Step[] = steps()): string[] {
  const problems: string[] = [];

  if (list.length > 7) problems.push(`до дела ${list.length} шагов: больше семи — это уже лабиринт, а не сценарий`);
  for (const step of list) {
    if (step.heard.trim() === "") problems.push(`«${step.key}»: не сказано, что услышит человек — сценарий без диктора неполон`);
    if (step.where.trim() === "") problems.push(`«${step.key}»: не сказано, куда попал`);
  }

  return problems;
}

/**
 * Escape.
 *
 * Возвращает на шаг назад — и говорит, куда вернул. «Просто закрылось» — это
 * потеря места, а не возврат.
 */
export function escape(from: number, list: readonly Step[] = steps()): { to: number; said: string } {
  if (from <= 0) return { to: 0, said: "уже в начале: закрываю палитру" };
  const target = list[from - 1];
  return { to: from - 1, said: target === undefined ? "возврат на шаг назад" : `вернулся: ${target.where}` };
}

/**
 * Сколько шагов до дела.
 *
 * Числом: пять — это сценарий, десять — это «лучше мышью».
 */
export function untilDone(list: readonly Step[] = steps()): number {
  return list.length;
}

/**
 * Чего сценарий не делает.
 *
 * Три запрета; главный — не Tab по кругу.
 */
export function notDo(): string[] {
  return [
    "не заставляет ходить Tab по кругу: переходы — клавишами",
    "не оставляет шаг без объявления: «тихо перешли» — это потеря места для диктора",
    "не запирает: Escape всегда возвращает на шаг назад",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу вопросов на каждом шаге.
 */
export function checks(): string[] {
  return [
    "пять шагов до дела, у каждого место и объявление",
    "Escape возвращает и говорит, куда",
    "больше семи шагов — лабиринт, а не сценарий",
  ];
}
