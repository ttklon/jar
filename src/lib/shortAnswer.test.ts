import { describe, expect, it } from "vitest";
import { moreLine, onScreen, sentences, spoken, wantsMore } from "./shortAnswer";

/**
 * Шаг 47: ответ по умолчанию короткий, длинный — по просьбе.
 *
 * Голосовой ответ — это ответ, а не чтение документа. Длинный ответ раздражает
 * вдвойне, потому что его нельзя пролистать.
 */
describe("что произносится", () => {
  it("по умолчанию — первое предложение, а не весь абзац", () => {
    const answer = "Папка создана. Внутри три файла. Ещё есть вложенная папка.";
    expect(spoken(answer)).toBe("Папка создана.");
  });

  it("по просьбе — целиком", () => {
    const answer = "Папка создана. Внутри три файла.";
    expect(spoken(answer, true)).toBe("Папка создана. Внутри три файла.");
  });

  it("произносить нечего — молчим, а не читаем «ничего не найдено»", () => {
    expect(spoken("")).toBeNull();
    expect(spoken("   ")).toBeNull();
  });

  it("на экране остаётся всё, без потерь", () => {
    // Короткий ответ не значит «выбросить текст»: то, что не прочли вслух,
    // человек должен прочесть.
    const answer = "Папка создана. Внутри три файла.";
    expect(onScreen(answer)).toBe(answer);
  });
});

describe("разбор предложений", () => {
  it("точка внутри числа не рвёт фразу", () => {
    // «1.5» — не конец предложения. Иначе версия приложения «0.1.0» станет
    // тремя «предложениями».
    expect(sentences("Версия 1.5 вышла.")).toEqual(["Версия 1.5 вышла."]);
    expect(sentences("Обновил до 0.2.1. Теперь работает.")).toEqual([
      "Обновил до 0.2.1.",
      "Теперь работает.",
    ]);
  });

  it("вопрос и восклицание — тоже границы", () => {
    expect(sentences("Готово! А дальше? Не знаю.")).toEqual(["Готово!", "А дальше?", "Не знаю."]);
  });

  it("текст без точки — одно предложение, а не ничего", () => {
    expect(sentences("готово")).toEqual(["готово"]);
  });
});

describe("просьба подробнее", () => {
  it("короткая просьба узнаётся", () => {
    expect(wantsMore("подробнее")).toBe(true);
    expect(wantsMore("Расскажи")).toBe(true);
    expect(wantsMore("а почему?")).toBe(true);
  });

  it("длинный вопрос про причину — новый вопрос, а не просьба", () => {
    // Иначе любой вопрос «почему упало» продолжал бы прошлый ответ вместо того,
    // чтобы отвечать на новый.
    expect(wantsMore("почему упало скачивание вчера вечером на моём компьютере")).toBe(false);
    // А явное «подробнее» в длинной фразе — всё равно просьба.
    expect(wantsMore("расскажи подробнее про эту папку вообще")).toBe(true);
  });

  it("обычная фраза — не просьба", () => {
    expect(wantsMore("создай папку")).toBe(false);
    expect(wantsMore("")).toBe(false);
  });

  it("сказано, что осталось на экране и как попросить", () => {
    // «Есть ещё кое-что» — загадка. Называется путь.
    const line = moreLine(2);
    expect(line).toContain("подробнее");
    expect(line).toContain("экран");
    expect(moreLine(0)).toBeNull(); // скрывать нечего — молчим
  });
});
