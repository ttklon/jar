/**
 * Шаг 488: ночи без красного — ночной прогон живого сценария.
 *
 * Обычный тест гоняет правила в изоляции. Но регрессия чаще всего не в правиле, а
 * **между** правилами: разбор понял, рука получила, экран показал не то. Такую
 * регрессию видно только в **живом сценарии**: «сказали фразу → нажали → увидели».
 *
 * Живой сценарий идёт **ночью**, потому что он медленный (секунды на шаг) и потому
 * что утром нужен ответ, а не во время работы. Три правила:
 *
 *  * **ночь без красного — норма**: если утром красное, это разбирают в тот же день,
 *    иначе красное становится фоном;
 *  * **сценарий — живой**: настоящий разбор, настоящий экран, настоящая рука в
 *    песочнице, а не моки;
 *  * **падение объяснено**: не «упало», а на каком шаге и что видел человек.
 */

/** Шаг живого сценария. */
export interface Step {
  /** Что делает человек. */
  readonly human: string;
  /** Что должно произойти. */
  readonly expect: string;
  /** Сколько идёт, секунд. */
  readonly seconds: number;
}

/** Результат прогона. */
export interface Run {
  /** Ночь — дата `YYYY-MM-DD`. */
  readonly night: string;
  /** На каком шаге упало; `0` — прошло. */
  readonly failedAt: number;
  /** Сколько шло, секунд. */
  readonly seconds: number;
}

/** Ночной прогон не должен вылезать за утро: до скольких он обязан закончиться. */
export const BUDGET_SECONDS = 600;

/**
 * Проверить сценарий.
 *
 * Нарушения: шаг без ожидания, шаг длиннее бюджета, сценарий короче трёх шагов
 * (тогда это не сценарий, а вызов функции).
 */
export function checkScenario(steps: readonly Step[]): string[] {
  const problems: string[] = [];

  if (steps.length < 3) problems.push(`шагов ${steps.length}: меньше трёх — это не сценарий, а вызов`);
  for (const step of steps) {
    if (step.expect.trim().length < 10) problems.push(`«${step.human}»: нет ожидания — что должно произойти?`);
    if (step.seconds > BUDGET_SECONDS / 2) problems.push(`«${step.human}»: ${step.seconds} с на шаг — сценарий не успеет за ночь`);
  }

  const total = steps.reduce((sum, step) => sum + step.seconds, 0);
  if (total > BUDGET_SECONDS) problems.push(`сценарий ${total} с: дольше ${BUDGET_SECONDS} — утром ответа не будет`);

  return problems;
}

/**
 * Что сказать утром.
 *
 * Одна строка: прошло или на каком шаге и что видел человек. И **срок разбора** —
 * красное до вечера, а не «когда-нибудь».
 */
export function morning(run: Run, steps: readonly Step[]): { red: boolean; said: string } {
  if (run.failedAt === 0) return { red: false, said: `ночь ${run.night}: сценарий прошёл за ${run.seconds} с, красного нет` };

  const step = steps[run.failedAt - 1];
  const where = step === undefined ? `шаг ${run.failedAt}` : `шаг ${run.failedAt} «${step.human}», ждали: ${step.expect}`;
  return { red: true, said: `ночь ${run.night}: красное на ${where} — разобрать до вечера, иначе красное станет фоном` };
}

/**
 * Что делает ночной прогон живым.
 *
 * Три условия, без любого — это не живой сценарий.
 */
export function alive(): string[] {
  return [
    "настоящий разбор фразы, а не подставленный ответ",
    "настоящая рука в песочнице: папка, файлы, корзина",
    "настоящий экран: проверяется то, что видит человек, а не состояние",
  ];
}

/**
 * Чего ночной прогон не делает.
 *
 * Три запрета; главный — не привыкать к красному.
 */
export function notDo(): string[] {
  return [
    "не оставляет красное до «когда-нибудь»: разбор в тот же день",
    "не подменяет шаги моками: тогда он проверяет моки",
    "не молчит о падении: утром есть строка с шагом и ожиданием",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "сценарий из трёх и более шагов, у каждого ожидание",
    "прогон укладывается в бюджет ночи",
    "утренняя строка называет шаг и что ждали",
  ];
}
