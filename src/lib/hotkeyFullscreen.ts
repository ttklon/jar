/**
 * Шаг 455: не перехватывать клавиши в полноэкранных приложениях.
 *
 * Шаг 444 сказал: в полноэкранном режиме горячие клавиши не работают. Здесь —
 * **где именно** это решается и почему нельзя решить «в обработчике нажатия».
 *
 * Ошибка, которую надо исключить: приложение получает нажатие, проверяет
 * «полноэкранное ли», и если да — глотает клавишу. Но клавиша уже **отнята** у
 * игры: игра не получила `Ctrl+Alt+Space`, а он ей был нужен.
 *
 * Значит, решение принимается **до** регистрации перехвата: если сейчас
 * полноэкранное приложение — горячая клавиша не регистрируется вовсе, и Windows
 * отдаёт её игре. Как только полноэкранное закрылось — регистрируется обратно.
 */

/** Что известно. */
export interface State {
  /** Есть ли полноэкранное приложение. */
  readonly fullscreen: boolean;
  /** Какой режим у программы: «работает» или «на паузе». */
  readonly paused: boolean;
}

/** Нужно ли перехватывать сейчас. */
export function grab(state: State): { on: boolean; said: string } {
  if (state.paused) return { on: false, said: "программа на паузе: клавиши не перехватываются вовсе" };
  if (state.fullscreen) {
    return {
      on: false,
      said: "открыто полноэкранное приложение: перехват снят. Клавиша достаётся игре — не «глотается» после проверки",
    };
  }
  return { on: true, said: "перехват включён: клавиша наша" };
}

/**
 * Что делать при смене состояния.
 *
 * Снимаем и возвращаем **по событию**, а не опросом раз в секунду: опрос на
 * слабой машине заметен, а окно между событиями — миллисекунды.
 */
export function change(before: State, after: State): { action: "grab" | "release" | "none"; said: string } {
  const was = grab(before).on;
  const now = grab(after).on;
  if (was === now) return { action: "none", said: "ничего не меняется" };
  return now ? { action: "grab", said: "полноэкранное закрылось: перехват вернул" } : { action: "release", said: "полноэкранное открылось: перехват снял" };
}

/**
 * Почему нельзя «проверить и проглотить».
 *
 * Объяснение — для комментария и для теста: это не стилистика, а поведение.
 */
export function whyBefore(): string {
  return "проверка в обработчике нажатия уже отняла клавишу у игры: `Ctrl+Alt+Space` не дошёл, а был нужен. Поэтому перехват снимается заранее";
}

/**
 * Что проверяет тест.
 *
 * Три состояния — и три разных ответа.
 */
export function cases(): State[] {
  return [
    { fullscreen: false, paused: false },
    { fullscreen: true, paused: false },
    { fullscreen: false, paused: true },
  ];
}

/**
 * Что не делает перехват.
 *
 * Три запрета — про клавиатуру.
 */
export function notDo(): string[] {
  return [
    "не глотает клавишу после проверки: перехват снят заранее",
    "не опрашивает состояние раз в секунду: реагирует на событие",
    "не остаётся снятым после выхода из полноэкранного: возвращается сразу",
  ];
}
