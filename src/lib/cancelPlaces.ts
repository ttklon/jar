/**
 * Шаг 377: отмена из ленты и из трея — одинаково. Одно поведение.
 *
 * Одна и та же кнопка в двух местах ведёт себя по-разному — это классика, которая
 * замечается в самый неподходящий момент: в ленте отмена спрашивает
 * подтверждение, в трее нет, и человек, нажав в трее, останавливает не то.
 *
 * Поэтому **решение принимается одной функцией**, а места только передают ей, что
 * знают. Здесь эта функция и проверка того, что места не «додумывают» своё.
 *
 * Что все места обязаны знать: можно ли отменить (шаг 368), ждёт ли дело
 * подтверждения (шаг 376), что уже отправлено.
 */

/** Что известно о деле. */
export interface Deed {
  readonly what: string;
  /** Можно ли отменить шаг сейчас. */
  readonly cancellable: boolean;
  /** Ждёт ли подтверждения. */
  readonly waiting: boolean;
  /** Есть ли уже отправленное действие. */
  readonly sent: boolean;
}

/** Откуда нажали. */
export type Place = "feed" | "tray" | "window" | "hotkey";

/** Что происходит. */
export interface Result {
  /** Спрашиваем подтверждение — и это одинаково везде. */
  readonly ask: boolean;
  /** Текст вопроса или сообщения — одинаковый везде. */
  readonly said: string;
}

/**
 * Решение об отмене — одно на все места.
 *
 * Спрашиваем подтверждение всегда, когда действие необратимо. Не «в трее быстрее,
 * поэтому без вопроса»: скорость места не меняет последствий.
 */
export function decide(deed: Deed, place: Place): Result {
  if (!deed.cancellable) {
    return {
      ask: false,
      said: `«${deed.what}» отменить нельзя: шаг уже отправлен — остановлю на следующем (${placeName(place)})`,
    };
  }
  if (deed.sent) {
    return {
      ask: true,
      said: `Часть «${deed.what}» уже отправлена — отменить остальное? (${placeName(place)})`,
    };
  }
  return { ask: false, said: `Отменить «${deed.what}»? (${placeName(place)})` };
}

/** Имя места — для журнала и для подсказки. */
export function placeName(place: Place): string {
  const names: Record<Place, string> = { feed: "лента", tray: "трей", window: "окно дела", hotkey: "горячая клавиша" };
  return names[place];
}

/**
 * Проверка одинаковости.
 *
 * Одинаково — когда `ask` и `said` совпадают **без имени места**: имя места в
 * тексте есть, но поведение от него не зависит.
 */
export function consistent(
  deed: Deed,
  places: readonly Place[],
  // Поведение можно подставить: иначе проверка сама себя проверяет и ничего не ловит.
  run: (deed: Deed, place: Place) => Result = decide,
): string[] {
  const results = places.map((place) => ({ place, result: run(deed, place) }));
  const problems: string[] = [];

  const asks = new Set(results.map((item) => item.result.ask));
  if (asks.size > 1) problems.push("в разных местах отмена спрашивает по-разному: одно поведение, а не два");

  const bodies = new Set(results.map((item) => item.result.said.replace(/\s*\((лента|трей|окно дела|горячая клавиша)\)$/, "")));
  if (bodies.size > 1) problems.push("текст отмены в разных местах разный: человек видит разные слова про одно дело");

  return problems;
}

/**
 * Что горячая клавиша не делает.
 *
 * Самое опасное место: нажатие случайное, и подтверждения не ждут.
 */
export function hotkeyRules(): string[] {
  return [
    "горячая клавиша отмены не срабатывает, если дело ждёт подтверждения: сначала ответ, потом отмена",
    "не отменяет неотменяемое, а говорит, что остановит на следующем шаге",
    "не срабатывает дважды: второе нажатие ничего не делает и не «отменяет отмену»",
  ];
}
