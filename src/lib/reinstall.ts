/**
 * Приложение работает после переустановки — без сети и без повторной загрузки
 * модели (шаг 219).
 *
 * Дефект. Модели и журналы лежат **внутри `%LOCALAPPDATA%\ZShelper`** — в папке
 * данных приложения. Это удобно ровно до переустановки: обычный совет «удалите
 * данные приложения и поставьте заново» стирает гигабайты, которые качались
 * часами, а человек этого не ждёт — он ждёт, что «переустановка» про программу,
 * а не про его файлы.
 *
 * Правила:
 *
 *  1. **что переустановка трогает — названо списком**, а не «данные»: программа,
 *     движок, ярлыки. Модели, память и журнал — **не** трогаются;
 *  2. **модель не качается заново**, если файл на месте и его хеш совпал. Хеш —
 *     единственный способ отличить «тот самый файл» от «файл с тем же именем»;
 *  3. **без сети переустановка не ломает запуск**: приложение обязано подняться,
 *     сказать «движка нет, модель на месте» и не пытаться ничего скачать само;
 *  4. **что уже на диске — проверяется до сети**, а не после: спрашивать сервер о
 *     том, что лежит рядом, — это и есть «качает заново»;
 *  5. **частичное состояние называется**: «движок есть, модели нет» и «модель
 *     есть, движка нет» — разные ответы, и второй лечится переустановкой, а не
 *     скачиванием гигабайтов.
 *
 * Модуль не ходит в сеть и не удаляет файлы: он отвечает, что произойдёт.
 */

/** Что переустановка трогает. */
export const TOUCHED = [
  "программа и её файлы",
  "движок (llama.cpp, whisper.cpp)",
  "ярлыки и автозапуск",
] as const;

/** Что переустановка не трогает — и это обещание, а не «обычно». */
export const KEPT = [
  "модели (гигабайты, которые качались часами)",
  "память и история разговоров",
  "журнал действий и отката",
  "настройки",
] as const;

/** Что лежит на диске до всякой сети. */
export interface OnDisk {
  /** Модель: файл и хеш, который ядро посчитало. */
  model: { file: string; sha256: string } | null;
  /** Эталон хеша — из реестра. Нет эталона — сверять не с чем. */
  expected: string | null;
  /** Движок установлен и прошёл проверку. */
  engine: boolean;
}

/** План после переустановки. */
export interface Plan {
  /** Что можно начать сразу, без сети. */
  canStart: boolean;
  /** Что докачать — и правда ли это нужно. */
  download: string[];
  /** Что сказать человеку. */
  said: string;
}

/**
 * План после переустановки: сначала диск, потом сеть.
 *
 * Порядок проверок — это и есть правило 4: если модель на месте и хеш сошёлся,
 * сети для разговора не нужно вовсе, и предлагать «скачать модель» значит
 * заставлять человека ждать без причины.
 */
export function plan(disk: OnDisk, online: boolean | null): Plan {
  const hasModel = disk.model !== null;
  // Эталона нет — файл на месте, но «тот самый» не доказано. Это не «качать
  // заново»: модель работает, и человек вправе решить сам.
  const verified = hasModel && disk.expected !== null && disk.model!.sha256 === disk.expected;

  if (!hasModel) {
    return {
      canStart: false,
      download: ["модель", "движок"].filter((item) => item === "движок" ? !disk.engine : true),
      said: online === false
        ? "модели после переустановки нет, а сети нет: скачать её сейчас не получится. Всё остальное — действия на компьютере, история, настройки — работает"
        : "модели после переустановки нет: её нужно скачать один раз, дальше она остаётся на месте",
    };
  }

  if (!disk.engine) {
    return {
      canStart: false,
      download: ["движок"],
      said:
        "модель на месте и не качается заново; не хватает движка — это сотни мегабайт, а не гигабайты. " +
        (online === false ? "Сети нет: движок придётся поставить, когда она появится" : "Движок ставится отдельно от модели"),
    };
  }

  if (!verified) {
    // Файл есть, эталона нет или хеш не совпал. Не молчим и не качаем молча.
    return {
      canStart: true,
      download: [],
      said:
        disk.expected === null
          ? "модель на месте, но эталона хеша нет: запустить можно, а «тот самый файл» не доказано"
          : "модель на месте, но хеш не совпал с эталоном: файл мог испортиться при копировании. Запускать можно, но это стоит знать до разговора",
    };
  }

  return {
    canStart: true,
    download: [],
    said: "после переустановки всё на месте: модель и движок не качаются заново, разговор начинается сразу" +
      (online === false ? " — и сеть для этого не нужна" : ""),
  };
}

/**
 * Обещание словами — для экрана.
 *
 * Списки, а не фраза «ваши данные в безопасности»: «данные» каждый понимает
 * по-своему, и обычно уже — чем нужно.
 */
export function promise(): string {
  return (
    `Переустановка трогает: ${TOUCHED.join(", ")}. Не трогает: ${KEPT.join(", ")}. ` +
    "Если модель на месте и хеш сошёлся, она не качается заново — без сети тоже"
  );
}

/**
 * Сколько придётся качать после переустановки — числом.
 *
 * Ноль здесь важнее любого числа: «ноль гигабайт» и есть ответ на вопрос «а мне
 * опять качать?».
 */
export function gigabytes(plan: Plan, modelGb: number, engineGb: number): number {
  return plan.download.reduce((total, item) => total + (item === "модель" ? modelGb : engineGb), 0);
}

/**
 * Проверка: обещания не противоречат друг другу.
 *
 * «Модели не трогаются» и «скачать модель» в одном ответе — прямое противоречие,
 * и заметить его должен не человек.
 */
export function consistent(plan: Plan): { ok: boolean; why: string } {
  if (plan.download.includes("модель") && plan.said.includes("не качается заново")) {
    return { ok: false, why: "сказано «не качается заново», а в плане — скачать модель" };
  }
  if (plan.canStart && plan.download.includes("модель")) {
    return { ok: false, why: "«можно начать» и «скачать модель» одновременно" };
  }
  return { ok: true, why: "" };
}
