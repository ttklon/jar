/**
 * Шаг 454: уведомления — системные, скрываются вместе с «не беспокоить».
 *
 * Правила уведомлений уже есть: системные вместо своих (`systemNotices`, шаг 442)
 * и уважение «не беспокоить» (`dndRespect`, шаг 445). Здесь — проверка **на
 * стыке**: что при включённом «не беспокоить» система действительно прячет наши
 * уведомления, и что ничего не «пролезает» мимо неё.
 *
 * Три способа пролезть мимо системного «не беспокоить», и все встречаются:
 *
 *  * **своя всплывашка** в обход системы — сюда её не пускаем (шаг 442);
 *  * **ложная срочность** (`urgent`, высокий приоритет) — система её пропустит;
 *  * **повтор** через минуту — пять одинаковых уведомлений тоже пролезают.
 */

import { notice, type Kind } from "./systemNotices";
import { decide } from "./dndRespect";

/** Что отправляется в систему. */
export interface Sent {
  /** Уходит ли в систему. */
  readonly toSystem: boolean;
  /** Пролезает ли мимо «не беспокоить». */
  readonly bypass: boolean;
  readonly said: string;
}

/**
 * Отправить уведомление.
 *
 * `dnd` — включено ли «не беспокоить». Уведомление уходит **только** в систему;
 * своей всплывашки нет вовсе, поэтому и обхода нет.
 */
export function send(kind: Kind, detail: string, dnd: boolean): Sent {
  const decided = decide({ dnd, byPerson: false, kind: kind === "вопрос" ? "вопрос" : "успех" });
  const built = notice(kind, detail);

  if (dnd && !decided.notify) {
    return { toSystem: false, bypass: false, said: "«не беспокоить» включено: уведомление не отправляю, оно в окне и в трее" };
  }

  return {
    toSystem: true,
    bypass: false, // системное по определению не обходит системный режим.
    said: `отправлено в систему: «${built.title}» (${built.action})`,
  };
}

/**
 * Повтор.
 *
 * Не повторяем: уведомление об одном деле показывается один раз. Иначе через
 * минуту приходит второе, и это уже обход «не беспокоить» своими руками.
 */
export function repeat(count: number): { send: boolean; said: string } {
  if (count <= 1) return { send: true, said: "первое уведомление об этом деле" };
  return { send: false, said: "об этом уже сообщали: повтор — это обход «не беспокоить» своими руками" };
}

/**
 * Срочность.
 *
 * Срочно — только вопрос, на который ждём ответа. Всё остальное — нет, даже
 * ошибка: ошибка подождёт до открытия окна.
 */
export function urgent(kind: Kind): boolean {
  return notice(kind, "").urgent;
}

/**
 * Что проверяет тест.
 *
 * Три способа обхода и три ответа.
 */
export function cases(): { way: string; ok: boolean }[] {
  return [
    { way: "своя всплывашка", ok: false },
    { way: "ложная срочность", ok: false },
    { way: "повтор", ok: false },
  ];
}

/**
 * Что не делают уведомления.
 *
 * Три запрета — и все про «не пролезать».
 */
export function notDo(): string[] {
  return [
    "не показывают свою всплывашку в обход системы",
    "не ставят высокий приоритет тому, что не вопрос",
    "не повторяют: об одном деле — одно уведомление",
  ];
}
