/**
 * Всё, что дольше бюджета, помечается в отчёте как нарушение (шаг 124).
 *
 * Дефект. Замер есть (121), бюджет есть (123), а **нарушение не видно в отчёте**:
 *
 *  * **«слабый компьютер» списывает всё**: медленное дело объясняется железом, и
 *    никто не чинит; повторяющаяся задержка остаётся «характером»;
 *  * **нарушение — не событие**: оно не считается, не группируется и не попадает в
 *    итог, поэтому «стало лучше» недоказуемо;
 *  * **в отчёте только «готово»**: человек не видит, что дело шло 4 секунды при
 *    бюджете 1,5, — и не может связать жалобу с фактом;
 *  * **пометка не отличает нарушение от пропуска**: «звука не было» и «звук был
 *    поздно» — разные факты, и смешивать их значит терять и тот, и другой.
 *
 * Правило: **нарушение бюджета — строка в отчёте, а не сноска**.
 *
 *  1. **Помечается там, где видно дело**: рядом с делом, а не в отдельной диагностике.
 *  2. **Нарушение называется нарушением**: число, предел и что именно медленно.
 *  3. **Считается**: сколько дел нарушили, из скольких замеренных, — иначе «иногда
 *     медленно» не превращается в задачу.
 *  4. **Пропуск — не нарушение**: «звука не было» и «не замерено» не засчитываются
 *     ни в нарушения, ни в соблюдения.
 *  5. **Слабый компьютер — не оправдание**: масштаб меняет предел (123), но нарушение
 *     остаётся нарушением и **называется**.
 *
 * Почему не «предупреждение в консоли». Предупреждение в консоли не видит никто, а
 * жалоба «почему так долго» приходит к человеку за экраном.
 */

/** Дело с замером — то, что попадает в отчёт. */
export interface Deed {
  /** Что за дело — словами. */
  what: string;
  /** Сколько шло до первого звука, мс. `null` — не замеряли. */
  ms: number | null;
  /** Предел, который действовал для этого дела (с учётом масштаба машины). */
  limit: number;
}

/** Пометка для строки отчёта. */
export interface Mark {
  /** Нарушено ли. `null` — сказать нечего: замера нет. */
  broken: boolean | null;
  /** Что дописать к строке; пусто — ничего. */
  note: string;
}

/**
 * Пометить одно дело.
 *
 * `null` — не «в порядке»: без замера нет ни соблюдения, ни нарушения, и зелёная
 * галочка здесь была бы обещанием.
 */
export function mark(deed: Deed): Mark {
  if (deed.ms === null) {
    return { broken: null, note: "" };
  }
  if (deed.ms <= deed.limit) {
    return { broken: false, note: "" };
  }
  // Число, предел и слово «нарушение» — всё, что нужно, чтобы связать жалобу с фактом.
  return {
    broken: true,
    note: `нарушение бюджета: ${Math.round(deed.ms)} мс при пределе ${deed.limit}`,
  };
}

/** Строка отчёта с пометкой — дело и нарушение вместе. */
export function line(deed: Deed): string {
  const got = mark(deed);
  if (got.note === "") {
    return deed.ms === null ? `${deed.what} · не замерено` : `${deed.what}`;
  }
  return `${deed.what} · ${got.note}`;
}

/** Итог по делам: сколько нарушений и из скольких. */
export interface Total {
  broken: Deed[];
  measured: number;
  skipped: number;
  said: string;
}

/**
 * Итог.
 *
 * Пропуски **считаются отдельно** и не входят ни в нарушения, ни в замеренные: иначе
 * «0 нарушений из 0 замеренных» выглядело бы успехом.
 */
export function total(deeds: readonly Deed[]): Total {
  const broken = deeds.filter((deed) => mark(deed).broken === true);
  const measured = deeds.filter((deed) => deed.ms !== null).length;
  const skipped = deeds.length - measured;

  const parts: string[] = [];
  parts.push(measured === 0 ? "замеров нет" : `нарушений бюджета: ${broken.length} из ${measured}`);
  if (skipped > 0) parts.push(`не замерено: ${skipped}`);
  if (broken.length > 0) {
    // Самое медленное из нарушений — чтобы «медленно» было к чему приложить.
    const worst = broken.reduce((acc, deed) => ((deed.ms ?? 0) > (acc.ms ?? 0) ? deed : acc), broken[0]!);
    parts.push(`медленнее всего: ${worst.what} — ${Math.round(worst.ms ?? 0)} мс`);
  }

  return { broken, measured, skipped, said: parts.join(", ") };
}

/**
 * Нарушение — дефект.
 *
 * Отдельная функция, потому что искушение назвать его «особенностью машины» велико:
 * так задержка перестаёт быть задачей.
 */
export function defect(deed: Deed): boolean {
  return mark(deed).broken === true;
}

/** Что чинить в первую очередь: повторяющееся дело или разовое. */
export function repeated(deeds: readonly Deed[]): { what: string; times: number }[] {
  const counts = new Map<string, number>();
  for (const deed of deeds) {
    if (!defect(deed)) continue;
    counts.set(deed.what, (counts.get(deed.what) ?? 0) + 1);
  }
  return [...counts.entries()]
    .map(([what, times]) => ({ what, times }))
    .sort((left, right) => right.times - left.times);
}
