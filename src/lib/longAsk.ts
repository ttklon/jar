/**
 * Порог, после которого человеку говорится «это долго, ждать?» (шаг 129).
 *
 * Дефект. Долгое дело не спрашивает — оно **молча идёт**, и человек уходит:
 *
 *  * **нет точки выбора**: узнать «это надолго?» можно только после того, как
 *    дождался, — то есть ценой ожидания;
 *  * **порог на глазок**: «долго» — это 2 секунды или 20? Без числа решают все
 *    по-разному, и вопрос задаётся то слишком рано (мешает), то слишком поздно
 *    (человек уже ушёл);
 *  * **спрашивают не там**: «ждать?» после начала работы — это уже не выбор;
 *  * **одно «долго» на всё**: прочитать диск 8 секунд — нормально, а думать 8 секунд о
 *    фразе — нет; сравнение с самим собой необходимое, иначе порог неверен в обе
 *    стороны.
 *
 * Правило: **порог — число, и оно говорит «ждать?» до того, как ждать стало поздно**.
 *
 *  1. **Порог названо числом** (4 с) и основание у него человеческое — «дольше этого
 *     человек уже не считает, что просто работает».
 *  2. **Спрашивают заранее**: как только ожидание перевалило порог — сразу, а не в
 *     конце.
 *  3. **Спрашивают ровно один раз**: повторный вопрос — это не выбор, а пила.
 *  4. **У вопроса есть оба ответа**: «жду» продолжает, «нет» останавливает; вопрос без
 *     остановки — это уведомление.
 *  5. **Ожидание, которое человек сам попросил, не переспрашивает**: он уже выбрал.
 *
 * Почему не «просто показать прогресс». Прогресс говорит «идёт», но не даёт выбрать;
 * порог с вопросом даёт выбор тогда, когда он ещё что-то значит.
 */

/** Сколько ждать молча, мс. */
export const LONG_MS = 4000;

/** Что известно о текущем ожидании. */
export interface Wait {
  /** Кто ждёт: «думаю», «читаю диск». Словами — по ним и вопрос. */
  what: string;
  /** Сколько уже ждём, мс. */
  ms: number;
  /** Спросили ли уже (вопрос задаётся один раз). */
  asked: boolean;
  /** Человек сам попросил ждать — тогда не переспрашиваем. */
  chosen: boolean;
  /** Можно ли вообще остановить именно это дело. */
  stoppable: boolean;
}

/** Ответ на вопрос. */
export interface Ask {
  /** Задавать ли вопрос сейчас. */
  ask: boolean;
  /** Что спросить; пусто — спрашивать нечего. */
  said: string;
  /** Почему не спрашиваем — чтобы «молчание» было обосновано. */
  why: string;
}

/**
 * Задать вопрос или нет.
 *
 * Вопрос задаётся **до** того, как ждать стало поздно, и ровно один раз.
 */
export function ask(wait: Wait, thresholdMs = LONG_MS): Ask {
  if (wait.chosen) {
    // Человек уже выбрал ждать: переспрашивать значит не слушать ответ.
    return { ask: false, said: "", why: "человек сам попросил ждать — ответ уже есть" };
  }
  if (wait.asked) {
    // Повторный вопрос — пила, а не выбор.
    return { ask: false, said: "", why: "уже спросили один раз" };
  }
  if (wait.ms <= thresholdMs) {
    return { ask: false, said: "", why: `ещё не долго: ${Math.round(wait.ms)} мс из ${thresholdMs}` };
  }
  if (!wait.stoppable) {
    // Вопрос без возможности остановить — это уведомление, а не выбор.
    return { ask: false, said: "", why: "остановить это нельзя — вопрос был бы уведомлением" };
  }
  return {
    ask: true,
    said: `«${wait.what}» — это долго (${Math.round(wait.ms / 1000)} с). Ждать?`,
    why: "",
  };
}

/**
 * Ответ человека.
 *
 * `wait` — продолжать и больше не спрашивать; `stop` — остановить сейчас.
 */
export function answered(reply: "wait" | "stop"): { continue: boolean; said: string } {
  if (reply === "wait") {
    return { continue: true, said: "жду до конца — больше не спрошу" };
  }
  return { continue: false, said: "останавливаю: не буду ждать" };
}

/**
 * Порог для дела, которое заведомо длинное.
 *
 * Чтение диска 8 секунд — норма, а думать 8 секунд о фразе — нет. Поэтому у дела,
 * которое человек сам назвал долгим, свой порог — и он **назван**, а не спрятан.
 */
export function threshold(kind: "think" | "read" | "write" | "network"): { ms: number; said: string } {
  switch (kind) {
    case "think":
      // Думать о фразе дольше 4 с — уже «это долго».
      return { ms: LONG_MS, said: `поиск ответа дольше ${LONG_MS / 1000} с — это долго` };
    case "read":
      // Чтение диска бывает долгим по делу: порог выше, но он есть.
      return { ms: 10_000, said: `чтение дольше 10 с — это долго` };
    case "write":
      // Запись меняет данные: ждать её — норма, но не бесконечно.
      return { ms: 15_000, said: `запись дольше 15 с — это долго` };
    case "network":
      // Сеть: порог низкий, потому что сеть — самое частое место отказа.
      return { ms: 5000, said: `сеть дольше 5 с — это долго` };
  }
}

/**
 * Правда ли порог сработал вовремя.
 *
 * Если вопрос задан **после** того, как дело кончилось, — это не вопрос, а отчёт:
 * его надо называть как опоздание, а не как заботу.
 */
export function inTime(askedAt: number | null, finishedAt: number | null, startedAt: number): { ok: boolean; said: string } {
  if (askedAt === null) return { ok: false, said: "вопрос не задан — человек ждал молча" };
  if (finishedAt !== null && askedAt >= finishedAt) {
    return { ok: false, said: "вопрос задан после конца — это отчёт, а не выбор" };
  }
  return { ok: true, said: `вопрос через ${Math.round(askedAt - startedAt)} мс, до конца` };
}
