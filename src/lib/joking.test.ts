import { describe, expect, it } from "vitest";
import { canRun, check, confirmIsJoke, say, toneWeight } from "./joking";

/**
 * Шаг 94: опасное намерение распознавать даже в шутливой форме.
 *
 * «Снеси всё к чёртовой матери» — шутка, если человек в хорошем настроении, и не
 * шутка, если он это делает механически: приложение не слышит интонации.
 */
describe("опасное распознаётся в любой форме", () => {
  it("«снеси всё» — опасное действие", () => {
    const got = check("снеси всё");
    expect(got.found).toBe(true);
    expect(got.everything).toBe(true);
  });

  it("«снеси всё нафиг» — то же намерение, а не «не найдено»", () => {
    // Эмоциональные слова не отбрасываются как мусор: вместе с ними уходит и «снеси».
    const got = check("снеси всё нафиг");
    expect(got.found).toBe(true);
    expect(got.joke).toBe(true);
  });

  it("«в топку», «сожги», «форматни» — те же действия", () => {
    expect(check("в топку эту папку").found).toBe(true);
    expect(check("сожги старые логи").found).toBe(true);
    expect(check("отформатируй диск").found).toBe(true);
  });

  it("«почисти всё нафиг» — объём плюс эмоция = похоже на «снести всё»", () => {
    expect(check("почисти всё нафиг").found).toBe(true);
  });
});

describe("тон не влияет на исполнение", () => {
  it("шутка не запускается без подтверждения", () => {
    // Шутка не оправдывает, а настроение угадывать нельзя.
    expect(canRun(check("снеси всё нафиг"))).toBe(false);
    expect(canRun(check("снеси всё"))).toBe(false);
  });

  it("шутливое подтверждение — тоже подтверждение, а не новая шутка", () => {
    // Вопрос уже задан, и человек ответил.
    expect(confirmIsJoke("да, сноси всё нафиг")).toBe(false);
  });

  it("эмоции не взвешиваются: оценка настроения — это угадывание", () => {
    expect(toneWeight("снеси всё нафиг")).toBe(0);
    expect(toneWeight("снеси всё")).toBe(0);
  });
});

describe("сказано, что понято и сколько", () => {
  it("шутка понята как шутка, а цена названа", () => {
    const said = say(check("снеси всё нафиг"), 100);
    expect(said).toContain("Даже если это шутка");
    expect(said).toContain("стереть можно один раз");
  });

  it("объём «всё» назван словом «всё», а не числом", () => {
    expect(say(check("снеси всё"), 300)).toContain("всё");
  });

  it("серьёзная форма — без морали, но с ценой", () => {
    const said = say(check("сожги логи"), 12);
    expect(said).toContain("12");
    expect(said).toContain("необратимо");
  });
});

describe("где опасности нет", () => {
  it("«найди большие файлы» — не опасное намерение", () => {
    expect(check("найди большие файлы").found).toBe(false);
    expect(canRun(check("найди большие файлы"))).toBe(true);
  });

  it("«всё» без опасного действия — ещё не приказ", () => {
    // «Покажи все файлы» — это чтение, а не снос.
    expect(check("покажи все файлы").found).toBe(false);
    expect(check("покажи все файлы").why).toContain("ещё не приказ");
  });

  it("пустая фраза — не опасна", () => {
    expect(check("").found).toBe(false);
  });
});
