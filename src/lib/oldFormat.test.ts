import { describe, expect, it } from "vitest";
import { READABLE, canRead, classify, coverage, parse, promise, report } from "./oldFormat";

/**
 * Шаг 320: тест — старый формат данных читается после обновления.
 *
 * Человек мог не запускать программу год: его файл — «старый формат», а не «испорченный».
 */

describe("разбор строки: понимаем старое и не теряем незнакомое", () => {
  it("новый вид: «вид: значение — откуда»", () => {
    expect(classify("файл: отчёт — сказал сам")).toBe("fact");
  });

  it("вид с двоеточием понимается и без тире с происхождением", () => {
    // Без этого правила такая строка попала бы в fact только по « — ».
    expect(classify("голос: потише пожалуйста")).toBe("fact");
  });

  it("старый вид без вида тоже понимаем", () => {
    expect(classify("отчёт лежит на рабочем столе — сказал сам")).toBe("fact");
  });

  it("шапка-цитата и комментарии — не факты", () => {
    expect(classify("> Память: одна строка на факт")).toBe("header");
    expect(classify("# собрано программой")).toBe("header");
  });

  it("незнакомое — unknown, а не мусор", () => {
    expect(classify("<xml>что-то из старой версии</xml>")).toBe("unknown");
  });
});

describe("прочитать файл целиком", () => {
  const old = [
    "# память версии 1",
    "",
    "отчёт лежит на рабочем столе — сказал сам",
    "голос: потише — сказал сам",
    "<сохранено старой версией>",
  ].join("\n");

  it("факты прочитаны, незнакомое сохранено", () => {
    const got = parse(old, 1);
    expect(got.facts.length).toBe(2);
    expect(got.unknown).toEqual(["<сохранено старой версией>"]);
  });

  it("незнакомые строки не выбрасываются: файл принадлежит человеку", () => {
    const got = parse(old, 1);
    expect(report(got)).toContain("оставил как есть");
  });

  it("файл есть, но не наш формат — это важный факт, а не молчание", () => {
    const got = parse("<xml>a</xml>\n<xml>b</xml>", 1);
    expect(report(got)).toContain("покажите файл нам");
  });

  it("пустой файл — тоже ответ", () => {
    expect(report(parse("", 1))).toBe("файл пуст");
  });

  it("всё понял — короткий отчёт", () => {
    expect(report(parse("голос: тихо — сказал сам", 3))).toBe("прочитано 1 фактов, схема 3");
  });
});

describe("обещание про старые форматы", () => {
  it("старые схемы читаются", () => {
    expect(canRead(1, 3)).toBe(true);
    expect(canRead(3, 3)).toBe(true);
  });

  it("обещание узкое: читаются, а не «работают как новые»", () => {
    const got = promise();
    expect(got).toContain("читаются");
    expect(got).toContain("не молча");
  });

  it("каждый обещанный формат имеет файл для теста", () => {
    expect(coverage(READABLE)).toEqual([]);
  });

  it("пропущенный формат — непроверенное обещание", () => {
    expect(coverage([1, 3]).join()).toContain("схема 2 обещана, но файла для теста нет");
  });
});
