/**
 * Шаг 308: инструкция «если не запускается» — три шага и диагностика.
 *
 * Плохая инструкция выглядит так: «проверьте, что у вас 64-разрядная Windows,
 * установлен WebView2, обновлены драйверы, нет антивируса…». Человек, у которого
 * не запускается, читает это и закрывает страницу: он не знает, что из этого —
 * его случай, и проверять всё подряд дольше, чем написать в поддержку.
 *
 * Хорошая инструкция — **три шага, каждый заканчивается фактом**, и на каждом
 * шаге видно, помогло или нет:
 *
 *  1. **посмотреть журнал первого запуска** — там последняя проверка, и она почти
 *     всегда называет причину;
 *  2. **запустить с диагностикой** — одна кнопка (или ключ), которая собирает
 *     отчёт: версия Windows, WebView2, папка данных, последние ошибки;
 *  3. **прислать отчёт** — одна кнопка, которая открывает папку, а не просит
 *     «найдите файлы в AppData».
 *
 * Правила: шагов ровно три; у каждого — **что увидеть**, а не «что попробовать»;
 * третий шаг никогда не «переустановите».
 */

/** Шаг инструкции. */
export interface HelpStep {
  readonly order: number;
  /** Что сделать. */
  readonly do: string;
  /** Что должно быть видно — иначе шаг не проверяем. */
  readonly see: string;
}

/** Ровно три шага, и это число не случайное: больше не дочитывают. */
export const STEPS: readonly HelpStep[] = [
  {
    order: 1,
    do: "откройте журнал первого запуска: «Пуск → ZShelper → Журнал первого запуска»",
    see: "последняя строка с пометкой «ошибка» — это и есть причина, обычно про WebView2 или место на диске",
  },
  {
    order: 2,
    do: "запустите «ZShelper с диагностикой» из той же папки в меню «Пуск»",
    see: "откроется папка с отчётом, там три строки: Windows, пользователь, запуск",
  },
  {
    order: 3,
    do: "нажмите «Прислать отчёт» в окне с ошибкой",
    see: "откроется письмо с уже приложенным отчётом — писать ничего не нужно",
  },
];

/**
 * Проверка инструкции.
 *
 * Ловит три вещи, которые делают инструкцию бесполезной: шагов больше трёх,
 * шаг без «что увидеть», и совет переустановить.
 */
export function audit(steps: readonly HelpStep[] = STEPS): string[] {
  const problems: string[] = [];

  if (steps.length !== 3) problems.push(`шагов ${steps.length}, а должно быть три: дальше не дочитывают`);

  for (const step of steps) {
    if (step.see.trim().length < 15) problems.push(`шаг ${step.order}: не сказано, что человек должен увидеть`);
    if (/переустан|снести|удалить и поставить/i.test(step.do)) {
      problems.push(`шаг ${step.order}: «переустановите» стирает следы, по которым ищут причину`);
    }
    if (/попробуйте|возможно|в некоторых случаях/i.test(step.do)) {
      problems.push(`шаг ${step.order}: «попробуйте» — не шаг; нужен факт`);
    }
  }

  const orders = steps.map((step) => step.order);
  if (new Set(orders).size !== orders.length) problems.push("два шага с одним номером");

  return problems;
}

/**
 * Первый ответ на «не запускается».
 *
 * Одна фраза, которая ведёт к журналу, а не к списку причин. Человек в этот
 * момент раздражён, и ему нужно одно действие.
 */
export function firstAnswer(known: string | null): string {
  if (known) return `похоже, причина вот в этом: ${known}. Вот что делать — ${oneStep(known)}`;
  return "откройте журнал первого запуска (меню «Пуск», папка ZShelper): последняя строка с ошибкой называет причину";
}

/**
 * Шаг под известную причину.
 *
 * Узнаём по словам, которые пишет журнал, а не по кодам: коды человеку ничего
 * не говорят.
 */
export function oneStep(problem: string): string {
  const text = problem.toLowerCase();
  if (text.includes("webview")) return "поставить WebView2 с сайта Microsoft: одна кнопка, без перезагрузки";
  if (text.includes("места") || text.includes("диск")) return "освободить 10 ГБ или перенести папку моделей на другой диск";
  if (text.includes("разряд")) return "нужна 64-разрядная Windows: на 32-разрядной помощник не запустится";
  return "прислать отчёт: в нём причина будет названа точнее";
}

/**
 * Чего инструкция не делает.
 *
 * Отдельным списком, потому что именно этих советов ждут: «отключите
 * антивирус», «запустите от администратора», «почистите реестр». Каждый из них
 * маскирует причину, и все три мы не советуем.
 */
export function notAdvise(): string[] {
  return [
    "отключить антивирус — маскирует причину и оставляет человека без защиты",
    "запустить от имени администратора — установка и так ставится без прав",
    "переустановить — стирает следы, по которым ищут причину",
  ];
}

/** Отчёт, который собирает кнопка: то же, что человек видел бы глазами. */
export function diagnosis(base: { windows: string; webView2: boolean; user: string }, lastError: string | null): string {
  return [
    `Windows: ${base.windows}`,
    `WebView2: ${base.webView2 ? "есть" : "нет"}`,
    `пользователь: ${base.user}`,
    `последняя ошибка: ${lastError ?? "нет записей — значит, программа не дошла до журнала"}`,
  ].join("\n");
}
