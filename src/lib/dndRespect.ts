/**
 * Шаг 445: уважать «не беспокоить» системы.
 *
 * «Не беспокоить» (Focus Assist) — единственный переключатель, которому человек
 * верит: включил — и никто не лезет. Приложение, которое его обходит, теряет
 * доверие один раз и навсегда.
 *
 * Что это значит на практике:
 *
 *  * **уведомления не показываются** — и не заменяются своей всплывашкой (нет
 *    своей всплывашки, шаг 442);
 *  * **горячие клавиши работают**: это не уведомление, а просьба человека;
 *  * **дела по расписанию — без уведомлений, но идут**, если безопасны
 *    (иначе «на паузе всё» человек включил бы паузу, а не DND);
 *  * **вопрос остаётся вопросом** — он в трее, и дело стоит. Но не всплывает.
 *
 * И одно исключение, которое надо назвать: **«Не беспокоить» не блокирует второе
 * приложение**. Если человек нажал у нас «выполнить», это его действие, а не
 * уведомление.
 */

/** Что известно. */
export interface Mode {
  /** Системное «не беспокоить». */
  readonly dnd: boolean;
  /** Нажал ли человек сам. */
  readonly byPerson: boolean;
  /** Что показываем. */
  readonly kind: "успех" | "ошибка" | "вопрос" | "расписание";
}

/** Решение. */
export interface Decision {
  /** Показать ли системное уведомление. */
  readonly notify: boolean;
  /** Выполнить ли дело. */
  readonly run: boolean;
  readonly said: string;
}

/**
 * Решить.
 *
 * DND выключает только **уведомления**. Дела идут, вопросы остаются вопросами —
 * и всё это видно в трее и в окне.
 */
export function decide(mode: Mode): Decision {
  if (!mode.dnd) {
    return { notify: true, run: true, said: "«не беспокоить» выключено: работаю как обычно" };
  }

  if (mode.byPerson) {
    return { notify: false, run: true, said: "вы попросили сами: выполняю молча, уведомление не показываю — вы уже знаете" };
  }

  if (mode.kind === "вопрос") {
    return { notify: false, run: false, said: "вопрос не показываю, но он в трее: дело стоит и ждёт вашего ответа" };
  }

  if (mode.kind === "расписание") {
    return { notify: true, run: true, said: "расписание сработает, но уведомление покажу: «не беспокоить» выключит именно его, а не дело" };
  }

  return { notify: false, run: true, said: "дело выполнится молча: о результате скажу в трее и в окне" };
}

/**
 * Что видно, пока DND включено.
 *
 * Не «ничего»: состояние в трее — не уведомление, и оно не мешает.
 */
export function visibleWhileDnd(): string[] {
  return ["состояние в трее: идёт, ждёт, на паузе", "всё в открытом окне", "результат — когда человек откроет окно"];
}

/**
 * Чего «не беспокоить» не выключает.
 *
 * Три вещи, и все — не уведомления.
 */
export function keepsRunning(): string[] {
  return ["дела, которые человек запустил сам", "дела по расписанию: они идут, а уведомления молчат", "горячие клавиши: это просьба, а не шум"];
}

/**
 * Что нельзя делать при DND.
 *
 * Три обхода, каждый из которых ломает доверие.
 */
export function notDo(): string[] {
  return [
    "не заменять системное уведомление своей всплывашкой: это обход «не беспокоить»",
    "не ставить «срочность», чтобы пробить режим: срочным его назначаем мы, а не человек",
    "не молчать о вопросах до бесконечности: вопрос виден в трее, и дело ждёт",
  ];
}
