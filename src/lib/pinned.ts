/**
 * Скачивание только с закреплённого адреса и с проверкой хеша (шаг 72).
 *
 * Здесь не новый механизм, а **общее правило** для уже работающего.
 *
 * Дефект. Каждый файл — модель, движок, голосовой движок — скачивался
 * «примерно одинаково», и правила жили в разных местах: где-то адрес брался из
 * ответа сервера, где-то хеш проверялся не всегда. Появлялся **новый файл** — и
 * правило приходилось вспоминать заново, а чаще не вспоминалось.
 *
 * Правило: **что не закреплено, то не скачивается**.
 *
 *  1. Адрес **закреплён при сборке**: ни редирект, ни «последняя версия», ни
 *     ответ сервера не могут его изменить. «Последняя версия» — это способ
 *     получить другой файл, чем проверяли.
 *  2. Хеш **обязателен** и сверяется **после скачивания, до запуска**. Хеш,
 *     которого нет, — это не «проверка не удалась», а **отказ**: файл без
 *     закреплённого хеша нельзя проверить в принципе.
 *  3. Скачанное кладётся **во временное имя** (`.part`) и переименовывается
 *     только после проверки: иначе недокачанный или подменённый файл может
 *     оказаться на месте настоящего, и следующая проверка его уже не отличит.
 *  4. Отказ называет **что именно** не так: адрес, хеш или размер, — иначе
 *     человек ищет поломку у себя.
 *
 * Почему не «доверяем сайту модели». Сайт — не наша часть: его могут взломать,
 * файл — заменить. Закреплённый хеш — это единственное, что не зависит от
 * сайта, и без него проверка сводится к доверию.
 */

/** Что известно о файле, который собираемся скачать. */
export interface Pinned {
  /** Адрес, закреплённый при сборке. */
  url: string;
  /** Ожидаемый sha256, закреплённый при сборке. */
  sha256: string;
  /** Ожидаемый размер в байтах; 0 — размер неизвестен. */
  bytes: number;
}

/** Почему скачать нельзя. */
export type Refusal =
  | { ok: false; why: string }
  | { ok: true; url: string; sha256: string };

/**
 * Проверка **до** скачивания.
 *
 * Адрес обязан быть `https`: по `http` файл можно подменить по дороге, и
 * проверка хеша тогда скажет «файл не тот» уже после загрузки.
 *
 * Редиректы **запрещены**: закреплённый адрес — это адрес, а не «куда он
 * приведёт». Редирект — законный способ отдать другой файл.
 */
export function allow(file: Pinned): Refusal {
  if (!/^https:\/\//i.test(file.url)) {
    return { ok: false, why: `адрес «${file.url}» не https — файл могут подменить по дороге` };
  }
  if (file.sha256.trim().length === 0) {
    // Файл без хеша нельзя проверить в принципе — это отказ, а не «не удалось».
    return { ok: false, why: "у файла нет закреплённого хеша — проверить его нечем, скачивать нельзя" };
  }
  if (!/^[0-9a-f]{64}$/i.test(file.sha256.trim())) {
    return { ok: false, why: "хеш не похож на sha256 — это не проверка, а её видимость" };
  }
  if (file.bytes < 0) {
    return { ok: false, why: "отрицательный размер — так не бывает" };
  }
  return { ok: true, url: file.url, sha256: file.sha256.trim().toLowerCase() };
}

/**
 * Проверка **после** скачивания.
 *
 * Размер проверяется первым: он ловит недокачанный файл дёшево, до чтения
 * четырёх гигабайт. Хеш — потом, он ловит подмену.
 */
export function check(
  file: Pinned,
  got: { bytes: number; sha256: string },
): { ok: true } | { ok: false; why: string } {
  if (file.bytes > 0 && got.bytes !== file.bytes) {
    return {
      ok: false,
      why: `размер не тот: ожидали ${file.bytes} байт, получили ${got.bytes} — файл недокачан или подменён`,
    };
  }
  if (got.sha256.trim().toLowerCase() !== file.sha256.trim().toLowerCase()) {
    return { ok: false, why: "хеш не совпал — файл повреждён или подменён, скачайте заново" };
  }
  return { ok: true };
}

/**
 * Где лежит скачанное, пока не проверено.
 *
 * `.part` — не украшение: файл с этим именем **не запускается ни при каких
 * условиях**. Без него недокачанный файл занимает место настоящего, и
 * следующая проверка его уже не отличит.
 */
export function partial(path: string): string {
  return `${path}.part`;
}

/** Можно ли запускать файл по его имени: только окончательное. */
export function runnable(path: string): boolean {
  return !path.endsWith(".part");
}

/**
 * Что сказать человеку при отказе.
 *
 * Названо **что именно** не так: адрес, хеш или размер. «Ошибка загрузки»
 * заставляет искать поломку у себя.
 */
export function say(refusal: { why: string }): string {
  return `не скачиваю: ${refusal.why}`;
}

/**
 * Что сказать, когда всё в порядке.
 *
 * Сказано, **что проверили**: человек должен знать, что проверка была, иначе
 * она ничем не отличается от её отсутствия.
 */
export function ok(file: Pinned): string {
  const gb = file.bytes > 0 ? `, ${Math.round((file.bytes / 1e9) * 10) / 10} ГБ` : "";
  return `скачано с закреплённого адреса, хеш совпал${gb}`;
}
