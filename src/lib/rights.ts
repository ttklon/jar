/**
 * Один список прав: что приложение делает и чего не делает никогда (шаг 161).
 *
 * Дефект. Правила были — и верные, — но **разбросаны**: `policy.ts` знал про
 * «деньги и учётные данные — только человек», реестр знал про 11 действий со
 * статусом `never` («купить билет», «оплатить счёт», «подписать документ»),
 * а `refusal.ts` знал, как назвать отказ. Человек, спросивший «что ты вообще
 * можешь и чего не сделаешь ни за что», получал ответ по частям — и по частям
 * же проверял.
 *
 * Правила этого списка:
 *
 *  1. **список собран из данных, а не написан отдельно.** «Никогда» — это
 *     `status: never` в реестре; второй перечень обещаний, который можно
 *     забыть обновить, был бы второй правдой;
 *  2. **каждое «никогда» называет, что вместо.** «Не покупаю билеты» без «а что
 *     тогда» — это стена, а не помощник: человеку нужно знать, что навигатор до
 *     оплаты доведёт, а платить он будет сам;
 *  3. **«денег не двигает» — отдельным правилом, а не следствием.** Это самое
 *     частое опасение, и оно должно читаться одной строкой, а не выводиться из
 *     таблицы рисков;
 *  4. **умеет — значит названо числом.** «Я много чего умею» не проверяется;
 *     «626 действий готовы, 198 в работе» — проверяется;
 *  5. **правда, а не обещание.** Список не говорит, чего приложение «не будет
 *     делать в будущем»: он говорит, чего оно не делает **сейчас**. Иначе это
 *     не список прав, а реклама.
 *
 * Модуль ничего не выполняет и ничего не запрещает — решение принимает ядро
 * (`policy.rs`). Здесь только собирается то, что уже решено, в одно место.
 */

/** Риск действия — как в реестре. */
export type Risk = "read" | "write-local" | "external" | "destructive" | "identity" | "money";

/** Статус: готово, в работе (`v2`/`later`) или не делаем никогда. */
export type Status = "v1" | "v2" | "later" | "never";

/** Одно действие реестра — только то, что нужно списку. */
export interface Row {
  id: string;
  verb: string;
  object: string;
  risk: Risk;
  status: Status;
  /** Заметка реестра: почему «никогда» или как это делается. */
  notes?: string;
}

/** Одно «никогда» с ответом «а что вместо». */
export interface Never {
  /** Что не делаем — словами действия. */
  what: string;
  /** Почему не делаем. */
  why: string;
  /** Что вместо: как довести дело до человека. */
  instead: string;
}

/**
 * Чем заменяется «никогда» — по риску.
 *
 * Замена выводится из риска, а не пишется у каждого действия: иначе одиннадцать
 * строк однажды сказали бы одиннадцать разных вещей об одном и том же правиле.
 */
const INSTEAD: Readonly<Record<Risk, string>> = {
  money: "доведу до оплаты и покажу сумму — платить будете вы, сами",
  identity: "подготовлю и покажу — войти или подписать может только человек",
  external: "покажу, что будет отправлено, и кому — отправите вы",
  destructive: "покажу, что удалится, и положу в корзину — решать вам",
  "write-local": "подготовлю файл и покажу — сохранить решите вы",
  read: "прочитаю и покажу — решения за вами",
};

/** Как назвать «никогда» по риску, когда заметки в реестре нет. */
const WHY: Readonly<Record<Risk, string>> = {
  money: "деньги двигает только человек",
  identity: "учётные данные и подпись — только человек",
  external: "наружу уходит по слову человека, а не по решению машины",
  destructive: "необратимое не делаем без слова человека",
  "write-local": "запись решает человек",
  read: "не читаем то, о чём не просили",
};

/**
 * Собрать «никогда» из реестра.
 *
 * `rows` — весь реестр: фильтр по статусу здесь, чтобы вызывающий не мог забыть
 * его и показать «никогда» для всего подряд.
 */
export function neverDones(rows: readonly Row[]): Never[] {
  return rows
    .filter((row) => row.status === "never")
    .map((row) => ({
      what: `${row.verb} ${row.object}`.trim(),
      // Заметка реестра — причина оттуда, где решали; шаблон — только если её нет.
      why: (row.notes ?? "").trim() || WHY[row.risk],
      instead: INSTEAD[row.risk],
    }));
}

/** Сколько чего есть: числом, а не «много». */
export interface Tally {
  ready: number;
  planned: number;
  never: number;
  total: number;
}

export function tally(rows: readonly Row[]): Tally {
  let ready = 0;
  let planned = 0;
  let never = 0;
  for (const row of rows) {
    if (row.status === "v1") ready += 1;
    else if (row.status === "v2" || row.status === "later") planned += 1;
    else never += 1;
  }
  return { ready, planned, never, total: rows.length };
}

/** Строка счёта: «готово 626, в работе 198, не делаем никогда 11». */
export function countWords(got: Tally): string {
  return `готово ${got.ready}, в работе ${got.planned}, не делаем никогда ${got.never}`;
}

/**
 * Правила «никогда», которые не про одно действие, а про все.
 *
 * Они и раньше были в коде — в `policy.ts` и в отказе; здесь они названы так,
 * чтобы человек мог прочитать их в одном месте и проверить.
 */
export interface Rule {
  /** Что не делаем. */
  what: string;
  /** Чем это видно: не обещание, а место, где правило срабатывает. */
  proof: string;
}

export const RULES: readonly Rule[] = [
  {
    what: "не двигаю деньги: не плачу, не покупаю, не списываю",
    proof: "риск money в реестре — отказ политики, а не подтверждение",
  },
  {
    what: "не вхожу в учётные записи и не подписываю документы за человека",
    proof: "риск identity — отказ политики",
  },
  {
    what: "не отправляю ничего наружу без слова человека",
    proof: "риск external — подтверждение, и адрес назван до отправки",
  },
  {
    what: "не удаляю без слова человека и в корзину, а не мимо неё",
    proof: "риск destructive — подтверждение и корзина",
  },
  {
    what: "не выхожу за выбранные папки",
    proof: "пути проверяются до запуска, а не после",
  },
  {
    what: "не работаю без сети иначе как локально: пропала сеть — локальное работает",
    proof: "сеть есть только в загрузке модели; остальное не ходит наружу",
  },
];

/** Список целиком — то, что показывается и проверяется. */
export interface Sheet {
  tally: Tally;
  count: string;
  rules: readonly Rule[];
  never: Never[];
}

export function sheet(rows: readonly Row[]): Sheet {
  const got = tally(rows);
  return {
    tally: got,
    count: countWords(got),
    rules: RULES,
    never: neverDones(rows),
  };
}

/**
 * Проверить, что список не разошёлся с реестром.
 *
 * `left` — то, что показано человеку; `right` — реестр. Список прав, который
 * отстал от данных, хуже отсутствия списка: он обещает не то, что происходит.
 * Возвращает тексты расхождений; пусто — сходится.
 */
export function drift(shown: readonly string[], rows: readonly Row[]): string[] {
  const out: string[] = [];
  const real = neverDones(rows).map((item) => item.what);
  for (const what of real) {
    if (!shown.includes(what)) out.push(`в списке нет: ${what}`);
  }
  for (const what of shown) {
    if (!real.includes(what)) out.push(`в списке лишнее: ${what}`);
  }
  return out;
}
