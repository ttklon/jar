/**
 * Отказ по-русски и коротко (шаг 87).
 *
 * Дефект. Когда приложение не может — оно молчит или говорит технически:
 *
 *  * **молчит**: «ничего не произошло» — и человек не знает, поняли ли его
 *    вообще. Молчание неотличимо от поломки;
 *  * **говорит кодом**: `policy_denied: destructive`, «нет прав на действие»,
 *    «операция невозможна» — это слова из мира, где человек не живёт;
 *  * **обвиняет молчанием**: отказ без причины читается как каприз. Человек
 *    пробует снова, потому что думает, что не поняли, — и получает то же.
 *
 * Правило: **отказ называет, чего не хватает**.
 *
 *  1. **Что**: «не умею» или «нельзя» — это разные вещи. «Не умею: нет руки» —
 *     функция не сделана; «нельзя: деньги» — не разрешено. Смешать их значит
 *     свалить недоделку на запрет.
 *  2. **Чего не хватает** — одной короткой причиной: «нет руки», «деньги»,
 *     «нет сети», «не нашёл файл».
 *  3. **Что можно сделать** — или прямо сказано, что нельзя ничего. Без этого
 *     отказ — тупик.
 *  4. **Одно предложение**, а не абзац: отказ читают тогда, когда хотят, чтобы
 *     что-то произошло, и абзац не читают вовсе.
 *
 * Почему не «показать техническую причину». Техническая причина нужна
 * разработчику, а не человеку; человеку нужен ответ на «что теперь делать». Обе
 * могут быть рядом, но **первой** — человеческая.
 */

/** Почему не вышло. */
export type Cause =
  /** Функция не сделана: у приложения нет такой возможности. */
  | "нет-руки"
  /** Не разрешено правилом: деньги, личные данные, опасное действие. */
  | "деньги"
  | "личное"
  | "опасное"
  /** Не хватает условий: сети, прав, места. */
  | "нет-сети"
  | "нет-доступа"
  | "нет-места"
  /** Не нашлось: файла, приложения, программы. */
  | "не-нашлось"
  /** Не понял фразу — это тоже отказ, и он честный. */
  | "не-понял"
  /** Не знаю — и это надо сказать, а не молчать. */
  | "не-знаю";

/** Что это: недоделка или запрет. */
export function kind(cause: Cause): "не-умею" | "нельзя" | "не-вышло" | "не-понял" {
  switch (cause) {
    case "нет-руки":
      return "не-умею";
    case "деньги":
    case "личное":
    case "опасное":
      return "нельзя";
    case "не-понял":
      return "не-понял";
    default:
      return "не-вышло";
  }
}

/**
 * Отказ короткой строкой.
 *
 * «Не умею» и «нельзя» **разные**: свалить недоделку на запрет — это ложь, из-за
 * которой человек перестаёт просить о том, что просить можно.
 */
export function say(cause: Cause, what = ""): string {
  const subject = what.trim() === "" ? "" : ` ${what.trim()}`;
  switch (cause) {
    case "нет-руки":
      return `не умею${subject}: такой возможности пока нет — это не запрет, а недоделка`;
    case "деньги":
      return `нельзя${subject}: это тратит деньги`;
    case "личное":
      return `нельзя${subject}: это личные данные`;
    case "опасное":
      return `нельзя${subject}: это опасно и не отменяется`;
    case "нет-сети":
      return `не вышло${subject}: нет сети`;
    case "нет-доступа":
      return `не вышло${subject}: нет доступа — проверьте права`;
    case "нет-места":
      return `не вышло${subject}: не хватает места`;
    case "не-нашлось":
      return `не нашлось${subject}: такого нет — проверьте название`;
    case "не-понял":
      return "не понял фразу: скажите проще или иначе — я не угадываю";
    case "не-знаю":
      return `не знаю, что с${subject === "" ? " этим" : subject} — не буду делать наугад`;
  }
}

/**
 * Что теперь делать — или прямо «ничего».
 *
 * Без этого отказ — тупик: человек остаётся с «нельзя» и без выхода.
 */
export function next(cause: Cause): string {
  switch (cause) {
    case "нет-руки":
      return "можно упростить просьбу — назовите, что именно нужно, и я скажу, что из этого умею";
    case "деньги":
      return "если нужно — скажите явно, и я спрошу подтверждение";
    case "личное":
      return "скажите, что именно можно прочитать, и я переспрошу";
    case "опасное":
      return "такое я не делаю ни по какой просьбе";
    case "нет-сети":
      return "попробуйте ещё раз, когда сеть появится";
    case "нет-доступа":
      return "проверьте права в настройках системы";
    case "нет-места":
      return "освободите место или укажите другой диск";
    case "не-нашлось":
      return "проверьте название — или скажите иначе";
    case "не-понял":
      return "пример: «найди большие файлы в загрузках»";
    case "не-знаю":
      return "уточните, что сделать, — или выберите из списка действий";
  }
}

/**
 * Отказ целиком: причина и выход — одно предложение с точкой.
 *
 * Одно предложение, потому что отказ читают, когда хотят, чтобы что-то
 * произошло, и абзац не читают.
 */
export function line(cause: Cause, what = ""): string {
  return `${say(cause, what)}. ${next(cause)}`;
}

/**
 * Техническая причина — отдельно и второй.
 *
 * Нужна тому, кто пишет в поддержку; человеку нужна первая. Порядок назван,
 * чтобы при правках не поменять местами.
 */
export function technical(detail: string): string {
  return `подробности для поддержки: ${detail}`;
}

/**
 * Проверка: отказ не должен быть пустым.
 *
 * Пустой отказ — это молчание с другим именем.
 */
export function usable(text: string): boolean {
  return text.trim().length > 0;
}

/**
 * Причина журнала (шаг 37) — в отказ.
 *
 * Журнал группирует причины по-своему («нет сети», «не хватает прав»), а отказ
 * говорит по-человечески. Мост нужен, чтобы на экране не было двух разных
 * языков об одном и том же. Неизвестная причина — «не-знаю»: она честно названа,
 * а не выдана за понятную.
 */
export function fromJournal(reason: string): Cause {
  const text = reason.toLowerCase();
  if (/сет/.test(text)) return "нет-сети";
  if (/прав|доступ/.test(text)) return "нет-доступа";
  if (/места/.test(text)) return "нет-места";
  if (/занят/.test(text)) return "нет-доступа";
  return "не-знаю";
}
