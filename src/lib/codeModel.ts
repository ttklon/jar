/**
 * Модель для кода — отдельно, включается только на задачах кода (шаг 77).
 *
 * Дефект. Модель для кода — самая большая, что есть (шаг 63): 7B и больше.
 * И если она загружена «на всякий случай», происходит вот что:
 *
 *  * **память занята** моделью, которая нужна раз в день, а не каждый час;
 *  * **разговор идёт через неё же** — потому что лень переключать, — и каждая
 *    фраза ждётся втрое дольше (шаг 65: это то, что человек считает
 *    «приложение тормозит»);
 *  * **путаница в ответе**: большая модель на «как дела» отвечает длинно и
 *    технически, и разговор становится странным.
 *
 * Правило: **код — отдельная модель, и она загружается только на код**.
 *
 *  1. Решение «это код?» принимается **дешёвой моделью** (шаг 66) или руками,
 *     но не большой: большая не должна просыпаться, чтобы понять, нужна ли она.
 *  2. Пока код не нужен, **кодовая модель не в памяти** — она лежит файлом и
 *     никому не мешает.
 *  3. Если кодовая модель **не влезает**, разговор продолжает работать, а код
 *     честно не работает: «нечем» лучше, чем «сделаю вид и напишу неверное»
 *     (шаг 62).
 *  4. Сказано, **какая модель сейчас отвечает**: иначе разная длина ответов
 *     выглядит как нестабильность.
 *
 * Почему не «всегда самая большая». Сильная модель на простой фразе тратит
 * секунды и даёт лишнее; человек судит по первому ответу, а первый ответ —
 * самый простой.
 */

/** Что человек просит: код или разговор. */
export type Task = "code" | "talk";

/**
 * Явные признаки задачи кода.
 *
 * Список **короткий и честный**: код просят словами «напиши», «исправь»,
 * «почему падает», «функция», «скрипт». Расширять его бессмысленно: «сделай
 * скрипт» и «напиши письмо» отличаются одним словом, и никакой список не
 * покроет все случаи — потому есть ручное переключение.
 */
const CODE_WORDS =
  /(?:^|\s)(код|функци|скрипт|программ|баг|ошибк в коде|компил|парсинг|алгоритм|запрос к базе|sql|регулярк|regex|рефактор|тест[ыа]? )(?=\s|$)/i;

const CODE_VERBS = /(?:^|\s)(напиши|исправь|отлади|допиши|отрефактор|почему падает)/i;

/**
 * Это задача кода?
 *
 * `false` — «не знаю», а не «точно разговор»: сомнительное уходит в ручное
 * переключение, а не в догадку.
 */
export function isCode(text: string): boolean {
  const clean = text.trim();
  if (clean.length === 0) return false;
  return CODE_WORDS.test(clean) || (CODE_VERBS.test(clean) && /код|функци|скрипт|программ|баг/i.test(clean));
}

/**
 * Какую модель брать.
 *
 * `null` — кодовой модели нет вовсе (не скачана или не влезает). Тогда код
 * **не работает**, и это сказано: «сделаю вид и напишу неверное» хуже.
 */
export interface Pick {
  /** Какую модель брать или `null`. */
  model: string | null;
  /** Почему именно её — или почему кода нет. */
  why: string;
}

/**
 * Выбор модели для задачи.
 *
 * `chat` — обычная модель; `code` — кодовая, если есть. Пока задача не код,
 * кодовая **не грузится**.
 */
export function pick(task: Task, chat: string, code: string | null): Pick {
  if (task === "talk") {
    return { model: chat, why: "разговор: обычная модель, кодовая не нужна и не грузится" };
  }
  if (code === null) {
    return {
      model: null,
      why: "модели для кода нет — она больше разговорной и не влезает; разговор при этом работает",
    };
  }
  return { model: code, why: "код: отдельная модель, ошибка дороже секунды" };
}

/**
 * Нужно ли грузить кодовую модель сейчас.
 *
 * Выгрузка при уходе с кода (шаг 74): модель на 7B не должна занимать память
 * весь день ради одной задачи.
 */
export function load(code: string | null, task: Task, loaded: boolean): boolean {
  return code !== null && task === "code" && !loaded;
}

/**
 * Что сказать человеку.
 *
 * Названа **какая модель отвечает и почему**: иначе разная длина и скорость
 * ответов выглядит как нестабильность.
 */
export function say(pick_: Pick): string {
  return pick_.model === null
    ? pick_.why
    : `отвечает «${pick_.model}»: ${pick_.why}`;
}

/**
 * Что делать, если кодовая модель не влезает.
 *
 * Предложен **разговорной модели на код** — с честной оговоркой: она пишет
 * код с ошибками, которые замечают только при запуске (шаг 63). Молча
 * подставить её значит уверенно выдать неверное.
 */
export function fallback(chat: string): string {
  return `кода нет — можно попросить «${chat}» написать, но она ошибается в коде, и ошибки видны только при запуске`;
}
