/**
 * Как окно должно себя вести на узком экране и при крупном масштабе.
 *
 * Зачем: при 200% масштабе окно шириной 940 логических пикселей выглядит как 470 —
 * а боковая колонка была жёстко 236 px. В итоге содержимое сжималось до полоски,
 * кнопки уезжали за край, и человек с плохим зрением получал сломанное приложение.
 * Это ровно то, чего не должно быть у продукта «для всех устройств».
 *
 * Правило держим здесь, без React, чтобы его проверяли тесты: инлайн-стиль по
 * `matchMedia` в компоненте глазами не проверишь.
 */

/** Порог, ниже которого колонка уходит вверх, а не отнимает ширину. */
export const NARROW_WIDTH = 760;

export type Layout = {
  /** Одна колонка: навигация сверху лентой. */
  narrow: boolean;
  /** Ширина боковой колонки. При узком окне её просто нет. */
  sidebarWidth: number;
};

/** Что применить к окну такой ширины. */
export function layoutFor(width: number): Layout {
  return {
    narrow: width < NARROW_WIDTH,
    // На узком экране колонка не нужна вовсе; на широком — прежние 236 px,
    // но не больше четверти окна, иначе содержимое сжимается.
    sidebarWidth: Math.min(236, Math.max(0, Math.floor(width / 4))),
  };
}
