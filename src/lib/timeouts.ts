/**
 * Таймауты с честным «долго, ждать?» вместо бесконечного спиннера (шаг 134).
 *
 * Дефект. У ожидания **не было конца**, и это не считалось дефектом:
 *
 *  * **спиннер бесконечен**: если ответ не придёт, крутиться он будет вечно, и человек
 *    не отличит «ещё работает» от «умерло»;
 *  * **отмена не предусмотрена**: уйдя на обед, человек возвращается к крутящемуся
 *    экрану и не знает, было ли что-то сделано;
 *  * **таймаут без выбора — просто ошибка**: «не дождались» ничего не даёт; человеку
 *    нужно решить — ждать дальше или бросить;
 *  * **разные дела — разные сроки**: сходить к модели за 30 с — норма, а к ядру за 3 с —
 *    уже сбой; один таймаут на всё врёт в обе стороны.
 *
 * Правило: **у каждого ожидания есть срок, и по его истечении человек выбирает**.
 *
 *  1. **Срок назван числом** и **свой у каждого дела**: ядро, модель, диск, сеть.
 *  2. **По истечении — выбор, а не ошибка**: «долго, ждать?» — продолжить срок или
 *     бросить.
 *  3. **Продление названо**: «ещё 30 с» — это решение человека, а не тишина.
 *  4. **Брошенное не выдаётся за сделанное**: `abandoned` — это факт, и он попадает в
 *     отчёт.
 *  5. **Спиннер не один на всё**: то, что задумано долгим, так и показывается — с
 *     прогрессом и сроком, а не с бесконечным кругом.
 *
 * Почему не «просто поставить таймаут побольше». Больший таймаут — это то же
 * бесконечное ожидание, только позже: человек всё равно не знает, чего ждёт.
 */

/** Род работы: у каждого свой срок. */
export type Kind = "kernel" | "model" | "disk" | "network" | "plan";

/** Сроки — числами, с основанием. */
export function deadline(kind: Kind): { ms: number; said: string } {
  switch (kind) {
    case "kernel":
      // Ядро на петле отвечает быстро; 3 с — уже сбой, а не «думает».
      return { ms: 3000, said: "ядро: 3 с — дольше это уже сбой, а не работа" };
    case "model":
      // Модель думает долго, и это нормально: ждать до 30 с.
      return { ms: 30_000, said: "модель: 30 с — она думает, и это нормально" };
    case "disk":
      // Диск на большом дереве бывает медленным, но не бесконечным.
      return { ms: 20_000, said: "диск: 20 с" };
    case "network":
      // Сеть — самое частое место отказа: срок короткий.
      return { ms: 10_000, said: "сеть: 10 с" };
    case "plan":
      // План из модели — тот же срок, что и ответ.
      return { ms: 30_000, said: "план: 30 с" };
  }
}

/** Что происходит с ожиданием. */
export interface Wait {
  kind: Kind;
  /** Сколько уже ждём. */
  ms: number;
  /** Сколько раз продлевали. */
  extended: number;
}

/** Состояние: ждём, спрашиваем или пора бросать. */
export type State = "wait" | "ask" | "give-up";

/**
 * Что делать.
 *
 * По истечении срока — **вопрос**, а не ошибка: «не дождались» ничего не даёт.
 */
export function state(wait: Wait): { state: State; said: string } {
  const limit = deadline(wait.kind);
  // Каждое продление — ещё один срок: человек решил ждать, и это решение уважается.
  const total = limit.ms * (1 + wait.extended);
  if (wait.ms < total) return { state: "wait", said: "" };
  if (wait.extended === 0) {
    return {
      state: "ask",
      said: `«${limit.said}» — срок вышел (${Math.round(wait.ms / 1000)} с). Ждать ещё ${limit.ms / 1000} с?`,
    };
  }
  // Больше двух продлений — это уже «бросить», а не «ещё раз».
  if (wait.extended >= 2) {
    return { state: "give-up", said: "дважды продлевали — ждать больше нечего, бросаю" };
  }
  return { state: "ask", said: `снова долго (${Math.round(wait.ms / 1000)} с). Ждать ещё или бросить?` };
}

/**
 * Ответ человека.
 *
 * `had` — сколько продлений уже было: счётчик **растёт**, а не сбрасывается в 1, иначе
 * «дважды продлевали» никогда не наступит и ожидание снова станет бесконечным.
 */
export function answer(
  reply: "extend" | "stop",
  had = 0,
): { extended: number; abandoned: boolean; said: string } {
  if (reply === "extend") {
    return { extended: had + 1, abandoned: false, said: "жду ещё один срок" };
  }
  return { extended: had, abandoned: true, said: "бросаю: ответа не дождались" };
}

/**
 * Брошенное — факт, а не пустота.
 *
 * «Ничего не произошло» — неправда: запрос был, время прошло, и это надо назвать, чтобы
 * отчёт не выглядел как «не начинали».
 */
export function abandoned(kind: Kind, ms: number): string {
  const limit = deadline(kind);
  return `${limit.said.split(" — ")[0]}: брошено через ${Math.round(ms)} мс — ответа не было`;
}

/**
 * Не завис ли спиннер.
 *
 * Спиннер без срока — это «вечный» индикатор; функция нужна, чтобы это было
 * проверяемо, а не «на глаз».
 */
export function spinning(waiting: boolean, hasDeadline: boolean): { ok: boolean; said: string } {
  if (!waiting) return { ok: true, said: "не ждём" };
  if (!hasDeadline) return { ok: false, said: "ждём без срока — это бесконечный спиннер" };
  return { ok: true, said: "ждём со сроком" };
}

/**
 * Что показать вместо круга.
 *
 * У долгого дела — срок и что именно делается; у неизвестного — «разбираюсь» (133).
 */
export function insteadOfSpinner(kind: Kind): string {
  const limit = deadline(kind);
  return `${limit.said}; если срок выйдет — спрошу, ждать ли дальше`;
}
