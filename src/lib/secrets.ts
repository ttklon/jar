/**
 * Проверять, что понятая фраза не содержит секретов до отправки модели (шаг 98).
 *
 * Дефект. Человек говорит «сохрани пароль от почты в файл» или «вставь ключ
 * `sk-…` в конфиг» — и **фраза уходит модели целиком**. Модель бывает локальной,
 * но не всегда: тот же путь в браузерном режиме идёт наружу. Дальше:
 *
 *  * **секрет уехал** — и он уже не отзывается кнопкой «отменить»;
 *  * **секрет попал в журнал** (шаг 60, 88) и остался там навсегда — журнал-то
 *    для улучшения разбора;
 *  * **человек не знает**: он говорил про пароль, а не отдавал его.
 *
 * Правило: **вычистка до, а не после**.
 *
 *  1. Проверка — **до отправки**: после отправки уже поздно, текста у модели.
 *  2. Вычищается **сам секрет**, а не фраза: «сохрани пароль в файл» остаётся,
 *     `hunter2` — нет. Иначе разбор не поймёт, о чём речь.
 *  3. Место вычищенного **помечено** (`[секрет]`), а не стёрто молча: «сохрани в
 *     файл» без «пароль» — это другая просьба.
 *  4. **Список узкий и точный**: длинные числа, ключи по префиксу (`sk-`,
 *     `ghp_`), явные `пароль: …`, `token=…`. Ложное срабатывание дешевле
 *     утечки, но и оно не бесплатно — вычистив «52», мы портим намерение.
 *  5. Журнал получает **уже вычищенное**: журнал нужен для разбора, а не для
 *     секретов.
 *
 * Почему не «спросить, можно ли отправить». Вопрос превращает каждую фразу в
 * анкету, а секрет всё равно уже произнесён. Вычистка — молчаливая и точная.
 */

/** Что найдено и что отправлено. */
export interface Clean {
  /** Текст **до отправки** модели. */
  text: string;
  /** Что вычищено — по видам, без самих значений. */
  found: string[];
  /** Был ли секрет вовсе. */
  any: boolean;
}

/** Заменяемый маркер: место секрета видно, значение — нет. */
export const MARK = "[секрет]";

/**
 * Шаблоны секретов.
 *
 * Список **узкий**: то, что точно секрет. Длинное число «52» — не секрет, а
 * «прошу 52 файла», и вычистить его значит сломать намерение.
 */
const PATTERNS: [RegExp, string][] = [
  // Ключи по префиксу: так их выдают, и так их узнают.
  [/\bsk-[A-Za-z0-9_-]{16,}/g, "ключ sk-"],
  [/\bghp_[A-Za-z0-9]{20,}/g, "токен GitHub"],
  [/\bglpat-[A-Za-z0-9_-]{16,}/g, "токен GitLab"],
  [/\bAKIA[0-9A-Z]{16}\b/g, "ключ AWS"],
  [/\bxox[baprs]-[A-Za-z0-9-]{10,}/g, "токен Slack"],
  // Явное «пароль: …», «токен=…», «ключ — …».
  // Между словом и значением бывают ещё слова: «пароль **от почты**: qwerty».
  // Без этого «пароль от почты» не вычищался — проверено делом, а не на глаз.
  [/(?:пароль|password|passwd|pwd|токен|token|api[_-]?key|ключ)(?:\s+[\p{L}\p{N}]{2,10}){0,3}\s*[:=]\s*(\S{4,})/giu, "пароль или ключ"],
  [/(?:пароль|password|passwd|pwd|токен|token|api[_-]?key|ключ)\s+(\S{4,})/giu, "пароль или ключ"],
  // Длинные числа с явным «карта» рядом — банковская карта.
  [/(?:карт[аы]|card)[^\d]{0,10}((?:\d[ -]?){13,19})/giu, "номер карты"],
];

/**
 * Вычистка.
 *
 * Один проход, потому что замены **не пересекаются по смыслу**: ключ с префиксом
 * и «пароль: …» — разные места, и второй проход по уже вычищенному ищет маркер.
 */
export function clean(phrase: string): Clean {
  let text = phrase;
  const found: string[] = [];

  for (const [pattern, kind] of PATTERNS) {
    const fresh = new RegExp(pattern.source, pattern.flags);
    text = text.replace(fresh, (match, group?: string) => {
      // Уже помеченное — не секрет: `[секрет]` это маркер, а не значение.
      // Без этой проверки вычищенный текст («пароль: [секрет]») оставался
      // «грязным»: шаблон «пароль: …» находил сам маркер, повторная проверка
      // кричала вечно, и «вычистить» было невозможно — после чистки память
      // выглядела так же грязно. Найдено тестом памяти: там важно не
      // «вычистили ли», а «чисто ли теперь».
      if (group === MARK) return match;
      if (!found.includes(kind)) found.push(kind);
      // Если в шаблоне есть группа-значение («пароль: X»), оставляем слово перед
      // ним: «сохрани пароль в файл» должно остаться про пароль.
      if (typeof group === "string" && group.length > 0) {
        return match.replace(group, MARK);
      }
      return MARK;
    });
  }

  return { text, found, any: found.length > 0 };
}

/**
 * Что сказать человеку.
 *
 * Названо **что найдено и что вычищено**, но не значение: человек должен знать,
 * что фраза ушла без секрета, иначе он решит, что не поняли.
 */
export function say(got: Clean): string {
  if (!got.any) return "";
  return `нашёл в фразе ${got.found.join(", ")} — вычистил до отправки: модель получит «${got.text}»`;
}

/**
 * Можно ли отправлять.
 *
 * **Всегда можно** — после вычистки. Отказывать целиком значит не понимать
 * просьбу, а человек просил не отдавать секрет, а сохранить пароль.
 */
export function sendable(_got: Clean): true {
  return true;
}

/**
 * Что записывается в журнал.
 *
 * Журнал получает **вычищенное**: он нужен для разбора, а не для секретов.
 */
export function forLog(got: Clean): string {
  return got.text;
}

/**
 * Проверка «секрет не остался».
 *
 * Нужна как отдельная функция, чтобы тест мог проверить на **реальных**
 * примерах: если после вычистки значение всё ещё в строке — это провал, а не
 * мелочь.
 */
export function leaks(original: string, got: Clean, secret: string): boolean {
  return got.text.includes(secret) && !original.includes(MARK);
}
