/**
 * Шаг 489: артефакт сборки с хешами и подписью.
 *
 * Человек скачивает установщик с сайта — и не может отличить настоящий от
 * подделанного. Хеш, опубликованный **рядом с установщиком**, этого не решает: если
 * подменили установщик, подменят и хеш.
 *
 * Поэтому у артефакта две вещи, и они разные:
 *
 *  * **хеш** — `SHA-256` содержимого: видно, что файл не побился при скачивании;
 *  * **подпись** — хеша, **приватным ключом**, а не самим файлом: публичный ключ
 *    вшит в программу, и человек может проверить, что хеш написали мы.
 *
 * И правило: **неподписанный артефакт не публикуется**. Артефакт без подписи — это
 * файл, о котором никто не может сказать, наш он или нет.
 */

/** Артефакт. */
export interface Artifact {
  /** Имя файла. */
  readonly name: string;
  /** Шестнадцатеричный SHA-256; `null` — не посчитан. */
  readonly sha256: string | null;
  /** Подпись хеша; `null` — не подписан. */
  readonly signature: string | null;
}

/** Длина SHA-256 в шестнадцатеричном виде. */
export const HASH_LENGTH = 64;

/**
 * Можно ли публиковать.
 *
 * Три условия: хеш посчитан и по форме, подпись есть, имя не подозрительное.
 */
export function check(artifact: Artifact): string[] {
  const problems: string[] = [];

  if (artifact.sha256 === null) {
    problems.push(`«${artifact.name}»: хеш не посчитан — не с чем сверять`);
  } else if (!/^[0-9a-f]{64}$/.test(artifact.sha256)) {
    problems.push(`«${artifact.name}»: хеш не SHA-256: «${artifact.sha256.slice(0, 12)}…» — ${artifact.sha256.length} знаков вместо ${HASH_LENGTH}`);
  }

  if (artifact.signature === null || artifact.signature.trim() === "") {
    problems.push(`«${artifact.name}»: не подписан — никто не скажет, наш это файл или нет`);
  }

  if (/\.(exe|msi)$/i.test(artifact.name) && artifact.sha256 === null) {
    problems.push(`«${artifact.name}»: установщик без хеша — худший случай для человека`);
  }

  return problems;
}

/**
 * Что опубликовать рядом.
 *
 * Две строки: хеш и подпись. Не «ссылка на страницу с хешем» — файл рядом.
 */
export function publish(artifact: Artifact): string[] {
  return [
    `${artifact.name}.sha256 — хеш содержимого`,
    `${artifact.name}.sig — подпись хеша нашим ключом`,
  ];
}

/**
 * Что проверяет человек.
 *
 * Три шага, и все — на его стороне: он не доверяет нам, он проверяет.
 */
export function verify(): string[] {
  return [
    "посчитать хеш скачанного файла и сверить с опубликованным",
    "проверить подпись хеша публичным ключом, вшитым в программу",
    "если подпись не сходится — не запускать, даже если хеш совпал",
  ];
}

/**
 * Чего подпись не делает.
 *
 * Три запрета; первый — не подписывать «чем есть».
 */
export function notDo(): string[] {
  return [
    "не подписывается ключом, который лежит в репозитории: такой ключ есть у всех",
    "не публикуется без подписи «на время»: неподписанный артефакт — это чужой файл",
    "не заменяет хеш подписью: хеш ловит битый файл, подпись — подмену",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "у каждого артефакта посчитан SHA-256",
    "хеш подписан ключом, которого нет в репозитории",
    "неподписанный артефакт не публикуется",
  ];
}
