/**
 * Шаг 493: свести открытые риски в один короткий список — чтобы не искать.
 *
 * Риски живут в трёх местах: в комментариях кода (`TODO`, `FIXME`), в заметках и в
 * голове. В голове — хуже всего: они всплывают в самый неподходящий момент.
 *
 * Один короткий список — это **не реестр на сто строк**, а семь-десять пунктов, у
 * каждого:
 *
 *  * **что может случиться** — по-человечески, а не «риск R-12»;
 *  * **насколько вероятно и насколько больно** — по трём ступеням, без «средне»;
 *  * **что сейчас делаем** — чтобы было видно, что это не забыто;
 *  * **когда пересмотреть** — дата, а не «когда-нибудь».
 *
 * И правило: короткий список — потому что в длинный не смотрят. Больше десяти
 * пунктов — значит риски не расставлены по важности, а сложены в кучу.
 */

/** Риск. */
export interface Risk {
  /** Что может случиться. */
  readonly what: string;
  /** Вероятность. */
  readonly likely: "низкая" | "средняя" | "высокая";
  /** Насколько больно. */
  readonly hurt: "мало" | "заметно" | "сильно";
  /** Что делаем сейчас. */
  readonly doing: string;
  /** Когда пересмотреть. */
  readonly review: string;
}

/** Больше — в список не смотрят. */
export const MAX_RISKS = 10;

/**
 * Насколько страшный.
 *
 * Считается, а не оценивается на глаз: три на три — девять уровней, и в список
 * первыми идут верхние. «Средне» не бывает: вероятность и боль — разные вопросы.
 */
export function level(risk: Risk): number {
  const scale = { низкая: 0, средняя: 1, высокая: 2 } as const;
  const pain = { мало: 0, заметно: 1, сильно: 2 } as const;
  return scale[risk.likely] + pain[risk.hurt];
}

/**
 * Проверить список.
 *
 * Нарушения: больше десяти, риск без «что делаем», дата пересмотра не по форме, два
 * риска с одинаковым названием.
 */
export function check(risks: readonly Risk[]): string[] {
  const problems: string[] = [];

  if (risks.length > MAX_RISKS) problems.push(`рисков ${risks.length}, а больше ${MAX_RISKS} не читают: расставить по важности`);

  const seen = new Set<string>();
  for (const risk of risks) {
    const key = risk.what.toLowerCase().trim();
    if (seen.has(key)) problems.push(`«${risk.what}» повторяется`);
    seen.add(key);

    if (risk.doing.trim().length < 10) problems.push(`«${risk.what}»: не сказано, что делаем сейчас`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(risk.review)) problems.push(`«${risk.what}»: дата пересмотра «${risk.review}» не по форме ГГГГ-ММ-ДД`);
  }

  return problems;
}

/**
 * Список по важности.
 *
 * Верхние — первыми: у них и `level` больше. Это и есть «короткий список»: если
 * смотреть только в начало, видно самое страшное.
 */
export function ordered(risks: readonly Risk[]): Risk[] {
  return [...risks].sort((a, b) => level(b) - level(a));
}

/**
 * Что сказать человеку перед пересмотром.
 *
 * Три факта: сколько рисков, самый страшный, когда пересматривать.
 */
export function summary(risks: readonly Risk[]): string {
  if (risks.length === 0) return "открытых рисков нет: список пуст, и это записано";

  const top = ordered(risks)[0]!;
  const soon = [...risks].map((risk) => risk.review).sort()[0] ?? "—";
  return `рисков ${risks.length}, самый страшный: «${top.what}» (${top.likely} вероятность, ${top.hurt} боль); ближайший пересмотр ${soon}`;
}

/**
 * Чего список не делает.
 *
 * Три запрета; главный — не превращаться в реестр.
 */
export function notDo(): string[] {
  return [
    "не превращается в реестр на сто строк: в такой не смотрят",
    "не пишет «средне»: вероятность и боль — два разных вопроса",
    "не оставляет риск без «что делаем»: иначе это не риск, а страх",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу частей риска.
 */
export function checks(): string[] {
  return [
    "не больше десяти рисков, по важности",
    "у каждого сказано, что делаем сейчас и когда пересмотрим",
    "важность считается из вероятности и боли, а не на глаз",
  ];
}
