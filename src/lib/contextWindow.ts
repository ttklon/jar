/**
 * Память контекста: не больше нужного (шаг 67).
 *
 * Дефект. Модель берёт окно контекста «с запасом» — на всякий случай побольше.
 * И платит за это **всегда**, а не иногда:
 *
 *  * **память** занята под кеш контекста, даже если в нём две строки. На 8 ГБ
 *    это разница между «влезает 3B» и «влезает 1.5B»;
 *  * **скорость** падает: внимание считается по всему окну, и пустое место в
 *    нём тоже считается;
 *  * **первый токен** ждётся дольше — а это то, что человек считает
 *    «приложение тормозит» (шаг 65).
 *
 * Правило: окно — **по задаче**, а не «побольше».
 *
 *  1. Голос — **узкое окно**: фраза это десять-двадцать слов, и всё, что
 *     больше, — не речь человека, а мусор. Голосовой ответ ждут, поэтому здесь
 *     каждая миллисекунда видна.
 *  2. Разговор — **среднее**: человек помнит, о чём говорил три реплики назад,
 *     но не двадцать.
 *  3. Код и план — **широкое**: там нужен файл целиком или вся цепочка шагов.
 *  4. Окно **называется числом** и с причиной: «не больше 20 реплик, дальше
 *     модель начнёт путаться» — это не ограничение, а обещание качества.
 *
 * Почему не «чем больше, тем лучше». Это верно для качества **до** предела, за
 * которым модель теряет середину (известное поведение длинных контекстов). И
 * неверно для скорости — а голосом пользуются каждый день.
 */

/** Задача: от неё зависит окно. */
export type Task = "voice" | "chat" | "plan" | "code";

/**
 * Сколько токенов в окне для задачи.
 *
 * Числа — не «максимум модели», а **нужное для задачи**. Меньше — начнём
 * обрезать смысл; больше — платим памятью и временем впустую.
 */
export const WINDOW: Record<Task, number> = {
  // Фраза — 10–20 слов ≈ 50 токенов; 512 с запасом на историю реплики.
  voice: 512,
  // Три — пять реплик разговора.
  chat: 2048,
  // Цепочка шагов плана и описания рук.
  plan: 4096,
  // Файл целиком или большая функция.
  code: 8192,
};

/**
 * Окно для задачи — с причиной.
 *
 * Причина нужна, чтобы число можно было оспорить, а не принять на веру.
 */
export function windowFor(task: Task): number {
  return WINDOW[task];
}

/**
 * Почему такое окно.
 *
 * Сказано **что произойдёт** при большем: не «ограничение», а «модель начнёт
 * путаться» или «будем ждать зря».
 */
export function why(task: Task): string {
  switch (task) {
    case "voice":
      return "голос — это фраза в десять-двадцать слов; большее окно здесь только замедляет первый токен";
    case "chat":
      return "разговор помнят на три-пять реплик назад, а не на двадцать";
    case "plan":
      return "план — это цепочка шагов; уже окна она не влезает";
    case "code":
      return "код нужен целиком: обрезанная функция хуже, чем медленный ответ";
  }
}

/**
 * Сколько памяти занимает кеш контекста.
 *
 * Приблизительно: KV-кеш растёт линейно с окном, и для 7B в Q4 это примерно
 * 0.5 МБ на токен. Число нужно, чтобы человек видел: «окно побольше» — это не
 * бесплатно.
 */
export const MB_PER_TOKEN = 0.5;

export function cacheMb(task: Task): number {
  return Math.round(windowFor(task) * MB_PER_TOKEN);
}

/**
 * Обрезать историю под окно — **умно**, а не с начала.
 *
 * Режем **старое**, но сохраняем начало: там «системная» часть — правила и
 * роль, — и без неё модель перестаёт быть той же моделью. Так же сохраняем
 * последние реплики: они и есть разговор.
 *
 * `keep` — сколько последних элементов обязательно оставить.
 */
export function fit<T>(history: readonly T[], window: number, cost: (item: T) => number, keep = 1): T[] {
  if (history.length === 0) return [];
  const first = history[0];
  const tail: T[] = [];
  let used = 0;
  // Начинаем с последних и идём назад, пока влезает.
  for (let index = history.length - 1; index >= 1; index -= 1) {
    const item = history[index];
    if (item === undefined) continue;
    const price = cost(item);
    if (used + price > window) break;
    tail.unshift(item);
    used += price;
  }
  if (tail.length >= keep) return first === undefined ? tail : [first, ...tail];
  // Не влезло даже обязательное — отдаём только хвост: начало без разговора
  // бесполезнее, чем разговор без начала.
  return history.slice(-Math.max(1, keep));
}

/**
 * Что сказать человеку про окно.
 *
 * Названо **число, причина и цена в памяти**: «окно побольше» — не бесплатно, и
 * человек должен это видеть до того, как попросит.
 */
export function say(task: Task): string {
  return `окно ${windowFor(task)} токенов (${cacheMb(task)} МБ памяти): ${why(task)}`;
}

/**
 * Окно больше нужного — это не запас, а потеря.
 *
 * Проверка нужна, чтобы настройка «побольше» не выглядела улучшением: при
 * превышении втрое скорость и память платят втрое.
 */
export function wasteful(task: Task, window: number): boolean {
  return window > windowFor(task) * 3;
}
