/**
 * Шаг 484: понятное сообщение об ошибке с «что сделать».
 *
 * «stale» — это не сообщение, а ребус. Человек (или я сам через месяц) видит слово
 * и не знает: перезапустить? закоммитить? позвать кого-то? Проверка, которая
 * требует разгадывать, — это проверка, которую обходят.
 *
 * Поэтому у каждого сообщения три части, и ни одна не пропускается:
 *
 *  * **что случилось** — на языке человека, без жаргона: «снимок отчёта старее
 *    данных»;
 *  * **что сделать** — одно действие, конкретное: «запустите
 *    `python3 tools/report_snapshot.py --write` и закоммитьте `data/report.json`»;
 *  * **где** — файл и строка, а если не файл, то имя проверки.
 *
 * И правило то же, что в поддержке (шаг 475): **одно действие**, а не три.
 */

/** Сообщение. */
export interface Message {
  /** Код — для журнала и для поиска. */
  readonly code: string;
  /** Что случилось, по-русски. */
  readonly what: string;
  /** Что сделать — одно действие. */
  readonly todo: string;
  /** Где: файл и строка или имя проверки. */
  readonly where: string;
}

/** Слова, которых в сообщении быть не должно. */
const JARGON = ["stale", "failed", "invalid", "ошибка 0x", "null", "undefined", "assert"];

/**
 * Проверить сообщение.
 *
 * Нарушения: жаргон, «что-то пошло не так», несколько действий, нет «где».
 */
export function check(message: Message): string[] {
  const problems: string[] = [];
  const text = `${message.what} ${message.todo}`.toLowerCase();

  for (const word of JARGON) {
    if (text.includes(word.toLowerCase())) problems.push(`«${message.code}»: жаргон «${word}» — человек не поймёт`);
  }

  if (/что-то пошло не так|неизвестная ошибка|см\. лог/i.test(message.what)) problems.push(`«${message.code}»: «${message.what}» не говорит, что случилось`);

  // Одно действие: две команды — это два действия. Считаем команды в обратных
  // кавычках, а не «и» — `\b` с кириллицей не работает, и «и» есть в обычных словах.
  const commands = Math.floor((message.todo.match(/`/g) ?? []).length / 2);
  if (commands > 1) {
    problems.push(`«${message.code}»: в «что сделать» больше одного действия (команд ${commands}): второе уходит в «Где» или в документацию`);
  }

  if (message.todo.trim() === "") problems.push(`«${message.code}»: не сказано, что сделать`);
  if (message.where.trim() === "") problems.push(`«${message.code}»: не сказано, где смотреть`);

  return problems;
}

/**
 * Собрать сообщение для человека.
 *
 * Порядок — как читает человек: что случилось, что сделать, где.
 */
export function text(message: Message): string {
  return `${message.what}\nЧто сделать: ${message.todo}\nГде: ${message.where}`;
}

/**
 * Готовые сообщения для частых проверок.
 *
 * Каждое — с кодом и одним действием; это образец, по которому пишут остальные.
 */
export function samples(): Message[] {
  return [
    { code: "report-stale", what: "снимок отчёта старее данных: в нём числа, которых уже нет", todo: "запустите `python3 tools/report_snapshot.py --write`: снимок перезапишется сам", where: "data/report.json" },
    { code: "ts-unused-import", what: "в тесте остался импорт, которым ничего не пользуются", todo: "уберите его из списка импорта в начале файла", where: "src/lib/x.test.ts:2" },
    { code: "plan-mark", what: "шаг сдан, но в плане не помечен: счётчик отстаёт от кода", todo: "поставьте «Сделано:» в строке шага плана", where: "docs/MASTER-PLAN-500.md:701" },
  ];
}

/**
 * Чего сообщение не делает.
 *
 * Три запрета; первый — «см. лог».
 */
export function notDo(): string[] {
  return [
    "не пишет «см. лог»: лог — для подробностей, а не вместо ответа",
    "не перечисляет три способа на выбор: способ один, остальные — в документации",
    "не обвиняет человека: «вы сделали не так» — это не сообщение об ошибке",
  ];
}

