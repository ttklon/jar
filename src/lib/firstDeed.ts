/**
 * Шаг 96: первое дело на знакомстве раньше настройки.
 *
 * Обычно программа знакомит так: «выберите модель, папку, тему, микрофон» — и только
 * через десять минут человек видит, что она делает. За это время он успевает решить,
 * что это сложно.
 *
 * Здесь наоборот: **сначала дело, потом настройка**. «Что умею» отвечает без модели
 * — готовый пример, который ничего не скачивает и не требует выбора. Человек видит
 * результат за двадцать секунд и **потом** отвечает на вопросы.
 *
 * Правила:
 *
 *  * первое дело работает **без модели и без настроек**;
 *  * после дела вопросов **не больше двух** — «как звать» и «что чаще делаете»;
 *  * настройка не отменяет дело: если человек пропустил вопросы, дело работает.
 */

/** Что происходит при знакомстве. */
export interface Greeting {
  /** Шаг: «что умею» без модели. */
  readonly demoFirst: boolean;
  /** Сколько вопросов после дела. */
  readonly questions: number;
  /** Работает ли дело, если настройку пропустили. */
  readonly worksWithoutSetup: boolean;
}

/** Допустимое число вопросов после первого дела. */
export const MAX_QUESTIONS = 2;

/**
 * Порядок шагов знакомства.
 *
 * Дело первым, и это проверяется порядком массива, а не обещанием.
 */
export function order(): string[] {
  return ["«что умею»: пример без модели и без скачивания", "первое дело на примере: видно результат", "два вопроса: как звать и что чаще делаете", "настройка: модель и папки — по желанию"];
}

/**
 * Проверить знакомство.
 *
 * Нарушения: сначала настройка (дело не первым), больше двух вопросов, дело не
 * работает без настройки.
 */
export function check(greeting: Greeting): string[] {
  const problems: string[] = [];

  if (!greeting.demoFirst) problems.push("«что умею» после настройки: человек десять минут не видит, что программа делает");
  if (greeting.questions > MAX_QUESTIONS) problems.push(`вопросов ${greeting.questions}: больше двух — это допрос, а не знакомство`);
  if (!greeting.worksWithoutSetup) problems.push("без настройки дело не работает: значит настройка была не «по желанию»");

  return problems;
}

/**
 * Что сказать, когда человек пропустил вопросы.
 *
 * Не «настройка не завершена», а «дело работает, вопросы можно ответить потом».
 */
export function skipped(): string {
  return "дело работает и так: имя и привычки нужны для подсказок, их можно ответить позже в Настройках";
}

/**
 * Чего знакомство не делает.
 *
 * Три запрета; главный — не начинать с выбора модели.
 */
export function notDo(): string[] {
  return [
    "не начинается с выбора модели: модель скачивается потом, когда человек увидел смысл",
    "не задаёт больше двух вопросов: остальное — в настройках, когда понадобится",
    "не отменяет дело за пропущенную настройку",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "«что умею» отвечает без модели",
    "после дела не больше двух вопросов",
    "пропущенная настройка не ломает дело",
  ];
}
