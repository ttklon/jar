/**
 * Журнал опасных действий поднимается выше обычных в «Обзоре» (шаг 176).
 *
 * Дефект. Журнал — плоская лента: сверху то, что случилось позже. Опасное
 * действие в ней тонет между «прочитал файл» и «открыл сайт», и человек,
 * открывший журнал с вопросом «не случилось ли чего?», получает хронологию, а не
 * ответ. При этом события уже есть, и в них есть `risk` — сортировать нечем
 * только потому, что сортировки не было.
 *
 * Правила:
 *
 *  1. **Опасное — выше обычного.** Не «по времени», а **сначала** разрушительное,
 *     внешнее, денежное, подписывающее. Время остаётся вторым ключом внутри
 *     группы: свежее выше старого;
 *  2. **порядок не выдуман, а тот же, что в реестре:** денежное и подписывающее
 *     опаснее разрушительного, потому что отменить нельзя;
 *  3. **отказ — не доказательство, но и не мусор.** Отказ политики остаётся
 *     видимым, просто ниже запусков с тем же риском: «не сделали» — тоже ответ;
 *  4. **счётчик назван.** «Опасных: 3 из 41» говорит, сколько смотреть, а не «найди
 *     сам»; ноль — законный ответ и повод не листать;
 *  5. **порядок устойчив.** Две пересортировки одного и того же журнала дают один
 *     и тот же список: журнал, который прыгает при обновлении, читать невозможно.
 *
 * Модуль не читает журнал и не знает событий: он только упорядочивает и считает.
 */

/**
 * Минимум события, нужный для порядка.
 *
 * Отдельный тип, а не журнальный: модуль сортирует **любое** событие с этими
 * полями и отдаёт его же, не обрезая. Так вызывающий не теряет `decision` и
 * `duration_ms` — журнал показывает их в таблице.
 */
export interface Orderable {
  subject: string;
  risk: string;
  kind: string;
  outcome: string;
  at_ms: number;
}

/**
 * Вес опасности. Больше — опаснее.
 *
 * Порядок тот же, что в реестре и в `policy.rs`: деньги и подпись необратимы,
 * удаление обратимо корзиной, внешнее — отправка наружу. Чтение — обычное.
 */
const WEIGHT: Readonly<Record<string, number>> = {
  money: 5,
  identity: 4,
  destructive: 3,
  external: 2,
  "write-local": 1,
  read: 0,
};

/** Насколько опасно — числом, для сортировки. */
export function weight(risk: string): number {
  return WEIGHT[risk] ?? 0;
}

/** Считается ли риск опасным — то есть тем, ради чего журнал открывают. */
export function dangerous(risk: string): boolean {
  return weight(risk) >= 2;
}

/**
 * Отказ политики.
 *
 * Такое событие **ниже** запуска с тем же риском: «политика не пустила» не
 * доказывает, что рука работает, но и прятать его нельзя — человек спрашивал.
 */
function refused(event: Orderable): boolean {
  return event.kind === "denied" || event.outcome.startsWith("denied");
}

/**
 * Разложить журнал: опасное выше обычного, внутри — свежее выше старого.
 *
 * Сортировка устойчивая (не `Array.prototype.sort` по одному ключу: равные пары
 * должны сохранять исходный порядок, иначе журнал «прыгает»).
 */
export function order<T extends Orderable>(events: readonly T[]): T[] {
  return events
    .map((event) => ({ event, key: weight(event.risk), refused: refused(event) }))
    .map((row, index) => ({ ...row, index }))
    .sort((a, b) => {
      // 1. Опасность — главный ключ.
      if (a.key !== b.key) return b.key - a.key;
      // 2. Запуск выше отказа при равном риске.
      if (a.refused !== b.refused) return a.refused ? 1 : -1;
      // 3. Свежее выше старого.
      if (a.event.at_ms !== b.event.at_ms) return b.event.at_ms - a.event.at_ms;
      // 4. Исходный порядок — чтобы список не прыгал.
      return a.index - b.index;
    })
    .map((row) => row.event);
}

/** Сколько в журнале опасного — для строки над списком. */
export interface Tally {
  /** Сколько событий всего. */
  total: number;
  /** Сколько из них опасных. */
  danger: number;
  /** События выше обычных: столько строк теперь сверху. */
  said: string;
  /** Есть ли на что смотреть: `false` — можно не листать. */
  see: boolean;
}

export function tally(events: readonly Orderable[]): Tally {
  const total = events.length;
  const danger = events.filter((event) => dangerous(event.risk)).length;
  if (total === 0) return { total: 0, danger: 0, said: "журнал пуст — и опасного в нём нет", see: false };
  if (danger === 0) {
    return {
      total,
      danger: 0,
      said: `опасного нет: ${total} ${total === 1 ? "событие" : "событий"} — все обычные, читать подряд незачем`,
      see: false,
    };
  }
  return {
    total,
    danger,
    said: `опасных ${danger} из ${total} — они сверху, остальное ниже по времени`,
    see: true,
  };
}

/**
 * Первая строка, ради которой журнал открыли.
 *
 * Если сверху стоит опасное действие, «что случилось?» уже отвечено. Если нет —
 * так и говорим: в журнале одни обычные события.
 */
export function first(events: readonly Orderable[]): string {
  const top = order(events)[0];
  if (top === undefined) return "журнал пуст";
  if (!dangerous(top.risk)) return `опасного не было: последнее — обычное «${top.subject}»`;
  return `сверху опасное: «${top.subject}» (${top.risk}) — ${top.outcome}`;
}
