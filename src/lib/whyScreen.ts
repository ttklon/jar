/**
 * Шаг 422: понятный «почему» для каждого отказа — на экране, а не в журнале.
 *
 * `journal.ts` (шаг 175) уже умеет советовать по причине отказа. Но у него другая
 * задача: он **группирует** отказы для разбора. Здесь — **один отказ одному
 * человеку**: короткая причина и одно действие, прямо там, где отказ случился.
 *
 * Четыре правила, без которых «почему» бесполезно:
 *
 *  * **причина на первой строке**, а не после трёх абзацев: человек читает до
 *    первой запятой, если она не по делу;
 *  * **одно действие**, а не «проверьте сетевое соединение, брандмауэр, прокси,
 *    антивирус». Человек делает одно, а не четыре;
 *  * **без кода ошибки в тексте** (`ECONNREFUSED`) — код выносится отдельно и
 *    мелко, для поддержки;
 *  * **без «попробуйте позже»**, если позже не изменится ничего: это не причина,
 *    а вежливое «не знаю».
 */

/** Отказ. */
export interface Failure {
  /** Что человек делал. */
  readonly doing: string;
  /** Код или техническая причина — мелко, для поддержки. */
  readonly code: string;
  /** Что известно про окружение. */
  readonly know: {
    readonly offline?: boolean;
    readonly noSpace?: boolean;
    readonly modelMissing?: boolean;
    readonly permission?: boolean;
    readonly timeout?: boolean;
  };
}

/** Что показать. */
export interface Why {
  /** Причина — первой строкой. */
  readonly cause: string;
  /** Одно действие. */
  readonly action: string;
  /** Код отдельно. */
  readonly code: string;
}

/**
 * Собрать объяснение.
 *
 * Порядок проверок — от «человек может исправить сам» к «нужна поддержка»: если
 * сеть выключена, а модель не скачана, причина — сеть, потому что с неё начинать.
 */
export function why(failure: Failure): Why {
  const k = failure.know;

  if (k.offline) {
    return { cause: `«${failure.doing}» не выполнено: нет сети`, action: "подключите сеть или подождите — остальное работает и без неё", code: failure.code };
  }
  if (k.noSpace) {
    return { cause: `«${failure.doing}» не выполнено: на диске нет места`, action: "освободите немного места — хватит пары гигабайт", code: failure.code };
  }
  if (k.permission) {
    return { cause: `«${failure.doing}» не выполнено: Windows не пустил в эту папку`, action: "выберите папку в своей домашней — туда приложение может писать без прав администратора", code: failure.code };
  }
  if (k.modelMissing) {
    return { cause: `«${failure.doing}» не выполнено: модель не скачана`, action: "скачайте модель на экране моделей — без неё приложение понимает только простые фразы", code: failure.code };
  }
  if (k.timeout) {
    return { cause: `«${failure.doing}» не выполнено: не уложилось во время`, action: "попробуйте ещё раз; если повторяется — сообщите нам, это наша ошибка", code: failure.code };
  }
  return { cause: `«${failure.doing}» не выполнено, и причину определить не удалось`, action: "пришлите отчёт: в нём то, что нужно, чтобы найти причину", code: failure.code };
}

/**
 * Строка целиком.
 *
 * Две строки, а не одна: причина и действие отдельно читаются лучше.
 */
export function text(failure: Failure): string {
  const got = why(failure);
  return `${got.cause}\n${got.action}`;
}

/**
 * Что «почему» не делает.
 *
 * Три запрета, и все три — про тексты, которые бесят.
 */
export function notDo(): string[] {
  return [
    "не пишет «попробуйте позже», если позже не изменится ничего",
    "не даёт четырёх действий: человек делает одно",
    "не прячет причину за кодом ошибки: код — отдельно и мелко",
  ];
}

/**
 * Какие причины есть.
 *
 * Список — чтобы не появилось «что-то пошло не так» в новой ветке кода.
 */
export function causes(): string[] {
  return ["нет сети", "нет места", "нет прав", "модель не скачана", "не уложилось во время", "причина неизвестна"];
}
