/**
 * Все отказы — один словарь причин (шаги 14 и 15).
 *
 * Дефект. Причина отказа называлась по-разному в разных местах: `no-room`,
 * `runtime-unsupported`, `runtime-owned`, `denied`, `cancelled`, а где-то —
 * живописным текстом от системы. Человек учится один раз — **но только если
 * слова одни и те же**. Иначе «нет места», «не хватает диска» и «мало
 * свободного» читаются как три разные беды, и каждую приходится понимать заново.
 *
 * Правило поэтому состоит из четырёх частей, и все четыре обязательны:
 *
 *  * **причина** — из закрытого списка. Пять причин покрывают то, что бывает на
 *    этой машине: нет программы, нет прав, нет места, нет сети, нельзя по
 *    политике. Шестая — «человек остановил»: это не отказ системы, и путать их
 *    нельзя, иначе «Стоп» превращается в ошибку;
 *  * **что делать** — не «повторите позже», а конкретный шаг, у трёх причин из
 *    шести он делается в приложении, и это называется;
 *  * **чьё это** — наша поломка или чужая настройка. От этого зависит, кому
 *    жаловаться и стоит ли вообще ждать;
 *  * **одно и то же слово везде** (шаг 15): один словарь, один перевод из
 *    системного текста, одна фраза.
 */

/** Почему не вышло. Закрытый список: расширять его — решение, а не мелочь. */
export type Reason =
  | "no-program"
  | "no-rights"
  | "no-room"
  | "no-network"
  | "by-policy"
  | "stopped";

/** Что сказать человеку: коротко и одними словами на всех экранах. */
export const REASON_TEXT: Record<Reason, string> = {
  "no-program": "нет программы",
  "no-rights": "нет прав",
  "no-room": "нет места",
  "no-network": "нет сети",
  "by-policy": "нельзя по правилу",
  stopped: "остановлено вами",
};

/**
 * Что делать. Конкретный шаг, а не «повторите позже».
 *
 * У трёх причин шаг делается в приложении, и это сказано прямо: «скачать
 * движок» — действие, а не совет. Там, где приложение ничего сделать не может
 * (нет прав, нет сети), честно говорится, что делать снаружи, — совет, который
 * человек может выполнить.
 */
export const REASON_ACTION: Record<Reason, string> = {
  "no-program": "скачайте движок на экране «Модели» — приложение умеет это само",
  "no-rights": "запустите приложение от администратора или выберите папку без защиты",
  "no-room": "освободите место или выберите другой диск — здесь не хватает",
  "no-network": "проверьте подключение и повторите: без сети это не скачается",
  "by-policy": "это запрещено правилом самого действия — не пытайтесь обойти",
  stopped: "ничего не сломано: вы остановили сами, можно начать заново",
};

/**
 * Чья это беда.
 *
 * `ours` — приложение или его данные; `machine` — настройки этой машины;
 * `choice` — решение человека, а не поломка. Разница нужна, чтобы «отказ»
 * не читался как «ошибка»: остановка человеком — не ошибка, и называть её так
 * значит обвинять человека в том, что он сделал осознанно.
 */
export function ownerOf(reason: Reason): "ours" | "machine" | "choice" {
  switch (reason) {
    case "no-program":
      return "ours";
    case "no-rights":
    case "no-room":
    case "no-network":
      return "machine";
    case "by-policy":
      return "ours";
    case "stopped":
      return "choice";
  }
}

/**
 * Перевод из того, что сказала система, в наш словарь.
 *
 * Зачем по тексту, а не по коду. Windows, PowerShell и node отдают кто errno,
 * кто английский текст, кто русскую фразу — единого кода нет. Поэтому правило
 * ищет **смысл** и приводит его к одной причине. Порядок проверок не случаен:
 * «net::ERR_ACCESS_DENIED» — это и права, и сеть; правильнее считать правами
 * (человек ничего не исправит повторной попыткой).
 *
 * Неизвестное не выдумывается: возвращается `null`, и вызывающий обязан
 * сказать «не удалось узнать причину» — а не навесить «нет сети» на всё
 * подряд, что уже однажды и делалось.
 */
export function reasonOf(error: unknown): Reason | null {
  const text = (error instanceof Error ? error.message : String(error ?? "")).toLowerCase();
  if (!text.trim()) return null;

  // Права — раньше сети: отказ доступа не лечится повтором.
  if (/access is denied|access denied|permission|eacces|eperm|администратор|прав|запрещ|denied/.test(text)) {
    return "no-rights";
  }
  // Нет места.
  if (/no space|enospc|disk full|недостаточно места|нет места|мало места/.test(text)) {
    return "no-room";
  }
  // Нет программы.
  if (/not found|enoent|не найден|не найдено|no such file|отсутству/.test(text)) {
    return "no-program";
  }
  // Сеть.
  if (/enotfound|econnrefused|etimedout|econnreset|internet_disconnected|net::err_internet|net::err_name|network|offline|сети|подключ/.test(text)) {
    return "no-network";
  }
  // Политика — наша, и человек её не обойдёт.
  if (/policy|политик|не разрешено|запрещено правилом/.test(text)) {
    return "by-policy";
  }
  if (/abort|cancel|отмен|остановлен/.test(text)) {
    return "stopped";
  }
  return null;
}

/**
 * Одна фраза для человека обо всём отказе (шаг 15).
 *
 * Порядок частей — от факта к действию: сначала что случилось, потом что
 * делать. Обратный порядок читается как совет без объяснения.
 */
export function reasonLine(reason: Reason): string {
  return `${REASON_TEXT[reason]} — ${REASON_ACTION[reason]}`;
}

/** Что сказать, когда причину определить не удалось. Не молчание и не выдумка. */
export const UNKNOWN_REASON = "не удалось узнать причину — подробности в журнале";
