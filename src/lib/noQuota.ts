/**
 * Квот нет, счёта нет: модели — локальные файлы с проверкой хеша (шаг 69).
 *
 * Дефект, который здесь лечится, не технический, а **доверительный**. Человек
 * боится двух вещей, и обе имеют основание:
 *
 *  * **счёт придёт**. «Бесплатно» в интернете обычно значит «бесплатно до
 *    порога», и человек, увидев счётчик, начинает считать фразы и говорить
 *    короче. Он платит вниманием за то, что обещали бесплатно;
 *  * **разговор уходит наружу**. Если модель в облаке, то каждое «найди файл
 *    с паспортом» уходит на чужой сервер, и обещание «локально» — только
 *    обещание.
 *
 * Правило: **бесплатность доказывается отсутствием механизма**, а не обещанием.
 *
 *  1. Модели — **файлы на диске**. Нет файла — нет работы; нет работы — нет
 *     счёта. Квоту нельзя «случайно исчерпать», потому что квоты нет вовсе.
 *  2. Проверка **хеша** — не для счёта, а для целостности: файл, который
 *     изменился (битый диск, подмена), не запускается. Без этого «локальная
 *     модель» может оказаться чем угодно.
 *  3. Хеш **назван и виден**: человек может сверить его со страницы загрузки.
 *     Проверка, которую никто не видит, — это ритуал, а не проверка.
 *  4. Счётчика **нет в интерфейсе**. Не потому что «не показываем», а потому
 *     что нечего показывать: нет ни квоты, ни баланса, ни «осталось».
 *
 * Почему не «мягкая квота для защиты от злоупотреблений». Злоупотреблять
 * локальной моделью может только её владелец — на своём компьютере. Квота здесь
 * защищает не от него, а от него же: turnит его в ожидании счёта.
 */

/** Что известно о файле модели. */
export interface File {
  /** Имя файла — как он лежит на диске. */
  name: string;
  /** Ожидаемый хеш (SHA-256), закреплённый при сборке. */
  sha256: string;
  /** Сколько байт — для быстрой проверки «тот ли файл». */
  size: number;
}

/**
 * Проверка целостности.
 *
 * `actual` — хеш, посчитанный по файлу на диске. Не совпал — файл **не
 * запускается**: это не паранойя, это разница между «модель» и «что угодно,
 * названное моделью».
 */
export function intact(file: File, actual: string): boolean {
  return file.sha256.toLowerCase() === actual.trim().toLowerCase();
}

/**
 * Что сказать при несовпадении.
 *
 * Не «ошибка хеша»: человеку нужно знать, **что это значит** (файл повреждён
 * или подменён) и **что делать** (скачать заново). Технический текст он
 * прочитает как «приложение сломалось».
 */
export function damage(file: File): string {
  return `файл «${file.name}» повреждён или подменён — скачайте заново, этот запускать нельзя`;
}

/**
 * Что обещано человеку.
 *
 * Названы **три вещи**, которых **нет**: квота, счёт, отправка наружу. Обещание
 * через отсутствие сильнее, чем обещание через «мы не будем»: нечему ломаться.
 */
export function promise(): string {
  return "ни квоты, ни счёта, ни отправки наружу: модели лежат файлами на этом компьютере";
}

/**
 * Можно ли работать.
 *
 * Проверяется **наличие файла и его целостность**, а не разрешение сервера: нет
 * сервера, который мог бы отказать.
 */
export function can(file: File | null, actual: string | null): boolean {
  if (file === null) return false;
  if (actual === null) return false;
  return intact(file, actual);
}

/**
 * Что сказать, если файла нет.
 *
 * Сказано, **откуда** его взять и что после этого ничего не нужно: человек
 * ждёт «регистрации» или «ключика», потому что так бывает везде.
 */
export function missing(name: string): string {
  return `файла «${name}» нет — скачайте один раз, и дальше он работает без интернета`;
}

/**
 * Есть ли в интерфейсе что-то, похожее на счётчик.
 *
 * Функция нужна тесту: она утверждает, что обещание не нарушено незаметно.
 * Появился баланс, «осталось фраз» или «лимит» — обещание сломано, и это
 * должно падать на тесте, а не выясняться через месяц.
 */
export function looksLikeQuota(text: string): boolean {
  return /осталось|баланс|лимит|квота|подписк|токенов на счёте|израсходовано/i.test(text);
}

/**
 * Как назвать модель, чтобы человек видел её как вещь, а не как сервис.
 *
 * «Файл 4.4 ГБ» — это то, что можно потрогать; «план Pro» — то, что можно
 * отобрать.
 */
export function asFile(file: File): string {
  const gb = Math.round((file.size / 1e9) * 10) / 10;
  return `файл ${file.name}, ${gb} ГБ — ваш, работает без интернета`;
}
