/**
 * Понимать отрицание: «не удаляй», «без копии» (шаг 84).
 *
 * Дефект — **самый дорогой из всех в разделе**, потому что цена ошибки не в
 * лишней секунде, а в стёртом файле и отправленном письме. Сегодня отрицание не
 * разбирается вовсе:
 *
 *  * **«не удаляй отчёты» исполняется как «удали отчёты»** — слово «не»
 *    отбрасывается как шум, потому что значимых слов в нём нет;
 *  * **«без копии»** читается как упоминание копии — и копия создаётся;
 *  * **«не отправляй, пока не проверю»** — двойное отрицание, и любая простая
 *    проверка на «не» даст ровно противоположный ответ;
 *  * **«не то чтобы срочно»** — не отрицание действия вовсе, а смягчение.
 *
 * Правило: **отрицание — это часть намерения, а не помеха в словах**.
 *
 *  1. «Не» **относится к глаголу**, а не к фразе целиком: «не удаляй отчёты» —
 *     это запрет удаления, а «найди не отчёты» — просто поиск другого.
 *  2. Отрицание **не отбрасывается**, если его можно понять: лучше
 *     переспросить, чем сделать наоборот.
 *  3. **Двойное отрицание** («не отправляй, пока не проверю») — это **условие**, а
 *     не отмена: «подожди, пока не проверю» значит «подожди». Простое «если
 *     есть «не», то запрет» тут даст противоположный ответ.
 *  4. **Не всякое «не» — отрицание**: «не то чтобы», «не только», «ничего» —
 *     смягчение или усиление, а не запрет. Ошибка в эту сторону дешевле, но
 *     всё равно ошибка: «не только найди» — это «найди и ещё что-то».
 *  5. Если есть сомнение — **переспросить**, а не угадать. Угадывание при
 *     отрицании — это ровно та ошибка, после которой человек удаляет приложение.
 *
 * Почему не «модель поймёт». Модель поймёт в 95% случаев, а оставшиеся 5% — это
 * удалённые файлы. Отрицание должно разбираться **до** модели, и результат должен
 * быть виден человеку до исполнения.
 */

/** Что делает «не» во фразе. */
export type Polarity =
  /** Обычное действие: «удали отчёты». */
  | "do"
  /** Запрет: «не удаляй отчёты». */
  | "dont"
  /** Условие ожидания: «не отправляй, пока не проверю». */
  | "wait"
  /** Смягчение, не отрицание: «не то чтобы срочно». */
  | "soften"
  /** Непонятно — спросить. */
  | "unclear";

/** Разбор отрицания. */
export interface Negation {
  /** Что значит «не». */
  polarity: Polarity;
  /** Слово, к которому относится «не» (глагол), — или `null`. */
  target: string | null;
  /** Почему решено так — для показа человеку и для теста. */
  why: string;
}

/**
 * Слова, после которых «не» — **не запрет**.
 *
 * «Не то чтобы», «не только», «не совсем» — это смягчение и усиление. Ошибка
 * тут дешевле запрета, но всё равно ошибка: «не только найди» — это «найди и
 * ещё что-то», а не «не ищи».
 */
const SOFTENERS = [
  /не то чтобы/i,
  /не только/i,
  /не совсем/i,
  /не очень/i,
  /не столько/i,
  /ничего страшного/i,
];

/**
 * Конструкция ожидания: «не делай, пока не …».
 *
 * Это **условие**, а не отмена: «не отправляй, пока не проверю» значит
 * «подожди». Простое «есть «не» → запрет» тут даёт противоположный ответ.
 */
const WAIT = /не\s+\S+\s*,?\s*(?:пока|до тех пор, пока)\s+не/i;

/** Глаголы, к которым относится «не»: запрет действия. */
const ACTION_VERBS =
  /(?:удал|сотр|стер|отправ|перезапиш|замен|перемест|скопир|оплат|перевед|куп|запуст|выключ|включ|закр|откры|выполн|загруз|установ|синхрон)/i;

/**
 * Разбор отрицания.
 *
 * `target` — слово, к которому «не» относится. Для «не удаляй отчёты» это
 * «удаляй»: запрет относится к действию, а не к объекту.
 */
export function parse(phrase: string): Negation {
  const clean = phrase.trim();
  if (clean.length === 0) {
    return { polarity: "do", target: null, why: "фразы нет — и отрицать нечего" };
  }

  if (!/не|без|ни/i.test(clean)) {
    return { polarity: "do", target: null, why: "отрицания во фразе нет" };
  }

  for (const pattern of SOFTENERS) {
    const found = pattern.exec(clean);
    // Смягчение — не отрицание действия: «не только найди» — это «найди и ещё».
    if (found !== null) {
      return { polarity: "soften", target: null, why: `«${found[0]}» — смягчение, а не запрет` };
    }
  }

  const wait = WAIT.exec(clean);
  if (wait !== null) {
    const verb = ACTION_VERBS.exec(wait[0]);
    return {
      polarity: "wait",
      target: verb ? verb[0] : null,
      why: "«не … пока не» — это условие: подождать, а не отменить",
    };
  }

  // «Без копии» — не запрет, а **условие выполнения**: сделать и не создавать копию.
  const without = /(?:^|\s)без\s+(\p{L}+)/iu.exec(clean);
  if (without !== null) {
    return {
      polarity: "do",
      target: without[1] ?? null,
      why: `«без ${without[1] ?? ""}» — делать, но этого не создавать`,
    };
  }

  const notVerb = /(?:^|\s)(?:не|ни)\s+(\p{L}+)/iu.exec(clean);
  if (notVerb !== null) {
    const word = notVerb[1] ?? "";
    // «Не удаляй» — запрет действия; «не отчёты» — отрицание объекта, и это
    // другой разбор, но всё равно **не** «удали».
    if (ACTION_VERBS.test(word)) {
      return { polarity: "dont", target: word, why: `«не ${word}» — запрет действия, а не просьба` };
    }
    // «Не отчёты», «не знаю» — «не» относится не к действию, и понять его
    // однозначно нельзя. Запрет тут был бы догадкой, а догадка при отрицании
    // стоит стёртого файла.
    return {
      polarity: "unclear",
      target: word,
      why: `«не ${word}» — не запрет действия: непонятно, к чему относится «не»`,
    };
  }

  return { polarity: "unclear", target: null, why: "во фразе есть «не», но к чему оно — непонятно; переспрошу" };
}

/**
 * Можно ли исполнять без вопроса.
 *
 * `dont` и `wait` — **нет**: это самое дорогое место. `soften` — да, это не
 * запрет. `unclear` — нет: переспросить дешевле, чем стереть.
 */
export function canDo(negation: Negation): boolean {
  return negation.polarity === "do" || negation.polarity === "soften";
}

/**
 * Что сказать человеку.
 *
 * Запрет **назван** (иначе человек не поймёт, почему ничего не произошло), а
 * ожидание — **с условием**, иначе он будет ждать вечно.
 */
export function say(negation: Negation): string {
  switch (negation.polarity) {
    case "do":
      return negation.target !== null
        ? `сделаю, но без этого: ${negation.target}`
        : "отрицания нет — делаю, как просили";
    case "dont":
      return `не буду: во фразе запрет («не ${negation.target ?? ""}»). Если это ошибка распознавания — скажите заново`;
    case "wait":
      return "подожду: вы просите не делать, пока не проверите — это условие, а не отмена";
    case "soften":
      return "это не запрет, а смягчение — делаю";
    case "unclear":
      return "во фразе есть «не», но непонятно, к чему оно. Не угадываю: переспрошу, потому что здесь цена ошибки — стёртое";
  }
}

/**
 * Опаснее ли ошибка в эту сторону.
 *
 * Названо, чтобы при правках не поменять местами: **сделать лишнее опаснее, чем
 * не сделать**. Пропущенный запрет — это стёртое; пропущенное действие — это
 * повторное «сделай».
 */
export function risk(negation: Negation): "safe" | "danger" {
  return canDo(negation) ? "safe" : "danger";
}
