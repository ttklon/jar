/**
 * Шаг 409: профиль не мешает основному сценарию — один человек ничего не выбирает.
 *
 * Главная опасность профилей — превратить простое приложение в систему с входом.
 * Человек один, ему нужно «почисти загрузки», а программа сначала спрашивает,
 * кто он. Это ровно тот случай, когда новая функция ухудшает продукт.
 *
 * Правило: **пока Profiles.length === 1, ни одного вопроса про людей нет**.
 * Ни «выберите профиля», ни бейджа «Анна» в углу, ни строки «профиль: я» в
 * настройках. Профиль существует, но не показывается.
 *
 * И второе правило: **переход к нескольким людям — тоже без вопроса**. Второй
 * профиль появляется, когда его заводят явно, а не когда приложение решило, что
 * «пора». До этого момента на экране нет ни слова про людей.
 */

import type { Profile } from "./peopleProfiles";

/**
 * Что показывать.
 *
 * `people` — заголовок про людей, `switcher` — переключатель, `hint` — подсказка
 * про профили. Всё пустое при одном человеке.
 */
export interface Shown {
  readonly people: boolean;
  readonly switcher: boolean;
  readonly hint: boolean;
  readonly said: string;
}

/**
 * Видно ли что-нибудь про людей.
 *
 * При одном профиле — ничего. При двух и больше — переключатель, потому что без
 * него нельзя выбрать.
 */
export function shown(profiles: readonly Profile[]): Shown {
  if (profiles.length <= 1) {
    return { people: false, switcher: false, hint: false, said: "человек один: на экране ничего про профили — основной сценарий не меняется" };
  }
  return { people: true, switcher: true, hint: false, said: `на компьютере ${profiles.length} человек: переключатель виден, но вопрос задаётся только перед опасным делом` };
}

/**
 * Первый запуск при одном человеке.
 *
 * Ничего не спрашиваем: имя — единственный вопрос (шаг 37), и он про человека, а
 * не про профиль.
 */
export function firstRun(): { questions: number; said: string } {
  return { questions: 1, said: "один вопрос — «как тебя называть?»; профиль создаётся сам, без выбора" };
}

/**
 * Когда появляется второй профиль.
 *
 * Только явно: человек нажал «добавить человека». Не «через N дел», не «если имя
 * не похоже».
 */
export function addWhen(): string {
  return "второй профиль появляется только по явному «добавить человека»: приложение не решает за человека, что пора";
}

/**
 * Что не меняется при одном человеке.
 *
 * Список — приёмочный: каждая строка была бы регрессией.
 */
export function unchanged(): string[] {
  return [
    "ни одного вопроса про профиль: ни при запуске, ни перед делом",
    "ни бейджа в углу, ни строки «профиль: я» в настройках",
    "дело выполняется от «я» — и это нигде не требуется подтверждать",
  ];
}

/**
 * Что меняется при двух.
 *
 * Тоже список, чтобы было видно: усложнение ровно там, где нужно.
 */
export function changes(): string[] {
  return ["перед опасным делом — вопрос «это вы?» (шаг 402)", "права и память — по человеку", "в журнале появляется, кто попросил"];
}
