/**
 * Свой словарь: человек добавляет имена файлов и программ (шаг 57).
 *
 * Дефект. У каждого есть слова, которых нет ни в одном общем словаре: имя
 * проекта, фамилия клиента, «Квартал-3», «диплом_финал». Распознавание их не
 * знает и слышит «квартал три», «диплом финал», а то и вовсе другое слово. И
 * человек ничего не может с этим сделать: правка общего словаря — не его дело,
 * а повторять фразу громче бесполезно.
 *
 * Правило: свой словарь **принадлежит человеку**.
 *
 *  1. Добавляется **как слышится**: человек вводит слово так, как его
 *     произносит, а не так, как оно пишется в файле. «Диплом финал» — законная
 *     запись, даже если файл называется `диплом_финал.docx`.
 *  2. Добавленное **сразу работает**: без перезапуска и без «применить».
 *     Отложенное действие — это действие, которое не сделают.
 *  3. Добавленное **видно и удаляется** одной кнопкой: словарь, который нельзя
 *     почистить, через месяц полон мусора и хуже пустого.
 *  4. Сказано, **сколько слов** и **сколько ещё поместится**: без числа человек
 *     не знает, кончилось место или он что-то сделал не так.
 *  5. Слово **не обязано быть уникальным**: если человек добавил «отчёт», а
 *     потом «отчёт квартал», оба остаются — выкидывать чужое слово за него
 *     нельзя.
 *
 * Почему не «просто подсказывать всё, что есть в папках». Папка с тысячей
 * файлов даст тысячу терминов, и подсказка перестанет помогать (шаг 56:
 * длинный список вредит). Словарь — то, что человек **выбрал сам**, и потому
 * он короткий и точный.
 */

/**
 * Сколько слов человек может добавить.
 *
 * Не технический предел, а смысловой: словарь из сотни слов перестаёт быть
 * «своим» и становится вторым общим. Пятьдесят — это уже много для одного
 * человека, и предел назван числом, чтобы не было сюрприза.
 */
export const MAX_WORDS = 50;

/** Самое длинное слово: длиннее — это уже фраза, а не термин. */
export const MAX_LENGTH = 40;

/** Что получилось при добавлении. */
export type Added =
  | { ok: true; words: string[]; said: string }
  | { ok: false; words: string[]; why: string };

/**
 * Привести слово к тому виду, в каком его храним.
 *
 * Убираем лишние пробелы и кавычки — человек копирует имя файла и приносит их с
 * собой. Регистр **сохраняем**: «Квартал-3» и «квартал-3» человек пишет
 * по-разному не случайно, а подсказке регистр безразличен.
 */
export function clean(word: string): string {
  return word
    .trim()
    .replace(/^[«"']+|[»"']+$/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Добавить слово.
 *
 * Все отказы названы **причиной и путём**, а не «нельзя»: человек должен
 * выйти из тупика сам.
 */
export function add(words: readonly string[], word: string): Added {
  const value = clean(word);
  const list = [...words];

  if (value.length === 0) {
    return { ok: false, words: list, why: "слово пустое — впишите его так, как произносите" };
  }
  if (value.length > MAX_LENGTH) {
    return {
      ok: false,
      words: list,
      why: `слишком длинно — не больше ${MAX_LENGTH} знаков, иначе это уже фраза, а не слово`,
    };
  }
  if (list.some((have) => have.toLowerCase() === value.toLowerCase())) {
    // Не ошибка, а «уже есть»: человек мог забыть, что добавил.
    return { ok: false, words: list, why: `«${value}» уже в словаре — добавьте другое слово` };
  }
  if (list.length >= MAX_WORDS) {
    return {
      ok: false,
      words: list,
      why: `словарь полон (${MAX_WORDS} слов) — удалите ненужное, чтобы добавить новое`,
    };
  }

  list.push(value);
  return { ok: true, words: list, said: `«${value}» добавлено — теперь распознаю его точнее` };
}

/**
 * Удалить слово.
 *
 * Удаляем по точному совпадению без учёта регистра: человек нажимает крестик у
 * слова, а не пишет его заново.
 */
export function remove(words: readonly string[], word: string): string[] {
  const value = clean(word).toLowerCase();
  return words.filter((have) => have.toLowerCase() !== value);
}

/**
 * Что сказать про словарь — всегда с числом.
 *
 * Без числа человек не знает, кончилось место или он что-то сделал не так.
 */
export function status(words: readonly string[]): string {
  if (words.length === 0) {
    return "свой словарь пуст — добавьте имена программ и файлов, которые плохо распознаются";
  }
  const left = MAX_WORDS - words.length;
  if (left === 0) return `${words.length} из ${MAX_WORDS} слов — словарь полон`;
  return `${words.length} из ${MAX_WORDS} слов, ещё ${left}`;
}

/**
 * Слова для подсказки распознавателю (шаг 56).
 *
 * Как есть, в порядке добавления: человек добавлял их по важности для себя, и
 * порядок — единственный сигнал важности, который у нас есть.
 */
export function terms(words: readonly string[]): string[] {
  return words.map(clean).filter((word) => word.length > 0);
}

/** Ключ, под которым словарь живёт между запусками. */
export const STORE_KEY = "zshelper.asr.words";

/** Минимум от `Storage`, чтобы не тянуть тип браузера в правило. */
interface StorageLike {
  getItem(key: string): string | null;
  setItem(key: string, value: string): void;
}

/**
 * Прочитать словарь.
 *
 * Битое хранилище — пустой словарь, а не падение: словарь — подсказка, и его
 * потеря не повод не запускаться. Читаем только строки: если в хранилище
 * окажется что-то другое, не тащим это дальше в подсказку.
 */
export function load(storage: StorageLike | null): string[] {
  if (!storage) return [];
  try {
    const raw = storage.getItem(STORE_KEY);
    if (raw === null) return [];
    const parsed: unknown = JSON.parse(raw);
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((word): word is string => typeof word === "string").slice(0, MAX_WORDS);
  } catch {
    return [];
  }
}

/** Записать словарь. Ошибку записи глотаем: правило важнее сохранности. */
export function save(storage: StorageLike | null, words: readonly string[]): void {
  if (!storage) return;
  try {
    storage.setItem(STORE_KEY, JSON.stringify(words.slice(0, MAX_WORDS)));
  } catch {
    // Место кончилось или хранилище запрещено — словарь поработает до перезапуска.
  }
}
