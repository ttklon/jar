/**
 * Сбой шага не скрывает, что уже сделано до него (шаг 119).
 *
 * Дефект. Провал в середине плана прячет всё, что было до него:
 *
 *  * **отчёт начинается с провала**: экран говорит «не получилось», и человек идёт
 *    делать заново то, что уже сделано — двойная работа;
 *  * **сделанное не названо**: три шага создали папки, переместили файлы, а
 *    сообщение — «ошибка на шаге 4», и неизвестно, на что опереться;
 *  * **откат наугад**: отменять нечего или, хуже, отменяют то, что нужно было
 *    оставить (шаг 120 — связать с откатом);
 *  * **провал и «неизвестно» смешаны**: часть шагов не проверялась (шаг 118), и
 *    «сделано 3» без «неизвестно 1» — неточный отчёт.
 *
 * Правило: **провал сообщается вместе со сделанным, а не вместо него**.
 *
 *  1. **Сначала сделанное**, потом провал: человеку нужно знать, на что опереться,
 *     чтобы решить, что делать дальше.
 *  2. **Сделанное названо по шагам**, а не числом без предметов: «создал папку
 *     Отчёты, перенёс 12 файлов» — это опора, «сделано 3» — нет.
 *  3. **Провал не отменяет сделанного**: отчёт не начинает с «ошибка» и не
 *     перечёркивает то, что получилось.
 *  4. **Неизвестное считается отдельно** (118): «сделано 3, неизвестно 1, провал на
 *     5-м» — три факта, а не один.
 *  5. **Дальше — предложение**, а не только констатация: что можно сделать с тем,
 *     что уже есть (продолжить с провалившегося, откатить, оставить как есть).
 *
 * Почему не «показать только ошибку». Ошибка без контекста заставляет человека
 * выяснять состояние мира самому — а приложение это состояние **уже знает**.
 */

import type { Tally } from "./threeWords";

/** Шаг в отчёте — то, что нужно для рассказа о сбое. */
export interface StepReport {
  /** Номер в плане, с единицы — как на экране. */
  position: number;
  /** Что делал — словами. */
  what: string;
  /** Итог: сделано / не сделано / неизвестно. */
  answer: "сделано" | "не сделано" | "неизвестно";
  /** Почему не сделано, если так. */
  reason?: string;
}

/** Что было до сбоя и где он. */
export interface Story {
  /** Шаги, которые удались, — по порядку. */
  done: StepReport[];
  /** Где провал: номер и причина. `null` — провала нет. */
  failed: StepReport | null;
  /** Неизвестные шаги — отдельно от провала. */
  unsure: StepReport[];
  /** Что ещё не начиналось. */
  left: number;
  /** Итог словами — **начиная со сделанного**. */
  said: string[];
  /** Что можно сделать дальше. */
  next: string[];
}

/**
 * Рассказать, что было до сбоя.
 *
 * Порядок строк — часть правила: сделанное идёт **до** провала, иначе человек
 * прочитает «не получилось» и не узнает, что получилось.
 */
export function tell(steps: readonly StepReport[], tally: Tally): Story {
  const done = steps.filter((step) => step.answer === "сделано");
  const failed = steps.find((step) => step.answer === "не сделано") ?? null;
  const unsure = steps.filter((step) => step.answer === "неизвестно");
  const left = Math.max(0, tally.total - steps.length);

  const said: string[] = [];
  if (done.length === 0) {
    // Нечего скрывать и нечего хвалить: так и сказано.
    said.push("до сбоя ничего не сделано");
  } else {
    said.push(`сделано до сбоя: ${done.length} — ${done.map((step) => step.what).join("; ")}`);
  }
  if (failed !== null) {
    said.push(`не сделано: шаг ${failed.position} «${failed.what}» — ${failed.reason ?? "причина не названа"}`);
  }
  if (unsure.length > 0) {
    // Неизвестное — не провал и не успех: отдельный факт (шаг 118).
    said.push(`неизвестно: ${unsure.length} — ${unsure.map((step) => `шаг ${step.position}`).join(", ")}`);
  }
  if (left > 0) said.push(`не начиналось: ${left}`);

  const next: string[] = [];
  if (failed !== null) {
    if (done.length > 0) {
      // Сделанное остаётся, и продолжать можно с провала, а не с начала.
      next.push(`продолжить с шага ${failed.position}: сделанное до него останется`);
    } else {
      next.push(`повторить шаг ${failed.position} — до него ничего не сделано`);
    }
  }
  if (unsure.length > 0) {
    next.push("проверить неизвестные шаги — по ним «готово» сказать нельзя");
  }
  if (done.length > 0) {
    // Откат — отдельное решение, и оно не должно выглядеть единственным.
    next.push("откатить сделанное — но это отдельное решение, а не отмена сбоя");
  }

  return { done, failed, unsure, left, said, next };
}

/**
 * Короткая строка для ленты.
 *
 * Одна строка, но **со сделённым впереди**: лента читается сверху вниз, и «ошибка»
 * первой строкой прячет работу.
 */
export function line(story: Story): string {
  const parts: string[] = [];
  if (story.done.length > 0) parts.push(`сделано ${story.done.length}`);
  if (story.failed !== null) parts.push(`сбой на шаге ${story.failed.position}`);
  if (story.unsure.length > 0) parts.push(`неизвестно ${story.unsure.length}`);
  if (story.left > 0) parts.push(`не начиналось ${story.left}`);
  return parts.length === 0 ? "шагов не было" : parts.join(", ");
}

/**
 * Можно ли продолжать с провалившегося шага.
 *
 * Да, если до него всё сделано: продолжение с шага 4 при неизвестном шаге 2 сделало
 * бы отчёт неправдой.
 */
export function resumable(story: Story): { ok: boolean; why: string } {
  if (story.failed === null) return { ok: false, why: "провала нет — продолжать нечего" };
  if (story.unsure.length > 0) {
    return { ok: false, why: "есть неизвестные шаги: сначала проверю их, иначе продолжение сделает отчёт неправдой" };
  }
  return { ok: true, why: `продолжу с шага ${story.failed.position}: сделанное до него останется` };
}
