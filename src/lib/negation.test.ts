import { describe, expect, it } from "vitest";
import { canDo, parse, risk, say } from "./negation";

/**
 * Шаг 84: понимать отрицание.
 *
 * «Не удаляй отчёты» сегодня исполняется как «удали отчёты» — цена ошибки не в
 * секунде, а в стёртом файле.
 */
describe("«не» относится к глаголу, а не к фразе целиком", () => {
  it("«не удаляй отчёты» — запрет действия", () => {
    const got = parse("не удаляй отчёты");
    expect(got.polarity).toBe("dont");
    expect(got.target).toContain("удаляй");
    expect(canDo(got)).toBe(false);
  });

  it("без «не» — обычное действие", () => {
    expect(parse("удали отчёты").polarity).toBe("do");
    expect(canDo(parse("удали отчёты"))).toBe(true);
  });

  it("запрет объяснён человеку, чтобы он понял, почему ничего не было", () => {
    // Иначе «ничего не произошло» выглядит как поломка.
    expect(say(parse("не удаляй отчёты"))).toContain("не буду");
    expect(say(parse("не удаляй отчёты"))).toContain("запрет");
  });
});

describe("«без копии» — условие, а не запрет", () => {
  it("делать, но не создавать копию", () => {
    const got = parse("перемести файлы без копии");
    expect(got.polarity).toBe("do");
    expect(got.target).toBe("копии");
    expect(canDo(got)).toBe(true);
    expect(say(got)).toContain("без этого");
  });
});

describe("двойное отрицание — условие ожидания", () => {
  it("«не отправляй, пока не проверю» значит «подожди», а не «отмени»", () => {
    // Простое «есть «не» → запрет» тут даёт противоположный ответ.
    const got = parse("не отправляй, пока не проверю");
    expect(got.polarity).toBe("wait");
    expect(got.why).toContain("подождать");
  });

  it("ожидание объяснено условием, иначе человек будет ждать вечно", () => {
    expect(say(parse("не отправляй, пока не проверю"))).toContain("пока не проверите");
  });
});

describe("не всякое «не» — запрет", () => {
  it("«не только» — смягчение, действие разрешено", () => {
    // «Не только найди» — это «найди и ещё что-то», а не «не ищи».
    const got = parse("не только найди, но и открой");
    expect(got.polarity).toBe("soften");
    expect(canDo(got)).toBe(true);
  });

  it("«не то чтобы срочно» — тоже смягчение", () => {
    expect(parse("не то чтобы срочно, отправь письмо").polarity).toBe("soften");
  });
});

describe("сомнение — переспросить, а не угадать", () => {
  it("непонятное «не» не исполняется", () => {
    // Угадывание при отрицании — та ошибка, после которой удаляют приложение.
    const got = parse("не знаю, может, отчёты");
    expect(canDo(got)).toBe(false);
    expect(say(got)).toContain("Не угадываю");
  });

  it("пустая фраза — не отрицание", () => {
    expect(parse("").polarity).toBe("do");
  });
});

describe("в какую сторону ошибка опаснее", () => {
  it("сделать лишнее опаснее, чем не сделать", () => {
    // Пропущенный запрет — это стёртое; пропущенное действие — повторное «сделай».
    expect(risk(parse("не удаляй"))).toBe("danger");
    expect(risk(parse("удали"))).toBe("safe");
  });
});
