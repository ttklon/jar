/**
 * Сон машины: как заметить, что мы вернулись, и не спутать это с обычным
 * переключением окна (шаг 142).
 *
 * Почему не событие ОС. Tauri на десктопе не отдаёт кроссплатформенного события
 * «машина проснулась» двоичным путём: на Windows это отдельный Win32-вызов, на
 * macOS — своя нотификация, и половина из этого не переживает сборку без
 * платформенных зависимостей. Заводить три реализации ради одного вопроса
 * значило бы завести три места, где ответ может разойтись.
 *
 * Почему не фоновый цикл. Шаг 384 требует, чтобы в простое не было регулярной
 * работы: таймер, тикающий всегда, тратит батарею и не даёт машине уснуть.
 *
 * Что остаётся: **разрыв во времени**. Пока окно невидимо, мы запоминаем
 * мгновение; когда оно снова видно — сравниваем, сколько прошло. Обычное
 * переключение окна — это секунды и минуты. Сон — часы. Порог и есть ответ на
 * вопрос «спала ли машина», и он чистый: его видно без ОС и без настоящего сна.
 *
 * Здесь только правило. Кто его зовёт и что делает после — решает вызывающий.
 */

/** Через сколько «нас не было» считаем, что машина спала, а не окно было свёрнуто. */
export const SLEEP_AFTER_MS = 5 * 60 * 1000;

/**
 * Сколько прошло между уходом и возвращением — и спала ли машина.
 *
 * `leftMs` — когда окно стало невидимым. `nowMs` — когда снова стало видимым.
 * Оба — `Date.now()`, то есть **настенные** часы: `performance.now()` в браузере
 * не идёт, пока страница скрыта, и разрыв им не измерить.
 */
export interface Away {
  /** Сколько миллисекунд окно было невидимо. Отрицательное значение — часы перевели назад. */
  awayMs: number;
  /** Считаем ли, что машина спала. */
  slept: boolean;
  /** Почему решили так — словами, для журнала. */
  why: string;
}

/**
 * Разрыв во времени и вывод из него.
 *
 * Отдельной функцией, а не внутри обработчика: правило «сон или переключение»
 * — то, что легко сделать неправильно (например, считать сном любую потерю
 * фокуса, и тогда перезапуск движка случался бы при каждом Alt+Tab).
 */
export function awayFor(leftMs: number, nowMs: number): Away {
  const awayMs = nowMs - leftMs;

  if (awayMs < 0) {
    // Часы перевели назад (перевод времени, ручная правка, синхронизация).
    // Это не сон, и «прошло −3600 секунд» — не факт, а сломанные часы.
    return {
      awayMs,
      slept: false,
      why: "часы переведены назад — по разрыву судить нельзя",
    };
  }

  if (awayMs < SLEEP_AFTER_MS) {
    return {
      awayMs,
      slept: false,
      why: `окна не было ${Math.round(awayMs / 1000)} с — это переключение, а не сон`,
    };
  }

  return {
    awayMs,
    slept: true,
    why: `окна не было ${Math.round(awayMs / 60000)} мин — похоже на сон машины`,
  };
}

/**
 * Проверять ли движок при возвращении.
 *
 * Отдельно от `awayFor`, потому что это второе правило и его хочется видеть
 * отдельно: спала ли машина — факт, а идти ли из-за этого к движку — решение.
 * Если человек не разговаривал, движка могло и не быть, и дёргать ядро на
 * каждое возвращение к окну незачем.
 */
export function shouldCheckAfterWake(away: Away, talking: boolean): boolean {
  return away.slept && talking;
}

/**
 * Подписка на возвращение окна. Возвращает функцию отписки.
 *
 * Замер ведётся только пока окно скрыто: один `Date.now()` при уходе и один при
 * возвращении. Никаких таймеров — в простое работа не идёт.
 */
export function watchWake(
  onWake: () => void,
  options: { talking: () => boolean; now?: () => number; doc?: Document } = {
    talking: () => true,
  },
): () => void {
  const doc = options.doc ?? (typeof document === "undefined" ? null : document);
  if (!doc) return () => {};

  const now = options.now ?? (() => Date.now());
  let leftMs: number | null = null;

  const onChange = () => {
    if (doc.visibilityState === "hidden") {
      leftMs = now();
      return;
    }
    if (doc.visibilityState !== "visible") return;

    // Окно стало видимым, но до этого мы его не покидали: первый показ при
    // запуске. Сравнивать не с чем — и это не сон.
    if (leftMs === null) return;

    const away = awayFor(leftMs, now());
    leftMs = null;
    if (shouldCheckAfterWake(away, options.talking())) onWake();
  };

  doc.addEventListener("visibilitychange", onChange);
  return () => doc.removeEventListener("visibilitychange", onChange);
}
