/**
 * Шаг 301: установщик без прав администратора и без перезагрузки.
 *
 * Дефект, который видно только на чужой машине: программа, поставленная «для
 * всех пользователей», просит UAC-окно. На домашнем ноутбуке человек нажимает
 * «Да» не читая, на рабочем — не может вообще: администратора нет, и установка
 * заканчивается ничем. А «требуется перезагрузка» после установки помощника,
 * который ничего не драйверит, — просто признание, что мы что-то сделали не так.
 *
 * Правила:
 *
 *  1. **своё место, свои права**: установка в `%LOCALAPPDATA%` — это папка
 *     человека, и прав администратора для неё не бывает;
 *  2. **UAC не «попросим на всякий случай»**: если установщик просит повышение,
 *     это ошибка сборки, а не поведение;
 *  3. **перезагрузка не нужна и не предлагается.** Нужна она драйверам и
 *     службам; помощнику — нет;
 *  4. **если понадобилось — сказать почему**, а не «запустите от имени
 *     администратора»: человек должен понимать, зачем.
 */

/** Что установщик собирается делать. */
export interface Plan {
  /** Куда ставим — путь. */
  readonly path: string;
  /** Что ставим: приложение, движок, ярлыки. */
  readonly adds: readonly string[];
  /** Есть ли в сборке что-то, что требует службы или драйвера. */
  readonly driver: boolean;
}

/** Где живёт установка по умолчанию. */
export const PER_USER = "%LOCALAPPDATA%\\ZShelper";

/** Проверка плана установки. */
export function check(plan: Plan): { ok: boolean; problems: string[] } {
  const problems: string[] = [];

  if (!plan.path.startsWith("%LOCALAPPDATA%")) {
    problems.push(`путь «${plan.path}» вне профиля человека: для него понадобятся права администратора`);
  }
  if (plan.driver) {
    problems.push("в сборке драйвер или служба — это как раз тот случай, когда повышение прав нужно, и это надо назвать");
  }
  if (plan.adds.length === 0) problems.push("не сказано, что устанавливается");

  return { ok: problems.length === 0, problems };
}

/** Нужны ли права администратора. */
export function needsAdmin(plan: Plan): boolean {
  return plan.driver || !plan.path.startsWith("%LOCALAPPDATA%");
}

/**
 * Что сказать до установки.
 *
 * Одна строка, без «возможно» и «в некоторых случаях»: человек решает, ставить ли,
 * по этому тексту.
 */
export function before(plan: Plan): string {
  if (needsAdmin(plan)) {
    return "понадобятся права администратора: без них установка не пройдёт (в обычной сборке их не требуется)";
  }
  return `устанавливается в вашу папку ${plan.path}: права администратора не нужны, перезагрузка не нужна`;
}

/**
 * Перезагрузка после установки.
 *
 * Ноль — это ответ, а не отсутствие ответа: если код где-то просит перезагрузку
 * для помощника, это ошибка, и её надо назвать, а не «перезагрузите на всякий».
 */
export function rebootNeeded(plan: Plan): { needed: boolean; why: string } {
  if (plan.driver) return { needed: true, why: "драйвер вступает в силу только после перезагрузки — это цена драйвера, а не помощника" };
  return { needed: false, why: "перезагрузка не нужна: ничего не меняет систему целиком" };
}

/**
 * Ярлыки и путь в реестре — без прав.
 *
 * `HKCU` вместо `HKLM`: это тот же реестр, только раздел человека.
 */
export function whereMarks(): { registry: string; shortcuts: string; why: string } {
  return {
    registry: "HKCU\\Software\\ZShelper",
    shortcuts: "%APPDATA%\\Microsoft\\Windows\\Start Menu\\Programs",
    why: "раздел человека, а не машины: писать в него можно без администратора",
  };
}
