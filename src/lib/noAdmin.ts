/**
 * Шаг 449: никаких прав администратора без явной причины и объяснения.
 *
 * Windows программы любят просить администратора «на всякий случай» — и теряют
 * половину пользователей: запрос UAC у человека без прав администратора означает
 * «программа не работает». Домашние пользователи зачастую не админы вовсе.
 *
 * Поэтому запрос UAC — **исключение с объяснением**, и правило простое: если
 * действие можно сделать без администратора, его надо делать без него.
 *
 * Три действия действительно требуют:
 *
 *  * установка в `Program Files`;
 *  * обновление для всех пользователей (HKLM);
 *  * изменение системы (сеть, файрвол) — если такого дела вообще просят.
 *
 * Всё остальное (память, модели, автозапуск в HKCU, дела с файлами в домашней
 * папке) — не требует, и просить его нельзя.
 */

/** Действие. */
export type Action = "install" | "updateAll" | "updateMe" | "memory" | "model" | "autostart" | "files" | "systemChange";

/**
 * Нужен ли администратор.
 *
 * `why` у отказа — **что делать вместо**: «выберите папку в домашней» понятнее,
 * чем «нужны права».
 */
export function needs(action: Action): { needed: boolean; why: string; alternative?: string } {
  switch (action) {
    case "install":
      return { needed: true, why: "запись в Program Files — единственное, что нельзя сделать без администратора", alternative: "поставить для одного пользователя в %LOCALAPPDATA% — без запроса UAC" };
    case "updateAll":
      return { needed: true, why: "обновление для всех пользователей меняет Program Files", alternative: "обновиться только для себя — без администратора" };
    case "systemChange":
      return { needed: true, why: "изменение системы (сеть, файрвол) без администратора невозможно", alternative: "сказать по шагам, как сделать самому, и не просить UAC" };
    case "updateMe":
    case "memory":
    case "model":
    case "autostart":
    case "files":
      return { needed: false, why: "делается в папке пользователя или в HKCU: администратор не нужен" };
  }
}

/**
 * Что сказать перед запросом UAC.
 *
 * Не «требуются права администратора» — а **что именно** будет сделано и почему
 * без этого не выйдет.
 */
export function explain(action: Action): string {
  const got = needs(action);
  if (!got.needed) return "администратор не нужен";
  const base = `понадобится разрешение Windows: ${got.why}`;
  return got.alternative ? `${base}. Можно иначе: ${got.alternative}` : base;
}

/**
 * Что делать, если человек отказал в UAC.
 *
 * Не «программа не установилась» — а что всё-таки можно.
 */
export function refused(action: Action): string {
  const got = needs(action);
  if (!got.alternative) return "без администратора это действие не сделать: скажем об этом прямо, а не будем просить снова";
  return `продолжу без администратора: ${got.alternative}`;
}

/**
 * Что не требует администратора.
 *
 * Список — приёмочный: каждый пункт был бы дефектом, если бы просил UAC.
 */
export function withoutAdmin(): string[] {
  return ["память и журнал", "скачивание и обновление модели", "автозапуск (HKCU)", "дела с файлами в домашней папке", "обновление только для себя"];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "UAC просится только у трёх действий из восьми",
    "у каждого запроса сказано, что именно будет сделано",
    "у отказа есть альтернатива, где она есть",
  ];
}
