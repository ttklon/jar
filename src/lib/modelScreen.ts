/**
 * Экран моделей: размер, лицензия, требования, замер на этой машине (шаг 71).
 *
 * Дефект. Человеку предлагают модели по названию и «примерно». Из этого нельзя
 * сделать выбор — а выбор здесь необратимый: скачанный файл на 4.7 ГБ занимает
 * диск, и «ой, не то» стоит часа загрузки.
 *
 * Правило: **четыре факта на модель**, и все четыре — те, по которым выбирают.
 *
 *  1. **Размер** — сколько скачивать и сколько займёт диск. Единственный факт,
 *     который человек действительно проверяет заранее.
 *  2. **Лицензия** — можно ли пользоваться и можно ли отдавать сделанное на ней
 *     другим. «Бесплатно» и «можно использовать» — разные вопросы.
 *  3. **Требования** — сколько нужно памяти. Без этого человек узнаёт
 *     нехватку после загрузки, а не до.
 *  4. **Замер на этой машине** — сколько будет ждать **он**, а не средний
 *     пользователь. Паспорт тут бесполезен (шаги 63, 65).
 *
 * Почему лицензия на экране, а не в «подробнее». Это единственный факт,
 * который может **запретить** использование, — и человек должен увидеть запрет
 * до скачивания, а не после.
 *
 * Почему нет звёздочек и рейтингов. Они не помогают выбрать на **этой** машине:
 * «4.5 звезды» на сильной машине и на 4 ГБ — разные модели.
 */

/** Что известно о модели. */
export interface Card {
  /** Имя, как его узнаёт человек. */
  name: string;
  /** Размер в мегабайтах: сколько скачивать и сколько займёт. */
  sizeMb: number;
  /** Лицензия — коротко, как её пишут в файлах моделей. */
  license: string;
  /** Нужно оперативной памяти, мегабайт. */
  needsMb: number;
  /** Замер на этой машине; `null` — не мерили. */
  measuredPerSecond: number | null;
  /** Что модель умеет — одно предложение, без рекламы. */
  good: string;
}

/**
 * Лицензия: можно ли пользоваться.
 *
 * Не «свободная/несвободная», а **что разрешено**: Apache-2.0 и MIT разрешают
 * коммерческое использование, и человеку это нужно знать, если он делает работу
 * для кого-то. Иные лицензии моделей запрещают коммерческое — и это **запрет**,
 * а не примечание.
 */
export interface Rights {
  /** Можно ли использовать в работе (в том числе за деньги). */
  commercial: boolean;
  /** Что сказать человеку: разрешение или запрет, словами. */
  said: string;
}

/**
 * Разбор лицензии.
 *
 * Список узкий и названный: неизвестная лицензия считается **запрещающей**, и
 * это осознанно. Ошибка в сторону «нельзя» стоит человеку минуты, ошибка в
 * сторону «можно» — нарушения лицензии.
 */
export function rights(license: string): Rights {
  const clean = license.trim().toLowerCase();
  if (clean === "" ) {
    return { commercial: false, said: "лицензия не указана — считаем, что использовать в работе нельзя" };
  }
  if (clean.startsWith("apache") || clean === "mit" || clean.startsWith("bsd")) {
    return { commercial: true, said: `лицензия ${license}: можно использовать и в работе` };
  }
  if (clean.includes("non-commercial") || clean.includes("nc")) {
    // Прямой запрет, и он должен стоять на экране, а не в примечании.
    return { commercial: false, said: `лицензия ${license}: только для личного, в работе нельзя` };
  }
  return {
    commercial: false,
    said: `лицензия ${license} — условия незнакомы, проверьте перед работой`,
  };
}

/**
 * Поместится ли на этой машине.
 *
 * Не «наверное, да»: сравнение с заявкой плюс небольшой запас. Запас здесь
 * меньше, чем в лестнице (шаг 63), потому что там считался размер целиком, а
 * здесь — заявленное требование.
 */
export const SPARE_MB = 512;

export function fitsHere(card: Card, availableMb: number): boolean {
  return card.needsMb + SPARE_MB <= availableMb;
}

/** Размер по-человечески: «1.1 ГБ», а не «1100 МБ». */
export function sizeWord(sizeMb: number): string {
  if (sizeMb < 1024) return `${sizeMb} МБ`;
  return `${Math.round((sizeMb / 1024) * 10) / 10} ГБ`;
}

/** Требование по-человечески. */
export function needsWord(card: Card): string {
  return `нужно ${sizeWord(card.needsMb)} памяти`;
}

/**
 * Что сказать про замер на этой машине.
 *
 * Названо, **мерили ли здесь**: «не мерили» честнее, чем паспорт, выданный за
 * замер.
 */
export function speedWord(card: Card): string {
  if (card.measuredPerSecond === null) return "на этой машине не мерили";
  return `на этой машине ${Math.round(card.measuredPerSecond * 10) / 10} ток/с`;
}

/**
 * Строки карточки — то, что человек читает.
 *
 * Порядок не случайный: сначала **можно ли** (лицензия), потом **влезет ли**
 * (требования), потом **сколько ждать** (замер) и только потом **что умеет**
 * (реклама). Если лицензия запрещает — остальное уже неважно.
 */
export function lines(card: Card, availableMb: number): string[] {
  const permit = rights(card.license);
  const fit = fitsHere(card, availableMb);
  return [
    `${card.name} — ${sizeWord(card.sizeMb)}`,
    permit.said,
    fit ? `${needsWord(card)} — помещается` : `${needsWord(card)} — на этой машине не помещается`,
    speedWord(card),
    card.good,
  ];
}

/**
 * Можно ли предложить карточку.
 *
 * Две причины отказа, и обе названы в строках: лицензия и нехватка памяти.
 * Предлагать модель, которая не помещается или которую нельзя использовать,
 * значит заставить человека скачать 4 ГБ зря.
 */
export function offered(card: Card, availableMb: number): boolean {
  return rights(card.license).commercial && fitsHere(card, availableMb);
}

/**
 * Что сказать, когда не предложено ничего.
 *
 * Названа причина и путь, а не «моделей нет»: чаще всего это нехватка памяти
 * или работа за деньги на лицензии «только для личного».
 */
export function nothingFits(availableMb: number): string {
  return `ни одна модель не подходит: свободной памяти ${sizeWord(availableMb)} — закройте программы или возьмите модель поменьше`;
}
