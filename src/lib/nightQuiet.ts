/**
 * Тише ночью (шаг 48).
 *
 * Мелочь, которая делает разницу: днём громкость ответа — личное дело, ночью —
 * общее. Человек говорит с приложением в час ночи, и приложение отвечает на всю
 * квартиру. Это не про удобство, а про то, что рядом спят.
 *
 * Правило нарочно **простое и предсказуемое**: тихие часы — с 22:00 до 7:00, и в
 * них громкость ниже. Не «по расписанию сна пользователя» (его нет), не «по
 * датчику освещённости» (его тоже нет) — по времени, которое человек может
 * назвать сам, если спросить.
 *
 * Что значит «тише». Не «выключено»: ответ, которого не слышно, — это отказ в
 * ответе, а не забота. И не «вдвое» — это догадка. Называется **доля**, и она
 * одна: 60% от обычной. Сказать «приглушено» без доли — то же «готово», от
 * которого мы ушли.
 *
 * Три исключения, и все три важны:
 *
 *  * **человек попросил громче** — просьба сильнее расписания;
 *  * **человек сказал, что не спит** (или сам включил ответы в полную силу) —
 *    правило про спящих рядом, а не про время как таковое;
 *  * **ответ идёт в наушники** — тогда соседей нет. Но наушники приложение
 *    определить не может, поэтому это не автоматическое исключение, а поле:
 *    без него правило было бы выдумкой.
 */

/** Тихие часы: с 22 вечера до 7 утра. */
export const QUIET_FROM = 22;
export const QUIET_TO = 7;

/** Громкость в тихие часы — доля от обычной. */
export const QUIET_SHARE = 0.6;

/** Что известно на момент решения. */
export interface Context {
  /** Час суток 0–23. */
  hour: number;
  /** Человек попросил полную громкость явно. */
  askedLouder: boolean;
}

/** Тихий ли час. Полночь — внутри: с 22 до 7, а не «с 22 до 24». */
export function quietHour(hour: number): boolean {
  const normalized = ((Math.floor(hour) % 24) + 24) % 24;
  return normalized >= QUIET_FROM || normalized < QUIET_TO;
}

/**
 * Какую долю громкости применить.
 *
 * `1` — полная, `QUIET_SHARE` — приглушённая. Больше `1` правило не возвращает:
 * «громче, чем обычно» — это настройка системы, а не наше дело.
 */
export function share(context: Context): number {
  if (context.askedLouder) return 1; // просьба сильнее расписания
  return quietHour(context.hour) ? QUIET_SHARE : 1;
}

/**
 * Как это назвать человеку.
 *
 * Сказано **и число, и почему**: «тише, потому что ночь» — это забота, а «тише» —
 * это поломка. И названо, как вернуть: иначе человек считает, что приложение
 * испортилось.
 */
export function quietLine(share_: number): string {
  if (share_ >= 1) return "громкость обычная";
  const percent = Math.round(share_ * 100);
  return `тише (${percent}% от обычной): сейчас тихие часы. Скажите «громче» — будет как обычно`;
}

/**
 * Следующий час, когда станет громче, — чтобы человек знал, сколько ждать.
 *
 * `null` — сейчас не тихо: ждать нечего.
 */
export function untilLoud(hour: number): string | null {
  if (!quietHour(hour)) return null;
  // До 7 утра — «в 7»; после 22 — тоже «в 7», потому что ночь переходит в утро.
  return `после ${QUIET_TO}:00`;
}
