import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import * as everything from "../i18n/ru";

/**
 * Шаг 218: никаких «рекомендованных» платных сервисов в интерфейсе.
 *
 * Тяжёлую проверку делает `tools/no_storefront.py` (весь словарь и разметка).
 * Здесь — то, что должно держаться **в самом словаре**, и то, что проверка не
 * ловит по определению: честная фраза «подписки нет» обязана существовать, иначе
 * молчание читается как «может, есть».
 */

const text = JSON.stringify(everything);

describe("витрины в словаре нет", () => {
  it("ни одного имени платного сервиса", () => {
    for (const name of ["OpenAI", "Anthropic", "ChatGPT", "Claude", "Gemini", "Copilot"]) {
      expect(text.toLowerCase()).not.toContain(name.toLowerCase());
    }
  });

  it("ни одной цены и ни одного тарифа", () => {
    // Проверяем **на исходнике**, а не на `JSON.stringify`: stringify превращает
    // перевод строки в `\n`, и `"0\n ₽"` перестаёт опознаваться как ноль —
    // наивная проверка падала на честном «бесплатно».
    const source = readFileSync(new URL("../i18n/ru.ts", import.meta.url), "utf8");
    // Ноль — честное «бесплатно» («0 ₽ — сейчас, через месяц и через год»).
    // Ноль стоит и после пробела, и после перевода строки («\n   */\n  0 ₽») —
    // поэтому исключается любой пробельный символ, а не только пробел.
    expect(source).not.toMatch(/(?<![\d.,])[1-9]\d*\s*(₽|руб|рублей|€)/);
    // `$` как валюта стоит **перед** числом; `2 $` в шаблоне — это `${…}` из кода.
    expect(source).not.toMatch(/\$\s*\d+(?![\w}])/);
    expect(text).not.toMatch(/тариф/i);
    expect(text).not.toMatch(/premium/i);
  });

  it("настоящая цена ловится, а ноль — нет: проверка не пустая", () => {
    // Иначе тест выше проходил бы на любой строке, включая ценник в 500 ₽.
    const price = /(?<![\d.,])[1-9]\d*\s*(₽|руб|рублей|€)/;
    expect(price.test("Тариф Pro: 500 ₽/мес")).toBe(true);
    expect(price.test("2990 руб")).toBe(true);
    expect(price.test("0 ₽ — бесплатно")).toBe(false);
  });

  it("ни одного партнёрского адреса", () => {
    expect(text).not.toMatch(/utm_|affiliate|partner_id|\?ref=/i);
  });
});

describe("но честный отказ от подписки назван", () => {
  it("сказано, что платить некому", () => {
    // Молчание про деньги читается как «может быть». Ответ должен быть словом.
    expect(text).toContain("Платить некому");
  });

  it("бесплатность названа нулём, а не словом «дёшево»", () => {
    expect(text).toContain("0 ₽");
  });
});
