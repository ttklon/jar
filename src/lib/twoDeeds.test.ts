import { describe, expect, it } from "vitest";
import { count, failed, plan, ready, says, split } from "./twoDeeds";

/**
 * Шаг 83: два дела в одной фразе — разложить и сделать по очереди.
 *
 * «Найди отчёт за март и отправь его маме» сегодня съедается целиком: вторая
 * половина теряется молча.
 */
describe("союз «и» — дело, только если дальше глагол", () => {
  it("два глагола — два дела", () => {
    const deeds = split("найди отчёт за март и отправь его маме");
    expect(count(deeds)).toBe(2);
    expect(deeds[0]?.intent.verb).toBe("найди");
    expect(deeds[1]?.intent.verb).not.toBe("неизвестно");
  });

  it("перечисление объектов — одно дело, а не два", () => {
    // «Найди отчёты и письма» — одно дело: после «и» не глагол.
    expect(count(split("найди отчёты и письма"))).toBe(1);
  });

  it("одно дело не ломается ради единообразия", () => {
    expect(count(split("открой загрузки"))).toBe(1);
    expect(count(split(""))).toBe(0);
  });

  it("«потом» и «затем» тоже делят", () => {
    expect(count(split("найди отчёт потом отправь его"))).toBe(2);
    expect(count(split("открой папку затем скопируй файл"))).toBe(2);
  });
});

describe("порядок сохраняется", () => {
  it("дела идут в том порядке, в котором сказаны", () => {
    // Человек сказал их в этом порядке не случайно.
    const deeds = split("найди отчёт и отправь его");
    expect(deeds[0]?.text).toContain("найди");
    expect(deeds[1]?.text).toContain("отправь");
  });

  it("список показан до исполнения", () => {
    // Иначе человек узнает о второй половине, когда она уже случилась.
    const lines = plan(split("найди отчёт и отправь его маме"));
    expect(lines[0]).toMatch(/^1\./);
    expect(lines[1]).toMatch(/^2\./);
    expect(lines.join(" ")).toContain("найди");
  });
});

describe("связь между делами не теряется", () => {
  it("«его» во второй половине указывает на первое", () => {
    const deeds = split("найди отчёт и отправь его маме");
    expect(deeds[1]?.usesPrevious).toBe(true);
  });

  it("второе дело не начинается, пока первое не готово", () => {
    // Иначе отправлять нечего.
    const deeds = split("найди отчёт и отправь его маме");
    expect(ready(deeds, 1, false)).toBe(false);
    expect(ready(deeds, 1, true)).toBe(true);
    expect(ready(deeds, 0, false)).toBe(true);
  });

  it("связь названа в списке дел", () => {
    expect(plan(split("найди отчёт и отправь его маме")).join(" ")).toContain("предыдущем");
  });
});

describe("первое не вышло — остановиться, а не продолжать", () => {
  it("второе опирается на первое — не начинаю", () => {
    // «Отправить что осталось» — это не то, что просили.
    const deeds = split("найди отчёт и отправь его маме");
    expect(failed(deeds, 0)).toContain("не начинаю");
  });

  it("второе не зависит — решает человек", () => {
    const deeds = split("открой папку и запусти программу");
    expect(failed(deeds, 0)).toContain("решайте вы");
  });

  it("последнее дело — и говорить не о чем", () => {
    expect(failed(split("открой папку"), 0)).toContain("дальше дел нет");
  });
});

describe("деление названо, а не молчаливое", () => {
  it("человеку сказано, что дел два", () => {
    // Молчаливое деление хуже: человек не понимает, почему что-то ещё делается.
    expect(says(split("найди отчёт и отправь его"))).toContain("2 дела");
    expect(says(split("открой папку"))).toBeNull();
  });
});
