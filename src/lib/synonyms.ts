/**
 * Синонимы: «почисти», «освободи место», «убери мусор» — одно намерение (шаг 93).
 *
 * Дефект. Реестр действий написан его авторами: «очистить корзину», «удалить
 * временные файлы», «найти крупные файлы». Человек говорит **своими словами**:
 * «почисти», «освободи место», «убери мусор», «место кончается». Слово «мусор»
 * в реестре не встречается ни разу — и разбор честно не находит ничего. Дальше:
 *
 *  * **человек обязан знать реестр**: чтобы что-то сделать, надо угадать, как это
 *    называется **у нас**, — а это внутренняя кухня;
 *  * **одно намерение живёт под десятью словами**, и каждое надо добавить
 *    отдельно, иначе «почисти» работает, а «место кончается» — нет;
 *  * **синонимы расходятся**: «почисти» тянет к «очистить», «освободи место» — к
 *    «найти крупные файлы», хотя просьба одна.
 *
 * Правило: **одно намерение — один ключ, и у ключа много слов**.
 *
 *  1. Ключ — **намерение**, а не действие реестра: `место`, `порядок`, `поиск`.
 *     Ключей должно быть мало, иначе это второй реестр.
 *  2. Слова — **как говорит человек**, включая грубые и неточные: «мусор»,
 *     «хлам», «распихнуть», «навести порядок».
 *  3. Слово из нескольких слов («освободи место») ищется **целиком**: «место» само
 *     по себе есть в «найди место в документе», и это другое намерение.
 *  4. Синоним **не подменяет действие**: он находит намерение, а что именно
 *     сделать — решает реестр и подтверждение. «Почисти» не значит «удали
 *     корзину» — это значит «навести порядок», и человек увидит шаги.
 *  5. Если слово **пересекается** с другим ключом — **спросить**, а не выбрать
 *     молча (шаг 95).
 *
 * Почему не «добавить примеры в реестр». Примеры — это по одному слову на
 * действие; синонимы нужны на **намерение**, и их порядок величины больше.
 */

/** Намерение — то, что человек хотел, а не то, как это действие называется. */
export type Intent =
  /** Освободить место: почистить, убрать мусор, удалить лишнее. */
  | "место"
  /** Навести порядок: разложить, отсортировать, переименовать. */
  | "порядок"
  /** Найти что-то. */
  | "поиск"
  /** Сделать копию или сохранить. */
  | "копия"
  /** Прочитать или посмотреть содержимое. */
  | "прочитать"
  /** Посчитать. */
  | "посчитать"
  /** Настроить. */
  | "настроить"
  /** Не понято. */
  | "неизвестно";

/**
 * Слова намерения.
 *
 * Порядок — от **более длинных** к коротким: «освободи место» должно сработать
 * раньше, чем «место» — иначе пересечение решается случайно.
 */
const WORDS: [RegExp, Intent][] = [
  // Место — самое частое намерение и самое опасное: оно кончается удалением.
  [/освободи(?:ть)?\s+(?:место|диск|память)/i, "место"],
  [/(?:место|диск|память)\s+(?:кончается|заканчивается|забит)/i, "место"],
  [/почист(?:и|ить|ка)/i, "место"],
  [/убери(?:те)?\s+(?:мусор|хлам|лишн)/i, "место"],
  [/(?:мусор|хлам|барахло)/i, "место"],
  [/удали(?:те)?\s+(?:лишн|старое|временн)/i, "место"],
  [/очист(?:и|ить)\s+(?:корзин|кэш|кеш|временн)/i, "место"],
  // Порядок.
  [/наведи(?:те)?\s+порядок/i, "порядок"],
  [/разложи(?:те)?\s+по\s+папкам/i, "порядок"],
  [/отсортируй(?:те)?/i, "порядок"],
  [/переименуй(?:те)?\s+по\s+порядку/i, "порядок"],
  // Поиск.
  [/найди|поищи|где\s+(?:лежит|находится)/i, "поиск"],
  // Копия.
  [/сделай\s+копию|скопируй|сохрани\s+копию/i, "копия"],
  [/заархивируй|сожми|упакуй/i, "копия"],
  // Прочитать.
  [/прочитай|покажи\s+содержимое|что\s+в\s+файле/i, "прочитать"],
  // Посчитать.
  [/посчитай|сколько\s+(?:файлов|места|папок)/i, "посчитать"],
  // Настроить.
  [/настрой|включи|выключи|поставь/i, "настроить"],
];

/**
 * Намерение фразы.
 *
 * Возвращает **все** ключи, которые совпали: если их два — это пересечение, и его
 * решает человек (шаг 95), а не порядок в списке.
 */
export function intents(phrase: string): Intent[] {
  const clean = phrase.trim();
  if (clean.length === 0) return [];
  const found: Intent[] = [];
  for (const [pattern, intent] of WORDS) {
    if (pattern.test(clean) && !found.includes(intent)) found.push(intent);
  }
  return found.length > 0 ? found : ["неизвестно"];
}

/**
 * Одно ли намерение.
 *
 * «Почисти» и «освободи место» — **одно**: это и есть смысл шага. Если бы они
 * расходились, человек, сказавший «место кончается», получил бы другой ответ,
 * чем сказавший «почисти».
 */
export function same(one: string, two: string): boolean {
  const left = intents(one);
  const right = intents(two);
  return left.length > 0 && right.length > 0 && left[0] === right[0];
}

/**
 * Пересечение.
 *
 * Два ключа — не «выбрать первый»: «почисти и найди большие файлы» — это и
 * освобождение, и поиск, и молчаливый выбор одного из них теряет половину
 * просьбы.
 */
export function collision(phrase: string): Intent[] {
  const found = intents(phrase);
  return found.length > 1 ? found : [];
}

/**
 * Что сказать человеку.
 *
 * Названо **намерение**, а не слово реестра: человек говорит «убери мусор» и
 * должен услышать «освободить место», а не «очистить корзину» — второе он не
 * просил.
 */
export function say(intent: Intent): string {
  switch (intent) {
    case "место":
      return "понял как «освободить место» — покажу, что занимает, и спрошу перед удалением";
    case "порядок":
      return "понял как «навести порядок» — покажу, что и куда переместится";
    case "поиск":
      return "понял как «найти» — ничего не меняю";
    case "копия":
      return "понял как «сделать копию» — оригинал не трону";
    case "прочитать":
      return "понял как «прочитать» — ничего не меняю";
    case "посчитать":
      return "понял как «посчитать» — считаю и показываю число";
    case "настроить":
      return "понял как «настроить» — покажу, что именно поменяется";
    case "неизвестно":
      return "не понял намерения: скажите проще — «почисти», «найди», «посчитай»";
  }
}

/**
 * Слова, которые выглядят как намерение, но им не являются.
 *
 * «Место в документе» — не про диск: такое надо назвать, а не освобождать
 * место. Функция проверяет **уточнение предмета**, а не слово.
 */
export function aboutDocument(phrase: string): boolean {
  return /место\s+в\s+(?:документе|тексте|строке)/i.test(phrase);
}
