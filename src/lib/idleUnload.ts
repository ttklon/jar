/**
 * Выгрузка модели из памяти по простою — с быстрым возвратом (шаг 74).
 *
 * Дефект. Модель, загруженная один раз, остаётся в памяти **навсегда**. Она
 * нужна человеку утром, когда он говорит, и не нужна весь день, пока он решает
 * другие задачи. И всё это время 4–7 ГБ заняты:
 *
 *  * **другие программы тормозят**, и виноватым выглядит не оно, а всё
 *    остальное;
 *  * **система свопится**, и это те самые «тридцать секунд на фразу», только
 *    не из-за модели, а из-за её тени;
 *  * **ноутбук греется и ест батарею** — модель в памяти не работает, но
 *    занимает.
 *
 * Правило: **простой — память обратно, но возврат быстрый**.
 *
 *  1. Выгружаем по **простою**, а не по таймеру от запуска: человек может
 *     работать час подряд, и это не простой.
 *  2. Порог достаточный (`IDLE_MS`), чтобы не выгружать между фразами: пауза в
 *     разговоре — не простой, а размышление.
 *  3. **Возврат быстрый**: выгруженная модель загружается за секунды с SSD, и
 *     человек не должен ждать полминуты за то, что приложение «экономило».
 *  4. **Первый токен после возврата ждётся дольше**, и это сказано: иначе
 *     человек решит, что приложение стало медленнее.
 *
 * Почему не «выгружать сразу после ответа». Каждая фраза стоила бы загрузки
 * модели — а это секунды на ровном месте. Экономия памяти не должна стоить
 * скорости разговора.
 */

/**
 * Через сколько простоя выгружать.
 *
 * Десять минут: пауза в разговоре редко дольше, а работа без модели — это
 * ровно те минуты, когда память нужна другим.
 */
export const IDLE_MS = 10 * 60 * 1000;

/**
 * Сколько стоит возврат — по типу диска.
 *
 * С SSD модель на 4.6 ГБ читается примерно за 23 секунды, но **в память
 * попадает не целиком сразу**: первые токены идут, пока читается остальное.
 * Поэтому возврат дешевле, чем полная загрузка, и это не отговорка.
 */
export function resumeMs(sizeMb: number, disk: "ssd" | "hdd" | "unknown"): number {
  const speed = disk === "hdd" ? 80 : 200;
  return Math.round((sizeMb / speed) * 1000);
}

/** Что известно о простое. */
export interface Idle {
  /** Сколько миллисекунд прошло с последней фразы. */
  idleMs: number;
  /** Загружена ли модель сейчас. */
  loaded: boolean;
}

/** Что делать с памятью. */
export type Action = "keep" | "unload";

/**
 * Выгружать ли.
 *
 * Только если модель загружена **и** простой достаточный. Выгружать
 * незагруженное — бессмысленная работа; выгружать на пятой минуте — значит
 * загружать снова через минуту.
 */
export function action(state: Idle): Action {
  if (!state.loaded) return "keep";
  return state.idleMs >= IDLE_MS ? "unload" : "keep";
}

/**
 * Что сказать при выгрузке.
 *
 * Названо **что произошло и сколько это стоит**: «освободил память, вернусь за
 * секунды» — это правда, и человек не боится, что теперь всё будет медленно.
 */
export function sayUnload(sizeMb: number, disk: "ssd" | "hdd" | "unknown"): string {
  const seconds = Math.round(resumeMs(sizeMb, disk) / 100) / 10;
  return `десять минут тишины — освободил ${Math.round((sizeMb / 1024) * 10) / 10} ГБ, вернусь за ${seconds} с`;
}

/**
 * Что сказать, когда человек вернулся после выгрузки.
 *
 * Предупреждение **до** первого ответа, а не объяснение после: иначе человек
 * решит, что приложение стало медленнее, и уйдёт искать причину.
 */
export function sayWaiting(disk: "ssd" | "hdd" | "unknown"): string {
  return disk === "hdd"
    ? "загружаю модель обратно — на этом диске это займёт до минуты"
    : "загружаю модель обратно — это займёт несколько секунд";
}

/**
 * Не выгружать, если идёт работа.
 *
 * `busy` — сейчас генерируется ответ или ждём подтверждения. Выгрузить в этот
 * момент значит **оборвать работу** человека, и это хуже, чем занять память.
 */
export function wouldHurt(state: Idle, busy: boolean): boolean {
  return busy && state.loaded;
}

/**
 * Сказано ли человеку, что память освобождается.
 *
 * Молчаливая выгрузка — это «приложение что-то сделало с памятью», и если потом
 * что-то пойдёт не так, виноватым будет это.
 */
export function words(state: Idle, sizeMb: number, disk: "ssd" | "hdd" | "unknown"): string | null {
  return action(state) === "unload" ? sayUnload(sizeMb, disk) : null;
}
