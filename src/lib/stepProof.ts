/**
 * Каждый шаг плана называет свою проверку результата до запуска (шаг 111).
 *
 * Дефект. «Готово» в приложении — это **вера**, а не проверка:
 *
 *  * **проверка появляется после**: шаг выполнился, ядро смотрит, что получилось, и
 *    только тогда выясняется, что проверять было нечего;
 *  * **проверка у разных рук разная по силе**: одна рука говорит «код возврата 0»,
 *    другая «путь существует» — и обе называются «готово»;
 *  * **проверки может не быть вовсе**: шаг отчитывается `ok`, доказательства нет, и
 *    это читается как успех (шаг 105);
 *  * **человек не знает, что будут проверять**: он соглашается на действие, не зная,
 *    по какому признаку его признают выполненным.
 *
 * Правило: **проверка называется до запуска, и она одна на шаг**.
 *
 *  1. **До запуска**, вместе с планом: «переименовать 12 файлов — проверю, что все
 *     12 переименованы», а не «готово» после.
 *  2. **Своя у каждого шага**, а не общая на план: у «создать папку» проверка —
 *     существование пути, у «посчитать» — число.
 *  3. **Слабая проверка называется слабой**: код возврата 0 доказательством успеха
 *     не является, и это сказано, а не спрятано за словом «готово».
 *  4. **Нет проверки — нет «готово»**: шаг без проверки помечен **до** запуска, и
 *     после него сказано «не проверено», а не «сделано».
 *  5. **Проверка не выбирается после результата**: иначе её подбирают под то, что
 *     получилось, и она перестаёт быть проверкой.
 *
 * Почему не «проверять по факту выполнения». «Факт выполнения» — это возврат
 * процесса; процесс возвращает 0 и когда ничего не сделал.
 */

/** Вид проверки — то, чем результат подтверждается. */
export type Proof =
  /** Путь появился или исчез. */
  | "path"
  /** Файл содержит то, что записали. */
  | "content"
  /** Число: сколько переименовано, посчитано, найдено. */
  | "count"
  /** Вывод содержит признак. */
  | "marker"
  /** Изменилось то, что видно на экране. */
  | "screen"
  /** Ничего: проверки нет, и это сказано. */
  | "none";

/** Шаг с проверкой, названной заранее. */
export interface Checked {
  /** Что делает — словами. */
  what: string;
  /** Чем будет подтверждено. */
  proof: Proof;
  /** Словами: «проверю, что путь существует». Пусто при `none`. */
  said: string;
}

/**
 * Проверка для вида доказательства — словами.
 *
 * `count` требует числа в подсказке: «проверю, что файлов 12» — проверка, «проверю,
 * что файлы переименованы» — надежда.
 */
export function checkFor(what: string, proof: Proof, hint = ""): Checked {
  switch (proof) {
    case "path":
      return { what, proof, said: `проверю, что путь существует${hint ? `: ${hint}` : ""}` };
    case "content":
      return { what, proof, said: `проверю, что в файле ровно то, что записали${hint ? `: ${hint}` : ""}` };
    case "count":
      return { what, proof, said: `проверю число${hint ? `: ${hint}` : ""}` };
    case "marker":
      return { what, proof, said: `проверю, что в выводе есть признак${hint ? ` «${hint}»` : ""}` };
    case "screen":
      return { what, proof, said: `проверю, что на экране изменилось${hint ? `: ${hint}` : ""}` };
    case "none":
      // Нет проверки — нет «готово»: это помечено до запуска, а не после.
      return { what, proof, said: "проверки нет — «готово» по этому шагу не скажу" };
  }
}

/**
 * Сильная ли проверка.
 *
 * `marker` и `count` — сильные: они привязаны к предмету. `path` — средняя.
 * `none` — не проверка вовсе.
 */
export function strong(proof: Proof): boolean {
  return proof === "content" || proof === "count" || proof === "marker" || proof === "screen";
}

/**
 * План проверок — до запуска.
 *
 * Возвращает **по строке на шаг** и сводку. Слабые проверки называются слабыми, а
 * шаги без проверки — отдельным числом: «проверок 7 из 10» — это отчёт, «всё
 * проверено» — обещание.
 */
export interface Plan {
  steps: Checked[];
  /** Сколько шагов с сильной проверкой. */
  strong: number;
  /** Сколько шагов без проверки вовсе. */
  unchecked: number;
  /** Строки для человека — до запуска. */
  said: string[];
}

export function plan(checks: readonly Checked[]): Plan {
  const strong_ = checks.filter((item) => strong(item.proof)).length;
  const unchecked = checks.filter((item) => item.proof === "none").length;
  const said = checks.map(
    (item, index) =>
      `${index + 1}. ${item.what} — ${item.said}${strong(item.proof) ? "" : item.proof === "none" ? "" : " (проверка слабая: только факт, а не предмет)"}`,
  );
  return { steps: [...checks], strong: strong_, unchecked, said };
}

/** Итог словами до запуска. */
export function say(got: Plan): string {
  const total = got.steps.length;
  if (total === 0) return "шагов нет — проверять нечего";
  const parts = [`проверок по предмету: ${got.strong} из ${total}`];
  if (got.unchecked > 0) parts.push(`без проверки: ${got.unchecked} — по ним «готово» не скажу`);
  return parts.join(", ");
}

/**
 * Можно ли говорить «готово» после шага.
 *
 * Только при сильной проверке, и только если она подтвердилась. Это функция, а не
 * решение на месте: иначе «готово» говорит тот, кому удобно.
 */
export function done(proof: Proof, confirmed: boolean): { ok: boolean; said: string } {
  if (proof === "none") return { ok: false, said: "не проверено — «готово» не скажу" };
  if (!confirmed) return { ok: false, said: "проверка не подтвердилась" };
  if (!strong(proof)) return { ok: true, said: "сделано, но проверка слабая: только факт" };
  return { ok: true, said: "сделано и проверено" };
}
