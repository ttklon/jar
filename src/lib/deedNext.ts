/**
 * Экран дела: что сделано, чем доказано, **что дальше** — одной карточкой (шаг 189).
 *
 * Дефект. Карточка отвечала на два вопроса из трёх. «Что сделано» — есть, «чем
 * доказано» — есть (у каждого шага), а «что дальше» — нет: внизу лежали кнопки
 * «Отменить», «Повторить», «Скопировать», но это **действия с отчётом**, а не
 * следующий шаг по делу.
 *
 * Разница не косметическая:
 *
 *  * дело **упало на третьем шаге** — человеку нужен не «повторить всё», а «начать
 *    с третьего» либо «посмотреть, почему»;
 *  * дело **кончилось отказом политики** — повторять бессмысленно, надо объяснить,
 *    чего не хватает (прав, папки, модели);
 *  * дело **ждёт подтверждения** — следующий шаг «подтвердить», и он один;
 *  * всё **получилось** — следующий шаг не «ещё раз», а «закончить и освободить
 *    место» либо ничего: пустая подсказка «что дальше» хуже её отсутствия.
 *
 * Правила:
 *
 *  1. **ровно один следующий шаг** и он назван: выбирать из трёх «что дальше»
 *     значит не ответить на вопрос;
 *  2. **у следующего шага есть способ** — что нажать или что сказать. Совет без
 *     способа — не шаг;
 *  3. **«дальше ничего» — законный ответ.** Успешное дело не обязано тянуть за
 *     собой новое: «всё сделано, дальше ничего не нужно» лучше выдуманного совета;
 *  4. **отказ — не «сбой»**: у отказa причина и следующее действие другое
 *     («посмотреть, чего не хватает»), а не «повторить»;
 *  5. **что сделано — числом.** «Сделано 3 из 5» отвечает, «выполнено» — нет.
 *
 * Модуль не знает разметки: он отвечает, что за дело, чем кончилось и что дальше.
 */

/** Шаг дела — минимум, нужный для ответа. */
export interface Step {
  position: number;
  /** Что делалось. */
  tool: string;
  /** `ok` | `failed` | `skipped` | `running`. */
  status: string;
  /** Доказательство. Пусто — его нет, и это отличается от «проверено». */
  proof?: string;
}

/** Дело. */
export interface Deed {
  subject: string;
  /** `running` | `ok` | `failed` | `denied` | `cancelled`. */
  outcome: string;
  steps: readonly Step[];
}

/** Что дальше. */
export interface Next {
  /** Что сделать — одной фразой. Пусто — дальше ничего не нужно. */
  said: string;
  /** Чем: что нажать или что сказать. Пусто, только если `said` пусто. */
  how: string;
}

/** Итог одной карточкой. */
export interface Card {
  /** «Сделано 3 из 5» — числом. */
  done: string;
  /** Чем доказано — числом проверенных шагов. */
  proof: string;
  /** Что дальше. */
  next: Next;
  /** Нужно ли внимание: провал, отказ или ожидание. */
  attention: boolean;
}

/** Сколько шагов сделано и сколько проверено. */
export function tally(deed: Deed): { did: number; total: number; proved: number } {
  const total = deed.steps.length;
  const did = deed.steps.filter((step) => step.status === "ok").length;
  const proved = deed.steps.filter((step) => (step.proof ?? "").trim().length > 0).length;
  return { did, total, proved };
}

/**
 * Что дальше — ровно одно.
 *
 * Порядок разбора — от самого срочного к самому спокойному: сначала то, что
 * требует человека **сейчас**, потом то, что можно сделать потом, и только в
 * конце — «ничего».
 */
export function next(deed: Deed): Next {
  const got = tally(deed);

  if (deed.outcome === "running") {
    return { said: "дело идёт — можно подождать или отменить", how: "«Отменить» внизу карточки" };
  }

  if (deed.outcome === "denied") {
    // Отказ — не сбой: повторять бессмысленно, пока не изменилось то, что не
    // пустило. Совет «повторить» здесь был бы издевательством.
    return {
      said: "это отказ, а не сбой: повторять то же самое — получить тот же отказ",
      how: "посмотрите, чего не хватает: экран «Состояние» и «Что мне разрешено»",
    };
  }

  if (deed.outcome === "cancelled") {
    return {
      said: "дело отменено — сделанное не откатилось само",
      how: "«Вернуть удалённое» на экране «Голос»: там видно, что вернётся",
    };
  }

  if (deed.outcome === "failed") {
    const at = deed.steps.find((step) => step.status === "failed");
    if (at !== undefined) {
      return {
        said: `упало на шаге ${at.position}: ${at.tool} — остальные не выполнялись`,
        how: "посмотрите причину в строке шага; повторять — только с изменённой фразой",
      };
    }
    return {
      said: "дело не закончилось — ни один шаг не дал итога",
      how: "проверьте, что дело не оборвалось: экран «История»",
    };
  }

  // Успех. Дальше — только если осталось что-то недоделанное.
  const skipped = deed.steps.filter((step) => step.status === "skipped").length;
  if (skipped > 0) {
    return {
      said: `сделано ${got.did} из ${got.total}; ${skipped} ${skipped === 1 ? "шаг пропущен" : "шага пропущены"}`,
      how: "«Повторить», если пропущенное действительно нужно",
    };
  }

  if (got.proved === 0 && got.total > 0) {
    // Успех без доказательств: честнее сказать это, чем поставить галочку.
    return {
      said: "сделано, но ни одного доказательства нет — это «прошло», а не «проверено»",
      how: "откройте журнал дела: там исход каждого шага",
    };
  }

  return { said: "", how: "" };
}

/** Карточка целиком — одна форма отчёта на все случаи. */
export function card(deed: Deed): Card {
  const got = tally(deed);
  const proved = got.total === 0 ? "шагов не было" : `проверено ${got.proved} из ${got.total}`;
  return {
    done:
      got.total === 0
        ? "дела не было: шагов ноль"
        : `сделано ${got.did} из ${got.total}`,
    proof: proved,
    next: next(deed),
    attention: deed.outcome === "failed" || deed.outcome === "denied" || deed.outcome === "running",
  };
}

/**
 * Проверка, что карточка отвечает на все три вопроса.
 *
 * Тест на это нужен потому, что «что дальше» легко превращается в пустую строку:
 * карточка с пустым `next` выглядит нормально и не отвечает на треть заявленного.
 */
export function complete(got: Card): { ok: boolean; why: string } {
  if (got.done.trim().length === 0) return { ok: false, why: "не сказано, что сделано" };
  if (got.proof.trim().length === 0) return { ok: false, why: "не сказано, чем доказано" };
  // Пустой «дальше» — законно, но только если он пуст **весь**, а не «фраза есть,
  // способа нет»: такой шаг нельзя выполнить.
  if (got.next.said.length > 0 && got.next.how.trim().length === 0) {
    return { ok: false, why: `«что дальше» без способа: ${got.next.said}` };
  }
  if (got.next.said.length === 0 && got.next.how.length > 0) {
    return { ok: false, why: `способ без «что дальше»: ${got.next.how}` };
  }
  return { ok: true, why: "" };
}
