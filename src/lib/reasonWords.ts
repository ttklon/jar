/**
 * Шаг 431: журнал пишет причину отказа словами человека, а не кодом ошибки.
 *
 * `journal.ts` (шаг 175) группирует причины, `whyScreen.ts` (шаг 422) объясняет
 * один отказ на экране. Здесь — **запись в журнал**: то, что человек прочитает
 * через месяц, когда ничего не помнит.
 *
 * «EACCES», «ETIMEDOUT», «ECONNREFUSED» ничего не говорят человеку. Перевести их
 * можно по-разному, и плохой перевод тоже бесполезен:
 *
 *  * **«ошибка доступа»** — не говорит, где и что делать;
 *  * **«таймаут»** — слово, которого человек не знает;
 *  * **«не удалось»** — не причина, а констатация.
 *
 * Хорошая причина отвечает на три вопроса: **что не получилось**, **где** и
 * **почему**. «Не удалил «старый.zip» в Загрузках: Windows не пустил — файл
 * открыт в другой программе».
 */

/** Что известно об отказе. */
export interface Fault {
  /** Технический код — мелко, для поддержки. */
  readonly code: string;
  /** Что пытались сделать. */
  readonly what: string;
  /** Где — папка или сервис. */
  readonly where: string;
  /** Что известно о причине. */
  readonly about?: "opened" | "denied" | "offline" | "full" | "timeout" | "missing";
}

/**
 * Перевести в слова.
 *
 * Неизвестный код — не «неизвестная ошибка», а «причину не знаю, и вот код»:
 * честная неизвестность лучше ложной понятности.
 */
export function words(fault: Fault): string {
  const about = fault.about;

  if (about === undefined) {
    return `не получилось ${fault.what} в «${fault.where}»: причину определить не удалось (код ${fault.code} — для поддержки)`;
  }

  // Ни одного латинского слова: «Windows не пустил» — понятно, но человек,
  // читающий журнал, ищет причину, а не название системы.
  const why: Record<NonNullable<Fault["about"]>, string> = {
    opened: "файл открыт в другой программе — закройте её и повторите",
    denied: "система не пустила: у приложения нет прав на эту папку",
    offline: "нет сети",
    full: "на диске кончилось место",
    timeout: "не дождался ответа: сервис не ответил вовремя",
    missing: "файла больше нет по этому пути — возможно, его переименовали",
  };

  return `не получилось ${fault.what} в «${fault.where}»: ${why[about]}`;
}

/**
 * Разобрать то, что записала рука, — без выдумывания.
 *
 * В памяти шага `reason` — свободная строка от инструмента: «EACCES: permission
 * denied», «os error 32: файл занят». Экран не должен показывать её как есть
 * (правило говорит: код отдельно, причина словами), но и **придумывать** вид
 * отказа нельзя: неузнанная строка остаётся строкой, и это честно.
 *
 * Что узнаётся:
 *
 *  * код в тексте (`EACCES`, `os error 32`, `ETIMEDOUT`, `ENOSPC`, `ENOENT`) —
 *    по нему определяется причина;
 *  * слова, которые пишут сами руки (`занят`, `нет места`, `нет сети`,
 *    `не пустил`, `не ответил`, `не найден`).
 */
export function kindOf(reason: string): Fault["about"] {
  const text = reason.toLowerCase();
  if (text === "") return undefined;
  // Порядок важен: «нет места» встречается вместе с «os error 112», и код
  // должен уточнять, а не перебивать уже понятную причину.
  if (text.includes("eacces") || text.includes("denied") || text.includes("не пустил") || text.includes("os error 5")) return "denied";
  if (text.includes("enospc") || text.includes("нет места") || text.includes("os error 112")) return "full";
  if (text.includes("etimedout") || text.includes("timed out") || text.includes("не ответил")) return "timeout";
  if (text.includes("enoent") || text.includes("не найден") || text.includes("os error 2")) return "missing";
  if (text.includes("econnrefused") || text.includes("нет сети") || text.includes("offline")) return "offline";
  if (text.includes("os error 32") || text.includes("занят") || text.includes("открыт в другой")) return "opened";
  return undefined;
}

/**
 * Код — отдельно.
 *
 * Чтобы поддержка нашла, а человек не спотыкался: код в конце, в скобках, мелко.
 */
export function line(fault: Fault): string {
  if (fault.about === undefined) return words(fault);
  return `${words(fault)} (код ${fault.code})`;
}

/**
 * Чего в причине быть не должно.
 *
 * Пять вещей, каждая из которых делает строку нечитаемой.
 */
export function neverWrite(): string[] {
  return [
    "голого кода ошибки без слов: «EACCES» человеку ничего не говорит",
    "«неизвестная ошибка»: честнее «причину не знаю» с кодом для поддержки",
    "«попробуйте позже», если позже не изменится ничего",
    "внутренних путей и номеров строк: они для поддержки в отчёте, а не в журнале",
    "английских слов вперемешку: «permission denied» без перевода",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три требования к каждой строке — их и проверяем.
 */
export function checks(): string[] {
  return [
    "есть что именно не получилось (не «ошибка»)",
    "есть где (папка или сервис)",
    "есть почему словами; код — отдельно и только для поддержки",
  ];
}
