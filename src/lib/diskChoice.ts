/**
 * Шаг 226: хранение не на системном диске, если он полон.
 *
 * Почему это не «мелочь установки». Модели — гигабайты, и на диске с Windows
 * место кончается первым. Дальше два плохих пути, и оба встречаются: приложение
 * отказывает («нет места») там, где рядом пустой диск D:, или — хуже — начинает
 * писать и ломается посередине, оставив недокачанный файл.
 *
 * Правило модуля: **решение принимается до записи**, а не после ошибки. Место
 * проверяется на том диске, куда собираемся писать, и если его мало — человеку
 * предлагается другой **с числом**: «на C: свободно 1,2 ГБ, на D: — 240 ГБ».
 *
 * Чего модуль не делает: не выбирает за человека и не переносит данные молча.
 * Тихий перенос в чужое место — это сюрприз, а сюрприз в хранении данных хуже
 * отказа: человек не знает, где его файлы.
 */

/** Где сейчас лежит папка данных. */
export interface Place {
  /** Буква диска или корень: `C:`, `D:`, `\\server\share`. */
  drive: string;
  /** Сколько свободно, в байтах. `null` — прочитать не удалось. */
  free: number | null;
  /** Системный ли это диск (там Windows). */
  system: boolean;
}

/** Предложение: куда писать и почему. */
export interface Choice {
  /** Куда писать по итогу (`null` — места нет нигде). */
  drive: string | null;
  /** Почему выбрано именно это — словами, с числами. */
  why: string;
  /** Нужен ли человек: перенос на другой диск — его решение, а не наше. */
  askHuman: boolean;
  /** Кандидаты, которые стоит предложить (по убыванию места). */
  others: Place[];
}

/**
 * Сколько места нужно, чтобы вообще начинать. Не «сколько нужно модели» —
 * у каждой модели своё, и об этом говорит загрузчик; здесь — минимум, ниже
 * которого писать бессмысленно.
 */
export const MIN_FREE_BYTES = 200 * 1024 * 1024;

function gb(bytes: number): string {
  const value = bytes / (1024 * 1024 * 1024);
  // Один знак после запятой: «1,2 ГБ» читается, «1,234567 ГБ» — нет.
  return `${value.toFixed(1).replace(".", ",")} ГБ`;
}

/**
 * Решить, где хранить, зная все диски.
 *
 * Порядок:
 *
 *  1. на текущем месте места хватает — ничего не меняем. Перенос работающего
 *     приложения ради красоты — это риск без пользы;
 *  2. места не хватает — ищем **несистемный** диск с местом. Системный не
 *     предлагаем: `C:` — это то, что и так кончается;
 *  3. места нет нигде — так и говорим, с числами по каждому диску.
 */
export function choose(places: readonly Place[], needed: number): Choice {
  const current = places[0];
  if (current && current.free !== null && current.free >= needed) {
    return {
      drive: current.drive,
      why: `места хватает: на ${current.drive} свободно ${gb(current.free)}`,
      askHuman: false,
      others: [],
    };
  }

  const candidates = places
    .filter((place) => !place.system && place.free !== null && place.free >= needed)
    .sort((a, b) => (b.free ?? 0) - (a.free ?? 0));

  if (candidates.length > 0) {
    const best = candidates[0]!;
    // Перенос — решение человека: спросить, а не сделать.
    return {
      drive: best.drive,
      why:
        `на ${current?.drive ?? "системном диске"} свободно ` +
        `${current?.free === null ? "неизвестно" : gb(current?.free ?? 0)}, ` +
        `а нужно ${gb(needed)}; на ${best.drive} свободно ${gb(best.free ?? 0)}`,
      askHuman: true,
      others: candidates.slice(1),
    };
  }

  // Места нет нигде. Числа по каждому диску — чтобы человек видел, что мы
  // смотрели, а не «не получилось».
  const seen = places
    .map((place) => `${place.drive}: ${place.free === null ? "не прочитано" : gb(place.free)}`)
    .join(", ");
  return {
    drive: null,
    why: `нужно ${gb(needed)}, а свободного места нет нигде: ${seen}`,
    askHuman: true,
    others: [],
  };
}

/**
 * Можно ли писать по выбранному решению **без вопроса**. Тихий перенос на другой
 * диск запрещён: человек должен знать, где его файлы, до того как они там
 * окажутся.
 */
export function canWriteMyself(choice: Choice): boolean {
  return choice.drive !== null && !choice.askHuman;
}

/** Строка для экрана: одно предложение, с числом и без «ошибки». */
export function describe(choice: Choice): string {
  if (choice.drive === null) return `Писать некуда: ${choice.why}.`;
  if (choice.askHuman) return `Предлагаю хранить на ${choice.drive}: ${choice.why}.`;
  return `Храню на ${choice.drive}: ${choice.why}.`;
}
