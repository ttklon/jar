/**
 * Отдельная дешёвая модель для «понять фразу» (шаг 66).
 *
 * Дефект. Каждая фраза идёт в ту же модель, что и планирование. Человек
 * сказал «открой блокнот» — и ждёт семь секунд, пока 7B разберётся, что это
 * две команды: открыть и блокнот. Семь секунд на «открой блокнот» — это не
 * медлительность, это **неверный выбор модели**, и он невидим: человек думает,
 * что приложение тормозит.
 *
 * Правило: **разбор намерения — отдельная и дешёвая модель**.
 *
 *  1. Разбор намерения — **задача на классификацию**, а не на рассуждение:
 *     «какая из известных команд это» решается небольшим контекстом и словарём
 *     (шаг 56). 7B здесь не нужна.
 *  2. **Скорость важнее глубины**: понять фразу надо до того, как человек
 *     закончил её ждать. Это доли секунды, а не секунды.
 *  3. **Не поняла — не врёт**. Дешёвая модель чаще ошибается, и это нормально,
 *     если ошибка видна: неуверенность уходит в `null` и большая модель
 *     разбирается заново (шаг 58: сомнение показывается словами).
 *  4. **Большая модель не зовётся дважды**: если дешёвая справилась, 7B не
 *     просыпается. Это и есть выигрыш.
 *
 * Почему не «правила вместо модели». Правила не понимают парафраз: «сделай
 * так, чтобы это ушло в архив» — это «заархивируй». Модель на 0.5B справляется
 * с парафразами и стоит доли секунды.
 */

/** Что может дать дешёвая модель. */
export type Verdict =
  /** Поняла: команда и уверенность. */
  | { ok: true; command: string; sure: number }
  /** Не поняла: пусть разбирается большая. */
  | { ok: false; why: string };

/**
 * Порог уверенности, ниже которого **не гадаем**.
 *
 * Дешёвая модель ошибается чаще, и ошибка её незаметна: «архивировать» вместо
 * «опубликовать» — это выполненное не то действие. Порог назван числом, чтобы
 * его можно было оспорить.
 */
export const SURE_AT = 0.6;

/**
 * Принять решение дешёвой модели.
 *
 * Уверенность ниже порога — **не** «почти наверняка», а «пусть разбирается
 * большая»: ошибка дороже секунды.
 *
 * Неизвестная команда — тоже отказ: дешёвая модель может «вспомнить» команду,
 * которой нет, и это худший вид ошибки — уверенный и неверный.
 */
export function accept(
  command: string | null,
  sure: number,
  known: readonly string[],
): Verdict {
  if (command === null || command.trim().length === 0) {
    return { ok: false, why: "дешёвая модель не назвала команду — разбирается большая" };
  }
  const clean = command.trim();
  if (!known.includes(clean)) {
    // «Вспомнила» команду, которой нет: уверенно и неверно — худший вид ошибки.
    return { ok: false, why: `команды «${clean}» нет — разбирается большая` };
  }
  if (sure < SURE_AT) {
    return {
      ok: false,
      why: `дешёвая модель не уверена (${Math.round(sure * 100)}%) — разбирается большая`,
    };
  }
  return { ok: true, command: clean, sure };
}

/**
 * Нужна ли большая модель после дешёвой.
 *
 * Ответ «нет» — это и есть весь выигрыш шага: 7B не просыпается, когда 0.5B
 * справилась.
 */
export function needsBig(verdict: Verdict): boolean {
  return !verdict.ok;
}

/**
 * Сколько фраз дешёвая модель закрывает сама — по замерам.
 *
 * Не «примерно все»: названа доля, потому что от неё зависит, стоит ли вообще
 * держать две модели. Доля ниже половины значит, что вторая модель только
 * занимает память.
 */
export interface Share {
  /** Сколько фраз разобрала дешёвая. */
  cheap: number;
  /** Сколько ушло большой. */
  big: number;
}

export function share(got: Share): number {
  const total = got.cheap + got.big;
  return total === 0 ? 0 : got.cheap / total;
}

/**
 * Стоит ли держать две модели.
 *
 * Порог половины: если дешёвая закрывает меньше половины, вторая модель только
 * занимает память (шаг 63: она нужна не бесплатно).
 */
export function worthTwo(got: Share): boolean {
  return share(got) >= 0.5;
}

/**
 * Что сказать человеку.
 *
 * Названо **что происходит и почему быстро**: иначе быстрый ответ на простую
 * фразу и медленный на сложную выглядят как нестабильность (шаг 62).
 */
export function say(verdict: Verdict): string {
  return verdict.ok
    ? `понял сразу: «${verdict.command}» — быстрая модель справилась`
    : `разбираю подробнее: ${verdict.why}`;
}
