/**
 * Шаг 273: показывать, откуда взят факт — сказал человек или вывело приложение.
 *
 * Различие, которое кажется очевидным, но нигде не хранилось. `freshWins`
 * (шаг 265) различал «сказано сейчас» и «из памяти» — но **в момент заполнения
 * поля**: человек видел подсказку один раз и потом уже не знал, он ли это сказал.
 * `preferences` хранит `why` («открывали 4 раза») — но это объяснение, а не
 * происхождение: из него нельзя узнать, чьё это слово.
 *
 * Почему это важно, а не любопытно:
 *
 *  1. **ошибку памяти человек исправляет, а свою — нет.** «Я так сказал» не
 *     обсуждают: человек уверен, что помнит себя. «Приложение вывело» — можно
 *     поправить без спора. Значит, различие должно пережить перезапуск, а не
 *     жить в подсказке;
 *  2. **выведенное нельзя показывать как сказанное.** Догадка «вы говорите
 *     шёпотом» — это вывод из громкости; если её показать как факт, человек
 *     начнёт искать, когда он такое говорил;
 *  3. **происхождение нельзя терять при переносе.** Файл памяти (шаг 266)
 *     переезжает на другой компьютер — и там тоже должно быть видно, что папку
 *     назвал человек, а программа лишь заметила;
 *  4. **у него есть срок.** Сказанное год назад не перестаёт быть сказанным, а
 *     выведенное год назад — устарело: изменились и папки, и привычки.
 */

/**
 * Откуда взялся факт.
 *
 * Три значения, а не два, и каждое по делу:
 *
 *  * `said` — человек сказал или напечатал прямо, в том числе просьбой
 *    «запомни». Это слово человека, и оно не обсуждается;
 *  * `shown` — приложение наблюдало и вывело правило (папка открывалась дважды,
 *    громкость ставилась в 30). Это **догадка**, хоть и обоснованная;
 *  * `imported` — факт приехал из файла памяти. Здесь важно не то, кто его
 *    вывел, а то, что на этом компьютере человек его **не подтверждал**.
 */
export type Origin = "said" | "shown" | "imported";

/** Факт с происхождением: то, что должно храниться, а не вычисляться. */
export interface Sourced {
  readonly kind: string;
  readonly value: string;
  readonly origin: Origin;
  /** Когда это стало фактом, мс. */
  readonly at: number;
  /** Словами, откуда: для `shown` — на чём основана догадка. */
  readonly from: string;
}

/**
 * Как происхождение выглядит для человека.
 *
 * Не «source: said»: человеку нужно понять, спорить ли с этим. Поэтому у
 * каждого — глагол, а не ярлык.
 */
export function label(origin: Origin): string {
  if (origin === "said") return "вы сказали";
  if (origin === "shown") return "приложение заметило";
  return "перенесено с другого компьютера";
}

/**
 * Насколько факту можно верить — словами, а не числом.
 *
 * Число («0,8») человек не переведёт в решение, а фразу — да. И фраза разная не
 * по величине, а по **что с этим делать**: сказанное не проверяют, замеченное
 * проверяют, перенесённое подтверждают.
 */
export function trust(origin: Origin): string {
  if (origin === "said") return "это вы";
  if (origin === "shown") return "это догадка — проверьте";
  return "на этом компьютере не подтверждено";
}

/**
 * Срок доверия к выведенному.
 *
 * Тридцать дней — как у предпочтений (`preferences.STALE_MS`): смена сезона
 * меняет и папки, и привычки. Сказанное этим сроком **не** ограничено: человек
 * сказал «моя папка — D:\Отчёты», и через год это его слова.
 */
export const SHOWN_LIFE = 30 * 24 * 60 * 60 * 1000;

/** Живо ли происхождение сейчас: выведенное стареет, сказанное — нет. */
export function fresh(fact: Sourced, now: number): { ok: boolean; said: string } {
  // Сказанное не стареет **по правилу**, а не «потому что до проверки не дошло»:
  // иначе первая же правка условия начнёт снимать слово человека по возрасту.
  if (fact.origin === "said") return { ok: true, said: "" };
  const age = now - fact.at;
  if (age > SHOWN_LIFE) {
    return {
      ok: false,
      said: `замечено ${ago(age)} назад — возможно, уже не так: спросите, а не подставляйте`,
    };
  }
  if (fact.origin === "imported") {
    return { ok: true, said: "перенесено с другого компьютера — пока не подтверждено здесь" };
  }
  return { ok: true, said: "" };
}

/**
 * Можно ли подставлять значение молча.
 *
 * Сказанное — можно. Замеченное — только свежее и с пометкой: молча подставленная
 * догадка неотличима от факта, и это ровно та ошибка, из-за которой человек
 * перестаёт понимать, что приложение о нём знает.
 */
export function silently(fact: Sourced, now: number): { ok: boolean; note: string } {
  if (fact.origin === "said") return { ok: true, note: "" };
  const check = fresh(fact, now);
  if (!check.ok) return { ok: false, note: check.said };
  return { ok: true, note: label(fact.origin) };
}

/** Отметить факт, приехавший из файла: на этом компьютере он не подтверждён. */
export function imported(fact: { kind: string; value: string; at: number; from: string }): Sourced {
  return { ...fact, origin: "imported" };
}

/**
 * Человек подтвердил перенесённое — оно становится его словом.
 *
 * Это не косметика: подтверждённое перестаёт стареть и перестаёт спрашиваться.
 * И именно поэтому подтверждение — отдельное действие, а не «первое
 * использование»: человек, который просто открыл папку, ничего не подтверждал.
 */
export function confirm(fact: Sourced, at: number): Sourced {
  if (fact.origin === "said") return fact;
  return { ...fact, origin: "said", at, from: fact.from === "" ? "подтверждено" : fact.from };
}

/**
 * Что показать рядом с фактом в списке памяти.
 *
 * Одна строка, в которой сказано и чьё это, и можно ли на это опираться, — но без
 * повторения самого значения: оно уже стоит слева, и второй раз занимает место,
 * которое нужно причине.
 */
export function note(fact: Sourced, now: number): string {
  const check = fresh(fact, now);
  const base = `${label(fact.origin)}${fact.from === "" ? "" : `: ${fact.from}`}`;
  return check.said === "" ? base : `${base} — ${check.said}`;
}

/**
 * Сводка для экрана: сколько чего.
 *
 * Нужна, чтобы «сколько приложение обо мне вывело само» было видно **всегда**, а
 * не после того, как человек догадается открыть каждый факт.
 */
export function counts(facts: readonly Sourced[]): string {
  const said = facts.filter((fact) => fact.origin === "said").length;
  const shown = facts.filter((fact) => fact.origin === "shown").length;
  const moved = facts.filter((fact) => fact.origin === "imported").length;
  if (facts.length === 0) return "память пуста";
  return `вы сказали: ${said}, приложение заметило: ${shown}, перенесено: ${moved}`;
}

/**
 * Слить одинаковые факты разного происхождения.
 *
 * Одно и то же значение, сказанное человеком и замеченное приложением, — **один**
 * факт, и он сказанный: слово человека сильнее догадки. Оставить два значит
 * показывать человеку одно и то же дважды с разными подписями и заставлять его
 * выбирать, чему верить, — там, где вопроса нет.
 */
export function merge(facts: readonly Sourced[]): Sourced[] {
  const byKey = new Map<string, Sourced>();
  // Порядок силы — по тому, насколько это проверено **здесь**: слово человека,
  // затем наблюдение на этом компьютере, затем перенесённое (его здесь никто не
  // видел). Перенесённое сильнее замеченного значило бы предпочитать то, чего
  // мы не проверяли, тому, что видели сами.
  const rank: Record<Origin, number> = { said: 2, shown: 1, imported: 0 };
  for (const fact of facts) {
    const key = `${fact.kind}:${fact.value}`;
    const existing = byKey.get(key);
    if (existing === undefined) {
      byKey.set(key, fact);
      continue;
    }
    if (rank[fact.origin] > rank[existing.origin]) byKey.set(key, fact);
  }
  return [...byKey.values()];
}

function ago(ms: number): string {
  const day = 24 * 60 * 60 * 1000;
  const days = Math.floor(ms / day);
  if (days < 1) return "меньше дня";
  if (days === 1) return "1 день";
  if (days < 5) return `${days} дня`;
  if (days < 30) return `${days} дней`;
  const months = Math.floor(days / 30);
  return months === 1 ? "месяц" : `${months} мес.`;
}
