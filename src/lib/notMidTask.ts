/**
 * Шаг 317: обновление не запускается во время дела — иначе дело рвётся.
 *
 * Обновление в неудачный момент — это не «мелкое неудобство»: программа
 * перезапускается посреди печати, разговора или цепочки действий, и человек
 * теряет не прогресс загрузки, а **свою работу**. Причём в самый неподходящий
 * момент, потому что именно тогда он ей и занят.
 *
 * Правило: **«дело идёт» — это состояние программы, а не догадка по времени.**
 * Признаки дела:
 *
 *  * идёт разговор (микрофон открыт или ответ ещё произносится);
 *  * выполняется цепочка действий (план, руки что-то нажимают);
 *  * открыт диалог, который человек заполняет;
 *  * идёт своя загрузка (модель, обновление модели).
 *
 * Пока дело идёт, обновление **ждёт**. Не «спросим посреди дела», не «отложим на
 * 5 минут» — ждёт до конца дела, а потом предлагает.
 */

/** Что сейчас происходит. */
export interface Busy {
  /** Идёт разговор: слушаем или говорим. */
  readonly talking: boolean;
  /** Выполняется цепочка действий. */
  readonly running: boolean;
  /** Открыт диалог, который человек заполняет. */
  readonly inDialog: boolean;
  /** Идёт загрузка, которую нельзя прерывать. */
  readonly downloading: boolean;
}

/** Пусто ли дело. */
export function idle(busy: Busy): boolean {
  return !busy.talking && !busy.running && !busy.inDialog && !busy.downloading;
}

/** Что именно идёт — по-человечески, чтобы назвать причину ожидания. */
export function whatGoingOn(busy: Busy): string[] {
  const going: string[] = [];
  if (busy.talking) going.push("разговор");
  if (busy.running) going.push("выполняется действие");
  if (busy.inDialog) going.push("вы заполняете окно");
  if (busy.downloading) going.push("идёт загрузка");
  return going;
}

/**
 * Можно ли начинать обновление.
 *
 * Отказ называет **что ждём**, а не «занято»: иначе кажется, что программа
 * сломалась.
 */
export function mayStart(busy: Busy): { ok: boolean; said: string } {
  if (idle(busy)) return { ok: true, said: "можно обновляться: дел нет" };
  return {
    ok: false,
    said: `обновление подождёт: сейчас ${whatGoingOn(busy).join(", ")} — не будем рвать дело`,
  };
}

/**
 * Что делать после окончания дела.
 *
 * Немедленное «пора обновляться!» сразу после разговора — тоже неудачно: человек
 * только что закончил и, скорее всего, начнёт следующее. Поэтому — пауза, и не
 * «через 5 минут», а **когда освободится**: окно без дела.
 */
export function afterTask(): string {
  return "обновление предлагается в первое окно без дела, а не сразу после разговора: сразу человек начинает следующее";
}

/**
 * Срочное обновление — исключение, и оно узкое.
 *
 * Если версия дырявая по безопасности, ждать «окна без дела» нельзя. Но и тогда
 * обновление не рвёт дело: оно спрашивает **сейчас**, а не ставится.
 */
export function urgent(dangerous: boolean): { ask: boolean; said: string } {
  if (!dangerous) return { ask: false, said: "обычное обновление ждёт конца дела" };
  return {
    ask: true,
    said: "в версии найден изъян безопасности — спросим сразу, но не прервём: «обновиться сейчас или через минуту?»",
  };
}

/**
 * Окна, в которых обновляться точно нельзя.
 *
 * Список нужен, чтобы «не во время дела» не расползлось в толкование: ночная
 * тихая установка допустима, а вот во время презентации или игры — нет, там
 * перезапуск заметнее всего.
 */
export function badTimes(): string[] {
  return [
    "идёт разговор или ответ ещё звучит",
    "руки выполняют цепочку действий",
    "открыт диалог ввода",
    "идёт загрузка, которую нельзя прервать",
    "демонстрация экрана или игра на весь экран",
  ];
}
