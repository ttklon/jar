/**
 * Шаг 497: журнал решений — почему так, а не иначе. Иначе следующая сессия передумает.
 *
 * Код говорит **что** сделано. Комментарии говорят **как**. Ни то, ни другое не
 * говорит **почему так, а не иначе** — а через полгода (или в следующей сессии, у
 * которой нет этой памяти) именно этого не хватает, и решение тихо отменяют, а потом
 * наступают на те же грабли.
 *
 * Поэтому у каждого неочевидного решения есть строка:
 *
 *  * **что решили** — одной фразой;
 *  * **почему** — с альтернативой: «не X, потому что Y»;
 *  * **что это стоит** — честная цена решения;
 *  * **когда пересмотреть** — при каком условии решение может стать неверным.
 *
 * И запрет: «так исторически сложилось» и «так проще» — не причина. Причина
 * называет альтернативу и то, что она ломает.
 */

/** Решение. */
export interface Decision {
  /** Что решили. */
  readonly what: string;
  /** Почему — с альтернативой. */
  readonly why: string;
  /** Чем платим. */
  readonly cost: string;
  /** Когда пересмотреть — условие, а не дата. */
  readonly revisit: string;
}

/** Слова, которые не объясняют ничего. */
const EMPTY = ["исторически", "так проще", "так принято", "всегда так было", "потому что надо"];

/**
 * Проверить строку журнала.
 *
 * Нарушения: причина без альтернативы, пустая цена, «так проще».
 */
export function check(decision: Decision): string[] {
  const problems: string[] = [];
  const why = decision.why.toLowerCase();

  for (const empty of EMPTY) {
    if (why.includes(empty)) problems.push(`«${decision.what}»: «${empty}» — не причина: что было альтернативой?`);
  }

  // `\b` с кириллицей не работает — ищем подстроки без границ слова.
  if (!/вместо|потому что|альтернатив/i.test(decision.why)) {
    problems.push(`«${decision.what}»: причина без альтернативы — не видно, от чего отказались`);
  }
  if (decision.cost.trim().length < 10) problems.push(`«${decision.what}»: не сказано, чем платим — честная цена обязательна`);
  if (decision.revisit.trim().length < 15 || /когда-нибудь|потом|со временем/i.test(decision.revisit)) {
    problems.push(`«${decision.what}»: не сказано, при каком условии пересмотреть`);
  }

  return problems;
}

/**
 * Найти решения, которые пора пересмотреть.
 *
 * `now` — что происходит сейчас: изменения в проекте. Пересматриваем те, чьё условие
 * сработало, — это и есть польза журнала.
 */
export function revisit(decisions: readonly Decision[], now: readonly string[]): string[] {
  // Сравниваем по значимым словам условия: событие описывают своими словами, и
  // совпадения целой строки ждать нечего.
  // По основам, а не по целым словам: «перевалит» и «перевалил» — одно и то же,
  // а русские окончания иначе не дают совпасть никогда.
  const words = (text_: string): string[] =>
    text_.toLowerCase().split(/[^\p{L}\p{N}]+/u).filter((word) => word.length >= 5).map((word) => word.slice(0, 5));

  return decisions
    .filter((decision) => {
      const need = words(decision.revisit);
      if (need.length === 0) return false;
      return now.some((event) => {
        const have = new Set(words(event));
        const hit = need.filter((word) => have.has(word)).length;
        // Событие описывают своими словами: достаточно большинства значимых слов
        // условия, иначе журнал молчит до буквального совпадения.
        return hit >= Math.ceil(need.length * 0.6);
      });
    })
    .map((decision) => decision.what);
}

/**
 * Строка журнала целиком.
 *
 * Четыре части, в порядке чтения: что, почему, цена, когда пересмотреть.
 */
export function text(decision: Decision): string {
  return `${decision.what}\nПочему: ${decision.why}\nЦена: ${decision.cost}\nПересмотреть: ${decision.revisit}`;
}

/**
 * Чего журнал не делает.
 *
 * Три запрета; главный — не «так сложилось».
 */
export function notDo(): string[] {
  return [
    "не принимает «так исторически сложилось» и «так проще» за причину",
    "не пишет решение без цены: решение без цены выглядит бесплатным и отменяется первым",
    "не оставляет решения без условия пересмотра: тогда его отменяют молча",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по частям, которые чаще всего пропускают.
 */
export function checks(): string[] {
  return [
    "у причины есть альтернатива: «не X, потому что Y»",
    "у решения названа цена",
    "у решения есть условие пересмотра, и оно срабатывает",
  ];
}
