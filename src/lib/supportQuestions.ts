/**
 * Шаг 467: инструкция для поддержки — что спросить и что приложить.
 *
 * Поддержка без инструкции начинает переписку с «здравствуйте, опишите проблему»
 * — и теряет два дня. С инструкцией первый ответ уже содержит всё нужное.
 *
 * Три вопроса, и они не «что случилось», а те, на которые **человек может
 * ответить**:
 *
 *  1. **что вы просили** — фраза дословно;
 *  2. **что произошло** — словами, а не «не работает»;
 *  3. **когда это началось** — до или после обновления.
 *
 * И три вещи, которые прикладываются **одной кнопкой**: отчёт (шаг 374), журнал
 * (шаг 423) и архив (шаг 440). Причём инструкция говорит, **чего в них нет**, —
 * иначе человек побоится их отправлять.
 */

/** Вопрос. */
export interface Ask {
  /** Вопрос — по-русски и коротко. */
  readonly ask: string;
  /** Зачем он — чтобы поддержка понимала, зачем спрашивает. */
  readonly why: string;
  /** Обязательный ли. */
  readonly must: boolean;
}

/**
 * Вопросы поддержки.
 *
 * Ровно три и обязательных: «необязательный» вопрос не задают.
 */
export function questions(): Ask[] {
  return [
    { ask: "Что вы просили? Напишите фразу, как говорили.", why: "по фразе видно, что понял разбор — а не что вы имели в виду", must: true },
    { ask: "Что произошло? Словами: не получилось, сделалось не то, зависло.", why: "«не работает» не отличает отказ от неверного результата", must: true },
    { ask: "Когда началось? После обновления или было всегда?", why: "разделяет новый дефект и старое ограничение", must: true },
  ];
}

/**
 * Что приложить.
 *
 * Три файла, и все — из приложения, а не «пришлите скриншот папки».
 */
export function attach(): { what: string; how: string }[] {
  return [
    { what: "отчёт о деле", how: "кнопка «скопировать отчёт» на экране дела" },
    { what: "журнал за сутки", how: "Настройки → Журнал → «выгрузить» (секреты уже вычищены)" },
    { what: "архив для поддержки", how: "Настройки → Помощь → «собрать архив» (с манифестом)" },
  ];
}

/**
 * Чего в файлах нет.
 *
 * Три факта, которые снимают страх «а не отправлю ли я личное».
 */
export function safeToSend(): string[] {
  return ["паролей и ключей: вычищены на записи и ещё раз при выгрузке", "имени пользователя Windows и полных путей", "памяти и профилей: в архив их не кладут"];
}

/**
 * Что делать, если человек не может приложить файлы.
 *
 * Не «тогда мы не поможем»: три вопроса уже дают половину ответа.
 */
export function withoutFiles(): string {
  return "три ответа уже дают половину: по фразе и симптому видно, где смотреть. Файлы помогут сузить, но не обязательны для первого ответа";
}

/**
 * Чего инструкция не делает.
 *
 * Три запрета — про уважение к человеку.
 */
export function notDo(): string[] {
  return [
    "не просит «описать проблему подробно»: вопросы конкретные",
    "не просит открывать папки и присылать скриншоты Проводника",
    "не требует файлов, чтобы ответить: сначала ответ, потом уточнения",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три вопроса, три вложения, три отсутствия.
 */
export function checks(): string[] {
  return [
    "ровно три вопроса, и все обязательные",
    "вложения собираются кнопкой в приложении",
    "сказано, чего в файлах нет — иначе человек побоится отправлять",
  ];
}
