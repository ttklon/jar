import { describe, expect, it } from "vitest";
import { aboutDocument, collision, intents, same, say } from "./synonyms";

/**
 * Шаг 93: синонимы — «почисти», «освободи место», «убери мусор» — одно намерение.
 *
 * Слово «мусор» не встречается в реестре ни разу, и разбор честно не находил
 * ничего: человек обязан угадать, как это называется у нас.
 */
describe("одно намерение — один ключ", () => {
  it("«почисти» и «освободи место» — одно", () => {
    // Если бы они расходились, «место кончается» работало бы иначе, чем «почисти».
    expect(same("почисти диск", "освободи место")).toBe(true);
    expect(intents("почисти")).toEqual(["место"]);
    expect(intents("освободи место на диске")).toEqual(["место"]);
    expect(intents("убери мусор")).toEqual(["место"]);
  });

  it("«место кончается» — тоже освобождение", () => {
    expect(intents("место кончается")).toEqual(["место"]);
    expect(intents("диск забит")).toEqual(["место"]);
  });

  it("грубые и неточные слова понимаются", () => {
    // «Хлам» и «барахло» — так и говорят.
    expect(intents("убери хлам")).toEqual(["место"]);
    expect(intents("наведи порядок в загрузках")).toEqual(["порядок"]);
    expect(intents("разложи по папкам")).toEqual(["порядок"]);
  });
});

describe("разные намерения — разные ключи", () => {
  it("поиск не путается с освобождением", () => {
    expect(intents("найди большие файлы")).toEqual(["поиск"]);
    expect(same("найди файлы", "почисти")).toBe(false);
  });

  it("копия не путается с перемещением", () => {
    expect(intents("сделай копию папки")).toEqual(["копия"]);
    expect(say("копия")).toContain("оригинал не трону");
  });

  it("«посчитай» — не «найди»", () => {
    expect(intents("посчитай файлы")).toEqual(["посчитать"]);
  });
});

describe("сказано намерение, а не слово реестра", () => {
  it("«убери мусор» слышит «освободить место»", () => {
    // «Очистить корзину» он не просил.
    const said = say("место");
    expect(said).toContain("освободить место");
    expect(said).toContain("спрошу перед удалением");
  });

  it("поиск и чтение прямо говорят: ничего не меняю", () => {
    expect(say("поиск")).toContain("ничего не меняю");
    expect(say("поиск")).toContain("ничего не меняю");
    expect(say("прочитать")).toContain("ничего не меняю");
  });
});

describe("пересечение решается человеком", () => {
  it("два намерения — это пересечение, а не «первый победил»", () => {
    // «Почисти и найди большие файлы» — и освобождение, и поиск.
    const both = collision("почисти и найди большие файлы");
    expect(both).toContain("место");
    expect(both).toContain("поиск");
  });

  it("одно намерение — не пересечение", () => {
    expect(collision("почисти")).toEqual([]);
  });

  it("непонятное намерение честно названо", () => {
    expect(say("неизвестно")).toContain("не понял");
    expect(intents("ыыы")).toEqual(["неизвестно"]);
    expect(intents("")).toEqual([]);
  });
});

describe("«место» бывает не на диске", () => {
  it("«место в документе» — не про диск", () => {
    // Такое надо назвать, а не освобождать место.
    expect(aboutDocument("найди место в документе")).toBe(true);
    expect(aboutDocument("освободи место на диске")).toBe(false);
  });
});
