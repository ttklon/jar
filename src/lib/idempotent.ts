/**
 * Повторный запуск того же плана видит, что уже сделано, и не делает дважды (шаг 114).
 *
 * Дефект. Один и тот же план можно запустить дважды — и он **сделает то же самое
 * второй раз**:
 *
 *  * **двойная работа**: «переименовать 12 файлов» переименовывает уже
 *    переименованные, и получается `фото-1-1.jpg` — работа сделана, а результат
 *    испорчен;
 *  * **провал на повторе**: «создать папку» падает, потому что папка уже есть —
 *    хотя это **успех**, а не провал;
 *  * **человек не знает, что уже сделано**: перед повторным запуском нет ни слова о
 *    прошлом, и он либо повторяет зря, либо боится повторять;
 *  * **разница между «сделано раньше» и «сделано сейчас» не видна**: отчёт
 *    выглядит одинаково, и нельзя понять, что было.
 *
 * Правило: **шаг знает, был ли он уже сделан, и повтор этого не повторяет**.
 *
 *  1. **Отпечаток шага** — адрес руки и параметры. Тот же отпечаток, что у согласия
 *     (шаг 102): два разных отпечатка одного шага разошлись бы.
 *  2. **Сделано раньше — пропуск с причиной**: `skipped` и «уже сделано в прошлый
 *     раз», а не молчание и не повтор.
 *  3. **Пропуск — не провал и не успех**: это третий исход, и он назван (шаг 106:
 *     отчёт числом).
 *  4. **«Уже есть» — успех там, где цель — наличие**: «создать папку» на
 *     существующую папку — успех, а не провал. Это знание **руки**, а не догадка
 *     экрана.
 *  5. **Повторить насильно можно** — но это названо: «повторить, хотя сделано», и
 *     человек знает, на что идёт.
 *
 * Почему не «запомнить, что план выполнен». План выполнен — но мир мог измениться:
 * папку удалили, файлы вернули. Поэтому решение принимается **по отпечатку шага**,
 * а не по отметке «план выполнен».
 */

/** Что осталось от прошлого запуска. */
export interface Past {
  /** Отпечаток шага: адрес и параметры. */
  print: string;
  /** Сделано ли (или «уже есть»). */
  done: boolean;
  /** Когда — чтобы «сделано» не жило вечно. */
  at: number;
}

/** Отпечаток шага.
 *
 * Порядок ключей не влияет — иначе один и тот же шаг давал бы разные отпечатки при
 * пересчёте плана (та же причина, что в шаге 102).
 */
export function print(tool: string, params: Record<string, string> | undefined): string {
  const body = Object.entries(params ?? {})
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([key, value]) => `${key}=${value}`)
    .join("&");
  return `${tool}|${body}`;
}

/** Что делать с шагом при повторном запуске. */
export type Verdict =
  /** Делать: в прошлый раз не делали (или было слишком давно). */
  | { kind: "run"; why: string }
  /** Пропустить: уже сделано. */
  | { kind: "skip"; why: string };

/**
 * Сколько живёт «уже сделано».
 *
 * Час: за час мир не меняется, а за сутки — меняется (файлы переименовали обратно).
 * Число названо, а не «давно».
 */
export const FRESH_MS = 60 * 60 * 1000;

/**
 * Решение по одному шагу.
 *
 * `force` — человек сказал «повторить, хотя сделано»: это его право, но причина
 * названа, а не проглочена.
 */
export function judge(
  tool: string,
  params: Record<string, string> | undefined,
  past: readonly Past[],
  now: number,
  force = false,
): Verdict {
  const want = print(tool, params);
  const found = past.find((item) => item.print === want && item.done);
  if (found === undefined) return { kind: "run", why: "в прошлый раз этого шага не было" };
  if (now - found.at > FRESH_MS) {
    // Мир мог измениться: старое «сделано» — не основание пропускать.
    return { kind: "run", why: "сделано давно — проверю заново, а не поверю отметке" };
  }
  if (force) {
    return { kind: "run", why: "повторяю, хотя сделано — вы так попросили" };
  }
  return { kind: "skip", why: "уже сделано в прошлый раз — не повторяю" };
}

/**
 * Что рука знает о повторе.
 *
 * «Уже есть» — успех только у рук, у которых цель — **наличие**. У «переименовать»
 * и «переместить» повтор меняет результат, поэтому там это не успех.
 */
const ALREADY_OK = new Set(["files|создать|папку", "files|создать|файл"]);

export function alreadyIsSuccess(tool: string): boolean {
  return ALREADY_OK.has(tool);
}

/**
 * Итог по шагу, если ядро сказало «уже есть».
 *
 * Возвращает `null`, если рука не из тех, где «уже есть» — успех: тогда это провал,
 * и притворяться иначе нельзя.
 */
export function alreadyDone(tool: string, reason: string): { ok: boolean; why: string } | null {
  if (!alreadyIsSuccess(tool)) return null;
  if (!/уже есть|уже существует/u.test(reason)) return null;
  return { ok: true, why: "цель была достигнута раньше — это успех, а не провал" };
}

/** Отметка для будущего запуска — по результату шага. */
export function remember(tool: string, params: Record<string, string> | undefined, ok: boolean, now: number): Past {
  return { print: print(tool, params), done: ok, at: now };
}

/**
 * Сводка по плану перед повторным запуском.
 *
 * Числом: «сделано раньше: 3 из 5, остальные 2 выполню». Без числа человек не знает,
 * повторяет он всё или доделывает.
 */
export function summary(verdicts: readonly Verdict[]): string {
  const skip = verdicts.filter((item) => item.kind === "skip").length;
  if (skip === 0) return `сделано раньше: 0 из ${verdicts.length}, выполню всё`;
  if (skip === verdicts.length) return `сделано раньше: всё (${skip} из ${verdicts.length}) — повторять нечего`;
  return `сделано раньше: ${skip} из ${verdicts.length}, остальные ${verdicts.length - skip} выполню`;
}
