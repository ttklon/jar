/**
 * Шаг 464: рецепты — 20 фраз, которые работают, и 20, которые честно отказывают.
 *
 * Список «что можно сказать» полезен, но односторонний: человек пробует похожие
 * фразы и получает отказы, которых не ждал. **Список отказов так же важен**, как
 * список успехов: он показывает **границу**, и человек перестаёт угадывать.
 *
 * Поэтому двадцать на двадцать, и в паре:
 *
 *  * успех — фраза и что будет;
 *  * отказ — фраза и **почему** откажет, причём отказы не «ерундовые» («абракадабра»),
 *    а **правдоподобные**: «напиши маме», «купи хлеб», «удали всё с диска».
 *
 * Именно правдоподобные отказы и создают доверие: человек видит, что программа
 * знает свои границы.
 */

/** Рецепт. */
export interface Recipe {
  /** Фраза. */
  readonly said: string;
  /** Что будет — при успехе; при отказе — почему. */
  readonly what: string;
  /** Группа — чтобы двадцать не оказались двадцатью вариациями одного. */
  readonly kind: string;
}

/** Сколько должно быть. */
export const NEEDED = 20;

/**
 * Проверить список.
 *
 * Нарушения: не двадцать, повторы, один жанр, отказ без причины.
 */
export function check(list: readonly Recipe[], label: string): string[] {
  const problems: string[] = [];

  if (list.length !== NEEDED) problems.push(`${label}: ${list.length} вместо ${NEEDED} — нужно ровно двадцать`);

  const seen = new Set<string>();
  for (const item of list) {
    const key = item.said.toLowerCase().replace(/\s+/g, " ").trim();
    if (seen.has(key)) problems.push(`${label}: «${item.said}» повторяется`);
    seen.add(key);
  }

  const kinds = new Set(list.map((item) => item.kind));
  if (kinds.size < 5) problems.push(`${label}: жанров ${kinds.size}, а нужно не меньше пяти — иначе это двадцать вариаций одного`);

  const empty = list.filter((item) => item.what.trim() === "").map((item) => item.said);
  if (empty.length > 0) problems.push(`${label}: без объяснения — ${empty.join(", ")}`);

  return problems;
}

