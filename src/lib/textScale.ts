/**
 * Шаг 235: масштаб шрифта 125/150/200% проверяется в тестах вёрстки.
 *
 * Почему «в тестах», а не «посмотрим глазами». Масштаб шрифта в Windows — не
 * зум браузера: он увеличивает **весь текст** интерфейса, а коробки вокруг
 * остаются прежними, если их задали в пикселях. Дальше три вещи, которые видно
 * только при большом масштабе и которые легко не заметить «на глаз», потому что
 * смотреть будут на 100%:
 *
 *  * **текст обрезается** — в кнопке высотой 32 px строка 200% не влезает, и
 *    вместо «Сбросить фильтры» человек видит «Сбросить фил…»;
 *  * **соседние цели слипаются** — подпись вылезает за коробку и накрывает
 *    следующую кнопку;
 *  * **строка ломается по слогам** — при 200% в узкой колонке остаётся два-три
 *    знака в строке, и текст читается по буквам.
 *
 * Правило модуля: размеры считаются **от базового шрифта**, и при масштабе
 * коробка растёт вместе со строкой — до предела, за которым начинается прокрутка
 * (прокрутка честнее обрезания).
 *
 * Чего модуль не делает: не выбирает «правильный» масштаб и не отключает
 * большой. Отключить масштаб — значит сказать человеку «твои глаза не наши
 * проблемы».
 */

/** Масштабы, которые обещаны. Список закрытый: 100% — база. */
export const SCALES = [1, 1.25, 1.5, 2] as const;
export type Scale = (typeof SCALES)[number];

/** Базовая строка: 14 px — обычный размер интерфейса. */
export const BASE_LINE = 14;

/** Базовые размеры коробок при 100%. */
export const BASE = {
  /** Высота кнопки. */
  button: 32,
  /** Отступы внутри кнопки по горизонтали. */
  padding: 12,
  /** Базовая ширина колонки. */
  column: 236,
} as const;

/** Что получается при масштабе. */
export interface Metrics {
  /** Размер строки. */
  line: number;
  /** Высота кнопки: растёт со строкой, а не стоит на месте. */
  button: number;
  /** Внутренний отступ по горизонтали. */
  padding: number;
  /** Ширина боковой колонки: текст крупнее — колонка шире. */
  column: number;
  /** Нужна ли прокрутка вместо обрезания. */
  scroll: boolean;
}

/**
 * Размеры при масштабе.
 *
 * Кнопка — это строка плюс вертикальные отступы: так она растёт **вместе** с
 * текстом, а не остаётся 32 px при строке 28. Прокрутка включается на 200%:
 * коробка, выросшая вдвое, уже не влезает в минимум 1024×600, и обрезать текст
 * хуже, чем дать прокрутку.
 */
export function metrics(scale: Scale): Metrics {
  const line = Math.round(BASE_LINE * scale);
  // Вертикальные отступы — четверть строки с каждой стороны: строка всегда
  // влезает, потому что коробка считается **от неё**, а не наоборот.
  const button = line + Math.round(line / 2);
  const padding = Math.round(BASE.padding * scale);
  const column = Math.round(BASE.column * Math.min(scale, 1.5));
  return { line, button, padding, column, scroll: scale >= 2 };
}

/**
 * Влезает ли подпись в кнопку — по **числу знаков**, а не «примерно».
 *
 * Оценка ширины знака — 0,55 строки: средняя для кириллицы в системном шрифте.
 * Оценка названа оценкой: точная ширина требует шрифта, а проверять надо до
 * отрисовки.
 */
export const CHAR_WIDTH = 0.55;

/**
 * Сколько знаков подписи влезает в кнопку такой ширины.
 *
 * Возвращается **число**, а не «да/нет»: по числу видно, насколько не влезает, и
 * это можно назвать в отчёте.
 */
export function fits(scale: Scale, width: number): number {
  const got = metrics(scale);
  const inner = width - got.padding * 2;
  if (inner <= 0) return 0;
  return Math.floor(inner / (got.line * CHAR_WIDTH));
}

/** Что не так при масштабе — списком, для теста и для отчёта. */
export function problems(scale: Scale, labels: readonly string[], width = 200): string[] {
  const found: string[] = [];
  const capacity = fits(scale, width);
  const got = metrics(scale);
  for (const label of labels) {
    if (label.length > capacity) {
      found.push(
        `«${label}» — ${label.length} знаков при масштабе ${Math.round(scale * 100)}%, ` +
          `влезает ${capacity}: нужно ${got.scroll ? "прокрутить" : "расширить"}`,
      );
    }
  }
  // Слипание целей: при большом масштабе строка вылезает за коробку.
  if (got.line > got.button) {
    found.push(`строка ${got.line} px выше кнопки ${got.button} px — подпись накроет соседнюю`);
  }
  return found;
}

/**
 * Ширина, нужная подписи, — чтобы её не пришлось обрезать.
 *
 * Зачем отдельно. При 200% «Сбросить фильтры» требует 295 px, а в узкой
 * раскладке (512 точек, 1024×600 при 200%) кнопка такой ширины не встанет в
 * строку с другими. Обрезать подпись нельзя — человек прочитает «Сбросить
 * фил…». Значит, на крупном масштабе кнопка занимает **всю ширину строки** и
 * переносит подпись, а не урезает её.
 */
export function needed(scale: Scale, label: string): number {
  const got = metrics(scale);
  return Math.ceil(label.length * got.line * CHAR_WIDTH) + got.padding * 2;
}

/**
 * Как показать кнопку: в строке с другими или во всю ширину.
 *
 * `full` — во всю ширину: подпись влезает, ряд ломается на две строки, и это
 * честнее обрезания. Правило по масштабу, а не по длине: при 200% любая подпись
 * длиннее шести знаков уже не встаёт рядом с соседкой.
 */
export function arrangement(scale: Scale, label: string, width: number): "row" | "full" {
  return needed(scale, label) > width ? "full" : "row";
}

/** Строка для журнала: масштаб назван числом. */
export function describe(scale: Scale): string {
  return `масштаб шрифта ${Math.round(scale * 100)}%: строка ${metrics(scale).line} px`;
}

/**
 * Разрешённый масштаб из того, что пришло. Необещанный масштаб приводится к
 * ближайшему обещанному **вверх**: увеличить — не обидеть, уменьшить —
 * отобрать у человека размер, который он выбрал.
 */
export function parse(value: number | null | undefined): Scale {
  if (!value || !Number.isFinite(value) || value <= 1) return 1;
  for (const scale of SCALES) {
    if (value <= scale) return scale;
  }
  return 2;
}
