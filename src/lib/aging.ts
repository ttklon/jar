/**
 * Шаг 279: старые факты стареют — раз в месяц спросить, актуально ли.
 *
 * Почему не «удалять старое». Срок уже есть у двух видов: временное забывается
 * (шаг 264), замеченное перестаёт подставляться (шаг 273). Оба решают **за**
 * человека, и оба правы только тогда, когда факт ничего не значит. А факт,
 * который значит, ведёт себя иначе: папка `D:\\Отчёты` может быть нужна годами, и
 * удалить её за давность — потеря. Замолчать её — тоже потеря, только тихая.
 *
 * Поэтому у старения не «срок годности», а **вопрос**. Раз в месяц — не чаще: за
 * месяц смена сезона видна, а за неделю нет, и вопрос каждую неделю становится
 * навязчивостью, на которую отвечают не читая.
 *
 * Четыре правила, без которых вопрос вреден:
 *
 *  1. **спрашивают не про всё сразу.** Один факт за раз: список из двадцати
 *     вопросов — это анкета, а её закрывают;
 *  2. **вопрос называет, что будет при каждом ответе.** «Ещё актуально?» без
 *     последствий — это просьба потратить внимание ни на что;
 *  3. **молчание — не «да».** Факт, про который не ответили, **остаётся** (не
 *     удаляется за невнимательность), но перестаёт подставляться молча: он
 *     теперь под вопросом, и это видно;
 *  4. **«нет» не стирает факт, а отправляет его в историю.** Человек может
 *     ошибиться, и «вернуть нельзя» (шаг 263) здесь неуместно: у стареющего
 *     факта обратный путь есть.
 */

import type { Sourced } from "./factOrigin";

/**
 * Через сколько факт считается старым.
 *
 * Тридцать дней — как у предпочтений (`STALE_MS`) и догадок (`SHOWN_LIFE`):
 * четвёртое число в той же памяти было бы случайным. Меняется сезон — меняются
 * папки.
 */
export const OLD_MS = 30 * 24 * 60 * 60 * 1000;

/**
 * Как часто спрашивать.
 *
 * Тоже месяц, но это **другой** срок: «факт старый» и «пора спросить» совпадают
 * не всегда. Спросили и не ответили — следующий раз через месяц, а не завтра.
 */
export const ASK_EVERY_MS = 30 * 24 * 60 * 60 * 1000;

/** Что спрашивают про факт. */
export interface Ask {
  readonly fact: Sourced;
  /** Когда спрашивать: мс. */
  readonly at: number;
  /** Что будет при «да». */
  readonly yes: string;
  /** Что будет при «нет». */
  readonly no: string;
}

/**
 * Какой факт спросить следующим.
 *
 * Один, самый старый: если спрашивать самый свежий, до старых очередь не дойдёт
 * никогда. И не тот, о котором только что спрашивали, — иначе один
 * неотвеченный вопрос повторяется до бесконечности и закрывает остальные.
 */
export function next(
  facts: readonly Sourced[],
  answered: Readonly<Record<string, number>>,
  now: number,
): Ask | null {
  // Спрашиваем про **любой** вид, включая сказанное: человек мог переехать, и
  // «моя папка — D:\Отчёты» через год может быть уже не его папкой.
  const candidates = facts
    .filter((fact) => now - fact.at >= OLD_MS)
    .filter((fact) => {
      const asked = answered[key(fact)];
      // Спросили недавно — не спрашиваем снова, даже если не ответили.
      return asked === undefined || now - asked >= ASK_EVERY_MS;
    })
    .sort((a, b) => a.at - b.at);

  const fact = candidates[0];
  if (fact === undefined) return null;

  return {
    fact,
    at: fact.at,
    yes: `${fact.value} — обновим дату, и я перестану спрашивать на месяц`,
    no: `${fact.value} — уйдёт в историю: подставляться не будет, но вернуть можно`,
  };
}

/** Ответ человека. */
export type Answer = "yes" | "no" | "later";

/**
 * Что стало с фактом после ответа.
 *
 * «Позже» — не «нет»: человек не сказал, что факт неверен, он сказал, что сейчас
 * не до этого. Поэтому дата не меняется, а вопрос откладывается; подставляться
 * факт продолжает — он ведь не опровергнут.
 */
export function apply(
  fact: Sourced,
  answer: Answer,
  now: number,
): { fact: Sourced; at: number | null; said: string } {
  if (answer === "yes") {
    // Обновляем дату: подтверждение делом — это новое знание о факте.
    return {
      fact: { ...fact, at: now },
      at: now,
      said: "оставил: спрошу снова через месяц",
    };
  }
  if (answer === "no") {
    return {
      fact: { ...fact, at: now, origin: "imported" },
      at: now,
      said: "убрал из подстановки: факт в истории, вернуть можно",
    };
  }
  return { fact, at: now, said: "хорошо, спрошу позже" };
}

/**
 * Что сказать, когда спрашивать нечего.
 *
 * «Всё актуально» — не то же, что «вопросов нет»: первое утверждение о фактах,
 * которого программа не проверяла.
 */
export function nothing(facts: readonly Sourced[], now: number): string {
  if (facts.length === 0) return "память пуста — спрашивать нечего";
  const old = facts.filter((fact) => now - fact.at >= OLD_MS).length;
  if (old === 0) return "всё свежее: среди фактов нет ни одного старше месяца";
  return `старых ${old}, но про каждый спрашивали меньше месяца назад — вернусь позже`;
}

/** Сколько фактов ждут вопроса — для сводки. */
export function waiting(
  facts: readonly Sourced[],
  answered: Readonly<Record<string, number>>,
  now: number,
): number {
  return facts.filter((fact) => {
    if (now - fact.at < OLD_MS) return false;
    const asked = answered[key(fact)];
    return asked === undefined || now - asked >= ASK_EVERY_MS;
  }).length;
}

function key(fact: Sourced): string {
  return `${fact.kind}:${fact.value}`;
}
