/**
 * Шаг 242: adversarial-набор — обход подтверждения, чужие пути, подделка результата.
 *
 * Почему отдельный набор, а не «ещё несколько тестов». Обычные проверки
 * спрашивают: «работает ли подтверждение?» — и это слабый вопрос, потому что на
 * него отвечает и подтверждение, которое обходится первой же фразой. Настоящий
 * вопрос другой: **что нужно сделать, чтобы правило перестало действовать?**
 * Набор перечисляет такие попытки, и каждая отвечает, где правило держится.
 *
 * Три семейства, и все три встречаются в жизни:
 *
 *  1. **обход подтверждения** — «да, и удали ещё», «я уже говорил да», молчание
 *     как согласие, вложенная просьба внутри согласия;
 *  2. **чужие пути** — `..\\`, длинное имя `\\\\?\\`, символьная ссылка на другой
 *     диск, путь из переменной окружения, который ведёт не туда;
 *  3. **подделка результата** — «сделано» без проверки, доказательство от самого
 *     агента («я проверил»), отчёт, который совпадает с ожиданием по построению.
 *
 * Модуль **не содержит правил**. Он содержит попытки и то, чем правило
 * отчитывается: `attack()` возвращает, удержалось ли правило. Правила живут там,
 * где живут (`consent.ts`, `capability`, проверка доказательств), и набор не
 * дублирует их — иначе он проверял бы сам себя.
 *
 * Чего модуль не делает: не запускает нападение на настоящую файловую систему.
 * Попытки — данные; проверяет их тест, а не пользователь.
 */

/** Семейство попытки. */
export type Family = "consent" | "path" | "proof";

/** Одна попытка: что пробуют и на что смотрят. */
export interface Attempt {
  /** Устойчивый ключ: по нему тест и говорит, что упало. */
  readonly id: string;
  readonly family: Family;
  /** Что человек увидел бы в журнале: попытка словами. */
  readonly what: string;
  /** Правило, которое обязано удержаться. */
  readonly rule: string;
}

