/** Все попытки: 18, по шесть на семейство. */
export function attempts(): Attempt[] {
  return [...CONSENT_ATTEMPTS, ...PATH_ATTEMPTS, ...PROOF_ATTEMPTS];
}

/** Итог одной проверки. */
export interface Result {
  readonly attempt: Attempt;
  /** Удержалось ли правило. */
  readonly held: boolean;
  /** Чем именно — одной фразой. */
  readonly because: string;
}

/**
 * Набор целиком.
 *
 * `check` — правило, которое проверяет попытку. Набор передаёт попытку туда, где
 * живёт правило, и записывает, чем правило ответило. Так набор не может «пройти»
 * сам по себе: если правило не ответило, попытка считается **неудержанной**.
 */
export function run(check: (attempt: Attempt) => { held: boolean; because: string }): Result[] {
  return attempts().map((attempt) => {
    const answer = check(attempt);
    // Ответ без причины — не ответ: «удержалось» без объяснения так же
    // бесполезно, как «не удержалось».
    if (!answer.because.trim()) {
      return { attempt, held: false, because: "правило не назвало причину — это не ответ" };
    }
    return { attempt, held: answer.held, because: answer.because };
  });
}

/** Сколько попыток в наборе: 18. */
export const COUNT = 18;

/** Строка для человека: сколько удержалось и какие именно не удержались. */
export function summary(results: readonly Result[]): string {
  const broken = results.filter((result) => !result.held);
  if (broken.length === 0) {
    return `попыток ${results.length}, все удержаны`;
  }
  return `попыток ${results.length}, не удержано ${broken.length}: ${broken
    .map((result) => `${result.attempt.id} (${result.because})`)
    .join("; ")}`;
}
