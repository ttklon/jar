import { describe, expect, it } from "vitest";
import { diff, notResume, open, preview, rebuild } from "./repeatEdited";

/**
 * Шаг 375: повторить дело — с изменённой фразой. Естественная правка.
 */

describe("правится фраза, а не поля формы", () => {
  it("фраза открывается как есть", () => {
    const got = open({ said: "почисти загрузки", did: "удалено 12 файлов" }, "почисти загрузки старше месяца");
    expect(got.said).toBe("почисти загрузки старше месяца");
  });

  it("разница видна словами, а не сравнением текстов", () => {
    const got = open({ said: "почисти загрузки", did: "" }, "почисти загрузки старше месяца");
    expect(got.diff.join()).toContain("добавлено: старше, месяца");
  });

  it("убрано и добавлено — отдельно", () => {
    expect(diff("почисти загрузки старше месяца", "почисти рабочий стол")).toEqual([
      "убрано: загрузки, старше, месяца",
      "добавлено: рабочий, стол",
    ]);
  });

  it("ничего не изменилось — разницы нет", () => {
    expect(diff("почисти загрузки", "Почисти загрузки.")).toEqual([]);
  });
});

describe("план строится заново", () => {
  it("иначе «другая папка» окажется в фразе, а в плане — старая", () => {
    expect(rebuild()).toContain("план строится заново");
  });
});

describe("до запуска видно последствия", () => {
  it("фраза, разница и предупреждение", () => {
    const edit = open({ said: "почисти загрузки", did: "" }, "почисти загрузки старше месяца");
    const lines = preview(edit, true);
    expect(lines[0]).toBe("Повторить: почисти загрузки старше месяца");
    expect(lines.join()).toContain("меняет файлы");
    expect(lines.join()).toContain("а не «доделает» прошлое");
  });

  it("без изменений — только фраза", () => {
    const edit = open({ said: "проверь диск", did: "" }, "проверь диск");
    expect(preview(edit, false).length).toBe(1);
  });
});

describe("повтор — не продолжение", () => {
  it("новая запись в журнале", () => {
    const got = notResume();
    expect(got).toContain("новое дело");
    expect(got).toContain("свою запись");
  });
});
