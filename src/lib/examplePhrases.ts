/**
 * Шаг 472: каждая фраза в примерах проверяется тестом — примеры не устаревают.
 *
 * Пример в документации — это **обещание**: «скажите так, и будет вот так». Через
 * три месяца рука меняется, фраза перестаёт разбираться, и пример молча врёт:
 * человек говорит, ничего не происходит, и решает, что программа не работает.
 *
 * Поэтому каждый пример проверяется **машинно**:
 *
 *  * фраза проходит разбор (шаг 022) и попадает в **конкретную руку**;
 *  * фраза **не** оказывается опасной без предупреждения;
 *  * для фразы, которая в примере названа работающей, разбор возвращает
 *    уверенность не ниже порога.
 *
 * Пример, который перестал работать, — **красный тест**, а не заметка «поправить
 * документацию».
 */

/** Пример: фраза и обещанный исход. */
export interface Example {
  /** Фраза, как её скажет человек. */
  readonly said: string;
  /** Рука, в которую она должна попасть. */
  readonly hand: string;
  /** Что видит человек — одна строка. */
  readonly gets: string;
}

/** Уверенность разбора, ниже которой пример нельзя обещать. */
export const MIN_CONFIDENCE = 0.6;

/** Разбор — вход извне, чтобы тест мог подставить. */
export interface Parse {
  /** Рука; `null` — не разобралось. */
  readonly hand: string | null;
  /** Уверенность 0..1. */
  readonly confidence: number;
  /** Опасная ли рука. */
  readonly dangerous: boolean;
}

/** Какие примеры сломались. */
export interface Result {
  readonly ok: boolean;
  /** Ломающиеся примеры — текстом, чтобы было видно, какой. */
  readonly broken: string[];
  /** Что сказать человеку. */
  readonly said: string;
}

/**
 * Проверить примеры против разбора.
 *
 * `parse` — функция разбора: тест подставляет свою, приложение — настоящую.
 */
export function check(examples: readonly Example[], parse: (said: string) => Parse): Result {
  const broken: string[] = [];

  for (const example of examples) {
    const got = parse(example.said);

    if (got.hand === null) {
      broken.push(`«${example.said}» — больше не разбирается`);
      continue;
    }
    if (got.hand !== example.hand) {
      broken.push(`«${example.said}» — попадает в «${got.hand}», а обещано «${example.hand}»`);
      continue;
    }
    if (got.confidence < MIN_CONFIDENCE) {
      broken.push(`«${example.said}» — уверенность ${got.confidence.toFixed(2)}, а обещано не ниже ${MIN_CONFIDENCE}`);
      continue;
    }
    if (got.dangerous && !example.gets.includes("спрос")) {
      broken.push(`«${example.said}» — рука опасная, а в примере не сказано, что спросит`);
    }
  }

  return {
    ok: broken.length === 0,
    broken,
    said: broken.length === 0
      ? `все ${examples.length} примеров работают: каждая фраза попадает туда, куда обещано`
      : `сломались примеры (${broken.length}): ${broken.join("; ")}`,
  };
}

/**
 * Что делать со сломанным примером.
 *
 * Два исхода, и оба честные: либо фраза должна работать (тогда это дефект разбора),
 * либо пример больше не обещают (тогда его убирают, а не оставляют «в честь».
 */
export function fix(): string[] {
  return [
    "если фраза должна работать — это дефект разбора, и он исправляется в коде, а не в примере",
    "если фраза больше не нужна — пример убирают и говорят об этом в changelog (шаг 466)",
  ];
}

/**
 * Чего проверка не делает.
 *
 * Три запрета: главное — не «поправить документацию».
 */
export function notDo(): string[] {
  return [
    "не правит пример под то, что получилось: пример — это обещание",
    "не пропускает пример с уверенностью ниже порога «пока так»",
    "не оставляет в примерах опасную руку без слова «спросит»",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу условий.
 */
export function checks(): string[] {
  return [
    "каждая фраза примера попадает в обещанную руку",
    "уверенность не ниже порога, а не «разобралось хоть как-то»",
    "опасная рука в примере названа той, что спрашивает",
  ];
}
