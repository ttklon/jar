import { describe, expect, it } from "vitest";
import { STALL_LINE, STALL_MS, decide, doingLine, settled, tail } from "./firstWords";

/**
 * Шаг 41: первый звук ответа — до конца генерации.
 *
 * Главная задержка разговора — не распознавание и не сеть, а ожидание конца
 * абзаца. Но «сказать раньше» не значит «сказать обрывок»: произносится только
 * **законченное**, иначе голос обрывается на «я нашёл три файла, но», и это хуже
 * молчания.
 */
describe("что можно произносить", () => {
  it("законченное предложение — можно, обрывок — нет", () => {
    expect(settled("Нашёл три файла.")).toBe("Нашёл три файла.");
    expect(settled("Нашёл три файла, но")).toBe("");
    // Запятая и тире — не граница: после них фраза не закончена.
    expect(settled("Смотрю —")).toBe("");
  });

  it("произносится всё законченное, остаток держится до следующего куска", () => {
    // Режем по последней границе, а не по первой: в потоке куски приходят как
    // получится, и ждать первую точку значит ждать конца ответа.
    expect(settled("Первое. Второе. Треть")).toBe("Первое. Второе.");
    expect(settled("Готово… и ещё")).toBe("Готово…");
  });

  it("пустое и пробелы — не фраза", () => {
    expect(settled("")).toBe("");
    expect(settled("   \n")).toBe("");
  });

  it("сказанное не повторяется", () => {
    // Поток присылает накопительный текст; без этого правила голос повторял бы
    // начало ответа на каждом куске.
    expect(tail("Первое. Второе.", "Первое.")).toBe(" Второе.");
    expect(tail("Начало", "")).toBe("Начало");
  });
});

describe("решение по куску", () => {
  it("есть законченное — говорим", () => {
    expect(decide("Нашёл.", "", 100)).toEqual({ kind: "speak", text: "Нашёл." });
  });

  it("не закончено — ждём, но недолго", () => {
    expect(decide("Нашёл три", "", 100)).toEqual({ kind: "wait" });
    // Молчание дольше секунды читается как поломка: честнее сказать, что думаем.
    expect(decide("Нашёл три", "", STALL_MS)).toEqual({ kind: "stall" });
    expect(STALL_LINE).toContain("думаю");
  });

  it("если говорить есть что — говорим, а не жалуемся на ожидание", () => {
    // Правило про молчание последнее: сказанное важнее ожидания.
    expect(decide("Готово.", "", 5000)).toEqual({ kind: "speak", text: "Готово." });
  });
});

describe("что сказать, пока ответа нет", () => {
  it("называется действие, а не обещание времени", () => {
    // «Секунду, сейчас посмотрю» — обещание времени, которого мы не знаем.
    expect(doingLine("папку")).toBe("смотрю: папку");
    expect(doingLine("папку")).not.toContain("секунд");
  });

  it("действия нет — честное «ещё думаю»", () => {
    expect(doingLine("")).toBe(STALL_LINE);
    expect(doingLine("  ")).toBe(STALL_LINE);
  });
});
