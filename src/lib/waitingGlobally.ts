/**
 * Шаг 376: дело, которое ждёт подтверждения, видно из любого экрана — не потерять.
 *
 * Дело, которое **идёт**, можно не заметить и оно всё равно закончится (шаг 367).
 * Дело, которое **ждёт подтверждения**, без человека не сдвинется с места
 * никогда. Поэтому оно настойчивее:
 *
 *  * **видно везде и заметнее**, чем идущее;
 *  * **в трее — значок и подсказка**, а не тишина;
 *  * **не исчезает само** через несколько секунд, как уведомление (шаг 324):
 *    исчезнувший вопрос — это вопрос без ответа;
 *  * **но и не блокирует работу**: человек может продолжать, ответ подождёт.
 *
 * Ловушка, ради которой этот шаг отдельный: **вопрос перекрывает сам себя**. Если
 * новый вопрос приходит поверх старого, ответив на нижний, человек отвечает не
 * зная, на что.
 */

/** Ждущий вопрос. */
export interface Waiting {
  /** Что за дело. */
  readonly what: string;
  /** Что именно спрашивают. */
  readonly ask: string;
  /** Сколько минут ждёт. */
  readonly since: number;
  /** Можно ли отложить. */
  readonly canDefer: boolean;
}

/** Что показываем на других экранах. */
export function badge(items: readonly Waiting[]): string | null {
  if (items.length === 0) return null;
  if (items.length === 1) return `${items[0]!.what}: ждёт ответа — ${items[0]!.ask}`;
  return `${items.length} ${plural(items.length, "дело ждёт", "дела ждут", "дел ждут")} ответа: ${items.map((item) => item.what).join(", ")}`;
}

/**
 * Сколько ждём прежде чем напомнить.
 *
 * Через пять минут — вежливое напоминание, через тридцать — «это дело не идёт без
 * вас». Не чаще: повтор каждую минуту приучает закрывать не читая.
 */
export function remindAfter(since: number): string | null {
  if (since < 5) return null;
  if (since < 30) return "ждёт ответа уже несколько минут";
  return "дело не идёт без вашего ответа: можно отложить, если сейчас не до него";
}

/**
 * Очередь вопросов.
 *
 * Новый вопрос **не перекрывает** старый: он встаёт за ним. Иначе ответ на нижний
 * даётся вслепую.
 */
export function queue(items: readonly Waiting[]): string[] {
  if (items.length === 0) return [];
  const first = items[0]!;
  const rest = items.slice(1);
  const head = [`сейчас спрашиваю: ${first.what} — ${first.ask}`];
  if (rest.length > 0) head.push(`после него ${rest.length} ${plural(rest.length, "вопрос", "вопроса", "вопросов")}: ${rest.map((item) => item.what).join(", ")}`);
  return head;
}

/**
 * Отложить.
 *
 * Отложить — не отменить: дело не выполнится само, оно подождёт. И вернуться к
 * нему надо не «когда-нибудь»: при следующем же окне без дела.
 */
export function defer(item: Waiting): { ok: boolean; said: string } {
  if (!item.canDefer) {
    return { ok: false, said: `«${item.what}» отложить нельзя: если сейчас не до него, дело придётся отменить — оно изменит файлы` };
  }
  return { ok: true, said: `«${item.what}» отложено: спрошу в следующее окно без дела` };
}

/**
 * Чего ожидание не делает.
 *
 * Три соблазна: исчезнуть, перекрыть, заблокировать.
 */
export function notDo(): string[] {
  return [
    "не исчезает через несколько секунд: исчезнувший вопрос — это вопрос без ответа",
    "не перекрывает другой вопрос: ответ на нижний даётся вслепую",
    "не блокирует работу: остальное приложение работает, дело просто ждёт",
  ];
}

/** Русское склонение по числу. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
