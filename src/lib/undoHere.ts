/**
 * Связать отчёт с откатом: что из сделанного можно вернуть прямо здесь (шаг 120).
 *
 * Дефект. Отчёт и откат живут в разных местах:
 *
 *  * **откат без отчёта**: чтобы понять, что вернуть, надо помнить, что делал;
 *  * **отчёт без отката**: «сделано: 5 шагов» и ни одного пути вернуть — человек ищет
 *    экран «Откат» и не знает, относится ли он к этому делу;
 *  * **откат обещает невозможное**: кнопка «отменить» у необратимого шага (шаг 105:
 *    сделанное названо неотменяемым) — ложь, а не удобство;
 *  * **частичный откат молчит**: 3 из 5 вернуть можно, 2 — нет, и приложение
 *    показывает «отменить всё» одной кнопкой.
 *
 * Правило: **у каждого шага отчёта видно, можно ли его вернуть, и одним нажатием**.
 *
 *  1. **Рядом с шагом** — «вернуть» или причина, по которой нельзя. Не на другом
 *     экране: человек смотрит отчёт, когда решает откатить.
 *  2. **Отказ назван причиной**, а не серой кнопкой: «нельзя: файл уже перезаписан».
 *  3. **Частичный откат разрешён, но назван**: «верну 3 из 5, два останутся».
 *  4. **Один клик** на откат того, что вернуть можно: выбор «что именно» — только там,
 *     где шагов больше одного.
 *  5. **Порядок отката — обратный**: вернуть последнее первым, иначе откат ломает то,
 *     что ещё стоит.
 *
 * Почему не «откатить всё одной кнопкой». «Всё» включает то, что вернуть нельзя, и
 * кнопка либо врёт, либо отказывает целиком — при том что три шага вернуть можно.
 */

/** Шаг отчёта — с точки зрения отката. */
export interface Undoable {
  /** Номер в плане, с единицы. */
  position: number;
  /** Что сделано — словами. */
  what: string;
  /** Можно ли вернуть. */
  undoable: boolean;
  /** Почему нельзя; пусто, если можно. */
  refusal?: string;
}

/** Что показать рядом с отчётом. */
export interface Here {
  /** Шаги в порядке отката — **обратном** порядку выполнения. */
  steps: Undoable[];
  /** Сколько вернуть можно. */
  can: number;
  /** Строка для человека. */
  said: string;
  /** Нужен ли выбор: `false` — откатить можно одним нажатием. */
  choose: boolean;
}

/**
 * Связать отчёт с откатом.
 *
 * Порядок — обратный: вернуть **последнее первым**. Иначе откат шага 1 ломает шаг 2,
 * который ещё стоит.
 */
export function here(steps: readonly Undoable[]): Here {
  const reversed = [...steps].reverse();
  const can = steps.filter((step) => step.undoable).length;
  if (steps.length === 0) {
    return { steps: [], can: 0, said: "откатывать нечего — шагов не было", choose: false };
  }
  if (can === 0) {
    return {
      steps: reversed,
      can: 0,
      // Не «недоступно»: причина у каждого шага, и она называется.
      said: "вернуть нельзя ничего — причины у каждого шага",
      choose: false,
    };
  }
  if (can === steps.length) {
    return {
      steps: reversed,
      can,
      said: `вернуть можно всё: ${can} из ${steps.length} — одним нажатием`,
      choose: false,
    };
  }
  return {
    steps: reversed,
    can,
    // Частичный откат назван: «верну 3 из 5» — это правда, «отменить всё» — нет.
    said: `вернуть можно ${can} из ${steps.length}, остальные ${steps.length - can} останутся`,
    choose: true,
  };
}

/**
 * Что сказать у шага.
 *
 * Отказ — причиной, а не серой кнопкой: серое не объясняет, почему.
 */
export function at(step: Undoable): string {
  if (step.undoable) return "можно вернуть";
  return `нельзя вернуть: ${step.refusal?.trim() || "причина не названа"}`;
}

/**
 * Что вернётся одним нажатием.
 *
 * Возвращает **только те шаги, что можно вернуть**, в порядке отката. Это и есть
 * содержимое кнопки «вернуть сделанное», а не «всё».
 */
export function oneClick(got: Here): Undoable[] {
  return got.steps.filter((step) => step.undoable);
}

/**
 * Итог после отката.
 *
 * Отдельная функция, потому что «сколько вернули» и «сколько не смогли» — два факта,
 * и сводить их в «отменено» значит скрывать отказ.
 */
export function after(done: readonly string[], refused: readonly string[], total: number): string {
  if (done.length === 0 && refused.length === 0) return "нечего было возвращать";
  const parts: string[] = [];
  if (done.length > 0) parts.push(`вернул ${done.length} из ${total}`);
  if (refused.length > 0) parts.push(`не смог ${refused.length}: ${refused.join("; ")}`);
  return parts.join(", ");
}

/**
 * Стоит ли предлагать откат.
 *
 * Не всегда: если всё необратимо, кнопка была бы ложью (шаг 105). Тогда — только
 * строки с причинами.
 */
export function offer(got: Here): boolean {
  return got.can > 0;
}
