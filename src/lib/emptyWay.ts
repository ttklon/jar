/**
 * Понятный экран «ничего не найдено» с тремя следующими шагами (шаг 188).
 *
 * Дефект. Пустота в интерфейсе — тупик. «Ничего не нашлось» отвечает на вопрос
 * «есть ли это здесь» и **не отвечает** на «что мне теперь делать»: человек либо
 * повторяет то же слово ещё раз, либо уходит.
 *
 * Что при этом бывает не так:
 *
 *  * **пусто по-разному.** «Такого действия нет», «есть, но сейчас недоступно»,
 *    «не понял фразу», «нечего показывать, потому что ещё ничего не делали» — это
 *    четыре разных пустоты, и один текст на все четыре говорит неправду в трёх;
 *  * **совет без адреса.** «Переформулируйте» — это не шаг: непонятно, что
 *    менять. «Скажите «размер папки» — так ищется» — шаг;
 *  * **три, а не десять.** Десять вариантов читают как меню и не выбирают ни
 *    одного; три — это выбор, который делают;
 *  * **ни одного тупика.** У каждого предложения есть **действие**: что набрать,
 *    какой экран открыть, где посмотреть список;
 *  * **пустота не повторяется молча.** Если человек уже второй раз ищет то же и
 *    получает то же, надо это назвать: «второй раз не нашлось то же самое» — а не
 *    показывать тот же текст.
 *
 * Модуль ничего не рисует: он отвечает, какая это пустота и что предложить.
 */

/** Почему пусто. */
export type Kind =
  /** Такого действия в реестре нет. */
  | "unknown"
  /** Действие есть, но сейчас не выполнится (нет прав, нет модели, нет папки). */
  | "blocked"
  /** Фраза не разобралась. */
  | "unclear"
  /** Показывать нечего: ещё ничего не делали. */
  | "nothing-yet"
  /** Поиск сломался — это не «не нашлось». */
  | "failed";

/** Что предложить. */
export interface Step {
  /** Что сделать — словами. */
  said: string;
  /** Что набрать или что нажать. Пусто — действие не текстовое. */
  act: string;
}

/** Экран пустоты. */
export interface Screen {
  kind: Kind;
  /** Заголовок — что именно случилось. */
  title: string;
  /** Почему так — одной фразой. */
  why: string;
  /** Три шага, у каждого — действие. */
  steps: Step[];
}

/**
 * Что предложить, когда ничего не нашлось.
 *
 * Порядок шагов — от «того же самого другими словами» к «другому месту»: сначала
 * правят запрос, потом идут смотреть списком. Третий шаг всегда возвращает
 * возможность **что-то сделать**, а не читать: иначе из тупика выходят в тупик.
 */
export function screen(kind: Kind, query = ""): Screen {
  const q = query.trim();
  const quoted = q.length > 0 ? `«${q}»` : "это";

  if (kind === "failed") {
    // Сбой поиска — не пустота: советовать «переформулируйте» значит свалить вину
    // за поломку на человека.
    return {
      kind,
      title: "поиск не сработал — это не «ничего не нашлось»",
      why: "ошибка поиска: список не прочитан, и «пусто» здесь ничего не доказывает",
      steps: [
        { said: "Повторите поиск", act: "Найти" },
        { said: "Откройте каталог целиком — он не зависит от поиска", act: "Что умею" },
        { said: "Проверьте, что реестр прочитан: экран состояния", act: "Состояние" },
      ],
    };
  }

  if (kind === "blocked") {
    return {
      kind,
      title: "действие есть, но сейчас не выполнится",
      why: "это не «нет такого»: оно есть в реестре, но упирается в предел — папки, права, модель или сеть",
      steps: [
        { said: "Посмотрите, чего не хватает: экран состояния", act: "Состояние" },
        { said: "Проверьте, что мне разрешено: «Что мне разрешено» на экране «Голос»", act: "Голос" },
        { said: "Выберите папку, если дело упирается в неё", act: "Голос" },
      ],
    };
  }

  if (kind === "unclear") {
    return {
      kind,
      title: `не понял ${quoted} — это не «такого нет»`,
      why: "фраза не разобралась: разница между «не понял» и «нет такого» важна, иначе человек ищет несуществующее",
      steps: [
        { said: "Скажите то же самое проще: что сделать и с чем", act: "создай папку на рабочем столе" },
        { said: "Посмотрите, как это называется в реестре", act: "Что умею" },
        { said: "Спросите своими словами на экране «Голос» — там разбор по смыслу", act: "Голос" },
      ],
    };
  }

  if (kind === "nothing-yet") {
    return {
      kind,
      title: "пока пусто — это не ошибка",
      why: "здесь появятся дела после первого: пустой список в начале — нормальное состояние, а не поломка",
      steps: [
        { said: "Скажите первое дело словами", act: "разбери Загрузки по папкам" },
        { said: "Или начните с готового сценария", act: "Сценарии" },
        { said: "Посмотрите, что умею, списком", act: "Что умею" },
      ],
    };
  }

  return {
    kind: "unknown",
    title: `по ${quoted} ничего нет — и это ответ`,
    why: "такого действия в реестре нет; «нет» лучше, чем «не понял»: человек не будет искать второй раз то же самое",
    steps: [
      { said: "Скажите иначе — по действию, а не по названию программы", act: "проверь свободное место на диске" },
      { said: "Посмотрите соседнее: каталог знает 835 действий словами", act: "Что умею" },
      { said: "Проверьте, что вообще возможно на этой машине", act: "Состояние" },
    ],
  };
}

/**
 * Повтор того же запроса.
 *
 * Второй раз тот же текст и тот же ответ — это уже не «не нашлось», а «не
 * меняется». Сказать об этом честно полезнее, чем показать тот же экран: человек
 * иначе решит, что нажатие не сработало.
 */
export function again(kind: Kind, query: string, previous: readonly string[]): string {
  const q = query.trim();
  if (q.length === 0 || !previous.includes(q)) return "";
  // Заголовок не повторяем: он уже на экране, и второй раз «ничего нет»
  // читается как две разные пустоты вместо одной.
  void screen(kind, q);
  return `«${q}» уже искали — ответ тот же`;
}

/**
 * Проверка, что экран не тупик: у каждого шага есть действие, и шагов ровно три.
 *
 * Тест на это — не формальность: «три шага» легко превращается в «три совета».
 */
export function usable(got: Screen): { ok: boolean; why: string } {
  // Сначала — совет без действия: это дефект в любом количестве, и сообщать
  // «шагов один» вместо «шаг без действия» значит лечить не то.
  const idle = got.steps.filter((step) => step.act.trim().length === 0);
  if (idle.length > 0) {
    return { ok: false, why: `без действия: ${idle.map((step) => step.said).join("; ")}` };
  }
  if (got.steps.length !== 3) {
    return { ok: false, why: `шагов ${got.steps.length}, а обещано три: больше — меню, меньше — не выбор` };
  }
  return { ok: true, why: "" };
}
