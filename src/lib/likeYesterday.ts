/**
 * Держать недосказанное: «сделай как вчера» должно найти вчерашнее (шаг 85).
 *
 * Дефект. Человек говорит «сделай как вчера» — и это **самая естественная**
 * фраза: он не хочет повторять пятнадцать слов о том, что уже говорил. А
 * приложение:
 *
 *  * **не понимает** и переспрашивает «что сделать?», хотя ответ у него есть —
 *    вчера это было сделано им же;
 *  * или, хуже, **понимает как попало** и делает что-то правдоподобное;
 *  * **не показывает, что именно** взяло из вчера: человек не может проверить,
 *    и в следующий раз не станет так говорить.
 *
 * Правило: **память — это не только факты, но и способы**.
 *
 *  1. Хранится **не текст фразы**, а **сделанное**: какие действия, с какими
 *     параметрами, по какому поводу. Текст «сделай отчёт за март» сам по себе
 *     ничего не значит — значит план.
 *  2. «Как вчера» ищет **конкретный день** (вчера, в прошлый раз, в пятницу), а
 *     не «что-нибудь похожее»: похожее — это угадывание.
 *  3. Найденное **показывается списком** до исполнения: человек проверяет, что
 *     взято именно то.
 *  4. Если вчера было **несколько дел**, а сказано одно — **выбрать не угадывая**:
 *     спросить, какое.
 *  5. Если вчера **ничего не было** — сказать прямо, а не делать похожее.
 *     Честное «не нашёл» дешевле неверного повтора.
 *
 * Почему не «взять последнее». Последнее — это не «вчера»: вчера в 9 утра была
 * одна работа, в 19 вечера — другая, а сегодня в 9 «как вчера» значит первую.
 * Разница между «последнее» и «тогда» — это разница между повтором и ошибкой.
 */

/** Сделанное дело: способ, а не фраза. */
export interface Done {
  /** Когда: начало дня, местное время, миллисекунды. */
  dayStart: number;
  /** Какие действия были выполнены, по порядку. */
  steps: string[];
  /** Параметры шагов — то, без чего повтор бессмысленен. */
  params: Record<string, string>;
  /** Что человек сказал тогда — для показа, а не для разбора. */
  said: string;
}

/** Что просит человек. */
export type When = "today" | "yesterday" | "last" | "named";

/**
 * Разбор «когда».
 *
 * «Вчера» — конкретный день, а не «недавно»: разница между повтором и ошибкой.
 */
export function when(phrase: string): When | null {
  const clean = phrase.toLowerCase();
  if (/сегодня/.test(clean)) return "today";
  if (/вчера|вчерашн/.test(clean)) return "yesterday";
  if (/в прошлый раз|как в последний раз|как обычно|прошлый раз/.test(clean)) return "last";
  if (/в (понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)/.test(clean)) return "named";
  return /как (?:вчера|обычно|в прошлый)/.test(clean) ? "last" : null;
}

/** Что найдено. */
export interface Found {
  /** Что брать — или ничего. */
  done: Done | null;
  /** Если подходящих несколько — сколько. */
  candidates: number;
  /** Почему так — для показа и теста. */
  why: string;
}

/**
 * Поиск сделанного.
 *
 * `dayStart` — начало **сегодняшнего** дня; всё, что раньше него на один день, —
 * вчера. Границы считаются по календарю, а не «24 часа назад»: вчера в 23:00 при
 * разговоре в 8 утра — это 9 часов, а сегодня в 9:00, если по часам, «вчера».
 */
export function find(history: readonly Done[], ask: When, todayStart: number): Found {
  if (history.length === 0) {
    return { done: null, candidates: 0, why: "до этого ничего не делалось — повторять нечего" };
  }

  const sorted = [...history].sort((left, right) => right.dayStart - left.dayStart);
  const DAY = 24 * 60 * 60 * 1000;

  let pool: Done[];
  switch (ask) {
    case "today":
      pool = sorted.filter((item) => item.dayStart >= todayStart);
      break;
    case "yesterday":
      pool = sorted.filter((item) => item.dayStart >= todayStart - DAY && item.dayStart < todayStart);
      break;
    case "last":
      pool = sorted.slice(0, 1);
      break;
    case "named":
      // Названный день — это «раньше», и берём ближайшее к названному: без
      // календаря разговорной фразы точнее не скажешь.
      pool = sorted.filter((item) => item.dayStart < todayStart);
      break;
  }

  if (pool.length === 0) {
    return {
      done: null,
      candidates: 0,
      why: ask === "yesterday" ? "вчера ничего не делалось — повторять нечего" : "такого дня в памяти нет",
    };
  }

  if (pool.length > 1) {
    // Выбрать не угадывая: показать и спросить, какое.
    return {
      done: null,
      candidates: pool.length,
      why: `подходит ${pool.length}: скажите, какое из них повторять`,
    };
  }

  const only = pool[0] as Done;
  return { done: only, candidates: 1, why: `взял то, что было сделано ${ask === "yesterday" ? "вчера" : "в прошлый раз"}` };
}

/**
 * Что будет повторено — списком, до исполнения.
 *
 * Иначе человек не может проверить, и в следующий раз не станет говорить «как
 * вчера» — то есть фраза перестала работать.
 */
export function plan(found: Found): string[] {
  if (found.done === null) return [found.why];
  const lines = [`«${found.done.said}»:`, ...found.done.steps.map((step, index) => `${index + 1}. ${step}`)];
  const params = Object.entries(found.done.params);
  if (params.length > 0) {
    lines.push(`с параметрами: ${params.map(([key, value]) => `${key} = ${value}`).join(", ")}`);
  }
  return lines;
}

/**
 * Параметры, которых не хватило.
 *
 * «Как вчера» с **сегодняшним** числом — не повтор вчерашнего: если вчера был
 * «отчёт за март», а сегодня говорят «как вчера», человек почти всегда имеет в
 * виду **то же действие с новыми данными**. Это надо назвать, а не молча
 * повторить устаревшее.
 */
export function stale(found: Found, now: number, dayMs = 24 * 60 * 60 * 1000): boolean {
  if (found.done === null) return false;
  return now - found.done.dayStart >= dayMs;
}

export function sayAge(found: Found, now: number): string | null {
  if (found.done === null) return null;
  const days = Math.floor((now - found.done.dayStart) / (24 * 60 * 60 * 1000));
  if (days <= 0) return null;
  return `это было ${days === 1 ? "вчера" : `${days} дн. назад`} — если нужны свежие данные, скажите заново`;
}

/**
 * Чего во фразе нет — то не придумывается.
 *
 * «Сделай как вчера» без найденного вчера — это не повод сделать похожее.
 * Честное «не нашёл» дешевле неверного повтора.
 */
export function nothing(ask: When): string {
  return ask === "yesterday"
    ? "вчера ничего не делалось — повторять нечего. Скажите словами, что сделать, и в следующий раз «как вчера» сработает"
    : "в памяти нет такого дня — повторить не могу. Скажите словами, что сделать";
}
