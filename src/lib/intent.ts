/**
 * Разбор намерения: глагол + объект, а не совпадение слов (шаг 81).
 *
 * Дефект. Сегодня фраза разбирается **общими словами**: ищутся слова в объекте
 * и глаголе, совпадения складываются в счёт (см. `planner.ts`). Из этого
 * следует ровно то, на что жалуется человек:
 *
 *  * «найди большие файлы» и «найди файл по имени» получают **одно и то же
 *    действие** — в обеих фразах есть «найди» и «файл». Но это разные дела:
 *    первое — поиск по размеру, второе — поиск по названию;
 *  * «удали старые отчёты» и «удали отчёты» — тоже «одно и то же», хотя первое
 *    требует правила «старые», а второе — уточнения, что удалять;
 *  * порядок слов **ничего не значит**: «открой папку в загрузках» и «в загрузках
 *    открой папку» — одно, а «папка открой загрузки» — тоже одно, хотя это
 *    бессмыслица.
 *
 * Правило: **у фразы есть глагол и объект, и они разные места в предложении**.
 *
 *  1. **Глагол — что делать**, и он один главный. «Найди и удали» — это **два
 *     действия** (шаг 83), а не глагол «найди-удали».
 *  2. **Объект — над чем делать**, и к нему прилипают **определения**: «большие»
 *     — к файлам, «вчерашние» — к отчётам. Определение меняет смысл, а не
 *     украшает фразу.
 *  3. **Разные определения — разные намерения**, даже когда глагол и объект
 *     совпадают. Это и есть ответ на вопрос, зачем разбор: «найди большие» и
 *     «найди по имени» — не одно действие.
 *  4. **Чего нет во фразе, того нет и в намерении**: если про размер не сказано,
 *     разбор не придумывает размер по умолчанию.
 *
 * Почему не «достаточно сильная модель поймёт». Модель поймёт, но она же и
 * **решит за человека**, а решать надо только то, что сказано. Разбор отдельно
 * от модели — это ещё и возможность показать человеку, как понята фраза
 * (шаг 86), прежде чем что-то сделать.
 */

/**
 * Глагол действия.
 *
 * Список вырос по **живым фразам каталога** (шаг 89): регрессия на 200 настоящих
 * примерах показала, что узнаётся только шестая часть. Добавлены те глаголы,
 * которыми люди действительно говорят («проверь», «настрой», «собери»), — но не
 * все 207 глаголов реестра: у редких хватает «неизвестно», и это честный ответ,
 * а не угадывание.
 */
export type Verb =
  | "найди"
  | "открой"
  | "удали"
  | "скопируй"
  | "перемести"
  | "покажи"
  | "запусти"
  | "напиши"
  | "создай"
  | "посчитай"
  | "переименуй"
  | "отправь"
  | "проверь"
  | "настрой"
  | "собери"
  | "сравни"
  | "измени"
  | "запиши"
  | "прочитай"
  | "переведи"
  | "составь"
  | "сожми"
  | "распакуй"
  | "восстанови"
  | "скрой"
  | "синхронизируй"
  | "зашифруй"
  | "отсортируй"
  | "неизвестно";

/** Определение объекта: то, что отличает «большие файлы» от «файла по имени». */
export type Qualifier = "размер" | "имя" | "дата" | "тип" | "место" | "нет";

/** Разобранная фраза. */
export interface Intent {
  /** Что делать. */
  verb: Verb;
  /** Над чем. */
  object: string;
  /** Какой именно объект — отличие, которое меняет действие. */
  qualifier: Qualifier;
  /** Слово-определение как его сказал человек («большие», «вчерашние»). */
  qualifierWord: string | null;
  /** Все глаголы по порядку: их может быть два (шаг 83). */
  verbs: Verb[];
}

/**
 * Слова-глаголы. Короткий список, потому что **больше не нужно**: глагол
 * действия в русской речи один, а остальные слова — объект и определения.
 */
const VERBS: [RegExp, Verb][] = [
  [/^(?:найди|найти|ищи|поищи|искать|находит|найдите)$/i, "найди"],
  [/^(?:открой|открыть|откройте)$/i, "открой"],
  // «Убери» намеренно **не** здесь: «убери шум из микрофона» — настройка, а не
  // удаление. Тест на живых фразах это поймал. «Убери» разбирается как
  // «неизвестно» — и человек поправит, а не потеряет файл.
  [/^(?:удали|удалить|сотри|стереть|удалите)$/i, "удали"],
  [/^(?:скопируй|скопировать|копируй|скопируйте)$/i, "скопируй"],
  [/^(?:перемести|переместить|перенеси|перенести|переместите)$/i, "перемести"],
  [/^(?:покажи|показать|выведи|покажите)$/i, "покажи"],
  [/^(?:запусти|запустить|запустите)$/i, "запусти"],
  [/^(?:напиши|написать|напишите)$/i, "напиши"],
  [/^(?:создай|создать|сделай|сделать|создайте)$/i, "создай"],
  [/^(?:посчитай|посчитать|сколько|посчитайте)$/i, "посчитай"],
  [/^(?:переименуй|переименовать|назови|переименуйте)$/i, "переименуй"],
  [/^(?:отправь|отправить|пошли|перешли|отправьте)$/i, "отправь"],
  [/^(?:проверь|проверить|проверьте|что)$/i, "проверь"],
  [/^(?:настрой|настроить|настройте)$/i, "настрой"],
  [/^(?:собери|собрать|соберите)$/i, "собери"],
  [/^(?:сравни|сравнить|сравните)$/i, "сравни"],
  [/^(?:измени|изменить|поменяй|измените)$/i, "измени"],
  [/^(?:запиши|записать|запишите)$/i, "запиши"],
  [/^(?:прочитай|прочитать|прочти|прочитайте)$/i, "прочитай"],
  [/^(?:переведи|перевести|переведите)$/i, "переведи"],
  [/^(?:составь|составить|составьте)$/i, "составь"],
  [/^(?:сожми|сжать|заархивируй|упакуй|заархивируйте)$/i, "сожми"],
  [/^(?:распакуй|распаковать|разархивируй|распакуйте)$/i, "распакуй"],
  [/^(?:восстанови|восстановить|верни|верните)$/i, "восстанови"],
  [/^(?:скрой|скрыть|спрячь|скройте)$/i, "скрой"],
  [/^(?:синхронизируй|синхронизировать|держи|синхронизируйте)$/i, "синхронизируй"],
  [/^(?:зашифруй|зашифровать|зашифруйте)$/i, "зашифруй"],
  [/^(?:отсортируй|сортировать|разложи|отсортируйте)$/i, "отсортируй"],
];

/**
 * Определения — то, что меняет смысл при том же глаголе и объекте.
 *
 * «Большие» — это размер, «по имени» — имя, «вчерашние» — дата, «в загрузках» —
 * место. Без этого различия «найди большие файлы» и «найди файл по имени» —
 * одно и то же действие, а это неправда.
 */
const QUALIFIERS: [RegExp, Qualifier][] = [
  [/(?:больш|крупн|тяжёл|тяжел|объём|объем|размеру|мегабайт|гигабайт|мб|гб)/i, "размер"],
  [/(?:по имени|по названию|имени|названию|называется|с именем)/i, "имя"],
  [/(?:вчера|сегодня|стары|новы|давн|за неделю|за месяц|за год|дате|по дате)/i, "дата"],
  [/(?:картинк|фото|документ|таблиц|музык|видео|pdf|png|jpg|txt|тип|формат)/i, "тип"],
  [/(?:в загрузк|в документ|на рабочем столе|в папке|в корне|в диске|место)/i, "место"],
];

/** Слова, которые ничего не значат для намерения, но бывают во фразе. */
const NOISE = new Set([
  "пожалуйста",
  "плиз",
  "мне",
  "надо",
  "нужно",
  "давай",
  "быстро",
  "сейчас",
  "все",
  "всё",
  "там",
]);

/** Объект по умолчанию, если названного нет: «найди» без объекта — вопрос, а не действие. */
function words(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .split(/[^\p{L}\p{N}]+/u)
    .filter((word) => word.length > 0 && !NOISE.has(word));
}

function verbOf(word: string): Verb {
  for (const [pattern, verb] of VERBS) {
    if (pattern.test(word)) return verb;
  }
  return "неизвестно";
}

/**
 * Разбор фразы.
 *
 * Порядок значим: **первое** слово-глагол — главное действие. Остальные
 * глаголы собираются в `verbs` — из них шаг 83 делает два дела.
 */
export function parse(phrase: string): Intent {
  const tokens = words(phrase);
  const verbs: Verb[] = [];
  for (const token of tokens) {
    const verb = verbOf(token);
    if (verb !== "неизвестно" && !verbs.includes(verb)) verbs.push(verb);
  }

  // Определение ищем по **всей** фразе: «по имени» — два слова, и по отдельности
  // они не значат ничего.
  const clean = phrase.toLowerCase().replace(/ё/g, "е");
  let qualifier: Qualifier = "нет";
  let qualifierWord: string | null = null;
  for (const [pattern, kind] of QUALIFIERS) {
    const found = pattern.exec(clean);
    if (found !== null) {
      qualifier = kind;
      qualifierWord = found[0];
      break;
    }
  }

  const object = tokens
    .filter((token) => verbOf(token) === "неизвестно" && !QUALIFIERS.some(([pattern]) => pattern.test(token)))
    .join(" ");

  return {
    verb: verbs[0] ?? "неизвестно",
    object,
    qualifier,
    qualifierWord,
    verbs: verbs.length > 0 ? verbs : ["неизвестно"],
  };
}

/**
 * Одно ли это намерение.
 *
 * Сравниваются **глагол, объект и определение** — все три. Совпадение только по
 * глаголу и объекту (сегодняшнее поведение) — это и есть дефект, ради которого
 * написан этот модуль.
 */
export function same(one: Intent, two: Intent): boolean {
  return one.verb === two.verb && one.object === two.object && one.qualifier === two.qualifier;
}

/**
 * Что человек сказал — словами.
 *
 * Это не для красоты: разбор надо **показать** (шаг 86), прежде чем действовать.
 * Человек должен увидеть «вы просите найти файлы по размеру» и поправить, если
 * разбор ошибся.
 */
export function say(intent: Intent): string {
  if (intent.verb === "неизвестно") {
    return "не понял, что делать: в фразе нет действия — скажите, например, «найди» или «открой»";
  }
  if (intent.object === "" && intent.verb !== "покажи") {
    return `${intent.verb} — а что именно? объект во фразе не назван`;
  }
  const qualifierWord =
    intent.qualifier === "размер"
      ? "по размеру"
      : intent.qualifier === "имя"
        ? "по названию"
        : intent.qualifier === "дата"
          ? "по дате"
          : intent.qualifier === "тип"
            ? "по типу"
            : intent.qualifier === "место"
              ? "в указанном месте"
              : "";
  return qualifierWord === ""
    ? `${intent.verb} ${intent.object}`
    : `${intent.verb} ${intent.object} — ${qualifierWord}`;
}

/**
 * Разные ли это дела при одинаковых глаголе и объекте.
 *
 * Прямой ответ на дефект: «найди большие файлы» и «найди файл по имени» — **не
 * одно и то же**, и приложение обязано это видеть.
 */
export function differ(one: string, two: string): boolean {
  return !same(parse(one), parse(two));
}

/**
 * Чего во фразе нет.
 *
 * Разбор не придумывает: если про размер не сказано — размера в намерении нет.
 * Это проверяется тестом, потому что соблазн «поставить размер по умолчанию»
 * велик, а результат — действие, которого человек не просил.
 */
export function missing(intent: Intent): string[] {
  const gaps: string[] = [];
  if (intent.verb === "неизвестно") gaps.push("действие");
  if (intent.object === "") gaps.push("объект");
  return gaps;
}
