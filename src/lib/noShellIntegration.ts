/**
 * Шаг 459: обновление контекстного меню и ярлыков не требуется для работы.
 *
 * Это шаг-обещание, и оно важнее многих функций: **обновление не должно
 * трогать систему**. Частая практика «при каждом обновлении перепишем ярлыки и
 * пункт контекстного меню Проводника» ломается тихо и злит по-настоящему:
 *
 *  * ярлык на рабочем столе **переименовали обратно** — человек переименовал его
 *    сам и не понимает, почему вернулось;
 *  * пункт контекстного меню **появился снова** после того, как его убрали;
 *  * Проводник **перезапустился** посреди работы с файлами.
 *
 * При этом программа работает без всего этого: контекстное меню — удобство, а не
 * условие. Поэтому правило: **обновление не пишет ничего вне своей папки и
 * `%APPDATA%`**, а ярлыки и контекстное меню — только по явному выбору при
 * установке.
 */

/** Что обновление хотело бы сделать. */
export type Touch = "shortcuts" | "contextMenu" | "explorerRestart" | "fileAssoc" | "programFiles" | "appdata";

/**
 * Можно ли трогать при обновлении.
 *
 * `chosen` — что человек выбрал при установке.
 */
export function may(touch: Touch, chosen: readonly Touch[] = []): { ok: boolean; said: string } {
  switch (touch) {
    case "appdata":
      return { ok: true, said: "свои данные: обновление само собой" };
    case "programFiles":
      return { ok: true, said: "своя программа: замена файлов — это и есть обновление" };
    case "shortcuts":
      return chosen.includes("shortcuts")
        ? { ok: true, said: "ярлыки — по вашему выбору при установке. Уже существующий ярлык не переименовываем" }
        : { ok: false, said: "ярлыки при обновлении не нужны для работы и не трогаются: человек мог их переименовать" };
    case "contextMenu":
      return chosen.includes("contextMenu")
        ? { ok: true, said: "пункт контекстного меню — по вашему выбору, и его можно убрать в настройках навсегда" }
        : { ok: false, said: "контекстное меню при обновлении не нужно для работы и не трогается" };
    case "explorerRestart":
      return { ok: false, said: "перезапуск Проводника посреди работы с файлами — недопустим ни при каких настройках" };
    case "fileAssoc":
      return { ok: false, said: "связи файлов не трогаем никогда: это решение системы, а не программы" };
  }
}

/**
 * Что обновление делает всегда.
 *
 * Три вещи, и больше ничего: этого достаточно, чтобы программа работала.
 */
export function does(): string[] {
  return ["меняет свои файлы в своей папке", "дописывает свои данные в %APPDATA%", "сохраняет настройки человека — ни одна не сбрасывается"];
}

/**
 * Что обновление не делает.
 *
 * Список — обещание, и каждое нарушение видно человеку.
 */
export function notDo(): string[] {
  return [
    "не переименовывает и не пересоздаёт ярлыки: человек мог их переименовать",
    "не возвращает пункт контекстного меню, который убрали",
    "не перезапускает Проводник и не меняет связи файлов",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу запретов.
 */
export function checks(): string[] {
  return [
    "обновление трогает только свою папку и %APPDATA% (если человек не выбрал иное при установке)",
    "существующий ярлык не переименовывается",
    "Проводник и связи файлов не трогаются никогда",
  ];
}
