/**
 * Шаг 418: память профиля не попадает в чужие поиски.
 *
 * Разделение памяти (шаг 401) проверено на уровне профилей. Но у поиска есть
 * **свои** пути, и каждый — дыра, если его не закрыть:
 *
 *  * **поиск по файлам** ищет в папках, а не в памяти: он не должен подмешивать
 *    факты вообще;
 *  * **подсказки при наборе** («вы раньше говорили…») берут факты — и берут их
 *    только текущего человека;
 *  * **поиск по журналу** находит чужие дела. Здесь честный компромисс: по
 *    умолчанию — только свои, но **хозяин может посмотреть чужие дела** — это его
 *    компьютер, и он отвечает за то, что на нём происходит (шаг 414).
 *    Гость чужих дел не видит никогда.
 *
 * Ключевое: «не попадает» — это **свойство каждой точки поиска**, а не одного
 * места. Поэтому модуль перечисляет точки, и каждая обязана спросить `may`.
 */

import type { Profile } from "./peopleProfiles";

/** Где ищут. */
export type Where = "memory" | "suggest" | "journal" | "files";

/** Можно ли этой точке поиска вернуть этот факт/дело. */
export function may(viewer: Profile, owner: Profile, where: Where): { ok: boolean; why: string } {
  if (where === "files") return { ok: true, why: "поиск по файлам не читает память: он ищет имена файлов" };

  if (viewer.person.id === owner.person.id) return { ok: true, why: "своё" };

  if (where === "memory" || where === "suggest") {
    return { ok: false, why: "чужая память не показывается: ни фактом, ни подсказкой" };
  }

  // Журнал: хозяин может, гость — никогда.
  if (viewer.guest) return { ok: false, why: "гость чужих дел не видит" };
  return { ok: true, why: "чужие дела видны хозяину компьютера — он отвечает за то, что здесь происходит" };
}

/**
 * Отфильтровать результаты поиска.
 *
 * Не «отфильтровать потом»: отброшенное не должно даже попасть в список, иначе
 * счётчики и «похожее» выдадут его существование.
 */
export function filter<T extends { readonly owner: Profile }>(viewer: Profile, where: Where, results: readonly T[]): T[] {
  return results.filter((result) => may(viewer, result.owner, where).ok);
}

/**
 * Что видит человек в поиске.
 *
 * Список — приёмочный, по точке поиска.
 */
export function scope(viewer: Profile): { where: Where; said: string }[] {
  return [
    { where: "memory", said: `факты: только свои${viewer.guest ? "" : ""}` },
    { where: "suggest", said: "подсказки при наборе: только из своей памяти" },
    { where: "journal", said: viewer.guest ? "дела: только свои" : "дела: свои, и при желании — остальных людей на этом компьютере" },
    { where: "files", said: "файлы: по именам, память не читается" },
  ];
}

/**
 * Что чужой поиск не выдаёт даже числом.
 *
 * Число найденного у другого — тоже утечка: «по слову «кошки» у другого есть 2
 * записи» выдаёт и существование, и тему.
 */
export function silent(): string {
  return "чужой поиск не выдаёт даже числа совпадений: «у другого есть 2 записи» — это уже утечка темы";
}
