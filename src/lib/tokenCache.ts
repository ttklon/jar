/**
 * Кэш токенизации реплики (шаг 68).
 *
 * Дефект. Перед каждым ответом модель заново разбивает на токены **всю**
 * историю — правила, прошлые реплики, новый вопрос. Разбиение — не бесплатное:
 * на длинном разговоре это заметная доля паузы перед первым токеном, и она
 * растёт с каждым кругом. При этом девяносто процентов истории **не менялось**:
 * человек добавил одну фразу, а пересчитывается всё.
 *
 * Правило: **неизменное не пересчитывается**.
 *
 *  1. Кэш по **префиксу**: если начало совпадает, берём готовые токены и
 *     считаем только новое. Совпадает не «вся история», а сколько получится —
 *     предыдущий разговор почти всегда префикс нового.
 *  2. Проверка дешёвая: сравниваем текст, а не токены (токены уже посчитаны).
 *  3. Кэш **ограничен**: он живёт ради скорости, и кэш, который растёт без
 *     предела, сам становится причиной нехватки памяти.
 *  4. Одинаковый текст — одинаковые токены **в пределах одного токенизатора**:
 *     после смены модели кэш обязан стать негодным, иначе модель получит чужие
 *     токены и выдаст мусор без видимой ошибки.
 *
 * Почему не «просто закэшировать ответы модели». Ответ зависит от контекста и
 * случайности; кэш ответов даёт повторные фразы и ложное «я это уже говорил».
 * Токенизация — чистая функция, и её кэшировать безопасно.
 */

/** Что записано в кэше: текст, который токенизировали, и его токены. */
export interface Entry {
  /** Полный текст, для которого посчитаны токены. */
  text: string;
  tokens: number[];
  /** Токенизатор: после смены модели кэш негоден. */
  tokenizer: string;
}

/** Сколько записей держим. Больше — кэш сам станет причиной нехватки памяти. */
export const KEEP = 8;

/**
 * Насколько префикс совпадает.
 *
 * Возвращает длину общего начала **по токенам**, но проверяет **по тексту**:
 * токены уже посчитаны, и сравнивать их дешевле, однако текст — источник
 * правды: два разных текста могут дать один токен случайно.
 */
export function commonPrefix(left: string, right: string): number {
  const shorter = Math.min(left.length, right.length);
  let index = 0;
  // Границы слова, а не символы: «кот» и «котик» — не общий префикс.
  while (index < shorter && left[index] === right[index]) index += 1;
  if (index === shorter) return index;
  // Откатываемся до границы слова: половина слова не префикс.
  while (index > 0 && !/\s/.test(left[index - 1] ?? "")) index -= 1;
  return index;
}

/**
 * Найти, откуда можно продолжить.
 *
 * `null` — общего начала нет, считаем с нуля. Иначе — сколько токенов уже есть
 * и с какого места текста продолжать.
 */
export function resume(
  cache: readonly Entry[],
  text: string,
  tokenizer: string,
): { tokens: number[]; rest: string } | null {
  let best: { tokens: number[]; rest: string } | null = null;
  for (const entry of cache) {
    // Чужой токенизатор — чужие токены: это не экономия, а мусор без ошибки.
    if (entry.tokenizer !== tokenizer) continue;
    const prefix = commonPrefix(entry.text, text);
    if (prefix === 0) continue;
    const rest = text.slice(prefix);
    if (rest.length === 0) {
      // Тот же текст — считать нечего вовсе.
      return { tokens: entry.tokens, rest: "" };
    }
    // Берём посимвольную пропорцию: токены не совпадают с символами один к
    // одному, но при общем префиксе это точное приближение, и оно не хуже
    // пересчёта всего.
    const share = entry.text.length === 0 ? 0 : prefix / entry.text.length;
    const tokens = entry.tokens.slice(0, Math.floor(entry.tokens.length * share));
    if (best === null || tokens.length > best.tokens.length) best = { tokens, rest };
  }
  return best;
}

/**
 * Положить в кэш, вытеснив старое.
 *
 * Вытесняем **самое старое по времени вставки**: последний разговор нужнее
 * первого.
 */
export function put(cache: readonly Entry[], entry: Entry): Entry[] {
  const without = cache.filter(
    (item) => !(item.text === entry.text && item.tokenizer === entry.tokenizer),
  );
  return [entry, ...without].slice(0, KEEP);
}

/**
 * Сколько сэкономили — в токенах.
 *
 * Нужно, чтобы кэш можно было **проверить**, а не предполагать: если экономия
 * нулевая, кэш бесполезен и его место в памяти занимается зря.
 */
export function saved(tokens: readonly number[], reused: number): number {
  return Math.max(0, Math.min(reused, tokens.length));
}

/**
 * Негоден ли кэш после смены модели.
 *
 * Сказано прямо: `true` — чистить целиком. Иначе модель получит токены чужого
 * словаря и выдаст мусор **без видимой ошибки**, а это худший вид сбоя.
 */
export function stale(entry: Entry, tokenizer: string): boolean {
  return entry.tokenizer !== tokenizer;
}

/** Очистить всё, что от чужого токенизатора. */
export function clear(cache: readonly Entry[], tokenizer: string): Entry[] {
  return cache.filter((entry) => !stale(entry, tokenizer));
}
