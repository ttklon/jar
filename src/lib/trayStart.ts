/**
 * Шаг 453: тихий старт в трее, без окна, по выбору.
 *
 * Тихий старт — смысл автозапуска (шаг 443): программа уже ждёт, но не мешает.
 * Проблема в том, что «тихо» бывает двух видов, и путать их нельзя:
 *
 *  * **тихо при входе в Windows** — правильно: человек не просил окно, он просил
 *    программу под рукой;
 *  * **тихо при обычном запуске** (двойной клик по ярлыку) — неправильно: он
 *    нажал, чтобы увидеть окно, и ничего не произошло.
 *
 * Поэтому решение зависит **от способа запуска**, а не от настройки вообще.
 * Настройка «начинать в трее» — про автозапуск; обычный запуск показывает окно
 * всегда, и это защищает от «программа не запускается».
 */

/** Как запустили. */
export type How = "autostart" | "shortcut" | "secondRun" | "update";

/** Что делать. */
export interface Start {
  /** Показать ли окно. */
  readonly window: boolean;
  /** Показать ли уведомление «я в трее». */
  readonly hint: boolean;
  readonly said: string;
}

/**
 * Решить.
 *
 * `quietAtStartup` — настройка «начинать в трее» (касается только автозапуска).
 * `firstRun` — первый запуск после установки: тогда окно нужно всегда, иначе
 * человек не поймёт, что установилось.
 */
export function start(how: How, quietAtStartup: boolean, firstRun = false): Start {
  if (firstRun) {
    return { window: true, hint: false, said: "первый запуск: окно показываю всегда — иначе непонятно, что установилось" };
  }

  switch (how) {
    case "autostart":
      return quietAtStartup
        ? { window: false, hint: true, said: "запуск при входе: тихо в трее. Подсказка один раз — чтобы вы знали, что программа здесь" }
        : { window: true, hint: false, said: "запуск при входе, но вы просили показывать окно" };
    case "shortcut":
      return { window: true, hint: false, said: "вы запустили сами: окно показываю — иначе это выглядит, как будто ничего не произошло" };
    case "secondRun":
      return { window: true, hint: false, said: "программа уже работает: показываю окно вместо второго экземпляра" };
    case "update":
      return { window: true, hint: true, said: "после обновления показываю окно: нужно сказать, что изменилось" };
  }
}

/**
 * Подсказка при тихом старте.
 *
 * Один раз и коротко: «я в трее». Не уведомление об успехе, а объяснение, куда
 * делась программа.
 */
export function hintText(): string {
  return "ZShelper в трее: фразу можно сказать горячей клавишей или из меню в трее";
}

/**
 * Через сколько закрывать подсказку.
 *
 * Сама — через пять секунд: это не вопрос, ответа не ждёт.
 */
export const HINT_MS = 5000;

/**
 * Что проверяет тест.
 *
 * Четыре способа запуска — и у каждого своё решение.
 */
export function cases(): { how: How; window: boolean }[] {
  return [
    { how: "autostart", window: false },
    { how: "shortcut", window: true },
    { how: "secondRun", window: true },
    { how: "update", window: true },
  ];
}

/**
 * Что тихий старт не делает.
 *
 * Три дефекта, каждый из которых выглядит как «программа не работает».
 */
export function notDo(): string[] {
  return [
    "не прячет окно при обычном запуске ярлыком: человек нажал и ждёт окно",
    "не молчит после обновления: нужно сказать, что изменилось",
    "не оставляет подсказку висеть: она закрывается сама через пять секунд",
  ];
}
