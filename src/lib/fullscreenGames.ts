/**
 * Шаг 444: не мешать играм и полноэкранным приложениям.
 *
 * Человек в игре или на видеоконференции на весь экран. Что в этот момент делает
 * приложение, если оно не умеет это замечать:
 *
 *  * **всплывает уведомление** — игра сворачивается, человек проигрывает;
 *  * **перехватывает горячую клавишу** — вместо действия в игре срабатывает
 *    голосовой ввод;
 *  * **запускает дело с удалением** — и оно выдёргивает файлы игры.
 *
 * Поэтому «полноэкранный режим» — это **тихий режим**: дела не начинаются сами
 * (расписание), уведомления не показываются, горячие клавиши не работают. Ждём.
 *
 * Важная тонкость: **нажатая самим человеком фраза работает всегда**. Если он
 * нажал, о чём бы то ни было, значит он не в игре прямо сейчас — и запрет
 * «ничего не делать» превратился бы в «программа сломалась».
 */

/** Что известно о полноэкранном режиме. */
export interface Screen {
  /** Активно ли полноэкранное приложение (игра, видео, конференция). */
  readonly fullscreen: boolean;
  /** Нажал ли человек сам. */
  readonly byPerson: boolean;
  /** Опасное ли дело. */
  readonly dangerous: boolean;
}

/** Решение. */
export interface Decision {
  /** Можно ли выполнять. */
  readonly run: boolean;
  /** Показывать ли уведомление. */
  readonly notice: boolean;
  /** Работает ли горячая клавиша. */
  readonly hotkey: boolean;
  readonly said: string;
}

/**
 * Решить.
 *
 * Три исключения, в которых тихий режим снимается:
 *  * человек нажал сам;
 *  * дело **опасное** и его запустил человек — спрашиваем подтверждение, но
 *    выполняем (иначе «нажал, а ничего не произошло» — это дефект);
 *  * полноэкранного нет.
 */
export function decide(screen: Screen): Decision {
  if (!screen.fullscreen) {
    return { run: true, notice: true, hotkey: true, said: "полноэкранного приложения нет: работаю как обычно" };
  }

  if (screen.byPerson) {
    return {
      run: true,
      notice: false,
      hotkey: false,
      said: "вы попросили сами: выполняю, но уведомление не покажу — вы и так знаете, что попросили",
    };
  }

  return {
    run: false,
    notice: false,
    hotkey: false,
    said: "открыто полноэкранное приложение: дела по расписанию не запускаю, уведомления не показываю, горячие клавиши не перехватываю. Продолжу, когда выйдете",
  };
}

/**
 * Что происходит после выхода из полноэкранного.
 *
 * Пропущенные дела **не выполняются** скопом сразу: сначала подтверждение
 * (шаг 328: «очередью не догоняем»). Показываем одно уведомление: «пока вы были
 * в игре, пропущено 2 дела — выполнить?».
 */
export function afterFullscreen(missed: number): string {
  if (missed === 0) return "";
  return `пока было открыто полноэкранное приложение, пропущено ${missed} ${missed === 1 ? "дело" : "дела"} — спрошу, выполнять ли, по одному`;
}

/**
 * Чего тихий режим не делает.
 *
 * Три запрета, и каждый — про «не мешать» без «не работать».
 */
export function notDo(): string[] {
  return [
    "не блокирует нажатое человеком: он не в игре, если нажал",
    "не вываливает пропущенное скопом после выхода: спрашиваем по одному",
    "не показывает уведомление об успехе, даже если очень хочется",
  ];
}

/**
 * Что считается полноэкранным.
 *
 * Список — не «все окна во весь экран»: браузер в фуллскрине тоже, и это
 * правильно — там может быть видео или конференция.
 */
export function kinds(): string[] {
  return ["игры в полноэкранном режиме", "видео на весь экран", "видеоконференции", "презентации"];
}
