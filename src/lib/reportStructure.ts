/**
 * Шаг 380: тест — отчёт дела содержит цель, шаги, доказательства и отмену.
 *
 * Это **структурный** тест: он проверяет не текст отчёта, а что в нём есть
 * обязательные части. Отчёт без цели — «что-то произошло»; без доказательств —
 * «поверьте»; без пути отмены — «поздно».
 *
 * Четыре части, и каждая отвечает на свой вопрос:
 *
 *  * **цель** — чего хотел человек (его фраза, не наша формулировка);
 *  * **шаги** — что делали, по порядку;
 *  * **доказательства** — чем подтверждено (имя файла, число, ответ сервиса);
 *  * **отмена** — можно ли было остановить и что будет, если отменить сейчас.
 *
 * Почему тест, а не проверка в отчёте: отчёт может быть собран по-разному (шаг 374
 * копирует текст), но структура обязана быть у всех.
 */

/** Шаг отчёта. */
export interface StepReport {
  readonly name: string;
  /** Что сделано — словами. */
  readonly detail: string;
  /** Доказательство: имя файла, число, ответ. Пусто — доказательства нет. */
  readonly proof: string;
}

/** Отчёт целиком. */
export interface Report {
  /** Цель — фразой человека. */
  readonly goal: string;
  readonly steps: readonly StepReport[];
  /** Можно ли отменить; `null` — уже поздно. */
  readonly cancellable: boolean | null;
  /** Что будет при отмене. */
  readonly cancelSaid?: string;
}

/**
 * Проверить структуру.
 *
 * Возвращает список недостающих частей **словами человека**: «нет доказательств»
 * понятнее, чем «proof missing».
 */
export function check(report: Report): string[] {
  const missing: string[] = [];

  if (report.goal.trim() === "") missing.push("нет цели: отчёт должен начинаться с фразы человека, а не с «система выполнила»");
  if (report.steps.length === 0) missing.push("нет шагов: без них отчёт — это одна строка «сделано»");

  const withoutProof = report.steps.filter((step) => step.proof.trim() === "");
  if (withoutProof.length > 0) {
    missing.push(`нет доказательств у ${withoutProof.length} ${withoutProof.length === 1 ? "шага" : "шагов"}: ${withoutProof.map((step) => step.name).join(", ")}`);
  }

  if (report.cancellable === undefined || report.cancellable === null) {
    // null — законное «поздно», но тогда должно быть сказано, почему.
    if (report.cancellable !== null) missing.push("нет пути отмены: не сказано, можно ли остановить и что будет");
  } else if (report.cancellable && (!report.cancelSaid || report.cancelSaid.trim() === "")) {
    missing.push("отмена возможна, но не сказано, что именно произойдёт");
  }

  return missing;
}

/**
 * Структура целиком — для теста.
 *
 * `ok` — прошёл; `missing` — чего нет.
 */
export function verify(report: Report): { ok: boolean; missing: string[] } {
  const missing = check(report);
  return { ok: missing.length === 0, missing };
}

/**
 * Порядок частей.
 *
 * Цель → шаги → доказательства (внутри шагов) → отмена. Не наоборот: отмена в
 * начале читается как «вы уже опоздали».
 */
export function order(): string[] {
  return ["цель", "шаги", "доказательства", "отмена"];
}

/**
 * Что считается доказательством.
 *
 * «Успешно» — не доказательство: это оценка. Доказательство — то, что можно
 * проверить, не веря нам.
 */
export function proofs(): string[] {
  return [
    "имя файла или папки, а не «файлы удалены»",
    "число с единицей: «340 МБ», а не «много»",
    "ответ сервиса или его отсутствие",
    "«не проверено» — честное доказательство отсутствия проверки",
  ];
}
