/**
 * Последнее место работы не теряется (шаг 191).
 *
 * Зачем отдельное правило. «Запомнить экран» выглядит как одна строка в
 * `localStorage`, и именно поэтому легко сделать неправильно — тремя способами:
 *
 *  * **запомнить «Знакомство»**. Тогда второй запуск откроется там, где
 *    человек был в первый раз, а не там, где он работал: он же ушёл с
 *    знакомства, а не остался. Поэтому запоминаются только рабочие экраны;
 *  * **запомнить чужое имя**. Настройки, экран из следующей версии, опечатка —
 *    всё это при запуске показало бы пустоту. Неизвестное — не место, а
 *    отсутствие места: открываем «Голос»;
 *  * **упасть на хранилище**. `localStorage` бросает при некоторых настройках
 *    приватности. Запомнить негде — не повод не открыть приложение.
 *
 * «Голос» — не только значение по умолчанию, но и то, куда мы не возвращаем
 * человека после сна и перезапуска: разговор — это место, где он говорит с
 * приложением, и открывать приложение в «Настройках» потому, что он там был
 * неделю назад, значит показывать ему чужое вчера.
 */

/** Ключ, под которым лежит последний экран. С версией — как у очереди и черновика. */
export const LAST_SCREEN_KEY = "zshelper.screen.v1";

/** Где открыть приложение, если места не помним. */
export const DEFAULT_SCREEN = "voice";

/**
 * Экран, который можно запомнить.
 *
 * `null` — этот экран не место работы: «Знакомство» показывается один раз и
 * запоминать его значит открывать приложение там, откуда человек ушёл.
 */
export function rememberable(screen: string): boolean {
  return screen !== "welcome";
}

/**
 * Прочитать сохранённое место.
 *
 * `known` — список настоящих экранов. Имя, которого там нет, — не место:
 * показать его значило бы открыть пустоту (экран из следующей версии, чужой
 * ключ, опечатка).
 */
export function readScreen(
  storage: Pick<Storage, "getItem"> | undefined,
  known: readonly string[],
): string {
  if (!storage) return DEFAULT_SCREEN;
  let saved: string | null = null;
  try {
    saved = storage.getItem(LAST_SCREEN_KEY);
  } catch {
    // Хранилище недоступно — это не ошибка человека, и молчать об этом не надо:
    // просто открываем «Голос».
    return DEFAULT_SCREEN;
  }
  if (!saved) return DEFAULT_SCREEN;
  return known.includes(saved) ? saved : DEFAULT_SCREEN;
}

/** Запомнить место. Ошибку хранилища не поднимаем: не запомнить — не сломать. */
export function saveScreen(storage: Pick<Storage, "setItem"> | undefined, screen: string): void {
  if (!storage || !rememberable(screen)) return;
  try {
    storage.setItem(LAST_SCREEN_KEY, screen);
  } catch {
    // У человека приватный режим или переполненное хранилище. Приложение
    // работает; место просто не запомнится.
  }
}
