/**
 * Шаг 312: проверка подписи и хеша скачанного обновления **до** запуска.
 *
 * Шаг 302 проверял пакет, который человек скачал руками с сайта. Здесь — пакет,
 * который программа скачала **сама**, и разница принципиальная: человек ничего не
 * видел, ничего не выбирал, и окна «вы уверены?» не было. Значит, проверка
 * обязана быть строже и **до** любого запуска — включая до распаковки в папку,
 * которую потом подхватят.
 *
 * Порядок, и он же — единственный правильный:
 *
 *  1. **размер** — дешёвая проверка, отсеивает обрыв загрузки;
 *  2. **хеш** — совпал ли с манифестом (шаг 303);
 *  3. **подпись** — та ли цепочка и тот ли издатель;
 *  4. **только теперь** распаковка и запуск.
 *
 * Что важно назвать словами:
 *
 *  * **скачанный обновлённый пакет не запускается сам по себе** — ни разу, ни
 *    на секунду: иначе проверка теряет смысл;
 *  * **нет подписи — не «наверное, можно»**: обновление без подписи не
 *    применяется вовсе, даже если хеш сошёлся: хеш говорит «тот файл», подпись —
 *    «наш файл»;
 *  * **проверка без сети**: манифест уже скачан, и подпись проверяется локально —
 *    иначе откат без сети (шаг 314) не работает.
 */

/** Что скачала программа. */
export interface Downloaded {
  readonly bytes: number;
  readonly sha256: string;
  /** Путь во временной папке — до проверки не исполняется. */
  readonly tempPath: string;
}

/** Что сказал манифест. */
export interface Expected {
  readonly bytes: number;
  readonly sha256: string;
  /** Издатель, которому доверяем. */
  readonly publisher: string;
}

/** Что показала подпись файла. */
export interface Signature {
  readonly present: boolean;
  readonly publisher: string | null;
  readonly chainValid: boolean;
  /** Отозван ли сертификат — проверяется локально по списку отзыва. */
  readonly revoked: boolean;
}

/** Что делать. */
export type Action = "install" | "stop";

/** Проверить скачанное обновление. */
export function verify(file: Downloaded, expected: Expected, signature: Signature): { action: Action; said: string } {
  if (file.bytes !== expected.bytes) {
    return { action: "stop", said: `скачалось ${file.bytes} байт вместо ${expected.bytes}: загрузка оборвалась или пакет не тот` };
  }
  if (file.sha256 !== expected.sha256) {
    return { action: "stop", said: "хеш не совпал с манифестом: файл изменился или подменён — обновление не применяем" };
  }
  if (!signature.present) {
    return { action: "stop", said: "подписи нет: обновление, которое мы скачали сами, применяем только подписанным — здесь некому спросить человека" };
  }
  if (!signature.chainValid) {
    return { action: "stop", said: "цепочка подписи не сходится: файл подписан не нашей цепочкой" };
  }
  if (signature.revoked) {
    return { action: "stop", said: "сертификат отозван: обновление не применяем, сообщаем и ждём нового выпуска" };
  }
  if (signature.publisher !== expected.publisher) {
    return { action: "stop", said: `подписал «${signature.publisher}», а ожидали «${expected.publisher}»` };
  }
  return { action: "install", said: `размер, хеш и подпись «${expected.publisher}» сошлись — можно применять` };
}

/**
 * Что скачать и проверить можно без сети.
 *
 * Обновление применяется, когда всё уже на диске: иначе «обновление» превращается
 * в «загрузку», и в самолёте оно падает на середине.
 */
export function offlineReady(file: Downloaded, expected: Expected, signature: Signature): boolean {
  return verify(file, expected, signature).action === "install";
}

/**
 * Что сказать человеку.
 *
 * Он не просил обновление и не видел процесса: одна строка, а не технический
 * отчёт с хешами.
 */
export function tell(action: Action, said: string): string {
  return action === "install"
    ? "Обновление скачано и проверено: применим после закрытия программы"
    : `Обновление не применим: ${said}. Программа работает как раньше`;
}

/**
 * Почему проверка «потом» не годится.
 *
 * Аргумент, который приходится повторять: распакованный файл уже попал в папку
 * программы, и «проверить после» — это «запустить до проверки», если что-то
 * подхватит его раньше нас.
 */
export function whyBefore(): string {
  return "распакованный файл уже лежит в папке программы: «проверить после распаковки» — значит дать ему шанс сработать до проверки";
}
