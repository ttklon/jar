/**
 * Шаг 500: ровно 500 шагов — остальное это новая версия плана, а не раздувание старого.
 *
 * У плана есть **граница**, и её надо уметь назвать. План, который растёт от 500 к
 * 800 «пока пишется», перестаёт быть планом: непонятно, сколько идти, и никто не
 * знает, где конец.
 *
 * Поэтому здесь:
 *
 *  * **план — ровно 500 шагов**: их можно перечислить, и они пронумерованы;
 *  * **новое требование** — это не 501-й шаг, а **новая версия плана**: отдельный
 *    документ, который сначала решает, что он собой заменяет;
 *  * **перенумеровать нельзя**: номера — ссылки. Шаг, добавленный «между», ломает
 *    все ссылки `step:` (шаг 478).
 *
 * И правило про завершение: **законченный план не открывают заново, чтобы поправить
 * формулировку**. Правка плана после 500 — это версия, и её видно.
 */

/** Версия плана. */
export interface Version {
  /** Название: «500» или «501+». */
  readonly name: string;
  /** Сколько шагов. */
  readonly steps: number;
  /** Какую версию заменяет; `null` — первая. */
  readonly replaces: string | null;
}

/** Сколько шагов в плане. */
export const LIMIT = 500;

/**
 * Проверить версию.
 *
 * Нарушения: больше пятисот (это раздувание), замена без объяснения, правка старой
 * версии вместо новой.
 */
export function check(version: Version): string[] {
  const problems: string[] = [];

  if (!/^\d+$/.test(version.name)) problems.push(`версия «${version.name}»: имя должно быть числом`);
  if (version.steps > LIMIT) problems.push(`«${version.name}»: шагов ${version.steps} — больше ${LIMIT}: это раздувание, а не новая версия`);
  if (version.steps <= 0) problems.push(`«${version.name}»: шагов ${version.steps} — версия без шагов не версия`);
  if (version.replaces === version.name) problems.push(`«${version.name}»: заменяет себя`);

  return problems;
}

/**
 * Можно ли править.
 *
 * Закрытая версия (ровно 500 и всё сдано) — **не правится**: новая версия решает,
 * что она заменяет. Открытая — правится, пока не закрыта.
 */
export function mayEdit(version: Version, done: number): { ok: boolean; said: string } {
  // Закрытость — по своей длине, а не по 500: новая версия на 100 шагов тоже
  // закрывается, когда сдано 100.
  const closed = done >= version.steps;

  return closed
    ? { ok: false, said: `«${version.name}» закрыта: ${done} из ${LIMIT} — правка идёт в новую версию, а не в закрытую` }
    : { ok: true, said: `«${version.name}» открыта: ${done} из ${version.steps} — править можно` };
}

/**
 * Что будет следующим.
 *
 * Два исхода: всё сдано — «план закрыт, дальше новая версия»; иначе — сколько
 * осталось **числом**.
 */
export function next(version: Version, done: number): string {
  const left = version.steps - done;
  return left <= 0
    ? `план ${version.name} закрыт: ${done} из ${version.steps}. Дальше — новая версия, а не 501-й шаг`
    : `осталось ${left}: ${done} из ${version.steps}`;
}

/**
 * Почему нельзя перенумеровать.
 *
 * Три причины — все про ссылки.
 */
export function whyNoRenumber(): string[] {
  return [
    "номера шагов — ссылки в документации и код (`step:452`), проверяемые в CI (шаг 478)",
    "вставка «между» сдвигает все последующие и ломает ссылки молча",
    "новый шаг — это новая версия: её видно, а сдвиг — нет",
  ];
}

/**
 * Чего граница не делает.
 *
 * Три запрета; главный — не раздувать.
 */
export function notDo(): string[] {
  return [
    "не добавляет 501-й шаг в тот же документ",
    "не правит закрытую версию, чтобы «уточнить формулировку»",
    "не перенумеровывает: сдвиг ломает ссылки молча",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "в плане ровно пятьсот шагов",
    "больше — это новая версия, а не раздувание",
    "закрытая версия не правится, открытая — правится",
  ];
}
