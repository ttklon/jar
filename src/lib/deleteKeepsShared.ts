/**
 * Шаг 417: удаление профиля не удаляет общие данные без подтверждения.
 *
 * «Забыть профиль» (шаг 408) убирает имя, факты и разрешения. Но у профиля есть
 * ещё **следы**: дела, которые он запускал, файлы, которые они вместе настраивали,
 * расписания, которые он создал и которые ведут в общую папку.
 *
 * Главная ошибка, которую этот шаг закрывает: удалить вместе с профилем
 * **расписание**, которое делало что-то нужное всей семье. Человек убрал своё имя,
 * а перестала идти резервная копия — и узнается это через месяц.
 *
 * Поэтому удаление делит данные на три группы:
 *
 *  * **личное** — уходит вместе с профилем, без вопросов;
 *  * **зависимое** — создано им, но нужно другим: спрашиваем, что с ним делать;
 *  * **общее** — не трогаем никогда: чужое или всех.
 */

/** Что связано с профилем. */
export interface Tied {
  /** Личное: факты, разрешения, имя. */
  readonly personal: readonly string[];
  /** Создано им, но используется другими — с числом тех, кому нужно. */
  readonly depended: readonly { readonly what: string; readonly by: number }[];
  /** Общее: модель, настройки, общие расписания. */
  readonly common: readonly string[];
}

/**
 * Что предлагается сделать с зависимым.
 *
 * Не «удалить всё связанное»: у каждого пункта — выбор и имя, кому он нужен.
 */
export function options(tied: Tied): { what: string; said: string; choices: string[] }[] {
  return tied.depended.map((item) => ({
    what: item.what,
    said: `«${item.what}» создано этим человеком, но нужно ещё ${item.by} ${item.by === 1 ? "человеку" : "людям"}`,
    choices: ["оставить и передать мне", "оставить как есть", "удалить вместе с профилем"],
  }));
}

/**
 * Подтверждение перед удалением.
 *
 * Перечисляет три группы **до** нажатия: если в списке «общее» человек увидит
 * модель и настройки, он поймёт, что их не тронут.
 */
export function confirm(name: string, tied: Tied): string[] {
  const lines = [`Забыть профиль «${name}»?`];
  lines.push(`Уйдёт с ним: ${tied.personal.join(", ")}.`);
  if (tied.depended.length > 0) {
    lines.push(`Создано им, но нужно другим: ${tied.depended.map((item) => `${item.what} (${item.by})`).join(", ")} — решите, что с этим делать.`);
  }
  lines.push(`Не тронем: ${tied.common.join(", ")}.`);
  return lines;
}

/**
 * Проверка перед выполнением.
 *
 * Если зависимое не решено — удаление **не выполняется**. Это не придирка:
 * удалить и «ну ладно, потом восстановим» нельзя, восстановить нечего.
 */
export function ready(tied: Tied, decided: readonly string[]): { ok: boolean; said: string } {
  const undecided = tied.depended.map((item) => item.what).filter((what) => !decided.includes(what));
  if (undecided.length === 0) return { ok: true, said: "всё решено: удаляю профиль и личное, общее остаётся" };
  return { ok: false, said: `не решено: ${undecided.join(", ")} — пока не решите, профиль не удаляю` };
}

/**
 * Что удаление не делает никогда.
 *
 * Три вещи, и все — общие: удаление профиля не должно останавливать чужие дела.
 */
export function neverTouches(): string[] {
  return [
    "расписания, которые ведут в общие папки: их создал он, но идут они не для него одного",
    "скачанную модель и настройки программы: они про компьютер",
    "дела других людей, даже если он их запускал",
  ];
}
