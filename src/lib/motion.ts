/**
 * Уменьшение движения для тех, кому оно мешает (шаг 187).
 *
 * Дефект. Настройка была **вычислена** (шаг 186: `plan(system).still`) и никуда не
 * доходила: оставалась переменной в `app.tsx`. Настройка, которая ничего не
 * меняет, — это не «почти сделано», а «не сделано»: человек включил уменьшение
 * движения в Windows, и приложение продолжило анимировать.
 *
 * Правила:
 *
 *  1. **один атрибут на корне документа** — `data-motion="still"`. Не «передать
 *     проп в сорок компонентов»: сорок мест, и в одном забудут. Атрибут на
 *     `<html>` видят все, включая сторонние компоненты и CSS;
 *  2. **выключить, а не замедлить.** `animation-duration: 0.01ms` вместо
 *     `0.5s` — распространённая ошибка: она оставляет анимацию включённой, просто
 *     быстрой, а некоторые вещи (пульсация, мигание) от этого становятся хуже —
 *     чаще;
 *  3. **и `transition`, и `animation`.** Отдельно отключить переходы значит
 *     оставить карусели; отдельно анимации — оставить плавные подсветки;
 *  4. **спиннер — тоже движение.** Ожидание можно показать словами («читаю
 *     реестр»), и это уже сделано (шаг 194); при `still` спиннер обязан замолчать
 *     как картинка, а не остаться единственным источником «что происходит»;
 *  5. **следовать за системой на лету.** Поменял настройку в Windows — приложение
 *     подхватывает без перезапуска: `matchMedia` меняется, а не только читается
 *     при старте.
 *
 * Модуль отдаёт **имя атрибута и значение**, а не CSS: правило проверяется без
 * браузера, а CSS — в одном месте, а не в сорока.
 */

/** Атрибут на корне документа. */
export const ATTR = "data-motion";

/** Значение, при котором движение выключено. */
export const STILL = "still";

/** Значение по умолчанию: движение как обычно. */
export const NORMAL = "normal";

/**
 * Что поставить на корень документа.
 *
 * `pref` — из `system.plan(...).still`; отдельным аргументом, потому что у
 * «движения» может появиться и своё переключение в приложении, и правило не
 * должно от этого зависеть.
 */
export function attribute(still: boolean): { name: string; value: string } {
  return { name: ATTR, value: still ? STILL : NORMAL };
}

/**
 * CSS, который делает `still` правдой, а не пожеланием.
 *
 * Одна строка на `transition` и одна на `animation`: отключить только одно значит
 * оставить половину движения. `scroll-behavior` — третья вещь, которую забывают:
 * плавная прокрутка тоже движение.
 */
export const CSS = `[${ATTR}="${STILL}"] *, [${ATTR}="${STILL}"] *::before, [${ATTR}="${STILL}"] *::after {
  animation-duration: 0.01ms !important;
  animation-iteration-count: 1 !important;
  transition-duration: 0.01ms !important;
  scroll-behavior: auto !important;
}`;

/**
 * Применить к документу.
 *
 * Возвращает функцию «вернуть как было» — чтобы компонент не оставлял за собой
 * атрибут после размонтирования и не влиял на следующий экран.
 */
export function apply(root: { setAttribute(name: string, value: string): void; removeAttribute(name: string): void }, still: boolean): () => void {
  const got = attribute(still);
  root.setAttribute(got.name, got.value);
  return () => root.removeAttribute(got.name);
}

/**
 * Что сказать человеку, если он включил уменьшение движения.
 *
 * Молчание здесь — тоже ответ, но плохой: человек не знает, услышали ли его.
 * Фраза говорит и что сделано, и что **не** сделано (движение выключено, а не
 * замедлено), потому что второе чаще всего и бывает дефектом.
 */
export function said(still: boolean): string {
  return still
    ? "уменьшение движения включено: анимации, переходы и плавная прокрутка выключены полностью, а не замедлены"
    : "уменьшение движения выключено: анимации как обычно";
}
