/**
 * Шаг 475: поддержка отвечает за один шаг — три вопроса и то, что приложить.
 *
 * Шаг 467 дал саму инструкцию. Здесь — **как она используется в ответе**: первый
 * ответ поддержки должен двигать дело, а не начинать переписку.
 *
 * Правило одно и жёсткое: **на каждый ответ — одно действие человека**. Не «опишите
 * подробно, пришлите логи, попробуйте перезапустить», а «нажмите вот эту кнопку и
 * пришлите файл, остальное мы видим сами».
 *
 * Если ответ требует двух действий — он требует второго письма, и половина людей
 * до него не доходит.
 */

/** Состояние обращения. */
export interface Case {
  /** Что уже есть: сколько ответов дал человек. */
  readonly answered: number;
  /** Может ли человек приложить файлы. */
  readonly canAttach: boolean;
  /** Воспроизводится ли у нас (по первой фразе). */
  readonly reproduced: boolean;
}

/** Ответ поддержки. */
export interface Reply {
  /** Что сказать — по-русски, без «уважаемый пользователь». */
  readonly said: string;
  /** Одно действие человека; `null` — от нас сейчас ничего не нужно. */
  readonly ask: string | null;
  /** Можно ли закрыть без переписки. */
  readonly done: boolean;
}

/**
 * Что ответить.
 *
 * Четыре состояния — и в каждом одно действие, а не три.
 */
export function reply(state: Case): Reply {
  if (state.reproduced) {
    return {
      said: "воспроизвели у себя: дефект наш, исправление будет в ближайшем обновлении. Ничего делать не нужно",
      ask: null,
      done: false,
    };
  }

  if (state.answered === 0) {
    return {
      said: "спасибо, этого достаточно, чтобы начать: проверяем по вашей фразе и симптому",
      ask: "нажмите «скопировать отчёт» на экране дела и вставьте сюда",
      done: false,
    };
  }

  if (state.canAttach) {
    return {
      said: "по отчёту видно, на каком шаге остановилось",
      ask: "Настройки → Помощь → «собрать архив» и приложите файл",
      done: false,
    };
  }

  return {
    said: "файлы не обязательны: по фразе и симптому видно, где смотреть. Ответим по существу без архива",
    ask: null,
    done: true,
  };
}

/**
 * Почему одно действие.
 *
 * Три причины — все про то, что человек не доходит до второго письма.
 */
export function whyOne(): string[] {
  return [
    "два действия — это два письма, и половина людей не напишет второе",
    "«опишите подробно» перекладывает работу на человека, у которого и так не работает",
    "действие должно быть кнопкой в приложении, а не поиском папки в Проводнике",
  ];
}

/**
 * Чего ответ не содержит.
 *
 * Четыре запрета; первый — «перезапустите» без причины.
 */
export function notDo(): string[] {
  return [
    "не просит «попробуйте перезапустить» без объяснения, зачем",
    "не спрашивает то, что уже есть в журнале: это неуважение к времени",
    "не отправляет в FAQ вместо ответа: FAQ дополняет, а не заменяет",
    "не заканчивает «если повторится — пишите»: это не ответ",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу правил.
 */
export function checks(): string[] {
  return [
    "на каждый ответ — не больше одного действия человека",
    "воспроизведённый дефект признаётся, а не «пришлите ещё»",
    "без файлов ответ всё равно есть",
  ];
}
