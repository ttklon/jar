/**
 * Поиск по настройкам и возможностям одним полем (шаг 192).
 *
 * Зачем отдельный список, а не «поиск по заголовкам экранов». Экран «Настройки» —
 * это один пункт в ленте, и внутри него три раздела и десяток нажимаемых мест.
 * Палитра, которая знает только экраны, на вопрос «где тема» отвечает «Настройки»
 * — то есть человек всё равно ищет глазами внутри. А вопрос «скачать модель» не
 * имеет экрана вовсе: это возможность, и она живёт на карточке готовности.
 *
 * Правило здесь только сопоставляет **что спросили** с **куда идти**. Тексты
 * берутся из словаря (`./i18n/ru`), а не пишутся заново: второй пересказ тех же
 * названий однажды разошёлся бы с экраном, и поиск вёл бы к тому, чего там нет.
 *
 * Настройки и возможности ведут на свои экраны: у приложения один экран
 * «Настройки» и одна карточка готовности, и вести человека к ним — честно. Делать
 * вид, что у каждой настройки свой адрес, значило бы обещать переход, которого
 * нет.
 */

import { t } from "../i18n/ru";
import type { Command } from "./commands";

/**
 * Что можно найти помимо экранов.
 *
 * `screen` — куда ведёт. Это настоящий экран, а не «место на экране»: адресов
 * внутри экранов у приложения нет, и выдумывать их ради поиска значило бы
 * обещать точный переход, которого не будет.
 */
export interface Findable extends Command {
  /** Что это: настройка, возможность или экран. Различается в подсказке. */
  kind: "screen" | "setting" | "ability";
}

/**
 * Список того, что ищется помимо экранов.
 *
 * Почему списком в коде, а не собранным из разметки. Собирать из разметки значит
 * искать то, что сейчас на экране: ушёл с «Настроек» — и тема перестала
 * находиться. Поиск обязан работать независимо от того, что открыто.
 */
export function findables(): Findable[] {
  const s = t;
  return [
    // Настройки: заголовки разделов и сами пункты — по тем словам, которыми
    // человек их называет, а не по тем, что в коде.
    { id: "settings", label: s.settingsTheme, kind: "setting", keywords: ["тема", "тёмная", "светлая", "оформление", "theme"] },
    { id: "settings", label: s.settingsSectionLook, kind: "setting", keywords: ["вид", "оформление", "масштаб"] },
    { id: "settings", label: s.settingsSectionStart, kind: "setting", keywords: ["автозапуск", "запуск", "старт", "трей", "startup"] },
    { id: "settings", label: s.settingsSectionData, kind: "setting", keywords: ["данные", "память", "копия", "удалить", "data"] },

    // Возможности: то, чего нет ни на одном экране как пункт, но что человек
    // ищет словом. Ведём на карточку готовности и на модели.
    { id: "models", label: "Скачать модель", kind: "ability", keywords: ["модель", "скачать", "загрузить", "gguf", "model"] },
    { id: "models", label: "Движок", kind: "ability", keywords: ["движок", "llama", "engine", "сервер"] },
    { id: "models", label: "Распознавание речи", kind: "ability", keywords: ["распознавание", "whisper", "микрофон", "речь", "speech"] },
    { id: "settings", label: "Автозапуск при входе", kind: "ability", keywords: ["автозапуск", "вход", "windows", "autostart"] },
    { id: "journal", label: "Журнал ошибок", kind: "ability", keywords: ["журнал", "ошибки", "лог", "logs", "история"] },
    { id: "hands", label: "Что разрешено", kind: "ability", keywords: ["права", "разрешено", "политика", "tools"] },
  ];
}

/**
 * Отфильтровать настройки и возможности по запросу.
 *
 * Те же правила, что у палитры экранов: подстрока без учёта регистра и ё/е,
 * пустой запрос — всё. Отдельной функцией не потому, что «так красивее», а
 * потому, что два списка должны искаться **одинаково**: иначе «Тема» находится,
 * а «тема» — нет.
 */
export function filterFindables(items: readonly Findable[], query: string): Findable[] {
  const needle = query.toLocaleLowerCase("ru").replace(/ё/g, "е").trim();
  if (needle.length === 0) return [...items];
  return items.filter((item) =>
    [item.label, ...(item.keywords ?? [])]
      .map((text) => text.toLocaleLowerCase("ru").replace(/ё/g, "е"))
      .some((text) => text.includes(needle)),
  );
}

/** Что показать рядом с названием: настройка это, возможность или экран. */
export function kindLabel(kind: Findable["kind"]): string {
  switch (kind) {
    case "screen":
      return "экран";
    case "setting":
      return "настройка";
    case "ability":
      return "возможность";
  }
}
