import { describe, expect, it } from "vitest";
import { heardWord, join, say, USABLE_MS, verdict } from "./micDrop";

/**
 * Шаг 55: не терять фразу, если микрофон отключился в середине.
 *
 * Выдернули гарнитуру, села батарейка — и всё сказанное исчезает. Человек
 * говорил двадцать секунд и получил пустоту.
 */
describe("оборванная запись — не потеря, а недоговорённая фраза", () => {
  it("сказанное сохраняется и разбирается", () => {
    // Звук был — распознать его можно, просто он оборван.
    expect(verdict({ recordedMs: 12_000, heard: "открой папку" })).toBe("keep");
  });

  it("слишком короткая запись не выдаётся за ответ", () => {
    // Обрывок в 200 мс — не фраза, и делать вид, что это ответ, значит врать.
    expect(verdict({ recordedMs: 200 })).toBe("ask");
    expect(USABLE_MS).toBeGreaterThan(200);
  });

  it("продолжение дописывается к сказанному", () => {
    // «Продолжите» обещает продолжение, а не новый вопрос.
    expect(verdict({ recordedMs: 8000, before: "создай папку" })).toBe("join");
    expect(join("создай папку", "и положи туда отчёт")).toBe("создай папку, и положи туда отчёт");
  });
});

describe("что сказать человеку", () => {
  it("названы что случилось, сколько успели и что делать", () => {
    // Без третьего сообщение об обрыве превращается в сообщение о поломке.
    const said = say({ recordedMs: 12_000 });
    expect(said).toContain("отключился");
    expect(said).toContain("12");
    expect(said).toContain("сохранено");
  });

  it("короткий обрывок — «повторите», а не «продолжите»", () => {
    // Продолжать нечего: «продолжите» здесь соврало бы.
    const said = say({ recordedMs: 100 });
    expect(said).toContain("повторите");
    expect(said).not.toContain("продолжите");
  });

  it("при дописывании сказано «продолжите»", () => {
    expect(say({ recordedMs: 6000, before: "создай папку" })).toContain("продолжите");
  });
});

describe("мелочи, которые видно только на живом тексте", () => {
  it("секунды склоняются по-русски", () => {
    // «12 секунд», но «1 секунда» и «2 секунды» — иначе текст выдаёт машину.
    expect(heardWord(400)).toBe("меньше секунды");
    expect(heardWord(1000)).toBe("1 секунда");
    expect(heardWord(3000)).toBe("3 секунды");
    expect(heardWord(12_000)).toBe("12 секунд");
    expect(heardWord(21_000)).toBe("21 секунда");
  });

  it("пустая половина не оставляет висящей запятой", () => {
    // Иначе на экране «создай папку,» — мелочь, но читается как сбой.
    expect(join("создай папку", "")).toBe("создай папку");
    expect(join("", "и отчёт")).toBe("и отчёт");
    expect(join("  ", "  ")).toBe("");
  });

  it("склейка не ставит запятую после уже имеющейся", () => {
    expect(join("создай папку,", "и отчёт")).toBe("создай папку, и отчёт");
  });
});
