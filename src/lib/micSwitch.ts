/**
 * Смена устройства на лету (шаг 54).
 *
 * Дефект. Человек включает гарнитуру посреди разговора — и ничего не меняется.
 * Микрофон, взятый один раз при запуске, остаётся прежним, и человек говорит в
 * гарнитуру, которая молчит, или в старый микрофон, которого уже нет. Приходится
 * перезапускать приложение, но об этом не сказано, и выглядит это как поломка.
 *
 * Правило: устройство **выбирается заново при каждом включении микрофона**, а
 * не один раз при запуске.
 *
 * Почему не «слушаем `devicechange` и переключаемся на лету». Переключение
 * посреди фразы режет её на две: первая половина с одного микрофона, вторая — с
 * другого, и распознавание получает склейку двух разных голосов. Отложенный
 * выбор безопаснее: заканчиваем фразу старым устройством, новое берём на
 * следующую.
 *
 * Почему не спросить человека каждый раз. Спрашивать «какой микрофон?» при
 * каждом включении — это вопрос, на который у человека нет ответа: он не знает
 * названий. Берём **устройство по умолчанию** системы: там гарнитура уже стоит
 * первой, если её подключили.
 */

/** Что известно об устройствах. */
export interface Devices {
  /** Устройства ввода, как их отдала система. */
  inputs: { id: string; label: string }[];
  /** Устройство, стоящее по умолчанию. */
  defaultId: string | null;
  /** Устройство, с которым сейчас работаем (может быть уже отключено). */
  currentId: string | null;
}

/**
 * Нужно ли переключаться **перед следующей фразой**.
 *
 * Не посреди фразы: склейка двух голосов в одной записи распознаётся хуже, чем
 * целая фраза со старого микрофона.
 */
export function switchTo(devices: Devices): string | null {
  const { inputs, defaultId, currentId } = devices;
  if (inputs.length === 0) return null;
  // Текущего устройства больше нет — переключаемся обязательно: иначе запись
  // не начнётся, и человек не поймёт, почему.
  if (currentId !== null && !inputs.some((input) => input.id === currentId)) {
    return defaultId ?? inputs[0]?.id ?? null;
  }
  // Гарнитуру подключили: она стала устройством по умолчанию.
  if (defaultId !== null && defaultId !== currentId) return defaultId;
  return null;
}

/** Что сказать при переключении: названо устройство, а не «устройство сменено». */
export function saySwitch(devices: Devices, nextId: string | null): string | null {
  if (nextId === null) return null;
  const next = devices.inputs.find((input) => input.id === nextId);
  const name = next?.label?.trim() || "микрофон по умолчанию";
  const lost = devices.currentId !== null && !devices.inputs.some((i) => i.id === devices.currentId);
  if (lost) {
    // Прежнего больше нет — это не «переключился», а «прежний пропал», и
    // человеку важно знать, что дальше говорить можно: путь есть.
    return `прежний микрофон отключился, теперь слушаю «${name}»`;
  }
  return `подключился новый микрофон — теперь слушаю «${name}»`;
}

/**
 * Что сказать, если переключаться не на что.
 *
 * Молчание здесь — худший ответ: человек говорит, ничего не происходит, и он не
 * знает, дело в микрофоне или в приложении.
 */
export function sayNoDevices(): string {
  return "микрофон не найден — подключите его или напечатайте фразу";
}
