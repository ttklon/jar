/**
 * Шаг 227: энергия — не крутить движок в простое, отпускать после N минут.
 *
 * Дефект был тонкий и потому живучий: механизм выгрузки **существовал**
 * (`idle.rs`, `release_if_idle`), но срабатывал только когда человек открывал
 * экран «Модели». Закрыл экран — и `engine_status` никто не спрашивает, значит
 * `release_if_idle` не вызывается ни разу: движок остаётся в памяти на весь день,
 * греет ноутбук и ест батарею — ровно то, против чего шаг.
 *
 * Почему не «таймер на выгрузку в Rust». Он тоже нужен, но у него есть цена:
 * будить приложение ради таймера. Поэтому проверка идёт **редко и дёшево** —
 * раз в минуту в интерфейсе, что уже работает, — и решение принимает `idle.rs`,
 * а не этот модуль: порог остаётся один, в одном месте.
 *
 * Правила:
 *
 *  1. **Редко.** Раз в минуту: чаще — работа ради работы, реже — движок живёт
 *     лишние минуты.
 *  2. **Независимо от экрана.** Закрытый экран «Модели» — не повод держать
 *     движок. Это и был дефект.
 *  3. **Не в фоне без окна.** Когда окно скрыто, проверять нечего: приложение уже
 *     не в простое, а не работает; такой случай называется отдельно.
 *  4. **Останавливается.** Сердцебиение, которое нельзя остановить, — это
 *     утечка таймера, и она видна только по нагрузке через час.
 */

/** Как часто проверять простой. Минута — компромисс: дёшево и не поздно. */
export const BEAT_MS = 60 * 1000;

/** Что приложение делает прямо сейчас. */
export interface BeatState {
  /** Окно видимо человеку. */
  visible: boolean;
  /** Движок загружен (иначе проверять нечего — он и так не занимает). */
  engineLoaded: boolean;
}

/**
 * Нужно ли спрашивать состояние движка **сейчас**.
 *
 * Три «нет»: окно скрыто (не простой, а не работаем), движок не загружен
 * (спрашивать не о чем) и всё остальное время — «да».
 */
export function shouldBeat(state: BeatState): boolean {
  if (!state.visible) return false;
  return state.engineLoaded;
}

/**
 * Запустить сердцебиение. Возвращает функцию остановки — её обязаны вызвать:
 * таймер без остановки живёт дольше того, кто его создал.
 *
 * `setInterval` намеренно не используется: `setTimeout` с перепланированием
 * позволяет остановиться между шагами, не дожидаясь срабатывания, и не копит
 * пропущенные вызовы, когда вкладка спала.
 */
export function startBeat(
  tick: () => void,
  options: { every?: number; schedule?: (run: () => void, ms: number) => unknown; cancel?: (handle: unknown) => void } = {},
): () => void {
  const every = options.every ?? BEAT_MS;
  const schedule =
    options.schedule ??
    ((run: () => void, ms: number) => (globalThis as { setTimeout: typeof setTimeout }).setTimeout(run, ms));
  const cancel =
    options.cancel ??
    ((handle: unknown) => (globalThis as { clearTimeout: typeof clearTimeout }).clearTimeout(handle as number));

  let stopped = false;
  let handle: unknown = null;

  const step = () => {
    if (stopped) return;
    try {
      tick();
    } finally {
      // Перепланирование в `finally`: исключение в тике не должно убивать
      // сердцебиение молча — иначе выгрузка перестанет случаться, и никто не
      // узнает, почему.
      if (!stopped) handle = schedule(step, every);
    }
  };

  handle = schedule(step, every);

  return () => {
    stopped = true;
    if (handle !== null) cancel(handle);
    handle = null;
  };
}
