/**
 * Отмена возвращает управление мгновенно, даже если ядро ещё считает (шаг 138).
 *
 * Дефект. «Стоп» ждал, пока ядро ответит:
 *
 *  * **интерфейс — заложник**: нажали «стоп», а экран остаётся в «думаю», пока ядро не
 *    вернёт ответ; при зависшем ядре — навсегда;
 *  * **отмена ждёт подтверждения**: если остановка — это «попросить ядро остановиться и
 *    дождаться», то она не работает именно тогда, когда нужна;
 *  * **поздний ответ оживает**: ядро отвечает через минуту после «стопа», и старый ответ
 *    появляется поверх нового дела;
 *  * **«идёт» после отмены** — это ложь: работа брошена, а состояние не снято.
 *
 * Правило: **отмена — это смена состояния сначала, а потом вежливая просьба ядру**.
 *
 *  1. **Сначала отпускаем** интерфейс (снимаем «идёт», включаем ввод), потом просим ядро
 *     остановиться. Ядро может считать сколько угодно — человек уже свободен.
 *  2. **Поздний ответ выбрасывается**: у каждого запроса есть номер, отмена его
 *     увеличивает, и пришедший ответ с чужим номером — не ответ.
 *  3. **Отменённое называется отменённым**, а не «ошибкой» и не «готово».
 *  4. **Ядро не бросают навсегда**: остановку просят, но **не ждут** — и это сказано.
 *  5. **Мгновенно — это сейчас**, а не «после ответа ядра»: проверяется числом (кадр).
 *
 * Почему не «дождаться остановки ядра и потом отпустить». Тогда «стоп» длится столько же,
 * сколько ответ, — то есть отмены нет; именно в этот момент она и нужна.
 */

/** Что было отменено. */
export interface Cancelled {
  /** Что остановили — словами, для отчёта. */
  what: string;
  /** Номер запроса на момент отмены. */
  token: number;
}

/**
 * Отмена: номер растёт, и всё, что придёт с меньшим, — не наше.
 *
 * Чистая функция, чтобы «поздний ответ» можно было проверить без ядра.
 */
export function cancel(token: number, what: string): { cancelled: Cancelled; token: number } {
  return { cancelled: { what, token }, token: token + 1 };
}

/**
 * Надо ли принять ответ ядра.
 *
 * Ответ с чужим номером — не ответ: его уже никто не ждёт, и показать его значило бы
 * оживить отменённое.
 */
export function accept(token: number, answer: number): { accept: boolean; said: string } {
  if (answer !== token) {
    return { accept: false, said: `поздний ответ (${answer}) после отмены (${token}) — выбрасываю` };
  }
  return { accept: true, said: "" };
}

/**
 * Что делаем в каком порядке.
 *
 * Порядок — часть условия: «сначала отпустить, потом просить» — это и есть мгновенность.
 */
export function order(): { first: "release"; second: "ask-kernel"; said: string } {
  return {
    first: "release",
    second: "ask-kernel",
    said: "сначала отпускаю интерфейс, потом прошу ядро остановиться — ядро может считать ещё сколько угодно",
  };
}

/**
 * Что сказать человеку.
 *
 * Не «останавливаю…» — это ждать; а «остановлено: управление у вас», и про ядро
 * отдельно.
 */
export function said(cancelled: Cancelled): string {
  return `«${cancelled.what}» остановлено — управление у вас; ядро досчитает и его ответ будет выброшен`;
}

/** Мгновенно ли: ≤ кадра, как и в 132. */
export const FRAME_MS = 16;

export function instant(ms: number): { ok: boolean; said: string } {
  if (ms <= FRAME_MS) return { ok: true, said: `${ms} мс — управление вернулось сразу` };
  return { ok: false, said: `${ms} мс — отмена ждала: это уже не мгновенно` };
}

/**
 * Отчёт: что было в работе на момент отмены.
 *
 * «Бросили» и «не начинали» — разные факты; отчёт не должен выглядеть как второй.
 */
export function report(cancelled: Cancelled, wasRunning: boolean): string {
  if (!wasRunning) return `«${cancelled.what}» не начиналось — отмены не потребовалось`;
  return `«${cancelled.what}» было в работе и остановлено; сделанное до отмены не откатывается`;
}

/**
 * Не осталось ли «идёт» после отмены.
 *
 * Состояние — по факту: отмена снимает «идёт» **до** ответа, и проверка ловит
 * забытое снятие.
 */
export function settled(busy: boolean, cancelled: Cancelled | null): { ok: boolean; said: string } {
  if (cancelled !== null && busy) {
    return { ok: false, said: `отменено, но состояние «идёт» осталось — интерфейс всё ещё заложник` };
  }
  return { ok: true, said: "" };
}
