/**
 * Журнал фраз: что услышано, что понято, что сделано (шаг 60).
 *
 * Дефект. Что-то пошло не так — модель сделала не то, не расслышала, ответила
 * мимо. Человек помнит **смысл** («я же просил отчёт!»), но не помнит **слов** —
 * и не может показать, где цепочка сломалась. Разбор превращается в «так было же»,
 * а приложение выглядит виноватым без доказательств (и человек тоже).
 *
 * Правило: по каждой фразе — **одна строка**, и в ней три разных факта:
 *
 *  1. **Услышано** — что разобрало распознавание (шаг 58: с оговоркой, если
 *     сомневалось);
 *  2. **Понято** — как это понял разбор (шаг 46: «понял так: …»);
 *  3. **Сделано** — что в итоге произошло.
 *
 * Три факта разделены, потому что ломаются они в разных местах: услышано
 * неверно, услышано верно но понято не так, понято верно но не сделано. Один
 * слитый текст «запрос: X, результат: Y» этого не показывает.
 *
 * Почему одна строка, а не подробный лог. Подробности человек не читает. Ему
 * нужно **найти** ту фразу и увидеть, где разошлось, — как строку в списке, а не
 * как простыню. Подробности доступны по нажатию.
 */

/** Что случилось с фразой — и где именно разошлось. */
export type Stage =
  /** Услышано неверно: распознавание подвело. */
  | "heard-wrong"
  /** Услышано верно, понято не так: разбор подвёл. */
  | "understood-wrong"
  /** Понято верно, но не выполнено: отказ, ошибка, ожидание подтверждения. */
  | "not-done"
  /** Всё хорошо. */
  | "done";

/** Одна фраза. */
export interface Line {
  /** Когда — по часам, а не «давно». */
  at: number;
  /** Что услышано. */
  heard: string;
  /** Как понято. `null` — не поняли вовсе. */
  understood: string | null;
  /** Что сделано (или что случилось вместо). */
  did: string;
  /** Где разошлось. */
  stage: Stage;
}

/**
 * Сколько строк храним.
 *
 * Не «всё»: журнал, который растёт без предела, через месяц нельзя пролистать, и
 * он же становится хранилищем чужих приватных фраз. Сто — это несколько дней
 * обычной работы и достаточно, чтобы найти вчерашнее.
 */
export const KEEP = 100;

/** Добавить строку. Новые — сверху: искать вчерашнее начинают с недавнего. */
export function push(lines: readonly Line[], line: Line): Line[] {
  return [line, ...lines].slice(0, KEEP);
}

/**
 * Где разошлось — по трём фактам.
 *
 * Отдельная функция, потому что это **вывод**, а не запись: определить, что
 * распознавание подвело, а не разбор, можно только сравнив «услышано» с тем,
 * что человек имел в виду, — а это известно лишь в случае, когда он поправил
 * фразу (шаг 58) или повторил её.
 */
export function stage(heard: string, understood: string | null, did: string | null): Stage {
  if (did === null) {
    // Не сделано ничего: либо не поняли, либо ждали и не дождались.
    return understood === null ? "understood-wrong" : "not-done";
  }
  if (understood === null) return "understood-wrong";
  return heard.trim().length > 0 ? "done" : "heard-wrong";
}

/**
 * Одна строка журнала — то, что человек читает.
 *
 * Названы **все три факта**, даже если один совпадает с другим: человек ищет
 * место, где разошлось, и «понято = услышано» — тоже сведения.
 */
export function text(line: Line): string {
  const time = clock(line.at);
  const heard = line.heard.trim().length > 0 ? line.heard.trim() : "(ничего)";
  const understood = line.understood === null ? "(не понял)" : line.understood;
  return `${time} · услышал: ${heard} · понял: ${understood} · сделал: ${line.did}`;
}

/** Время по часам: «14:07», а не «давно» или отметка времени в миллисекундах. */
export function clock(at: number): string {
  const date = new Date(at);
  const hours = String(date.getHours()).padStart(2, "0");
  const minutes = String(date.getMinutes()).padStart(2, "0");
  return `${hours}:${minutes}`;
}

/** Что сказать, если журнал пуст: пустой экран непонятен. */
export function empty(): string {
  return "журнал пуст — здесь появятся ваши фразы по одной строке";
}

/**
 * Найти строки, где разошлось.
 *
 * Нужно для разбора: человек не читает сто строк подряд, он ищет **плохие**.
 */
export function broken(lines: readonly Line[]): Line[] {
  return lines.filter((line) => line.stage !== "done");
}

/** Что сказать про строку: коротко, где разошлось. */
export function why(line: Line): string {
  switch (line.stage) {
    case "heard-wrong":
      return "услышано неверно — распознавание подвело";
    case "understood-wrong":
      return "услышано верно, понято не так — разбор подвёл";
    case "not-done":
      return "понято верно, но не выполнено";
    case "done":
      return "сделано";
  }
}
