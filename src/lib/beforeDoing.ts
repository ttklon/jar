/**
 * Фраза показывается до исполнения — и её можно поправить (шаг 46).
 *
 * Дефект. Распознанный текст сразу уходил в исполнение: `search(heard)` в том же
 * обработчике, без паузы. Ошибка распознавания запускала действие — а неверно
 * понятая просьба стоит дороже, чем неверно понятое слово: одно дело «создай
 * папку» вместо «создай папку X», другое — «удали папку» вместо «удали папку X».
 *
 * Что значит «показать до исполнения». Не «спросить разрешения на каждую
 * фразу» — это превратило бы разговор в анкету, и человек говорил бы вдвое
 * больше, чтобы сделать вдвое меньше. Показывать надо **только там, где ошибка
 * стоит денег или времени**:
 *
 *  * **необратимое** — удаление, замена, перезапись. Здесь пауза обязательна:
 *    отменить уже нечего;
 *  * **далеко идущее** — действие, которое трогает много файлов или ходит
 *    наружу. Одно слово меняет много;
 *  * **уверенность низкая** — распознавание сомневается. Но сомнение — не
 *    всегда повод спрашивать: у «покажи историю» сомнение безвредно.
 *
 * И наоборот: **обратимое и близкое** — не спрашиваем. «Покажи» без паузы лучше,
 * чем «покажи» с вопросом: человек просил показать, а не подтвердить, что просил
 * показать.
 *
 * Вторая половина шага — **поправить**. Показать фразу без возможности её
 * исправить — это не проверка, а уведомление. Поэтому у решения есть правка и
 * два ответа: «да, так» и «повторить». «Поправить» — это поле, а не кнопка: человек
 * может исправить одно слово, не начиная заново.
 */

/** Что известно о фразе и действии на момент решения. */
export interface Situation {
  /** Распознанный текст. */
  text: string;
  /** Действие необратимо: отменить его нельзя. */
  irreversible: boolean;
  /** Действие трогает много или ходит наружу. */
  broad: boolean;
  /** Уверенность распознавания от 0 до 1; `null` — неизвестна. */
  confidence: number | null;
}

/** Что делать с фразой. */
export type Before =
  | { kind: "go"; text: string }
  | { kind: "ask"; text: string; why: string };

/** Уверенность, ниже которой фраза не идёт сразу. 0.7 — «скорее да, чем нет». */
export const SURE = 0.7;

/**
 * Показать или исполнить.
 *
 * `ask` — потому что ошибка стоит дорого; `go` — потому что пауза стоит дороже
 * ошибки, которую она предотвращает.
 *
 * Уверенность `null` **не** считается низкой: неизвестная уверенность — это
 * «неизвестно», а не «плохо». Иначе в окружении без оценки уверенности всё
 * спрашивало бы подтверждения, и разговор снова стал бы анкетой.
 */
export function before(situation: Situation): Before {
  const text = situation.text.trim();
  if (text.length === 0) {
    // Пустое — не фраза, его нечего показывать и нечего исполнять.
    return { kind: "ask", text: "", why: "ничего не расслышал — повторите" };
  }
  if (situation.irreversible) {
    return { kind: "ask", text, why: "это не отменить — проверьте, что понял верно" };
  }
  if (situation.broad) {
    return { kind: "ask", text, why: "это затронет многое — проверьте, что понял верно" };
  }
  if (situation.confidence !== null && situation.confidence < SURE) {
    return { kind: "ask", text, why: "расслышал не всё — поправьте, если что-то не так" };
  }
  return { kind: "go", text };
}

/**
 * Как фраза показывается.
 *
 * Слово «понял», а не «услышал»: важно, **что мы поняли**, — иначе человек
 * исправляет то, что и так было сказано, а не то, что мы разобрали.
 */
export function shade(text: string): string {
  return `понял так: «${text}»`;
}

/**
 * Что человек может сделать с показанной фразой.
 *
 * Три пути, и «поправить» — именно правка текста, а не повтор всего заново:
 * исправить одно слово должно быть дешевле, чем сказать фразу снова.
 */
export interface Choices {
  confirm: string;
  edit: string;
  again: string;
}

export const CHOICES: Choices = {
  confirm: "да, так",
  edit: "поправить",
  again: "повторить",
};
