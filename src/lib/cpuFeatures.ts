/**
 * Проверка совместимости квантования с железом: AVX2 / AVX512 / GPU (шаг 78).
 *
 * Дефект тихий, и потому худший из всех в этом разделе. Движок собран под
 * определённые инструкции процессора. Если их нет, происходит не ошибка, а
 * **тихая деградация**:
 *
 *  * модель **работает**, но втрое-впятеро медленнее: движок откатывается на
 *    скалярный код;
 *  * человек думает «эта модель медленная» и **выбирает меньшую** — а дело было
 *    не в модели;
 *  * или движок **падает с невнятной ошибкой** об инструкции, и это выглядит
 *    как поломка приложения.
 *
 * Правило: **совместимость проверяется до запуска и называется словами**.
 *
 *  1. Проверяем **набор инструкций**, а не «примерно новое железо». Процессор
 *     без AVX2 — это не «старый», это конкретный факт.
 *  2. Сказано, **что произойдёт**: «без AVX2 будет втрое медленнее» — человек
 *     должен знать, чего ждать, до запуска.
 *  3. Модель, требующая AVX512, **не предлагается** процессору без него: тихая
 *     деградация тут не «медленнее», а «падает».
 *  4. GPU проверяется отдельно (шаг 61): «видеокарта есть» не значит «движок
 *     умеет на ней считать».
 *
 * Почему не «просто попробуем и посмотрим». Проба стоит загрузки модели и
 * минуты ожидания; проверка инструкций стоит ноль.
 */

/** Что умеет процессор. */
export interface Cpu {
  /** AVX2 — базовая инструкция для всех современных сборок. */
  avx2: boolean;
  /** AVX512 — быстрее, но только на части процессоров. */
  avx512: boolean;
  /** Есть ли видеокарта, на которой движок умеет считать. */
  gpu: boolean;
}

/** Что требуется от сборки движка. */
export type Need = "avx2" | "avx512" | "gpu" | "plain";

/**
 * Что произойдёт при запуске.
 *
 * `fast` — как задумано; `slow` — работает, но медленнее (и это сказано);
 * `crash` — не запускается. `crash` — не «может быть»: требование AVX512 на
 * процессоре без него падает предсказуемо.
 */
export type Outcome = "fast" | "slow" | "crash";

/**
 * Проверка совместимости.
 *
 * `plain` — сборка без специальных инструкций: работает везде, потому что ничего
 * не требует.
 */
export function outcome(cpu: Cpu, need: Need): Outcome {
  switch (need) {
    case "plain":
      return "fast";
    case "avx2":
      // Без AVX2 движок откатится на скалярный код: работает, но медленно.
      return cpu.avx2 ? "fast" : "slow";
    case "avx512":
      // Не «медленнее»: сборка под AVX512 на процессоре без него падает.
      return cpu.avx512 ? "fast" : cpu.avx2 ? "crash" : "crash";
    case "gpu":
      // Нет видеокарты — считаем на процессоре, и это не сбой, а другой путь.
      return cpu.gpu ? "fast" : "slow";
  }
}

/**
 * Можно ли предложить.
 *
 * `crash` — нельзя: предложить то, что падает, значит устроить поломку на
 * ровном месте. `slow` — можно, но **с предупреждением**.
 */
export function offered(cpu: Cpu, need: Need): boolean {
  return outcome(cpu, need) !== "crash";
}

/**
 * Что сказать человеку.
 *
 * Названо **чего ждать**, а не «требования к процессору»: человеку нужно знать
 * «быстро / медленно / не пойдёт», а не названия инструкций.
 */
export function say(cpu: Cpu, need: Need): string {
  switch (outcome(cpu, need)) {
    case "fast":
      return need === "gpu"
        ? "видеокарта подходит — считать будет на ней"
        : "процессор подходит — будет быстро";
    case "slow":
      return need === "gpu"
        ? "видеокарты для движка нет — считать будет на процессоре, это медленнее"
        : "без AVX2 будет втрое медленнее — работает, но ждать дольше";
    case "crash":
      return "эта сборка требует AVX512, а в процессоре его нет — запускать нельзя, будет падение";
  }
}

/**
 * Лучшая сборка, которая **точно работает**.
 *
 * Порядок предпочтения: AVX512 → AVX2 → plain. GPU — отдельно и только если
 * он есть. Выбор нужен, чтобы не предлагать падающее и не давать медленное,
 * когда есть быстрое.
 */
export function best(cpu: Cpu): Need {
  if (cpu.avx512) return "avx512";
  if (cpu.avx2) return "avx2";
  return "plain";
}

/**
 * Как проверяются инструкции — честно.
 *
 * В браузере набор инструкций **не виден**; в приложении — виден из системы.
 * Функция называет это, чтобы не выдавать «неизвестно» за «есть».
 */
export function howKnown(inApp: boolean): string {
  return inApp
    ? "набор инструкций прочитан из системы"
    : "в браузере набор инструкций не виден — проверка будет при запуске движка";
}

/**
 * Осторожное значение, когда неизвестно.
 *
 * Не знать — не повод обещать AVX512. По умолчанию считаем, что есть только
 * AVX2: это верно для подавляющего большинства машин и **безопасно** — лучше
 * медленнее, чем падение.
 */
export function assumed(): Cpu {
  return { avx2: true, avx512: false, gpu: false };
}
