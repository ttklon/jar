/**
 * Шаг 446: горячие клавиши без конфликтов с системой, с проверкой занятости.
 *
 * Горячая клавиша, которая не срабатывает, — это «программа сломана». А которая
 * срабатывает **вместо** системной — «программа захватила клавиатуру». Оба
 * варианта плохи, и оба происходят от одной ошибки: назначить, не проверив.
 *
 * Поэтому:
 *
 *  * **проверка до сохранения**, а не после: нажал «сохранить» — узнал, что
 *    `Ctrl+Shift+Z` занята другой программой;
 *  * **системные сочетания не трогаем** — список короткий, но жёсткий;
 *  * **если проверить нельзя — не назначаем молча**: предлагаем другую и
 *    говорим, что именно не проверили.
 */

/** Что нажали. */
export interface Combo {
  /** Модификаторы в нормальном порядке: ctrl, alt, shift, win. */
  readonly mods: readonly ("ctrl" | "alt" | "shift" | "win")[];
  /** Основная клавиша: одна буква, цифра или имя. */
  readonly key: string;
}

/**
 * Системные сочетания, которые нельзя занимать.
 *
 * Список — только те, что ломают Windows, если их отнять: рабочий стол, меню
 * «Пуск», переключение раскладки, диспетчер задач, блокировка экрана.
 */
export const SYSTEM: readonly string[] = ["ctrl+alt+delete", "win", "win+d", "win+e", "win+l", "win+r", "win+tab", "alt+tab", "alt+f4", "ctrl+shift+escape", "alt+shift"];

/**
 * Записанное сочетание в одну строку.
 *
 * Модификаторы в одном порядке: `Ctrl+Shift+Z` и `Shift+Ctrl+Z` — одно и то же, а
 * строка разная. Сравнивать надо нормализованное.
 */
export function format(combo: Combo): string {
  const order: ("ctrl" | "alt" | "shift" | "win")[] = ["ctrl", "alt", "shift", "win"];
  const mods = order.filter((mod) => combo.mods.includes(mod));
  const key = combo.key.toLowerCase();
  return [...mods, key].join("+");
}

/**
 * Можно ли назначить.
 *
 * Три отказа: занято системой, не сработает (нет модификатора на букве), и «не
 * проверить» — честно названный.
 */
export function check(combo: Combo, taken: readonly string[] = [], known = true): { ok: boolean; said: string } {
  const key = format(combo);

  if (SYSTEM.includes(key)) {
    return { ok: false, said: `${key} — системное сочетание Windows: если его занять, перестанет работать то, к чему человек привык` };
  }

  if (combo.mods.length === 0 && combo.key.length === 1) {
    return { ok: false, said: "одна буква без модификатора не годится: она сработает при наборе текста, где угодно" };
  }

  if (!known) {
    return { ok: false, said: `занятость ${key} проверить не удалось: не назначаю молча — выберите другую или подтвердите эту` };
  }

  const clash = taken.map((item) => item.toLowerCase()).includes(key);
  if (clash) {
    return { ok: false, said: `${key} уже занята другой программой: она не сработает, и вы решите, что приложение сломалось` };
  }

  return { ok: true, said: `${key} свободна: можно назначать` };
}

/**
 * Как проверять занятость.
 *
 * Не «просто попробуем»: до сохранения показываем результат, а если не вышло —
 * говорим об этом прямо.
 */
export function howChecked(): string[] {
  return [
    "до сохранения: нажали «назначить» — увидели ответ",
    "системный список — отдельно, он не требует проверки",
    "не проверилось — сказано и предложено выбрать другую",
  ];
}

/**
 * Что горячая клавиша не делает.
 *
 * Три запрета — про захват клавиатуры.
 */
export function notDo(): string[] {
  return [
    "не перехватывает без модификатора: одна буква сработала бы при наборе",
    "не занимает системное сочетание даже по просьбе: сломается привычное",
    "не срабатывает дважды при удержании: повтор — отдельное правило",
  ];
}

/**
 * Сочетание по умолчанию.
 *
 * `Ctrl+Alt+Space`: не занято ничем привычным и требует двух модификаторов, то
 * есть случайно не нажмётся.
 */
export function byDefault(): Combo {
  return { mods: ["ctrl", "alt"], key: "space" };
}
