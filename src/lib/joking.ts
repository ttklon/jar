/**
 * Опасное намерение распознавать даже в шутливой форме (шаг 94).
 *
 * Дефект. «Снеси всё к чёртовой матери» — это шутка, если человек в хорошем
 * настроении, и не шутка, если он это делает **механически**: приложение не
 * слышит интонации и не видит, что человек улыбается. Сегодня происходит одно
 * из двух:
 *
 *  * **шуточная форма проходит мимо защиты**: «почисти всё нафиг» не совпадает
 *    со словом «удали», и защита не срабатывает — а объём при этом «всё»;
 *  * или **шуточная форма отвергается целиком**: «да сожги ты уже эту папку» —
 *    и человек не получает ничего, хотя просил конкретное.
 *
 * Правило: **исполнение — по намерению, а не по тону; объём важнее тона**.
 *
 *  1. Шутка — это **тон**, а опасность — это **объём и необратимость**. «Снеси
 *     всё» опасно не потому, что «снеси», а потому что «всё».
 *  2. **Опасное намерение распознаётся в любой форме**: «снеси», «сожги»,
 *     «в топку», «нафиг», «к чёртовой матери» — те же действия.
 *  3. Распознать — **не значит исполнить**. Распознанное опасное намерение идёт
 *     через подтверждение с числом (шаг 73, 82) — шутка или нет.
 *  4. **Шутка не оправдывает**: приложение не оценивает настроение, потому что
 *     оценка настроения — это угадывание. Оно спрашивает.
 *  5. **Эмоциональные слова не отбрасываются как мусор** («нафиг», «блин»,
 *     «давай уже»): вместе с ними уходит и «снеси всё».
 *
 * Почему не «отличить шутку от серьёзного». Отличить нельзя: интонации нет,
 * контекста нет, а цена ошибки необратима. «Спросить всегда» дешевле, чем
 * «стереть потому что он улыбался».
 */

/** Что человек хочет с объёмом и тоном. */
export interface Dangerous {
  /** Опасное действие найдено. */
  found: boolean;
  /** Что именно: слово, которое это выдало. */
  word: string | null;
  /** Объём: «всё» — самый опасный. */
  everything: boolean;
  /** Была ли шутливая/эмоциональная форма. */
  joke: boolean;
  /** Почему так — для показа и теста. */
  why: string;
}

/**
 * Слова опасных действий **в любой форме**.
 *
 * «Снеси», «сожги», «в топку», «сотри» — это одно и то же действие, и шутить ими
 * можно, а исполнять без вопроса нельзя.
 */
const DANGEROUS = [
  /снеси|снести|снес/i,
  /сожги|сжечь|в\s+топку|в\s+печь/i,
  /сотри|стереть|удали(?:те)?\s+всё|удали(?:те)?\s+все/i,
  /форматни|отформатируй|переустанови/i,
  /затри|затереть|уничтожь/i,
];

/** Эмоциональные слова: с ними уходит и «снеси». */
const EMOTION = /(?:нафиг|нахуй|нахер|к\s+чёртовой\s+матери|к\s+чертовой\s+матери|блин|давай\s+уже|срочно)/i;

/** Объём «всё»: самый опасный признак. */
const EVERYTHING = /(?:^|\s)(?:всё|все|весь|всю|all)(?=\s|$|,|\.)/i;

/**
 * Разбор опасного намерения.
 *
 * Тон **не влияет** на «найдено»: «снеси всё нафиг» и «снеси всё» — одно
 * намерение, и оба требуют вопроса.
 */
export function check(phrase: string): Dangerous {
  const clean = phrase.trim();
  if (clean.length === 0) {
    return { found: false, word: null, everything: false, joke: false, why: "фразы нет" };
  }

  let word: string | null = null;
  for (const pattern of DANGEROUS) {
    const match = pattern.exec(clean);
    if (match !== null) {
      word = match[0];
      break;
    }
  }

  const everything = EVERYTHING.test(clean);
  const joke = EMOTION.test(clean);

  if (word === null && !(everything && joke)) {
    return {
      found: false,
      word: null,
      everything,
      joke,
      why: everything ? "объём «всё», но опасного действия не названо — это ещё не приказ" : "опасного намерения нет",
    };
  }

  const why =
    word !== null
      ? joke
        ? `опасное действие «${word}» в шутливой форме — тон не меняет объём`
        : `опасное действие «${word}»${everything ? " и объём «всё»" : ""}`
      : "объём «всё» с эмоцией — похоже на «снести всё», спрошу";

  return { found: true, word: word ?? (everything ? "всё" : null), everything, joke, why };
}

/**
 * Можно ли исполнять без подтверждения.
 *
 * **Нельзя** ни в шутку, ни всерьёз: шутка не оправдывает, а настроение
 * угадывать нельзя.
 */
export function canRun(got: Dangerous): boolean {
  return !got.found;
}

/**
 * Что сказать человеку.
 *
 * Названо **что понято и сколько это**, без морали о шутках: человек, который
 * шутил, увидит, что шутка понята, и нажмёт «нет»; человек, который не шутил,
 * увидит цену.
 */
export function say(got: Dangerous, count: number | null): string {
  if (!got.found) return "опасного намерения нет";
  const volume = got.everything ? "всё" : count !== null ? String(count) : "несколько";
  return got.joke
    ? `понял: ${got.word ?? "удалить"} ${volume}. Даже если это шутка — стереть можно один раз, подтвердите или отмените`
    : `понял: ${got.word ?? "удалить"} ${volume}. Это необратимо — подтвердите`;
}

/**
 * Подтверждение не считается шуткой.
 *
 * «Да, сноси всё нафиг» — это **подтверждение**, а не новая шутка: вопрос уже
 * задан, и человек ответил. Функция нужна, чтобы это не потерялось при правках.
 */
export function confirmIsJoke(_phrase: string): false {
  return false;
}

/**
 * Сколько эмоций в фразе — ноль для решения.
 *
 * Функция названа прямо, чтобы никто не добавил «оценку тона» при правках:
 * оценка настроения — это угадывание, а угадывание при удалении недопустимо.
 */
export function toneWeight(_phrase: string): 0 {
  return 0;
}
