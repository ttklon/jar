/**
 * Шаг 426: ошибки модели (таймаут, битый ответ) не выглядят как «ты не понял».
 *
 * Это самая обидная путаница в голосовых приложениях. Модель не ответила вовремя
 * — приложение пишет «не понял запрос». Человек начинает переформулировать
 * **правильную** фразу, всё сильнее веря, что проблема в нём. На самом деле
 * проблема на нашей стороне.
 *
 * Поэтому три вида отказа называются **разными словами**, и слова говорят, чья
 * это проблема:
 *
 *  * **таймаут** — «я не успел ответить» (моя вина, ждать или повторить);
 *  * **битый ответ** — «мой ответ сломался» (моя вина, повтор помогает);
 *  * **не понял** — «не разобрал вашу фразу» (может быть обоюдная, и предлагается
 *    пример).
 *
 * И четвёртый, который нельзя путать ни с чем: **отказано политикой** — «понял,
 * но не буду». Это не ошибка, а решение.
 */

/** Что случилось. */
export type Fault = "timeout" | "broken" | "unclear" | "refused" | "offline";

/** Что сказать человеку. */
export interface Said {
  /** Чья это проблема: моя, ваша или обоюдная. */
  readonly whose: "моя" | "ваша" | "обоюдная" | "никого";
  /** Что сказать. */
  readonly text: string;
  /** Что предложить сделать. */
  readonly next: string;
  /** Стоит ли повторять ту же фразу. */
  readonly repeatSame: boolean;
}

/**
 * Назвать отказ.
 *
 * `repeatSame` — главное поле: при таймауте и битом ответе ту же фразу **стоит**
 * повторить, при «не понял» — нет, её надо сказать иначе.
 */
export function say(fault: Fault): Said {
  switch (fault) {
    case "timeout":
      return { whose: "моя", text: "я не успел ответить: это моя ошибка, фраза была нормальная", next: "повторите ту же фразу — или подождите, если модель ещё грузится", repeatSame: true };
    case "broken":
      return { whose: "моя", text: "мой ответ сломался по дороге: это моя ошибка", next: "повторите ту же фразу: обычно со второго раза выходит", repeatSame: true };
    case "unclear":
      return { whose: "обоюдная", text: "не разобрал вашу фразу", next: "скажите иначе — например, «сколько места на диске»", repeatSame: false };
    case "refused":
      return { whose: "никого", text: "понял, но этого не сделаю: дело опасное без вашего согласия", next: "подтвердите, если хотите, чтобы я его выполнил", repeatSame: false };
    case "offline":
      return { whose: "моя", text: "нет связи с моделью: она не запущена или выключена", next: "проверьте, что модель скачана и движок работает", repeatSame: true };
  }
}

/**
 * Чья это ошибка — для журнала.
 *
 * Отдельное поле, а не текст: по нему считают, и «ты не понял» не должно попадать
 * в статистику ошибок модели.
 */
export function blame(fault: Fault): "модель" | "человек" | "ничья" {
  const whose = say(fault).whose;
  if (whose === "моя") return "модель";
  if (whose === "ваша") return "человек";
  if (whose === "обоюдная") return "человек";
  return "ничья";
}

/**
 * Что нельзя говорить.
 *
 * Пять фраз, каждая из которых перекладывает нашу ошибку на человека.
 */
export function neverSay(): string[] {
  return [
    "«не понял» при таймауте: человек начинает переделывать правильную фразу",
    "«попробуйте ещё раз» без указания, что именно менять",
    "«ошибка» без сказанного, чья она",
    "«неверный запрос» — это протокол, а не человек",
    "«не удалось распознать речь» при ошибке модели: речь тут не при чём",
  ];
}
