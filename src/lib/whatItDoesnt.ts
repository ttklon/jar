/**
 * Проверить документ.
 *
 * Нарушения: без причины, слишком длинно, «не поддерживается» вместо объяснения.
 */
export function check(list: readonly Limit[]): string[] {
  const problems: string[] = [];

  if (list.length > 15) problems.push(`пунктов ${list.length}, а больше пятнадцати не читают`);

  const noWhy = list.filter((item) => item.why.trim().length < 10).map((item) => item.what);
  if (noWhy.length > 0) problems.push(`без причины: ${noWhy.join(", ")}`);

  const vague = list.filter((item) => /не поддерживается|не реализовано|в будущих версиях/i.test(item.why)).map((item) => item.what);
  if (vague.length > 0) problems.push(`оправдание вместо причины: ${vague.join(", ")}`);

  return problems;
}

/**
 * Где видно.
 *
 * Три места, и все — те, куда человек действительно смотрит.
 */
export function visibleAt(): string[] {
  return [
    "первый экран: ссылка «чего я не делаю» рядом с примерами фраз",
    "ответ на отказ: «почему» содержит ссылку на этот документ",
    "документация: раздел целиком",
  ];
}

/**
 * Что документ не делает.
 *
 * Три запрета — про честность списка.
 */
export function notDo(): string[] {
  return [
    "не перечисляет «в будущих версиях»: обещание на будущее — это не ограничение",
    "не прячется в документации для разработчиков",
    "не растёт до сотни пунктов: длинный список никто не прочитает, и он перестанет работать",
  ];
}
