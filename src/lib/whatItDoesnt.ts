/**
 * Шаг 465: документ «чего приложение не делает» на виду.
 *
 * Самый честный документ проекта — список того, чего он **не** делает. Он же
 * самый полезный: человек перестаёт ждать невозможного и находит **то, что
 * есть**. «Не отправляет сообщения» объясняет, почему фраза «напиши маме»
 * отказывает, лучше, чем любое описание функций.
 *
 * Три правила:
 *
 *  * **на виду** — ссылка с главного экрана и из первого ответа, а не спрятан в
 *    документации для разработчиков;
 *  * **каждый пункт с причиной** — «не делает X, потому что Y», а не «не
 *    поддерживается»: причина объясняет границу, а не оправдывается;
 *  * **коротко** — не больше пятнадцати пунктов, иначе это уже не читают.
 */

/** Пункт. */
export interface Limit {
  /** Чего не делает. */
  readonly what: string;
  /** Почему — так, чтобы было понятно без контекста. */
  readonly why: string;
  /** Чем заменить — если есть чем. */
  readonly instead?: string;
}

