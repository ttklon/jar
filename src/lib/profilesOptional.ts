/**
 * Шаг 411: профиль человека — необязательная функция, по умолчанию один.
 *
 * Самая частая смерть полезной функции — когда её включили всем. Профили,
 * сделанные «по умолчанию», дают приложению повод спрашивать «кто вы» у человека,
 * который всю жизнь один за компьютером.
 *
 * Поэтому профиль — **настройка, выключенная по умолчанию**, и у неё четыре
 * состояния, а не два:
 *
 *  * **один человек (по умолчанию)** — ни слова про профили;
 *  * **пришёл гость** — включилось само, но без слов «создайте профиль»;
 *  * **несколько человек** — включено явно, с переключателем;
 *  * **выключено** — человек попробовал и решил, что ему не нужно, и это уважается.
 *
 * Отдельно: **выключение не стирает данные**. Человек, выключивший профили, не
 * соглашался потерять память второго человека — она просто перестаёт
 * показываться.
 */

/** Как устроены люди на этом компьютере. */
export type Mode = "alone" | "guest" | "several" | "off";

/** Что известно. */
export interface State {
  /** Сколько профилей заведено, не считая «я». */
  readonly others: number;
  /** Явно выключено человеком. */
  readonly offByUser: boolean;
  /** Пришёл гость — временный профиль без имени. */
  readonly guest: boolean;
}

/**
 * Режим.
 *
 * Явное «не нужно» сильнее всего: если человек выключил, гость не включает
 * обратно.
 */
export function mode(state: State): Mode {
  if (state.offByUser) return "off";
  if (state.others > 0) return "several";
  if (state.guest) return "guest";
  return "alone";
}

/**
 * Что показывается на экране.
 *
 * Единственное место, где решается «профили видно или нет» — чтобы экран не
 * решал это сам и не разошёлся с другими.
 */
export function visible(state: State): { settingsLine: boolean; switcher: boolean; said: string } {
  const m = mode(state);
  if (m === "alone") return { settingsLine: false, switcher: false, said: "один человек: в настройках нет строки про профили — она появляется, только если людей стало больше" };
  if (m === "off") return { settingsLine: false, switcher: false, said: "профили выключены: память и разрешения второго человека лежат на месте, но не показываются" };
  if (m === "guest") return { settingsLine: true, switcher: true, said: "гость: безопасные руки, и его память не смешивается с вашей" };
  return { settingsLine: true, switcher: true, said: `${state.others + 1} человек: переключатель виден` };
}

/**
 * Включить и выключить.
 *
 * Выключение **не удаляет**: это разные просьбы, и «выключить» не должно значить
 * «стереть».
 */
export function set(state: State, off: boolean): { state: State; said: string } {
  if (off) return { state: { ...state, offByUser: true }, said: "профили выключены: память второго человека осталась, но не показывается" };
  return { state: { ...state, offByUser: false }, said: mode({ ...state, offByUser: false }) === "alone" ? "профили включены: пока вы один, на экране ничего не изменится" : "профили включены" };
}

/**
 * Что не делает «по умолчанию один».
 *
 * Список — приёмочный: каждая строка была бы регрессией для одинокого человека.
 */
export function promises(): string[] {
  return [
    "при первом запуске нет ни слова про людей и профили",
    "нет кнопки «добавить человека» на главном экране: она в настройках",
    "выключенные профили не удаляют память, а прячут её",
  ];
}
