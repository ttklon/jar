/**
 * Разбор «когда» отдельно от «что»: время, событие, условие (шаг 91).
 *
 * Дефект. «Когда» слипается с фразой целиком, и из-за этого:
 *
 *  * **расписания невозможны**: «завтра в девять сделай отчёт» исполняется
 *    **сейчас** — потому что разбор ищет, что делать, и не отделяет «когда»;
 *  * **условие принимается за действие**: «когда закончится копирование, выключи
 *    компьютер» — выключает сразу, если «выключи» находится лучше по словам;
 *  * **«потом» и «через час» неразличимы**: одно значит «после предыдущего», а
 *    другое — «по часам», и это разные вещи с разными последствиями.
 *
 * Правило: **«когда» — отдельная часть фразы, а не украшение**.
 *
 *  1. Три разных «когда», и они не одно и то же:
 *     **время** («в девять», «завтра», «через час») — исполняется по часам;
 *     **событие** («когда закончится копирование») — ждёт другого дела;
 *     **условие** («если диск заполнится больше 90%») — ждёт проверки.
 *  2. Время **без даты** («в девять») — это ближайшие девять, а не «сегодня или
 *     завтра по желанию»: неоднозначность называем, а не решаем за человека.
 *  3. Событие **не начинается**, пока оно не наступило, и не подменяется
 *     «попробовать сейчас». «Попробовать» тихо делает не то.
 *  4. Условие **проверяется**, а не считается выполненным: «если больше 90%» —
 *     это проверка, а не повод сделать сразу.
 *  5. Если «когда» не понято — **не исполнять сразу**: сказать и переспросить.
 *     Сделать сейчас то, что просили на завтра, — это ошибка, которую видно не
 *     сразу.
 *
 * Почему не «сделать сразу и потом повторить». Повтор по расписанию — это уже
 * другая задача, и молчаливое исполнение сейчас её не заменяет.
 */

/** Когда исполнять. */
export type When =
  /** Сейчас — «сделай отчёт». */
  | { kind: "now" }
  /** По времени: конкретный момент или «через». */
  | { kind: "time"; at: number; text: string }
  /** После события: другого дела. */
  | { kind: "event"; event: string }
  /** По условию: проверять, а не исполнять сразу. */
  | { kind: "condition"; check: string }
  /** Не понято. */
  | { kind: "unknown"; text: string };

/** Числа словами — то, что человек говорит вслух и не пишет цифрами. */
const WORDS: Record<string, number> = {
  один: 1,
  два: 2,
  три: 3,
  четыре: 4,
  пять: 5,
  шесть: 6,
  семь: 7,
  восемь: 8,
  девять: 9,
  десять: 10,
  пятнадцать: 15,
  двадцать: 20,
  тридцать: 30,
};

/** Слово в число: «девять» → 9, «9» → 9. Иначе `null` — не угадываем. */
export function number(word: string): number | null {
  const clean = word.toLowerCase().trim();
  if (/^\d+$/.test(clean)) return Number(clean);
  return WORDS[clean] ?? null;
}

/**
 * Разбор «когда».
 *
 * `now` — текущее время, чтобы «завтра в девять» стало моментом, а не словом:
 * без перевода в момент расписание невозможно.
 */
export function parse(phrase: string, now: number): When {
  const clean = phrase.toLowerCase().replace(/ё/g, "е");

  // Событие: «когда закончится …», «после того как …».
  const event = /(?:^|\s)(?:когда|после того как|как только)\s+([^,.;]{3,})/.exec(clean);
  if (event !== null) {
    return { kind: "event", event: (event[1] ?? "").trim() };
  }

  // Условие: «если …».
  const condition = /(?:^|\s)если\s+([^,.;]{3,})/.exec(clean);
  if (condition !== null) {
    return { kind: "condition", check: (condition[1] ?? "").trim() };
  }

  // «Через N минут/часов» — от текущего момента.
  const after = /через\s+(\S+)\s+(минут|час|часа|часов|день|дня|дней)/.exec(clean);
  if (after !== null) {
    const value = number(after[1] ?? "");
    if (value !== null) {
      const unit = after[2] ?? "";
      const unitMs = /час/.test(unit) ? 3_600_000 : /день|дн/.test(unit) ? 86_400_000 : 60_000;
      return { kind: "time", at: now + value * unitMs, text: after[0] };
    }
  }

  // «Завтра/послезавтра/сегодня в девять» — день и час.
  const day = /(сегодня|завтра|послезавтра)/.exec(clean);
  const clock = /(?:в\s+)?(\d{1,2}|один|два|три|четыре|пять|шесть|семь|восемь|девять|десять|одиннадцать|двенадцать)\s*(?:час(?:ов|а)?|:00|утра|вечера|дня|ночи)?/.exec(
    clean,
  );
  if (day !== null || (clock !== null && /утра|вечера|дня|ночи|час/.test(clean))) {
    const base = new Date(now);
    const shift = day?.[1] === "завтра" ? 1 : day?.[1] === "послезавтра" ? 2 : 0;
    base.setDate(base.getDate() + shift);
    const hour = clock !== null ? number(clock[1] ?? "") : null;
    // «В девять вечера» — 21, «в девять утра» — 9: без половины суток фраза
    // неоднозначна, и это надо назвать, а не решить молча.
    if (hour !== null) {
      const evening = /вечера|ночи/.test(clean) && hour < 12;
      base.setHours(evening ? hour + 12 : hour, 0, 0, 0);
    } else {
      base.setHours(9, 0, 0, 0);
    }
    return { kind: "time", at: base.getTime(), text: (day?.[1] ?? "") + (clock?.[0] ?? "") };
  }

  // «В девять» без дня — ближайшие девять, но неоднозначность называем.
  if (clock !== null && number(clock[1] ?? "") !== null) {
    const hour = number(clock[1] ?? "") ?? 0;
    const base = new Date(now);
    base.setHours(hour, 0, 0, 0);
    if (base.getTime() <= now) base.setDate(base.getDate() + 1);
    return { kind: "time", at: base.getTime(), text: clock[0] ?? "" };
  }

  return { kind: "now" };
}

/**
 * Можно ли исполнять сейчас.
 *
 * Только `now`. Всё остальное — ждать: сделать сейчас то, что просили на завтра,
 * это ошибка, которую видно не сразу.
 */
export function ready(when: When, now: number, eventHappened = false): boolean {
  switch (when.kind) {
    case "now":
      return true;
    case "time":
      return now >= when.at;
    case "event":
      return eventHappened;
    case "condition":
      // Условие проверяется отдельно — и это не «готово».
      return false;
    case "unknown":
      return false;
  }
}

/**
 * Что сказать человеку.
 *
 * Не «запланировано»: названо **когда** и **по какому признаку**, иначе человек
 * не может проверить, что понято верно.
 */
export function say(when: When, now: number): string {
  switch (when.kind) {
    case "now":
      return "сейчас";
    case "time": {
      const left = when.at - now;
      const hours = Math.round(left / 3_600_000);
      const clock = new Date(when.at).toLocaleTimeString("ru-RU", { hour: "2-digit", minute: "2-digit" });
      return left <= 0
        ? `пора: ${when.text} — ${clock}`
        : `по часам: ${when.text} — ${clock} (через ${hours < 1 ? "меньше часа" : `${hours} ч`})`;
    }
    case "event":
      return `после события «${when.event}» — не раньше: сейчас не начинаю`;
    case "condition":
      return `если «${when.check}» — проверю и решу, а не сделаю сразу`;
    case "unknown":
      return `не понял, когда именно («${when.text}») — сделаю сразу не буду: скажите по-другому`;
  }
}

/**
 * «В девять» без «утра/вечера» — неоднозначно.
 *
 * Названо, а не решено молча: человек, сказавший «в девять», почти всегда знает,
 * утро это или вечер, а приложение — нет.
 */
export function ambiguous(phrase: string): boolean {
  const clean = phrase.toLowerCase();
  return /(?:^|\s)в\s+\d{1,2}(?:\s|$)/.test(clean) && !/утра|вечера|дня|ночи|час/.test(clean);
}
