/**
 * Первый звук ответа — до конца генерации (шаг 41).
 *
 * Дефект. Ответ ждался целиком: модель генерирует 800 токенов, приложение молчит
 * всё это время, и человек решает, что его не услышали. Это **главная**
 * задержка разговора — не распознавание и не сеть, а ожидание конца абзаца.
 *
 * Что можно сказать раньше. Не «первую половину ответа»: половина фразы — это
 * обрывок, и произносить его вслух хуже, чем подождать. Можно сказать то, что
 * **не зависит** от остального ответа:
 *
 *  1. **что я делаю** — «смотрю папку», если действие уже выбрано. Это правда
 *     с первой миллисекунды и не изменится;
 *  2. **сколько ждать** — «это займёт немного», если известно действие;
 *  3. **сам ответ** — только когда он **закончен**. Куски, слепленные в
 *     предложение, — это ответ; кусок сам по себе — нет.
 *
 * Поэтому правило режет не по размеру, а по **законченности**: фрагмент можно
 * произносить, только если он заканчивается границей предложения. Запятая и
 * тире — не граница: на «я нашёл три файла, но» голос обрывается, и это хуже
 * молчания.
 *
 * Аварийная мера: если длинного ответа ещё нет, а прошло больше секунды, честнее
 * сказать «ещё думаю», чем молчать. Молчание читается как поломка.
 */

/** Сколько можно молчать, прежде чем сказать, что работа идёт. */
export const STALL_MS = 1000;

/** Что сказать, пока ответа нет. Правда: работа идёт, ответа ещё нет. */
export const STALL_LINE = "ещё думаю — ответ будет через пару секунд";

/**
 * Законченная часть потока — та, которую можно произносить.
 *
 * Возвращает всё до последней границы предложения включительно. Остаток — не
 * мусор: он придёт в следующем куске и станет законченным.
 *
 * Почему не «первое предложение целиком и точка». В потоке куски приходят как
 * получится, и ждать первую точку значит ждать конца первого предложения — а это
 * уже может быть весь короткий ответ. Режем по **последней** границе: произносим
 * всё, что закончено, остаток держим.
 */
export function settled(text: string): string {
  const trimmed = text.replace(/\s+$/u, "");
  if (trimmed.length === 0) return "";
  let cut = -1;
  for (let index = trimmed.length - 1; index >= 0; index -= 1) {
    const char = trimmed[index];
    if (char === "." || char === "!" || char === "?" || char === "…") {
      cut = index;
      break;
    }
  }
  if (cut === -1) return "";
  return trimmed.slice(0, cut + 1).trim();
}

/**
 * Сколько текста ещё не произнесено.
 *
 * Нужен, чтобы не повторять сказанное: поток присылает накопительный текст или
 * куски, и правило одно — «произноси то, что правее уже сказанного».
 */
export function tail(text: string, alreadySaid: string): string {
  if (alreadySaid.length === 0) return text;
  return text.startsWith(alreadySaid) ? text.slice(alreadySaid.length) : text;
}

/** Что делать с текущим потоком. */
export type Say = { kind: "speak"; text: string } | { kind: "wait" } | { kind: "stall" };

/**
 * Решение по одному куску.
 *
 * `elapsed` — сколько ждём. Правило про молчание последнее: если говорить есть
 * что, говорим, а не жалуемся на ожидание.
 */
export function decide(stream: string, alreadySaid: string, elapsed: number): Say {
  const fresh = tail(stream, alreadySaid);
  const ready = settled(fresh);
  if (ready.length > 0) return { kind: "speak", text: ready };
  if (elapsed >= STALL_MS) return { kind: "stall" };
  return { kind: "wait" };
}

/**
 * Что сказать **до** ответа, если действие уже известно.
 *
 * Не «секунду, сейчас посмотрю» — это обещание времени, а мы его не знаем.
 * Называется действие: оно правда с первой миллисекунды, и человек слышит, что
 * его услышали.
 */
export function doingLine(what: string): string {
  const action = what.trim();
  if (action.length === 0) return STALL_LINE;
  return `смотрю: ${action}`;
}
