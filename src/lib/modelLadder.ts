/**
 * Лестница моделей: 0.5B / 1.5B / 3B / 7B (шаг 63).
 *
 * Дефект. «Какая модель лучше» — вопрос без ответа: всё зависит от машины.
 * Паспортные цифры с сайта модели меряны на чужом железе; на этом ноутбуке 7B
 * может не влезть в память вовсе, а 3B — обогнать её благодаря квантованию.
 *
 * Правило: лестница **от маленькой к большой**, и каждая ступень говорит
 * **что теряет**.
 *
 *  1. Ступени не «плохая/хорошая», а **разные компромиссы**: 0.5B быстрая и
 *     скучная, 7B умная и требует памяти. Человек выбирает не «лучшую», а ту,
 *     чьи потери его устраивают.
 *  2. Каждая ступень знает **свой минимум памяти**: обещать 7B на 8 ГБ значит
 *     получить своп и «приложение медленное».
 *  3. Ступень, которая не влезает, **не предлагается вовсе**: «попробуйте,
 *     может, пойдёт» — это не выбор, а лотерея, и проигрыш человек спишет на
 *     приложение.
 *  4. Замер **на этой машине** важнее паспорта. Если он есть — он главный;
 *     паспорт — только чтобы не предлагать заведомо негодное.
 */

/** Ступень лестницы. */
export interface Step {
  /** Как называем: «0.5B», «1.5B», «3B», «7B». */
  name: string;
  /** Размер файла модели в мегабайтах (Q4_K_M — см. шаг 64). */
  sizeMb: number;
  /** Сколько нужно памяти, чтобы работало без свопа: размер плюс запас. */
  needsMb: number;
  /** Что эта ступень умеет хорошо. */
  good: string;
  /** Что теряет — названо, а не замолчано. */
  loses: string;
}

/**
 * Запас сверх размера модели.
 *
 * Модель в памяти — это не только веса: нужен контекст, кеш и сам движок.
 * Полтора гигабайта — практический запас, проверенный на 4 ГБ машинах.
 */
export const OVERHEAD_MB = 1500;

/**
 * Сама лестница.
 *
 * Размеры — для Q4_K_M: 0.5B ≈ 400 МБ, 1.5B ≈ 1.1 ГБ, 3B ≈ 2.2 ГБ,
 * 7B ≈ 4.6 ГБ. Числа из паспорта, но «нужно памяти» и «что теряет» — из
 * практики: это и есть разница между таблицей и лестницей.
 */
export const STEPS: Step[] = [
  {
    name: "0.5B",
    sizeMb: 400,
    needsMb: 400 + OVERHEAD_MB,
    good: "понимает фразу и короткий ответ — мгновенно, на любом ноутбуке",
    loses: "не планирует: на длинном рассуждении путается и обрывает мысль",
  },
  {
    name: "1.5B",
    sizeMb: 1100,
    needsMb: 1100 + OVERHEAD_MB,
    good: "разговор и простой план; отвечает за доли секунды",
    loses: "код пишет с ошибками, которые замечает только при запуске",
  },
  {
    name: "3B",
    sizeMb: 2200,
    needsMb: 2200 + OVERHEAD_MB,
    good: "план в несколько шагов и простой код",
    loses: "на сложном коде и длинном контексте начинает забывать начало",
  },
  {
    name: "7B",
    sizeMb: 4600,
    needsMb: 4600 + OVERHEAD_MB,
    good: "сложный код и длинные планы; держит контекст",
    loses: "первый ответ ждётся секунды: на слабой машине это заметно",
  },
];

/**
 * Что из лестницы помещается на этой машине.
 *
 * Не «может ли загрузиться» (загрузиться может и не влезть), а «будет ли
 * работать без свопа». Своп — это когда модель есть, но пользоваться ей
 * нельзя, и человек не понимает, почему.
 */
export function fits(availableMb: number): Step[] {
  return STEPS.filter((step) => step.needsMb <= availableMb);
}

/**
 * Что предложить: самая большая из влезающих.
 *
 * Не «самая маленькая, чтобы наверняка»: если машина тянет 3B, предлагать 0.5B
 * значит наказывать человека за хорошее железо. И не «самая большая вообще»:
 * см. `fits`.
 */
export function pick(availableMb: number): Step | null {
  const fit = fits(availableMb);
  return fit.length === 0 ? null : (fit[fit.length - 1] ?? null);
}

/**
 * Что сказать, когда не влезает **ничего**.
 *
 * Не молчание и не «машина не подходит»: 0.5B требует 1.9 ГБ и влезает почти
 * везде, так что такой случай значит, что свободной памяти почти нет — и
 * причина названа, а не выдана за приговор железу.
 */
export function nothing(): string {
  return "свободной памяти почти нет — закройте тяжёлые программы, и самая маленькая модель поместится";
}

/**
 * Паспорт против замера на этой машине.
 *
 * Замер главнее: паспорт мерян на чужом железе. Но замер **не отменяет**
 * память: модель, которая не влезла, будет медленной независимо от того, что
 * показал замер на другой машине.
 *
 * `measured` — сколько токенов в секунду показала эта машина (шаг 65);
 * `passport` — что обещают для этой ступени вообще.
 */
export interface Speed {
  step: Step;
  /** Замер на этой машине, токенов в секунду. `null` — не мерили. */
  measured: number | null;
  /** Паспортное значение. */
  passport: number;
}

/** Какая ступень быстрее — по замеру, если он есть, иначе по паспорту. */
export function faster(left: Speed, right: Speed): Speed {
  const value = (speed: Speed) => speed.measured ?? speed.passport;
  return value(left) >= value(right) ? left : right;
}

/**
 * Честная подпись к скорости.
 *
 * Названо, **откуда** число: «по паспорту» и «на этой машине» — разные вещи, и
 * выдавать одно за другое нечестно.
 */
export function speedWord(speed: Speed): string {
  const value = speed.measured ?? speed.passport;
  const rounded = Math.round(value * 10) / 10;
  return speed.measured === null
    ? `${rounded} ток/с — по паспорту, на этой машине не мерили`
    : `${rounded} ток/с — на этой машине`;
}

/**
 * Что теряет выбранная ступень — то, что человек должен знать заранее.
 *
 * Без этого выбора нет: выбирают не «лучшую модель», а потери, которые
 * устраивают.
 */
export function warning(step: Step): string {
  return `«${step.name}»: ${step.loses}`;
}
