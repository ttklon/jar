/**
 * «Что сделать» рядом с каждой ошибкой.
 *
 * Зачем это правило, а не текст на каждом экране. Ошибка без совета — это
 * тупик: человек прочитал «не удалось запустить движок» и не знает, что
 * дальше. Совет, написанный руками на сорока трёх местах, разойдётся с ними
 * же через месяц: где-то будет «попробуйте ещё раз», где-то ничего.
 *
 * Три правила:
 *
 *  * **у каждой ошибки есть совет** — либо по причине (сеть, права, место,
 *    движение движка), либо общий: «подробности в „Истории“», но не пустота;
 *  * **совет про действие, а не про чувство.** «Попробуйте ещё раз» — не
 *    совет: он не меняет ничего и звучит как отговорка;
 *  * **совет не обещает того, чего приложение не сделает.** Если причина
 *    «файл занят», совет — закрыть программу, а не «подождите»: ждать можно
 *    бесконечно.
 *
 * Текст ошибки приходит из ядра и бывает на английском (curl, Windows). Правила
 * поэтому узнают причину по словам на обоих языках, как и `reasonOf` в журнале,
 * но здесь отдельно: журнал складывает прошлое, а это — про сейчас.
 */

/** Короткие причины, которые приложение узнаёт само. */
export type Cause = "network" | "rights" | "busy" | "space" | "hash" | "engine" | "model" | "unknown";

/** Что советует экран. Всегда непустое — иначе это не совет. */
export interface Hint {
  cause: Cause;
  /** Что сделать. Одно предложение, глаголом. */
  advice: string;
}

/**
 * Причина ошибки по её тексту.
 *
 * Порядок важен: «нет сети» раньше таймаута (таймаут в офлайне — следствие),
 * «повреждён» раньше «модели» (битый файл и неверная модель — разные советы).
 */
export function causeOf(error: string): Cause {
  const text = error.toLowerCase();
  if (/сет|network|dns|resolve|host|офлайн|offline/.test(text)) return "network";
  if (/доступ|access|denied|прав|permission|запрещ|administrator|администратор/.test(text)) {
    return "rights";
  }
  if (/занят|locked|busy|используется|in use/.test(text)) return "busy";
  if (/места|space|диск|disk full/.test(text)) return "space";
  if (/хеш|hash|поврежд|corrupt|sha-?256/.test(text)) return "hash";
  if (/движок|engine|llama|server/.test(text)) return "engine";
  if (/модел|model|gguf/.test(text)) return "model";
  return "unknown";
}

/**
 * Совет по тексту ошибки. Всегда непустой: «действия нет» — это тоже ответ,
 * но он называется словами, чтобы человек не искал кнопку, которой нет.
 */
export function hintFor(error: string): Hint {
  const cause = causeOf(error);
  switch (cause) {
    case "network":
      return {
        cause,
        advice: "Всё остальное работает без сети: проверьте соединение и повторите.",
      };
    case "rights":
      return {
        cause,
        advice: "Запустите приложение от администратора или выберите папку, куда можно писать.",
      };
    case "busy":
      return {
        cause,
        advice: "Закройте программу, которая держит файл, и повторите.",
      };
    case "space":
      return {
        cause,
        advice: "Освободите место: «Модели» → «Удалить всё скачанное».",
      };
    case "hash":
      return {
        cause,
        advice: "Скачайте заново — хеш проверится, битый файл не останется.",
      };
    case "engine":
      return {
        cause,
        advice: "Настройки → «Проверка себя» → «Переустановить движок».",
      };
    case "model":
      return {
        cause,
        advice: "Откройте «Модели»: там видно, какой файл подходит и что скачать.",
      };
    default:
      // Неизвестная ошибка: совет не выдуман, но путь к разбору назван — это
      // не «попробуйте ещё раз», а конкретное место, где есть подробности.
      return {
        cause,
        advice: "Подробности — в «Истории»: там весь журнал построчно.",
      };
  }
}
