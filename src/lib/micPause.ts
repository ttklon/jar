/**
 * Пауза микрофона одной кнопкой — с возвратом (шаг 53).
 *
 * Дефект. Выключить микрофон насовсем слишком легко, а вернуть — трудно, и это
 * не мелочь. Человек закашлялся, кто-то вошёл в комнату, зазвонил телефон — он
 * жмёт «выключить». Дальше две беды:
 *
 *  * **выключил — и не заметил** (кнопка изменилась, а он смотрит в текст);
 *    говорит минуту в пустоту и решает, что приложение сломалось;
 *  * **выключил «на минуту» — и оставил на день**, потому что включить заново
 *    страшно: непонятно, слушают его уже или нет.
 *
 * Правило: пауза — это **состояние с возвратом**, а не выключение.
 *
 *  1. Пауза ничего не забывает: то, что не договорено, не пропадает, и после
 *     «продолжить» человек продолжает, а не начинает сначала.
 *  2. Пауза **сама напоминает о себе**: раз в `REMIND_MS` тихо говорит, что
 *     микрофон на паузе, — не молчание в пустоту и не модальное окно.
 *  3. Пауза **кончается сама** через `RETURN_MS`, если её не продлили: минута
 *     тишины не должна превращаться в день без микрофона.
 *  4. Возврат — **одной кнопкой, той же самой**, и сказано, что случилось
 *     («снова слушаю»), а не просто исчезла иконка.
 *
 * Почему пауза сама кончается. «Я сам решу, когда включить» звучит уважительно,
 * но на практике человек забывает. Молчащий микрофон — это не выбор, а
 * забытое действие, и напоминание здесь лучше свободы.
 */

/** Сколько держится пауза, если её не продлили. */
export const RETURN_MS = 60_000;

/** Как часто напоминать, что микрофон на паузе. */
export const REMIND_MS = 20_000;

/** Состояние паузы. */
export interface Pause {
  /** Микрофон на паузе. */
  paused: boolean;
  /** Сколько миллисекунд уже длится пауза. */
  forMs: number;
  /** Сколько осталось до автоматического возврата. */
  leftMs: number;
  /** Сколько раз напоминали. */
  reminded: number;
}

/** Начало паузы: ничего не потеряно, таймер пошёл. */
export const START: Pause = { paused: true, forMs: 0, leftMs: RETURN_MS, reminded: 0 };

/** Микрофон работает. */
export const RUNNING: Pause = { paused: false, forMs: 0, leftMs: 0, reminded: 0 };

/**
 * Что происходит, когда прошло `ms` миллисекунд.
 *
 * Возвращает новое состояние и **что сказать**: напоминание или «снова
 * слушаю». Молчаливый возврат плох так же, как молчаливая пауза: человек уже
 * привык, что его не слышат, и говорит громче и медленнее, чем нужно.
 */
export function tick(pause: Pause, ms: number): { next: Pause; say: string | null } {
  if (!pause.paused) return { next: pause, say: null };
  const forMs = pause.forMs + ms;
  if (forMs >= RETURN_MS) {
    // Пауза кончилась сама. Это возврат, а не продление.
    return { next: RUNNING, say: "снова слушаю" };
  }
  const leftMs = RETURN_MS - forMs;
  const due = Math.floor(forMs / REMIND_MS);
  if (due > pause.reminded) {
    // Напоминание с остатком, а не просто «на паузе»: человеку нужно знать,
    // сколько ещё, иначе он не решит, продлевать или нет.
    const seconds = Math.ceil(leftMs / 1000);
    return {
      next: { paused: true, forMs, leftMs, reminded: due },
      say: `микрофон на паузе, верну через ${seconds} с`,
    };
  }
  return { next: { paused: true, forMs, leftMs, reminded: pause.reminded }, say: null };
}

/**
 * Продлить паузу — по нажатию, пока она идёт.
 *
 * Продление — не бесконечное: каждое нажатие даёт ещё `RETURN_MS`, но не
 * больше, и это сказано человеку. Иначе «ещё минуту» нажимается машинально и
 * микрофон не возвращается никогда.
 */
export function extend(pause: Pause): Pause {
  return pause.paused ? { ...pause, forMs: 0, leftMs: RETURN_MS, reminded: 0 } : START;
}

/**
 * Нажатие на кнопку микрофона — что оно делает **сейчас**.
 *
 * Одна кнопка на паузу и возврат: две кнопки заставляют выбирать и промахиваться.
 * Пока слушаю — пауза; на паузе — вернуть сразу, без ожидания таймера.
 */
export function onPress(pause: Pause): Pause {
  return pause.paused ? RUNNING : START;
}

/**
 * Что человеку сказать сейчас — словами, а не иконкой.
 *
 * Пауза называется **паузой**, а не «выключено»: «выключено» звучит как «всё,
 * больше не включится», и человек идёт в настройки вместо кнопки.
 */
export function word(pause: Pause): string {
  if (!pause.paused) return "слушаю";
  const seconds = Math.ceil(pause.leftMs / 1000);
  return `на паузе, верну через ${seconds} с — нажмите, чтобы вернуть`;
}

/**
 * Что не потеряно, пока пауза идёт.
 *
 * Это второй ответ, и он важнее первого: человек боится потерять недоговорённую
 * фразу сильнее, чем забыть включить микрофон. Сказано прямо, что она на месте.
 */
export function kept(pause: Pause): string | null {
  return pause.paused ? "недоговорённое сохранено — продолжите с того же места" : null;
}
