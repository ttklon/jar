/**
 * Шаг 458: завершение работы системы — корректно сохранить незавершённое.
 *
 * Windows выключается и **даёт приложению несколько секунд** (`WM_QUERYENDSESSION`
 * → `WM_ENDSESSION`). Если в эти секунды ничего не сделать, происходит самое
 * обидное: человек нажал «завершить работу», а на утро дело, которое шло, не
 * продолжилось — потому что номер шага не сохранился.
 *
 * Три правила, и каждое проверяется:
 *
 *  * **сохранить до согласия**, а не после: ответ «можно выключать» надо дать
 *    быстро, и лучше успеть записать;
 *  * **сохранять только то, что нужно для продолжения** — номер шага и фразу, а
 *    не весь отчёт: у нас секунды, а не минуты;
 *  * **не мешать выключению**: если запись не удалась, всё равно согласиться.
 *    Блокировать выключение компьютера из-за нашего журнала — хамство.
 */

/** Что надо сохранить. */
export interface Need {
  /** Дело, если шло. */
  readonly deed?: string;
  /** Номер шага. */
  readonly step: number;
  /** Фраза — чтобы человек не набирал заново. */
  readonly said: string;
  /** Что в поле ввода, но не отправлено. */
  readonly draft: string;
}

/** Что успели. */
export interface Saved {
  /** Можно ли выключать. */
  readonly allow: boolean;
  /** Что именно сохранено. */
  readonly saved: string[];
  readonly said: string;
}

/**
 * Успеть сохранить.
 *
 * `ok` — удалась ли запись. Ответ «можно выключать» — в любом случае.
 */
export function save(need: Need, ok: boolean): Saved {
  const items: string[] = [];
  if (need.deed !== undefined) items.push(`дело «${need.deed}» на шаге ${need.step}`);
  if (need.said.trim() !== "") items.push("фраза");
  if (need.draft.trim() !== "" && need.draft !== need.said) items.push("незаконченная фраза в поле");

  if (!ok) {
    return {
      allow: true,
      saved: [],
      said: "сохранить не успели, но выключению не мешаю: работа компьютера важнее нашего журнала. Продолжить дело можно будет вручную",
    };
  }

  return {
    allow: true,
    saved: items,
    said: items.length === 0 ? "сохранять нечего: дел и фраз не было" : `сохранено: ${items.join(", ")}. После включения можно продолжить`,
  };
}

/**
 * Что после включения компьютера.
 *
 * Не «продолжаю молча»: спрашиваем (шаг 457 — то же правило).
 */
export function afterRestart(saved: Saved): string {
  if (saved.saved.length === 0) return "";
  return `после включения: ${saved.saved.join(", ")} на месте. Продолжить — с того же шага, по вашему ответу`;
}

/**
 * Что сохраняется обязательно.
 *
 * Список — минимум для продолжения, и он намеренно короткий: у нас секунды.
 */
export function mustSave(): string[] {
  return ["номер шага и имя дела", "фраза человека", "незаконченная фраза в поле ввода"];
}

/**
 * Что не делаем при выключении.
 *
 * Три запрета — про секунды и про хамство.
 */
export function notDo(): string[] {
  return [
    "не блокируем выключение, даже если запись не удалась",
    "не сохраняем отчёты и журнал целиком: у нас секунды, а нужно только «с чего продолжить»",
    "не продолжаем дело молча после включения: спрашиваем",
  ];
}
