/**
 * Отчёт «почему выбрана эта модель» на экране (шаг 79).
 *
 * Дефект. Приложение выбрало модель — и молчит о том, почему. Дальше три беды:
 *
 *  * **человек не доверяет решению**, потому что не понимает его: «почему 1.5B,
 *    а не 7B? у меня же 32 гига»;
 *  * **он не может его оспорить**: если причина не названа, спорить не с чем, и
 *    остаётся только ругаться в отзывах;
 *  * **когда машина изменится** (поставил память, закрыл браузер), решение
 *    останется прежним без объяснения, и это будет выглядеть ошибкой.
 *
 * Правило: **каждое решение объяснимо теми фактами, на которых оно принято**.
 *
 *  1. Причина — **факт о его машине**, а не «мы так решили»: «16 ГБ памяти,
 *     помещается 7B» объясняет, а «оптимально для вас» — нет.
 *  2. Причина **проверяема**: человек может сам посмотреть память и сравнить с
 *     требованием. Если проверить нельзя, это не объяснение.
 *  3. Отчёт называет **все сработавшие условия**, а не одно: модель выбрана по
 *     памяти **и** диску **и** совместимости, и скрыть два из трёх — значит
 *     дать неполное объяснение.
 *  4. Отчёт говорит, **что изменит решение**: «закройте браузер — поместится 7B».
 *     Без этого объяснение констатирует, а не помогает.
 *
 * Почему не «подробности в логах». Логи не читают; отчёт должен стоять рядом с
 * моделью, на том же экране, и быть коротким.
 */

/** Один факт, который повлиял на выбор. */
export interface Fact {
  /** Что проверили: «память», «диск», «совместимость». */
  what: string;
  /** Что нашли: «16 ГБ», «SSD», «AVX2 есть». */
  found: string;
  /** Что из этого следует для выбора. */
  means: string;
  /** Помогло ли это выбрать модель побольше (да/нет). */
  helped: boolean;
}

/** Отчёт целиком. */
export interface Report {
  /** Выбранная модель. */
  model: string;
  /** Факты по порядку важности: память решает больше, чем диск. */
  facts: Fact[];
}

/**
 * Отчёт по фактам.
 *
 * Порядок важен: память решает больше, чем диск, и отчёт начинается с неё.
 * Человек читает первые две строки — в них должно быть главное.
 */
export function report(model: string, facts: readonly Fact[]): Report {
  const order = ["память", "совместимость", "диск", "замер"];
  const sorted = [...facts].sort((left, right) => {
    const a = order.findIndex((word) => left.what.toLowerCase().includes(word));
    const b = order.findIndex((word) => right.what.toLowerCase().includes(word));
    return (a < 0 ? 99 : a) - (b < 0 ? 99 : b);
  });
  return { model, facts: sorted };
}

/**
 * Строки отчёта — то, что человек читает.
 *
 * Каждая строка — **факт и следствие**: «память 16 ГБ — помещается 7B». Не
 * «память: 16 ГБ» отдельно и «выбрана 7B» отдельно: связь — это и есть
 * объяснение.
 */
export function lines(got: Report): string[] {
  if (got.facts.length === 0) {
    return [`выбрана «${got.model}» — причин не записано, и это ошибка отчёта`];
  }
  return got.facts.map((fact) => `${fact.what}: ${fact.found} — ${fact.means}`);
}

/**
 * Что изменит решение.
 *
 * Названы только факты, которые **мешают** большей модели: «закройте браузер,
 * поместится 7B». Без этого объяснение констатирует, а не помогает.
 */
export function change(got: Report): string | null {
  const blockers = got.facts.filter((fact) => !fact.helped);
  if (blockers.length === 0) return null;
  return `решение изменится, если: ${blockers.map((fact) => fact.means).join("; ")}`;
}

/**
 * Короткая подпись — одна строка для карточки.
 *
 * Не отчёт целиком: на карточке нужна причина, а не таблица. Подробности — по
 * нажатию.
 */
export function short(got: Report): string {
  const main = got.facts[0];
  return main ? `«${got.model}»: ${main.means}` : `«${got.model}»: причина не записана`;
}

/**
 * Все ли факты названы.
 *
 * Скрыть два из трёх — значит дать неполное объяснение, и человек, найдя
 * пропущенное, перестанет верить остальному.
 */
export const REQUIRED = ["память", "совместимость"] as const;

export function complete(got: Report): boolean {
  return REQUIRED.every((what) => got.facts.some((fact) => fact.what.toLowerCase().includes(what)));
}

/**
 * Что сказать, если объяснить нечем.
 *
 * Честнее, чем выдумать причину: «причина не записана» — это ошибка, которую
 * видно, а «оптимально для вас» — ошибка, которую не видно.
 */
export function unexplained(): string {
  return "почему выбрана эта модель — не записано: это ошибка отчёта, а не решение без причины";
}
