/**
 * Шаг 495: повторять цикл — измерение → правка → доказательство. Процесс вместо героизма.
 *
 * Один подвиг даёт один результат. Цикл даёт результат **каждый раз**, и главное —
 * не зависит от того, кто сегодня в ударе.
 *
 * Цикл из трёх шагов, и каждый обязателен:
 *
 *  1. **измерение** — сначала цифра (шаг 491), иначе непонятно, что править;
 *  2. **правка** — одна, самая дешёвая из тех, что двигают цифру;
 *  3. **доказательство** — та же цифра **тем же способом**, плюс тест, который не
 *     даст вернуться назад.
 *
 * Два нарушения, которые ломают цикл чаще всего: **правка без измерения** (правим
 * то, что кажется) и **доказательство без той же линейки** (стало 200 «потому что
 * мерили по-другому»). Оба ловятся здесь.
 */

/** Шаг цикла. */
export type Phase = "измерение" | "правка" | "доказательство";

/** Проход цикла. */
export interface Pass {
  /** Номер прохода, с единицы. */
  readonly n: number;
  /** Что мерили — название замера. */
  readonly measured: string;
  /** Цифра до правки. */
  readonly before: number;
  /** Что правили. */
  readonly fixed: string;
  /** Цифра после правки. */
  readonly after: number;
  /** Та же линейка? */
  readonly sameRuler: boolean;
  /** Есть тест, который ловит возврат. */
  readonly guarded: boolean;
}

/**
 * Порядок обязателен.
 *
 * Проверка прохода: измерение → правка → доказательство. Правка без замера — правка
 * «по ощущению».
 */
export function ordered(pass: Pass): string[] {
  const problems: string[] = [];

  if (pass.measured.trim() === "") problems.push(`проход ${pass.n}: правка без измерения — правим то, что кажется`);
  if (pass.fixed.trim() === "") problems.push(`проход ${pass.n}: измерение без правки — цикл не двигается`);
  if (!pass.sameRuler) problems.push(`проход ${pass.n}: доказательство другой линейкой — это другая цифра, а не результат`);
  if (!pass.guarded) problems.push(`проход ${pass.n}: нет теста, который ловит возврат — правка вернётся`);

  return problems;
}

/**
 * Двинулся ли цикл.
 *
 * Три исхода: лучше, столько же (правка не та), хуже (правка не та, и это видно).
 * «Столько же» — тоже результат: значит причина не в том, что правили.
 */
export function moved(pass: Pass): { verdict: "лучше" | "столько же" | "хуже"; said: string } {
  if (pass.before === pass.after) return { verdict: "столько же", said: `проход ${pass.n}: ${pass.before} → ${pass.after}, столько же — причина не в том, что правили` };
  const better = pass.after < pass.before;
  return { verdict: better ? "лучше" : "хуже", said: `проход ${pass.n}: ${pass.before} → ${pass.after} (${better ? "лучше" : "хуже"}) — ${pass.fixed}` };
}

/**
 * Серия проходов.
 *
 * Цикл — это когда проходов **больше одного**, и каждый следующий начинается с
 * замера, а не с новой правки.
 */
export function series(passes: readonly Pass[]): { ok: boolean; said: string } {
  if (passes.length === 0) return { ok: false, said: "ни одного прохода: цикла нет, есть намерение" };

  const problems = passes.flatMap(ordered);
  const results = passes.map(moved);
  const best = results.filter((result) => result.verdict === "лучше").length;

  if (problems.length > 0) return { ok: false, said: problems.join("; ") };
  return {
    ok: true,
    said: `проходов ${passes.length}, из них с улучшением ${best}: ${passes.map((pass) => `#${pass.n} ${pass.before}→${pass.after}`).join(", ")}`,
  };
}

/**
 * Чего цикл не делает.
 *
 * Три запрета; главный — не героизм.
 */
export function notDo(): string[] {
  return [
    "не заменяется подвигом: один подвиг — один результат, цикл — каждый раз",
    "не правит без замера: правка «по ощущению» — это лотерея",
    "не доказывает другой линейкой: тогда результат — это смена измерителя",
  ];
}

/**
 * Что проверяет тест.
 *
 * Три проверки — по числу шагов цикла.
 */
export function checks(): string[] {
  return [
    "порядок: измерение, правка, доказательство",
    "доказательство той же линейкой и с тестом против возврата",
    "«столько же» — тоже результат, и он назван",
  ];
}
