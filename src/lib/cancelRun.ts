/**
 * Отмена обрывает текущий шаг и не запускает следующий (шаг 104).
 *
 * Дефект. «Отменить» в приложении, которое делает несколько шагов подряд, значит
 * три разные вещи, и путают их молча:
 *
 *  * **отмена после конца**: шаг уже выполнился, а кнопка изображает отмену —
 *    человек думает, что вернул, и не возвращает;
 *  * **отмена в середине**: выполнено три шага из семи, и непонятно, отменилось
 *    всё или только четвёртый;
 *  * **отмена ждёт текущий шаг**: следующий уже запущен, потому что проверка
 *    отмены была перед запуском, а не между шагами.
 *
 * Правило: **отмена — это состояние, которое читают перед каждым шагом**.
 *
 *  1. **Между шагами, а не внутри**: шаг атомарен; обрывать его посередине значит
 *     оставить полдела, о которых человек не просил.
 *  2. **Сделанное не отменяется молча**: то, что уже выполнено, остаётся, и это
 *     **названо**: «сделано 3 из 7, остальное не запускаю».
 *  3. **Отменять нечего — сказано честно**: «уже готово, отменять нечего», а не
 *     кнопка, которая делает вид, что вернула.
 *  4. **Дальше не запускается ничего**, даже безопасного: человек сказал
 *     «хватит», и «но вот это же безобидное» — это не его «хватит».
 *  5. **Отмена не отменяется**: повторное нажатие не возвращает выполнение — иначе
 *     отмена зависит от того, кто сколько раз нажал.
 *
 * Почему не «откатить всё». Откат — другая работа с другим риском (шаг 101:
 * необратимость названа отдельно), и выдавать отмену за откат — обман, из-за
 * которого человек не сделает резервную копию.
 */

/** Ход выполнения: сколько сделано и хватит ли. */
export interface Run {
  /** Всего шагов в принятом плане. */
  total: number;
  /** Сколько уже завершено — именно завершено, а не начато. */
  done: number;
  /** Нажата ли отмена. */
  stopped: boolean;
}

/** Свежий прогон. */
export function start(total: number): Run {
  return { total, done: 0, stopped: false };
}

/**
 * Нажать «отменить».
 *
 * Отмена — только флаг: текущий шаг доводится до конца, и следующий уже не
 * начнётся. Прерывать посреди шага — оставить полдела.
 */
export function stop(run: Run): Run {
  return { ...run, stopped: true };
}

/**
 * Можно ли начинать шаг.
 *
 * Читается **перед каждым** шагом. Проверка «один раз в начале» — ровно та
 * ошибка, из-за которой отмена не работает.
 */
export function mayStart(run: Run): boolean {
  return !run.stopped && run.done < run.total;
}

/**
 * Завершить шаг.
 *
 * Сделанное остаётся: отмена не отматывает назад, и притворяться иначе значит
 * врать про состояние файлов.
 */
export function finished(run: Run): Run {
  return { ...run, done: Math.min(run.total, run.done + 1) };
}

/** Что сказать человеку после нажатия «отменить». */
export function say(run: Run): string {
  const left = run.total - run.done;
  if (!run.stopped) {
    return run.done === run.total && run.total > 0 ? "готово — отменять нечего" : `сделано ${run.done} из ${run.total}`;
  }
  if (run.done === run.total && run.total > 0) {
    return "уже готово, отменять нечего — сделанное осталось";
  }
  if (run.done === 0) {
    return "отменено — не начинал";
  }
  // Сделанное не отменяется молча: человек должен знать, что именно осталось.
  return `остановился: сделано ${run.done} из ${run.total}, остальные ${left} не запускаю — сделанное осталось`;
}

/**
 * Дальше не запускается ничего.
 *
 * Отдельная функция, потому что соблазн «безопасные шаги доделать» велик, а
 * «хватит» относится ко всему плану, а не к опасной части.
 */
export function blocked(run: Run): { any: boolean; why: string } {
  if (!run.stopped) return { any: false, why: "" };
  return { any: true, why: "вы отменили — дальше ничего не запускаю" };
}
