/**
 * Шаг 311: установщик не требует отключения антивируса — иначе подозрительно.
 *
 * «Добавьте в исключения» — это не решение, это перекладывание проблемы на
 * человека. Он выключает защиту, ставит что-то, потом забывает включить, и
 * виноватым в его глазах становится наша программа, которая «просила так сделать».
 *
 * Почему антивирус ругается на самом деле — три разные причины, и лечатся они
 * по-разному:
 *
 *  1. **нет подписи или счётчик репутации маленький** — лечится подписью и
 *     временем, а не просьбой;
 *  2. **эвристика на что-то в установщике** (самораспаковка, скрипт внутри,
 *     запрос в реестр) — лечится изменением установщика;
 *  3. **ложное срабатывание конкретного вендора** — лечится обращением к
 *     вендору, а не к человеку.
 *
 * Правило: **ни одна из трёх причин не решается отключением антивируса**, и наша
 * программа никогда об этом не просит — ни в инструкции, ни в окне ошибки.
 */

/** Что говорит антивирус. */
export interface Alarm {
  /** Что именно произошло: подпись, эвристика или ложное. */
  readonly kind: "unsigned" | "heuristic" | "falsePositive";
  /** Сообщение антивируса, если оно есть. */
  readonly message?: string;
}

/** Что отвечаем человеку. */
export interface Reply {
  /** Что сказать человеку — без «отключите защиту». */
  readonly said: string;
  /** Что делаем мы. */
  readonly weDo: string;
}

/** Ответ на срабатывание. */
export function reply(alarm: Alarm): Reply {
  if (alarm.kind === "unsigned") {
    return {
      said: "антивирус не знает этот файл: подпись наша есть, но репутация у новой версии ещё не набралась — это проходит за несколько дней",
      weDo: "подписываем каждую сборку и следим за счётчиком репутации; человеку делать ничего не нужно",
    };
  }
  if (alarm.kind === "heuristic") {
    return {
      said: "антивирус нашёл в установщике что-то подозрительное по поведению — это наша проблема, а не ваша",
      weDo: "разбираем, что именно в установщике вызвало эвристику, и меняем установщик",
    };
  }
  return {
    said: "похоже на ложное срабатывание: так бывает у новых сборок",
    weDo: "пишем вендору с хешем файла — исправление приходит с их обновлением баз, обычно за дни",
  };
}

/**
 * Любой совет, который просит отключить защиту.
 *
 * Проверяется по тексту, потому что такие советы проникают в инструкцию тихо:
 * «если не ставится — временно отключите антивирус».
 */
export function asksToDisable(text: string): boolean {
  const forbidden = [
    /отключ\S*\s+(антивирус|защит\S*)/i,
    /добав\S*(?:\s+\S+){0,3}\s+в\s+(?:список\s+)?исключени\S*/i,
    /выключ\S*\s+(антивирус|защит\S*)/i,
    /приостанов\S*\s+защит/i,
  ];
  return forbidden.some((pattern) => pattern.test(text));
}

/** Проверить инструкцию и окна: ни слова про отключение защиты. */
export function audit(texts: readonly string[]): string[] {
  const problems: string[] = [];
  for (const text of texts) {
    if (asksToDisable(text)) problems.push(`найдено «отключите защиту»: ${text.slice(0, 60)}…`);
  }
  return problems;
}

/**
 * Что человеку делать, если очень хочется поставить сейчас.
 *
 * Даём действие, которое **не** выключает защиту: проверить подпись самому.
 */
export function safeAlternative(): string {
  return "проверьте подпись файла: правый клик → «Свойства» → «Цифровые подписи» — там должно быть указано наше имя";
}

/**
 * Что говорим, когда антивирус удалил установщик прямо во время установки.
 *
 * Не «отключите и повторите»: пусть скачает заново — это дешевле, чем
 * выключенная защита на неделю.
 */
export function ifDeleted(): string {
  return "скачайте установщик заново: антивирус его удалил, и это не то же самое, что блокировка — повторная загрузка обычно проходит";
}
