import { describe, expect, it } from "vitest";
import { check, clock, own, over, report, slow, timed } from "./latencyProof";

/**
 * Шаг 130: бюджет задержки проверяется с подставным медленным ядром.
 *
 * Регрессия скорости проходила молча: тест ждал, ядро отвечало мгновенно, и «стало
 * медленнее» замечали только по жалобе.
 */
describe("время подставное — тест не зависит от скорости машины", () => {
  it("медленное ядро изображается, а не ждётся", async () => {
    const clk = clock();
    const kernel = slow(clk, 2400);
    const took = await timed(clk, kernel.run);
    // Тот же результат, что и от реального ожидания, но без 2,4 секунды в прогоне.
    expect(took).toBe(2400);
    expect(clk.now).toBe(2400);
  });

  it("часы идут только по шагам ядра", () => {
    const clk = clock();
    expect(clk.now).toBe(0);
    clk.now += 400;
    expect(clk.now).toBe(400);
  });
});

describe("бюджет — число, и превышение называется превышением", () => {
  it("в бюджете — без нарушения", () => {
    expect(over(400, 1500).over).toBe(false);
    expect(over(400, 1500).said).toBe("400 мс из 1500 — в бюджете");
  });

  it("за бюджетом — на сколько именно", () => {
    const got = over(2400, 1500);
    expect(got.over).toBe(true);
    expect(got.by).toBe(900);
    expect(got.said).toContain("превышение на 900 мс");
  });

  it("медленный сценарий называют по имени, а не номером", () => {
    const got = check({ name: "первый звук", budget: 1500, ms: 2400 });
    expect(got.ok).toBe(false);
    expect(got.said).toBe("первый звук: 2400 мс при бюджете 1500 — превышение на 900 мс");
  });
});

describe("быстрое ядро не оправдывает медленный код", () => {
  it("свои расходы отделены от расходов ядра", () => {
    // Ядро 100 мс, всего 2400: 2300 — это код, и регрессия сидит здесь.
    const got = own(2400, 100);
    expect(got.ms).toBe(2300);
    expect(got.said).toContain("этого ядро не объясняет");
  });

  it("если всё время у ядра — так и сказано", () => {
    expect(own(2400, 2400).said).toBe("своих расходов нет: всё время — у ядра");
  });
});

describe("отчёт по сценариям сравнивает числа", () => {
  it("все в бюджете", () => {
    expect(
      report([
        { name: "первый звук", budget: 1500, ms: 400 },
        { name: "план", budget: 4000, ms: 1200 },
      ]),
    ).toBe("все 2 сценариев в бюджете");
  });

  it("за бюджетом — кто именно, по именам", () => {
    expect(
      report([
        { name: "первый звук", budget: 1500, ms: 2400 },
        { name: "план", budget: 4000, ms: 1200 },
      ]),
    ).toBe("за бюджетом 1 из 2: первый звук");
  });
});
