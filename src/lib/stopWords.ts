/**
 * «Стоп» и «подожди» — слова разные, и поведения разные (шаг 45).
 *
 * Дефект. Слова-команды не хранились вовсе: любое услышанное слово шло обычным
 * путём — в модель как просьба. Человек говорил «стоп», и приложение… думало над
 * словом «стоп».
 *
 * Разница, которую надо чувствовать, а не записывать:
 *
 *  * **стоп** — отказ. Ничего не делать, ничего не спрашивать, не продолжать.
 *    Это не «пауза в разговоре», это «замолчи и не начинай»;
 *  * **перебивание** («подожди», «погоди», «хватит») — разговор. Приложение
 *    замолкает **и слушает дальше**, потому что человек собирается сказать что-то
 *    ещё. Ответ на «подожди» — не тишина, а внимание.
 *
 * Почему это отдельное правило, а не строка `if`. Три вещи легко перепутать:
 *
 *  1. **слово посреди фразы** — не команда. «Стоп-кран в поезде» — это про
 *     поезд, а не «остановись». Команда — это когда **всё** сказанное и есть
 *     команда (с точностью до вежливости: «стоп, пожалуйста»);
 *  2. **стоп vs перебивание** — разное поведение, и оно должно быть названо в
 *     одном месте, иначе на одном экране «хватит» останавливает всё, а на
 *     другом — только речь;
 *  3. **незнакомое слово — не команда**. Считать «остановись» командой, которой
 *     нет в списке, значит угадывать. Угадывание в этой области стоит дорого:
 *     человек просит остановиться, а приложение делает вид, что не поняло.
 *
 * Поэтому список закрыт, а совпадение — по **всей** фразе: `стоп` — команда,
 * `стоп-кран` — тоже (одно слово с дефисом), `стоп, где мой файл` — просьба.
 */

/** Что человек хочет, когда сказал слово-команду. */
export type Intent = "stop" | "interrupt";

/** Что делать приложению. Поведение — часть правила, а не места вызова. */
export interface Behaviour {
  /** Прекратить всё: не слушать, не думать, не спрашивать. */
  halt: boolean;
  /** Замолчать и слушать дальше: человек собирается сказать ещё. */
  listenOn: boolean;
  /** Спрашивать ли подтверждение. У «стоп» — нет: он и есть ответ. */
  confirm: boolean;
}

export const BEHAVIOUR: Record<Intent, Behaviour> = {
  // «Стоп» — отказ целиком. Подтверждение было бы издевательством: человек уже
  // сказал «нет».
  stop: { halt: true, listenOn: false, confirm: false },
  // «Подожди» — приложение замолкает и слушает, потому что дальше будет фраза.
  // Не «пауза»: пауза — это тишина, а здесь — внимание.
  interrupt: { halt: false, listenOn: true, confirm: false },
};

/**
 * Слова. Закрытый список: незнакомое слово считается речью, а не командой.
 *
 * Список назван по тому, как говорят люди, а не по тому, как удобно коду:
 * «стоп», «хватит», «подожди», «погоди», «тихо», «помолчи».
 */
const STOP = new Set(["стоп", "stop", "хватит", "достаточно", "отмена", "отмени"]);
const INTERRUPT = new Set(["подожди", "погоди", "минуту", "секунду", "помолчи", "тихо", "тише"]);

/** Вежливость, которая не меняет смысла: «стоп, пожалуйста» — всё ещё стоп. */
const POLITE = new Set(["пожалуйста", "плиз", "пожалуиста"]);

/** Что осталось от фразы: слова без знаков, в нижнем регистре. */
function words(text: string): string[] {
  return text
    .toLocaleLowerCase("ru")
    .replace(/ё/g, "е")
    .replace(/[^\p{L}\p{N}\s-]+/gu, " ")
    .split(/\s+/u)
    .map((word) => word.trim())
    .filter((word) => word.length > 0);
}

/**
 * Что человек сказал: команду или обычную фразу.
 *
 * `null` — это не команда. Тогда фраза идёт обычным путём, и приложение её не
 * угадывает.
 *
 * Совпадение — по всей фразе: одно слово команды, остальные — вежливость.
 * «Стоп-кран» распознаётся как «стоп» только если это **всё**, что сказали: это
 * слово целиком и есть команда. А «стоп, где мой файл» — просьба, и её нельзя
 * глотать.
 */
export function command(text: string): Intent | null {
  const list = words(text);
  if (list.length === 0) return null;

  // Дефис внутри слова: «стоп-кран» — одно слово. Если всё сказанное — одно
  // слово, и оно начинается с команды, это команда: «стоп-кран» человек говорит
  // редко, а «стоп» с автозаменой дефиса — часто.
  const meaningful = list.filter((word) => !POLITE.has(word));
  if (meaningful.length === 0) return null;

  const first = meaningful[0] ?? "";
  const base = first.split("-")[0] ?? first;
  const known = STOP.has(base) ? "stop" : INTERRUPT.has(base) ? "interrupt" : null;
  if (known === null) return null;

  // Команда — только когда кроме неё не сказано ничего другого. Всё остальное —
  // речь, и её нельзя съесть.
  if (meaningful.length > 1) return null;
  return known;
}

/** Что делать по услышанному. `null` — обычная фраза. */
export function behaviourFor(text: string): Behaviour | null {
  const intent = command(text);
  return intent === null ? null : BEHAVIOUR[intent];
}

/**
 * Как это назвать человеку — в подсказке и в журнале.
 *
 * Сказано, что произойдёт: у «стоп» и «подожди» последствия разные, и человек
 * должен знать их до того, как скажет.
 */
export function sayFor(intent: Intent): string {
  switch (intent) {
    case "stop":
      return "«стоп» — прекращает всё и ничего не спрашивает";
    case "interrupt":
      return "«подожди» — приложение замолкает и слушает дальше";
  }
}
