/**
 * Замер «первый токен / токены в секунду» на этой машине (шаг 65).
 *
 * Дефект. Паспортные цифры меряны на чужом железе, и по ним нельзя ответить на
 * единственный вопрос, который у человека есть: **сколько ждать**. Причём ждать
 * приходится дважды, и это разные ожидания:
 *
 *  * **первый токен** — пауза перед ответом. Именно она решает, «быстрое ли
 *    приложение»: пять секунд тишины человек считает зависанием, даже если
 *    потом ответ идёт бойко;
 *  * **токены в секунду** — скорость самого ответа. Если медленно, человек
 *    успевает уйти и вернуться.
 *
 * Правило: мерим **оба** и называем **оба**, с честной оговоркой о том, как
 * мерили.
 *
 *  1. «Пуск» и «скорость» — разные числа. Одно без другого обманывает:
 *     быстрый пуск с вялым потоком и долгий пуск с бойким потоком — разные
 *     впечатления.
 *  2. Замер — **на этой машине**, а не с сайта. Паспорт годится только чтобы
 *     не мерить заведомо негодное (шаг 63).
 *  3. Замер **не обещает**, что так будет всегда: первый запуск читает модель с
 *     диска и греет кеш, поэтому **первый прогон выбрасывается**. Иначе человек
 *     получает завышенную цифру и разочарование при следующем запуске.
 *  4. Честные единицы: токен — не слово. Русское слово — это два-три токена, и
 *     «20 ток/с» звучит быстрее, чем читается. Переводим в **слов в секунду**.
 */

/**
 * Сколько токенов в русском слове.
 *
 * Не единица, а **опытная оценка**: русские слова длиннее английских и в
 * токенизаторе разваливаются на части. Два с половиной — середина диапазона,
 * и это сказано, чтобы цифру можно было оспорить.
 */
export const TOKENS_PER_WORD = 2.5;

/** Замер на этой машине. */
export interface Measured {
  /** Сколько миллисекунд до первого токена. */
  firstTokenMs: number;
  /** Токенов в секунду после первого. */
  perSecond: number;
  /** Сколько токенов всего сгенерировано — по нему понятно, можно ли верить. */
  tokens: number;
  /** Когда мерили: цифра стареет вместе с машиной. */
  at: number;
}

/**
 * Меньше этого замер не считается за замер.
 *
 * Десять токенов — слишком мало: один медленный токен сдвинет всю цифру, и
 * человек получит случайность вместо скорости.
 */
export const MIN_TOKENS = 10;

/**
 * Замер по событиям движка.
 *
 * Считаем **по событиям**, а не по таймеру вокруг вызова: таймер вокруг
 * включает загрузку модели и сетевые задержки, и цифра перестаёт быть про
 * скорость счёта.
 *
 * `first` — когда пришёл первый токен; `last` — когда последний; `count` —
 * сколько пришло.
 */
export function measure(
  first: number,
  last: number,
  count: number,
  now: number,
): Measured | null {
  if (count < MIN_TOKENS) return null;
  const span = last - first;
  // Один токен — это ещё не поток: скорость считаем по тем, что после первого.
  const rest = count - 1;
  if (span <= 0 || rest <= 0) return null;
  return {
    firstTokenMs: Math.max(0, Math.round(first)),
    perSecond: Math.round((rest / span) * 1000 * 10) / 10,
    tokens: count,
    at: now,
  };
}

/**
 * Примерно сколько ждать ответ из `words` слов.
 *
 * Две части: пауза до первого токена и время на остальные. Именно это человек
 * и хочет знать — «сколько ждать», а не «токенов в секунду».
 */
export function waitMs(speed: Measured, words: number): number {
  if (words <= 0) return speed.firstTokenMs;
  const tokens = words * TOKENS_PER_WORD;
  const rest = Math.max(0, tokens - 1);
  return Math.round(speed.firstTokenMs + (rest / speed.perSecond) * 1000);
}

/**
 * Ожидание словами.
 *
 * «Меньше секунды», «около двух секунд», «пять секунд» — человек считает
 * секундами, а не миллисекундами. И если дольше пяти, сказано, что это долго:
 * притворяться, что всё хорошо, значит потерять доверие.
 */
export function waitWord(ms: number): string {
  const seconds = ms / 1000;
  if (seconds < 1) return "меньше секунды";
  if (seconds < 5) return `около ${Math.round(seconds)} секунд`;
  return `долго — около ${Math.round(seconds)} секунд, лучше модель поменьше`;
}

/**
 * Скорость словами — в словах в секунду, а не токенах.
 *
 * «20 ток/с» звучит быстрее, чем читается: русское слово — это два-три токена.
 * Честнее перевести, и сказать, что перевели.
 */
export function speedWord(speed: Measured): string {
  const words = Math.round((speed.perSecond / TOKENS_PER_WORD) * 10) / 10;
  return `${words} слов в секунду (${speed.perSecond} токенов — русское слово это ${TOKENS_PER_WORD} токена)`;
}

/**
 * Замер, сделанный **первым прогоном**, выбрасывается.
 *
 * Первый запуск читает модель с диска и греет кеш: цифра занижена, и человек
 * получит разочарование от цифры, а не от работы. `warm` — был ли уже прогрев.
 */
export function usable(speed: Measured | null, warm: boolean): Measured | null {
  if (!warm) return null;
  return speed;
}

/**
 * Не устарел ли замер.
 *
 * Машина меняется: закрыли браузер, включили режим экономии. Замер старше
 * недели — не про сегодняшний день.
 */
export const STALE_MS = 7 * 24 * 60 * 60 * 1000;

export function stale(speed: Measured, now: number): boolean {
  return now - speed.at > STALE_MS;
}

/**
 * Что сказать человеку о замере — с оговоркой.
 *
 * Названо, **на какой машине** и **когда**: без этого цифра выглядит обещанием.
 */
export function say(speed: Measured, now: number): string {
  const age = Math.round((now - speed.at) / (60 * 60 * 1000));
  const when = age < 1 ? "только что" : age < 48 ? `${age} ч назад` : "давно";
  return `на этой машине (${when}): первый токен ${Math.round(speed.firstTokenMs / 100) / 10} с, ${speedWord(speed)}`;
}
