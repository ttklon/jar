/**
 * Шаг 419: смена человека посреди дела не меняет права исполнения.
 *
 * Это самая тонкая ловушка раздела. Дело идёт, шаг 3 из 7, и человек
 * переключается. Что должно случиться с правами?
 *
 * Соблазн понятный: «права теперь нового человека» — то есть шаг, который был
 * разрешён Анне, может оказаться запрещён Сыну, и дело остановится на середине.
 * Или наоборот: Сыну не разрешено удалять — но Анна уже разрешила, и дело
 * продолжается **под её согласием**, хотя на экране уже «Сын».
 *
 * Второе — настоящая ошибка безопасности (шаг 403: чужое согласие не считается
 * моим). Поэтому правило:
 *
 *  * **права фиксируются на входе в дело** и не меняются до его конца;
 *  * **смена человека не расширяет прав**: новый человек получает **пересечение**
 *    (то, что разрешено обоим), а не свои права поверх чужих;
 *  * **сужение останавливает дело честно**: «дальше нельзя — шаг требует удаления,
 *    а вы этого не разрешали», и предлагается вернуть прежнего.
 */

import type { Risk } from "./dangerPolicy";
import { isDangerous } from "./dangerPolicy";

/** Кто и что может. */
export interface Who {
  readonly name: string;
  readonly allowed: readonly Risk[];
}

/** Состояние дела. */
export interface Running {
  /** Права, зафиксированные на входе. */
  readonly fixed: readonly Risk[];
  /** Кто начал. */
  readonly started: string;
  /** Сколько шагов выполнено. */
  readonly done: number;
}

/**
 * Права на входе.
 *
 * Копия, а не ссылка: если у человека потом отзовут разрешение, идущее дело от
 * этого не остановится на середине — но **новые** дела уже пойдут без него.
 */
export function enter(started: Who, riskOfStep: Risk): { running: Running; said: string } {
  return {
    running: { fixed: [...started.allowed], started: started.name, done: 0 },
    said: isDangerous(riskOfStep)
      ? `дело начинается по разрешению «${started.name}»: до конца оно не изменится`
      : "дело начинается: чтение разрешения не требует",
  };
}

/**
 * Что можно после смены человека.
 *
 * Пересечение, а не объединение: новый человек не получает прав, которых у него
 * нет, и прежний не теряет уже начатого.
 */
export function afterSwitch(running: Running, now: Who, riskOfStep: Risk): { ok: boolean; fixed: Risk[]; said: string } {
  if (!isDangerous(riskOfStep)) {
    return { ok: true, fixed: [...running.fixed], said: `чтение: шаг продолжится, права не при чём (д${running.done > 0 ? "ело идёт" : "ело начинается"})` };
  }

  const intersection = running.fixed.filter((risk) => now.allowed.includes(risk));
  if (!intersection.includes(riskOfStep)) {
    return {
      ok: false,
      fixed: intersection,
      said: `дальше нельзя: шаг требует «${riskOfStep}», а «${now.name}» этого не разрешал. Верните «${running.started}» или остановите дело`,
    };
  }
  return {
    ok: true,
    fixed: intersection,
    said: `дело продолжается по общему согласию «${intersection.join(", ")}»: «${now.name}» не получил прав, которых у него не было`,
  };
}

/**
 * Что происходит с уже выполненным.
 *
 * Не переименовывается (шаг 410) и не откатывается: шаги выполнены по согласию
 * того, кто их начал.
 */
export function kept(done: number): string {
  if (done === 0) return "выполненных шагов нет";
  return `${done} ${done === 1 ? "шаг" : "шагов"} выполнены по согласию прежнего человека — в журнале так и останется`;
}

/**
 * Что смена человека не делает.
 *
 * Три запрета — и все три про то, чтобы не расширить права по дороге.
 */
export function notDo(): string[] {
  return [
    "не даёт новому человеку его прав поверх прежних: только пересечение",
    "не расширяет права по ходу дела, даже если новый человек согласен на всё",
    "не откатывает выполненные шаги и не переписывает их автора",
  ];
}
