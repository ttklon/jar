//! Сказать человеку словами — отдельно от «понять, что делать».
//!
//! Зачем отдельный модуль, а не тот же разговор, что `intent`: там модель обязана
//! ответить **объектом JSON** (`{"kind":"call",…}`). Это правильно для выбора
//! действия и совершенно непригодно для речи: прочитать вслух «фигурная скобка
//! kind call» — значит показать человеку протокол вместо ответа. Первая попытка
//! озвучить поток это и сделала, и тест её поймал.
//!
//! Здесь граница проведена жёстко:
//!
//!  * **никаких скобок.** Промпт прямо запрещает JSON и требует обычный текст —
//!    так же, как человек ответил бы другу;
//!  * **коротко.** Это речь, а не статья: длинный ответ человек не дослушает, а
//!    при потоке ещё и не увидит конца;
//!  * **без действий.** Модуль ничего не планирует, не вызывает и не пишет в
//!    память. Ответ — текст, и только он.
//!
//! Функции чистые: строка на входе, строка на выходе. Это позволяет проверить
//! правила без модели, а модель — не выдумывать за тест.

/// Что просим у модели. Одна реплика, без истории — как и в `intent`.
///
/// Три запрета в промпте не случайны: модель охотно скатывается в списки,
/// markdown и «конечно! вот что я сделал» — всё это при произнесении звучит
/// ужасно.
pub fn prompt(question: &str) -> String {
    format!(
        "Ответь человеку вслух, коротко и по-русски.\n\
         Твоя задача — сказать по делу, а не описать, что ты мог бы сделать.\n\
         Не пиши JSON, не пиши markdown, не перечисляй список — это речь.\n\
         Не начинай с «конечно» и «вот»: сразу ответ.\n\
         Не больше трёх предложений.\n\
         Если ответа не знаешь — так и скажи одной фразой.\n\n\
         Вопрос: {question}"
    )
}

/// Разрешён ли этот ответ как речь.
///
/// Проверка нужна на выходе модели, а не только в промпте: модель, которую
/// просят не писать JSON, иногда всё равно его пишет. Произносить такое нельзя,
/// а притворяться, что это ответ, — тем более.
pub fn speakable(answer: &str) -> Result<String, String> {
    let text = answer.trim();

    if text.is_empty() {
        return Err("модель ничего не сказала".to_string());
    }

    // JSON-объект целиком: `{"kind":"call"}` и подобное — это не речь.
    if (text.starts_with('{') && text.ends_with('}'))
        && serde_json::from_str::<serde_json::Value>(text).is_ok()
    {
        return Err("пришёл JSON вместо речи: произносить такое нельзя".to_string());
    }

    // Служебные строки протокола тоже не речь.
    let lower = text.to_lowercase();
    if lower.contains("data:") && lower.contains("[done]") {
        return Err("пришёл поток протокола вместо речи".to_string());
    }

    // Обрезки, которые модель оставляет, когда её оборвали.
    let trimmed = text.trim_end_matches(['…', '.', ' ']).trim_end();
    if trimmed.is_empty() {
        return Err("от модели пришла одна точка".to_string());
    }

    Ok(text.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_prompt_forbids_json_markdown_and_lists() {
        let text = prompt("сколько места на диске");
        // Три вещи, которые при произнесении звучат хуже всего.
        assert!(text.contains("Не пиши JSON"), "{text}");
        assert!(text.contains("не пиши markdown"), "{text}");
        assert!(text.contains("не перечисляй список"), "{text}");
        // Вопрос человека — в промпте целиком, без обрезки.
        assert!(text.contains("сколько места на диске"), "{text}");
        // Ограничение длины: речь, а не статья.
        assert!(text.contains("Не больше трёх предложений"), "{text}");
    }

    #[test]
    fn plain_speech_passes_through_unchanged() {
        let answer = "  На диске 42 гигабайта свободно.  ";
        assert_eq!(
            speakable(answer).expect("речь"),
            "На диске 42 гигабайта свободно."
        );
    }

    #[test]
    fn a_json_intent_is_refused_instead_of_read_aloud() {
        // Ровно то, что вернул бы `intent`: произносить это нельзя.
        let error = speakable(r#"{"kind":"call","registry":"disk.space","params":{}}"#)
            .expect_err("JSON — не речь");
        assert!(error.contains("JSON"), "{error}");

        // Даже если это валидный JSON, но не объект — отвечать им тоже нельзя.
        assert!(
            speakable("{это не json}").is_ok(),
            "не-json в скобках — это текст"
        );
    }

    #[test]
    fn protocol_lines_and_empty_answers_are_named_not_spoken() {
        assert!(speakable("")
            .expect_err("пусто")
            .contains("ничего не сказала"));
        assert!(speakable("   ").is_err());
        assert!(speakable("...").is_err(), "одна точка — не ответ");
        let stream = "data: {\"choices\":[{\"delta\":{}}]}\ndata: [DONE]";
        assert!(speakable(stream)
            .expect_err("протокол")
            .contains("протокол"));
    }
}
