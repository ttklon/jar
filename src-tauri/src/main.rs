// В релизе это GUI-приложение: консольное окно не должно появляться.
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]

fn main() {
    // Режим проверки из командной строки. Нужен не пользователю, а приёмке: на
    // настоящей Windows CI должен убедиться, что установленная программа
    // запускается без прав администратора и может выполнить безопасное действие.
    //
    // Почему отдельный режим, а не окно: у GUI-приложения нет консоли, и проверить
    // «запустилось ли» через окно в CI нельзя — окно не отличит успех от белого
    // экрана. Здесь ответ — код возврата и одна строка, которую нельзя подделать
    // молчанием.
    if zshelper_lib::selfcheck::wants(std::env::args().skip(1)) {
        std::process::exit(zshelper_lib::selfcheck::run());
    }
    zshelper_lib::run();
}
